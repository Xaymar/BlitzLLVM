#!/usr/bin/env bash
# Compiles and runs a .bb program with the ORIGINAL Blitz3D 1.118 compiler under Wine and Xvfb (Mesa llvmpipe), for functional
# comparisons only (screenshots via SaveBuffer, program output). Never use it for performance numbers.
# Usage: tools/original_blitz3d.sh setup | run <program.bb> [timeout-seconds]
# Needs the original bin/ (blitzcc.exe, debugger.dll, linker.dll, runtime.dll) in $B3D_ORIG_BIN, default
# /mnt/project-files/blitz3d-original/bin. The program runs with its directory as the working directory, so
# SaveBuffer(FrontBuffer(),"shot.bmp") lands next to the .bb file.
# AUTOGENERATED COPYRIGHT HEADER START
# Copyright (C) 2026 Claude <noreply@anthropic.com>
# AUTOGENERATED COPYRIGHT HEADER END
set -eu

bin="${B3D_ORIG_BIN:-/mnt/project-files/blitz3d-original/bin}"
home="${B3D_ORIG_HOME:-/opt/b3d}"
export WINEARCH=win32 WINEPREFIX="${WINEPREFIX:-/opt/wine32}" WINEDEBUG=-all BLITZPATH="Z:${home//\//\\}"

setup() {
	dpkg --add-architecture i386
	apt-get update -qq
	DEBIAN_FRONTEND=noninteractive apt-get install -y -qq wine wine32:i386 xvfb libgl1-mesa-dri:i386 libgl1:i386
	mkdir -p "$home/bin" "$home/cfg" "$home/userlibs"
	cp "$bin"/*.exe "$bin"/*.dll "$home/bin/"
	xvfb-run -a wine "$home/bin/blitzcc.exe" -v # creates the Wine prefix
}

run() {
	local src dir name
	src="$(realpath "$1")"; dir="$(dirname "$src")"; name="$(basename "${src%.*}")"
	cd "$dir"
	xvfb-run -a -s "-screen 0 1280x1024x24" bash -c '
		wine "$0/bin/blitzcc.exe" -q -o "$1.exe" "$2" || exit 1
		timeout "$3" wine "$1.exe" 2>&1 | grep -v "^ALSA lib"; exit "${PIPESTATUS[0]}"' "$home" "$name" "$src" "${2:-120}"
}

case "${1:-}" in
setup) setup ;;
run) [ -n "${2:-}" ] || { echo "usage: $0 run program.bb [timeout]" >&2; exit 2; }; shift; run "$@" ;;
*) echo "usage: $0 setup | run program.bb [timeout]" >&2; exit 2 ;;
esac
