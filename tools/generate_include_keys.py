#!/usr/bin/env python3
"""Writes code_compiler/include/keys.bb, the key constants shipped with BlitzLLVM (Include "<keys.bb>").

KEY_* are the codes of KeyDown/KeyHit, taken from the table of the runtime (code_runtime/source/graphics_input.cpp).
VKEY_* are the SDL scancodes of VKeyDown/VKeyHit, taken from SDL's header (third_party/SDL/include/SDL3/SDL_scancode.h).

Usage: generate_include_keys.py [--check]
  --check  Don't write, fail if the file is not what would be written.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUNTIME_TABLE = ROOT / "code_runtime" / "source" / "graphics_input.cpp"
SDL_HEADER = ROOT / "third_party" / "SDL" / "include" / "SDL3" / "SDL_scancode.h"
OUTPUT = ROOT / "code_compiler" / "include" / "keys.bb"

# Names that Blitz programs use for keys more often than SDL's, as a second name for the same code.
ALIASES = {"RETURN": ["ENTER"], "NUMLOCKCLEAR": ["NUMLOCK"], "LGUI": ["LWIN"], "RGUI": ["RWIN"], "APPLICATION": ["APPS"]}


def runtime_keys():
    text = RUNTIME_TABLE.read_text(encoding="utf-8")
    table = text[text.index("key_table[] = {"):]
    table = table[:table.index("};")]
    return [(name, int(code)) for name, code in re.findall(r"\{\s*SDL_SCANCODE_(\w+),\s*(\d+)\s*\}", table)]


def sdl_scancodes():
    text = SDL_HEADER.read_text(encoding="utf-8")
    out = []
    for name, code in re.findall(r"^\s*SDL_SCANCODE_(\w+)\s*=\s*(\d+)\s*,", text, re.M):
        if name in ("UNKNOWN", "COUNT", "RESERVED"):
            continue
        out.append((name, int(code)))
    return out


def block(prefix, entries):
    lines = []
    for name, code in entries:
        for each in [name] + ALIASES.get(name, []):
            lines.append(f"Const {prefix}{each} = {code}")
    return lines


def render():
    keys = sorted(runtime_keys(), key=lambda e: e[1])
    vkeys = sorted(sdl_scancodes(), key=lambda e: e[1])
    lines = [
        "; Key codes, shipped with BlitzLLVM: Include \"<keys.bb>\"",
        "; Generated by tools/generate_include_keys.py, don't edit.",
        ";",
        "; KEY_* are the codes of KeyDown and KeyHit, the DirectInput scan codes of the original. They name the position of a",
        "; key on a US keyboard, not the letter printed on it: KEY_Z is the key left of X, even on a German keyboard.",
        "; VKEY_* are the SDL scan codes of VKeyDown and VKeyHit, which every key has.",
        "",
    ]
    lines += block("KEY_", keys)
    lines += [""]
    lines += block("VKEY_", vkeys)
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        # The copyright header that the pre-commit hook adds is not part of what is generated.
        body = re.sub(r"^;.*AUTOGENERATED COPYRIGHT HEADER START.*?AUTOGENERATED COPYRIGHT HEADER END\n", "", current, flags=re.S | re.M)
        if body != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date, run tools/generate_include_keys.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
