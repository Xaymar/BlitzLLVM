#!/usr/bin/env bash
# Git pre-commit hook: brings the copyright header of every file that this commit adds, copies or modifies up to date.
# Runs with bash on Linux and macOS, and with git-bash on Windows. Install it with tools/install-hooks.sh.
#
# The authors and years are taken from the history of the file (git log --follow) plus the author of the commit being made.
# Only staged files are touched. The header is rewritten in the staged version (the index) and, if the file exists in the
# working tree, in the working tree, so unstaged changes and partially staged hunks are never staged or lost.
# Set SKIP_COPYRIGHT=1 (or use git commit --no-verify) to skip it.
# AUTOGENERATED COPYRIGHT HEADER START
# Copyright (C) 2026 Claude <noreply@anthropic.com>
# AUTOGENERATED COPYRIGHT HEADER END
set -u

[ "${SKIP_COPYRIGHT:-0}" = "1" ] && exit 0

top="$(git rev-parse --show-toplevel)" || exit 1
cd "$top" || exit 1

section_start="AUTOGENERATED COPYRIGHT HEADER START"
section_end="AUTOGENERATED COPYRIGHT HEADER END"

work="$(mktemp -d)" || exit 1
trap 'rm -rf "$work"' EXIT

# Sets $prefix and $suffix to the comment style of the file, and returns 1 for files that get no header.
style_for() {
	local name ext
	name="$(printf '%s' "${1##*/}" | tr '[:upper:]' '[:lower:]')"
	ext="$name"
	case "$name" in *.*) ext=".${name#*.}" ;; esac
	if [ "$name" = "cmakelists.txt" ]; then
		prefix="# "; suffix=""; return 0
	fi
	case "$ext" in
		.clang-tidy|.clang-format|.cmake|.editorconfig|.gitignore|.gitmodules|.yml|.sh)
			prefix="# "; suffix="" ;;
		.iss|.iss.in|.bb|.bpl)
			prefix="; "; suffix="" ;;
		.c|.c.in|.cpp|.cpp.in|.h|.h.in|.hpp|.hpp.in|.js|.rc|.rc.in|.effect)
			prefix="// "; suffix="" ;;
		.htm|.htm.in|.html|.html.in|.xml|.xml.in|.plist|.plist.in|.pkgproj|.pkgproj.in|.md)
			prefix="<!-- "; suffix=" -->" ;;
		*) return 1 ;;
	esac
}

# Prints one "Copyright (C) <years> <name> <<mail>>" line per author of the file, the earliest author first.
copyright_lines() {
	local file="$1" ident now_year now_epoch
	ident="$(git var GIT_AUTHOR_IDENT)" || return 1
	ident="${ident% *}"; ident="${ident% *}" # Drop the timestamp and the timezone.
	now_epoch="$(date -u +%s)"
	now_year="$(date -u +%Y)"
	{
		TZ=UTC git log --follow --date=format-local:%Y --format='%at|%ad|%aN <%aE>' -- "$file" 2>/dev/null
		printf '%s|%s|%s\n' "$now_epoch" "$now_year" "$ident"
	} | awk -F'|' '
		NF >= 3 {
			name = $3
			for (i = 4; i <= NF; i++) name = name "|" $i
			if (!(name in first)) { order[++count] = name; first[name] = $1; last[name] = $1; fy[name] = $2; ly[name] = $2 }
			if ($1 < first[name]) { first[name] = $1; fy[name] = $2 }
			if ($1 > last[name]) { last[name] = $1; ly[name] = $2 }
		}
		END {
			# Stable insertion sort by the time of the first commit.
			for (i = 2; i <= count; i++) {
				v = order[i]
				for (j = i - 1; j >= 1 && first[order[j]] > first[v]; j--) order[j + 1] = order[j]
				order[j + 1] = v
			}
			for (i = 1; i <= count; i++) {
				n = order[i]
				years = (fy[n] != ly[n]) ? fy[n] "-" ly[n] : ly[n]
				print "Copyright (C) " years " " n
			}
		}'
}

# Reads the file $1 and writes it with the header $2 (one line per line) to standard output.
# Replaces the existing section if there is one, otherwise prepends it (after a #! line). Exits with 3 if nothing changes.
apply_header() {
	awk -v hdrfile="$2" '
		BEGIN { while ((getline l < hdrfile) > 0) h[++hn] = l; close(hdrfile) }
		{ line[++n] = $0; t = $0; if (sub(/\r$/, "", t)) crlf = 1; bare[n] = t }
		END {
			eol = crlf ? "\r\n" : "\n"
			s = 0; e = 0
			for (i = 1; i <= n; i++) if (bare[i] == h[1]) { s = i; break }
			for (i = n; i >= 1; i--) if (bare[i] == h[hn]) { e = i; break }
			if (s && e >= s) {
				same = (e - s + 1 == hn)
				for (k = 1; same && k <= hn; k++) if (bare[s + k - 1] != h[k]) same = 0
				if (same) exit 3
				for (i = 1; i < s; i++) printf "%s\n", line[i]
				for (k = 1; k <= hn; k++) printf "%s%s", h[k], eol
				for (i = e + 1; i <= n; i++) printf "%s\n", line[i]
			} else {
				from = 1
				if (bare[1] ~ /^#!/) { printf "%s\n", line[1]; from = 2 }
				for (k = 1; k <= hn; k++) printf "%s%s", h[k], eol
				for (i = from; i <= n; i++) printf "%s\n", line[i]
			}
		}' "$1"
}

# Everything runs inside a function, so bash has parsed the whole script before this hook rewrites itself.
main() {
	status=0
	while IFS= read -r -d '' file; do
		case "$file" in
			.git/*|.github/workflows/*|cmake/clang/*|cmake/version/*|third-party/*|third_party/*) continue ;;
		esac
		style_for "$file" || continue

		# Skip submodules, symlinks and binary files.
		mode="$(git ls-files -s -- "$file" | cut -d' ' -f1)"
		case "$mode" in 100644|100755) ;; *) continue ;; esac
		case "$(git diff --cached --numstat -- "$file")" in -$'\t'-*) continue ;; esac

		lines="$(copyright_lines "$file")" || { echo "pre-commit: could not read the history of '$file'." >&2; status=1; continue; }
		{
			printf '%s%s%s\n' "$prefix" "$section_start" "$suffix"
			while IFS= read -r l; do printf '%s%s%s\n' "$prefix" "$l" "$suffix"; done <<< "$lines"
			printf '%s%s%s\n' "$prefix" "$section_end" "$suffix"
		} > "$work/header"

		changed=0

		# The staged version: never touches the working tree, so unstaged hunks stay unstaged.
		git show ":$file" > "$work/index" 2>/dev/null || continue
		apply_header "$work/index" "$work/header" > "$work/index.new"; rc=$?
		if [ $rc -eq 0 ]; then
			sha="$(git hash-object -w --no-filters "$work/index.new")" \
				&& git update-index --cacheinfo "$mode,$sha,$file" || { status=1; continue; }
			changed=1
		elif [ $rc -ne 3 ]; then
			echo "pre-commit: failed to update '$file'." >&2; status=1; continue
		fi

		# The working tree copy gets the same header, so it does not show up as an unstaged change.
		if [ -f "$file" ] && [ ! -L "$file" ]; then
			apply_header "$file" "$work/header" > "$work/tree.new"; rc=$?
			if [ $rc -eq 0 ]; then
				cat "$work/tree.new" > "$file" || { status=1; continue; }
				changed=1
			elif [ $rc -ne 3 ]; then
				echo "pre-commit: failed to update '$file' in the working tree." >&2; status=1; continue
			fi
		fi

		[ $changed -eq 1 ] && echo "pre-commit: updated copyright header of '$file'."
	done < <(git diff --cached --name-only -z --diff-filter=ACM)
	return $status
}

main "$@"; exit $?
