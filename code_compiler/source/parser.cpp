blitz::parser::~parser() {}

blitz::parser::parser() : _file(), _file_ptr(), _tokens(), _pos(0), _include_stack(), _included(), _program(), _depth(0), _in_function(false) {}

std::unique_ptr<blitz::ast::program> blitz::parser::parse(std::filesystem::path file)
{
	_program = std::make_unique<ast::program>();
	_include_stack.clear();
	_depth    = 0;
	_root_dir = file.parent_path();
	_global_slots.clear();
	_main_slots.clear();
	_function_slots.clear();
	_functions.clear();
	_global_uses.clear();
	_function_uses.clear();
	_implicit_uses.clear();
	_scope_id    = 0;
	_scope_count = 0;
	_in_function = false;
	_suffix_error.reset();
	parse_file(file, _program->main);
	resolve_suffixes();
	return std::move(_program);
}

