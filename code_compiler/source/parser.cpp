blitz::parser::~parser() {}

blitz::parser::parser() : _file(), _file_ptr(), _tokens(), _pos(0), _include_stack(), _program(), _depth(0), _in_function(false) {}

std::unique_ptr<blitz::ast::program> blitz::parser::parse(std::filesystem::path file)
{
	_program = std::make_unique<ast::program>();
	_include_stack.clear();
	_depth    = 0;
	_root_dir = file.parent_path();
	_global_slots.clear();
	_main_slots.clear();
	_function_slots.clear();
	_functions.clear();
	_global_uses.clear();
	_function_uses.clear();
	_in_function = false;
	_suffix_error.reset();
	parse_file(file, _program->main);
	resolve_suffixes();
	return std::move(_program);
}

////////////////////////////////////////////////////////////////////////////////
// Suffix propagation
////////////////////////////////////////////////////////////////////////////////
void blitz::parser::note_variable_use(blitz::token const& name, blitz::types::type type, std::string const& struct_name)
{
	if (type == blitz::types::type::UNKNOWN) {
		return;
	}
	use by{ name, type, struct_name, _file };
	auto& scope = _in_function ? _function_slots : _main_slots;
	if (auto found = scope.find(lower(name.text)); found != scope.end()) {
		apply_suffix(found->second, by);
	} else {
		// Maybe a Global, which can be declared further down.
		_global_uses.push_back(std::move(by));
	}
}

void blitz::parser::note_function_use(blitz::token const& name, blitz::types::type type, std::string const& struct_name)
{
	if (type != blitz::types::type::UNKNOWN) {
		_function_uses.push_back(use{ name, type, struct_name, _file });
	}
}

void blitz::parser::apply_suffix(slot& target, use const& by)
{
	if (!target.typed) {
		*target.type        = by.type;
		*target.struct_name = by.struct_name;
		target.typed        = true;
		return;
	}
	if ((*target.type == by.type) && ((by.type != blitz::types::type::STRUCT) || (lower(*target.struct_name) == lower(by.struct_name)))) {
		return;
	}
	if (!_suffix_error) {
		auto describe = [](blitz::types::type type, std::string const& struct_name) {
			return (type == blitz::types::type::STRUCT) ? ("Object of type '" + struct_name + "'") : ("'" + blitz::types::to_string(type) + "'");
		};
		_suffix_error = std::make_unique<blitz::error>(blitz::error(by.file, by.name.location, by.name.location,
			blitz::format("Type mismatch: '%s' is used as %s, but was defined as %s.", by.name.text.c_str(), describe(by.type, by.struct_name).c_str(),
						  describe(*target.type, *target.struct_name).c_str())));
	}
}

void blitz::parser::resolve_suffixes()
{
	for (auto const& by : _global_uses) {
		if (auto found = _global_slots.find(lower(by.name.text)); found != _global_slots.end()) {
			apply_suffix(found->second, by);
		}
	}
	for (auto const& by : _function_uses) {
		if (auto found = _functions.find(lower(by.name.text)); found != _functions.end()) {
			apply_suffix(found->second, by);
		}
	}
	if (_suffix_error) {
		throw *_suffix_error;
	}
}

////////////////////////////////////////////////////////////////////////////////
// Token handling
////////////////////////////////////////////////////////////////////////////////
blitz::token const& blitz::parser::tk(size_t offset) const
{
	size_t idx = std::min(_pos + offset, _tokens.size() - 1); // The last token is always EndOfFile.
	return _tokens[idx];
}

void blitz::parser::advance()
{
	if (_pos < _tokens.size() - 1) {
		_pos++;
	}
}

blitz::ast::location blitz::parser::here(blitz::token const& token) const
{
	return ast::location{ _file_ptr, token.location.first, token.location.second };
}

blitz::error blitz::parser::error(blitz::token const& token, std::string const& reason) const
{
	return blitz::error(_file, token.location, token.location, reason);
}

bool blitz::parser::is_keyword(blitz::token const& token, const char* keyword) const
{
	return (token.type == blitz::token::variant::TEXT) && (lower(token.text) == keyword);
}

bool blitz::parser::is_symbol(blitz::token const& token, const char* symbol) const
{
	return (token.type == blitz::token::variant::SYMBOL) && (token.text == symbol);
}

bool blitz::parser::is_terminator(blitz::token const& token) const
{
	return (token.type == blitz::token::variant::NEWLINE) || (token.type == blitz::token::variant::SEPARATOR) || (token.type == blitz::token::variant::ENDOFFILE) || is_keyword(token, "else");
}

bool blitz::parser::adjacent(blitz::token const& lhs, blitz::token const& rhs) const
{
	return (lhs.location.first == rhs.location.first) && ((lhs.location.second + lhs.text.length()) == rhs.location.second);
}

void blitz::parser::skip_empty()
{
	while ((tk().type == blitz::token::variant::NEWLINE) || (tk().type == blitz::token::variant::SEPARATOR)) {
		advance();
	}
}

void blitz::parser::expect_keyword(const char* keyword)
{
	if (!is_keyword(tk(), keyword)) {
		throw error(tk(), blitz::format("Unexpected %s, expected '%s'.", tk().to_string().c_str(), keyword));
	}
	advance();
}

void blitz::parser::expect_symbol(const char* symbol)
{
	if (!is_symbol(tk(), symbol)) {
		throw error(tk(), blitz::format("Unexpected %s, expected '%s'.", tk().to_string().c_str(), symbol));
	}
	advance();
}

