void blitz::parser::load(std::filesystem::path file)
{
	_file     = file;
	_file_ptr = std::make_shared<const std::filesystem::path>(file);
	_tokens.clear();
	_pos = 0;

	blitz::lexer lex(file);
	while (true) {
		auto token = lex.next();
		if (token.type == blitz::token::variant::COMMENT) {
			continue;
		}
		_tokens.push_back(token);
		if (token.type == blitz::token::variant::ENDOFFILE) {
			break;
		}
	}
}

void blitz::parser::parse_file(std::filesystem::path file, ast::block& into)
{
	std::error_code ec;
	auto            canonical = std::filesystem::weakly_canonical(file, ec);
	if (std::find(_include_stack.begin(), _include_stack.end(), canonical) != _include_stack.end()) {
		throw blitz::error(_file, { 0, 0 }, { 0, 0 }, blitz::format("Recursive include of '%s'.", file.lexically_normal().generic_string().c_str()));
	}
	_include_stack.push_back(canonical);

	// Includes interrupt the parsing of the current file, so we have to restore it afterwards.
	auto saved_file   = _file;
	auto saved_ptr    = _file_ptr;
	auto saved_tokens = std::move(_tokens);
	auto saved_pos    = _pos;

	load(file);
	while (true) {
		skip_empty();
		if (tk().type == blitz::token::variant::ENDOFFILE) {
			break;
		}
		if (at_block_end()) {
			throw error(tk(), blitz::format("Unexpected %s.", tk().to_string().c_str()));
		}
		parse_statement(into);
		if ((tk().type == blitz::token::variant::NEWLINE) || (tk().type == blitz::token::variant::SEPARATOR)) {
			advance();
		} else if (!starts_statement(tk()) && (tk().type != blitz::token::variant::ENDOFFILE)) {
			throw error(tk(), blitz::format("Unexpected %s, expected end of statement.", tk().to_string().c_str()));
		}
	}

	_file     = saved_file;
	_file_ptr = saved_ptr;
	_tokens   = std::move(saved_tokens);
	_pos      = saved_pos;
	_include_stack.pop_back();
}
