	// x86_64, x86 or arm64: the architecture of the target triple, or of this computer when there is no target.
	std::string architecture_of(std::string const& target)
	{
		if (target.empty()) {
#if defined(__aarch64__) || defined(_M_ARM64)
			return "arm64";
#elif defined(__x86_64__) || defined(_M_X64)
			return "x86_64";
#else
			return "x86";
#endif
		}
		auto name = target.substr(0, target.find('-'));
		if (name == "aarch64" || name == "arm64" || name == "arm64e") {
			return "arm64";
		}
		if (name == "x86_64" || name == "x86_64h" || name == "amd64") {
			return "x86_64";
		}
		if (name.size() == 4 && name[0] == 'i' && name[2] == '8' && name[3] == '6') {
			return "x86";
		}
		return name;
	}

	std::filesystem::path executable_path()
	{
#if defined(_WIN32)
		wchar_t buffer[32768];
		DWORD   length = GetModuleFileNameW(nullptr, buffer, DWORD(std::size(buffer)));
		return std::filesystem::path(std::wstring(buffer, length));
#elif defined(__APPLE__)
		char     buffer[4096];
		uint32_t size = sizeof(buffer);
		if (_NSGetExecutablePath(buffer, &size) == 0) {
			return std::filesystem::weakly_canonical(buffer);
		}
		return {};
#else
		std::error_code ec;
		return std::filesystem::read_symlink("/proc/self/exe", ec);
#endif
	}

	// A new folder for the files of one build, that nobody else has made or can write to. The name can't be guessed from the files
	// that are built, as anyone else who can write to the temporary folder could otherwise make the folder first (or replace the
	// files in it while they are built), and have the compiler write to where they point or build what they wrote.
	std::filesystem::path make_temp_dir()
	{
		std::random_device                      device;
		std::uniform_int_distribution<uint64_t> any;
		auto base = std::filesystem::temp_directory_path();
		for (int attempt = 0; attempt < 100; attempt++) {
			char name[40];
			std::snprintf(name, sizeof(name), "blitzllvm-%016llx", static_cast<unsigned long long>(any(device)));
			auto path = base / name;
#if defined(_WIN32)
			std::error_code ec;
			if (std::filesystem::create_directory(path, ec) && !ec) {
				return path;
			}
#else
			if (::mkdir(path.c_str(), 0700) == 0) {
				return path;
			}
			if (errno != EEXIST) {
				throw std::runtime_error("Creating the folder '" + path.generic_string() + "' failed: " + std::strerror(errno));
			}
#endif
		}
		throw std::runtime_error("Creating a folder for the build in '" + base.generic_string() + "' failed.");
	}

	std::string quote(std::string const& arg)
	{
		// Only what no shell does anything with is left as it is. A list of what shells do something with is never complete (a line
		// break, a leading ~ or #, [ ] { } and ! are some that it used to miss), and what is missing from it starts another command.
		if (!arg.empty() && (arg.find_first_not_of("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-+=:,./@") == std::string::npos)) {
			return arg;
		}
#if defined(_WIN32)
		return "\"" + arg + "\"";
#else
		std::string out = "'";
		for (char c : arg) {
			out += (c == '\'') ? std::string("'\\''") : std::string(1, c);
		}
		return out + "'";
#endif
	}

	int run(std::vector<std::string> const& command, bool verbose)
	{
		std::string line;
		for (auto const& part : command) {
			line += (line.empty() ? "" : " ") + quote(part);
		}
		if (verbose) {
			std::cout << line << std::endl;
		}
#if defined(_WIN32)
		line = "\"" + line + "\""; // cmd.exe strips the outermost quotes.
#endif
		return std::system(line.c_str());
	}

	void write_file(std::filesystem::path const& path, std::string const& data)
	{
		std::ofstream stream(path, std::ios_base::binary);
		stream.write(data.data(), std::streamsize(data.size()));
		if (!stream.good()) {
			throw std::runtime_error("Writing file '" + path.generic_string() + "' failed.");
		}
	}

	bool parse_arguments(int argc, char** argv, options& opt)
	{
		// --help and --version answer before anything else is looked at, so a bad option next to them does not matter. What is
		// after --args or -- belongs to the program or to clang, and the value of an option such as -o is skipped. Whichever of the two
		// comes first wins.
		for (int idx = 1; idx < argc; idx++) {
			std::string arg = argv[idx];
			std::string lowered = arg;
			std::transform(lowered.begin(), lowered.end(), lowered.begin(), [](unsigned char c) { return char(std::tolower(c)); });
			if ((arg == "--args") || (arg == "--")) {
				break;
			} else if ((lowered == "--fast-math") || (arg == "--userlibs-dir") || (arg == "-o") || (arg == "--target") || (arg == "--llvm-flag")
					   || (arg == "--llvm-arg") || (arg == "--cc") || (arg == "--runtime-dir")) {
				idx++; // The value of an option, which may well be spelled like --help.
			} else if ((arg == "-h") || (arg == "--help")) {
				opt.help = true;
				return true;
			} else if (arg == "--version") {
				opt.long_version = true;
				return true;
			}
		}
		for (int idx = 1; idx < argc; idx++) {
			std::string arg = argv[idx];
			auto        value = [&]() -> std::string {
                if (idx + 1 >= argc) {
                    throw std::runtime_error("Option " + arg + " requires a value.");
                }
                return argv[++idx];
			};

			std::string lowered = arg;
			std::transform(lowered.begin(), lowered.end(), lowered.begin(), [](unsigned char c) { return char(std::tolower(c)); });

			if ((arg == "-h") || (arg == "--help")) {
				opt.help = true;
			} else if (lowered == "-q") {
				opt.quiet = true;
			} else if (lowered == "+q") {
				opt.quiet = opt.very_quiet = true;
			} else if (opt.warnings.parse(lowered)) {
				// A -W option, the warnings are set up.
			} else if (lowered == "-c") {
				opt.compile_only = true;
			} else if (lowered == "--fast-math") {
				opt.fast_math = value();
				if ((opt.fast_math != "full") && (opt.fast_math != "safe") && (opt.fast_math != "off")) {
					throw std::runtime_error("--fast-math needs full, safe or off.");
				}
			} else if (lowered == "-d") {
				opt.debug = true;
			} else if (lowered == "-g") {
				opt.debug_info = true;
			} else if (lowered == "-k") {
				opt.dump_keys = true;
			} else if (lowered == "+k") {
				opt.dump_keys = opt.dump_syntax = true;
			} else if (arg == "--dump-keywords") {
				opt.dump_keys = opt.dump_native = true;
			} else if (lowered == "-v") {
				opt.version = true;
			} else if (arg == "--console") {
				opt.console = true;
			} else if (arg == "--userlibs-dir") {
				opt.userlibs_dir = value();
			} else if (arg == "-o") {
				opt.output = value();
			} else if ((arg == "-O0") || (arg == "-O1") || (arg == "-O2") || (arg == "-O3") || (arg == "-Os") || (arg == "-Oz")) {
				opt.optimization = arg;
			} else if ((arg == "-S") || (arg == "--emit-llvm")) {
				opt.emit_ir = true;
			} else if (arg == "--target") {
				opt.target = value();
			} else if (arg == "--llvm-flag") {
				opt.flags.push_back(value());
			} else if (arg == "--llvm-arg") {
				opt.flags.push_back("-mllvm");
				opt.flags.push_back(value());
			} else if (arg == "--cc") {
				opt.cc = value();
			} else if (arg == "--sane-evaluation-order") {
				opt.sane_order = true;
			} else if (arg == "--profile") {
				opt.profile = true;
			} else if (arg == "--no-runtime-inline") {
				opt.no_inline = true;
			} else if (arg == "--runtime-dir") {
				opt.runtime_dir = value();
			} else if (arg == "--dump-tokens") {
				opt.tokens = true;
			} else if (arg == "--keep-temps") {
				opt.keep_temps = true;
			} else if (arg == "--verbose") {
				opt.verbose = true;
			} else if (arg == "--args") {
				for (idx++; idx < argc; idx++) {
					opt.run_args.push_back(argv[idx]);
				}
			} else if (arg == "--") {
				for (idx++; idx < argc; idx++) {
					opt.flags.push_back(argv[idx]);
				}
			} else if (!arg.empty() && (arg[0] == '-')) {
				throw std::runtime_error("Unknown option " + arg + ", see --help.");
			} else if (opt.input.empty()) {
				opt.input = arg;
			} else {
				throw std::runtime_error("Only one input file is supported.");
			}
		}
		return true;
	}

	// The 'userlibs' directory: --userlibs-dir, else the environment variable BLITZLLVM_USERLIBS, else the one of the installation, which
	// is <prefix>/userlibs (portable layout, with the compiler in <prefix>/bin), next to the compiler (<prefix>/userlibs for a flat zip) or
	// <prefix>/share/blitzllvm/userlibs for packages.
	std::filesystem::path find_userlibs(options const& opt)
	{
		if (!opt.userlibs_dir.empty()) {
			return opt.userlibs_dir;
		}
		if (const char* env = std::getenv("BLITZLLVM_USERLIBS"); env && *env) {
			return env;
		}
		auto bin_dir = executable_path().parent_path();
		for (auto const& candidate : { bin_dir / ".." / "userlibs", bin_dir / "userlibs", bin_dir / ".." / "share" / "blitzllvm" / "userlibs" }) {
			if (std::filesystem::is_directory(candidate)) {
				return std::filesystem::weakly_canonical(candidate);
			}
		}
		return {};
	}

