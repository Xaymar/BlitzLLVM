#pragma once
#include <cinttypes>
#include <filesystem>
#include <stdexcept>
#include <string>
#include <utility>

namespace blitz {
	class error : public std::runtime_error {
		std::filesystem::path         _file;
		std::pair<uint64_t, uint64_t> _base;
		std::pair<uint64_t, uint64_t> _at;

		public:
		~error();
		error(std::filesystem::path file, std::pair<uint64_t, uint64_t> base, std::pair<uint64_t, uint64_t> at, std::string reason);

		std::filesystem::path const& file() const;

		std::pair<uint64_t, uint64_t> const& base() const;

		std::pair<uint64_t, uint64_t> const& at() const;
	};

	std::string format(const char* format, ...);

	/** The source line at the given 1-based line and column, followed by a line pointing at the column, like
	 * "<line>\n<padding>^^^------- HERE\n", where the carets cover the length (in bytes, from the column; a single caret if that is 0)
	 * and the dashes continue to the end of the line. Empty if there is nothing to show, which is the case for line 0 and for files that can't
	 * be read. Without a column (0) only the line is shown. Long lines are cut around the column. */
	std::string source_excerpt(std::filesystem::path const& file, uint64_t line, uint64_t column, uint64_t length = 0);

	/** "file:line:column: kind: reason", with the file lexically normalized (no "." or ".." parts), followed by the source_excerpt
	 * and, if there is one, a "notice: <notice>" line, without a trailing new line. */
	std::string diagnostic(std::filesystem::path const& file, uint64_t line, uint64_t column, std::string const& kind, std::string const& reason, uint64_t length = 0, std::string const& notice = std::string());
} // namespace blitz
