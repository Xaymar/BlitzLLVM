blitz::compiler::value blitz::compiler::gen(ast::expression const* expr)
{
	auto v = gen_node(expr);
	if (v.need <= 0) {
		v.need = default_need(expr);
	}
	_needs[expr] = v.need;
	return v;
}

blitz::compiler::value blitz::compiler::gen_node(ast::expression const* expr)
{
	at here(*this, expr->where);
	if (auto n = dynamic_cast<ast::literal const*>(expr)) {
		return gen_literal(n);
	} else if (auto n = dynamic_cast<ast::reference const*>(expr)) {
		return gen_reference(n);
	} else if (auto n = dynamic_cast<ast::call const*>(expr)) {
		return gen_call(n);
	} else if (auto n = dynamic_cast<ast::unary const*>(expr)) {
		return gen_unary(n);
	} else if (auto n = dynamic_cast<ast::binary const*>(expr)) {
		return gen_binary(n);
	} else if (auto n = dynamic_cast<ast::field_access const*>(expr)) {
		return gen_field(n);
	} else if (auto n = dynamic_cast<ast::index_access const*>(expr)) {
		return gen_index(n);
	} else if (auto n = dynamic_cast<ast::new_object const*>(expr)) {
		return gen_new(n);
	} else if (auto n = dynamic_cast<ast::list_end const*>(expr)) {
		return gen_list_end(n);
	} else if (auto n = dynamic_cast<ast::list_neighbor const*>(expr)) {
		return gen_neighbor(n);
	} else if (auto n = dynamic_cast<ast::object_from_handle const*>(expr)) {
		return gen_from_handle(n);
	}
	throw err(expr->where, "Unsupported expression.");
}

blitz::compiler::value blitz::compiler::gen_literal(ast::literal const* node)
{
	switch (node->kind) {
	case ast::literal::variant::STRING:
		return { string_constant(node->text), type::STRING };
	case ast::literal::variant::NULLPTR:
		return { "null", type::STRUCT, "" };
	case ast::literal::variant::REAL:
		return constant(type::FLOAT32, node->f);
	case ast::literal::variant::UNSIGNED_INTEGER:
		if (node->u > UINT32_MAX) {
			return { std::to_string((long long)(int64_t)node->u), type::UINT64 };
		}
		return { std::to_string((int32_t)(uint32_t)node->u), type::UINT32 };
	default:
		if ((node->i > INT32_MAX) || (node->i < INT32_MIN)) {
			return { std::to_string((long long)node->i), type::INT64 };
		}
		return { std::to_string((long long)node->i), type::INT32 };
	}
}

blitz::compiler::value blitz::compiler::gen_reference(ast::reference const* node)
{
	if (auto var = find(node->name)) {
		if (var->dims || var->count) {
			throw err(node->where, "'" + node->name + "' is an array, it needs an index.");
		}
		var->used = true;
		auto r = tmp();
		emit(r + " = load " + blitz::types::to_llvm(var->type) + ", ptr " + var->pointer);
		return { r, var->type, var->sname };
	}

	// Not a variable: a function can be called without parenthesis.
	auto key = lower(node->name);
	if (_functions.count(key) || find_builtin(key) || find_userlib(key) || (key == "int") || (key == "float") || (key == "str")) {
		ast::call fake;
		fake.where = node->where;
		fake.name  = node->name;
		fake.type  = node->type;
		return gen_call(&fake);
	}
	if (key == "pi") {
		return constant(type::FLOAT32, 3.14159265358979323846);
	}

	// Automatically declare the variable.
	warn(node->where, "implicit-variable", "'" + node->name + "' was not declared, it is a new local variable.", "Declare it first, such as 'Local " + node->name + "'.", {}, declaration_suffix(node->type, node->struct_name));
	create_local(node->name, (node->type == type::UNKNOWN) ? type::INT32 : node->type, false, node->where, node->struct_name);
	return gen_reference(node);
}

blitz::compiler::value blitz::compiler::gen_builtin(ast::call const* node, bool& handled)
{
	handled   = true;
	auto key  = lower(node->name);
	auto args = node->arguments.size();

	auto need = [&](size_t min, size_t max) {
		if ((args < min) || (args > max)) {
			throw err(node->where, "Function '" + node->name + "' expects " + (min == max ? std::to_string(min) : std::to_string(min) + " to " + std::to_string(max)) + " arguments, got " + std::to_string(args) + ".");
		}
	};

	if (key == "handle") {
		need(1, 1);
		auto object = gen(node->arguments[0].get());
		if (object.type != type::STRUCT) {
			throw err(node->where, "Handle needs an object.");
		}
		// Which type the handle is for is what keeps Object.Type from giving back an object of another type.
		std::string list = object.sname.empty() ? std::string("null") : need_type(object.sname, node->where).list;
		return call_runtime("bb_handle", type::INT32, { object, { list, type::STRUCT } });
	} else if (key == "int") {
		need(1, 1);
		return convert_explicit(gen(node->arguments[0].get()), type::INT32, false, node->where);
	} else if (key == "float") {
		need(1, 1);
		return convert(gen(node->arguments[0].get()), type::FLOAT32, node->where, false);
	} else if (key == "str") {
		need(1, 1);
		return convert(gen(node->arguments[0].get()), type::STRING, node->where, false);
	} else if ((key == "abs") || (key == "sgn")) {
		need(1, 1);
		auto v = gen(node->arguments[0].get());
		auto t = common_type(v.type, v.type, node->where);
		v      = convert(v, t, node->where, false);
		auto llvm = blitz::types::to_llvm(t);
		bool real = blitz::types::is_real(t);
		auto zero_v = zero(t);
		auto one    = constant(t, 1), minus_one = constant(t, -1);
		if (!real && !blitz::types::is_signed(t)) {
			// An unsigned number is never below 0: it is its own absolute value, and its sign is 0 or 1.
			if (key == "abs") {
				return v;
			}
			auto nz = tmp(), r = tmp();
			emit(nz + " = icmp ne " + llvm + " " + v.repr + ", 0");
			emit(r + " = zext i1 " + nz + " to " + llvm);
			return { r, t };
		}
		if (key == "abs") {
			auto neg = tmp(), is_neg = tmp(), r = tmp();
			emit(is_neg + (real ? " = fcmp olt " : " = icmp slt ") + llvm + " " + v.repr + ", " + zero_v.repr);
			emit(neg + (real ? " = fneg " : " = sub ") + llvm + (real ? " " : " 0, ") + v.repr);
			emit(r + " = select i1 " + is_neg + ", " + llvm + " " + neg + ", " + llvm + " " + v.repr);
			return { r, t };
		}
		auto gt = tmp(), lt = tmp(), s1 = tmp(), r = tmp();
		emit(gt + (real ? " = fcmp ogt " : " = icmp sgt ") + llvm + " " + v.repr + ", " + zero_v.repr);
		emit(lt + (real ? " = fcmp olt " : " = icmp slt ") + llvm + " " + v.repr + ", " + zero_v.repr);
		emit(s1 + " = select i1 " + lt + ", " + llvm + " " + minus_one.repr + ", " + llvm + " " + zero_v.repr);
		emit(r + " = select i1 " + gt + ", " + llvm + " " + one.repr + ", " + llvm + " " + s1);
		return { r, t };
	} else if ((key == "min") || (key == "max")) {
		need(2, 8);
		auto acc = gen(node->arguments[0].get());
		for (size_t idx = 1; idx < args; idx++) {
			auto next = gen(node->arguments[idx].get());
			auto t    = common_type(acc.type, next.type, node->where);
			acc       = convert(acc, t, node->where, false);
			next      = convert(next, t, node->where, false);
			auto pick = compare((key == "min") ? ast::binary::op::LESS : ast::binary::op::GREATER, acc, next, node->where);
			auto r    = tmp();
			auto llvm = blitz::types::to_llvm(t);
			emit(r + " = select i1 " + pick + ", " + llvm + " " + acc.repr + ", " + llvm + " " + next.repr);
			acc = { r, t };
		}
		return acc;
	}

	auto numeric = gen_numeric(node, handled);
	if (handled) {
		return numeric;
	}
	handled = true;

	auto entry = find_builtin(key);
	if (!entry) {
		handled = false;
		return {};
	}

	size_t total = strlen(entry->params);
	need(size_t(entry->required), total);

	// Figure out which parameters the provided arguments belong to. The original evaluates all of them, defaults included, in the
	// order of the registers they need.
	std::vector<value>   values(total);
	std::vector<bool>    given(total, false);
	std::vector<operand> operands(total);
	size_t               offset = (entry->lead && (args == 1) && (total == 2)) ? 1 : 0;
	for (size_t idx = 0; idx < args; idx++) {
		operands[idx + offset] = capture(node->arguments[idx].get());
		given[idx + offset]    = true;
	}
	for (size_t idx = 0; idx < total; idx++) {
		if (!given[idx]) {
			auto want       = builtin_type(entry->params[idx]);
			operands[idx].v = (want == type::STRING) ? zero(want) : constant(want, entry->defaults[idx]);
			operands[idx].v.need = 1;
		}
	}
	int chain = place_sequence(operands);
	for (size_t idx = 0; idx < args; idx++) {
		auto want            = builtin_type(entry->params[idx + offset]);
		// Anything can be turned into a string without it being surprising, so only warn for the other direction.
		values[idx + offset] = convert(operands[idx + offset].v, want, node->arguments[idx]->where, want != type::STRING, std::string(), &node->arguments[idx]->covers);
	}
	for (size_t idx = 0; idx < total; idx++) {
		if (!given[idx]) {
			values[idx] = operands[idx].v;
		}
	}
	bool inlined = false;
	auto fast    = inline_builtin(entry->symbol, values, inlined);
	if (inlined) {
		fast.need = chain;
		return fast;
	}
	auto called = call_runtime(entry->symbol, builtin_type(entry->ret), values);
	called.need = chain;
	return called;
}

blitz::keywords::user_function const* blitz::compiler::find_userlib(std::string const& key) const
{
	for (auto const& fn : userlibs) {
		if (lower(fn.name) == key) {
			return &fn;
		}
	}
	return nullptr;
}

// A function that a .decls file declares, called with the C calling convention. Strings are passed as C strings, banks as the
// address of their memory and objects as the address of the object. A returned string is copied, as the library may reuse it.
blitz::compiler::value blitz::compiler::gen_userlib(ast::call const* node, bool& handled)
{
	auto entry = find_userlib(lower(node->name));
	handled    = (entry != nullptr);
	if (!entry) {
		return {};
	}
	auto args = node->arguments.size();
	if (args != entry->params.size()) {
		throw err(node->where, "Function '" + node->name + "' expects " + std::to_string(entry->params.size()) + " arguments, got " + std::to_string(args) + ".");
	}

	std::vector<operand> operands;
	for (size_t idx = 0; idx < args; idx++) {
		operands.push_back(capture(node->arguments[idx].get()));
	}
	int chain = place_sequence(operands);

	std::vector<value> values;
	for (size_t idx = 0; idx < args; idx++) {
		auto const& expr  = node->arguments[idx];
		auto        v     = operands[idx].v;
		auto const& param = entry->params[idx];
		if (param.pointer) {
			if (v.type == type::STRUCT) {
				values.push_back(v);
			} else {
				v = convert(v, type::INT32, expr->where, true, std::string(), &expr->covers);
				values.push_back(call_runtime("bb_bank_pointer", type::STRUCT, { v }));
			}
		} else {
			// Strings are the only type that is not a number, and nothing is turned into a string with a warning.
			values.push_back(convert(v, param.type, expr->where, param.type != type::STRING, std::string(), &expr->covers));
		}
	}

	// The function is looked up when the program first calls it: the library is loaded then (LoadLibrary or dlopen), and the pointer is kept.
	auto slot = "@bb.ul." + std::to_string(_counter++);
	_globals << slot << " = internal global ptr null\n";
	auto symbol = call_runtime("bb_userlib_function", type::STRUCT,
							   { { slot, type::STRUCT },
								 { string_constant(entry->lib), type::STRUCT },
								 { string_constant(entry->symbol), type::STRUCT },
								 { userlibs_dir.empty() ? std::string("null") : string_constant(userlibs_dir), type::STRUCT },
								 { string_constant(source_dir), type::STRUCT } });

	// Whole numbers smaller than 32 bits are extended by the caller, as the C calling convention has it.
	auto extension = [](type t) -> std::string {
		if (blitz::types::is_integer(t) && (blitz::types::bits(t) < 32)) {
			return blitz::types::is_signed(t) ? " signext" : " zeroext";
		}
		return "";
	};
	std::string params, list;
	for (size_t idx = 0; idx < values.size(); idx++) {
		auto llvm_type = blitz::types::to_llvm(values[idx].type);
		params += (idx ? ", " : "") + llvm_type;
		list += (idx ? ", " : "") + llvm_type + extension(values[idx].type) + " " + values[idx].repr;
	}
	auto ret      = entry->ret;
	auto llvm_ret = blitz::types::to_llvm(ret);
	if (ret == type::UNKNOWN) {
		emit("call void (" + params + ") " + symbol.repr + "(" + list + ")");
		value none{ "", type::UNKNOWN };
		none.need = chain;
		return none;
	}
	auto r = tmp();
	emit(r + " = call" + extension(ret) + " " + llvm_ret + " (" + params + ") " + symbol.repr + "(" + list + ")");
	if (ret == type::STRING) {
		auto dup = call_runtime("bb_str_dup", type::STRING, { { r, type::STRING } });
		dup.need = chain;
		return dup;
	}
	value result{ r, ret };
	result.need = chain;
	return result;
}

// The variable, array element or field that an Out or InOut parameter writes to.
blitz::compiler::address blitz::compiler::gen_reference_argument(ast::call const* node, size_t idx, ast::parameter const& param, ast::function const& fn)
{
	auto const* arg      = node->arguments[idx].get();
	auto        keyword  = (param.mode == ast::direction::OUT) ? std::string("Out") : std::string("InOut");
	auto        describe = keyword + " parameter '" + param.name + "' of '" + fn.name + "'";
	bool        place    = dynamic_cast<ast::reference const*>(arg) || dynamic_cast<ast::field_access const*>(arg) || dynamic_cast<ast::index_access const*>(arg);
	if (auto c = dynamic_cast<ast::call const*>(arg)) {
		place = find_dim(c->name) != nullptr; // `Dim` arrays are indexed like a call.
	}
	if (!place) {
		throw err(arg->where, describe + " needs a variable, array element or field to write to, not a value.");
	}
	auto addr = gen_address(arg, param.mode == ast::direction::OUT);
	if (addr.constant) {
		throw err(arg->where, describe + " can't write to a constant.");
	}
	if (addr.count) {
		throw err(arg->where, describe + " can't take a whole array, give it an element.");
	}
	if ((addr.type != param.type) || ((param.type == type::STRUCT) && (addr.sname != lower(param.struct_name)))) {
		auto name = [](type t, std::string const& sname) { return (t == type::STRUCT) ? "object of type '" + sname + "'" : blitz::types::display(t); };
		throw err(arg->where, describe + " has to be given a variable of type " + name(param.type, lower(param.struct_name)) + ", not " + name(addr.type, addr.sname) + ".");
	}
	if (param.mode == ast::direction::INOUT) {
		if (auto r = dynamic_cast<ast::reference const*>(arg)) {
			if (auto var = find(r->name)) {
				var->used = true;
			}
		}
	}
	return addr;
}

blitz::compiler::value blitz::compiler::gen_call(ast::call const* node)
{
	auto key = lower(node->name);
	if (find_dim(key)) {
		auto addr   = gen_dim_address(node);
		auto loaded = load_address(addr);
		loaded.need = addr.need;
		return loaded;
	}

	// Functions in the program take priority over built-in ones.
	auto it = _functions.find(key);
	if (it == _functions.end()) {
		bool handled;
		auto result = gen_builtin(node, handled);
		if (handled) {
			return result;
		}
		result = gen_userlib(node, handled);
		if (handled) {
			return result;
		}
		// Keep going, so that every missing function is found in one go. Generate() reports them.
		_unknown.emplace(key, std::make_pair(node->name, node->where));
		return { "0", type::INT32 };
	}

	_called.insert(key);
	auto const& fn = *it->second.declaration;
	size_t      required = 0;
	for (auto const& p : fn.parameters) {
		if (!p.initial) {
			required = &p - fn.parameters.data() + 1;
		}
	}
	if ((node->arguments.size() < required) || (node->arguments.size() > fn.parameters.size())) {
		throw err(node->where, "Function '" + fn.name + "' expects " + std::to_string(required) + " to " + std::to_string(fn.parameters.size()) + " arguments, got " + std::to_string(node->arguments.size()) + ".");
	}

	// The original evaluates the arguments in the order of the registers they need, which is not left to right.
	std::vector<operand> operands;
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		auto const& param = fn.parameters[idx];
		if (param.mode != ast::direction::IN) {
			// Out and InOut take the address of a variable, or nothing if the argument was left out.
			operand o;
			if (idx < node->arguments.size()) {
				o.code = capture_code([&] {
					auto addr = gen_reference_argument(node, idx, param, fn);
					o.v       = value{ addr.pointer, param.type, lower(param.struct_name) };
					o.v.need  = addr.need;
				});
			} else {
				o.v = value{ "null", type::STRUCT };
			}
			operands.push_back(std::move(o));
			continue;
		}
		operands.push_back((idx < node->arguments.size()) ? capture(node->arguments[idx].get()) : capture(param.initial.get()));
	}
	int  chain = place_sequence(operands);
	std::string list;
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		auto const& param = fn.parameters[idx];
		value       v;
		if (param.mode != ast::direction::IN) {
			list += (idx ? ", " : "") + std::string("ptr ") + operands[idx].v.repr;
			continue;
		}
		if (idx < node->arguments.size()) {
			v = convert(operands[idx].v, param.type, node->arguments[idx]->where, true, param.struct_name, &node->arguments[idx]->covers);
		} else {
			v = convert(operands[idx].v, param.type, param.where, true, param.struct_name);
		}
		list += (idx ? ", " : "") + blitz::types::to_llvm(param.type) + " " + v.repr;
	}

	auto ret = fn.type;
	if (fn.is_void) {
		emit("call void " + it->second.symbol + "(" + list + ")");
		value none{ "", type::UNKNOWN };
		none.need = chain;
		return none;
	}
	auto r   = tmp();
	emit(r + " = call " + blitz::types::to_llvm(ret) + " " + it->second.symbol + "(" + list + ")");
	if (ret == type::STRING) {
		_string_temps++; // The function returns it as a temporary of this statement.
		_uses_strings = true;
	}
	value result{ r, ret, lower(fn.struct_name) };
	result.need = chain;
	return result;
}

blitz::compiler::value blitz::compiler::gen_unary(ast::unary const* node)
{
	namespace t = blitz::types;
	auto v      = gen(node->operand.get());

	if (node->kind == ast::unary::op::NOT) {
		if (v.type == type::STRING) {
			// Not x is x = 0 in Blitz, which compares a string with "0" as text.
			return from_bool(compare(ast::binary::op::EQUAL, v, { "0", type::INT32 }, node->where));
		}
		std::string cond;
		if (blitz::types::is_real(v.type)) {
			// Not x is x = 0 in Blitz, which compares a real with 0 as a real.
			cond = tmp();
			emit(cond + " = fcmp une " + t::to_llvm(v.type) + " " + v.repr + ", 0.0");
		} else {
			cond = truthy(v, node->where);
		}
		auto r = tmp();
		emit(r + " = xor i1 " + cond + ", true");
		return from_bool(r);
	}

	if (!is_number(v.type)) {
		throw err(node->where, "Operation requires a number.");
	}
	auto promoted = common_type(v.type, v.type, node->where);
	v             = convert(v, promoted, node->where, false);
	auto llvm     = t::to_llvm(promoted);
	auto r        = tmp();

	switch (node->kind) {
	case ast::unary::op::PLUS:
		return v;
	case ast::unary::op::NEGATE:
		if (t::is_real(promoted)) {
			emit(r + " = fneg " + (fast_math.empty() ? std::string() : fast_math + " ") + llvm + " " + v.repr);
		} else {
			emit(r + " = sub " + llvm + " 0, " + v.repr);
		}
		return { r, promoted };
	default: // COMPLEMENT
		if (!t::is_integer(promoted)) {
			throw err(node->where, "Operation requires an integer.");
		}
		emit(r + " = xor " + llvm + " " + v.repr + ", -1");
		return { r, promoted };
	}
}

// Returns an i1 operand.
std::string blitz::compiler::compare(ast::binary::op kind, value lhs, value rhs, ast::location const& where)
{
	using op = ast::binary::op;
	std::string pred_s, pred_u, pred_f;
	switch (kind) {
	case op::EQUAL:
		pred_s = pred_u = "eq";
		pred_f          = "oeq";
		break;
	case op::NOT_EQUAL:
		pred_s = pred_u = "ne";
		pred_f          = "une";
		break;
	case op::LESS:
		pred_s = "slt", pred_u = "ult", pred_f = "olt";
		break;
	case op::LESS_EQUAL:
		pred_s = "sle", pred_u = "ule", pred_f = "ole";
		break;
	case op::GREATER:
		pred_s = "sgt", pred_u = "ugt", pred_f = "ogt";
		break;
	default:
		pred_s = "sge", pred_u = "uge", pred_f = "oge";
		break;
	}

	auto r = tmp();
	if ((lhs.type == type::STRUCT) || (rhs.type == type::STRUCT)) {
		if ((lhs.type != type::STRUCT) || (rhs.type != type::STRUCT)) {
			throw err(where, "Objects can only be compared with objects and Null.");
		}
		if (!lhs.sname.empty() && !rhs.sname.empty() && (lhs.sname != rhs.sname)) {
			throw err(where, "Type mismatch: '" + lhs.sname + "' can't be compared with '" + rhs.sname + "'.");
		}
		if ((kind != op::EQUAL) && (kind != op::NOT_EQUAL)) {
			throw err(where, "Objects can only be checked for being equal or not.");
		}
		emit(r + " = icmp " + pred_s + " ptr " + lhs.repr + ", " + rhs.repr);
		return r;
	}
	if ((lhs.type == type::STRING) || (rhs.type == type::STRING)) {
		auto a   = convert(lhs, type::STRING, where, false);
		auto b   = convert(rhs, type::STRING, where, false);
		auto cmp = call_runtime("bb_str_cmp", type::INT32, { a, b });
		emit(r + " = icmp " + pred_s + " i32 " + cmp.repr + ", 0");
		return r;
	}

	auto t = common_type(lhs.type, rhs.type, where);
	auto a = convert(lhs, t, where, false);
	auto b = convert(rhs, t, where, false);
	if (blitz::types::is_real(t)) {
		emit(r + " = fcmp " + (fast_math.empty() ? std::string() : fast_math + " ") + pred_f + " " + blitz::types::to_llvm(t) + " " + a.repr + ", " + b.repr);
	} else {
		emit(r + " = icmp " + (blitz::types::is_signed(t) ? pred_s : pred_u) + " " + blitz::types::to_llvm(t) + " " + a.repr + ", " + b.repr);
	}
	return r;
}

blitz::compiler::value blitz::compiler::gen_binary(ast::binary const* node)
{
	using op    = ast::binary::op;
	namespace t = blitz::types;

	auto l = capture(node->lhs.get());
	auto r = capture(node->rhs.get());
	bool rhs_first;
	int  need;
	plan_binary(node, l, r, rhs_first, need);
	place(rhs_first ? r.code : l.code);
	place(rhs_first ? l.code : r.code);
	auto result = gen_binary_values(node, l.v, r.v);
	result.need = need;
	return result;
}

blitz::compiler::value blitz::compiler::gen_binary_values(ast::binary const* node, value lhs, value rhs)
{
	using op    = ast::binary::op;
	namespace t = blitz::types;

	if ((lhs.type == type::UNKNOWN) || (rhs.type == type::UNKNOWN)) {
		throw err(node->where, "Expression does not return a value.");
	}

	if (node->kind >= op::EQUAL) {
		return from_bool(compare(node->kind, lhs, rhs, node->where));
	}

	// Strings can be added to each other, and to numbers. The bitwise operators below take them as integers.
	bool bitwise = (node->kind == op::AND) || (node->kind == op::OR) || (node->kind == op::XOR) || (node->kind == op::SHL) || (node->kind == op::SHR) || (node->kind == op::SAR);
	if (!bitwise && ((lhs.type == type::STRING) || (rhs.type == type::STRING))) {
		if (node->kind != op::ADD) {
			throw err(node->where, "Strings only support adding and comparing.");
		}
		auto a = convert(lhs, type::STRING, node->where, false);
		auto b = convert(rhs, type::STRING, node->where, false);
		return call_runtime("bb_str_concat", type::STRING, { a, b });
	}

	if (node->kind == op::POWER) {
		auto result = (lhs.type == type::FLOAT64 || rhs.type == type::FLOAT64) ? type::FLOAT64 : type::FLOAT32;
		auto a      = convert(lhs, type::FLOAT64, node->where, false);
		auto b      = convert(rhs, type::FLOAT64, node->where, false);
		declare("llvm.pow.f64", "declare double @llvm.pow.f64(double, double)");
		auto r = tmp();
		emit(r + " = call " + (fast_math.empty() ? std::string() : fast_math + " ") + "double @llvm.pow.f64(double " + a.repr + ", double " + b.repr + ")");
		return convert({ r, type::FLOAT64 }, result, node->where, false);
	}

	// Bitwise and logical operators work on integers only. Reals are truncated.
	if ((node->kind == op::AND) || (node->kind == op::OR) || (node->kind == op::XOR) || (node->kind == op::SHL) || (node->kind == op::SHR) || (node->kind == op::SAR)) {
		if (t::is_real(lhs.type) || (lhs.type == type::STRING)) {
			lhs = convert(lhs, type::INT32, node->where, false);
		}
		if (t::is_real(rhs.type) || (rhs.type == type::STRING)) {
			rhs = convert(rhs, type::INT32, node->where, false);
		}
		auto result = common_type(lhs.type, rhs.type, node->where);
		if ((node->kind == op::SHL) || (node->kind == op::SHR) || (node->kind == op::SAR)) {
			result = common_type(lhs.type, lhs.type, node->where);
		}
		auto a = convert(lhs, result, node->where, false);
		auto b = convert(rhs, result, node->where, false);
		if ((node->kind == op::SHL) || (node->kind == op::SHR) || (node->kind == op::SAR)) {
			// The processor only looks at the lowest bits of the count, so 1 Shl 32 is 1. LLVM makes a count that is too large undefined.
			auto masked = tmp();
			emit(masked + " = and " + t::to_llvm(result) + " " + b.repr + ", " + std::to_string(t::bits(result) - 1));
			b = { masked, result };
		}
		const char* name;
		switch (node->kind) {
		case op::AND:
			name = "and";
			break;
		case op::OR:
			name = "or";
			break;
		case op::XOR:
			name = "xor";
			break;
		case op::SHL:
			name = "shl";
			break;
		case op::SHR:
			name = "lshr";
			break;
		default:
			name = "ashr";
			break;
		}
		auto r = tmp();
		emit(r + " = " + name + " " + t::to_llvm(result) + " " + a.repr + ", " + b.repr);
		return { r, result };
	}

	auto result = common_type(lhs.type, rhs.type, node->where);
	auto a      = convert(lhs, result, node->where, false);
	auto b      = convert(rhs, result, node->where, false);
	auto llvm   = t::to_llvm(result);
	bool real   = t::is_real(result);
	bool sign   = t::is_signed(result);

	const char* name;
	switch (node->kind) {
	case op::ADD:
		name = real ? "fadd" : "add";
		break;
	case op::SUBTRACT:
		name = real ? "fsub" : "sub";
		break;
	case op::MULTIPLY:
		name = real ? "fmul" : "mul";
		break;
	case op::DIVIDE:
		name = real ? "fdiv" : (sign ? "sdiv" : "udiv");
		break;
	default:
		name = real ? "frem" : (sign ? "srem" : "urem");
		break;
	}

	if (((node->kind == op::DIVIDE) || (node->kind == op::MODULO)) && (is_zero_constant(rhs.repr) || (rhs.repr == "0x0000000000000000") || (rhs.repr == "0x8000000000000000"))) {
		// The original refuses to compile a division by a constant zero.
		throw err(node->where, "Division by zero.");
	}
	if (!real && ((node->kind == op::DIVIDE) || (node->kind == op::MODULO)) && !is_nonzero_constant(b.repr)) {
		// Dividing by zero is undefined in LLVM, but a runtime error in Blitz.
		auto zero_b = tmp();
		emit(zero_b + " = icmp eq " + llvm + " " + b.repr + ", 0");
		guard(zero_b, "Integer divide by zero");
	}

	auto r = tmp();
	emit(r + " = " + name + (real && !fast_math.empty() ? " " + fast_math : std::string()) + " " + llvm + " " + a.repr + ", " + b.repr);
	return { r, result };
}
