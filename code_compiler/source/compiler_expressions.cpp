blitz::compiler::value blitz::compiler::gen(ast::expression const* expr)
{
	if (auto n = dynamic_cast<ast::literal const*>(expr)) {
		return gen_literal(n);
	} else if (auto n = dynamic_cast<ast::reference const*>(expr)) {
		return gen_reference(n);
	} else if (auto n = dynamic_cast<ast::call const*>(expr)) {
		return gen_call(n);
	} else if (auto n = dynamic_cast<ast::unary const*>(expr)) {
		return gen_unary(n);
	} else if (auto n = dynamic_cast<ast::binary const*>(expr)) {
		return gen_binary(n);
	} else if (auto n = dynamic_cast<ast::field_access const*>(expr)) {
		return gen_field(n);
	} else if (auto n = dynamic_cast<ast::index_access const*>(expr)) {
		return gen_index(n);
	} else if (auto n = dynamic_cast<ast::new_object const*>(expr)) {
		return gen_new(n);
	} else if (auto n = dynamic_cast<ast::list_end const*>(expr)) {
		return gen_list_end(n);
	} else if (auto n = dynamic_cast<ast::list_neighbor const*>(expr)) {
		return gen_neighbor(n);
	} else if (auto n = dynamic_cast<ast::object_from_handle const*>(expr)) {
		return gen_from_handle(n);
	}
	throw err(expr->where, "Unsupported expression.");
}

blitz::compiler::value blitz::compiler::gen_literal(ast::literal const* node)
{
	switch (node->kind) {
	case ast::literal::variant::STRING:
		return { string_constant(node->text), type::STRING };
	case ast::literal::variant::NULLPTR:
		return { "null", type::STRUCT, "" };
	case ast::literal::variant::REAL:
		return constant(type::FLOAT32, node->f);
	case ast::literal::variant::UNSIGNED_INTEGER:
		if (node->u > UINT32_MAX) {
			return { std::to_string((long long)(int64_t)node->u), type::UINT64 };
		}
		return { std::to_string((int32_t)(uint32_t)node->u), type::UINT32 };
	default:
		if ((node->i > INT32_MAX) || (node->i < INT32_MIN)) {
			return { std::to_string((long long)node->i), type::INT64 };
		}
		return { std::to_string((long long)node->i), type::INT32 };
	}
}

blitz::compiler::value blitz::compiler::gen_reference(ast::reference const* node)
{
	if (auto var = find(node->name)) {
		if (var->dims || var->count) {
			throw err(node->where, "'" + node->name + "' is an array, it needs an index.");
		}
		auto r = tmp();
		emit(r + " = load " + blitz::types::to_llvm(var->type) + ", ptr " + var->pointer);
		return { r, var->type, var->sname };
	}

	// Not a variable: a function can be called without parenthesis.
	auto key = lower(node->name);
	if (_functions.count(key) || find_builtin(key) || (key == "int") || (key == "float") || (key == "str")) {
		ast::call fake;
		fake.where = node->where;
		fake.name  = node->name;
		fake.type  = node->type;
		return gen_call(&fake);
	}
	if (key == "pi") {
		return constant(type::FLOAT32, 3.14159265358979323846);
	}

	// Automatically declare the variable.
	create_local(node->name, (node->type == type::UNKNOWN) ? type::INT32 : node->type, false, node->where, node->struct_name);
	return gen_reference(node);
}

blitz::compiler::value blitz::compiler::gen_builtin(ast::call const* node, bool& handled)
{
	handled   = true;
	auto key  = lower(node->name);
	auto args = node->arguments.size();

	auto need = [&](size_t min, size_t max) {
		if ((args < min) || (args > max)) {
			throw err(node->where, "Function '" + node->name + "' expects " + (min == max ? std::to_string(min) : std::to_string(min) + " to " + std::to_string(max)) + " arguments, got " + std::to_string(args) + ".");
		}
	};

	if (key == "handle") {
		need(1, 1);
		auto object = gen(node->arguments[0].get());
		if (object.type != type::STRUCT) {
			throw err(node->where, "Handle needs an object.");
		}
		return call_runtime("bb_handle", type::INT32, { object });
	} else if (key == "int") {
		need(1, 1);
		return convert(gen(node->arguments[0].get()), type::INT32, node->where, false);
	} else if (key == "float") {
		need(1, 1);
		return convert(gen(node->arguments[0].get()), type::FLOAT32, node->where, false);
	} else if (key == "str") {
		need(1, 1);
		return convert(gen(node->arguments[0].get()), type::STRING, node->where, false);
	} else if ((key == "abs") || (key == "sgn")) {
		need(1, 1);
		auto v = gen(node->arguments[0].get());
		auto t = common_type(v.type, v.type, node->where);
		v      = convert(v, t, node->where, false);
		auto llvm = blitz::types::to_llvm(t);
		bool real = blitz::types::is_real(t);
		auto zero_v = zero(t);
		auto one    = constant(t, 1), minus_one = constant(t, -1);
		if (key == "abs") {
			auto neg = tmp(), is_neg = tmp(), r = tmp();
			emit(is_neg + (real ? " = fcmp olt " : " = icmp slt ") + llvm + " " + v.repr + ", " + zero_v.repr);
			emit(neg + (real ? " = fneg " : " = sub ") + llvm + (real ? " " : " 0, ") + v.repr);
			emit(r + " = select i1 " + is_neg + ", " + llvm + " " + neg + ", " + llvm + " " + v.repr);
			return { r, t };
		}
		auto gt = tmp(), lt = tmp(), s1 = tmp(), r = tmp();
		emit(gt + (real ? " = fcmp ogt " : " = icmp sgt ") + llvm + " " + v.repr + ", " + zero_v.repr);
		emit(lt + (real ? " = fcmp olt " : " = icmp slt ") + llvm + " " + v.repr + ", " + zero_v.repr);
		emit(s1 + " = select i1 " + lt + ", " + llvm + " " + minus_one.repr + ", " + llvm + " " + zero_v.repr);
		emit(r + " = select i1 " + gt + ", " + llvm + " " + one.repr + ", " + llvm + " " + s1);
		return { r, t };
	} else if ((key == "min") || (key == "max")) {
		need(2, 8);
		auto acc = gen(node->arguments[0].get());
		for (size_t idx = 1; idx < args; idx++) {
			auto next = gen(node->arguments[idx].get());
			auto t    = common_type(acc.type, next.type, node->where);
			acc       = convert(acc, t, node->where, false);
			next      = convert(next, t, node->where, false);
			auto pick = compare((key == "min") ? ast::binary::op::LESS : ast::binary::op::GREATER, acc, next, node->where);
			auto r    = tmp();
			auto llvm = blitz::types::to_llvm(t);
			emit(r + " = select i1 " + pick + ", " + llvm + " " + acc.repr + ", " + llvm + " " + next.repr);
			acc = { r, t };
		}
		return acc;
	}

	auto entry = find_builtin(key);
	if (!entry) {
		handled = false;
		return {};
	}

	size_t total = strlen(entry->params);
	need(size_t(entry->required), total);

	// Figure out which parameters the provided arguments belong to.
	std::vector<value> values(total);
	std::vector<bool>  given(total, false);
	size_t             offset = (entry->lead && (args == 1) && (total == 2)) ? 1 : 0;
	for (size_t idx = 0; idx < args; idx++) {
		auto want = builtin_type(entry->params[idx + offset]);
		// Anything can be turned into a string without it being surprising, so only warn for the other direction.
		values[idx + offset] = convert(gen(node->arguments[idx].get()), want, node->arguments[idx]->where, want != type::STRING);
		given[idx + offset]  = true;
	}
	for (size_t idx = 0; idx < total; idx++) {
		if (!given[idx]) {
			auto want = builtin_type(entry->params[idx]);
			values[idx] = (want == type::STRING) ? zero(want) : constant(want, entry->defaults[idx]);
		}
	}
	return call_runtime(entry->symbol, builtin_type(entry->ret), values);
}

blitz::compiler::value blitz::compiler::gen_call(ast::call const* node)
{
	auto key = lower(node->name);
	if (find_dim(key)) {
		return load_address(gen_dim_address(node));
	}

	// Functions in the program take priority over built-in ones.
	auto it = _functions.find(key);
	if (it == _functions.end()) {
		bool handled;
		auto result = gen_builtin(node, handled);
		if (handled) {
			return result;
		}
		// Keep going, so that every missing function is found in one go. Generate() reports them.
		_unknown.emplace(key, std::make_pair(node->name, node->where));
		return { "0", type::INT32 };
	}

	auto const& fn = *it->second.declaration;
	size_t      required = 0;
	for (auto const& p : fn.parameters) {
		if (!p.initial) {
			required = &p - fn.parameters.data() + 1;
		}
	}
	if ((node->arguments.size() < required) || (node->arguments.size() > fn.parameters.size())) {
		throw err(node->where, "Function '" + fn.name + "' expects " + std::to_string(required) + " to " + std::to_string(fn.parameters.size()) + " arguments, got " + std::to_string(node->arguments.size()) + ".");
	}

	std::string list;
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		auto const& param = fn.parameters[idx];
		value       v;
		if (idx < node->arguments.size()) {
			v = convert(gen(node->arguments[idx].get()), param.type, node->arguments[idx]->where, true, param.struct_name);
		} else {
			v = convert(gen(param.initial.get()), param.type, param.where, true, param.struct_name);
		}
		list += (idx ? ", " : "") + blitz::types::to_llvm(param.type) + " " + v.repr;
	}

	auto ret = fn.type;
	auto r   = tmp();
	emit(r + " = call " + blitz::types::to_llvm(ret) + " " + it->second.symbol + "(" + list + ")");
	if (ret == type::STRING) {
		_string_temps++; // The function returns it as a temporary of this statement.
		_uses_strings = true;
	}
	return { r, ret, lower(fn.struct_name) };
}

blitz::compiler::value blitz::compiler::gen_unary(ast::unary const* node)
{
	namespace t = blitz::types;
	auto v      = gen(node->operand.get());

	if (node->kind == ast::unary::op::NOT) {
		auto cond = truthy(v, node->where);
		auto r    = tmp();
		emit(r + " = xor i1 " + cond + ", true");
		return from_bool(r);
	}

	if (!is_number(v.type)) {
		throw err(node->where, "Operation requires a number.");
	}
	auto promoted = common_type(v.type, v.type, node->where);
	v             = convert(v, promoted, node->where, false);
	auto llvm     = t::to_llvm(promoted);
	auto r        = tmp();

	switch (node->kind) {
	case ast::unary::op::PLUS:
		return v;
	case ast::unary::op::NEGATE:
		if (t::is_real(promoted)) {
			emit(r + " = fneg " + llvm + " " + v.repr);
		} else {
			emit(r + " = sub " + llvm + " 0, " + v.repr);
		}
		return { r, promoted };
	default: // COMPLEMENT
		if (!t::is_integer(promoted)) {
			throw err(node->where, "Operation requires an integer.");
		}
		emit(r + " = xor " + llvm + " " + v.repr + ", -1");
		return { r, promoted };
	}
}

// Returns an i1 operand.
std::string blitz::compiler::compare(ast::binary::op kind, value lhs, value rhs, ast::location const& where)
{
	using op = ast::binary::op;
	std::string pred_s, pred_u, pred_f;
	switch (kind) {
	case op::EQUAL:
		pred_s = pred_u = "eq";
		pred_f          = "oeq";
		break;
	case op::NOT_EQUAL:
		pred_s = pred_u = "ne";
		pred_f          = "une";
		break;
	case op::LESS:
		pred_s = "slt", pred_u = "ult", pred_f = "olt";
		break;
	case op::LESS_EQUAL:
		pred_s = "sle", pred_u = "ule", pred_f = "ole";
		break;
	case op::GREATER:
		pred_s = "sgt", pred_u = "ugt", pred_f = "ogt";
		break;
	default:
		pred_s = "sge", pred_u = "uge", pred_f = "oge";
		break;
	}

	auto r = tmp();
	if ((lhs.type == type::STRUCT) || (rhs.type == type::STRUCT)) {
		if ((lhs.type != type::STRUCT) || (rhs.type != type::STRUCT)) {
			throw err(where, "Objects can only be compared with objects and Null.");
		}
		if (!lhs.sname.empty() && !rhs.sname.empty() && (lhs.sname != rhs.sname)) {
			throw err(where, "Type mismatch: '" + lhs.sname + "' can't be compared with '" + rhs.sname + "'.");
		}
		if ((kind != op::EQUAL) && (kind != op::NOT_EQUAL)) {
			throw err(where, "Objects can only be checked for being equal or not.");
		}
		emit(r + " = icmp " + pred_s + " ptr " + lhs.repr + ", " + rhs.repr);
		return r;
	}
	if ((lhs.type == type::STRING) || (rhs.type == type::STRING)) {
		auto a   = convert(lhs, type::STRING, where, false);
		auto b   = convert(rhs, type::STRING, where, false);
		auto cmp = call_runtime("bb_str_cmp", type::INT32, { a, b });
		emit(r + " = icmp " + pred_s + " i32 " + cmp.repr + ", 0");
		return r;
	}

	auto t = common_type(lhs.type, rhs.type, where);
	auto a = convert(lhs, t, where, false);
	auto b = convert(rhs, t, where, false);
	if (blitz::types::is_real(t)) {
		emit(r + " = fcmp " + pred_f + " " + blitz::types::to_llvm(t) + " " + a.repr + ", " + b.repr);
	} else {
		emit(r + " = icmp " + (blitz::types::is_signed(t) ? pred_s : pred_u) + " " + blitz::types::to_llvm(t) + " " + a.repr + ", " + b.repr);
	}
	return r;
}

blitz::compiler::value blitz::compiler::gen_binary(ast::binary const* node)
{
	using op    = ast::binary::op;
	namespace t = blitz::types;

	auto lhs = gen(node->lhs.get());
	auto rhs = gen(node->rhs.get());
	if ((lhs.type == type::UNKNOWN) || (rhs.type == type::UNKNOWN)) {
		throw err(node->where, "Expression does not return a value.");
	}

	if (node->kind >= op::EQUAL) {
		return from_bool(compare(node->kind, lhs, rhs, node->where));
	}

	// Strings can be added to each other, and to numbers.
	if ((lhs.type == type::STRING) || (rhs.type == type::STRING)) {
		if (node->kind != op::ADD) {
			throw err(node->where, "Strings only support adding and comparing.");
		}
		auto a = convert(lhs, type::STRING, node->where, false);
		auto b = convert(rhs, type::STRING, node->where, false);
		return call_runtime("bb_str_concat", type::STRING, { a, b });
	}

	if (node->kind == op::POWER) {
		auto result = (lhs.type == type::FLOAT64 || rhs.type == type::FLOAT64) ? type::FLOAT64 : type::FLOAT32;
		auto a      = convert(lhs, type::FLOAT64, node->where, false);
		auto b      = convert(rhs, type::FLOAT64, node->where, false);
		declare("llvm.pow.f64", "declare double @llvm.pow.f64(double, double)");
		auto r = tmp();
		emit(r + " = call double @llvm.pow.f64(double " + a.repr + ", double " + b.repr + ")");
		return convert({ r, type::FLOAT64 }, result, node->where, false);
	}

	// Bitwise and logical operators work on integers only. Reals are truncated.
	if ((node->kind == op::AND) || (node->kind == op::OR) || (node->kind == op::XOR) || (node->kind == op::SHL) || (node->kind == op::SHR) || (node->kind == op::SAR)) {
		if (t::is_real(lhs.type)) {
			lhs = convert(lhs, type::INT32, node->where, false);
		}
		if (t::is_real(rhs.type)) {
			rhs = convert(rhs, type::INT32, node->where, false);
		}
		auto result = common_type(lhs.type, rhs.type, node->where);
		if ((node->kind == op::SHL) || (node->kind == op::SHR) || (node->kind == op::SAR)) {
			result = common_type(lhs.type, lhs.type, node->where);
		}
		auto a = convert(lhs, result, node->where, false);
		auto b = convert(rhs, result, node->where, false);
		const char* name;
		switch (node->kind) {
		case op::AND:
			name = "and";
			break;
		case op::OR:
			name = "or";
			break;
		case op::XOR:
			name = "xor";
			break;
		case op::SHL:
			name = "shl";
			break;
		case op::SHR:
			name = "lshr";
			break;
		default:
			name = "ashr";
			break;
		}
		auto r = tmp();
		emit(r + " = " + name + " " + t::to_llvm(result) + " " + a.repr + ", " + b.repr);
		return { r, result };
	}

	auto result = common_type(lhs.type, rhs.type, node->where);
	auto a      = convert(lhs, result, node->where, false);
	auto b      = convert(rhs, result, node->where, false);
	auto llvm   = t::to_llvm(result);
	bool real   = t::is_real(result);
	bool sign   = t::is_signed(result);

	const char* name;
	switch (node->kind) {
	case op::ADD:
		name = real ? "fadd" : "add";
		break;
	case op::SUBTRACT:
		name = real ? "fsub" : "sub";
		break;
	case op::MULTIPLY:
		name = real ? "fmul" : "mul";
		break;
	case op::DIVIDE:
		name = real ? "fdiv" : (sign ? "sdiv" : "udiv");
		break;
	default:
		name = real ? "frem" : (sign ? "srem" : "urem");
		break;
	}

	if (!real && ((node->kind == op::DIVIDE) || (node->kind == op::MODULO)) && !is_nonzero_constant(b.repr)) {
		// Dividing by zero is undefined in LLVM, but a runtime error in Blitz.
		auto wide = convert(b, type::INT64, node->where, false);
		call_runtime("bb_check_div", type::UNKNOWN, { wide });
	}

	auto r = tmp();
	emit(r + " = " + name + " " + llvm + " " + a.repr + ", " + b.repr);
	return { r, result };
}
