namespace {
	// Same tokens as the original: Identifiers, quoted strings, and everything else as itself.
	struct decls_reader {
		std::string text;
		size_t      pos = 0;
		int         curr = 0; // 0 = end, -1 = identifier, -2 = string, otherwise the character.
		std::string word;

		int next()
		{
			word.clear();
			for (;;) {
				while (pos < text.size() && isspace((unsigned char)text[pos])) {
					pos++;
				}
				if (pos >= text.size()) {
					return curr = 0;
				}
				if (text[pos] != ';') {
					break;
				}
				while (pos < text.size() && text[pos] != '\n') {
					pos++;
				}
			}
			unsigned char c = (unsigned char)text[pos++];
			if (isalpha(c)) {
				word += char(c);
				while (pos < text.size() && (isalnum((unsigned char)text[pos]) || text[pos] == '_')) {
					word += text[pos++];
				}
				return curr = -1;
			}
			if (c == '"') {
				while (pos < text.size() && text[pos] != '"') {
					word += text[pos++];
				}
				pos++;
				return curr = -2;
			}
			return curr = c;
		}
	};

	char type_of(int c)
	{
		switch (c) {
		case '%':
			return 'i';
		case '#':
			return 'f';
		case '$':
			return 's';
		case '*':
			return 'p';
		}
		return 0;
	}

	void load_userlib(std::filesystem::path const& file, std::set<std::string>& seen, std::vector<blitz::keywords::user_function>& into)
	{
		std::ifstream     in(file, std::ios_base::binary);
		std::stringstream buffer;
		buffer << in.rdbuf();
		decls_reader r{ buffer.str() };
		bool         have_lib = false;

		r.next();
		while (r.curr) {
			if (r.curr == '.') {
				if (r.next() != -1) {
					throw std::runtime_error("expecting identifier after '.'");
				}
				if (blitz::compiler_detail::lower(r.word) != "lib") {
					throw std::runtime_error("unknown decl directive");
				}
				if (r.next() != -2) {
					throw std::runtime_error("expecting string after lib directive");
				}
				have_lib = true;
				r.next();
			} else if (r.curr == -1) {
				if (!have_lib) {
					throw std::runtime_error("function decl without lib directive");
				}
				blitz::keywords::user_function fn;
				fn.name = r.word;
				if (!seen.insert(blitz::compiler_detail::lower(fn.name)).second) {
					throw std::runtime_error("duplicate identifier");
				}

				char ret = type_of(r.next());
				if (ret && ret != 'p') {
					r.next();
					fn.ret = ret;
				}
				if (r.curr != '(') {
					throw std::runtime_error("expecting '(' after function identifier");
				}
				r.next();
				while (r.curr == -1) {
					std::string arg  = r.word;
					char        type = type_of(r.next());
					if (type) {
						r.next();
					} else {
						type = 'i';
					}
					fn.params.emplace_back(arg, type);
					if (r.curr != ',') {
						break;
					}
					r.next();
				}
				if (r.curr != ')') {
					throw std::runtime_error("expecting ')' after function decl");
				}
				if (r.next() == ':') { // Real name of the function in the library.
					r.next();
					if (r.curr != -1 && r.curr != -2) {
						throw std::runtime_error("expecting identifier or string after alias");
					}
					r.next();
				}
				into.push_back(std::move(fn));
			} else {
				throw std::runtime_error("unexpected character");
			}
		}
	}

	// Name, then the syntax the way the original quick help does: 'Name$ ( a,[b$] )' for functions that return something,
	// 'Name a,b' for the ones that don't. Parameters with a default value are in brackets.
	std::string syntax_of(std::string name, char ret, std::vector<std::pair<std::string, char>> const& params, size_t required)
	{
		if (ret == 'f') {
			name += '#';
		} else if (ret == 's') {
			name += '$';
		}
		std::string list;
		for (size_t idx = 0; idx < params.size(); idx++) {
			std::string param = params[idx].first;
			switch (params[idx].second) {
			case 'f':
				param += '#';
				break;
			case 's':
				param += '$';
				break;
			case 'p':
				param += '*';
				break;
			}
			if (idx >= required) {
				param = "[" + param + "]";
			}
			list += (idx ? "," : "") + param;
		}
		if (ret != 'v') {
			return name + " ( " + list + (list.empty() ? ")" : " )");
		}
		return list.empty() ? name : name + " " + list;
	}
} // namespace

std::vector<std::string> blitz::keywords::language()
{
	std::vector<std::string> words{ "Dim", "Goto", "Gosub", "Return", "Exit", "If", "Then", "Else", "EndIf", "ElseIf", "While", "Wend", "For", "To", "Step", "Next", "Function", "Type", "Each", "Local", "Global", "Field", "Const", "Select", "Case", "Default", "Repeat", "Until", "Forever", "Data", "Read", "Restore", "Abs", "Sgn", "Mod", "Pi", "True", "False", "Int", "Float", "Str", "Include", "New", "Delete", "First", "Last", "Insert", "Before", "After", "Null", "Object", "Handle", "And", "Or", "Xor", "Not", "Shl", "Shr", "Sar" };
	std::sort(words.begin(), words.end());
	return words;
}

std::vector<blitz::keywords::user_function> blitz::keywords::load_userlibs(std::filesystem::path const& dir)
{
	std::vector<user_function> functions;
	std::error_code            ec;
	if (dir.empty() || !std::filesystem::is_directory(dir, ec)) {
		return functions;
	}

	std::vector<std::filesystem::path> files;
	for (auto const& entry : std::filesystem::directory_iterator(dir, ec)) {
		if (entry.is_regular_file() && (compiler_detail::lower(entry.path().extension().string()) == ".decls")) {
			files.push_back(entry.path());
		}
	}
	std::sort(files.begin(), files.end());

	std::set<std::string> seen;
	for (auto const& file : files) {
		try {
			load_userlib(file, seen, functions);
		} catch (std::runtime_error const& ex) {
			throw std::runtime_error("Error in userlib '" + file.filename().generic_string() + "' - " + ex.what());
		}
	}
	return functions;
}

void blitz::keywords::dump(std::ostream& out, bool syntax, std::filesystem::path const& userlibs)
{
	for (auto const& word : language()) {
		out << word << "\n";
	}

	for (auto const& entry : compiler_detail::builtins) {
		std::vector<std::pair<std::string, char>> params;
		for (size_t idx = 0; entry.params[idx]; idx++) {
			params.emplace_back("param" + std::to_string(idx + 1), entry.params[idx]);
		}
		out << (syntax ? syntax_of(entry.name, entry.ret, params, size_t(entry.required)) : std::string(entry.name)) << "\n";
	}

	for (auto const& fn : load_userlibs(userlibs)) {
		out << (syntax ? syntax_of(fn.name, fn.ret, fn.params, fn.params.size()) : fn.name) << "\n";
	}
	out.flush();
}
