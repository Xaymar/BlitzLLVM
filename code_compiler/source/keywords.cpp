std::vector<std::string> blitz::keywords::language()
{
	std::vector<std::string> words{ "Dim", "Goto", "Gosub", "Return", "Exit", "If", "Then", "Else", "EndIf", "EndSelect", "EndFunction", "ElseIf", "While", "Wend", "For", "To", "Step", "Next", "Function", "Type", "Each", "Local", "Global", "Field", "Const", "Select", "Case", "Default", "Repeat", "Until", "Forever", "Data", "Read", "Restore", "Abs", "Sgn", "Mod", "Pi", "True", "False", "Int", "Float", "Str", "Include", "New", "Delete", "First", "Last", "Insert", "Before", "After", "Null", "Object", "Handle", "And", "Or", "Xor", "Not", "Shl", "Shr", "Sar", "In", "Out", "InOut" };
	std::sort(words.begin(), words.end());
	return words;
}

std::vector<blitz::keywords::user_function> blitz::keywords::load_userlibs(std::filesystem::path const& dir)
{
	std::vector<user_function> functions;
	std::error_code            ec;
	if (dir.empty() || !std::filesystem::is_directory(dir, ec)) {
		return functions;
	}

	std::vector<std::filesystem::path> files;
	for (auto const& entry : std::filesystem::directory_iterator(dir, ec)) {
		if (entry.is_regular_file() && (compiler_detail::lower(entry.path().extension().string()) == ".decls")) {
			files.push_back(entry.path());
		}
	}
	std::sort(files.begin(), files.end());

	std::set<std::string> seen;
	for (auto const& file : files) {
		try {
			load_userlib(file, seen, functions);
		} catch (std::runtime_error const& ex) {
			throw std::runtime_error("Error in userlib '" + file.filename().generic_string() + "' - " + ex.what());
		}
	}
	return functions;
}

void blitz::keywords::dump(std::ostream& out, dump_mode mode, std::filesystem::path const& userlibs)
{
	for (auto const& word : language()) {
		out << word << "\n";
	}

	for (auto const& entry : compiler_detail::builtins) {
		std::vector<std::pair<std::string, char>> params;
		for (size_t idx = 0; entry.params[idx]; idx++) {
			params.emplace_back("param" + std::to_string(idx + 1), entry.params[idx]);
		}
		switch (mode) {
		case dump_mode::NAMES:
			out << entry.name;
			break;
		case dump_mode::BLITZ3D:
			out << syntax_of(entry.name, entry.ret, params, size_t(entry.required));
			break;
		case dump_mode::NATIVE:
			out << native_syntax_of(entry.name, entry.ret, params, size_t(entry.required), entry.defaults, entry.lead);
			break;
		}
		out << "\n";
	}

	for (auto const& fn : load_userlibs(userlibs)) {
		std::vector<std::pair<std::string, char>> params;
		for (auto const& param : fn.params) {
			params.emplace_back(param.name, param.pointer ? 'p' : blitz::compiler_detail::type_code(param.type));
		}
		switch (mode) {
		case dump_mode::NAMES:
			out << fn.name;
			break;
		case dump_mode::BLITZ3D:
			out << syntax_of(fn.name, blitz::compiler_detail::type_code(fn.ret), params, params.size());
			break;
		case dump_mode::NATIVE:
			out << native_syntax_of(fn.name, blitz::compiler_detail::type_code(fn.ret), params, params.size(), nullptr);
			break;
		}
		out << "\n";
	}
	out.flush();
}
