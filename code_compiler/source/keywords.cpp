	// Same tokens as the original: Identifiers, quoted strings, and everything else as itself.
	struct decls_reader {
		std::string text;
		size_t      pos = 0;
		int         curr = 0; // 0 = end, -1 = identifier, -2 = string, otherwise the character.
		std::string word;

		int next()
		{
			word.clear();
			for (;;) {
				while (pos < text.size() && isspace((unsigned char)text[pos])) {
					pos++;
				}
				if (pos >= text.size()) {
					return curr = 0;
				}
				if (text[pos] != ';') {
					break;
				}
				while (pos < text.size() && text[pos] != '\n') {
					pos++;
				}
			}
			unsigned char c = (unsigned char)text[pos++];
			if (isalpha(c)) {
				word += char(c);
				while (pos < text.size() && (isalnum((unsigned char)text[pos]) || text[pos] == '_')) {
					word += text[pos++];
				}
				return curr = -1;
			}
			if (c == '"') {
				while (pos < text.size() && text[pos] != '"') {
					word += text[pos++];
				}
				pos++;
				return curr = -2;
			}
			return curr = c;
		}
	};

	// The type that ends a name, in the short form (% %% # ## $ *) or the long form (:Type, with Pointer for '*'). Leaves the
	// reader on the token after it. Returns false if there is no type.
	bool read_type(decls_reader& r, blitz::types::type& type, bool& pointer, bool allow_void)
	{
		pointer = false;
		switch (r.curr) {
		case '%':
			type = (r.next() == '%') ? (r.next(), blitz::types::type::INT64) : blitz::types::type::INT32;
			return true;
		case '#':
			type = (r.next() == '#') ? (r.next(), blitz::types::type::FLOAT64) : blitz::types::type::FLOAT32;
			return true;
		case '$':
			r.next();
			type = blitz::types::type::STRING;
			return true;
		case '*':
			r.next();
			type    = blitz::types::type::STRUCT;
			pointer = true;
			return true;
		case ':': {
			if (r.next() != -1) {
				throw std::runtime_error("expecting type name after ':'");
			}
			auto name = blitz::compiler_detail::lower(r.word);
			r.next();
			if ((name == "pointer") || (name == "ptr")) {
				type    = blitz::types::type::STRUCT;
				pointer = true;
			} else if (allow_void && (name == "void")) {
				type = blitz::types::type::UNKNOWN;
			} else {
				type = blitz::types::from_string(name);
				if (type == blitz::types::type::UNKNOWN) {
					throw std::runtime_error("unknown type '" + name + "'");
				}
			}
			return true;
		}
		}
		return false;
	}

	void load_userlib(std::filesystem::path const& file, std::set<std::string>& seen, std::vector<blitz::keywords::user_function>& into)
	{
		std::ifstream     in(file, std::ios_base::binary);
		std::stringstream buffer;
		buffer << in.rdbuf();
		decls_reader r{ buffer.str() };
		bool         have_lib = false;
		std::string  lib;

		r.next();
		while (r.curr) {
			if (r.curr == '.') {
				if (r.next() != -1) {
					throw std::runtime_error("expecting identifier after '.'");
				}
				if (blitz::compiler_detail::lower(r.word) != "lib") {
					throw std::runtime_error("unknown decl directive");
				}
				if (r.next() != -2) {
					throw std::runtime_error("expecting string after lib directive");
				}
				have_lib = true;
				lib      = r.word;
				r.next();
			} else if (r.curr == -1) {
				if (!have_lib) {
					throw std::runtime_error("function decl without lib directive");
				}
				blitz::keywords::user_function fn;
				fn.name   = r.word;
				fn.lib    = lib;
				fn.symbol = r.word;
				if (!seen.insert(blitz::compiler_detail::lower(fn.name)).second) {
					throw std::runtime_error("duplicate identifier");
				}

				r.next();
				{
					blitz::types::type type;
					bool               pointer;
					if (read_type(r, type, pointer, true)) {
						if (pointer) {
							throw std::runtime_error("a function can't return a pointer");
						}
						fn.ret = type;
					}
				}
				if (r.curr != '(') {
					throw std::runtime_error("expecting '(' after function identifier");
				}
				r.next();
				while (r.curr == -1) {
					blitz::keywords::user_param param;
					param.name = r.word;
					r.next();
					read_type(r, param.type, param.pointer, false);
					fn.params.push_back(std::move(param));
					if (r.curr != ',') {
						break;
					}
					r.next();
				}
				if (r.curr != ')') {
					throw std::runtime_error("expecting ')' after function decl");
				}
				if (r.next() == ':') { // Real name of the function in the library.
					r.next();
					if (r.curr != -1 && r.curr != -2) {
						throw std::runtime_error("expecting identifier or string after alias");
					}
					fn.symbol = r.word;
					r.next();
				}
				into.push_back(std::move(fn));
			} else {
				throw std::runtime_error("unexpected character");
			}
		}
	}

	// How a type is written after a name, like the original does: % for every integer type, # for every float type, $ for
	// strings. Nothing for no type.
	std::string suffix_of(char code)
	{
		auto type = blitz::compiler_detail::builtin_type(code);
		if (blitz::types::is_integer(type)) {
			return "%";
		} else if (blitz::types::is_real(type)) {
			return "#";
		} else if (type == blitz::types::type::STRING) {
			return "$";
		}
		return "";
	}

	// Name and syntax byte for byte like the original quick help ('Name% ( a%,b#[,c$] )'), except for the types: Every
	// function has the '( )', and every parameter with a default value is in a bracket of its own, with its comma in it.
	std::string syntax_of(std::string name, char ret, std::vector<std::pair<std::string, char>> const& params, size_t required)
	{
		name += suffix_of(ret);
		std::string list;
		for (size_t idx = 0; idx < params.size(); idx++) {
			std::string param = (idx ? "," : "") + params[idx].first + (params[idx].second == 'p' ? std::string("*") : suffix_of(params[idx].second));
			list += (idx >= required) ? "[" + param + "]" : param;
		}
		return name + " ( " + list + (list.empty() ? ")" : " )");
	}

	// The type by its full name, as the wiki lists it, for the codes of the tables ('p' is the address of a bank or object).
	std::string native_type_of(char code)
	{
		if (code == 'p') {
			return "Pointer";
		}
		return blitz::types::long_name(blitz::compiler_detail::builtin_type(code));
	}

	std::string number_of(double value)
	{
		std::ostringstream out;
		out << value;
		return out.str();
	}

	// Name and syntax in the notation of the wiki ('Name:Int32 a:Int32, b:Float32=1'): The return type is behind the name unless
	// there is none, and a parameter with a default value has it behind an '='.
	std::string native_syntax_of(std::string name, char ret, std::vector<std::pair<std::string, char>> const& params, size_t required, double const* defaults, bool lead = false)
	{
		// With one argument for two parameters, the argument is the second one: Rand(10) is Rand(1, 10).
		bool first = lead && (params.size() == 2) && (required == 1);
		if (ret != 'v') {
			name += ":" + native_type_of(ret);
		}
		std::string list;
		for (size_t idx = 0; idx < params.size(); idx++) {
			list += (idx ? ", " : " ") + std::string(params[idx].second == 'X' ? "Out " : "") + params[idx].first + ":" + native_type_of(params[idx].second);
			if (first ? (idx == 0) : (idx >= required)) {
				list += "=" + ((params[idx].second == 's') ? std::string("\"\"") : number_of(defaults ? defaults[idx] : 0));
			}
		}
		return name + list;
	}
