bool blitz::compiler::fold_int(ast::expression const* expr, int64_t& out)
{
	if (auto l = dynamic_cast<ast::literal const*>(expr)) {
		if (l->kind == ast::literal::variant::INTEGER) {
			out = l->i;
			return true;
		} else if (l->kind == ast::literal::variant::UNSIGNED_INTEGER) {
			out = int64_t(l->u);
			return true;
		}
	} else if (auto r = dynamic_cast<ast::reference const*>(expr)) {
		auto key = lower(r->name);
		auto own = _locals.find(key);
		if ((own != _locals.end()) && !own->second.constant) {
			return false; // A Local of a function hides the Const of the same name.
		}
		auto it = _const_values.find(key);
		if (it != _const_values.end()) {
			out = it->second;
			return true;
		}
	} else if (auto u = dynamic_cast<ast::unary const*>(expr)) {
		int64_t v;
		if (fold_int(u->operand.get(), v)) {
			if (u->kind == ast::unary::op::NEGATE) {
				out = int64_t(0 - uint64_t(v)); // Wraps around, as the program does.
				return true;
			} else if (u->kind == ast::unary::op::PLUS) {
				out = v;
				return true;
			}
		}
	} else if (auto b = dynamic_cast<ast::binary const*>(expr)) {
		int64_t l, r;
		if (fold_int(b->lhs.get(), l) && fold_int(b->rhs.get(), r)) {
			switch (b->kind) {
			case ast::binary::op::ADD:
				out = int64_t(uint64_t(l) + uint64_t(r));
				return true;
			case ast::binary::op::SUBTRACT:
				out = int64_t(uint64_t(l) - uint64_t(r));
				return true;
			case ast::binary::op::MULTIPLY:
				out = int64_t(uint64_t(l) * uint64_t(r));
				return true;
			case ast::binary::op::DIVIDE:
				if (r != 0) {
					// The smallest number divided by -1 does not fit, it wraps around to itself.
					out = (r == -1) ? int64_t(0 - uint64_t(l)) : (l / r);
					return true;
				}
				break;
			default:
				break;
			}
		}
	}
	return false;
}

blitz::compiler::type_info& blitz::compiler::need_type(std::string const& name, ast::location const& where)
{
	auto it = _types.find(lower(name));
	if (it == _types.end()) {
		throw err(where, "Unknown type '" + name + "'.");
	}
	return it->second;
}

void blitz::compiler::register_types(ast::program const& program)
{
	// First make all types known, as fields can refer to types that are defined later.
	for (auto const& decl : program.types) {
		auto key = lower(decl->name);
		if (_types.count(key)) {
			throw err(decl->where, "Type '" + decl->name + "' has already been defined.");
		}
		type_info info;
		info.name = decl->name;
		info.llvm = "%bb.t" + std::to_string(_counter);
		info.list = "@bb.list" + std::to_string(_counter);
		_counter++;
		_types[key] = info;
	}

	for (auto const& decl : program.types) {
		auto&       info    = _types[lower(decl->name)];
		std::string members = "ptr, ptr, i32, i32"; // Next, previous, handle and flags: see bb_object in the runtime.
		uint32_t    index   = 4;
		for (auto const& f : decl->fields) {
			if (!f.typed) {
				warn_typeless(f.where, f.name, "Field ");
			}
			if (f.default_value && !field_defaults) {
				warn(f.default_where, "field-default-ignored", "The default value of field '" + f.name + "' is never used, New sets the field to 0, 0.0, \"\" or Null like in the original.", "Set the field after New instead, or build with --field-defaults to use the default values.");
			}
			for (auto const& other : info.fields) {
				if (lower(other.name) == lower(f.name)) {
					throw err(f.where, "'" + f.name + "' has already been declared as a field of '" + decl->name + "'.");
				}
			}
			field_info field;
			field.name  = f.name;
			field.type  = f.type;
			field.sname = lower(f.struct_name);
			field.count = 0;
			field.index = index++;
			field.default_value = field_defaults ? f.default_value.get() : nullptr;
			if ((f.type == type::STRUCT) && !_types.count(field.sname)) {
				throw err(f.where, "Unknown type '" + f.struct_name + "'.");
			}
			if (f.array_size) {
				int64_t size;
				if (!fold_int(f.array_size.get(), size) || (size < 0) || (size > 100000000)) {
					throw err(f.where, "The size of an array in a Type has to be a constant number.");
				}
				field.count = uint32_t(size) + 1; // Like Dim, the upper bound is included.
			}
			if (!f.shape.empty()) {
				if (f.array_size || (f.type == type::STRING) || (f.type == type::STRUCT)) {
					throw err(f.where, "The size of a vector or matrix can only be given for numbers.");
				}
				field.shape = f.shape;
			}
			members += ", " + (!field.shape.empty() ? "[" + std::to_string(shape_total(field.shape)) + " x " + blitz::types::to_llvm(f.type) + "]" : (field.count ? "[" + std::to_string(field.count) + " x " + blitz::types::to_llvm(f.type) + "]" : blitz::types::to_llvm(f.type)));
			info.fields.push_back(field);
		}
		_constants << info.llvm << " = type { " << members << " }\n";

		// Which fields are strings, so that deleting an object can free them.
		std::string entries;
		size_t      string_fields = 0;
		for (auto const& field : info.fields) {
			if (field.type == type::STRING) {
				entries += ", i32 ptrtoint (ptr getelementptr (" + info.llvm + ", ptr null, i32 0, i32 " + std::to_string(field.index) + ") to i32), i32 " + std::to_string(field.count);
				string_fields++;
			}
		}
		std::string descriptor = "null";
		if (string_fields) {
			descriptor = info.list + ".strings";
			_globals << descriptor << " = internal constant [" << (1 + 2 * string_fields) << " x i32] [i32 " << string_fields << entries << "]\n";
		}
		// Which fields hold objects, so that deleting an object lets go of them: the offset, the count and the list of the type.
		std::string object_entries;
		size_t      object_fields = 0;
		for (auto const& field : info.fields) {
			if (field.type == type::STRUCT) {
				object_entries += (object_fields ? ", " : "") + std::string("{ i32, i32, ptr } { i32 ptrtoint (ptr getelementptr (") + info.llvm + ", ptr null, i32 0, i32 " + std::to_string(field.index) + ") to i32), i32 " + std::to_string(field.count) + ", ptr " + _types[field.sname].list + " }";
				object_fields++;
			}
		}
		std::string objects = "null";
		if (object_fields) {
			objects = info.list + ".objects";
			_globals << objects << " = internal constant [" << (object_fields + 1) << " x { i32, i32, ptr }] [" << object_entries << ", { i32, i32, ptr } zeroinitializer]\n";
		}
		_globals << info.list << " = internal global { ptr, ptr, ptr, ptr, i64, ptr } { ptr null, ptr null, ptr " << descriptor << ", ptr null, i64 0, ptr " << objects << " }\n";
	}
}

blitz::compiler::address blitz::compiler::gen_address(ast::expression const* expr, bool write)
{
	if (auto r = dynamic_cast<ast::reference const*>(expr)) {
		variable* var = find(r->name);
		if (!var) {
			refuse_array(r->name, r->where);
			warn(r->where, "implicit-variable", "'" + r->name + "' was not declared, it is a new local variable.", "Declare it first, such as 'Local " + r->name + "'.", {}, declaration_suffix(r->type, r->struct_name));
			create_local(r->name, (r->type == type::UNKNOWN) ? type::INT32 : r->type, false, r->where, r->struct_name);
			var = find(r->name);
		}
		if (!write) {
			var->used = true;
		}
		address result{ var->pointer, var->type, var->sname, var->count, var->constant };
		result.shape = var->shape;
		return result;
	} else if (auto c = dynamic_cast<ast::call const*>(expr)) {
		if (!find_dim(c->name)) {
			throw err(c->where, "'" + c->name + "' is not an array.");
		}
		return gen_dim_address(c);
	} else if (auto f = dynamic_cast<ast::field_access const*>(expr)) {
		return field_address(gen(f->object.get()), f);
	} else if (auto i = dynamic_cast<ast::index_access const*>(expr)) {
		address base;
		auto const* inner = i->base.get();
		bool        place = dynamic_cast<ast::reference const*>(inner) || dynamic_cast<ast::field_access const*>(inner) || dynamic_cast<ast::index_access const*>(inner);
		if (auto c = dynamic_cast<ast::call const*>(inner)) {
			place = find_dim(c->name) != nullptr; // `Dim` arrays are indexed like a call.
		}
		auto const* swizzled = dynamic_cast<ast::field_access const*>(inner);
		if (swizzled) {
			auto name = lower(swizzled->name);
			if (!((name.size() > 1) && (name.size() <= 4) && (name.find_first_not_of("xyzwrgba") == std::string::npos))) {
				swizzled = nullptr;
			}
		}
		if (swizzled) {
			// `v\zyx[0]`: the components that are picked, or a field of an object that is named like them.
			auto object = gen(swizzled->object.get());
			if (!object.shape.empty()) {
				auto picked = swizzle(object, swizzled);
				base        = address{ picked.repr, picked.type, std::string(), 0, false };
				base.shape  = picked.shape;
			} else {
				base = field_address(object, swizzled);
			}
			base.need = object.need;
		} else if (place) {
			base = gen_address(inner, write);
		} else {
			// The result of a calculation or of a function: `(a + b)[1]`, `Cross(a, b)[2]`.
			auto computed = gen(inner);
			if (computed.shape.empty()) {
				throw err(i->where, "This is not an array.");
			}
			base       = address{ computed.repr, computed.type, std::string(), 0, false };
			base.shape = computed.shape;
			base.need  = computed.need;
		}
		if (!base.shape.empty()) {
			// An element of a vector, or a column of a matrix. Checked against the size, like the index of an array.
			auto index = convert(gen(i->index.get()), type::INT32, i->index->where, true, std::string(), &i->index->covers);
			call_runtime("bb_check_index", type::UNKNOWN, { index, { std::to_string(base.shape[0]), type::INT32 } });
			shape_t rest(base.shape.begin() + 1, base.shape.end());
			auto    wide = tmp(), offset = tmp(), p = tmp();
			emit(wide + " = sext i32 " + index.repr + " to i64");
			emit(offset + " = mul i64 " + wide + ", " + std::to_string(shape_total(rest)));
			emit(p + " = getelementptr inbounds " + blitz::types::to_llvm(base.type) + ", ptr " + base.pointer + ", i64 " + offset);
			address result{ p, base.type, std::string(), 0, base.constant };
			result.shape = rest;
			result.need  = (dynamic_cast<ast::reference const*>(i->base.get()) != nullptr) ? _needs[i->index.get()] : compiler_detail::pair_need(_needs[i->index.get()], base.need);
			return result;
		}
		if (!base.count) {
			throw err(i->where, "This is not an array.");
		}
		auto index = convert(gen(i->index.get()), type::INT32, i->index->where, true, std::string(), &i->index->covers);
		call_runtime("bb_check_index", type::UNKNOWN, { index, { std::to_string(base.count), type::INT32 } });
		auto p = tmp();
		emit(p + " = getelementptr inbounds [" + std::to_string(base.count) + " x " + blitz::types::to_llvm(base.type) + "], ptr " + base.pointer + ", i32 0, i32 " + index.repr);
		address result{ p, base.type, base.sname, 0, base.constant };
		result.need = (dynamic_cast<ast::reference const*>(i->base.get()) != nullptr) ? _needs[i->index.get()] : compiler_detail::pair_need(_needs[i->index.get()], base.need);
		return result;
	}
	throw err(expr->where, "This can't be assigned to.");
}

// Where the field of an object (or the component of a vector) is.
blitz::compiler::address blitz::compiler::field_address(value const& object, ast::field_access const* f)
{
	if (!object.shape.empty()) {
		return component_address(object, f);
	}
	if ((object.type != type::STRUCT) || object.sname.empty()) {
		throw err(f->where, "'\\" + f->name + "' can only be used on an object.");
	}
	auto& info = need_type(object.sname, f->where);
	for (auto const& field : info.fields) {
		if (lower(field.name) == lower(f->name)) {
			auto missing = tmp(), flags_p = tmp(), flags = tmp(), deleted = tmp(), bad = tmp();
			emit(missing + " = icmp eq ptr " + object.repr + ", null");
			guard(missing, "Object does not exist.");
			emit(flags_p + " = getelementptr inbounds { ptr, ptr, i32, i32 }, ptr " + object.repr + ", i32 0, i32 3");
			emit(flags + " = load i32, ptr " + flags_p);
			emit(deleted + " = and i32 " + flags + ", 1");
			emit(bad + " = icmp ne i32 " + deleted + ", 0");
			guard(bad, "Object does not exist.");
			auto p = tmp();
			emit(p + " = getelementptr inbounds " + info.llvm + ", ptr " + object.repr + ", i32 0, i32 " + std::to_string(field.index));
			address result{ p, field.type, field.sname, field.count, false };
			result.shape = field.shape;
			result.need = object.need;
			return result;
		}
	}
	throw err(f->where, "Type '" + info.name + "' has no field '" + f->name + "'.");
}

blitz::compiler::value blitz::compiler::load_address(address const& addr)
{
	if (addr.count) {
		throw blitz::error(std::filesystem::path(), { 0, 0 }, { 0, 0 }, "An array can only be used with an index.");
	}
	if (!addr.shape.empty()) {
		// A vector or matrix stays where it is, what is done with it works on its memory.
		value aggregate{ addr.pointer, addr.type, std::string() };
		aggregate.shape = addr.shape;
		return aggregate;
	}
	auto r = tmp();
	emit(r + " = load " + blitz::types::to_llvm(addr.type) + ", ptr " + addr.pointer + (addr.element ? ", !tbaa !900004" : ""));
	return { r, addr.type, addr.sname };
}

blitz::compiler::value blitz::compiler::gen_field(ast::field_access const* node)
{
	auto name = lower(node->name);
	bool several = (name.size() > 1) && (name.size() <= 4) && (name.find_first_not_of("xyzwrgba") == std::string::npos);
	if (several) {
		// `v\xy` reads several components of a vector. An object can have a field with such a name.
		auto object = gen(node->object.get());
		if (!object.shape.empty()) {
			auto picked = swizzle(object, node);
			picked.need = object.need;
			return picked;
		}
		auto addr = field_address(object, node);
		if (addr.count) {
			throw err(node->where, "An array can only be used with an index.");
		}
		auto loaded = load_address(addr);
		loaded.need = addr.need;
		return loaded;
	}
	auto addr = gen_address(node);
	if (addr.count) {
		throw err(node->where, "An array can only be used with an index.");
	}
	auto loaded = load_address(addr);
	loaded.need = addr.need;
	return loaded;
}

blitz::compiler::value blitz::compiler::gen_index(ast::index_access const* node)
{
	auto addr   = gen_address(node);
	auto loaded = load_address(addr);
	loaded.need = addr.need;
	return loaded;
}

blitz::compiler::value blitz::compiler::gen_new(ast::new_object const* node)
{
	auto& info = need_type(node->type_name, node->where);
	// With --field-defaults the default values are worked out first, from the top field down, so nothing they call can delete the
	// object before it is filled in. They only see Globals and Consts, wherever the New is.
	std::vector<std::pair<field_info const*, value>> defaults;
	auto key = lower(info.name);
	for (auto const& field : info.fields) {
		if (!field.default_value) {
			continue;
		}
		if (_defaulting_types.count(key)) {
			throw err(node->where, "The default value of a field of '" + info.name + "' makes a new '" + info.name + "', which would never end.");
		}
		bool outer        = _in_field_default;
		_in_field_default = true;
		_defaulting_types.insert(key);
		value v;
		try {
			v = gen(field.default_value);
		} catch (...) {
			_in_field_default = outer;
			_defaulting_types.erase(key);
			throw;
		}
		_in_field_default = outer;
		_defaulting_types.erase(key);
		if (field.shape.empty() && v.shape.empty()) {
			v = convert(v, field.type, field.default_value->where, true, field.sname, &field.default_value->covers);
		}
		defaults.emplace_back(&field, v);
	}
	auto end = tmp(), size = tmp();
	emit(end + " = getelementptr " + info.llvm + ", ptr null, i32 1");
	emit(size + " = ptrtoint ptr " + end + " to i64");
	auto object = call_runtime("bb_object_new", type::STRUCT, { { size, type::INT64 }, { info.list, type::STRUCT } });
	object.sname = lower(info.name);
	for (auto const& [field, v] : defaults) {
		auto p = tmp();
		emit(p + " = getelementptr inbounds " + info.llvm + ", ptr " + object.repr + ", i32 0, i32 " + std::to_string(field->index));
		address target{ p, field->type, field->sname, 0, false };
		target.shape = field->shape;
		if (!target.shape.empty() || !v.shape.empty()) {
			assign_aggregate(target, v, field->default_value->where, &field->default_value->covers);
		} else {
			store_value(target, v);
		}
	}
	return object;
}

blitz::compiler::value blitz::compiler::gen_list_end(ast::list_end const* node)
{
	auto& info   = need_type(node->type_name, node->where);
	auto  object = call_runtime(node->last ? "bb_list_last" : "bb_list_first", type::STRUCT, { { info.list, type::STRUCT } });
	object.sname = lower(info.name);
	return object;
}

blitz::compiler::value blitz::compiler::gen_neighbor(ast::list_neighbor const* node)
{
	auto object = gen(node->object.get());
	if (object.type != type::STRUCT) {
		throw err(node->where, "Before and After need an object.");
	}
	auto result  = call_runtime(node->after ? "bb_object_next" : "bb_object_prev", type::STRUCT, { object });
	result.sname = object.sname;
	return result;
}

blitz::compiler::value blitz::compiler::gen_from_handle(ast::object_from_handle const* node)
{
	auto& info   = need_type(node->type_name, node->where);
	auto  handle = convert(gen(node->handle.get()), type::INT32, node->handle->where, true, std::string(), &node->handle->covers);
	auto  result = call_runtime("bb_object_from_handle", type::STRUCT, { handle, { info.list, type::STRUCT } });
	result.sname = lower(info.name);
	return result;
}

void blitz::compiler::gen_for_each(ast::for_statement const* node)
{
	auto& info = need_type(node->each_type, node->where);
	auto& var  = lookup(node->variable->name, type::STRUCT, node->variable->where, node->each_type);
	if ((var.type != type::STRUCT) || (var.sname != lower(info.name))) {
		throw err(node->where, "The variable of 'For Each " + info.name + "' has to be of that type.");
	}
	auto pointer = var.pointer;

	// While the loop runs, Delete keeps the memory of the objects it deletes (the loop finds its next object through the
	// one it stands on, which Delete has set to Null in the variable). The flag also lets the exit of the function end
	// the loop's claim when Return or Goto leaves it.
	auto flag = "%each.flag" + std::to_string(_each_flags.size());
	auto cur  = "%each.cur" + std::to_string(_each_flags.size());
	_allocas << "  " << flag << " = alloca i8\n  store i8 0, ptr " << flag << "\n  " << cur << " = alloca ptr\n  store ptr null, ptr " << cur << "\n";
	_each_flags.push_back({ flag, info.list });
	declare("bb_loop_enter", "declare void @bb_loop_enter(ptr, ptr)");
	emit("call void @bb_loop_enter(ptr " + info.list + ", ptr " + flag + ")");

	auto first = call_runtime("bb_list_first", type::STRUCT, { { info.list, type::STRUCT } });
	store_value({ pointer, type::STRUCT, var.sname, 0, false }, { first.repr, type::STRUCT, var.sname });

	auto cond_l = label("each.cond"), body_l = label("each.body"), step_l = label("each.step"), end_l = label("each.end");
	begin_label(cond_l);
	auto current = tmp(), more = tmp();
	emit(current + " = load ptr, ptr " + pointer);
	emit(more + " = icmp ne ptr " + current + ", null");
	emit_terminator("br i1 " + more + ", label %" + body_l + ", label %" + end_l);

	begin_label(body_l);
	emit("store ptr " + current + ", ptr " + cur);
	_exits.push_back(end_l);
	_each_active.push_back({ node, flag, info.list });
	gen_block(node->body);
	_each_active.pop_back();
	_exits.pop_back();

	// The body might have deleted the object, which still knows what comes next.
	begin_label(step_l);
	auto at = tmp(), held = tmp(), gone = tmp();
	emit(at + " = load ptr, ptr " + pointer);
	emit(held + " = load ptr, ptr " + cur);
	emit(gone + " = icmp eq ptr " + at + ", null");
	auto from = tmp();
	emit(from + " = select i1 " + gone + ", ptr " + held + ", ptr " + at);
	auto next = call_runtime("bb_object_next", type::STRUCT, { { from, type::STRUCT } });
	store_value({ pointer, type::STRUCT, var.sname, 0, false }, { next.repr, type::STRUCT, var.sname });
	emit_terminator("br label %" + cond_l);
	begin_label(end_l);
	declare("bb_loop_leave", "declare void @bb_loop_leave(ptr, ptr)");
	emit("call void @bb_loop_leave(ptr " + info.list + ", ptr " + flag + ")");
}

void blitz::compiler::gen_delete(ast::delete_statement const* node)
{
	if (!node->each_type.empty()) {
		auto& info = need_type(node->each_type, node->where);
		call_runtime("bb_list_clear", type::UNKNOWN, { { info.list, type::STRUCT } });
		return;
	}
	// A variable (or field, or array element) that is deleted becomes Null, so that it can't be used by mistake.
	auto const* expr = node->object.get();
	bool        place = dynamic_cast<ast::reference const*>(expr) || dynamic_cast<ast::field_access const*>(expr) || dynamic_cast<ast::index_access const*>(expr);
	address     addr;
	value       object;
	if (place) {
		addr = gen_address(expr, false);
		if (addr.count) {
			throw err(node->where, "An array can only be used with an index.");
		}
		object = load_address(addr);
	} else {
		object = gen(expr);
	}
	if (object.type != type::STRUCT) {
		throw err(node->where, "Delete needs an object.");
	}
	if (object.sname.empty()) {
		// Null has no type, so there is nothing to delete: this is a mistake in the program.
		call_runtime("bb_check_object", type::UNKNOWN, { object });
		return;
	}
	auto& info = need_type(object.sname, node->where);
	call_runtime("bb_object_delete", type::UNKNOWN, { object, { info.list, type::STRUCT } });
	if (place && !addr.constant) {
		store_value(addr, { "null", type::STRUCT, object.sname });
	}
}

void blitz::compiler::gen_insert(ast::insert_statement const* node)
{
	gen_insert_object(node->object.get(), node->other.get(), node->after, node->where);
}

blitz::compiler::value blitz::compiler::gen_insert_object(ast::expression const* object_expr, ast::expression const* other_expr, bool after, ast::location const& where)
{
	auto object = gen(object_expr);
	auto other  = gen(other_expr);
	if ((object.type != type::STRUCT) || (other.type != type::STRUCT)) {
		throw err(where, "Insert needs two objects.");
	}
	std::string sname = object.sname.empty() ? other.sname : object.sname;
	if (sname.empty()) {
		return object;
	}
	if (!object.sname.empty() && !other.sname.empty() && (object.sname != other.sname)) {
		throw err(where, "Type mismatch: '" + object.sname + "' can't be inserted next to '" + other.sname + "'.");
	}
	auto& info = need_type(sname, where);
	call_runtime("bb_object_insert", type::UNKNOWN, { object, other, { after ? "1" : "0", type::INT32 }, { info.list, type::STRUCT } });
	object.sname = sname;
	return object;
}
