std::string blitz::types::to_string(blitz::types::type type)
{
	if (type == type::STRUCT) {
		return "struct";
	}

	for (auto kv : _map_to) {
		if (type == kv.second) {
			return kv.first;
		}
	}

	return "Unknown";
}

std::string blitz::types::display(blitz::types::type type)
{
	switch (type) {
	case type::INT8:
		return "Byte";
	case type::UINT8:
		return "UByte";
	case type::INT16:
		return "Short";
	case type::UINT16:
		return "UShort";
	case type::INT32:
		return "Int";
	case type::UINT32:
		return "UInt";
	case type::INT64:
		return "Long";
	case type::UINT64:
		return "ULong";
	case type::FLOAT16:
		return "Half";
	case type::FLOAT32:
		return "Float";
	case type::FLOAT64:
		return "Double";
	case type::STRING:
		return "String";
	default:
		return "Unknown";
	}
}

blitz::types::type blitz::types::from_string(std::string text)
{
	std::transform(text.cbegin(), text.cend(), text.begin(), [](char from) {
		if (from & 0b10000000) { // Exclude Unicode
			return from;
		}
		return (char)std::tolower(from);
	});

	for (auto kv : _map_to) {
		if (text == kv.first) {
			return kv.second;
		}
	}

	return blitz::types::type::UNKNOWN;
}

bool blitz::types::is_integer(blitz::types::type type)
{
	switch (type) {
	case type::INT8:
	case type::UINT8:
	case type::INT16:
	case type::UINT16:
	case type::INT32:
	case type::UINT32:
	case type::INT64:
	case type::UINT64:
		return true;
	default:
		return false;
	}
}

bool blitz::types::is_real(blitz::types::type type)
{
	return (type == type::FLOAT16) || (type == type::FLOAT32) || (type == type::FLOAT64);
}

bool blitz::types::is_signed(blitz::types::type type)
{
	switch (type) {
	case type::INT8:
	case type::INT16:
	case type::INT32:
	case type::INT64:
		return true;
	default:
		return false;
	}
}

unsigned blitz::types::bits(blitz::types::type type)
{
	switch (type) {
	case type::INT8:
	case type::UINT8:
		return 8;
	case type::INT16:
	case type::UINT16:
	case type::FLOAT16:
		return 16;
	case type::INT32:
	case type::UINT32:
	case type::FLOAT32:
		return 32;
	case type::INT64:
	case type::UINT64:
	case type::FLOAT64:
		return 64;
	default:
		return 0;
	}
}

std::string blitz::types::to_llvm(blitz::types::type type)
{
	switch (type) {
	case type::FLOAT16:
		return "half";
	case type::FLOAT32:
		return "float";
	case type::FLOAT64:
		return "double";
	case type::STRING:
	case type::STRUCT:
		return "ptr";
	case type::UNKNOWN:
		return "void";
	default:
		return "i" + std::to_string(bits(type));
	}
}
