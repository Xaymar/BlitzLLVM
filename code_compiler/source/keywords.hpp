// The keywords of the language, the functions of the runtime and of the user libraries, for blitzcc -k and +k.
#pragma once
#include <filesystem>
#include <iosfwd>
#include <string>
#include <vector>
#include "types.hpp"

namespace blitz::keywords {
	// A parameter of a function of a user library. A pointer ('*', or ':Pointer') is a bank or an object, passed as the address of its memory.
	struct user_param {
		std::string        name;
		blitz::types::type type    = blitz::types::type::INT32;
		bool               pointer = false;
	};

	// A function that a user library (userlibs/*.decls) declares.
	struct user_function {
		std::string                            name;
		blitz::types::type                     ret = blitz::types::type::UNKNOWN; // UNKNOWN is nothing: The function is void.
		std::vector<user_param>                params;
		std::string                            lib;    // The library from the .lib directive, such as 'mylib.dll'.
		std::string                            symbol; // The name in the library: the decorated name, or else the name above.
	};

	// The words that are part of the language itself, such as Dim or While, sorted. Words with a space (End If) are left out.
	std::vector<std::string> language();

	// Read all .decls files in the directory, sorted by file name. Throws on a malformed file or a duplicate name.
	std::vector<user_function> load_userlibs(std::filesystem::path const& dir);

	// How dump writes the functions: Only the names, the syntax like Blitz3D lists it ('Left$ ( param1$,param2% )', every
	// integer type is a '%'), or the syntax in our own notation ('Left:String param1:String, param2:Int32', every type by name).
	enum class dump_mode {
		NAMES,
		BLITZ3D,
		NATIVE,
	};

	// Write all keywords, one per line: The language, the runtime functions and the functions of the user libraries. The
	// functions are followed by their parameters, depending on the mode.
	void dump(std::ostream& out, dump_mode mode, std::filesystem::path const& userlibs);
} // namespace blitz::keywords
