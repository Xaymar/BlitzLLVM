#pragma once
#include <filesystem>
#include <memory>
#include <vector>
#include "ast/ast.hpp"
#include "lexer.hpp"

namespace blitz {
	/** Turns a Blitz source file (and everything it includes) into an Abstract Syntax Tree.
	 *
	 * Statements outside of functions end up in the main block, Functions are collected separately so they can be
	 * called before their definition. Errors are thrown as blitz::error.
	 */
	class parser {
		// State of the file that is currently being parsed. Includes push/pop this.
		std::filesystem::path                        _file;
		std::shared_ptr<const std::filesystem::path> _file_ptr;
		std::vector<blitz::token>                    _tokens;
		size_t                                       _pos;

		std::vector<std::filesystem::path> _include_stack;
		std::filesystem::path              _root_dir; // Where the main program is.
		std::unique_ptr<ast::program>      _program;
		int                                _depth; // Block nesting depth, functions may only exist at depth 0.
		std::string                        _struct_name; // Type name found by the last parse_type_suffix, for `Name.TypeName`.

		public:
		~parser();
		parser();

		std::unique_ptr<ast::program> parse(std::filesystem::path file);

		private:
		// Token handling
		blitz::token const& tk(size_t offset = 0) const;
		void                advance();
		ast::location       here(blitz::token const& token) const;
		blitz::error        error(blitz::token const& token, std::string const& reason) const;
		bool                is_keyword(blitz::token const& token, const char* keyword) const;
		bool                is_symbol(blitz::token const& token, const char* symbol) const;
		bool                is_terminator(blitz::token const& token) const;
		bool                adjacent(blitz::token const& lhs, blitz::token const& rhs) const;
		void                skip_empty();
		void                expect_keyword(const char* keyword);
		void                expect_symbol(const char* symbol);

		// Files
		void load(std::filesystem::path file);
		void parse_file(std::filesystem::path file, ast::block& into);

		// Statements
		bool at_block_end() const;
		bool starts_statement(blitz::token const& token) const;
		void parse_block(ast::block& into);
		void parse_line(ast::block& into);
		void parse_statement(ast::block& into);
		void parse_declare(ast::block& into);
		void parse_if(ast::block& into);
		void parse_while(ast::block& into);
		void parse_repeat(ast::block& into);
		void parse_for(ast::block& into);
		void parse_select(ast::block& into);
		void parse_function();
		void parse_include(ast::block& into);
		void parse_type_decl();
		void parse_dim(ast::block& into);
		void parse_label(ast::block& into);
		void parse_data(ast::block& into);
		void parse_jump(ast::block& into);
		void parse_delete(ast::block& into);
		void parse_insert(ast::block& into);
		void parse_identifier_statement(ast::block& into);
		void expect_block_end(const char* single, const char* first, const char* second);

		// Expressions
		blitz::types::type                 parse_type_suffix(blitz::token const& name);
		std::vector<ast::expression_ptr>   parse_arguments();
		ast::expression_ptr                parse_expression();
		ast::expression_ptr                parse_or();
		ast::expression_ptr                parse_and();
		ast::expression_ptr                parse_not();
		ast::expression_ptr                parse_comparison();
		ast::expression_ptr                parse_shift();
		ast::expression_ptr                parse_additive();
		ast::expression_ptr                parse_multiplicative();
		ast::expression_ptr                parse_power();
		ast::expression_ptr                parse_unary();
		ast::expression_ptr                parse_primary();
		ast::expression_ptr                parse_postfix(ast::expression_ptr base);
		ast::expression_ptr                parse_number(blitz::token const& token);
		ast::expression_ptr                make_binary(blitz::token const& at, ast::binary::op kind, ast::expression_ptr lhs, ast::expression_ptr rhs);
	};
} // namespace blitz
