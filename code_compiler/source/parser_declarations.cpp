void blitz::parser::parse_function()
{
	auto first = tk();
	if (_depth != 0) {
		throw error(first, "Functions can't be defined inside of other blocks.");
	}
	advance();

	auto name = tk();
	if ((name.type != blitz::token::variant::TEXT) || reserved.count(lower(name.text))) {
		throw error(name, blitz::format("Unexpected %s, expected a function name.", name.to_string().c_str()));
	}
	advance();

	auto fn   = std::make_unique<ast::function>();
	fn->where = here(first);
	fn->name  = name.text;
	fn->name_where = here(name);
	if (is_void_suffix(name)) {
		// `Name:Void` returns no data, so it has no type to convert to.
		advance();
		advance();
		_struct_name.clear();
		fn->is_void = true;
	} else {
		fn->type = parse_type_suffix(name, true);
		fn->shape = _shape;
	}
	fn->struct_name = _struct_name;
	_functions.emplace(lower(fn->name), slot{ &fn->type, &fn->struct_name });
	if (fn->is_void) {
		fn->type  = blitz::types::type::UNKNOWN;
		fn->typed = true;
	} else if (fn->type == blitz::types::type::UNKNOWN) {
		fn->type = blitz::types::type::INT32;
	} else {
		fn->typed = true;
	}

	expect_symbol("(");
	if (!is_symbol(tk(), ")")) {
		while (true) {
			// `In`, `Out` and `InOut` only mean something in front of another name, so they stay usable as names.
			auto mode = ast::direction::IN;
			{
				auto word = lower(tk().text);
				bool word_first = (tk().type == blitz::token::variant::TEXT) && ((word == "in") || (word == "out") || (word == "inout"));
				bool name_next  = (tk(1).type == blitz::token::variant::TEXT) && !reserved.count(lower(tk(1).text));
				if (word_first && name_next) {
					mode = (word == "in") ? ast::direction::IN : ((word == "out") ? ast::direction::OUT : ast::direction::INOUT);
					advance();
				}
			}
			auto pname = tk();
			if ((pname.type != blitz::token::variant::TEXT) || reserved.count(lower(pname.text))) {
				throw error(pname, blitz::format("Unexpected %s, expected a parameter name.", pname.to_string().c_str()));
			}
			advance();
			if (is_void_suffix(pname)) {
				throw error(tk(1), "Void is only a type for functions, a parameter needs a type that holds data.");
			}

			ast::parameter param;
			param.where = here(pname);
			param.mode  = mode;
			param.name  = pname.text;
			param.type  = parse_type_suffix(pname, true);
			param.shape = _shape;
			param.struct_name = _struct_name;
			param.typed = (param.type != blitz::types::type::UNKNOWN);
			if (param.type == blitz::types::type::UNKNOWN) {
				param.type = blitz::types::type::INT32;
			}
			if (is_symbol(tk(), "=")) {
				advance();
				param.initial = parse_expression();
			}
			fn->parameters.push_back(std::move(param));

			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
	}
	expect_symbol(")");

	// Parameters and Locals only exist inside of the function.
	_function_slots.clear();
	for (size_t idx = 0; idx < fn->parameters.size(); idx++) {
		auto& param = fn->parameters[idx];
		_function_slots.emplace(lower(param.name), slot{ &param.type, &param.struct_name });
	}
	_in_function = true;
	_scope_id    = ++_scope_count;
	parse_block(fn->body);
	_in_function = false;
	_scope_id    = 0;
	_function_slots.clear();
	expect_block_end("endfunction", "end", "function");
	finish(*fn, first);
	_program->functions.push_back(std::move(fn));
}

namespace {
	// Windows opens a device for these names in any folder, with any extension (`COM1.bb`, `nul.txt`), which can block the compiler or
	// send data to real hardware. They are never a file that can be included.
	bool is_device_name(std::filesystem::path const& part)
	{
		std::string name = part.string();
		name             = name.substr(0, name.find('.'));
		while (!name.empty() && ((name.back() == ' ') || (name.back() == '.'))) {
			name.pop_back();
		}
		std::transform(name.begin(), name.end(), name.begin(), [](unsigned char c) { return char(std::toupper(c)); });
		if ((name == "CON") || (name == "PRN") || (name == "AUX") || (name == "NUL") || (name == "CONIN$") || (name == "CONOUT$")) {
			return true;
		}
		if ((name.size() >= 4) && ((name.compare(0, 3, "COM") == 0) || (name.compare(0, 3, "LPT") == 0))) {
			std::string number = name.substr(3);
			// A digit, or the superscript 1, 2 and 3 (UTF-8), which Windows also takes.
			return ((number.size() == 1) && std::isdigit((unsigned char)number[0])) || (number == "\xC2\xB9") || (number == "\xC2\xB2") || (number == "\xC2\xB3");
		}
		return false;
	}
} // namespace

void blitz::parser::parse_include(ast::block& into)
{
	advance();
	auto file_tk = tk();
	if (file_tk.type != blitz::token::variant::STRING) {
		throw error(file_tk, blitz::format("Unexpected %s, expected a file name in quotes.", file_tk.to_string().c_str()));
	}
	advance();

	// Includes are relative to the file that includes them.
	// Blitz programs come from Windows: paths use backslashes, and don't care about the case of names.
	std::string text = file_tk.text;
	std::replace(text.begin(), text.end(), '\\', '/');
	std::filesystem::path target  = std::filesystem::path(text);
	bool                  shipped = (text.size() >= 2) && (text.front() == '<') && (text.back() == '>');
	for (auto const& part : (shipped ? std::filesystem::path(text.substr(1, text.size() - 2)) : target).relative_path()) {
		if (is_device_name(part)) {
			throw error(file_tk, blitz::format("Can't include '%s': '%s' is the name of a Windows device, not of a file.", file_tk.text.c_str(), part.string().c_str()));
		}
	}
	if (shipped) {
		// `Include "<keys.bb>"` names a file shipped with BlitzLLVM. Windows forbids '<' and '>' in file names, so the original
		// can never open such a file and stops with "Unable to open include file". The form is decided by the text alone: a file
		// that is really called '<keys.bb>' is never looked for.
		std::filesystem::path name = std::filesystem::path(text.substr(1, text.size() - 2));
		bool                  valid = !name.empty() && !name.has_root_path();
		for (auto const& part : name) {
			valid = valid && (part != "..");
		}
		if (!valid) {
			throw error(file_tk, blitz::format("'%s' is not a name of a shipped include: it can't be empty, absolute or contain '..'.", file_tk.text.c_str()));
		}
		target.clear();
		std::string looked;
		for (auto const& dir : include_dirs) {
			auto candidate = find_file(dir / name);
			if (std::filesystem::is_regular_file(candidate)) {
				target = candidate;
				break;
			}
			looked += (looked.empty() ? "" : ", ") + dir.generic_string();
		}
		if (target.empty()) {
			throw error(file_tk, looked.empty() ? blitz::format("Shipped include '%s' not found: there is no include directory (use -I or BLITZLLVM_INCLUDE).", file_tk.text.c_str())
			                                    : blitz::format("Shipped include '%s' does not exist (looked in %s).", file_tk.text.c_str(), looked.c_str()));
		}
	} else if (target.is_relative()) {
		// Relative to the file that includes, or else to the main program (which is where Blitz runs from).
		auto local = find_file(_file.parent_path() / target);
		target     = std::filesystem::exists(local) ? local : (_root_dir / target);
	}
	target = find_file(target);
	if (!std::filesystem::exists(target)) {
		throw error(file_tk, blitz::format("Included file '%s' does not exist.", file_tk.text.c_str()));
	}
	if (!std::filesystem::is_regular_file(target)) {
		throw error(file_tk, blitz::format("Can't include '%s': it is not a file.", file_tk.text.c_str()));
	}
	// A file is only read once, like in the original, so that it can be included from several places without declaring
	// everything in it twice.
	std::error_code ec;
	if (_included.count(std::filesystem::weakly_canonical(target, ec))) {
		return;
	}
	parse_file(target, into);
}

std::filesystem::path blitz::parser::installed_include_dir(std::filesystem::path const& bin_dir)
{
	if (const char* env = std::getenv("BLITZLLVM_INCLUDE"); env && *env) {
		return env;
	}
	for (auto const& candidate : { bin_dir / ".." / "include", bin_dir / ".." / ".." / "include", bin_dir / "include", bin_dir / ".." / "share" / "blitzllvm" / "include" }) {
		std::error_code ec;
		// A directory with Blitz files, not the C headers of a prefix such as /usr.
		if (std::filesystem::is_regular_file(candidate / "keys.bb", ec)) {
			return std::filesystem::weakly_canonical(candidate, ec);
		}
	}
	return {};
}

void blitz::parser::parse_type_decl()
{
	auto first = tk();
	if (_depth != 0) {
		throw error(first, "Types can't be defined inside of other blocks.");
	}
	advance();

	auto name = tk();
	if ((name.type != blitz::token::variant::TEXT) || reserved.count(lower(name.text))) {
		throw error(name, blitz::format("Unexpected %s, expected a type name.", name.to_string().c_str()));
	}
	advance();

	auto decl   = std::make_unique<ast::type_decl>();
	decl->where = here(first);
	decl->name  = name.text;

	while (true) {
		skip_empty();
		if (is_keyword(tk(), "end") && is_keyword(tk(1), "type")) {
			advance();
			advance();
			break;
		} else if (is_keyword(tk(), "endtype")) {
			advance();
			break;
		} else if (!is_keyword(tk(), "field")) {
			throw error(tk(), blitz::format("Unexpected %s, expected 'Field' or 'End Type'.", tk().to_string().c_str()));
		}
		advance();

		while (true) {
			auto fname = tk();
			if (fname.type != blitz::token::variant::TEXT) {
				throw error(fname, blitz::format("Unexpected %s, expected a field name.", fname.to_string().c_str()));
			}
			advance();
			if (is_void_suffix(fname)) {
				throw error(tk(1), "Void is only a type for functions, a field needs a type that holds data.");
			}

			ast::field_decl field;
			field.where       = here(fname);
			field.name        = fname.text;
			field.type        = parse_type_suffix(fname, true);
			field.shape       = _shape;
			field.struct_name = _struct_name;
			field.typed = (field.type != blitz::types::type::UNKNOWN);
			if (field.type == blitz::types::type::UNKNOWN) {
				field.type = blitz::types::type::INT32;
			}
			if (is_symbol(tk(), "[")) {
				if (!field.shape.empty()) {
					throw error(tk(), "A field that has its size in the type can't have a second size.");
				}
				advance();
				field.array_size = parse_expression();
				expect_symbol("]");
			}
			decl->fields.push_back(std::move(field));

			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
	}
	_program->types.push_back(std::move(decl));
}

void blitz::parser::parse_dim(ast::block& into)
{
	auto first = tk();
	advance();

	auto node   = std::make_unique<ast::dim_statement>();
	node->where = here(first);
	while (true) {
		auto name = tk();
		if ((name.type != blitz::token::variant::TEXT) || reserved.count(lower(name.text))) {
			throw error(name, blitz::format("Unexpected %s, expected an array name.", name.to_string().c_str()));
		}
		advance();

		ast::dim_declaration decl;
		decl.where       = here(name);
		decl.name        = name.text;
		decl.type        = parse_type_suffix(name);
		decl.struct_name = _struct_name;
		expect_symbol("(");
		while (true) {
			decl.sizes.push_back(parse_expression());
			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
		expect_symbol(")");
		if (decl.sizes.size() > 4) {
			throw error(name, "Arrays can have up to 4 dimensions.");
		}
		node->arrays.push_back(std::move(decl));

		if (is_symbol(tk(), ",")) {
			advance();
			continue;
		}
		break;
	}
	into.push_back(std::move(node));
}

void blitz::parser::parse_delete(ast::block& into)
{
	auto first = tk();
	advance();

	auto node   = std::make_unique<ast::delete_statement>();
	node->where = here(first);
	if (is_keyword(tk(), "each")) {
		advance();
		auto type_tk = tk();
		if (type_tk.type != blitz::token::variant::TEXT) {
			throw error(type_tk, blitz::format("Unexpected %s, expected a type name.", type_tk.to_string().c_str()));
		}
		advance();
		node->each_type = type_tk.text;
	} else {
		node->object = parse_expression();
	}
	into.push_back(std::move(node));
}

void blitz::parser::parse_insert(ast::block& into)
{
	auto first = tk();
	advance();

	auto node    = std::make_unique<ast::insert_statement>();
	node->where  = here(first);
	node->object = parse_unary();
	if (is_keyword(tk(), "before")) {
		node->after = false;
	} else if (is_keyword(tk(), "after")) {
		node->after = true;
	} else {
		throw error(tk(), blitz::format("Unexpected %s, expected 'Before' or 'After'.", tk().to_string().c_str()));
	}
	advance();
	node->other = parse_unary();
	into.push_back(std::move(node));
}

void blitz::parser::parse_identifier_statement(ast::block& into)
{
	auto name  = tk();
	size_t start = _pos;

	// Assignment: the left side can be a variable, a field, or an array element.
	try {
		auto target = parse_primary();
		if (is_symbol(tk(), "=")) {
			auto node    = std::make_unique<ast::assign>();
			node->where  = here(name);
			node->target = std::move(target);
			advance();
			node->value = parse_expression();
			into.push_back(std::move(node));
			return;
		}
	} catch (blitz::error const&) {
		// Not an assignment, the command parsing below reports errors properly.
	}
	_pos = start;

	advance();
	auto type        = parse_type_suffix(name);
	auto struct_name = _struct_name;

	auto node                = std::make_unique<ast::call_statement>();
	node->where              = here(name);
	node->invocation         = std::make_unique<ast::call>();
	node->invocation->where  = here(name);
	node->invocation->name   = name.text;
	node->invocation->type   = type;
	node->invocation->struct_name = struct_name;

	if (is_symbol(tk(), "(")) {
		// Try `Name(Arg, ...)` first. If something follows the `)`, it's actually `Name (Expression)...`.
		size_t saved = _pos;
		advance();
		auto args = parse_arguments();
		expect_symbol(")");
		if (is_terminator(tk())) {
			node->invocation->arguments = std::move(args);
			into.push_back(std::move(node));
			return;
		}
		_pos = saved;
	}

	if (!is_terminator(tk())) {
		while (true) {
			node->invocation->arguments.push_back(parse_expression());
			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
	}
	into.push_back(std::move(node));
}
