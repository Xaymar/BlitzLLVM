void blitz::parser::parse_function()
{
	auto first = tk();
	if (_depth != 0) {
		throw error(first, "Functions can't be defined inside of other blocks.");
	}
	advance();

	auto name = tk();
	if ((name.type != blitz::token::variant::TEXT) || reserved.count(lower(name.text))) {
		throw error(name, blitz::format("Unexpected %s, expected a function name.", name.to_string().c_str()));
	}
	advance();

	auto fn   = std::make_unique<ast::function>();
	fn->where = here(first);
	fn->name  = name.text;
	fn->type  = parse_type_suffix(name);
	fn->struct_name = _struct_name;
	_functions.emplace(lower(fn->name), slot{ &fn->type, &fn->struct_name });
	if (fn->type == blitz::types::type::UNKNOWN) {
		fn->type = blitz::types::type::INT32;
	} else {
		fn->typed = true;
	}

	expect_symbol("(");
	if (!is_symbol(tk(), ")")) {
		while (true) {
			auto pname = tk();
			if ((pname.type != blitz::token::variant::TEXT) || reserved.count(lower(pname.text))) {
				throw error(pname, blitz::format("Unexpected %s, expected a parameter name.", pname.to_string().c_str()));
			}
			advance();

			ast::parameter param;
			param.where = here(pname);
			param.name  = pname.text;
			param.type  = parse_type_suffix(pname);
			param.struct_name = _struct_name;
			param.typed = (param.type != blitz::types::type::UNKNOWN);
			if (param.type == blitz::types::type::UNKNOWN) {
				param.type = blitz::types::type::INT32;
			}
			if (is_symbol(tk(), "=")) {
				advance();
				param.initial = parse_expression();
			}
			fn->parameters.push_back(std::move(param));

			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
	}
	expect_symbol(")");

	// Parameters and Locals only exist inside of the function.
	_function_slots.clear();
	for (size_t idx = 0; idx < fn->parameters.size(); idx++) {
		auto& param = fn->parameters[idx];
		_function_slots.emplace(lower(param.name), slot{ &param.type, &param.struct_name });
	}
	_in_function = true;
	parse_block(fn->body);
	_in_function = false;
	_function_slots.clear();
	expect_block_end("endfunction", "end", "function");
	finish(*fn, first);
	_program->functions.push_back(std::move(fn));
}

void blitz::parser::parse_include(ast::block& into)
{
	advance();
	auto file_tk = tk();
	if (file_tk.type != blitz::token::variant::STRING) {
		throw error(file_tk, blitz::format("Unexpected %s, expected a file name in quotes.", file_tk.to_string().c_str()));
	}
	advance();

	// Includes are relative to the file that includes them.
	// Blitz programs come from Windows: paths use backslashes, and don't care about the case of names.
	std::string text = file_tk.text;
	std::replace(text.begin(), text.end(), '\\', '/');
	std::filesystem::path target = std::filesystem::path(text);
	if (target.is_relative()) {
		// Relative to the file that includes, or else to the main program (which is where Blitz runs from).
		auto local = find_file(_file.parent_path() / target);
		target     = std::filesystem::exists(local) ? local : (_root_dir / target);
	}
	target = find_file(target);
	if (!std::filesystem::exists(target)) {
		throw error(file_tk, blitz::format("Included file '%s' does not exist.", file_tk.text.c_str()));
	}
	parse_file(target, into);
}

void blitz::parser::parse_type_decl()
{
	auto first = tk();
	if (_depth != 0) {
		throw error(first, "Types can't be defined inside of other blocks.");
	}
	advance();

	auto name = tk();
	if ((name.type != blitz::token::variant::TEXT) || reserved.count(lower(name.text))) {
		throw error(name, blitz::format("Unexpected %s, expected a type name.", name.to_string().c_str()));
	}
	advance();

	auto decl   = std::make_unique<ast::type_decl>();
	decl->where = here(first);
	decl->name  = name.text;

	while (true) {
		skip_empty();
		if (is_keyword(tk(), "endtype")) {
			advance();
			break;
		} else if (is_keyword(tk(), "end") && is_keyword(tk(1), "type")) {
			advance();
			advance();
			break;
		} else if (!is_keyword(tk(), "field")) {
			throw error(tk(), blitz::format("Unexpected %s, expected 'Field' or 'End Type'.", tk().to_string().c_str()));
		}
		advance();

		while (true) {
			auto fname = tk();
			if (fname.type != blitz::token::variant::TEXT) {
				throw error(fname, blitz::format("Unexpected %s, expected a field name.", fname.to_string().c_str()));
			}
			advance();

			ast::field_decl field;
			field.where       = here(fname);
			field.name        = fname.text;
			field.type        = parse_type_suffix(fname);
			field.struct_name = _struct_name;
			field.typed = (field.type != blitz::types::type::UNKNOWN);
			if (field.type == blitz::types::type::UNKNOWN) {
				field.type = blitz::types::type::INT32;
			}
			if (is_symbol(tk(), "[")) {
				advance();
				field.array_size = parse_expression();
				expect_symbol("]");
			}
			decl->fields.push_back(std::move(field));

			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
	}
	_program->types.push_back(std::move(decl));
}

void blitz::parser::parse_dim(ast::block& into)
{
	auto first = tk();
	advance();

	auto node   = std::make_unique<ast::dim_statement>();
	node->where = here(first);
	while (true) {
		auto name = tk();
		if ((name.type != blitz::token::variant::TEXT) || reserved.count(lower(name.text))) {
			throw error(name, blitz::format("Unexpected %s, expected an array name.", name.to_string().c_str()));
		}
		advance();

		ast::dim_declaration decl;
		decl.where       = here(name);
		decl.name        = name.text;
		decl.type        = parse_type_suffix(name);
		decl.struct_name = _struct_name;
		expect_symbol("(");
		while (true) {
			decl.sizes.push_back(parse_expression());
			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
		expect_symbol(")");
		if (decl.sizes.size() > 4) {
			throw error(name, "Arrays can have up to 4 dimensions.");
		}
		node->arrays.push_back(std::move(decl));

		if (is_symbol(tk(), ",")) {
			advance();
			continue;
		}
		break;
	}
	into.push_back(std::move(node));
}

void blitz::parser::parse_delete(ast::block& into)
{
	auto first = tk();
	advance();

	auto node   = std::make_unique<ast::delete_statement>();
	node->where = here(first);
	if (is_keyword(tk(), "each")) {
		advance();
		auto type_tk = tk();
		if (type_tk.type != blitz::token::variant::TEXT) {
			throw error(type_tk, blitz::format("Unexpected %s, expected a type name.", type_tk.to_string().c_str()));
		}
		advance();
		node->each_type = type_tk.text;
	} else {
		node->object = parse_expression();
	}
	into.push_back(std::move(node));
}

void blitz::parser::parse_insert(ast::block& into)
{
	auto first = tk();
	advance();

	auto node    = std::make_unique<ast::insert_statement>();
	node->where  = here(first);
	node->object = parse_unary();
	if (is_keyword(tk(), "before")) {
		node->after = false;
	} else if (is_keyword(tk(), "after")) {
		node->after = true;
	} else {
		throw error(tk(), blitz::format("Unexpected %s, expected 'Before' or 'After'.", tk().to_string().c_str()));
	}
	advance();
	node->other = parse_unary();
	into.push_back(std::move(node));
}

void blitz::parser::parse_identifier_statement(ast::block& into)
{
	auto name  = tk();
	size_t start = _pos;

	// Assignment: the left side can be a variable, a field, or an array element.
	try {
		auto target = parse_primary();
		if (is_symbol(tk(), "=")) {
			auto node    = std::make_unique<ast::assign>();
			node->where  = here(name);
			node->target = std::move(target);
			advance();
			node->value = parse_expression();
			into.push_back(std::move(node));
			return;
		}
	} catch (blitz::error const&) {
		// Not an assignment, the command parsing below reports errors properly.
	}
	_pos = start;

	advance();
	auto type        = parse_type_suffix(name);
	auto struct_name = _struct_name;

	auto node                = std::make_unique<ast::call_statement>();
	node->where              = here(name);
	node->invocation         = std::make_unique<ast::call>();
	node->invocation->where  = here(name);
	node->invocation->name   = name.text;
	node->invocation->type   = type;
	node->invocation->struct_name = struct_name;

	if (is_symbol(tk(), "(")) {
		// Try `Name(Arg, ...)` first. If something follows the `)`, it's actually `Name (Expression)...`.
		size_t saved = _pos;
		advance();
		auto args = parse_arguments();
		expect_symbol(")");
		if (is_terminator(tk())) {
			node->invocation->arguments = std::move(args);
			into.push_back(std::move(node));
			return;
		}
		_pos = saved;
	}

	if (!is_terminator(tk())) {
		while (true) {
			node->invocation->arguments.push_back(parse_expression());
			if (is_symbol(tk(), ",")) {
				advance();
				continue;
			}
			break;
		}
	}
	into.push_back(std::move(node));
}
