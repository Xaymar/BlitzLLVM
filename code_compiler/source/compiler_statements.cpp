void blitz::compiler::gen_block(ast::block const& block)
{
	bool reported = false;
	for (auto const& stmt : block) {
		// Anything after a Return, End, Goto or Exit is skipped over, unless a label (or Data, which is not code) can be jumped to.
		if (_terminated && !reported && !dynamic_cast<ast::label_statement const*>(stmt.get()) && !dynamic_cast<ast::data_statement const*>(stmt.get())) {
			warn(stmt->where, "unreachable-code", "This statement can never run.");
			reported = true;
		}
		if (dynamic_cast<ast::label_statement const*>(stmt.get())) {
			reported = false;
		}
		gen_statement(stmt.get());
	}
}

void blitz::compiler::gen_statement(ast::statement const* node)
{
	at here(*this, node->where);

	// Statements that make temporary strings free them when they are done.
	if (dynamic_cast<ast::declare const*>(node) || dynamic_cast<ast::assign const*>(node) || dynamic_cast<ast::call_statement const*>(node) || dynamic_cast<ast::read_statement const*>(node) || dynamic_cast<ast::select_statement const*>(node)) {
		scope sc;
		scope_begin(sc);
		gen_statement_inner(node);
		scope_end(sc);
		return;
	}
	gen_statement_inner(node);
}

// Whether any Return in the block (or the blocks inside of it) brings a value back.
static bool returns_value(blitz::ast::block const& body)
{
	namespace ast = blitz::ast;
	for (auto const& stmt : body) {
		auto const* node = stmt.get();
		if (auto n = dynamic_cast<ast::return_statement const*>(node)) {
			if (n->value) {
				return true;
			}
		} else if (auto n = dynamic_cast<ast::if_statement const*>(node)) {
			for (auto const& br : n->branches) {
				if (returns_value(br.body)) {
					return true;
				}
			}
		} else if (auto n = dynamic_cast<ast::while_statement const*>(node)) {
			if (returns_value(n->body)) {
				return true;
			}
		} else if (auto n = dynamic_cast<ast::repeat_statement const*>(node)) {
			if (returns_value(n->body)) {
				return true;
			}
		} else if (auto n = dynamic_cast<ast::for_statement const*>(node)) {
			if (returns_value(n->body)) {
				return true;
			}
		} else if (auto n = dynamic_cast<ast::select_statement const*>(node)) {
			for (auto const& c : n->cases) {
				if (returns_value(c.body)) {
					return true;
				}
			}
		}
	}
	return false;
}

void blitz::compiler::gen_statement_inner(ast::statement const* node)
{
	if (auto n = dynamic_cast<ast::declare const*>(node)) {
		gen_declare(n);
	} else if (auto n = dynamic_cast<ast::assign const*>(node)) {
		gen_assign(n);
	} else if (auto n = dynamic_cast<ast::call_statement const*>(node)) {
		auto result = gen_call(n->invocation.get());
		// A function of the program always has a type, but one without 'Return value' is a procedure and has nothing to throw away.
		bool has_value = (result.type != type::UNKNOWN);
		auto user      = _functions.find(lower(n->invocation->name));
		if (has_value && (user != _functions.end()) && !find_dim(lower(n->invocation->name))) {
			has_value = returns_value(user->second.declaration->body);
		}
		if (has_value) {
			warn(n->invocation->where, "unused-result", "The result of '" + n->invocation->name + "' is not used.", "Store it in a variable, or turn this off with -Wno-unused-result.");
		}
	} else if (auto n = dynamic_cast<ast::if_statement const*>(node)) {
		gen_if(n);
	} else if (auto n = dynamic_cast<ast::while_statement const*>(node)) {
		gen_while(n);
	} else if (auto n = dynamic_cast<ast::repeat_statement const*>(node)) {
		gen_repeat(n);
	} else if (auto n = dynamic_cast<ast::for_statement const*>(node)) {
		gen_for(n);
	} else if (auto n = dynamic_cast<ast::select_statement const*>(node)) {
		gen_select(n);
	} else if (auto n = dynamic_cast<ast::return_statement const*>(node)) {
		gen_return(n);
	} else if (dynamic_cast<ast::data_statement const*>(node)) {
		// Data does nothing when it is run, it was collected before.
	} else if (auto n = dynamic_cast<ast::read_statement const*>(node)) {
		gen_read(n);
	} else if (auto n = dynamic_cast<ast::restore_statement const*>(node)) {
		gen_restore(n);
	} else if (auto n = dynamic_cast<ast::label_statement const*>(node)) {
		gen_label(n);
	} else if (auto n = dynamic_cast<ast::goto_statement const*>(node)) {
		gen_goto(n);
	} else if (auto n = dynamic_cast<ast::gosub_statement const*>(node)) {
		gen_gosub(n);
	} else if (auto n = dynamic_cast<ast::dim_statement const*>(node)) {
		gen_dim(n);
	} else if (auto n = dynamic_cast<ast::delete_statement const*>(node)) {
		gen_delete(n);
	} else if (auto n = dynamic_cast<ast::insert_statement const*>(node)) {
		gen_insert(n);
	} else if (dynamic_cast<ast::exit_statement const*>(node)) {
		if (_exits.empty()) {
			throw err(node->where, "Exit can only be used inside of a loop.");
		}
		emit_terminator("br label %" + _exits.back());
	} else if (dynamic_cast<ast::stop_statement const*>(node)) {
		// Stop is for the debugger: a debug build breaks here, any other build carries on.
		if (debug) {
			declare("llvm.debugtrap", "declare void @llvm.debugtrap()");
			emit("call void @llvm.debugtrap()");
		}
	} else if (dynamic_cast<ast::end_statement const*>(node)) {
		call_runtime("bb_end", type::UNKNOWN, {});
		emit_terminator("unreachable");
	} else {
		throw err(node->where, "Unsupported statement.");
	}
}

void blitz::compiler::gen_declare(ast::declare const* node)
{
	for (auto const& decl : node->variables) {
		variable var;
		if (node->global || node->constant) {
			var = _global_variables.at(lower(decl.name));
		} else {
			if (decl.type == type::UNKNOWN) {
				warn_typeless(decl.where, decl.name);
			}
			type t = (decl.type == type::UNKNOWN) ? type::INT32 : decl.type;
			uint32_t count = decl.array_size ? array_count(decl.array_size.get(), decl.where) : 0;
			if (count && !_in_main && uint64_t(count) * array_element_size(t) > 4096) {
				auto kib = (uint64_t(count) * array_element_size(t) + 1023) / 1024;
				warn(decl.where, "large-local-array", "'" + decl.name + "' is a Local array of " + std::to_string(kib) + " KiB, which is made again on every call of the function.", "A Local array above 4 KiB costs time on every call, and above 64 KiB it lives on the heap. Declare it with Global or Dim outside of the function to make it once, or turn this off with -Wno-large-local-array.");
			}
			var            = create_local(decl.name, t, false, decl.where, decl.struct_name, count);
			auto& stored        = _locals[lower(decl.name)];
			stored.where        = decl.where;
			stored.name         = decl.name;
			stored.check_unused = true;
		}
		if (var.count) {
			if (decl.initial) {
				throw err(decl.where, "Arrays can't have a value.");
			}
			if (!node->global) {
				// Like other locals, arrays start out empty every time they are declared.
				auto array = "[" + std::to_string(var.count) + " x " + blitz::types::to_llvm(var.type) + "]";
				if (var.type == type::STRING) {
					declare("bb_str_free_array", "declare void @bb_str_free_array(ptr, i32)");
					emit("call void @bb_str_free_array(ptr " + var.pointer + ", i32 " + std::to_string(var.count) + ")");
				}
				emit(zero_memory(var.pointer, array));
			}
			continue;
		}

		auto llvm = blitz::types::to_llvm(var.type);
		if (decl.initial) {
			auto v = convert(gen(decl.initial.get()), var.type, decl.initial->where, true, var.sname, &decl.initial->covers);
			store_value({ var.pointer, var.type, var.sname, 0, false }, v);
		} else if (!node->global) {
			// Locals start out as zero every time the declaration is executed.
			store_value({ var.pointer, var.type, var.sname, 0, false }, zero(var.type));
		}
	}
}

bool blitz::compiler::calls_function_of_program(ast::expression const* expr) const
{
	if (!expr) {
		return false;
	}
	if (auto c = dynamic_cast<ast::call const*>(expr)) {
		if (_functions.count(lower(c->name))) {
			return true;
		}
		for (auto const& arg : c->arguments) {
			if (calls_function_of_program(arg.get())) {
				return true;
			}
		}
	} else if (auto u = dynamic_cast<ast::unary const*>(expr)) {
		return calls_function_of_program(u->operand.get());
	} else if (auto b = dynamic_cast<ast::binary const*>(expr)) {
		return calls_function_of_program(b->lhs.get()) || calls_function_of_program(b->rhs.get());
	} else if (auto f = dynamic_cast<ast::field_access const*>(expr)) {
		return calls_function_of_program(f->object.get());
	} else if (auto i = dynamic_cast<ast::index_access const*>(expr)) {
		return calls_function_of_program(i->base.get()) || calls_function_of_program(i->index.get());
	} else if (auto n = dynamic_cast<ast::list_neighbor const*>(expr)) {
		return calls_function_of_program(n->object.get());
	} else if (auto h = dynamic_cast<ast::object_from_handle const*>(expr)) {
		return calls_function_of_program(h->handle.get());
	} else if (auto r = dynamic_cast<ast::reference const*>(expr)) {
		return _functions.count(lower(r->name)) != 0; // A function can be called without parenthesis.
	}
	return false;
}

void blitz::compiler::gen_assign(ast::assign const* node)
{
	value   rhs;
	address addr;
	if (dynamic_cast<ast::reference const*>(node->target.get())) {
		rhs  = gen(node->value.get());
		addr = gen_address(node->target.get(), true);
	} else {
		// The original evaluates the value and the place it is stored to in the order of the registers they need. Numbers are moved
		// to the place, strings and objects are handed to a function together with it.
		auto value_part = capture(node->value.get());
		auto addr_code  = capture_code([&] { addr = gen_address(node->target.get(), true); });
		bool by_call    = (addr.type == type::STRING) || (addr.type == type::STRUCT);
		bool addr_first = sane_evaluation_order || (by_call ? !compiler_detail::right_first(addr.need, value_part.v.need) : compiler_detail::right_first(value_part.v.need, addr.need));
		// A function of the program can Dim the array again, which frees the memory that the address of the element points into.
		auto const* target_call = dynamic_cast<ast::call const*>(node->target.get());
		if (addr_first && target_call && find_dim(target_call->name) && _redim_in_function.count(lower(target_call->name)) && calls_function_of_program(node->value.get())) {
			addr_first = false;
		}
		place(addr_first ? addr_code : value_part.code);
		place(addr_first ? value_part.code : addr_code);
		rhs = value_part.v;
	}
	if (addr.constant) {
		throw err(node->where, "This is a constant and can't be changed.");
	}
	if (addr.count) {
		throw err(node->where, "Arrays can't be assigned as a whole, use an index.");
	}
	auto v = convert(rhs, addr.type, node->value->where, true, addr.sname, &node->value->covers);
	store_value(addr, v);
}

void blitz::compiler::gen_if(ast::if_statement const* node)
{
	auto end = label("if.end");
	for (size_t idx = 0; idx < node->branches.size(); idx++) {
		auto const& branch = node->branches[idx];
		if (!branch.condition) {
			// Else
			gen_block(branch.body);
			break;
		}

		auto then_l = label("if.then"), next_l = label("if.next");
		scope sc;
		scope_begin(sc);
		auto cond = truthy(gen(branch.condition.get()), branch.condition->where);
		scope_end(sc);
		emit_terminator("br i1 " + cond + ", label %" + then_l + ", label %" + next_l);
		begin_label(then_l);
		gen_block(branch.body);
		if (!_terminated) {
			emit_terminator("br label %" + end);
		}
		begin_label(next_l);
	}
	begin_label(end);
}

void blitz::compiler::gen_while(ast::while_statement const* node)
{
	auto cond_l = label("while.cond"), body_l = label("while.body"), end_l = label("while.end");
	begin_label(cond_l);
	scope sc;
	scope_begin(sc);
	auto cond = truthy(gen(node->condition.get()), node->condition->where);
	scope_end(sc);
	emit_terminator("br i1 " + cond + ", label %" + body_l + ", label %" + end_l);

	begin_label(body_l);
	_exits.push_back(end_l);
	gen_block(node->body);
	_exits.pop_back();
	if (!_terminated) {
		emit_terminator("br label %" + cond_l);
	}
	begin_label(end_l);
}

void blitz::compiler::gen_repeat(ast::repeat_statement const* node)
{
	auto body_l = label("repeat.body"), end_l = label("repeat.end");
	begin_label(body_l);
	_exits.push_back(end_l);
	gen_block(node->body);
	_exits.pop_back();

	if (node->condition) {
		scope sc;
		scope_begin(sc);
		auto cond = truthy(gen(node->condition.get()), node->condition->where);
		scope_end(sc);
		emit_terminator("br i1 " + cond + ", label %" + end_l + ", label %" + body_l);
	} else if (!_terminated) {
		emit_terminator("br label %" + body_l);
	}
	begin_label(end_l);
}

// The counter of a For loop has one type, and the start, end and step are turned into it. When it is smaller than the end (a Byte
// counting to 300) it never reaches the end and the loop never stops, and a counter of another kind rounds what it is given.
void blitz::compiler::warn_loop_type(ast::expression const* expr, std::string const& name, blitz::types::type counter, const char* part, blitz::types::type given)
{
	namespace t = blitz::types;
	// A number that is written out and fits in the counter is fine (`For b:Byte = 0 To 10`).
	data_value folded;
	if (fold_data(expr, folded) && (folded.kind != data_value::STRING)) {
		if (t::is_real(counter)) {
			return;
		}
		double amount = (folded.kind == data_value::REAL) ? folded.f : double(folded.i);
		unsigned bits = t::bits(counter);
		double   lo   = t::is_signed(counter) ? -std::ldexp(1.0, int(bits) - 1) : 0.0;
		double   hi   = t::is_signed(counter) ? std::ldexp(1.0, int(bits) - 1) - 1.0 : std::ldexp(1.0, int(bits)) - 1.0;
		if ((amount == std::floor(amount)) && (amount >= lo) && (amount <= hi)) {
			return;
		}
	}
	auto const& where = expr->where;
	std::string note;
	// In a program compiled with -d every mismatch is an error, in a release it is a warning.
	if (t::is_integer(counter) && t::is_integer(given) && (t::bits(counter) < t::bits(given))) {
		note = " A value that doesn't fit in " + t::display(counter) + " can't be reached by the counter, so the loop may never end.";
	} else if (t::is_integer(counter) && t::is_real(given)) {
		note = " The counter is an integer, so the " + std::string(part) + " is rounded.";
	} else if (t::is_integer(counter) && !t::is_signed(counter) && t::is_signed(given)) {
		note = " The counter can't go below 0, so a negative " + std::string(part) + " makes the loop never end.";
	}
	warn(where, "loop-type-mismatch", "The " + std::string(part) + " of the For loop is " + t::display(given) + ", but '" + name + "' is " + t::display(counter) + "." + note, "Give '" + name + "' and the " + part + " the same type, or turn this off with -Wno-loop-type-mismatch.", {}, std::string(), true);
}

void blitz::compiler::gen_for(ast::for_statement const* node)
{
	namespace t = blitz::types;

	if (!node->each_type.empty()) {
		gen_for_each(node);
		return;
	}
	auto& var = lookup(node->variable->name, node->variable->type, node->variable->where);
	if (!is_number(var.type)) {
		throw err(node->where, "The variable of a For loop has to be a number.");
	}
	if (var.constant) {
		throw err(node->where, "'" + node->variable->name + "' is a constant and can't be changed.");
	}
	auto llvm = t::to_llvm(var.type);
	bool real = t::is_real(var.type);
	bool sign = t::is_signed(var.type) || real;

	if (real) {
		warn(node->where, "loop-iterator-type-unsafe", "'" + node->variable->name + "' is " + t::display(var.type) + ", which can't count exactly.", "A loop that counts with a real number can run once more or less than expected, or never end. Count with an integer and calculate the real number from it, or turn this off with -Wno-loop-iterator-type-unsafe.");
	}
	if (node->step) {
		data_value folded;
		if (fold_data(node->step.get(), folded) && (folded.kind != data_value::STRING)) {
			double amount = (folded.kind == data_value::REAL) ? folded.f : double(folded.i);
			if (amount == 0.0) {
				throw err(node->step->where, "The step of a For loop can't be 0, because the loop would never end.");
			} else if (!std::isfinite(amount)) {
				throw err(node->step->where, "The step of a For loop can't be infinite or not a number, because the loop would never end.");
			}
		} else {
			warn(node->step->where, "loop-unroll-requires-constant", "The step of this For loop is not a constant.", "The loop can only be unrolled when the step is known at compile time. Use a constant step, or turn this off with -Wno-loop-unroll-requires-constant.");
		}
	}

	scope sc;
	scope_begin(sc);
	auto from_raw = gen(node->from.get());
	auto from     = convert(from_raw, var.type, node->from->where, true, std::string(), &node->from->covers);
	value step_raw{ "", var.type };
	if (node->step) {
		step_raw = gen(node->step.get());
	}
	auto step = node->step ? convert(step_raw, var.type, node->step->where, true, std::string(), &node->step->covers) : constant(var.type, 1);
	scope_end(sc);
	if (from_raw.type != var.type) {
		warn_loop_type(node->from.get(), node->variable->name, var.type, "Start", from_raw.type);
	}
	if (node->step && (step_raw.type != var.type)) {
		warn_loop_type(node->step.get(), node->variable->name, var.type, "Step", step_raw.type);
	}
	emit("store " + llvm + " " + from.repr + ", ptr " + var.pointer);

	// A Return from a Gosub can jump into the middle of the loop, past the place where the step was worked out. It lives in the stack
	// frame then, like in the original, so that every way into the loop sees it.
	std::string step_slot;
	if (!_gosub_stack.empty()) {
		step_slot = "%for.step." + std::to_string(_counter++);
		_allocas << "  " << step_slot << " = alloca " << llvm << "\n";
		emit("store " + llvm + " " + step.repr + ", ptr " + step_slot);
	}

	auto cond_l = label("for.cond"), body_l = label("for.body"), step_l = label("for.step"), end_l = label("for.end");
	begin_label(cond_l);
	auto cur = tmp(), neg = tmp(), up = tmp(), down = tmp(), cont = tmp();
	if (!step_slot.empty()) {
		auto loaded_step = tmp();
		emit(loaded_step + " = load " + llvm + ", ptr " + step_slot);
		step.repr = loaded_step;
	}
	// Like in the original, the limit is worked out again before every pass, so changing what it uses changes the loop.
	scope limit_scope;
	scope_begin(limit_scope);
	auto to_raw = gen(node->to.get());
	auto to     = convert(to_raw, var.type, node->to->where, true, std::string(), &node->to->covers);
	scope_end(limit_scope);
	if (to_raw.type != var.type) {
		warn_loop_type(node->to.get(), node->variable->name, var.type, "End", to_raw.type);
	}
	emit(cur + " = load " + llvm + ", ptr " + var.pointer);
	if (sign) {
		emit(neg + (real ? " = fcmp olt " : " = icmp slt ") + llvm + " " + step.repr + ", " + zero(var.type).repr);
	} else {
		neg = "false"; // Unsigned steps never count down.
	}
	emit(up + (real ? " = fcmp ole " : (sign ? " = icmp sle " : " = icmp ule ")) + llvm + " " + cur + ", " + to.repr);
	emit(down + (real ? " = fcmp oge " : (sign ? " = icmp sge " : " = icmp uge ")) + llvm + " " + cur + ", " + to.repr);
	emit(cont + " = select i1 " + neg + ", i1 " + down + ", i1 " + up);
	emit_terminator("br i1 " + cont + ", label %" + body_l + ", label %" + end_l);

	begin_label(body_l);
	_exits.push_back(end_l);
	gen_block(node->body);
	_exits.pop_back();

	begin_label(step_l);
	auto next = tmp(), after = tmp();
	if (!step_slot.empty()) {
		auto loaded_step = tmp();
		emit(loaded_step + " = load " + llvm + ", ptr " + step_slot);
		step.repr = loaded_step;
	}
	emit(next + " = load " + llvm + ", ptr " + var.pointer);
	emit(after + (real ? " = fadd " : " = add ") + llvm + " " + next + ", " + step.repr);
	emit("store " + llvm + " " + after + ", ptr " + var.pointer);
	emit_terminator("br label %" + cond_l);
	begin_label(end_l);
}

void blitz::compiler::gen_select(ast::select_statement const* node)
{
	auto subject = gen(node->subject.get());
	if (subject.type == type::UNKNOWN) {
		throw err(node->subject->where, "Expression does not return a value.");
	}
	auto end_l = label("select.end");

	// Test all cases in order, the Default (wherever it is) runs if none matched.
	std::vector<std::string> body_labels;
	for (size_t idx = 0; idx < node->cases.size(); idx++) {
		body_labels.push_back(label("select.case"));
	}
	std::string default_l = end_l;

	for (size_t idx = 0; idx < node->cases.size(); idx++) {
		auto const& entry = node->cases[idx];
		if (entry.values.empty()) {
			default_l = body_labels[idx];
			continue;
		}
		for (auto const& expr : entry.values) {
			auto next_l = label("select.next");
			auto given  = gen(expr.get());
			if (is_number(subject.type) || (subject.type == type::STRING)) {
				// The cases are converted to the type of what is selected, so Select 2 Case 2.4 matches.
				given = convert(given, subject.type, expr->where, false);
			}
			auto match = compare(ast::binary::op::EQUAL, subject, given, expr->where);
			emit_terminator("br i1 " + match + ", label %" + body_labels[idx] + ", label %" + next_l);
			begin_label(next_l);
		}
	}
	emit_terminator("br label %" + default_l);

	for (size_t idx = 0; idx < node->cases.size(); idx++) {
		begin_label(body_labels[idx]);
		gen_block(node->cases[idx].body);
		if (!_terminated) {
			emit_terminator("br label %" + end_l);
		}
	}
	begin_label(end_l);
}

void blitz::compiler::gen_return(ast::return_statement const* node)
{
	// Without a value, Return ends a Gosub if there is one to end.
	if (!node->value && !_gosub_stack.empty()) {
		gen_gosub_return(node->where);
		return;
	}
	if (_in_main) {
		throw err(node->where, "Return can only be used inside of a function, or after a Gosub.");
	}
	if (_return_void) {
		if (node->value) {
			throw err(node->value->where, "Return can't give a value in a function that returns Void.");
		}
		emit_terminator("br label %" + _exit_label);
		return;
	}
	if (!node->value) {
		_return_kinds.insert("void");
	}
	if (!node->value && _return_typed) {
		std::string suggestion = blitz::types::is_integer(_return_type) ? "0" : (blitz::types::is_real(_return_type) ? "0.0" : (_return_type == type::STRING ? "\"\"" : "Null"));
		warn(node->where, "return-missing-value", "Return has no value, but the function returns " + (_return_type == type::STRUCT ? "an object" : blitz::types::display(_return_type)) + ".", "Return a value, such as 'Return " + suggestion + "'.");
	}
	auto  llvm = blitz::types::to_llvm(_return_type);
	value v    = zero(_return_type);
	if (node->value) {
		auto given = gen(node->value.get());
		_return_kinds.insert((given.type == type::INT32) ? "int" : (given.type == type::FLOAT32) ? "float" : (given.type == type::STRING) ? "string" : "other");
		// A number written in the program that fits is fine, like it is for the implicit conversions.
		bool literal = blitz::types::is_integer(given.type) && !given.repr.empty() && (given.repr.find_first_not_of("-0123456789") == std::string::npos);
		bool report  = (given.type != _return_type) && (given.type != type::STRUCT) && (_return_type != type::STRUCT) && (given.type != type::UNKNOWN) && !(literal && !is_lossy(given.type, _return_type, given.repr));
		if (report && warning_options.enabled("return-type-mismatch")) {
			namespace t = blitz::types;
			std::string fix;
			if (_return_type == type::INT32) {
				fix = "Int(value)";
			} else if (_return_type == type::FLOAT32) {
				fix = "Float(value)";
			} else if (_return_type == type::STRING) {
				fix = "Str(value)";
			}
			warn(node->value->where, "return-type-mismatch", "Return gives " + t::display(given.type) + ", but the function returns " + t::display(_return_type) + ".", fix.empty() ? "Change the type of the function or of the returned value." : "Use " + fix + " to convert on purpose.");
			// This says what the implicit conversion warnings would say.
			v = convert(given, _return_type, node->value->where, false, _return_sname, &node->value->covers);
		} else {
			v = convert(given, _return_type, node->value->where, true, _return_sname, &node->value->covers);
		}
	}
	if (_return_type == type::STRING) {
		// The caller gets a copy as its own temporary, and what this function made is freed.
		declare("bb_str_return", "declare ptr @bb_str_return(ptr, i32)");
		auto copy = tmp();
		emit(copy + " = call ptr @bb_str_return(ptr " + v.repr + ", i32 %entry.mark)");
		v             = { copy, type::STRING };
		_uses_strings = true;
	}
	emit("store " + llvm + " " + v.repr + ", ptr " + _ret_slot);
	emit_terminator("br label %" + _exit_label);
}
