void blitz::compiler::gen_block(ast::block const& block)
{
	for (auto const& stmt : block) {
		gen_statement(stmt.get());
	}
}

void blitz::compiler::gen_statement(ast::statement const* node)
{
	// Statements that make temporary strings free them when they are done.
	if (dynamic_cast<ast::declare const*>(node) || dynamic_cast<ast::assign const*>(node) || dynamic_cast<ast::call_statement const*>(node) || dynamic_cast<ast::read_statement const*>(node) || dynamic_cast<ast::select_statement const*>(node)) {
		scope sc;
		scope_begin(sc);
		gen_statement_inner(node);
		scope_end(sc);
		return;
	}
	gen_statement_inner(node);
}

void blitz::compiler::gen_statement_inner(ast::statement const* node)
{
	if (auto n = dynamic_cast<ast::declare const*>(node)) {
		gen_declare(n);
	} else if (auto n = dynamic_cast<ast::assign const*>(node)) {
		gen_assign(n);
	} else if (auto n = dynamic_cast<ast::call_statement const*>(node)) {
		gen_call(n->invocation.get());
	} else if (auto n = dynamic_cast<ast::if_statement const*>(node)) {
		gen_if(n);
	} else if (auto n = dynamic_cast<ast::while_statement const*>(node)) {
		gen_while(n);
	} else if (auto n = dynamic_cast<ast::repeat_statement const*>(node)) {
		gen_repeat(n);
	} else if (auto n = dynamic_cast<ast::for_statement const*>(node)) {
		gen_for(n);
	} else if (auto n = dynamic_cast<ast::select_statement const*>(node)) {
		gen_select(n);
	} else if (auto n = dynamic_cast<ast::return_statement const*>(node)) {
		gen_return(n);
	} else if (dynamic_cast<ast::data_statement const*>(node)) {
		// Data does nothing when it is run, it was collected before.
	} else if (auto n = dynamic_cast<ast::read_statement const*>(node)) {
		gen_read(n);
	} else if (auto n = dynamic_cast<ast::restore_statement const*>(node)) {
		gen_restore(n);
	} else if (auto n = dynamic_cast<ast::label_statement const*>(node)) {
		gen_label(n);
	} else if (auto n = dynamic_cast<ast::goto_statement const*>(node)) {
		gen_goto(n);
	} else if (auto n = dynamic_cast<ast::gosub_statement const*>(node)) {
		gen_gosub(n);
	} else if (auto n = dynamic_cast<ast::dim_statement const*>(node)) {
		gen_dim(n);
	} else if (auto n = dynamic_cast<ast::delete_statement const*>(node)) {
		gen_delete(n);
	} else if (auto n = dynamic_cast<ast::insert_statement const*>(node)) {
		gen_insert(n);
	} else if (dynamic_cast<ast::exit_statement const*>(node)) {
		if (_exits.empty()) {
			throw err(node->where, "Exit can only be used inside of a loop.");
		}
		emit_terminator("br label %" + _exits.back());
	} else if (dynamic_cast<ast::end_statement const*>(node)) {
		call_runtime("bb_end", type::UNKNOWN, {});
		emit_terminator("unreachable");
	} else {
		throw err(node->where, "Unsupported statement.");
	}
}

void blitz::compiler::gen_declare(ast::declare const* node)
{
	for (auto const& decl : node->variables) {
		variable var;
		if (node->global || node->constant) {
			var = _global_variables.at(lower(decl.name));
		} else {
			type t = (decl.type == type::UNKNOWN) ? type::INT32 : decl.type;
			uint32_t count = decl.array_size ? array_count(decl.array_size.get(), decl.where) : 0;
			var            = create_local(decl.name, t, false, decl.where, decl.struct_name, count);
		}
		if (var.count) {
			if (decl.initial) {
				throw err(decl.where, "Arrays can't have a value.");
			}
			if (!node->global) {
				// Like other locals, arrays start out empty every time they are declared.
				auto array = "[" + std::to_string(var.count) + " x " + blitz::types::to_llvm(var.type) + "]";
				if (var.type == type::STRING) {
					declare("bb_str_free_array", "declare void @bb_str_free_array(ptr, i32)");
					emit("call void @bb_str_free_array(ptr " + var.pointer + ", i32 " + std::to_string(var.count) + ")");
				}
				emit("store " + array + " zeroinitializer, ptr " + var.pointer);
			}
			continue;
		}

		auto llvm = blitz::types::to_llvm(var.type);
		if (decl.initial) {
			auto v = convert(gen(decl.initial.get()), var.type, decl.initial->where, true, var.sname);
			store_value({ var.pointer, var.type, var.sname, 0, false }, v);
		} else if (!node->global) {
			// Locals start out as zero every time the declaration is executed.
			store_value({ var.pointer, var.type, var.sname, 0, false }, zero(var.type));
		}
	}
}

void blitz::compiler::gen_assign(ast::assign const* node)
{
	auto rhs  = gen(node->value.get());
	auto addr = gen_address(node->target.get());
	if (addr.constant) {
		throw err(node->where, "This is a constant and can't be changed.");
	}
	if (addr.count) {
		throw err(node->where, "Arrays can't be assigned as a whole, use an index.");
	}
	auto v = convert(rhs, addr.type, node->value->where, true, addr.sname);
	store_value(addr, v);
}

void blitz::compiler::gen_if(ast::if_statement const* node)
{
	auto end = label("if.end");
	for (size_t idx = 0; idx < node->branches.size(); idx++) {
		auto const& branch = node->branches[idx];
		if (!branch.condition) {
			// Else
			gen_block(branch.body);
			break;
		}

		auto then_l = label("if.then"), next_l = label("if.next");
		scope sc;
		scope_begin(sc);
		auto cond = truthy(gen(branch.condition.get()), branch.condition->where);
		scope_end(sc);
		emit_terminator("br i1 " + cond + ", label %" + then_l + ", label %" + next_l);
		begin_label(then_l);
		gen_block(branch.body);
		if (!_terminated) {
			emit_terminator("br label %" + end);
		}
		begin_label(next_l);
	}
	begin_label(end);
}

void blitz::compiler::gen_while(ast::while_statement const* node)
{
	auto cond_l = label("while.cond"), body_l = label("while.body"), end_l = label("while.end");
	begin_label(cond_l);
	scope sc;
	scope_begin(sc);
	auto cond = truthy(gen(node->condition.get()), node->condition->where);
	scope_end(sc);
	emit_terminator("br i1 " + cond + ", label %" + body_l + ", label %" + end_l);

	begin_label(body_l);
	_exits.push_back(end_l);
	gen_block(node->body);
	_exits.pop_back();
	if (!_terminated) {
		emit_terminator("br label %" + cond_l);
	}
	begin_label(end_l);
}

void blitz::compiler::gen_repeat(ast::repeat_statement const* node)
{
	auto body_l = label("repeat.body"), end_l = label("repeat.end");
	begin_label(body_l);
	_exits.push_back(end_l);
	gen_block(node->body);
	_exits.pop_back();

	if (node->condition) {
		scope sc;
		scope_begin(sc);
		auto cond = truthy(gen(node->condition.get()), node->condition->where);
		scope_end(sc);
		emit_terminator("br i1 " + cond + ", label %" + end_l + ", label %" + body_l);
	} else if (!_terminated) {
		emit_terminator("br label %" + body_l);
	}
	begin_label(end_l);
}

void blitz::compiler::gen_for(ast::for_statement const* node)
{
	namespace t = blitz::types;

	if (!node->each_type.empty()) {
		gen_for_each(node);
		return;
	}
	auto& var = lookup(node->variable->name, node->variable->type);
	if (!is_number(var.type)) {
		throw err(node->where, "The variable of a For loop has to be a number.");
	}
	if (var.constant) {
		throw err(node->where, "'" + node->variable->name + "' is a constant and can't be changed.");
	}
	auto llvm = t::to_llvm(var.type);
	bool real = t::is_real(var.type);
	bool sign = t::is_signed(var.type) || real;

	scope sc;
	scope_begin(sc);
	auto from = convert(gen(node->from.get()), var.type, node->from->where, true);
	auto to   = convert(gen(node->to.get()), var.type, node->to->where, true);
	auto step = node->step ? convert(gen(node->step.get()), var.type, node->step->where, true) : constant(var.type, 1);
	scope_end(sc);
	emit("store " + llvm + " " + from.repr + ", ptr " + var.pointer);

	auto cond_l = label("for.cond"), body_l = label("for.body"), step_l = label("for.step"), end_l = label("for.end");
	begin_label(cond_l);
	auto cur = tmp(), neg = tmp(), up = tmp(), down = tmp(), cont = tmp();
	emit(cur + " = load " + llvm + ", ptr " + var.pointer);
	if (sign) {
		emit(neg + (real ? " = fcmp olt " : " = icmp slt ") + llvm + " " + step.repr + ", " + zero(var.type).repr);
	} else {
		neg = "false"; // Unsigned steps never count down.
	}
	emit(up + (real ? " = fcmp ole " : (sign ? " = icmp sle " : " = icmp ule ")) + llvm + " " + cur + ", " + to.repr);
	emit(down + (real ? " = fcmp oge " : (sign ? " = icmp sge " : " = icmp uge ")) + llvm + " " + cur + ", " + to.repr);
	emit(cont + " = select i1 " + neg + ", i1 " + down + ", i1 " + up);
	emit_terminator("br i1 " + cont + ", label %" + body_l + ", label %" + end_l);

	begin_label(body_l);
	_exits.push_back(end_l);
	gen_block(node->body);
	_exits.pop_back();

	begin_label(step_l);
	auto next = tmp(), after = tmp();
	emit(next + " = load " + llvm + ", ptr " + var.pointer);
	emit(after + (real ? " = fadd " : " = add ") + llvm + " " + next + ", " + step.repr);
	emit("store " + llvm + " " + after + ", ptr " + var.pointer);
	emit_terminator("br label %" + cond_l);
	begin_label(end_l);
}

void blitz::compiler::gen_select(ast::select_statement const* node)
{
	auto subject = gen(node->subject.get());
	auto end_l   = label("select.end");

	// Test all cases in order, the Default (wherever it is) runs if none matched.
	std::vector<std::string> body_labels;
	for (size_t idx = 0; idx < node->cases.size(); idx++) {
		body_labels.push_back(label("select.case"));
	}
	std::string default_l = end_l;

	for (size_t idx = 0; idx < node->cases.size(); idx++) {
		auto const& entry = node->cases[idx];
		if (entry.values.empty()) {
			default_l = body_labels[idx];
			continue;
		}
		for (auto const& expr : entry.values) {
			auto next_l = label("select.next");
			auto match  = compare(ast::binary::op::EQUAL, subject, gen(expr.get()), expr->where);
			emit_terminator("br i1 " + match + ", label %" + body_labels[idx] + ", label %" + next_l);
			begin_label(next_l);
		}
	}
	emit_terminator("br label %" + default_l);

	for (size_t idx = 0; idx < node->cases.size(); idx++) {
		begin_label(body_labels[idx]);
		gen_block(node->cases[idx].body);
		if (!_terminated) {
			emit_terminator("br label %" + end_l);
		}
	}
	begin_label(end_l);
}

void blitz::compiler::gen_return(ast::return_statement const* node)
{
	// Without a value, Return ends a Gosub if there is one to end.
	if (!node->value && !_gosub_stack.empty()) {
		gen_gosub_return(node->where);
		return;
	}
	if (_in_main) {
		throw err(node->where, "Return can only be used inside of a function, or after a Gosub.");
	}
	auto  llvm = blitz::types::to_llvm(_return_type);
	value v    = node->value ? convert(gen(node->value.get()), _return_type, node->value->where, true, _return_sname) : zero(_return_type);
	if (_return_type == type::STRING) {
		// The caller gets a copy as its own temporary, and what this function made is freed.
		declare("bb_str_return", "declare ptr @bb_str_return(ptr, i32)");
		auto copy = tmp();
		emit(copy + " = call ptr @bb_str_return(ptr " + v.repr + ", i32 %entry.mark)");
		v             = { copy, type::STRING };
		_uses_strings = true;
	}
	emit("store " + llvm + " " + v.repr + ", ptr " + _ret_slot);
	emit_terminator("br label %" + _exit_label);
}
