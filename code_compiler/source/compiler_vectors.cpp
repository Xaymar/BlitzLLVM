////////////////////////////////////////////////////////////////////////////////
// Vectors and matrices
//
// A vector or matrix (`Float3`, `Int[8]`, `Double4x4`) is a value that is held by value, not an object: assigning it copies every element, and a
// function that gets one can't change the one of its caller. Its elements are numbers of one type, in one piece of memory without padding. The
// last size is the one that changes fastest, so `Float[4][3]` (4 columns of 3 rows) has the 3 numbers of the first column first.
//
// While the program is compiled, such a value is the pointer to its memory (`value::repr`) and its sizes (`value::shape`). A variable is its own
// memory. The result of an operation is a temporary that lives in the entry block of the function, so that loops do not grow the stack.
// Everything that is done to the elements is done one number at a time by the code that handles single numbers, which means that vectors
// follow the same rules as numbers (promotion, wrapping, division checks, rounding) without a second implementation of them. Small ones
// are unrolled, which lets LLVM make vector instructions of them, and larger ones loop.
////////////////////////////////////////////////////////////////////////////////
uint64_t blitz::compiler::shape_total(shape_t const& shape)
{
	uint64_t total = 1;
	for (auto size : shape) {
		total *= size;
	}
	return total;
}

// The LLVM type of the elements, as nested arrays: { 4, 3 } is `[4 x [3 x float]]`.
std::string blitz::compiler::shape_llvm(type t, shape_t const& shape)
{
	auto text = blitz::types::to_llvm(t);
	for (size_t idx = shape.size(); idx-- > 0;) {
		text = "[" + std::to_string(shape[idx]) + " x " + text + "]";
	}
	return text;
}

// The name that the program would use: `Float[4][3]`.
std::string blitz::compiler::shape_name(type t, shape_t const& shape)
{
	auto text = blitz::types::display(t);
	for (auto size : shape) {
		text += "[" + std::to_string(size) + "]";
	}
	return text;
}

// Memory for the result of an operation. Big ones are not put on the stack (which is 1 MB on Windows) but in memory of their own, which a
// recursive function would share between its calls.
std::string blitz::compiler::aggregate_temp(type t, shape_t const& shape)
{
	auto total = shape_total(shape);
	auto llvm  = blitz::types::to_llvm(t);
	if (total * array_element_size(t) > 65536) {
		auto symbol = "@bb.agg" + std::to_string(_counter++);
		_globals << symbol << " = internal global [" << total << " x " << llvm << "] zeroinitializer\n";
		return symbol;
	}
	auto pointer = "%agg" + std::to_string(_counter++);
	_allocas << "  " << pointer << " = alloca [" << total << " x " << llvm << "]\n";
	return pointer;
}

std::string blitz::compiler::element_pointer(std::string const& pointer, type t, std::string const& index)
{
	auto p = tmp();
	emit(p + " = getelementptr inbounds " + blitz::types::to_llvm(t) + ", ptr " + pointer + ", i64 " + index);
	return p;
}

// The number at the given place (counting through all elements) of a vector or matrix.
blitz::compiler::value blitz::compiler::load_element(value const& aggregate, std::string const& index)
{
	auto p = element_pointer(aggregate.repr, aggregate.type, index);
	auto r = tmp();
	emit(r + " = load " + blitz::types::to_llvm(aggregate.type) + ", ptr " + p);
	return { r, aggregate.type };
}

// Runs the code for every element. `index` is an i64 operand: a constant when the elements are few enough to be unrolled.
void blitz::compiler::for_each_element(uint64_t count, std::function<void(std::string const&)> const& body)
{
	if (count <= 16) {
		for (uint64_t idx = 0; idx < count; idx++) {
			body(std::to_string(idx));
		}
		return;
	}
	auto counter = "%loop" + std::to_string(_counter++);
	_allocas << "  " << counter << " = alloca i64\n";
	emit("store i64 0, ptr " + counter);
	auto cond_l = label("vec.cond"), body_l = label("vec.body"), end_l = label("vec.end");
	begin_label(cond_l);
	auto idx = tmp(), more = tmp();
	emit(idx + " = load i64, ptr " + counter);
	emit(more + " = icmp ult i64 " + idx + ", " + std::to_string(count));
	emit_terminator("br i1 " + more + ", label %" + body_l + ", label %" + end_l);
	begin_label(body_l);
	body(idx);
	auto next = tmp();
	emit(next + " = add i64 " + idx + ", 1");
	emit("store i64 " + next + ", ptr " + counter);
	emit_terminator("br label %" + cond_l);
	begin_label(end_l);
}

// Makes a vector or matrix of the given sizes out of the numbers that the operation gives for each element. The inputs are vectors or matrices of
// that size, or single numbers that stand for all elements.
blitz::compiler::value blitz::compiler::elementwise(shape_t const& shape, std::vector<value> const& inputs, std::function<value(std::vector<value> const&)> const& op)
{
	std::string out;
	type        result = type::UNKNOWN;
	for_each_element(shape_total(shape), [&](std::string const& index) {
		std::vector<value> numbers;
		for (auto const& input : inputs) {
			numbers.push_back(input.shape.empty() ? input : load_element(input, index));
		}
		auto r = op(numbers);
		if (out.empty()) {
			result = r.type;
			out    = aggregate_temp(result, shape);
		}
		auto p = element_pointer(out, result, index);
		emit("store " + blitz::types::to_llvm(result) + " " + r.repr + ", ptr " + p);
	});
	value v{ out, result };
	v.shape = shape;
	return v;
}

void blitz::compiler::require_scalar(value const& v, ast::location const& where)
{
	if (!v.shape.empty()) {
		throw err(where, "A " + shape_name(v.type, v.shape) + " can't be used where a single number is needed.");
	}
}

void blitz::compiler::require_same_shape(value const& a, value const& b, ast::location const& where)
{
	if (a.shape != b.shape) {
		throw err(where, "Can't use " + shape_name(a.type, a.shape) + " together with " + shape_name(b.type, b.shape) + ", they have to be of the same size.");
	}
}

// Stores a vector or matrix into the place of a variable, field or element.
void blitz::compiler::assign_aggregate(address const& target, value const& v, ast::location const& where, ast::range const* covers)
{
	if (v.shape != target.shape) {
		throw err(where, "Can't assign " + (v.shape.empty() ? blitz::types::display(v.type) : shape_name(v.type, v.shape)) + " to " + (target.shape.empty() ? blitz::types::display(target.type) : shape_name(target.type, target.shape)) + ", the sizes have to be the same.");
	}
	auto total = shape_total(target.shape);
	if (v.type == target.type) {
		// Overlapping is fine for memmove, which is what `a = a` is.
		declare("llvm.memmove.p0.p0.i64", "declare void @llvm.memmove.p0.p0.i64(ptr, ptr, i64, i1)");
		emit("call void @llvm.memmove.p0.p0.i64(ptr " + target.pointer + ", ptr " + v.repr + ", i64 " + std::to_string(total * array_element_size(v.type)) + ", i1 false)");
		return;
	}
	bool warned = false;
	for_each_element(total, [&](std::string const& index) {
		auto number = convert(load_element(v, index), target.type, where, !warned, std::string(), covers);
		warned      = true;
		emit("store " + blitz::types::to_llvm(target.type) + " " + number.repr + ", ptr " + element_pointer(target.pointer, target.type, index));
	});
}
