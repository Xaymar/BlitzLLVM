blitz::types::type blitz::parser::parse_type_suffix(blitz::token const& name)
{
	_struct_name.clear();
	auto const& next = tk();
	if (next.type == blitz::token::variant::SYMBOL) {
		if (!adjacent(name, next)) {
			return blitz::types::type::UNKNOWN;
		}
		if (next.text == "%") {
			advance();
			return blitz::types::type::INT32;
		} else if (next.text == "%%") {
			advance();
			return blitz::types::type::INT64;
		} else if (next.text == "#") {
			advance();
			return blitz::types::type::FLOAT32;
		} else if (next.text == "##") {
			advance();
			return blitz::types::type::FLOAT64;
		} else if (next.text == "$") {
			advance();
			return blitz::types::type::STRING;
		} else if (next.text == ".") {
			// `Name.TypeName`
			auto const& type_tk = tk(1);
			if ((type_tk.type != blitz::token::variant::TEXT) || !adjacent(next, type_tk)) {
				throw error(next, "Expected a type name after '.'.");
			}
			_struct_name = type_tk.text;
			advance();
			advance();
			return blitz::types::type::STRUCT;
		}
	} else if ((next.type == blitz::token::variant::SEPARATOR) && adjacent(name, next)) {
		// `Name:Type` is only a type if directly attached, and the type is a known one.
		auto const& type_tk = tk(1);
		if ((type_tk.type == blitz::token::variant::TEXT) && adjacent(next, type_tk)) {
			auto type = blitz::types::from_string(type_tk.text);
			if (type != blitz::types::type::UNKNOWN) {
				advance();
				advance();
				return type;
			}
		}
	}
	return blitz::types::type::UNKNOWN;
}

std::vector<blitz::ast::expression_ptr> blitz::parser::parse_arguments()
{
	std::vector<ast::expression_ptr> args;
	if (is_symbol(tk(), ")")) {
		return args;
	}
	while (true) {
		args.push_back(parse_expression());
		if (is_symbol(tk(), ",")) {
			advance();
			continue;
		}
		break;
	}
	return args;
}

blitz::ast::expression_ptr blitz::parser::make_binary(blitz::token const& at, ast::binary::op kind, ast::expression_ptr lhs, ast::expression_ptr rhs)
{
	auto node   = std::make_unique<ast::binary>();
	node->where = here(at);
	node->kind  = kind;
	node->covers = covering(at);
	node->covers.line   = lhs->covers.line;
	node->covers.column = lhs->covers.column;
	node->lhs   = std::move(lhs);
	node->rhs   = std::move(rhs);
	return node;
}

blitz::ast::expression_ptr blitz::parser::parse_expression()
{
	// Not is the loosest operator: it applies to a whole chain of And, Or and Xor, so `Not a And b` is `Not (a And b)`.
	if (is_keyword(tk(), "not")) {
		auto op = tk();
		advance();
		auto node     = std::make_unique<ast::unary>();
		node->where   = here(op);
		node->kind    = ast::unary::op::NOT;
		node->operand = parse_or();
		finish(*node, op);
		return node;
	}
	return parse_or();
}

// And, Or and Xor share a single level and go from left to right, so `a Or b And c` is `(a Or b) And c`.
blitz::ast::expression_ptr blitz::parser::parse_or()
{
	auto lhs = parse_not();
	while (true) {
		auto op = tk();
		ast::binary::op kind;
		if (is_keyword(op, "or")) {
			kind = ast::binary::op::OR;
		} else if (is_keyword(op, "xor")) {
			kind = ast::binary::op::XOR;
		} else if (is_keyword(op, "and")) {
			kind = ast::binary::op::AND;
		} else {
			return lhs;
		}
		advance();
		lhs = make_binary(op, kind, std::move(lhs), parse_not());
	}
}

// The original only allows Not in front of a whole expression. Behind And, Or and Xor it is accepted here too, and applies to the comparison after it.
blitz::ast::expression_ptr blitz::parser::parse_not()
{
	if (is_keyword(tk(), "not")) {
		auto op = tk();
		advance();
		auto node     = std::make_unique<ast::unary>();
		node->where   = here(op);
		node->kind    = ast::unary::op::NOT;
		node->operand = parse_not();
		finish(*node, op);
		return node;
	}
	return parse_comparison();
}

blitz::ast::expression_ptr blitz::parser::parse_comparison()
{
	auto lhs = parse_additive();
	while (true) {
		auto op = tk();
		if (op.type != blitz::token::variant::SYMBOL) {
			return lhs;
		}
		ast::binary::op kind;
		if ((op.text == "=") || (op.text == "==")) {
			kind = ast::binary::op::EQUAL;
		} else if (op.text == "<>") {
			kind = ast::binary::op::NOT_EQUAL;
		} else if (op.text == "<") {
			kind = ast::binary::op::LESS;
		} else if (op.text == "<=") {
			kind = ast::binary::op::LESS_EQUAL;
		} else if (op.text == ">") {
			kind = ast::binary::op::GREATER;
		} else if (op.text == ">=") {
			kind = ast::binary::op::GREATER_EQUAL;
		} else {
			return lhs;
		}
		advance();
		lhs = make_binary(op, kind, std::move(lhs), parse_additive());
	}
}

// Shifts bind tighter than + and -, so `1 + 2 Shl 3` is `1 + (2 Shl 3)`.
blitz::ast::expression_ptr blitz::parser::parse_shift()
{
	auto lhs = parse_multiplicative();
	while (true) {
		auto op = tk();
		ast::binary::op kind;
		if (is_keyword(op, "shl")) {
			kind = ast::binary::op::SHL;
		} else if (is_keyword(op, "shr")) {
			kind = ast::binary::op::SHR;
		} else if (is_keyword(op, "sar")) {
			kind = ast::binary::op::SAR;
		} else {
			return lhs;
		}
		advance();
		lhs = make_binary(op, kind, std::move(lhs), parse_multiplicative());
	}
}

blitz::ast::expression_ptr blitz::parser::parse_additive()
{
	auto lhs = parse_shift();
	while (is_symbol(tk(), "+") || is_symbol(tk(), "-")) {
		auto op = tk();
		advance();
		lhs = make_binary(op, (op.text == "+") ? ast::binary::op::ADD : ast::binary::op::SUBTRACT, std::move(lhs), parse_shift());
	}
	return lhs;
}

blitz::ast::expression_ptr blitz::parser::parse_multiplicative()
{
	auto lhs = parse_power();
	while (true) {
		auto op = tk();
		ast::binary::op kind;
		if (is_symbol(op, "*")) {
			kind = ast::binary::op::MULTIPLY;
		} else if (is_symbol(op, "/")) {
			kind = ast::binary::op::DIVIDE;
		} else if (is_keyword(op, "mod")) {
			kind = ast::binary::op::MODULO;
		} else {
			return lhs;
		}
		advance();
		lhs = make_binary(op, kind, std::move(lhs), parse_power());
	}
}

blitz::ast::expression_ptr blitz::parser::parse_power()
{
	auto lhs = parse_unary();
	while (is_symbol(tk(), "^")) {
		auto op = tk();
		advance();
		lhs = make_binary(op, ast::binary::op::POWER, std::move(lhs), parse_unary());
	}
	return lhs;
}

blitz::ast::expression_ptr blitz::parser::parse_unary()
{
	auto first = tk();
	auto node  = parse_unary_inner();
	finish(*node, first);
	return node;
}

blitz::ast::expression_ptr blitz::parser::parse_unary_inner()
{
	auto op = tk();
	// `Int%`, `Float#` and `Str$` may carry the suffix of their own type, as in `Str$(5)`.
	auto cast_suffix = [&](blitz::token const& word) -> char const* {
		auto const& next = tk(1);
		if ((next.type != blitz::token::variant::SYMBOL) || !adjacent(word, next)) {
			return nullptr;
		}
		if (is_keyword(word, "int") && (next.text == "%")) {
			return "%";
		} else if (is_keyword(word, "float") && (next.text == "#")) {
			return "#";
		} else if (is_keyword(word, "str") && (next.text == "$")) {
			return "$";
		}
		return nullptr;
	};
	if (is_keyword(op, "int") || is_keyword(op, "float") || is_keyword(op, "str")) {
		bool suffixed = cast_suffix(op) != nullptr;
		if (suffixed || !is_symbol(tk(1), "(")) {
			// `Float x` converts without needing parenthesis, and binds tighter than any operator.
			advance();
			if (suffixed) {
				advance();
			}
			auto node   = std::make_unique<ast::call>();
			node->where = here(op);
			node->name  = op.text;
			node->arguments.push_back(parse_unary());
			return node;
		}
	}
	if (is_keyword(op, "handle") && !is_symbol(tk(1), "(")) {
		// `Handle obj` needs no parenthesis either, but a variable called Handle must keep working.
		auto next    = tk(1);
		bool operand = (next.type == blitz::token::variant::TEXT) && (!reserved.count(lower(next.text)) || is_keyword(next, "new") || is_keyword(next, "first") || is_keyword(next, "last") || is_keyword(next, "before") || is_keyword(next, "after") || is_keyword(next, "object"));
		if (operand) {
			advance();
			auto node   = std::make_unique<ast::call>();
			node->where = here(op);
			node->name  = op.text;
			node->arguments.push_back(parse_unary());
			return node;
		}
	}
	if (is_keyword(op, "new") || is_keyword(op, "first") || is_keyword(op, "last")) {
		advance();
		auto type_tk = tk();
		if ((type_tk.type != blitz::token::variant::TEXT) || reserved.count(lower(type_tk.text))) {
			throw error(type_tk, blitz::format("Unexpected %s, expected a type name.", type_tk.to_string().c_str()));
		}
		advance();
		if (is_keyword(op, "new")) {
			auto node       = std::make_unique<ast::new_object>();
			node->where     = here(op);
			node->type_name = type_tk.text;
			return node;
		}
		auto node       = std::make_unique<ast::list_end>();
		node->where     = here(op);
		node->type_name = type_tk.text;
		node->last      = is_keyword(op, "last");
		return node;
	} else if (is_keyword(op, "before") || is_keyword(op, "after")) {
		advance();
		auto node    = std::make_unique<ast::list_neighbor>();
		node->where  = here(op);
		node->after  = is_keyword(op, "after");
		node->object = parse_unary();
		return node;
	}
	if (is_symbol(op, "-") || is_symbol(op, "+") || is_symbol(op, "~")) {
		advance();
		auto node     = std::make_unique<ast::unary>();
		node->where   = here(op);
		node->kind    = (op.text == "-") ? ast::unary::op::NEGATE : ((op.text == "+") ? ast::unary::op::PLUS : ast::unary::op::COMPLEMENT);
		node->operand = parse_unary();
		return node;
	}
	return parse_primary();
}

blitz::ast::expression_ptr blitz::parser::parse_number(blitz::token const& token)
{
	auto node   = std::make_unique<ast::literal>();
	node->where = here(token);

	if (token.type == blitz::token::variant::REAL) {
		node->kind = ast::literal::variant::REAL;
		errno      = 0;
		node->f    = strtod(token.text.c_str(), nullptr);
		if (errno == ERANGE) {
			throw error(token, blitz::format("Real '%s' is not representable on this system.", token.text.c_str()));
		}
		return node;
	}

	std::string text = token.text;
	bool        is_unsigned = false;
	if (!text.empty() && ((text.back() == 'u') || (text.back() == 'U'))) {
		is_unsigned = true;
		text.pop_back();
	}
	int base = 10;
	if ((text.length() >= 2) && ((text[0] == '$') || (text[0] == '%'))) {
		// Like in the original, `$` and `%` numbers only keep their lowest 32 bits, so $FFFFFFFF is -1 and not 4294967295.
		base                  = (text[0] == '$') ? 16 : 2;
		uint32_t     wrapped  = 0;
		for (size_t idx = 1; idx < text.length(); idx++) {
			wrapped = (base == 16) ? ((wrapped << 4) | uint32_t(isdigit((unsigned char)text[idx]) ? (text[idx] & 0xf) : ((text[idx] & 7) + 9))) : ((wrapped << 1) | uint32_t(text[idx] == '1'));
		}
		node->kind = ast::literal::variant::INTEGER;
		node->i    = int32_t(wrapped);
		return node;
	}
	if ((text.length() >= 2) && (text[0] == '0') && ((text[1] == 'x') || (text[1] == 'X'))) {
		base = 16;
		text = text.substr(2);
	} else if ((text.length() >= 2) && (text[0] == '0') && ((text[1] == 'b') || (text[1] == 'B'))) {
		base = 2;
		text = text.substr(2);
	}
	if (text.empty()) {
		throw error(token, blitz::format("Integer '%s' has no digits.", token.text.c_str()));
	}

	errno        = 0;
	uintmax_t ui = strtoull(text.c_str(), nullptr, base);
	if (errno == ERANGE) {
		throw error(token, blitz::format("Integer '%s' is not representable on this system.", token.text.c_str()));
	}
	if (is_unsigned || (ui > uintmax_t(INTMAX_MAX))) {
		node->kind = ast::literal::variant::UNSIGNED_INTEGER;
		node->u    = ui;
	} else {
		node->kind = ast::literal::variant::INTEGER;
		node->i    = intmax_t(ui);
	}
	return node;
}

// Field access (`Object\Field`) and array elements (`Array[Index]`) that follow something.
blitz::ast::expression_ptr blitz::parser::parse_postfix(ast::expression_ptr base, blitz::token const& first)
{
	while (true) {
		if (is_symbol(tk(), "\\")) {
			auto slash = tk();
			advance();
			auto field = tk();
			if (field.type != blitz::token::variant::TEXT) {
				throw error(field, blitz::format("Unexpected %s, expected a field name.", field.to_string().c_str()));
			}
			advance();
			parse_type_suffix(field); // The field already has a type, the suffix is optional.

			auto node    = std::make_unique<ast::field_access>();
			node->where  = here(slash);
			node->object = std::move(base);
			node->name   = field.text;
			finish(*node, first);
			base         = std::move(node);
		} else if (is_symbol(tk(), "[")) {
			auto bracket = tk();
			advance();
			auto node   = std::make_unique<ast::index_access>();
			node->where = here(bracket);
			node->base  = std::move(base);
			node->index = parse_expression();
			expect_symbol("]");
			finish(*node, first);
			base = std::move(node);
		} else {
			return base;
		}
	}
}

blitz::ast::expression_ptr blitz::parser::parse_primary()
{
	auto first = tk();
	auto node  = parse_primary_inner();
	finish(*node, first);
	return node;
}

blitz::ast::expression_ptr blitz::parser::parse_primary_inner()
{
	auto token = tk();
	switch (token.type) {
	case blitz::token::variant::INTEGER:
	case blitz::token::variant::REAL:
		advance();
		return parse_number(token);
	case blitz::token::variant::STRING: {
		advance();
		auto node   = std::make_unique<ast::literal>();
		node->where = here(token);
		node->kind  = ast::literal::variant::STRING;
		node->text  = token.text;
		return node;
	}
	case blitz::token::variant::SYMBOL: {
		if (token.text == "(") {
			advance();
			auto inner = parse_expression();
			expect_symbol(")");
			return parse_postfix(std::move(inner), token);
		}
		break;
	}
	case blitz::token::variant::TEXT: {
		std::string word = lower(token.text);
		if ((word == "true") || (word == "false") || (word == "null")) {
			advance();
			auto node   = std::make_unique<ast::literal>();
			node->where = here(token);
			node->kind  = (word == "null") ? ast::literal::variant::NULLPTR : ast::literal::variant::INTEGER;
			node->i     = (word == "true") ? 1 : 0;
			return node;
		} else if (reserved.count(word) || unsupported.count(word)) {
			throw error(token, blitz::format("Unexpected '%s' in expression.", token.text.c_str()));
		}

		advance();
		auto type        = parse_type_suffix(token);
		auto struct_name = _struct_name;
		if ((word == "object") && (type == blitz::types::type::STRUCT)) {
			// Object.TypeName Handle, with or without parenthesis: the handle is a unary operand.
			auto node       = std::make_unique<ast::object_from_handle>();
			node->where     = here(token);
			node->type_name = struct_name;
			if (is_symbol(tk(), "(")) {
				advance();
				node->handle = parse_expression();
				expect_symbol(")");
				return parse_postfix(std::move(node), token);
			}
			node->handle = parse_unary();
			return node;
		}
		if (!is_symbol(tk(), "(")) {
			note_variable_use(token, type, struct_name);
		} else {
			note_function_use(token, type, struct_name);
		}
		if (is_symbol(tk(), "(")) {
			advance();
			auto node         = std::make_unique<ast::call>();
			node->where       = here(token);
			node->name        = token.text;
			node->type        = type;
			node->struct_name = struct_name;
			node->arguments   = parse_arguments();
			expect_symbol(")");
			return parse_postfix(std::move(node), token);
		}
		auto node         = std::make_unique<ast::reference>();
		node->where       = here(token);
		node->name        = token.text;
		node->type        = type;
		node->struct_name = struct_name;
		return parse_postfix(std::move(node), token);
	}
	default:
		break;
	}
	throw error(token, blitz::format("Unexpected %s, expected an expression.", token.to_string().c_str()));
}
