// Debug information is emitted as LLVM metadata (DIBuilder in text form), so that a debugger can map every instruction
// back to the file, line and column it was made from. Every instruction gets a `!dbg` location while debug_info is set.

namespace {
	std::string md_string(std::string const& text)
	{
		std::string out = "\"";
		for (unsigned char c : text) {
			if ((c == '"') || (c == '\\') || (c < 0x20)) {
				out += blitz::format("\\%02X", c);
			} else {
				out += char(c);
			}
		}
		return out + "\"";
	}

	std::filesystem::path absolute_path(std::filesystem::path const& path)
	{
		std::error_code ec;
		auto            abs = std::filesystem::absolute(path, ec);
		return ec ? path : abs.lexically_normal();
	}
} // namespace

std::string blitz::compiler::md(std::string const& node, bool distinct)
{
	if (!distinct) {
		auto it = _md_index.find(node);
		if (it != _md_index.end()) {
			return "!" + std::to_string(it->second);
		}
		_md_index[node] = _md.size();
	}
	_md.push_back(node);
	return "!" + std::to_string(_md.size() - 1);
}

std::string blitz::compiler::di_file(std::filesystem::path const& path)
{
	auto abs = absolute_path(path);
	return md("!DIFile(filename: " + md_string(abs.filename().generic_string()) + ", directory: " + md_string(abs.parent_path().generic_string()) + ")");
}

// Where an instruction is, as a location in the subprogram that is being generated.
std::string blitz::compiler::di_location(ast::location const& where)
{
	std::string scope = _di_scope;
	if (where.file && (absolute_path(*where.file) != _di_sp_file)) {
		// Code of another file (Include) inside of this function needs a block that says so.
		auto key = absolute_path(*where.file).generic_string();
		auto it  = _di_blocks.find(key);
		if (it == _di_blocks.end()) {
			it = _di_blocks.emplace(key, md("!DILexicalBlockFile(scope: " + _di_scope + ", file: " + di_file(*where.file) + ", discriminator: 0)")).first;
		}
		scope = it->second;
	}
	return md("!DILocation(line: " + std::to_string(where.line) + ", column: " + std::to_string(where.column) + ", scope: " + scope + ")");
}

std::string blitz::compiler::dbg()
{
	if (!debug_info || _di_scope.empty() || !_loc.line) {
		return std::string();
	}
	return ", !dbg " + di_location(_loc);
}

// The size and alignment in bits of what a variable, field or element of this type is in memory.
namespace {
	uint64_t di_bits(type t)
	{
		return ((t == type::STRING) || (t == type::STRUCT)) ? 64 : blitz::types::bits(t);
	}
} // namespace

// A String is a pointer to its characters (which end in a NUL, its length is in front of them), so a debugger shows the text.
// An empty string is a null pointer.
std::string blitz::compiler::di_string_type()
{
	auto chars = md("!DIBasicType(name: \"char\", size: 8, encoding: DW_ATE_signed_char)");
	auto ptr   = md("!DIDerivedType(tag: DW_TAG_pointer_type, baseType: " + chars + ", size: 64)");
	return md("!DIDerivedType(tag: DW_TAG_typedef, name: \"String\", baseType: " + ptr + ")");
}

// An object is a pointer to the fields of its Type. The fields are described at the end of the module, as Types are known by then
// and can refer to each other (and to themselves).
std::string blitz::compiler::di_object_type(std::string const& sname)
{
	auto it = _di_objects.find(sname);
	if (it == _di_objects.end()) {
		it = _di_objects.emplace(sname, md("", true)).first;
		_di_pending.push_back(sname);
	}
	return md("!DIDerivedType(tag: DW_TAG_pointer_type, baseType: " + it->second + ", size: 64)");
}

void blitz::compiler::di_finish_objects()
{
	// Describing one Type can ask for others, which are added to the end.
	for (size_t at = 0; at < _di_pending.size(); at++) {
		auto const  sname = _di_pending[at];
		auto const  id    = _di_objects[sname];
		auto        known = _types.find(sname);
		std::string name  = (known != _types.end()) ? known->second.name : sname;

		std::string members;
		auto        member = [&](std::string const& field, std::string const& base, uint64_t size, uint64_t offset) {
            members += (members.empty() ? "" : ", ") + md("!DIDerivedType(tag: DW_TAG_member, name: " + md_string(field) + ", scope: " + id + ", baseType: " + base + ", size: " + std::to_string(size) + ", offset: " + std::to_string(offset) + ")");
		};
		// The header every object starts with, see bb_object in the runtime.
		auto self = md("!DIDerivedType(tag: DW_TAG_pointer_type, baseType: " + id + ", size: 64)");
		auto int32 = di_type(type::INT32, std::string(), 0);
		member("__next", self, 64, 0);
		member("__previous", self, 64, 64);
		member("__handle", int32, 32, 128);
		member("__flags", int32, 32, 160);
		uint64_t offset = 192, align = 64;
		if (known != _types.end()) {
			for (auto const& field : known->second.fields) {
				uint64_t unit  = di_bits(field.type);
				uint32_t count = field.shape.empty() ? field.count : uint32_t(shape_total(field.shape));
				uint64_t size  = unit * (count ? count : 1);
				offset         = (offset + unit - 1) / unit * unit; // Naturally aligned, like in the structure of the IR.
				member(field.name, di_type(field.type, field.sname, count), size, offset);
				offset += size;
			}
		}
		offset = (offset + align - 1) / align * align;
		_md[std::stoul(id.substr(1))] = "!DICompositeType(tag: DW_TAG_structure_type, name: " + md_string(name) + ", size: " + std::to_string(offset) + ", elements: " + md("!{" + members + "}") + ")";
	}
}

// What a Dim array is: the address of its elements and how many there are in each dimension. A debugger shows the first element
// by following Data, the others are Data[1] and so on (Count says where the first dimension ends, and Pitch is how far apart the
// rows of a 2D array are, in elements).
std::string blitz::compiler::di_dim_type(type t, std::string const& sname, uint32_t dims)
{
	std::string members;
	auto        id     = md("", true);
	auto        member = [&](std::string const& field, std::string const& base, uint64_t size, uint64_t offset) {
        members += (members.empty() ? "" : ", ") + md("!DIDerivedType(tag: DW_TAG_member, name: " + md_string(field) + ", scope: " + id + ", baseType: " + base + ", size: " + std::to_string(size) + ", offset: " + std::to_string(offset) + ")");
	};
	auto element = di_type(t, lower(sname), 0);
	auto int32   = di_type(type::INT32, std::string(), 0);
	member("Data", md("!DIDerivedType(tag: DW_TAG_pointer_type, baseType: " + element + ", size: 64)"), 64, 0);
	for (uint32_t dim = 0; dim < dims; dim++) {
		member("Count" + std::to_string(dim), int32, 32, 64 + 32 * dim);
	}
	if (dims > 1) {
		member("Pitch", int32, 32, 64 + 32 * 4);
	}
	std::string name = blitz::types::to_string(t);
	name[0]          = char(std::toupper((unsigned char)name[0]));
	if (t == type::STRING) {
		name = "String";
	} else if (t == type::STRUCT) {
		name = sname.empty() ? "Object" : sname; // As it was written, Types are not known yet when the globals are collected.
	} else if (t == type::FLOAT32) {
		name = "Float";
	}
	_md[std::stoul(id.substr(1))] = "!DICompositeType(tag: DW_TAG_structure_type, name: " + md_string("Array of " + name + ", " + std::to_string(dims) + (dims == 1 ? " dimension" : " dimensions")) + ", size: " + std::to_string(256) + ", elements: " + md("!{" + members + "}") + ")";
	return id;
}

std::string blitz::compiler::di_type(type t, std::string const& sname, uint32_t count)
{
	std::string base;
	switch (t) {
	case type::UNKNOWN:
		return "null";
	case type::STRING:
		base = di_string_type();
		break;
	case type::STRUCT:
		base = sname.empty() ? md("!DIDerivedType(tag: DW_TAG_pointer_type, name: \"Object\", baseType: null, size: 64)") : di_object_type(sname);
		break;
	default: {
		std::string name = blitz::types::to_string(t);
		name[0]          = char(std::toupper((unsigned char)name[0]));
		if (t == type::FLOAT32) {
			name = "Float";
		}
		const char* enc  = blitz::types::is_real(t) ? "DW_ATE_float" : (blitz::types::is_signed(t) ? "DW_ATE_signed" : "DW_ATE_unsigned");
		base             = md("!DIBasicType(name: " + md_string(name) + ", size: " + std::to_string(blitz::types::bits(t)) + ", encoding: " + enc + ")");
		break;
	}
	}
	if (count) {
		uint64_t size = di_bits(t);
		return md("!DICompositeType(tag: DW_TAG_array_type, baseType: " + base + ", size: " + std::to_string(size * count) + ", elements: " + md("!{" + md("!DISubrange(count: " + std::to_string(count) + ")") + "}") + ")");
	}
	return base;
}

// Starts the debug information of a function, which the following instructions belong to.
std::string blitz::compiler::di_begin_function(std::string const& name, std::string const& symbol, ast::location const& where, type ret, std::string const& ret_sname, std::vector<ast::parameter> const* params, bool local)
{
	if (!debug_info) {
		return std::string();
	}
	std::filesystem::path file = where.file ? *where.file : source;
	std::string           types = di_type(ret, ret_sname, 0);
	if (params) {
		for (auto const& p : *params) {
			types += ", " + di_type(p.type, lower(p.struct_name), 0);
		}
	}
	auto fn = md("!DISubroutineType(types: " + md("!{" + types + "}") + ")");
	auto sp = md("distinct !DISubprogram(name: " + md_string(name) + ", linkageName: " + md_string(symbol) + ", scope: " + di_file(file) + ", file: " + di_file(file) + ", line: " + std::to_string(where.line) + ", type: " + fn + ", scopeLine: " + std::to_string(where.line) + ", spFlags: DISPFlagDefinition" + (local ? " | DISPFlagLocalToUnit" : "") + ", unit: " + _di_cu + ")", true);

	_di_scope   = sp;
	_di_sp_file = absolute_path(file);
	_di_blocks.clear();
	_loc = where;
	if (!_loc.file) {
		_loc.file = std::make_shared<const std::filesystem::path>(file);
	}
	return sp;
}

void blitz::compiler::di_end_function()
{
	_di_scope.clear();
	_loc = ast::location{};
}

// Tells the debugger about a variable that lives in the stack slot `pointer`.
void blitz::compiler::di_declare_local(std::string const& name, std::string const& pointer, type t, std::string const& sname, uint32_t count, ast::location const& where, uint32_t arg)
{
	if (!debug_info || _di_scope.empty()) {
		return;
	}
	ast::location at   = where.line ? where : _loc;
	std::string   file = (at.file ? di_file(*at.file) : di_file(source));
	auto          var  = md("!DILocalVariable(name: " + md_string(name) + (arg ? ", arg: " + std::to_string(arg) : std::string()) + ", scope: " + _di_scope + ", file: " + file + ", line: " + std::to_string(at.line) + ", type: " + di_type(t, sname, count) + ")");
	auto          saved = _loc;
	_loc                = at;
	declare("llvm.dbg.declare", "declare void @llvm.dbg.declare(metadata, metadata, metadata)");
	emit("call void @llvm.dbg.declare(metadata ptr " + pointer + ", metadata " + var + ", metadata !DIExpression())");
	_loc = saved;
}

// Attaches the debug information of a global variable.
std::string blitz::compiler::di_global(std::string const& name, type t, std::string const& sname, uint32_t count, ast::location const& where)
{
	if (!debug_info) {
		return std::string();
	}
	return di_global_of(name, di_type(t, sname, count), where);
}

// The same for a Dim array, whose variable is the descriptor of it.
std::string blitz::compiler::di_global_dim(std::string const& name, type t, std::string const& sname, uint32_t dims, ast::location const& where)
{
	if (!debug_info) {
		return std::string();
	}
	return di_global_of(name, di_dim_type(t, sname, dims), where);
}

std::string blitz::compiler::di_global_of(std::string const& name, std::string const& type_md, ast::location const& where)
{
	std::filesystem::path file = where.file ? *where.file : source;
	auto var = md("distinct !DIGlobalVariable(name: " + md_string(name) + ", scope: " + _di_cu + ", file: " + di_file(file) + ", line: " + std::to_string(where.line) + ", type: " + type_md + ", isLocal: true, isDefinition: true)", true);
	auto expression = md("!DIGlobalVariableExpression(var: " + var + ", expr: !DIExpression())");
	_di_globals.push_back(expression);
	return ", !dbg " + expression;
}

void blitz::compiler::di_begin_module()
{
	if (!debug_info) {
		return;
	}
	_di_cu = md("", true); // Filled in once the globals are known.
}

// The named metadata that ties everything together.
std::string blitz::compiler::di_end_module()
{
	if (!debug_info) {
		return std::string();
	}
	di_finish_objects();
	std::string flags = codeview ? md("!{i32 2, !\"CodeView\", i32 1}") : md("!{i32 7, !\"Dwarf Version\", i32 4}");
	flags += ", " + md("!{i32 2, !\"Debug Info Version\", i32 3}");

	std::string globals;
	for (auto const& global : _di_globals) {
		globals += (globals.empty() ? "" : ", ") + global;
	}
	_md[std::stoul(_di_cu.substr(1))] = "distinct !DICompileUnit(language: DW_LANG_C99, file: " + di_file(source) + ", producer: \"BlitzLLVM\", isOptimized: false, runtimeVersion: 0, emissionKind: FullDebug, splitDebugInlining: false" + (globals.empty() ? std::string() : ", globals: " + md("!{" + globals + "}")) + ")";

	std::string out = "\n!llvm.dbg.cu = !{" + _di_cu + "}\n!llvm.module.flags = !{" + flags + "}\n";
	for (size_t idx = 0; idx < _md.size(); idx++) {
		out += "!" + std::to_string(idx) + " = " + _md[idx] + "\n";
	}
	return out;
}
