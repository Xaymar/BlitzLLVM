#pragma once
#include <cinttypes>
#include <filesystem>
#include <memory>
#include <string>
#include <vector>
#include "../types.hpp"

// BlitzBasic Built-Ins
// - Include: Followed by a String, which is the file to include at this location.
// - Const: Defines one or more constants, which can not be modified.
// - Local: Defines one or more local variables, which can be modified.
// - Global: Defines one or more global variables, which can be modified from anywhere.
// - Dim: Defines a dynamically resizable array, globally accessible and modifyable.
// - If, Then, ElseIf, Else, EndIf: Your classic If.
// - Select, Case, Default, End Select: Your classic Select.
// - For, To, Step, Next: Your classic For loop.
// - While, Wend: Your classic While loop.
// - Repeat, Until, Forever: Similar to While/Wend, but the condition is at the end and loops until the condition is true.
// - Exit: Exit from the innermost active loop.
// - True, False: True and False. What, did you expect something else?
// - Stop: Pause the program for the debugger, if there happens to be one.
// - End: Terminate the program.
// - Goto: Jump to a specific label, without setting the return address.
// - Gosub, Return: Jump to a specific label (subroutine), setting the return address appropriately, and Return from it eventually.
// - Function, Return, End Function: Defines a function, and allows returning values. Yes, I know, End itself terminates the program, this is a special case. Thanks younger Sibly.
// - And, Or, Not: Logical operator, self-explanatory really.
//
// Variable type notation:
// - 8bit Signed Integer:   Variable:Byte, Variable:Int8
// - 8bit Unsigned Integer: Variable:UByte, Variable:UInt8
// - 16bit Integers:        Variable:Short, Variable:Int16, Variable:UShort, Variable:UInt16
// - 32bit Integers:        Variable (default), Variable%, Variable:Int, Variable:Int32, Variable:UInt, Variable:UInt32
// - 64bit Integers:        Variable%%, Variable:Long, Variable:Int64, Variable:ULong, Variable:UInt64
// - 32bit Real:            Variable#, Variable:Float, Variable:Float32, Variable:Real, Variable:Real32
// - 64bit Real:            Variable##, Variable:Double, Variable:Float64, Variable:Real64
// - UTF-8 String:          Variable$, Variable:String

namespace blitz {
	namespace ast {
		/** Where in which file a node originates from. */
		struct location {
			std::shared_ptr<const std::filesystem::path> file;
			uint64_t                                     line   = 0;
			uint64_t                                     column = 0;
			uint64_t                                     length = 0; // In bytes from the column, 0 if the end is not known.
		};

		/** The part of a file that a node covers, from the first character of its first token up to the end of its last token (exclusive). All 0 if unknown. */
		struct range {
			uint64_t line       = 0;
			uint64_t column     = 0;
			uint64_t end_line   = 0;
			uint64_t end_column = 0;
		};

		struct node {
			location where;
			range    covers;

			virtual ~node() = default;
		};

		////////////////////////////////////////////////////////////////////////
		// Expressions
		////////////////////////////////////////////////////////////////////////
		struct expression : public node {};
		using expression_ptr = std::unique_ptr<expression>;

		/** Integer, Real and String literals. True, False and Null are Integer literals. */
		struct literal : public expression {
			enum class variant { INTEGER, UNSIGNED_INTEGER, REAL, STRING, NULLPTR } kind = variant::INTEGER;
			intmax_t    i                                                       = 0;
			uintmax_t   u                                                       = 0;
			double      f                                                       = 0;
			std::string text;
		};

		/** A name, with optional type information: `Name`, `Name%`, `Name:Float`. Might also be a function called without parenthesis. */
		struct reference : public expression {
			std::string        name;
			blitz::types::type type = blitz::types::type::UNKNOWN; // UNKNOWN if there is no explicit type.
			std::string        struct_name;                         // For `Name.TypeName`.
		};

		/** A function call: `Name(Arg, ...)`. */
		struct call : public expression {
			std::string                 name;
			blitz::types::type          type = blitz::types::type::UNKNOWN;
			std::string                 struct_name;
			std::vector<expression_ptr> arguments;
		};

		/** `Object\Field`. */
		struct field_access : public expression {
			expression_ptr object;
			std::string    name;
		};

		/** `Array[Index]`, for arrays that are not Dim arrays (fields and local/global arrays). */
		struct index_access : public expression {
			expression_ptr base;
			expression_ptr index;
		};

		/** `New TypeName` */
		struct new_object : public expression {
			std::string type_name;
		};

		/** `First TypeName`, `Last TypeName` */
		struct list_end : public expression {
			std::string type_name;
			bool        last = false;
		};

		/** `Before Object`, `After Object` */
		struct list_neighbor : public expression {
			expression_ptr object;
			bool           after = false;
		};

		/** `Object.TypeName(Handle)` */
		struct object_from_handle : public expression {
			std::string    type_name;
			expression_ptr handle;
		};

		struct unary : public expression {
			enum class op { NEGATE, PLUS, NOT, COMPLEMENT } kind = op::NEGATE;
			expression_ptr operand;
		};

		struct binary : public expression {
			enum class op {
				ADD,
				SUBTRACT,
				MULTIPLY,
				DIVIDE,
				MODULO,
				POWER,
				SHL,
				SHR,
				SAR,
				AND,
				OR,
				XOR,
				EQUAL,
				NOT_EQUAL,
				LESS,
				LESS_EQUAL,
				GREATER,
				GREATER_EQUAL,
			} kind = op::ADD;
			expression_ptr lhs;
			expression_ptr rhs;
		};

		////////////////////////////////////////////////////////////////////////
		// Statements
		////////////////////////////////////////////////////////////////////////
		struct statement : public node {};
		using statement_ptr = std::unique_ptr<statement>;
		using block         = std::vector<statement_ptr>;

		/** One declared variable in `Local a, b% = 1, c$ = "Hello"`. */
		struct declaration {
			location           where;
			range              covers; // From the name to the end of the type, size and initial value.
			std::string        name;
			blitz::types::type type = blitz::types::type::UNKNOWN;
			std::string        struct_name;
			expression_ptr     array_size; // `Name[Size]`
			expression_ptr     initial;
		};

		/** `Local`, `Global` and `Const`. */
		struct declare : public statement {
			bool                     global   = false;
			bool                     constant = false;
			std::vector<declaration> variables;
		};

		/** One array in `Dim Name(Size, Size), Name2$(Size)`. */
		struct dim_declaration {
			location                    where;
			std::string                 name;
			blitz::types::type          type = blitz::types::type::UNKNOWN; // Without a suffix: Int, or what the array already was.
			std::string                 struct_name;
			std::vector<expression_ptr> sizes; // The highest valid index of each dimension.
		};

		/** `Dim`: allocates (or reallocates) global arrays. */
		struct dim_statement : public statement {
			std::vector<dim_declaration> arrays;
		};

		/** `Name = Expression` */
		struct assign : public statement {
			expression_ptr target; // A reference, field, or array element.
			expression_ptr value;
		};

		/** `Name Arg, Arg` or `Name(Arg, Arg)` as a statement. */
		struct call_statement : public statement {
			std::unique_ptr<call> invocation;
		};

		struct branch {
			expression_ptr condition; // Empty for the final Else.
			block          body;
		};

		/** `If`, `ElseIf`, `Else` */
		struct if_statement : public statement {
			std::vector<branch> branches;
		};

		struct while_statement : public statement {
			expression_ptr condition;
			block          body;
		};

		/** `Repeat ... Until Cond` or `Repeat ... Forever` (no condition). */
		struct repeat_statement : public statement {
			expression_ptr condition;
			block          body;
		};

		struct for_statement : public statement {
			std::unique_ptr<reference> variable;
			expression_ptr             from;
			expression_ptr             to;
			expression_ptr             step;      // Optional
			std::string                each_type; // For `For v = Each TypeName`, which has no from, to and step.
			block                      body;
		};

		/** `Delete Object` or `Delete Each TypeName` */
		struct delete_statement : public statement {
			expression_ptr object;
			std::string    each_type;
		};

		/** `Insert Object Before Other` / `Insert Object After Other` */
		struct insert_statement : public statement {
			expression_ptr object;
			expression_ptr other;
			bool           after = false;
		};

		struct select_case {
			std::vector<expression_ptr> values; // Empty for Default.
			block                       body;
		};

		struct select_statement : public statement {
			expression_ptr           subject;
			std::vector<select_case> cases;
		};

		struct exit_statement : public statement {};

		/** `Data 1, 2.5, "Text"`: constants for Read, in the order they appear in the program. */
		struct data_statement : public statement {
			std::vector<expression_ptr> items;
		};

		/** `Read a, b$` */
		struct read_statement : public statement {
			std::vector<expression_ptr> targets;
		};

		/** `Restore Label`: Read starts again at the Data after that label. */
		struct restore_statement : public statement {
			std::string label;
		};

		/** `.Name`: a place that Goto and Gosub can jump to. */
		struct label_statement : public statement {
			std::string name;
		};

		struct goto_statement : public statement {
			std::string label;
		};

		/** Jumps to a label, and comes back at the next Return. */
		struct gosub_statement : public statement {
			std::string label;
		};

		/** `End`, terminates the program. */
		struct end_statement : public statement {};
		struct stop_statement : public statement {};

		struct return_statement : public statement {
			expression_ptr value; // Optional
		};

		////////////////////////////////////////////////////////////////////////
		// Program
		////////////////////////////////////////////////////////////////////////
		struct parameter {
			location           where;
			std::string        name;
			std::string        struct_name;
			blitz::types::type type = blitz::types::type::INT32;
			bool               typed = false; // If the program gave it a type, instead of the default Int.
			expression_ptr     initial; // Optional default value
		};

		/** A field of a Type: `Field Name`, `Field Name#`, `Field Name.OtherType`, `Field Name[Size]`. */
		struct field_decl {
			location           where;
			std::string        name;
			blitz::types::type type = blitz::types::type::INT32;
			bool               typed = false; // If the program gave it a type, instead of the default Int.
			std::string        struct_name;
			expression_ptr     array_size;
		};

		struct type_decl : public node {
			std::string             name;
			std::vector<field_decl> fields;
		};

		struct function : public node {
			std::string            name;
			std::string            struct_name; // If it returns an object.
			blitz::types::type     type = blitz::types::type::INT32;
			bool                   typed = false; // If the program gave it a type, instead of the default Int.
			std::vector<parameter> parameters;
			block                  body;
		};

		/** A type written as a character behind a name (`x%`, `x#`, `x##`, `x%%`, `x$`) instead of as `x:Int32`. */
		struct short_notation {
			location    where;        // The character(s) of the suffix.
			std::string replacement;  // The long form that takes its place, such as ":Int32".
		};

		struct program {
			std::vector<short_notation>            short_notations;
			std::vector<std::unique_ptr<type_decl>> types;
			block                                  main;
			std::vector<std::unique_ptr<function>> functions;
		};
	} // namespace ast
} // namespace blitz
