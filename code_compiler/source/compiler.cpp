blitz::compiler::variable* blitz::compiler::find(std::string const& name)
{
	auto key = lower(name);
	auto it  = _locals.find(key);
	if (it != _locals.end()) {
		return &it->second;
	}
	auto git = _global_variables.find(key);
	if (git != _global_variables.end()) {
		return &git->second;
	}
	return nullptr;
}

// Sets the memory of an array to 0. A store of the whole array as a constant takes clang minutes and gigabytes for a big array (1 million
// elements take 21 seconds, 5 million more than 7 GB), a memset takes no time.
std::string blitz::compiler::zero_memory(std::string const& pointer, std::string const& array_type)
{
	declare("llvm.memset.p0.i64", "declare void @llvm.memset.p0.i64(ptr, i8, i64, i1)");
	return "call void @llvm.memset.p0.i64(ptr " + pointer + ", i8 0, i64 ptrtoint (ptr getelementptr (" + array_type + ", ptr null, i32 1) to i64), i1 false)";
}

// The size of one element of an array: numbers as wide as their type, everything else (strings, objects) is a pointer.
uint64_t blitz::compiler::array_element_size(blitz::types::type t)
{
	return is_number(t) ? std::max<unsigned>(blitz::types::bits(t) / 8, 1) : 8;
}

blitz::compiler::variable blitz::compiler::create_local(std::string const& name, type t, bool is_constant, ast::location const& where, std::string const& sname, uint32_t count)
{
	auto key = lower(name);
	if (t == type::STRUCT) {
		need_type(sname, where);
	}
	if (_locals.count(key) || (_in_main && _global_variables.count(key))) {
		// Functions can have locals that are named like a global, but the main program can't.
		throw err(where, "'" + name + "' has already been declared.");
	}

	// Allocas live in the entry block, so that loops don't grow the stack.
	auto ptr  = "%v" + std::to_string(_counter++);
	auto llvm = blitz::types::to_llvm(t);
	if (count) {
		// Arrays too big for the stack (1 MB on Windows) live on the heap, made zeroed when the function starts and freed when it ends.
		// The main program has no end to free them at, it keeps them until the program ends.
		uint64_t element = array_element_size(t);
		if (uint64_t(count) * element > 65536) {
			declare("bb_array_alloc", "declare ptr @bb_array_alloc(i64, i64)");
			_allocas << "  " << ptr << " = call ptr @bb_array_alloc(i64 " << count << ", i64 " << element << ")\n";
			if (!_in_main) {
				_heap_locals.push_back(ptr);
			}
		} else {
			auto array = "[" + std::to_string(count) + " x " + llvm + "]";
			_allocas << "  " << ptr << " = alloca " << array << "\n";
			_allocas << "  " << zero_memory(ptr, array) << "\n";
		}
	} else {
		_allocas << "  " << ptr << " = alloca " << llvm << "\n";
		_allocas << "  store " << llvm << " " << zero(t).repr << ", ptr " << ptr << "\n";
	}

	variable var{ ptr, t, is_constant, lower(sname), count };
	_locals[key] = var;
	di_declare_local(name, ptr, t, lower(sname), count, where, _arg);
	if ((t == type::STRING) && !_in_main) {
		_string_locals.push_back({ ptr, count });
		_uses_strings = true;
	}
	return var;
}

blitz::compiler::variable& blitz::compiler::lookup(std::string const& name, type hint, ast::location const& where, std::string const& sname)
{
	if (auto var = find(name)) {
		var->used = true;
		return *var;
	}
	refuse_array(name, where);
	warn(where, "implicit-variable", "'" + name + "' was not declared, it is a new local variable.", "Declare it first, such as 'Local " + name + "'.", {}, declaration_suffix(hint, sname));
	// Variables that were not declared are automatically declared as local.
	if (hint == type::STRUCT) {
		need_type(sname, where);
	}
	create_local(name, (hint == type::UNKNOWN) ? type::INT32 : hint, false, ast::location{}, sname);
	return _locals[lower(name)];
}

// A name that belongs to an array is not a new variable.
void blitz::compiler::refuse_array(std::string const& name, ast::location const& where)
{
	if (find_dim(name)) {
		throw err(where, "'" + name + "' is an array, it can't be used as a variable.");
	}
}

// What goes behind the name of a variable to give it the type.
std::string blitz::compiler::declaration_suffix(type t, std::string const& sname)
{
	switch (t) {
	case type::UNKNOWN: return ":" + blitz::types::long_name(type::INT32);
	case type::STRUCT: return "." + sname;
	default: return ":" + blitz::types::long_name(t);
	}
}

void blitz::compiler::warn_typeless(ast::location const& where, std::string const& name, std::string const& kind)
{
	// Only the declarations of variables have a fix: the location of the others is not known to be at the name.
	std::vector<edit> edits;
	if (kind.empty() && where.file && (where.line != 0)) {
		uint64_t at = where.column + name.size();
		edits.push_back(edit{ *where.file, ast::range{ where.line, at, where.line, at }, ":Int32" });
	}
	auto before = findings.size();
	warn(where, "typeless-declaration", kind + "'" + name + "' has no type, it is an Int.", "Add the type to the name: '" + name + ":Int32', '" + name + ":Float32', '" + name + ":String' or '" + name + ".TypeName' (object).", std::move(edits));
	if ((kind == "Function ") && (findings.size() > before) && where.file) {
		// suggest_return_type adds to this finding once it knows what the function returns.
		_typeless_functions[where.file->generic_string() + ":" + std::to_string(where.line) + ":" + std::to_string(where.column)] = before;
	}
}

void blitz::compiler::warn_short_notations(std::vector<ast::short_notation> const& notations)
{
	std::set<std::string> seen;
	for (auto const& notation : notations) {
		auto const& where = notation.where;
		if (!seen.insert((where.file ? where.file->generic_string() : std::string()) + ":" + std::to_string(where.line) + ":" + std::to_string(where.column)).second) {
			continue;
		}
		std::vector<edit> edits;
		if (where.file && (where.line != 0)) {
			edits.push_back(edit{ *where.file, ast::range{ where.line, where.column, where.line, where.column + where.length }, notation.replacement });
		}
		warn(where, "short-type-notation", "The type is written in the short form.", "Write the long form instead: '" + notation.replacement + "'.", std::move(edits));
	}
}

void blitz::compiler::report_unused(std::map<std::string, variable>& variables)
{
	for (auto const& entry : variables) {
		auto const& var = entry.second;
		if (var.check_unused && !var.used) {
			warn(var.where, "unused-variable", "'" + var.name + "' is never read, it is optimized away.", "Remove the variable, or use its value.");
		}
	}
}

void blitz::compiler::collect_globals(ast::block const& block)
{
	for (auto const& stmt : block) {
		if (auto d = dynamic_cast<ast::declare const*>(stmt.get())) {
			if (!d->global && !d->constant) {
				continue;
			}
			for (auto const& decl : d->variables) {
				auto key = lower(decl.name);
				if (_global_variables.count(key)) {
					throw err(decl.where, "'" + decl.name + "' has already been declared.");
				}
				type t = decl.type;
				if (t == type::STRUCT) {
					_struct_uses.emplace_back(decl.struct_name, decl.where);
				}
				if (t == type::UNKNOWN) {
					warn_typeless(decl.where, decl.name);
					t = type::INT32; // Also for a Const, so `Const Half = 0.5` is 0 like in the original.
				}
				auto     symbol = "@bb.g" + std::to_string(_counter++);
				uint32_t count  = decl.array_size ? array_count(decl.array_size.get(), decl.where) : 0;
				auto debug_attachment = di_global(decl.name, t, lower(decl.struct_name), count, decl.where);
				if (count) {
					_globals << symbol << " = internal global [" << count << " x " << blitz::types::to_llvm(t) << "] zeroinitializer" << debug_attachment << "\n";
				} else {
					_globals << symbol << " = internal global " << blitz::types::to_llvm(t) << " " << zero(t).repr << debug_attachment << "\n";
				}
				_global_variables[key] = variable{ symbol, t, d->constant, lower(decl.struct_name), count };
				if (!d->constant) {
					auto& declared        = _global_variables[key];
					declared.where        = decl.where;
					declared.name         = decl.name;
					declared.check_unused = true;
				}
				int64_t folded;
				if (d->constant && decl.initial && fold_int(decl.initial.get(), folded)) {
					_const_values[key] = folded;
				}
			}
		} else if (auto dim = dynamic_cast<ast::dim_statement const*>(stmt.get())) {
			for (auto const& decl : dim->arrays) {
				auto key = lower(decl.name);
				if (_collecting_function) {
					_redim_in_function.insert(key);
				}
				auto old = _arrays.find(key);
				if (old != _arrays.end()) {
					// Dimensioning an array again is fine, as long as it stays the same kind of array.
					if ((old->second.dims != decl.sizes.size()) || ((decl.type != type::UNKNOWN) && (old->second.type != decl.type))) {
						throw err(decl.where, "'" + decl.name + "' has already been declared as something else.");
					}
					continue;
				}
				if (decl.type == type::STRUCT) {
					_struct_uses.emplace_back(decl.struct_name, decl.where);
				}
				if (decl.type == type::UNKNOWN) {
					warn_typeless(decl.where, decl.name);
				}
				auto symbol = "@bb.d" + std::to_string(_counter++);
				_globals << symbol << " = internal global { ptr, i32, i32, i32, i32, i32 } zeroinitializer\n";
				variable var{ symbol, (decl.type == type::UNKNOWN) ? type::INT32 : decl.type, false, lower(decl.struct_name), 0, uint32_t(decl.sizes.size()) };
				_arrays[key] = var;
			}
		} else if (auto i = dynamic_cast<ast::if_statement const*>(stmt.get())) {
			for (auto const& b : i->branches) {
				collect_globals(b.body);
			}
		} else if (auto w = dynamic_cast<ast::while_statement const*>(stmt.get())) {
			collect_globals(w->body);
		} else if (auto r = dynamic_cast<ast::repeat_statement const*>(stmt.get())) {
			collect_globals(r->body);
		} else if (auto f = dynamic_cast<ast::for_statement const*>(stmt.get())) {
			collect_globals(f->body);
		} else if (auto s = dynamic_cast<ast::select_statement const*>(stmt.get())) {
			for (auto const& c : s->cases) {
				collect_globals(c.body);
			}
		}
	}
}

std::string blitz::compiler::generate(ast::program const& program)
{
	di_begin_module();

	warn_short_notations(program.short_notations);

	// Make all functions known first, so they can be used before they are defined.
	for (auto const& fn : program.functions) {
		auto key = lower(fn->name);
		if (_functions.count(key)) {
			throw err(fn->where, "Function '" + fn->name + "' has already been defined.");
		}
		_functions[key] = function_info{ "@\"bb.f." + std::to_string(_counter++) + "\"", fn.get() };
		if (!fn->typed) {
			warn_typeless(fn->where, fn->name, "Function ");
		}
		for (auto const& param : fn->parameters) {
			if (!param.typed) {
				warn_typeless(param.where, param.name, "Parameter ");
			}
		}
	}

	// Same for global variables and constants.
	collect_globals(program.main);
	_collecting_function = true;
	for (auto const& fn : program.functions) {
		collect_globals(fn->body);
	}
	_collecting_function = false;
	register_types(program);
	for (auto const& use : _struct_uses) {
		need_type(use.first, use.second);
	}
	for (auto const& fn : program.functions) {
		if (fn->type == type::STRUCT) {
			need_type(fn->struct_name, fn->where);
		}
		for (auto const& param : fn->parameters) {
			if (param.type == type::STRUCT) {
				need_type(param.struct_name, param.where);
			}
		}
	}
	collect_data("", program.main);
	for (auto const& fn : program.functions) {
		collect_data(lower(fn->name), fn->body);
	}

	for (auto const& fn : program.functions) {
		gen_function(*fn);
	}
	gen_main(program);
	report_unused(_global_variables);
	for (auto const& fn : program.functions) {
		if (!_called.count(lower(fn->name))) {
			warn(fn->where, "unused-function", "Function '" + fn->name + "' is never called, it is optimized away.", "Remove the function, or call it.");
		}
	}

	// What Read reads.
	if (_data_items.empty()) {
		_globals << "@bb.data = internal constant [1 x { i32, i64 }] zeroinitializer\n";
	} else {
		_globals << "@bb.data = internal constant [" << _data_items.size() << " x { i32, i64 }] [";
		for (size_t i = 0; i < _data_items.size(); i++) {
			_globals << (i ? ", " : " ") << "{ i32, i64 } " << _data_items[i];
		}
		_globals << " ]\n";
	}
	_globals << "@bb.data.pos = internal global i32 0\n";

	if (!_unknown.empty()) {
		std::string names;
		for (auto const& entry : _unknown) {
			names += (names.empty() ? "" : ", ") + entry.second.first;
		}
		auto const& first = _unknown.begin()->second;
		throw err(first.second, std::to_string(_unknown.size()) + " functions don't exist: " + names + ".");
	}

	std::string out = "; Generated by BlitzLLVM\n";
	out += _constants.str() + "\n" + _globals.str() + "\n" + _declarations.str() + "\n" + _definitions.str() + tbaa_metadata() + di_end_module();
	return out;
}

// Builtins that are a single instruction or a libm call become LLVM intrinsics, so that they can be folded, hoisted and selected
// as instructions, where a call into the runtime library would stop the optimizer at its boundary.
blitz::compiler::value blitz::compiler::inline_builtin(std::string const& symbol, std::vector<value> const& args, bool& handled)
{
	handled = true;
	auto intrinsic = [&](const char* name, const char* t, std::vector<std::string> const& operands) {
		std::string params, list;
		for (size_t idx = 0; idx < operands.size(); idx++) {
			params += std::string(idx ? ", " : "") + t;
			list += std::string(idx ? ", " : "") + t + " " + operands[idx];
		}
		declare(name, std::string("declare ") + t + " @" + name + "(" + params + ")");
		auto r = tmp();
		emit(r + " = call " + t + " @" + name + "(" + list + ")");
		return r;
	};

	static const std::map<std::string, const char*> single = {
		{ "bb_sqr", "llvm.sqrt.f32" },   { "bb_floor", "llvm.floor.f32" }, { "bb_ceil", "llvm.ceil.f32" },
		{ "bb_exp", "llvm.exp.f32" },    { "bb_log", "llvm.log.f32" },     { "bb_log10", "llvm.log10.f32" },
	};
	if (auto it = single.find(symbol); it != single.end()) {
		return { intrinsic(it->second, "float", { args[0].repr }), type::FLOAT32 };
	}

	// Blitz works in degrees: sin(v) is sin(v * pi / 180), calculated in double like the runtime does.
	if ((symbol == "bb_sin") || (symbol == "bb_cos")) {
		auto wide = tmp(), scaled = tmp(), narrow = tmp();
		emit(wide + " = fpext float " + args[0].repr + " to double");
		emit(scaled + " = fmul double " + wide + ", " + constant(type::FLOAT64, 3.14159265358979323846 / 180.0).repr);
		auto r = intrinsic((symbol == "bb_sin") ? "llvm.sin.f64" : "llvm.cos.f64", "double", { scaled });
		emit(narrow + " = fptrunc double " + r + " to float");
		return { narrow, type::FLOAT32 };
	}

	// Peek and Poke on a bank: the table of banks is a global of the runtime, so the lookup and the range check are part of the
	// program and the access is a load or store at the end of it. Whatever fails the check goes to the runtime function, which
	// raises the error with its message.
	struct bank_access {
		const char* symbol;
		const char* llvm; // The type in memory.
		bool        poke;
	};
	static const std::map<std::string, bank_access> banks = {
		{ "bb_peek_byte", { "bb_peek_byte", "i8", false } },    { "bb_peek_short", { "bb_peek_short", "i16", false } },
		{ "bb_peek_int", { "bb_peek_int", "i32", false } },     { "bb_peek_float", { "bb_peek_float", "float", false } },
		{ "bb_poke_byte", { "bb_poke_byte", "i8", true } },     { "bb_poke_short", { "bb_poke_short", "i16", true } },
		{ "bb_poke_int", { "bb_poke_int", "i32", true } },      { "bb_poke_float", { "bb_poke_float", "float", true } },
	};
	if (auto it = banks.find(symbol); it != banks.end()) {
		auto const& access = it->second;
		std::string mem    = access.llvm;
		int         width  = (mem == "i8") ? 1 : (mem == "i16") ? 2 : 4;
		std::string handle = args[0].repr, offset = args[1].repr;

		declare("bb_banks", "@bb_banks = external global ptr");
		declare("bb_bank_count", "@bb_bank_count = external global i32");
		auto count = tmp(), table = tmp(), index = tmp(), limit = tmp(), valid = tmp();
		emit(count + " = load i32, ptr @bb_bank_count");
		emit(table + " = load ptr, ptr @bb_banks");
		// Handle 0 is no bank, which wraps to the largest number and fails the same comparison as a handle past the end.
		emit(index + " = sub i32 " + handle + ", 1");
		emit(limit + " = sub i32 " + count + ", 1");
		emit(valid + " = icmp ult i32 " + index + ", " + limit);
		auto check_l = label("bank.check"), fast_l = label("bank.fast"), slow_l = label("bank.slow"), done_l = label("bank.done");
		emit_terminator("br i1 " + valid + ", label %" + check_l + ", label %" + slow_l);

		begin_label(check_l);
		auto slot = tmp(), data = tmp(), size_p = tmp(), size = tmp(), has = tmp(), last = tmp(), wide = tmp(), in = tmp(), fits = tmp(), ok = tmp();
		emit(slot + " = getelementptr inbounds { ptr, i32 }, ptr " + table + ", i32 " + handle);
		emit(data + " = load ptr, ptr " + slot);
		emit(size_p + " = getelementptr inbounds { ptr, i32 }, ptr " + slot + ", i32 0, i32 1");
		emit(size + " = load i32, ptr " + size_p);
		emit(has + " = icmp ne ptr " + data + ", null");
		// offset + width <= size without overflow: the offset may not be negative, and may not be past size - width. A bank that is
		// smaller than the width has no offset at all, which size - width can't say because it wraps around to a large number.
		emit(last + " = sub i32 " + size + ", " + std::to_string(width));
		emit(wide + " = icmp uge i32 " + size + ", " + std::to_string(width));
		emit(in + " = icmp ule i32 " + offset + ", " + last);
		emit(fits + " = and i1 " + wide + ", " + in);
		emit(ok + " = and i1 " + has + ", " + fits);
		emit_terminator("br i1 " + ok + ", label %" + fast_l + ", label %" + slow_l);

		begin_label(fast_l);
		auto at = tmp();
		emit(at + " = getelementptr inbounds i8, ptr " + data + ", i32 " + offset);
		std::string result;
		if (access.poke) {
			std::string stored = args[2].repr;
			if (mem == "i8" || mem == "i16") {
				auto narrow = tmp();
				emit(narrow + " = trunc i32 " + stored + " to " + mem);
				stored = narrow;
			}
			emit("store " + mem + " " + stored + ", ptr " + at + ", align 1");
		} else {
			auto loaded = tmp();
			emit(loaded + " = load " + mem + ", ptr " + at + ", align 1");
			result = loaded;
			if (mem == "i8" || mem == "i16") {
				result = tmp();
				emit(result + " = zext " + mem + " " + loaded + " to i32");
			}
		}
		emit_terminator("br label %" + done_l);

		begin_label(slow_l);
		std::string list = "i32 " + handle + ", i32 " + offset;
		if (access.poke) {
			list += std::string(", ") + (mem == "float" ? "float " : "i32 ") + args[2].repr;
			declare(access.symbol, std::string("declare void @") + access.symbol + (mem == "float" ? "(i32, i32, float)" : "(i32, i32, i32)"));
		} else {
			declare(access.symbol, std::string("declare ") + (mem == "float" ? "float" : "i32") + " @" + access.symbol + "(i32, i32)");
		}
		emit(std::string("call ") + (access.poke ? "void" : (mem == "float" ? "float" : "i32")) + " @" + access.symbol + "(" + list + ") cold");
		emit_terminator("unreachable");

		begin_label(done_l);
		if (access.poke) {
			return { "", type::UNKNOWN };
		}
		return { result, (mem == "float") ? type::FLOAT32 : type::INT32 };
	}

	// Rnd and Rand step the generator of the runtime (see bb_rng_unit there) inside the program, without a call. The operations are the
	// same and carry no fast-math flags, so that a seeded program gets the same numbers as before.
	if ((symbol == "bb_rnd") || (symbol == "bb_rand")) {
		declare("bb_rng", "@bb_rng = external global i32");
		auto state = tmp(), quot = tmp(), rem = tmp(), hi_part = tmp(), lo_part = tmp(), next = tmp(), neg = tmp(), wrapped = tmp(), fixed = tmp(),
			 bits = tmp(), whole = tmp(), unit = tmp(), unit_biased = tmp();
		emit(state + " = load i32, ptr @bb_rng");
		emit(quot + " = sdiv i32 " + state + ", 44488");
		emit(rem + " = srem i32 " + state + ", 44488");
		emit(hi_part + " = mul i32 " + rem + ", 48271");
		emit(lo_part + " = mul i32 " + quot + ", 3399");
		emit(next + " = sub i32 " + hi_part + ", " + lo_part);
		emit(neg + " = icmp slt i32 " + next + ", 0");
		emit(wrapped + " = add i32 " + next + ", 2147483647");
		emit(fixed + " = select i1 " + neg + ", i32 " + wrapped + ", i32 " + next);
		emit("store i32 " + fixed + ", ptr @bb_rng");
		emit(bits + " = and i32 " + fixed + ", 65535");
		emit(whole + " = sitofp i32 " + bits + " to float");
		emit(unit + " = fdiv float " + whole + ", " + constant(type::FLOAT32, 65536.0).repr);
		emit(unit_biased + " = fadd float " + unit + ", " + constant(type::FLOAT32, 0.5 / 65536.0).repr);
		if (symbol == "bb_rnd") {
			auto span = tmp(), scaled = tmp(), r = tmp();
			emit(span + " = fsub float " + args[1].repr + ", " + args[0].repr);
			emit(scaled + " = fmul float " + unit_biased + ", " + span);
			emit(r + " = fadd float " + scaled + ", " + args[0].repr);
			return { r, type::FLOAT32 };
		}
		auto swap = tmp(), lo = tmp(), hi = tmp(), diff = tmp(), count = tmp(), count_f = tmp(), scaled = tmp(), whole_r = tmp(), r = tmp();
		emit(swap + " = icmp slt i32 " + args[1].repr + ", " + args[0].repr);
		emit(lo + " = select i1 " + swap + ", i32 " + args[1].repr + ", i32 " + args[0].repr);
		emit(hi + " = select i1 " + swap + ", i32 " + args[0].repr + ", i32 " + args[1].repr);
		emit(diff + " = sub i32 " + hi + ", " + lo);
		emit(count + " = add i32 " + diff + ", 1");
		emit(count_f + " = sitofp i32 " + count + " to float");
		emit(scaled + " = fmul float " + unit_biased + ", " + count_f);
		emit(whole_r + " = fptosi float " + scaled + " to i32");
		emit(r + " = add i32 " + whole_r + ", " + lo);
		return { r, type::INT32 };
	}

	handled = false;
	return {};
}
