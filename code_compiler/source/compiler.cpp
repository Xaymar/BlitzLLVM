std::string blitz::compiler::tmp()
{
	return "%t" + std::to_string(_counter++);
}

std::string blitz::compiler::label(const char* prefix)
{
	return std::string(prefix) + "." + std::to_string(_counter++);
}

// Two unrelated scalar types, so that stores to the elements of a Dim array can't change the descriptor (data pointer and sizes) of an array,
// which lets loops keep these in registers. Anything without a tag still aliases all of them.
std::string blitz::compiler::tbaa_metadata()
{
	return "\n!900001 = !{!\"BlitzLLVM TBAA\"}\n"
		   "!900002 = !{!\"descriptor\", !900001, i64 0}\n"
		   "!900003 = !{!900002, !900002, i64 0}\n"
		   "!900005 = !{!\"element\", !900001, i64 0}\n"
		   "!900004 = !{!900005, !900005, i64 0}\n";
}

void blitz::compiler::emit(std::string const& line)
{
	if (_terminated) {
		// Code after a terminator (Exit, Return, End) is unreachable, but the IR still needs a block for it.
		_body << label("dead") << ":\n";
		_terminated = false;
	}
	_body << "  " << line << dbg() << "\n";
}

void blitz::compiler::emit_terminator(std::string const& line)
{
	emit(line);
	_terminated = true;
}

void blitz::compiler::begin_label(std::string const& name)
{
	if (!_terminated) {
		_body << "  br label %" << name << dbg() << "\n";
	}
	_body << name << ":\n";
	_terminated = false;
}

void blitz::compiler::declare(std::string const& symbol, std::string const& line)
{
	if (_declared.insert(symbol).second) {
		_declarations << line << "\n";
	}
}

std::string blitz::compiler::string_constant(std::string const& text)
{
	auto it = _strings.find(text);
	if (it != _strings.end()) {
		return it->second;
	}

	std::string name = "@.str." + std::to_string(_strings.size());
	std::string escaped;
	for (unsigned char c : text) {
		if (isalnum(c) || c == ' ' || c == '_' || c == '.' || c == ',' || c == '!' || c == '-') {
			escaped += char(c);
		} else {
			escaped += blitz::format("\\%02X", c);
		}
	}
	// The length is in front of the characters, like in the strings the runtime makes, and the value is where the characters begin.
	std::string layout = "<{ i32, [" + std::to_string(text.size() + 1) + " x i8] }>";
	_constants << name << " = private unnamed_addr constant " << layout << " <{ i32 " << text.size() << ", [" << (text.size() + 1) << " x i8] c\"" << escaped
			   << "\\00\" }>\n";
	std::string value = "getelementptr inbounds (" + layout + ", ptr " + name + ", i32 0, i32 1)";
	_strings[text]    = value;
	return value;
}

