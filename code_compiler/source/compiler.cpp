blitz::error blitz::compiler::err(ast::location const& where, std::string const& reason) const
{
	std::pair<uint64_t, uint64_t> at{ where.line, where.column };
	return blitz::error(where.file ? *where.file : std::filesystem::path(), at, at, reason);
}

size_t blitz::compiler::warning_errors() const
{
	return _warning_errors;
}

void blitz::compiler::warn(ast::location const& where, const char* name, std::string const& reason, std::string const& notice, std::vector<edit> edits, std::string const& detail)
{
	if (!warning_options.enabled(name)) {
		return;
	}
	_warnings++;
	findings.push_back(finding{ name, where, reason, notice, std::move(edits), detail });
	// With -Werror the warning is an error: It is printed as one, even with -q, and fails the compilation after everything was checked.
	bool as_error = warning_options.is_error(name);
	if (as_error) {
		_warning_errors++;
	}
	if ((quiet && !as_error) || silent) {
		return;
	}
	std::string flag = std::string("[-W") + (as_error ? "error=" : "") + name + "]";
	const char* kind = as_error ? "error" : (blitz::find_warning(name).hint ? "notice" : "warning");
	std::cerr << blitz::diagnostic(where.file ? *where.file : std::filesystem::path("<unknown>"), where.line, where.column, kind, reason + " " + flag, where.length, notice) << std::endl;
}

