blitz::compiler::compiler() : _counter(0), _warnings(0), _return_type(type::UNKNOWN), _in_main(false), _terminated(false) {}

blitz::compiler::~compiler() {}

size_t blitz::compiler::warnings() const
{
	return _warnings;
}

////////////////////////////////////////////////////////////////////////////////
// Errors and warnings
////////////////////////////////////////////////////////////////////////////////
blitz::error blitz::compiler::err(ast::location const& where, std::string const& reason) const
{
	std::pair<uint64_t, uint64_t> at{ where.line, where.column };
	return blitz::error(where.file ? *where.file : std::filesystem::path(), at, at, reason);
}

void blitz::compiler::warn(ast::location const& where, std::string const& reason)
{
	_warnings++;
	if (quiet) {
		return;
	}
	std::cerr << blitz::diagnostic(where.file ? *where.file : std::filesystem::path("<unknown>"), where.line, where.column, "warning", reason) << std::endl;
}

////////////////////////////////////////////////////////////////////////////////
// Emission
////////////////////////////////////////////////////////////////////////////////
std::string blitz::compiler::tmp()
{
	return "%t" + std::to_string(_counter++);
}

std::string blitz::compiler::label(const char* prefix)
{
	return std::string(prefix) + "." + std::to_string(_counter++);
}

void blitz::compiler::emit(std::string const& line)
{
	if (_terminated) {
		// Code after a terminator (Exit, Return, End) is unreachable, but the IR still needs a block for it.
		_body << label("dead") << ":\n";
		_terminated = false;
	}
	_body << "  " << line << dbg() << "\n";
}

void blitz::compiler::emit_terminator(std::string const& line)
{
	emit(line);
	_terminated = true;
}

void blitz::compiler::begin_label(std::string const& name)
{
	if (!_terminated) {
		_body << "  br label %" << name << dbg() << "\n";
	}
	_body << name << ":\n";
	_terminated = false;
}

void blitz::compiler::declare(std::string const& symbol, std::string const& line)
{
	if (_declared.insert(symbol).second) {
		_declarations << line << "\n";
	}
}

std::string blitz::compiler::string_constant(std::string const& text)
{
	auto it = _strings.find(text);
	if (it != _strings.end()) {
		return it->second;
	}

	std::string name = "@.str." + std::to_string(_strings.size());
	std::string escaped;
	for (unsigned char c : text) {
		if (isalnum(c) || c == ' ' || c == '_' || c == '.' || c == ',' || c == '!' || c == '-') {
			escaped += char(c);
		} else {
			escaped += blitz::format("\\%02X", c);
		}
	}
	_constants << name << " = private unnamed_addr constant [" << (text.size() + 1) << " x i8] c\"" << escaped << "\\00\"\n";
	_strings[text] = name;
	return name;
}

