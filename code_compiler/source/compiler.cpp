blitz::compiler::value blitz::compiler::zero(type t)
{
	if ((t == type::STRING) || (t == type::STRUCT)) {
		return { "null", t };
	} else if (blitz::types::is_real(t)) {
		return { "0.0", t };
	}
	return { "0", t };
}

blitz::compiler::value blitz::compiler::constant(type t, double number)
{
	if (blitz::types::is_integer(t)) {
		return { std::to_string((long long)number), t };
	} else if (t == type::FLOAT16) {
		auto base = constant(type::FLOAT32, number);
		auto r    = tmp();
		emit(r + " = fptrunc float " + base.repr + " to half");
		return { r, t };
	}

	double rounded = (t == type::FLOAT32) ? double(float(number)) : number;
	uint64_t bits;
	memcpy(&bits, &rounded, sizeof(bits));
	return { blitz::format("0x%016llX", (unsigned long long)bits), t };
}

blitz::compiler::value blitz::compiler::call_runtime(const char* symbol, type ret, std::vector<value> const& args)
{
	std::string params, list;
	for (size_t idx = 0; idx < args.size(); idx++) {
		auto llvm_type = blitz::types::to_llvm(args[idx].type);
		params += (idx ? ", " : "") + llvm_type;
		list += (idx ? ", " : "") + llvm_type + " " + args[idx].repr;
	}
	declare(symbol, "declare " + blitz::types::to_llvm(ret) + " @" + symbol + "(" + params + ")");

	if (ret == type::UNKNOWN) {
		emit(std::string("call void @") + symbol + "(" + list + ")");
		return { "", type::UNKNOWN };
	}
	auto r = tmp();
	emit(r + " = call " + blitz::types::to_llvm(ret) + " @" + symbol + "(" + list + ")");
	if ((ret == type::STRING) && (std::string(symbol) != "bb_data_string")) {
		// A string that a function made is a temporary, which the statement frees when it has been used.
		declare("bb_str_temp", "declare ptr @bb_str_temp(ptr)");
		auto t = tmp();
		emit(t + " = call ptr @bb_str_temp(ptr " + r + ")");
		_string_temps++;
		_uses_strings = true;
		return { t, ret };
	}
	return { r, ret };
}

// Raises a runtime error when the i1 condition holds. The check is part of the program, not a call into the runtime, so that
// LLVM can see it, hoist it out of loops and drop it where it can prove it can't fail.
void blitz::compiler::guard(std::string const& failed, const char* message)
{
	auto fail_l = label("guard.fail"), ok_l = label("guard.ok");
	emit_terminator("br i1 " + failed + ", label %" + fail_l + ", label %" + ok_l + "");
	begin_label(fail_l);
	declare("bb_runtime_error", "declare void @bb_runtime_error(ptr)");
	emit("call void @bb_runtime_error(ptr " + string_constant(message) + ") noreturn cold");
	emit_terminator("unreachable");
	begin_label(ok_l);
}

bool blitz::compiler::is_lossy(type from, type to, std::string const& literal) const
{
	namespace t = blitz::types;
	// A number written in the program is fine if it fits, because nothing is lost for it.
	bool     digits = !literal.empty() && (literal.find_first_not_of("0123456789") == std::string::npos || (literal[0] == '-' && literal.size() > 1 && literal.find_first_not_of("0123456789", 1) == std::string::npos));
	long double value = 0;
	if (digits && literal.size() < 19) {
		value = std::stold(literal);
	} else {
		digits = false;
	}
	if (t::is_integer(from) && t::is_integer(to)) {
		unsigned bits = t::bits(to) - (t::is_signed(to) ? 1 : 0);
		if (digits) {
			long double low = t::is_signed(to) ? -std::ldexp(1.0L, int(bits)) : 0, high = std::ldexp(1.0L, int(bits)) - 1;
			return (value < low) || (value > high);
		}
		// All values of the source have to fit, which for a source with a sign needs a target with a sign.
		unsigned have = t::bits(from) - (t::is_signed(from) ? 1 : 0);
		return (have > bits) || (t::is_signed(from) && !t::is_signed(to));
	} else if (t::is_integer(from) && t::is_real(to)) {
		unsigned mantissa = (to == type::FLOAT16) ? 11 : ((to == type::FLOAT32) ? 24 : 53);
		if (digits) {
			return std::fabs(value) > std::ldexp(1.0L, int(mantissa));
		}
		return t::bits(from) - (t::is_signed(from) ? 1 : 0) > mantissa;
	}
	return t::bits(to) < t::bits(from);
}

namespace {
	// Puts the expression in a call of the function: `2.5` becomes `Int(2.5)`.
	std::vector<blitz::edit> wrap_in(blitz::ast::location const& where, blitz::ast::range const* covers, std::string const& function)
	{
		if (!covers || function.empty() || !where.file || (covers->line == 0)) {
			return {};
		}
		blitz::ast::range begin{ covers->line, covers->column, covers->line, covers->column };
		blitz::ast::range end{ covers->end_line, covers->end_column, covers->end_line, covers->end_column };
		return { blitz::edit{ *where.file, begin, function + "(" }, blitz::edit{ *where.file, end, ")" } };
	}
} // namespace

blitz::compiler::value blitz::compiler::convert(value from, type to, ast::location const& where, bool warn_lossy, std::string const& to_sname, ast::range const* covers)
{
	if (from.type == type::UNKNOWN) {
		throw err(where, "Expression does not return a value.");
	} else if (from.type == to) {
		if (to == type::STRUCT) {
			std::string wanted = lower(to_sname);
			if (!from.sname.empty() && !wanted.empty() && (from.sname != wanted)) {
				throw err(where, "Type mismatch: '" + from.sname + "' is not '" + wanted + "'.");
			}
			if (from.sname.empty()) {
				from.sname = wanted; // Null becomes whatever it is assigned to.
			}
		}
		return from;
	} else if ((from.type == type::STRUCT) && from.sname.empty() && (from.repr == "null")) {
		// Null
		if (blitz::types::is_integer(to)) {
			return { "0", to };
		} else if (blitz::types::is_real(to)) {
			return { "0.0", to };
		} else if (to == type::STRING) {
			return { "null", to };
		}
	}

	namespace t    = blitz::types;
	bool from_int  = t::is_integer(from.type), from_real = t::is_real(from.type), from_str = (from.type == type::STRING);
	bool to_int    = t::is_integer(to), to_real = t::is_real(to), to_str = (to == type::STRING);
	auto from_llvm = t::to_llvm(from.type), to_llvm = t::to_llvm(to);

	if (warn_lossy && ((from_int && to_int) || (from_int && to_real) || (from_real && to_real)) && is_lossy(from.type, to, from.repr)) {
		const char* name = (from_int && to_int) ? "implicit-lossy-int-to-int" : (from_int ? "implicit-lossy-int-to-real" : "implicit-lossy-real-to-real");
		// Whole numbers can also be converted so that they stop at the limits of the target.
		std::string notice = "Use " + t::converter(to) + "(value) to convert on purpose";
		if (from_int && to_int) {
			notice += ", or Sat" + t::converter(to) + "(value) to stop at the limits instead of wrapping around";
		}
		warn(where, name, "Implicit conversion from " + t::long_name(from.type) + " to " + t::long_name(to) + " can change the value.", notice + ".", wrap_in(where, covers, t::converter(to)));
	}
	if (from_int && to_int) {
		auto bf = t::bits(from.type), bt = t::bits(to);
		if (bf == bt) {
			return { from.repr, to };
		}
		auto r = tmp();
		if (bt < bf) {
			emit(r + " = trunc " + from_llvm + " " + from.repr + " to " + to_llvm);
		} else {
			emit(r + " = " + (t::is_signed(from.type) ? "sext " : "zext ") + from_llvm + " " + from.repr + " to " + to_llvm);
		}
		return { r, to };
	} else if (from_int && to_real) {
		auto r = tmp();
		emit(r + " = " + (t::is_signed(from.type) ? "sitofp " : "uitofp ") + from_llvm + " " + from.repr + " to " + to_llvm);
		return { r, to };
	} else if (from_real && to_int) {
		if (warn_lossy) {
			warn(where, "implicit-lossy-real-to-int", "Implicit conversion from " + t::long_name(from.type) + " to " + t::long_name(to) + ", the fractional part is lost.", "Use " + t::converter(to) + "(value) to convert on purpose, or Sat" + t::converter(to) + "(value) to stop at the limits of " + t::long_name(to) + ".", wrap_in(where, covers, t::converter(to)));
		}
		// Blitz rounds to the nearest whole number (halves go to the even one) instead of cutting off the fraction. What does not fit
		// (and NaN) becomes the smallest Int/Int64, like in the original, as a plain conversion of LLVM is undefined for them.
		return saturate_real(from, to, where, true);
	} else if (from_real && to_real) {
		auto r = tmp();
		emit(r + (t::bits(to) > t::bits(from.type) ? " = fpext " : " = fptrunc ") + from_llvm + " " + from.repr + " to " + to_llvm);
		return { r, to };
	} else if (to_str && (from_int || from_real)) {
		if (warn_lossy) {
			warn(where, "implicit-number-to-string", "Implicit conversion from " + t::long_name(from.type) + " to String.", "Use Str(value) to convert on purpose.", wrap_in(where, covers, "Str"));
		}
		if (from_int) {
			bool sign = t::is_signed(from.type);
			auto wide = convert(from, sign ? type::INT64 : type::UINT64, where, false);
			return call_runtime(sign ? "bb_str_from_i64" : "bb_str_from_u64", type::STRING, { wide });
		}
		auto wide = convert(from, type::FLOAT64, where, false);
		return call_runtime("bb_str_from_f64", type::STRING, { wide });
	} else if (from_str && (to_int || to_real)) {
		if (warn_lossy) {
			warn(where, "implicit-string-to-number", "Implicit conversion from String to " + t::long_name(to) + ".", "Use " + t::converter(to) + "(value) to convert on purpose.", wrap_in(where, covers, t::converter(to)));
		}
		if (to_int) {
			// Like atoi: what does not fit stops at the largest number, and 64 bit targets get more room.
			if (t::bits(to) > 32) {
				return convert(call_runtime("bb_str_to_i64", type::INT64, { from }), to, where, false);
			}
			return convert(call_runtime("bb_str_to_i32", type::INT32, { from }), to, where, false);
		}
		auto wide = call_runtime("bb_str_to_f64", type::FLOAT64, { from });
		return convert(wide, to, where, false);
	}

	throw err(where, "Can't convert from " + t::to_string(from.type) + " to " + t::to_string(to) + ".");
}

type blitz::compiler::common_type(type lhs, type rhs, ast::location const& where)
{
	namespace t = blitz::types;
	if (!is_number(lhs) || !is_number(rhs)) {
		throw err(where, "Operation requires numbers.");
	}

	if (t::is_real(lhs) || t::is_real(rhs)) {
		unsigned bits = std::max(t::is_real(lhs) ? t::bits(lhs) : 0u, t::is_real(rhs) ? t::bits(rhs) : 0u);
		bits          = std::max(bits, 32u);
		return (bits == 64) ? type::FLOAT64 : type::FLOAT32;
	}

	// Integers are promoted to at least 32 bits. The wider type wins, unsigned wins if the widths are equal.
	unsigned bits = std::max({ t::bits(lhs), t::bits(rhs), 32u });
	bool     uns  = (!t::is_signed(lhs) && t::bits(lhs) >= bits) || (!t::is_signed(rhs) && t::bits(rhs) >= bits);
	if (bits == 64) {
		return uns ? type::UINT64 : type::INT64;
	}
	return uns ? type::UINT32 : type::INT32;
}

std::string blitz::compiler::truthy(value v, ast::location const& where)
{
	auto r = tmp();
	if (blitz::types::is_integer(v.type)) {
		emit(r + " = icmp ne " + blitz::types::to_llvm(v.type) + " " + v.repr + ", 0");
	} else if (blitz::types::is_real(v.type)) {
		// A condition is an integer in Blitz, so a real is rounded first and 0.4 is false.
		auto num = convert(v, type::INT32, where, false);
		emit(r + " = icmp ne i32 " + num.repr + ", 0");
	} else if (v.type == type::STRING) {
		// Conditions are integers in Blitz, so a string is true when it starts with a number that is not 0.
		auto num = convert(v, type::INT32, where, false);
		emit(r + " = icmp ne i32 " + num.repr + ", 0");
	} else if (v.type == type::STRUCT) {
		emit(r + " = icmp ne ptr " + v.repr + ", null");
	} else {
		throw err(where, "Expression does not return a value.");
	}
	return r;
}

blitz::compiler::value blitz::compiler::from_bool(std::string const& i1)
{
	auto r = tmp();
	emit(r + " = zext i1 " + i1 + " to i32");
	return { r, type::INT32 };
}

