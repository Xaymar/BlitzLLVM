std::string blitz::format(const char* format, ...)
{
	va_list arg1;
	va_list arg2;
	va_start(arg1, format);
	va_copy(arg2, arg1);
	int               length = vsnprintf(nullptr, 0, format, arg1);
	std::vector<char> buffer(length + 1);
	vsnprintf(buffer.data(), buffer.size(), format, arg2);
	va_end(arg1);
	va_end(arg2);
	return {buffer.data(), buffer.data() + length};
}

std::string blitz::source_excerpt(std::filesystem::path const& file, uint64_t line, uint64_t column)
{
	if (line == 0 || file.empty()) {
		return {};
	}
	std::ifstream stream(file, std::ios::binary);
	if (!stream) {
		return {};
	}
	std::string data((std::istreambuf_iterator<char>(stream)), std::istreambuf_iterator<char>());

	// Find the line, which ends at "\n", "\r\n" or "\r". A line after the last one is the end of the file, which is empty.
	size_t start = 0;
	for (uint64_t current = 1; current < line; current++) {
		size_t end = data.find_first_of("\r\n", start);
		if (end == std::string::npos) {
			return {};
		}
		start = end + ((data[end] == '\r' && end + 1 < data.size() && data[end + 1] == '\n') ? 2 : 1);
	}
	std::string text = data.substr(start, data.find_first_of("\r\n", start) - start);

	// Columns count bytes, starting at 1. A column behind the line (like the end of the file) points right after it.
	size_t caret = (column == 0) ? 0 : size_t(std::min<uint64_t>(column - 1, text.size()));

	// Cut very long lines to a window around the column, without splitting a UTF-8 sequence.
	const size_t window = 100;
	bool         cut_front = false, cut_back = false;
	auto         is_continuation = [](char c) { return (static_cast<unsigned char>(c) & 0xC0) == 0x80; };
	if (text.size() > 2 * window) {
		size_t from = (caret > window) ? caret - window : 0;
		size_t to   = std::min(text.size(), caret + window);
		while (from < caret && is_continuation(text[from])) {
			from++;
		}
		while (to < text.size() && is_continuation(text[to])) {
			to++;
		}
		cut_front = from > 0;
		cut_back  = to < text.size();
		text      = text.substr(from, to - from);
		caret -= from;
	}
	std::string prefix = cut_front ? "..." : "";
	std::string result = prefix + text + (cut_back ? "..." : "") + "\n";
	if (column == 0) {
		return result;
	}

	// Pad with the characters of the line, so that tabs line up and multi-byte characters count once.
	std::string padding = std::string(prefix.size(), ' ');
	for (size_t idx = 0; idx < caret && idx < text.size(); idx++) {
		if (text[idx] == '\t') {
			padding += '\t';
		} else if (!is_continuation(text[idx])) {
			padding += ' ';
		}
	}
	return result + padding + "^---------- HERE\n";
}

std::string blitz::diagnostic(std::filesystem::path const& file, uint64_t line, uint64_t column, std::string const& kind, std::string const& reason)
{
	// Without any "." and ".." parts. This is only lexical, the file itself is read through the path as it was given.
	std::string result = file.lexically_normal().generic_string() + ":" + std::to_string(line) + ":" + std::to_string(column) + ": " + kind + ": " + reason;
	std::string excerpt = source_excerpt(file, line, column);
	if (!excerpt.empty()) {
		result += "\n" + excerpt;
		result.pop_back();
	}
	return result;
}
