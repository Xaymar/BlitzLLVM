using blitz::types::type;
using namespace blitz::compiler_detail;

namespace {
	namespace t = blitz::types;

	struct conversion {
		type target;
		bool saturate;
	};

	// The functions that turn a number or a string into one of the sized types. The plain ones wrap integers around and round
	// reals, the Sat ones stop at the smallest and largest number of the type. Reals always stop there, as nothing else is defined.
	const std::map<std::string, conversion> conversions = {
		{ "byte", { type::INT8, false } },     { "ubyte", { type::UINT8, false } },   { "short", { type::INT16, false } },
		{ "ushort", { type::UINT16, false } }, { "uint", { type::UINT32, false } },   { "long", { type::INT64, false } },
		{ "ulong", { type::UINT64, false } },  { "half", { type::FLOAT16, false } },  { "double", { type::FLOAT64, false } },
		{ "pointer", { type::POINTER, false } },
		{ "satbyte", { type::INT8, true } },   { "satubyte", { type::UINT8, true } }, { "satshort", { type::INT16, true } },
		{ "satushort", { type::UINT16, true } }, { "satint", { type::INT32, true } }, { "satuint", { type::UINT32, true } },
		{ "satlong", { type::INT64, true } },  { "satulong", { type::UINT64, true } },
	};

	const std::map<std::string, const char*> bit_functions = {
		{ "popcount", "ctpop" }, { "leadingzeros", "ctlz" }, { "trailingzeros", "cttz" }, { "rotl", "fshl" }, { "rotr", "fshr" }, { "byteswap", "bswap" },
	};

	// The math functions that work with doubles when they are given one. The runtime has a version of each that ends in _d.
	const std::map<std::string, unsigned> double_math = {
		{ "sin", 1 }, { "cos", 1 }, { "tan", 1 },  { "asin", 1 },  { "acos", 1 },  { "atan", 1 }, { "atan2", 2 },
		{ "sqr", 1 }, { "floor", 1 }, { "ceil", 1 }, { "exp", 1 }, { "log", 1 }, { "log10", 1 },
	};

	std::string int_min(type to)
	{
		if (!t::is_signed(to)) {
			return "0";
		}
		return "-" + std::to_string(uint64_t(1) << (t::bits(to) - 1)); // -2^(bits-1), also for 64 bits.
	}

	std::string int_max(type to)
	{
		unsigned bits = t::bits(to) - (t::is_signed(to) ? 1 : 0);
		return (bits == 64) ? std::string("18446744073709551615") : std::to_string((uint64_t(1) << bits) - 1);
	}
} // namespace

// A real becomes the nearest whole number (halves go to the even one), and what does not fit stops at the smallest or largest number.
blitz::compiler::value blitz::compiler::saturate_real(value v, type to, ast::location const& where)
{
	if (v.type == type::FLOAT16) {
		v = convert(v, type::FLOAT32, where, false);
	}
	auto from_llvm = t::to_llvm(v.type), to_llvm = t::to_llvm(to);
	auto rounder   = std::string("llvm.nearbyint.") + (v.type == type::FLOAT32 ? "f32" : "f64");
	declare(rounder, "declare " + from_llvm + " @" + rounder + "(" + from_llvm + ")");
	auto rounded = tmp();
	emit(rounded + " = call " + from_llvm + " @" + rounder + "(" + from_llvm + " " + v.repr + ")");
	auto name = std::string("llvm.") + (t::is_signed(to) ? "fptosi" : "fptoui") + ".sat." + to_llvm + (v.type == type::FLOAT32 ? ".f32" : ".f64");
	declare(name, "declare " + to_llvm + " @" + name + "(" + from_llvm + ")");
	auto r = tmp();
	emit(r + " = call " + to_llvm + " @" + name + "(" + from_llvm + " " + rounded + ")");
	return { r, to };
}

// An integer becomes the closest number of the other integer type. The comparison is done with 128 bits, which holds every
// 64 bit number whether it is signed or not.
blitz::compiler::value blitz::compiler::saturate_integer(value v, type to, ast::location const&)
{
	auto from_llvm = t::to_llvm(v.type), to_llvm = t::to_llvm(to);
	auto wide      = tmp();
	emit(wide + (t::is_signed(v.type) ? " = sext " : " = zext ") + from_llvm + " " + v.repr + " to i128");
	auto under = tmp(), over = tmp(), lo = tmp(), hi = tmp(), narrow = tmp();
	emit(under + " = icmp slt i128 " + wide + ", " + int_min(to));
	emit(lo + " = select i1 " + under + ", i128 " + int_min(to) + ", i128 " + wide);
	emit(over + " = icmp sgt i128 " + lo + ", " + int_max(to));
	emit(hi + " = select i1 " + over + ", i128 " + int_max(to) + ", i128 " + lo);
	emit(narrow + " = trunc i128 " + hi + " to " + to_llvm);
	return { narrow, to };
}

blitz::compiler::value blitz::compiler::gen_numeric(ast::call const* node, bool& handled)
{
	handled  = true;
	auto key = lower(node->name);
	auto args = node->arguments.size();

	auto need = [&](size_t count) {
		if (args != count) {
			throw err(node->where, "Function '" + node->name + "' expects " + std::to_string(count) + " arguments, got " + std::to_string(args) + ".");
		}
	};

	auto conv = conversions.find(key);
	if (conv != conversions.end()) {
		need(1);
		auto v = gen(node->arguments[0].get());
		return convert_explicit(v, conv->second.target, conv->second.saturate, node->where);
	}

	auto bit = bit_functions.find(key);
	if (bit != bit_functions.end()) {
		bool two = (key == "rotl") || (key == "rotr");
		need(two ? 2 : 1);
		// Like the bitwise operators, these take reals and strings as integers. They keep the width of the number they are given.
		auto v = gen(node->arguments[0].get());
		if (!t::is_integer(v.type)) {
			v = convert(v, type::INT32, node->where, false);
		}
		auto llvm = t::to_llvm(v.type);
		auto name = std::string("llvm.") + bit->second + "." + llvm;
		auto r    = tmp();
		if (key == "byteswap") {
			if (t::bits(v.type) == 8) {
				return v;
			}
			declare(name, "declare " + llvm + " @" + name + "(" + llvm + ")");
			emit(r + " = call " + llvm + " @" + name + "(" + llvm + " " + v.repr + ")");
			return { r, v.type };
		} else if (two) {
			auto count = gen(node->arguments[1].get());
			count      = convert(convert(count, type::INT32, node->where, false), v.type, node->where, false);
			declare(name, "declare " + llvm + " @" + name + "(" + llvm + ", " + llvm + ", " + llvm + ")");
			emit(r + " = call " + llvm + " @" + name + "(" + llvm + " " + v.repr + ", " + llvm + " " + v.repr + ", " + llvm + " " + count.repr + ")");
			return { r, v.type };
		}
		bool zeros = (key != "popcount");
		declare(name, "declare " + llvm + " @" + name + "(" + llvm + (zeros ? ", i1" : "") + ")");
		emit(r + " = call " + llvm + " @" + name + "(" + llvm + " " + v.repr + (zeros ? ", i1 false" : "") + ")");
		// A count is at most 64, so it is the same number whether it is widened as signed or not.
		return convert({ r, v.type }, type::INT32, node->where, false);
	}

	auto math = double_math.find(key);
	if (math != double_math.end()) {
		need(math->second);
		std::vector<value> values;
		bool               wide = false;
		for (auto const& arg : node->arguments) {
			values.push_back(gen(arg.get()));
			wide = wide || (values.back().type == type::FLOAT64);
		}
		for (auto& v : values) {
			v = convert(v, wide ? type::FLOAT64 : type::FLOAT32, node->where, true);
		}
		auto entry = find_builtin(key);
		if (wide) {
			auto symbol = std::string(entry->symbol) + "_d";
			return call_runtime(symbol.c_str(), type::FLOAT64, values);
		}
		return call_runtime(entry->symbol, type::FLOAT32, values);
	}

	handled = false;
	return {};
}

// What Byte(x), Short(x), Sat... and the other conversion functions do.
blitz::compiler::value blitz::compiler::convert_explicit(value v, type to, bool saturate, ast::location const& where)
{
	if ((v.type == type::POINTER) || (to == type::POINTER)) {
		// The address as a whole number as wide as the biggest pointer, which is then converted like any other whole number.
		if (v.type == to) {
			return v;
		} else if (v.type == type::POINTER) {
			if (!t::is_integer(to)) {
				throw err(where, "A Pointer can only be converted to a whole number.");
			}
			auto r = tmp();
			emit(r + " = ptrtoint ptr " + v.repr + " to i64");
			return convert_explicit({ r, type::UINT64 }, to, saturate, where);
		} else if ((v.type == type::STRUCT) && v.sname.empty() && (v.repr == "null")) {
			return { "null", to };
		} else if (!t::is_integer(v.type)) {
			throw err(where, "A Pointer can only be made from a whole number.");
		}
		auto wide = convert(v, t::is_signed(v.type) ? type::INT64 : type::UINT64, where, false);
		auto r    = tmp();
		emit(r + " = inttoptr i64 " + wide.repr + " to ptr");
		return { r, type::POINTER };
	}
	if (!is_number(v.type) && (v.type != type::STRING)) {
		throw err(where, "Conversion requires a number or a string.");
	}
	if ((v.type == type::STRING) && t::is_integer(to)) {
		// What does not fit stops at the largest number, as it does when a string is assigned to an integer.
		return saturate ? saturate_integer(convert(v, type::INT64, where, false), to, where) : convert(v, to, where, false);
	}
	if (t::is_real(v.type) && t::is_integer(to)) {
		return saturate_real(v, to, where);
	}
	if (saturate && t::is_integer(v.type) && (v.type != to)) {
		return saturate_integer(v, to, where);
	}
	return convert(v, to, where, false);
}
