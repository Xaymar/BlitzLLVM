void blitz::compiler::begin_function()
{
	_body.str("");
	_allocas.str("");
	_locals.clear();
	_exits.clear();
	_each_flags.clear();
	_labels.clear();
	_gosubs.clear();
	_gosub_stack.clear();
	_gosub_depth.clear();
	_terminated   = false;
	_uses_strings = false;
	_string_locals.clear();
	_object_locals.clear();
	_heap_locals.clear();
	_exit_label.clear();
	_ret_slot.clear();
	_copy_outs.clear();
}

void blitz::compiler::scope_begin(scope& sc)
{
	if (_terminated) {
		sc.active = false; // Unreachable code does not need cleaning up.
		return;
	}
	sc.active = true;
	sc.outer.swap(_body);
	sc.before = _string_temps;
}

void blitz::compiler::scope_end(scope& sc)
{
	if (!sc.active) {
		return;
	}
	std::string text = _body.str();
	_body.swap(sc.outer);
	if ((_string_temps != sc.before) && !_terminated) {
		auto mark = tmp();
		declare("bb_str_mark", "declare i32 @bb_str_mark()");
		declare("bb_str_release", "declare void @bb_str_release(i32)");
		// These calls carry a location as well, a function with debug info needs one on every call.
		_body << "  " << mark << " = call i32 @bb_str_mark()" << dbg() << "\n" << text << "  call void @bb_str_release(i32 " << mark << ")" << dbg() << "\n";
	} else {
		_body << text;
	}
}

// Gives a variable, field or element a copy of the string and frees what it had before. An object is held instead, and the
// one it held before let go.
void blitz::compiler::store_value(address const& target, value const& v)
{
	if ((target.type == type::STRUCT) && !target.sname.empty()) {
		declare("bb_object_assign", "declare ptr @bb_object_assign(ptr, ptr, ptr)");
		auto old = tmp(), fresh = tmp();
		emit(old + " = load ptr, ptr " + target.pointer + (target.element ? ", !tbaa !900004" : ""));
		emit(fresh + " = call ptr @bb_object_assign(ptr " + old + ", ptr " + v.repr + ", ptr " + need_type(target.sname, {}).list + ")");
		emit("store ptr " + fresh + ", ptr " + target.pointer + (target.element ? ", !tbaa !900004" : ""));
		return;
	}
	if (target.type != type::STRING) {
		emit("store " + blitz::types::to_llvm(target.type) + " " + v.repr + ", ptr " + target.pointer + (target.element ? ", !tbaa !900004" : ""));
		return;
	}
	declare("bb_str_assign", "declare ptr @bb_str_assign(ptr, ptr)");
	auto old = tmp(), fresh = tmp();
	emit(old + " = load ptr, ptr " + target.pointer + (target.element ? ", !tbaa !900004" : ""));
	emit(fresh + " = call ptr @bb_str_assign(ptr " + old + ", ptr " + v.repr + ")");
	emit("store ptr " + fresh + ", ptr " + target.pointer + (target.element ? ", !tbaa !900004" : ""));
	_uses_strings = true;
}

// Finds the labels and Gosubs of a function (or the main program), and sets up what Gosub needs.
void blitz::compiler::prepare_flow(ast::block const& block)
{
	std::function<void(ast::block const&)> walk = [&](ast::block const& statements) {
		for (auto const& stmt : statements) {
			if (auto label = dynamic_cast<ast::label_statement const*>(stmt.get())) {
				if (!_labels.insert(lower(label->name)).second) {
					throw err(label->where, "Label '" + label->name + "' already exists.");
				}
			} else if (auto gosub = dynamic_cast<ast::gosub_statement const*>(stmt.get())) {
				int id         = int(_gosubs.size());
				_gosubs[gosub] = id;
			} else if (auto i = dynamic_cast<ast::if_statement const*>(stmt.get())) {
				for (auto const& b : i->branches) {
					walk(b.body);
				}
			} else if (auto w = dynamic_cast<ast::while_statement const*>(stmt.get())) {
				walk(w->body);
			} else if (auto r = dynamic_cast<ast::repeat_statement const*>(stmt.get())) {
				walk(r->body);
			} else if (auto f = dynamic_cast<ast::for_statement const*>(stmt.get())) {
				walk(f->body);
			} else if (auto s = dynamic_cast<ast::select_statement const*>(stmt.get())) {
				for (auto const& c : s->cases) {
					walk(c.body);
				}
			}
		}
	};
	walk(block);

	if (!_gosubs.empty()) {
		_gosub_stack = "%gosub.stack";
		_gosub_depth = "%gosub.depth";
		_allocas << "  " << _gosub_stack << " = alloca [256 x i32]\n";
		_allocas << "  " << _gosub_depth << " = alloca i32\n";
		_allocas << "  store i32 0, ptr " << _gosub_depth << "\n";
	}
}

// The block of a label of the program. Names can have characters that are not allowed in a name of the IR (bytes of UTF-8 are), so
// those are written as their number.
static std::string user_label(std::string const& name)
{
	std::string result = "lbl.";
	for (unsigned char c : lower(name)) {
		if (isalnum(c) || (c == '_')) {
			result += char(c);
		} else {
			result += blitz::format(".%02x", c);
		}
	}
	return result;
}

void blitz::compiler::gen_label(ast::label_statement const* node)
{
	begin_label(user_label(node->name));
}

void blitz::compiler::gen_goto(ast::goto_statement const* node)
{
	if (!_labels.count(lower(node->label))) {
		throw err(node->where, "Label '" + node->label + "' does not exist in this function.");
	}
	emit_terminator("br label %" + user_label(node->label));
}

void blitz::compiler::gen_gosub(ast::gosub_statement const* node)
{
	if (!_labels.count(lower(node->label))) {
		throw err(node->where, "Label '" + node->label + "' does not exist in this function.");
	}
	int id = _gosubs.at(node);

	auto depth = tmp(), full = tmp(), slot = tmp(), next = tmp();
	auto ok_l = label("gosub.ok"), overflow_l = label("gosub.overflow");
	emit(depth + " = load i32, ptr " + _gosub_depth);
	emit(full + " = icmp sge i32 " + depth + ", 256");
	emit_terminator("br i1 " + full + ", label %" + overflow_l + ", label %" + ok_l);
	begin_label(overflow_l);
	call_runtime("bb_runtime_error", type::UNKNOWN, { { string_constant("Too many Gosubs without Return."), type::STRING } });
	emit_terminator("unreachable");
	begin_label(ok_l);
	emit(slot + " = getelementptr inbounds [256 x i32], ptr " + _gosub_stack + ", i32 0, i32 " + depth);
	emit("store i32 " + std::to_string(id) + ", ptr " + slot);
	emit(next + " = add i32 " + depth + ", 1");
	emit("store i32 " + next + ", ptr " + _gosub_depth);
	emit_terminator("br label %" + user_label(node->label));

	// Where Return comes back to.
	begin_label("gosub.back." + std::to_string(id));
}

// Return from a Gosub: jumps to the block behind the Gosub that was called last.
void blitz::compiler::gen_gosub_return(ast::location const& where)
{
	(void)where;
	auto depth = tmp(), any = tmp();
	auto pop_l = label("return.pop"), none_l = label("return.none");
	emit(depth + " = load i32, ptr " + _gosub_depth);
	emit(any + " = icmp sgt i32 " + depth + ", 0");
	emit_terminator("br i1 " + any + ", label %" + pop_l + ", label %" + none_l);

	begin_label(none_l);
	if (_in_main) {
		call_runtime("bb_runtime_error", type::UNKNOWN, { { string_constant("Return without Gosub."), type::STRING } });
		emit_terminator("unreachable");
	} else {
		// In a function, Return also means returning from the function itself.
		auto llvm = blitz::types::to_llvm(_return_type);
		if (!_copy_outs.empty()) {
			// Out and InOut parameters have to be handed back first.
			emit("store " + llvm + " " + zero(_return_type).repr + ", ptr " + _ret_slot);
			emit_terminator("br label %" + _exit_label);
		} else {
			emit_terminator("ret " + llvm + " " + zero(_return_type).repr);
		}
	}

	begin_label(pop_l);
	auto last = tmp(), slot = tmp(), id = tmp();
	emit(last + " = sub i32 " + depth + ", 1");
	emit("store i32 " + last + ", ptr " + _gosub_depth);
	emit(slot + " = getelementptr inbounds [256 x i32], ptr " + _gosub_stack + ", i32 0, i32 " + last);
	emit(id + " = load i32, ptr " + slot);
	std::string cases;
	for (size_t i = 0; i < _gosubs.size(); i++) {
		cases += " i32 " + std::to_string(i) + ", label %gosub.back." + std::to_string(i);
	}
	emit_terminator("switch i32 " + id + ", label %" + none_l + " [" + cases + " ]");
}

// `@"bb.f.3"` is called `bb.f.3` in the debug information.
static std::string linkage_name(std::string symbol)
{
	symbol.erase(std::remove_if(symbol.begin(), symbol.end(), [](char c) { return (c == '@') || (c == '"'); }), symbol.end());
	return symbol;
}

// What the Return statements of a function without a type give is what its type should be: no Return that gives a value means Void, and Returns that all give the same
// type mean that type. The warning that the function has no type was made earlier, and gets the type to write (or none if the Returns disagree) as its detail.
void blitz::compiler::suggest_return_type(ast::function const& fn)
{
	std::string suffix;
	// A Return without a value gives the 0 of the default Int, which is fine for a function that is an Int otherwise.
	auto kinds = _return_kinds;
	if ((kinds.size() == 2) && kinds.count("void") && kinds.count("int")) {
		kinds.erase("void");
	}
	if (kinds.empty() || ((kinds.size() == 1) && kinds.count("void"))) {
		suffix = ":Void";
	} else if (kinds.size() == 1) {
		auto const& kind = *kinds.begin();
		suffix = (kind == "int") ? ":Int32" : (kind == "float") ? ":Float32" : (kind == "string") ? ":String" : "";
	}
	auto typeless = fn.where.file ? _typeless_functions.find(fn.where.file->generic_string() + ":" + std::to_string(fn.where.line) + ":" + std::to_string(fn.where.column)) : _typeless_functions.end();
	if (typeless != _typeless_functions.end()) {
		auto& f = findings[typeless->second];
		f.detail = suffix;
		if (!suffix.empty() && fn.name_where.file && (fn.name_where.line != 0)) {
			// A type that is not Int changes what the callers get (Float 1.5 is 1 as an Int), so blitz-tidy leaves it to "unsafe".
			uint64_t at = fn.name_where.column + fn.name.size();
			f.edits.push_back(edit{ *fn.name_where.file, ast::range{ fn.name_where.line, at, fn.name_where.line, at }, suffix });
			f.detail = ((suffix == ":Void") || (suffix == ":Int32")) ? suffix : "changes-program";
		}
		if (suffix == ":Void") {
			f.notice = "It never returns a value: add ':Void' to the name, such as 'Function " + fn.name + ":Void'.";
		} else if (!suffix.empty()) {
			f.notice = "Every Return gives the same type: add '" + suffix + "' to the name, such as 'Function " + fn.name + suffix + "'.";
		}
	}
}

void blitz::compiler::gen_function(ast::function const& fn)
{
	begin_function();
	_in_main      = false;
	_return_type  = fn.type;
	_return_sname = lower(fn.struct_name);
	_return_typed = fn.typed;
	_return_void  = fn.is_void;
	_scope        = lower(fn.name);
	_return_kinds.clear();

	auto const& info = _functions.at(lower(fn.name));
	std::string params;
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		// Out and InOut parameters are the address of the variable of the caller.
		params += (idx ? ", " : "") + ((fn.parameters[idx].mode == ast::direction::IN) ? blitz::types::to_llvm(fn.parameters[idx].type) : std::string("ptr")) + " %a" + std::to_string(idx);
	}

	std::string sp = di_begin_function(fn.name, linkage_name(info.symbol), fn.where, fn.type, lower(fn.struct_name), &fn.parameters, true);
	check_written(fn);
	prepare_flow(fn.body);
	_exit_label = label("fn.exit");
	_ret_slot   = "%ret.slot";
	if (!fn.is_void) {
		_allocas << "  " << _ret_slot << " = alloca " << blitz::types::to_llvm(fn.type) << "\n";
	}
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		auto const& param = fn.parameters[idx];
		_arg                  = uint32_t(idx + 1);
		auto        var   = create_local(param.name, param.type, false, param.where, param.struct_name);
		_arg                  = 0;
		if (param.mode != ast::direction::IN) {
			gen_reference_parameter(param, var, idx);
		} else if (param.type == type::STRING) {
			// What was passed belongs to the caller, so the function works on a copy.
			declare("bb_str_dup", "declare ptr @bb_str_dup(ptr)");
			auto copy = tmp();
			emit(copy + " = call ptr @bb_str_dup(ptr %a" + std::to_string(idx) + ")");
			emit("store ptr " + copy + ", ptr " + var.pointer);
		} else if ((param.type == type::STRUCT) && !param.struct_name.empty()) {
			// The function holds what it was given, so that it stays while the function runs.
			store_value({ var.pointer, param.type, lower(param.struct_name), 0, false }, value{ "%a" + std::to_string(idx), param.type, lower(param.struct_name) });
		} else {
			emit("store " + blitz::types::to_llvm(param.type) + " %a" + std::to_string(idx) + ", ptr " + var.pointer);
		}
	}
	gen_block(fn.body);
	report_unused(_locals);
	if (!fn.typed) {
		suggest_return_type(fn);
	}
	if (!_terminated) {
		if (!fn.is_void) {
			emit("store " + blitz::types::to_llvm(fn.type) + " " + zero(fn.type).repr + ", ptr " + _ret_slot);
		}
		emit_terminator("br label %" + _exit_label);
	}

	// Everything leaves through here: what the function made is freed, and then the value goes back.
	begin_label(_exit_label);
	for (auto const& each : _each_flags) {
		declare("bb_loop_leave", "declare void @bb_loop_leave(ptr, ptr)");
		emit("call void @bb_loop_leave(ptr " + each.second + ", ptr " + each.first + ")");
	}
	gen_copy_outs();
	for (auto const& local : _object_locals) {
		if (local.count) {
			declare("bb_object_drop_array", "declare void @bb_object_drop_array(ptr, i64, ptr)");
			emit("call void @bb_object_drop_array(ptr " + local.pointer + ", i64 " + std::to_string(local.count) + ", ptr " + need_type(local.sname, {}).list + ")");
		} else {
			declare("bb_object_drop", "declare void @bb_object_drop(ptr, ptr)");
			auto held = tmp();
			emit(held + " = load ptr, ptr " + local.pointer);
			emit("call void @bb_object_drop(ptr " + held + ", ptr " + need_type(local.sname, {}).list + ")");
		}
	}
	if (_uses_strings) {
		declare("bb_str_mark", "declare i32 @bb_str_mark()");
		_allocas << "  %entry.mark = call i32 @bb_str_mark()" << dbg() << "\n";
		for (auto const& local : _string_locals) {
			if (local.second) {
				declare("bb_str_free_array", "declare void @bb_str_free_array(ptr, i32)");
				emit("call void @bb_str_free_array(ptr " + local.first + ", i32 " + std::to_string(local.second) + ")");
			} else {
				declare("bb_str_free", "declare void @bb_str_free(ptr)");
				auto held = tmp();
				emit(held + " = load ptr, ptr " + local.first);
				emit("call void @bb_str_free(ptr " + held + ")");
			}
		}
		if (fn.type != type::STRING) {
			declare("bb_str_release", "declare void @bb_str_release(i32)");
			emit("call void @bb_str_release(i32 %entry.mark)");
		}
	}
	if (!_heap_locals.empty()) {
		declare("bb_free", "declare void @bb_free(ptr)");
		for (auto const& array : _heap_locals) {
			emit("call void @bb_free(ptr " + array + ")");
		}
	}
	if (fn.is_void) {
		emit_terminator("ret void");
	} else {
		auto result = tmp();
		emit(result + " = load " + blitz::types::to_llvm(fn.type) + ", ptr " + _ret_slot);
		emit_terminator("ret " + blitz::types::to_llvm(fn.type) + " " + result);
	}

	di_end_function();
	_definitions << "define internal " << blitz::types::to_llvm(fn.type) << " " << info.symbol << "(" << params << ")" << (sp.empty() ? "" : " !dbg " + sp) << " {\n"
				 << "entry:\n"
				 << _allocas.str() << _body.str() << "}\n\n";
}

// Starts an Out or InOut parameter: Out begins with its default value, InOut with what the caller has.
void blitz::compiler::gen_reference_parameter(ast::parameter const& param, variable const& var, size_t idx)
{
	auto arg  = "%a" + std::to_string(idx);
	auto llvm = blitz::types::to_llvm(param.type);
	bool optional = (param.initial != nullptr);

	auto set_default = [&] {
		auto v = convert(gen(param.initial.get()), param.type, param.where, true, param.struct_name);
		if (param.type == type::STRING) {
			declare("bb_str_dup", "declare ptr @bb_str_dup(ptr)");
			auto copy = tmp();
			emit(copy + " = call ptr @bb_str_dup(ptr " + v.repr + ")");
			v = { copy, type::STRING };
			_uses_strings = true;
		}
		if ((param.type == type::STRUCT) && !param.struct_name.empty()) {
			store_value({ var.pointer, param.type, lower(param.struct_name), 0, false }, { v.repr, param.type, lower(param.struct_name) });
			return;
		}
		emit("store " + llvm + " " + v.repr + ", ptr " + var.pointer);
	};

	if (param.mode == ast::direction::OUT) {
		if (optional) {
			set_default();
		}
	} else {
		auto copy_in = [&] {
			auto held = tmp();
			emit(held + " = load " + llvm + ", ptr " + arg);
			if (param.type == type::STRING) {
				declare("bb_str_dup", "declare ptr @bb_str_dup(ptr)");
				auto copy = tmp();
				emit(copy + " = call ptr @bb_str_dup(ptr " + held + ")");
				held = copy;
				_uses_strings = true;
			}
			if ((param.type == type::STRUCT) && !param.struct_name.empty()) {
				store_value({ var.pointer, param.type, lower(param.struct_name), 0, false }, { held, param.type, lower(param.struct_name) });
				return;
			}
			emit("store " + llvm + " " + held + ", ptr " + var.pointer);
		};
		if (optional) {
			// The caller left it out, which means the default.
			auto missing = tmp();
			auto use_default = label("param.default"), use_given = label("param.given"), joined = label("param.ready");
			emit(missing + " = icmp eq ptr " + arg + ", null");
			emit_terminator("br i1 " + missing + ", label %" + use_default + ", label %" + use_given);
			begin_label(use_default);
			set_default();
			emit_terminator("br label %" + joined);
			begin_label(use_given);
			copy_in();
			emit_terminator("br label %" + joined);
			begin_label(joined);
		} else {
			copy_in();
		}
	}
	_copy_outs.push_back({ var.pointer, arg, param.type, lower(param.struct_name), optional });
}

// Hands the Out and InOut parameters back to the variables of the caller.
void blitz::compiler::gen_copy_outs()
{
	for (auto const& out : _copy_outs) {
		std::string done;
		if (out.optional) {
			auto missing = tmp();
			auto store_l = label("param.store");
			done         = label("param.stored");
			emit(missing + " = icmp eq ptr " + out.target + ", null");
			emit_terminator("br i1 " + missing + ", label %" + done + ", label %" + store_l);
			begin_label(store_l);
		}
		auto held = tmp();
		emit(held + " = load " + blitz::types::to_llvm(out.type) + ", ptr " + out.local);
		store_value(address{ out.target, out.type, out.sname, 0, false }, value{ held, out.type, out.sname });
		if (out.optional) {
			emit_terminator("br label %" + done);
			begin_label(done);
		}
	}
}

namespace {
	using blitz::compiler_detail::lower;
	namespace ast = blitz::ast;

	// How far a function got with writing to an Out or InOut parameter. Unreachable is a state too, so that paths merge properly.
	enum written : int { UNREACHABLE = 0, UNWRITTEN = 1, WRITTEN = 2 };

	int merge(int a, int b)
	{
		if (a == UNREACHABLE) return b;
		if (b == UNREACHABLE) return a;
		return std::min(a, b);
	}
} // namespace

// Out parameters have to be written on every path that leaves the function, and InOut parameters should be.
void blitz::compiler::check_written(ast::function const& fn)
{
	for (auto const& param : fn.parameters) {
		if (param.mode == ast::direction::IN) {
			continue;
		}
		auto name = lower(param.name);

		// Gotos and Gosubs make the paths too hard to follow, so those functions are not checked.
		bool jumps = false;
		std::vector<std::pair<ast::location, int>>   returns;
		std::vector<std::vector<int>>                exits;

		// Whether the expression gives the parameter to a parameter of another function (or itself) that writes to it.
		std::function<bool(ast::expression const*)> expr_writes = [&](ast::expression const* e) -> bool {
			if (!e) {
				return false;
			}
			if (auto c = dynamic_cast<ast::call const*>(e)) {
				auto it = _functions.find(lower(c->name));
				for (size_t idx = 0; idx < c->arguments.size(); idx++) {
					if ((it != _functions.end()) && (idx < it->second.declaration->parameters.size()) && (it->second.declaration->parameters[idx].mode != ast::direction::IN)) {
						if (auto r = dynamic_cast<ast::reference const*>(c->arguments[idx].get())) {
							if (lower(r->name) == name) {
								return true;
							}
						}
					}
					if (expr_writes(c->arguments[idx].get())) {
						return true;
					}
				}
				return false;
			} else if (auto b = dynamic_cast<ast::binary const*>(e)) {
				return expr_writes(b->lhs.get()) || expr_writes(b->rhs.get());
			} else if (auto u = dynamic_cast<ast::unary const*>(e)) {
				return expr_writes(u->operand.get());
			} else if (auto f = dynamic_cast<ast::field_access const*>(e)) {
				return expr_writes(f->object.get());
			} else if (auto i = dynamic_cast<ast::index_access const*>(e)) {
				return expr_writes(i->base.get()) || expr_writes(i->index.get());
			}
			return false;
		};
		auto is_param = [&](ast::expression const* e) {
			auto r = dynamic_cast<ast::reference const*>(e);
			return r && (lower(r->name) == name);
		};

		std::function<int(ast::block const&, int)> flow = [&](ast::block const& block, int state) -> int {
			for (auto const& stmt : block) {
				if (state == UNREACHABLE) {
					break;
				}
				auto raw = stmt.get();
				if (auto a = dynamic_cast<ast::assign const*>(raw)) {
					if (is_param(a->target.get()) || expr_writes(a->value.get())) {
						state = WRITTEN;
					}
				} else if (auto c = dynamic_cast<ast::call_statement const*>(raw)) {
					if (expr_writes(c->invocation.get())) {
						state = WRITTEN;
					}
				} else if (auto r = dynamic_cast<ast::read_statement const*>(raw)) {
					for (auto const& t : r->targets) {
						if (is_param(t.get())) {
							state = WRITTEN;
						}
					}
				} else if (auto i = dynamic_cast<ast::if_statement const*>(raw)) {
					if (!i->branches.empty() && expr_writes(i->branches.front().condition.get())) {
						state = WRITTEN;
					}
					int  after = UNREACHABLE;
					bool other = false;
					for (auto const& b : i->branches) {
						after = merge(after, flow(b.body, state));
						other = other || !b.condition;
					}
					state = other ? after : merge(after, state);
				} else if (auto w = dynamic_cast<ast::while_statement const*>(raw)) {
					if (expr_writes(w->condition.get())) {
						state = WRITTEN;
					}
					exits.emplace_back();
					flow(w->body, state);
					int after = state;
					for (int e : exits.back()) after = merge(after, e);
					exits.pop_back();
					state = after;
				} else if (auto rp = dynamic_cast<ast::repeat_statement const*>(raw)) {
					exits.emplace_back();
					int end = flow(rp->body, state);
					int after = UNREACHABLE;
					if (rp->condition) {
						after = (end != UNREACHABLE) ? ((expr_writes(rp->condition.get()) ? WRITTEN : end)) : UNREACHABLE;
					}
					for (int e : exits.back()) after = merge(after, e);
					exits.pop_back();
					state = after;
				} else if (auto f = dynamic_cast<ast::for_statement const*>(raw)) {
					if (is_param(f->variable.get()) || expr_writes(f->from.get()) || expr_writes(f->to.get()) || expr_writes(f->step.get())) {
						state = WRITTEN;
					}
					exits.emplace_back();
					flow(f->body, state);
					int after = state;
					for (int e : exits.back()) after = merge(after, e);
					exits.pop_back();
					state = after;
				} else if (auto s = dynamic_cast<ast::select_statement const*>(raw)) {
					if (expr_writes(s->subject.get())) {
						state = WRITTEN;
					}
					int  after       = UNREACHABLE;
					bool has_default = false;
					for (auto const& c : s->cases) {
						after       = merge(after, flow(c.body, state));
						has_default = has_default || c.values.empty();
					}
					state = has_default ? after : merge(after, state);
				} else if (dynamic_cast<ast::exit_statement const*>(raw)) {
					if (!exits.empty()) {
						exits.back().push_back(state);
					}
					state = UNREACHABLE;
				} else if (auto rt = dynamic_cast<ast::return_statement const*>(raw)) {
					if (expr_writes(rt->value.get())) {
						state = WRITTEN;
					}
					returns.emplace_back(rt->where, state);
					state = UNREACHABLE;
				} else if (dynamic_cast<ast::end_statement const*>(raw) || dynamic_cast<ast::stop_statement const*>(raw)) {
					state = UNREACHABLE;
				} else if (dynamic_cast<ast::goto_statement const*>(raw) || dynamic_cast<ast::gosub_statement const*>(raw) || dynamic_cast<ast::label_statement const*>(raw)) {
					jumps = true;
				}
			}
			return state;
		};

		int end = flow(fn.body, UNWRITTEN);
		if (jumps) {
			continue;
		}
		ast::location finish = fn.where;
		if (fn.covers.end_line) {
			finish.line   = fn.covers.end_line;
			finish.column = 1; // The End Function.
		}
		if (end == UNWRITTEN) {
			returns.emplace_back(finish, UNWRITTEN);
		}
		for (auto const& leave : returns) {
			if (leave.second != UNWRITTEN) {
				continue;
			}
			if (param.mode == ast::direction::OUT) {
				throw err(leave.first, "Out parameter '" + param.name + "' of '" + fn.name + "' is not written on every path, it has to be before the function returns.");
			}
			warn(leave.first, "inout-parameter-unwritten", "InOut parameter '" + param.name + "' of '" + fn.name + "' is not written on this path, the caller keeps the value it had.", "Write to '" + param.name + "' before returning, or declare it with 'In'.");
		}
	}
}

void blitz::compiler::gen_main(ast::program const& program)
{
	begin_function();
	_in_main      = true;
	_return_type  = type::INT32;
	_return_sname = "";
	_return_typed = false;
	_return_void  = false;
	_scope        = "";

	ast::location start;
	start.file = std::make_shared<const std::filesystem::path>(source);
	start.line = start.column = 1;
	std::string sp = di_begin_function("main", "bb_program", start, type::INT32, "", nullptr, false);
	prepare_flow(program.main);
	if (debug) {
		call_runtime("bb_set_debug", type::UNKNOWN, { { "1", type::INT32 } });
	}
	if (profile) {
		// Bit 0: time the runtime. Bit 1: the program has symbols, so BLITZLLVM_PROFILE_SAMPLE also records call stacks.
		call_runtime("bb_set_profile", type::UNKNOWN, { { debug_info ? "3" : "1", type::INT32 } });
	}
	gen_block(program.main);
	report_unused(_locals);
	if (!_terminated) {
		call_runtime("bb_end", type::UNKNOWN, {}); // Falling off the end is End, which takes the graphics down before the libraries unwind.
		emit_terminator("ret i32 0");
	}

	di_end_function();
	_definitions << "define i32 @bb_program()" << (sp.empty() ? "" : " !dbg " + sp) << " {\n"
				 << "entry:\n"
				 << _allocas.str() << _body.str() << "}\n\n";
}
