void blitz::compiler::begin_function()
{
	_body.str("");
	_allocas.str("");
	_locals.clear();
	_exits.clear();
	_labels.clear();
	_gosubs.clear();
	_gosub_stack.clear();
	_gosub_depth.clear();
	_terminated   = false;
	_uses_strings = false;
	_string_locals.clear();
	_exit_label.clear();
	_ret_slot.clear();
}

void blitz::compiler::scope_begin(scope& sc)
{
	if (_terminated) {
		sc.active = false; // Unreachable code does not need cleaning up.
		return;
	}
	sc.active = true;
	sc.outer.swap(_body);
	sc.before = _string_temps;
}

void blitz::compiler::scope_end(scope& sc)
{
	if (!sc.active) {
		return;
	}
	std::string text = _body.str();
	_body.swap(sc.outer);
	if ((_string_temps != sc.before) && !_terminated) {
		auto mark = tmp();
		declare("bb_str_mark", "declare i32 @bb_str_mark()");
		declare("bb_str_release", "declare void @bb_str_release(i32)");
		_body << "  " << mark << " = call i32 @bb_str_mark()\n" << text << "  call void @bb_str_release(i32 " << mark << ")\n";
	} else {
		_body << text;
	}
}

// Gives a variable, field or element a copy of the string and frees what it had before.
void blitz::compiler::store_value(address const& target, value const& v)
{
	if (target.type != type::STRING) {
		emit("store " + blitz::types::to_llvm(target.type) + " " + v.repr + ", ptr " + target.pointer);
		return;
	}
	declare("bb_str_assign", "declare ptr @bb_str_assign(ptr, ptr)");
	auto old = tmp(), fresh = tmp();
	emit(old + " = load ptr, ptr " + target.pointer);
	emit(fresh + " = call ptr @bb_str_assign(ptr " + old + ", ptr " + v.repr + ")");
	emit("store ptr " + fresh + ", ptr " + target.pointer);
	_uses_strings = true;
}

// Finds the labels and Gosubs of a function (or the main program), and sets up what Gosub needs.
void blitz::compiler::prepare_flow(ast::block const& block)
{
	std::function<void(ast::block const&)> walk = [&](ast::block const& statements) {
		for (auto const& stmt : statements) {
			if (auto label = dynamic_cast<ast::label_statement const*>(stmt.get())) {
				if (!_labels.insert(lower(label->name)).second) {
					throw err(label->where, "Label '" + label->name + "' already exists.");
				}
			} else if (auto gosub = dynamic_cast<ast::gosub_statement const*>(stmt.get())) {
				int id         = int(_gosubs.size());
				_gosubs[gosub] = id;
			} else if (auto i = dynamic_cast<ast::if_statement const*>(stmt.get())) {
				for (auto const& b : i->branches) {
					walk(b.body);
				}
			} else if (auto w = dynamic_cast<ast::while_statement const*>(stmt.get())) {
				walk(w->body);
			} else if (auto r = dynamic_cast<ast::repeat_statement const*>(stmt.get())) {
				walk(r->body);
			} else if (auto f = dynamic_cast<ast::for_statement const*>(stmt.get())) {
				walk(f->body);
			} else if (auto s = dynamic_cast<ast::select_statement const*>(stmt.get())) {
				for (auto const& c : s->cases) {
					walk(c.body);
				}
			}
		}
	};
	walk(block);

	if (!_gosubs.empty()) {
		_gosub_stack = "%gosub.stack";
		_gosub_depth = "%gosub.depth";
		_allocas << "  " << _gosub_stack << " = alloca [256 x i32]\n";
		_allocas << "  " << _gosub_depth << " = alloca i32\n";
		_allocas << "  store i32 0, ptr " << _gosub_depth << "\n";
	}
}

void blitz::compiler::gen_label(ast::label_statement const* node)
{
	begin_label("lbl." + lower(node->name));
}

void blitz::compiler::gen_goto(ast::goto_statement const* node)
{
	if (!_labels.count(lower(node->label))) {
		throw err(node->where, "Label '" + node->label + "' does not exist in this function.");
	}
	emit_terminator("br label %lbl." + lower(node->label));
}

void blitz::compiler::gen_gosub(ast::gosub_statement const* node)
{
	if (!_labels.count(lower(node->label))) {
		throw err(node->where, "Label '" + node->label + "' does not exist in this function.");
	}
	int id = _gosubs.at(node);

	auto depth = tmp(), full = tmp(), slot = tmp(), next = tmp();
	auto ok_l = label("gosub.ok"), overflow_l = label("gosub.overflow");
	emit(depth + " = load i32, ptr " + _gosub_depth);
	emit(full + " = icmp sge i32 " + depth + ", 256");
	emit_terminator("br i1 " + full + ", label %" + overflow_l + ", label %" + ok_l);
	begin_label(overflow_l);
	call_runtime("bb_runtime_error", type::UNKNOWN, { { string_constant("Too many Gosubs without Return."), type::STRING } });
	emit_terminator("unreachable");
	begin_label(ok_l);
	emit(slot + " = getelementptr inbounds [256 x i32], ptr " + _gosub_stack + ", i32 0, i32 " + depth);
	emit("store i32 " + std::to_string(id) + ", ptr " + slot);
	emit(next + " = add i32 " + depth + ", 1");
	emit("store i32 " + next + ", ptr " + _gosub_depth);
	emit_terminator("br label %lbl." + lower(node->label));

	// Where Return comes back to.
	begin_label("gosub.back." + std::to_string(id));
}

// Return from a Gosub: jumps to the block behind the Gosub that was called last.
void blitz::compiler::gen_gosub_return(ast::location const& where)
{
	(void)where;
	auto depth = tmp(), any = tmp();
	auto pop_l = label("return.pop"), none_l = label("return.none");
	emit(depth + " = load i32, ptr " + _gosub_depth);
	emit(any + " = icmp sgt i32 " + depth + ", 0");
	emit_terminator("br i1 " + any + ", label %" + pop_l + ", label %" + none_l);

	begin_label(none_l);
	if (_in_main) {
		call_runtime("bb_runtime_error", type::UNKNOWN, { { string_constant("Return without Gosub."), type::STRING } });
		emit_terminator("unreachable");
	} else {
		// In a function, Return also means returning from the function itself.
		auto llvm = blitz::types::to_llvm(_return_type);
		emit_terminator("ret " + llvm + " " + zero(_return_type).repr);
	}

	begin_label(pop_l);
	auto last = tmp(), slot = tmp(), id = tmp();
	emit(last + " = sub i32 " + depth + ", 1");
	emit("store i32 " + last + ", ptr " + _gosub_depth);
	emit(slot + " = getelementptr inbounds [256 x i32], ptr " + _gosub_stack + ", i32 0, i32 " + last);
	emit(id + " = load i32, ptr " + slot);
	std::string cases;
	for (size_t i = 0; i < _gosubs.size(); i++) {
		cases += " i32 " + std::to_string(i) + ", label %gosub.back." + std::to_string(i);
	}
	emit_terminator("switch i32 " + id + ", label %" + none_l + " [" + cases + " ]");
}

// `@"bb.f.3"` is called `bb.f.3` in the debug information.
static std::string linkage_name(std::string symbol)
{
	symbol.erase(std::remove_if(symbol.begin(), symbol.end(), [](char c) { return (c == '@') || (c == '"'); }), symbol.end());
	return symbol;
}

void blitz::compiler::gen_function(ast::function const& fn)
{
	begin_function();
	_in_main      = false;
	_return_type  = fn.type;
	_return_sname = lower(fn.struct_name);
	_scope        = lower(fn.name);

	auto const& info = _functions.at(lower(fn.name));
	std::string params;
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		params += (idx ? ", " : "") + blitz::types::to_llvm(fn.parameters[idx].type) + " %a" + std::to_string(idx);
	}

	std::string sp = di_begin_function(fn.name, linkage_name(info.symbol), fn.where, fn.type, lower(fn.struct_name), &fn.parameters, true);
	prepare_flow(fn.body);
	_exit_label = label("fn.exit");
	_ret_slot   = "%ret.slot";
	_allocas << "  " << _ret_slot << " = alloca " << blitz::types::to_llvm(fn.type) << "\n";
	for (size_t idx = 0; idx < fn.parameters.size(); idx++) {
		auto const& param = fn.parameters[idx];
		_arg                  = uint32_t(idx + 1);
		auto        var   = create_local(param.name, param.type, false, param.where, param.struct_name);
		_arg                  = 0;
		if (param.type == type::STRING) {
			// What was passed belongs to the caller, so the function works on a copy.
			declare("bb_str_dup", "declare ptr @bb_str_dup(ptr)");
			auto copy = tmp();
			emit(copy + " = call ptr @bb_str_dup(ptr %a" + std::to_string(idx) + ")");
			emit("store ptr " + copy + ", ptr " + var.pointer);
		} else {
			emit("store " + blitz::types::to_llvm(param.type) + " %a" + std::to_string(idx) + ", ptr " + var.pointer);
		}
	}
	gen_block(fn.body);
	report_unused(_locals);
	if (!_terminated) {
		emit("store " + blitz::types::to_llvm(fn.type) + " " + zero(fn.type).repr + ", ptr " + _ret_slot);
		emit_terminator("br label %" + _exit_label);
	}

	// Everything leaves through here: what the function made is freed, and then the value goes back.
	begin_label(_exit_label);
	if (_uses_strings) {
		declare("bb_str_mark", "declare i32 @bb_str_mark()");
		_allocas << "  %entry.mark = call i32 @bb_str_mark()\n";
		for (auto const& local : _string_locals) {
			if (local.second) {
				declare("bb_str_free_array", "declare void @bb_str_free_array(ptr, i32)");
				emit("call void @bb_str_free_array(ptr " + local.first + ", i32 " + std::to_string(local.second) + ")");
			} else {
				declare("bb_str_free", "declare void @bb_str_free(ptr)");
				auto held = tmp();
				emit(held + " = load ptr, ptr " + local.first);
				emit("call void @bb_str_free(ptr " + held + ")");
			}
		}
		if (fn.type != type::STRING) {
			declare("bb_str_release", "declare void @bb_str_release(i32)");
			emit("call void @bb_str_release(i32 %entry.mark)");
		}
	}
	auto result = tmp();
	emit(result + " = load " + blitz::types::to_llvm(fn.type) + ", ptr " + _ret_slot);
	emit_terminator("ret " + blitz::types::to_llvm(fn.type) + " " + result);

	di_end_function();
	_definitions << "define internal " << blitz::types::to_llvm(fn.type) << " " << info.symbol << "(" << params << ")" << (sp.empty() ? "" : " !dbg " + sp) << " {\n"
				 << "entry:\n"
				 << _allocas.str() << _body.str() << "}\n\n";
}

void blitz::compiler::gen_main(ast::program const& program)
{
	begin_function();
	_in_main      = true;
	_return_type  = type::INT32;
	_return_sname = "";
	_scope        = "";

	ast::location start;
	start.file = std::make_shared<const std::filesystem::path>(source);
	start.line = start.column = 1;
	std::string sp = di_begin_function("main", "main", start, type::INT32, "", nullptr, false);
	prepare_flow(program.main);
	call_runtime("bb_init", type::UNKNOWN, { { "%argc", type::INT32 }, { "%argv", type::STRUCT } });
	if (debug) {
		call_runtime("bb_set_debug", type::UNKNOWN, { { "1", type::INT32 } });
	}
	gen_block(program.main);
	report_unused(_locals);
	if (!_terminated) {
		emit_terminator("ret i32 0");
	}

	di_end_function();
	_definitions << "define i32 @main(i32 %argc, ptr %argv)" << (sp.empty() ? "" : " !dbg " + sp) << " {\n"
				 << "entry:\n"
				 << _allocas.str() << _body.str() << "}\n\n";
}
