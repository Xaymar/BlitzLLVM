#pragma once
#include <filesystem>
#include <map>
#include <string>
#include <vector>
#include "ast/ast.hpp"

namespace blitz {
	/** A kind of warning: Its name is used by -W<name> and -Wno-<name>, and it is on from its level (-W1 to -W4) upwards. */
	struct warning_info {
		const char* name;
		int         level;
		bool        hint; // A hint is printed as a notice, and isn't made an error by -Werror (only by -Werror=<name>).
		const char* description;
	};

	/** A change to a source file: the text from the start of the range up to its end (exclusive) is replaced with the text. Nothing is replaced if the range is empty, which inserts. */
	struct edit {
		std::filesystem::path file;
		ast::range            at;
		std::string           text;
	};

	/** A warning that was emitted, and what would fix it. */
	struct finding {
		std::string   warning; // The name, such as "implicit-lossy-real-to-int".
		ast::location where;
		std::string   reason;
		std::string   notice; // What the compiler suggests.
		std::vector<edit> edits; // Empty if the compiler doesn't know the fix.
		std::string       detail; // Extra data for the fix, such as the declaration for implicit-variable.
	};

	/** The warning with this name, throws std::runtime_error if there is none. */
	warning_info const& find_warning(std::string const& name);

	/** All warnings, ordered by level and then by name. */
	std::vector<warning_info> const& all_warnings();

	/** Which warnings are on, and which of them are errors. Set from the -W options of the command line. */
	class warning_settings {
		int                   _level = 2; // -W2 is the default.
		bool                  _error = false;
		std::map<std::string, bool> _enabled; // -W<name> and -Wno-<name>, which win over the level.
		std::map<std::string, bool> _errors; // -Werror=<name> and -Wno-error=<name>, which win over -Werror.

		public:
		/** Handles the option (like "-W3", "-Wreal-to-int", "-Wno-real-to-int", "-Werror", "-Werror=real-to-int" or "-Wno-error=real-to-int"), in lower case.
		 * Returns false if it isn't a -W option, throws std::runtime_error if it is one but names a warning that doesn't exist. */
		bool parse(std::string const& option);

		bool enabled(std::string const& name) const;
		bool is_error(std::string const& name) const;

		/** Whether -Werror=<name> or -Wno-error=<name> was given, which decides whether the warning is an error whatever else is set. */
		bool error_given(std::string const& name) const;
	};
} // namespace blitz
