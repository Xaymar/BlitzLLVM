// The constant value of a Data item. Integers are 32 bit like in the original, and numbers become Floats when one side is.
bool blitz::compiler::fold_data(ast::expression const* expr, data_value& out)
{
	if (auto l = dynamic_cast<ast::literal const*>(expr)) {
		switch (l->kind) {
		case ast::literal::variant::INTEGER:
			out = { data_value::INTEGER, l->i, 0.0, {} };
			return true;
		case ast::literal::variant::UNSIGNED_INTEGER:
			out = { data_value::INTEGER, int64_t(l->u), 0.0, {} };
			return true;
		case ast::literal::variant::REAL:
			out = { data_value::REAL, 0, l->f, {} };
			return true;
		case ast::literal::variant::STRING:
			out = { data_value::STRING, 0, 0.0, l->text };
			return true;
		default:
			return false;
		}
	} else if (dynamic_cast<ast::reference const*>(expr)) {
		int64_t v;
		if (fold_int(expr, v)) {
			out = { data_value::INTEGER, v, 0.0, {} };
			return true;
		}
	} else if (auto u = dynamic_cast<ast::unary const*>(expr)) {
		data_value v;
		if (!fold_data(u->operand.get(), v) || (v.kind == data_value::STRING)) {
			return false;
		}
		out = v;
		switch (u->kind) {
		case ast::unary::op::PLUS:
			return true;
		case ast::unary::op::NEGATE:
			out.i = int32_t(-v.i);
			out.f = -v.f;
			return true;
		case ast::unary::op::NOT:
			out = { data_value::INTEGER, ((v.kind == data_value::REAL) ? (v.f == 0.0) : (v.i == 0)) ? 1 : 0, 0.0, {} };
			return true;
		case ast::unary::op::COMPLEMENT:
			if (v.kind == data_value::REAL) {
				return false;
			}
			out.i = int32_t(~v.i);
			return true;
		}
	} else if (auto b = dynamic_cast<ast::binary const*>(expr)) {
		data_value l, r;
		if (!fold_data(b->lhs.get(), l) || !fold_data(b->rhs.get(), r)) {
			return false;
		}
		if ((l.kind == data_value::STRING) || (r.kind == data_value::STRING)) {
			// Strings can only be joined, and compared.
			if ((l.kind != r.kind) || ((b->kind != ast::binary::op::ADD) && (b->kind != ast::binary::op::EQUAL) && (b->kind != ast::binary::op::NOT_EQUAL))) {
				return false;
			}
			if (b->kind == ast::binary::op::ADD) {
				out = { data_value::STRING, 0, 0.0, l.s + r.s };
			} else {
				out = { data_value::INTEGER, ((l.s == r.s) == (b->kind == ast::binary::op::EQUAL)) ? 1 : 0, 0.0, {} };
			}
			return true;
		}
		bool    real = (l.kind == data_value::REAL) || (r.kind == data_value::REAL);
		double  lf   = (l.kind == data_value::REAL) ? l.f : double(l.i);
		double  rf   = (r.kind == data_value::REAL) ? r.f : double(r.i);
		int64_t li = int32_t(l.i), ri = int32_t(r.i);
		auto    number = [&](double f, int64_t i) { out = real ? data_value{ data_value::REAL, 0, f, {} } : data_value{ data_value::INTEGER, int32_t(i), 0.0, {} }; };
		auto    flag   = [&](bool v) { out = { data_value::INTEGER, v ? 1 : 0, 0.0, {} }; };
		switch (b->kind) {
		case ast::binary::op::ADD:
			number(lf + rf, li + ri);
			return true;
		case ast::binary::op::SUBTRACT:
			number(lf - rf, li - ri);
			return true;
		case ast::binary::op::MULTIPLY:
			number(lf * rf, li * ri);
			return true;
		case ast::binary::op::DIVIDE:
			if (real ? (rf == 0.0) : (ri == 0)) {
				return false;
			}
			number(lf / rf, li / ri);
			return true;
		case ast::binary::op::MODULO:
			if (real || (ri == 0)) {
				return false;
			}
			out = { data_value::INTEGER, int32_t(li % ri), 0.0, {} };
			return true;
		case ast::binary::op::POWER:
			out = { data_value::REAL, 0, std::pow(lf, rf), {} };
			return true;
		case ast::binary::op::SHL:
		case ast::binary::op::SHR:
		case ast::binary::op::SAR:
		case ast::binary::op::AND:
		case ast::binary::op::OR:
		case ast::binary::op::XOR: {
			if (real) {
				return false;
			}
			uint32_t lu = uint32_t(li), amount = uint32_t(ri) & 31;
			int32_t  v  = 0;
			switch (b->kind) {
			case ast::binary::op::SHL: v = int32_t(lu << amount); break;
			case ast::binary::op::SHR: v = int32_t(lu >> amount); break;
			case ast::binary::op::SAR: v = int32_t(li) >> amount; break;
			case ast::binary::op::AND: v = int32_t(li & ri); break;
			case ast::binary::op::OR: v = int32_t(li | ri); break;
			default: v = int32_t(li ^ ri); break;
			}
			out = { data_value::INTEGER, v, 0.0, {} };
			return true;
		}
		case ast::binary::op::EQUAL: flag(lf == rf); return true;
		case ast::binary::op::NOT_EQUAL: flag(lf != rf); return true;
		case ast::binary::op::LESS: flag(lf < rf); return true;
		case ast::binary::op::LESS_EQUAL: flag(lf <= rf); return true;
		case ast::binary::op::GREATER: flag(lf > rf); return true;
		case ast::binary::op::GREATER_EQUAL: flag(lf >= rf); return true;
		}
	}
	return false;
}

void blitz::compiler::collect_data(std::string const& scope, ast::block const& block)
{
	for (auto const& stmt : block) {
		if (auto data = dynamic_cast<ast::data_statement const*>(stmt.get())) {
			for (auto const& item : data->items) {
				// Only constants are allowed, which includes expressions of constants like `40 - 170`: the original folds those too.
				data_value value;
				if (!fold_data(item.get(), value)) {
					throw err(item->where, "Data expression must be constant.");
				}
				switch (value.kind) {
				case data_value::INTEGER:
					_data_items.push_back("{ i32 0, i64 " + std::to_string(value.i) + " }");
					break;
				case data_value::REAL: {
					uint64_t bits;
					memcpy(&bits, &value.f, sizeof(bits));
					_data_items.push_back("{ i32 1, i64 " + std::to_string((long long)bits) + " }");
					break;
				}
				case data_value::STRING:
					_data_items.push_back("{ i32 2, i64 ptrtoint (ptr " + string_constant(value.s) + " to i64) }");
					break;
				}
			}
		} else if (auto label = dynamic_cast<ast::label_statement const*>(stmt.get())) {
			_data_labels[scope + ":" + lower(label->name)] = _data_items.size();
		} else if (auto i = dynamic_cast<ast::if_statement const*>(stmt.get())) {
			for (auto const& b : i->branches) {
				collect_data(scope, b.body);
			}
		} else if (auto w = dynamic_cast<ast::while_statement const*>(stmt.get())) {
			collect_data(scope, w->body);
		} else if (auto r = dynamic_cast<ast::repeat_statement const*>(stmt.get())) {
			collect_data(scope, r->body);
		} else if (auto f = dynamic_cast<ast::for_statement const*>(stmt.get())) {
			collect_data(scope, f->body);
		} else if (auto sel = dynamic_cast<ast::select_statement const*>(stmt.get())) {
			for (auto const& c : sel->cases) {
				collect_data(scope, c.body);
			}
		}
	}
}

void blitz::compiler::gen_read(ast::read_statement const* node)
{
	std::string count = std::to_string(_data_items.size());
	for (auto const& target : node->targets) {
		auto addr = gen_address(target.get(), true);
		if (addr.count || (addr.type == type::STRUCT)) {
			throw err(target->where, "Read can only read numbers and strings.");
		}
		std::vector<value> args = { { "@bb.data", type::STRUCT }, { count, type::INT32 }, { "@bb.data.pos", type::STRUCT } };
		value              v;
		if (addr.type == type::STRING) {
			v = call_runtime("bb_data_string", type::STRING, args);
		} else if (blitz::types::is_real(addr.type)) {
			v = convert(call_runtime("bb_data_float", type::FLOAT32, args), addr.type, node->where, false);
		} else {
			v = convert(call_runtime("bb_data_int", type::INT32, args), addr.type, node->where, false);
		}
		store_value(addr, v);
	}
}

void blitz::compiler::gen_restore(ast::restore_statement const* node)
{
	size_t index = 0;
	if (!node->label.empty()) {
		// In a function the original looks for the label in the main program, where Data can be.
		auto it = _data_labels.find(":" + lower(node->label));
		if (it == _data_labels.end()) {
			it = _data_labels.find(_scope + ":" + lower(node->label));
		}
		if (it == _data_labels.end()) {
			throw err(node->where, "Label '" + node->label + "' does not exist.");
		}
		index = it->second;
	}
	emit("store i32 " + std::to_string(index) + ", ptr @bb.data.pos");
}
