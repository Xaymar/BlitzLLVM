// Arrays made with Dim are global, and know their size at run time.
blitz::compiler::variable* blitz::compiler::find_dim(std::string const& name)
{
	auto it = _arrays.find(lower(name));
	return (it != _arrays.end()) ? &it->second : nullptr;
}

// How many elements an array of the given upper bound has.
uint32_t blitz::compiler::array_count(ast::expression const* size, ast::location const& where)
{
	int64_t bound;
	if (!fold_int(size, bound) || (bound < 0) || (bound > 100000000)) {
		throw err(where, "The size of this array has to be a constant number, use Dim for others.");
	}
	return uint32_t(bound) + 1; // Like Dim, the upper bound is included.
}

blitz::compiler::address blitz::compiler::gen_dim_address(ast::call const* node)
{
	variable* var = find_dim(node->name);
	if (node->arguments.size() != var->dims) {
		throw err(node->where, "Array '" + node->name + "' has " + std::to_string(var->dims) + " dimensions, not " + std::to_string(node->arguments.size()) + ".");
	}

	auto field = [&](uint32_t index, const char* llvm_type) {
		auto p = tmp(), v = tmp();
		emit(p + " = getelementptr inbounds { ptr, i32, i32, i32, i32 }, ptr " + var->pointer + ", i32 0, i32 " + std::to_string(index));
		emit(v + " = load " + llvm_type + ", ptr " + p);
		return v;
	};

	std::string linear;
	for (uint32_t dim = 0; dim < var->dims; dim++) {
		auto index = convert(gen(node->arguments[dim].get()), type::INT32, node->arguments[dim]->where, true, std::string(), &node->arguments[dim]->covers);
		auto size  = field(dim + 1, "i32");
		auto out = tmp();
		emit(out + " = icmp uge i32 " + index.repr + ", " + size); // Unsigned, so that negative indices are caught too.
		guard(out, "Array index out of bounds.");

		auto wide = tmp();
		emit(wide + " = sext i32 " + index.repr + " to i64");
		if (dim == 0) {
			linear = wide;
		} else {
			auto wide_size = tmp(), scaled = tmp(), sum = tmp();
			emit(wide_size + " = sext i32 " + size + " to i64");
			emit(scaled + " = mul i64 " + linear + ", " + wide_size);
			emit(sum + " = add i64 " + scaled + ", " + wide);
			linear = sum;
		}
	}
	auto data = field(0, "ptr");
	auto p    = tmp();
	emit(p + " = getelementptr inbounds " + blitz::types::to_llvm(var->type) + ", ptr " + data + ", i64 " + linear);
	return { p, var->type, var->sname, 0, false };
}

void blitz::compiler::gen_dim(ast::dim_statement const* node)
{
	for (auto const& decl : node->arrays) {
		variable* var = find_dim(decl.name);
		if (!var) {
			throw err(decl.where, "'" + decl.name + "' is not an array.");
		}

		// Element size, without having to know the target.
		auto end = tmp(), size = tmp();
		emit(end + " = getelementptr " + blitz::types::to_llvm(var->type) + ", ptr null, i32 1");
		emit(size + " = ptrtoint ptr " + end + " to i64");

		std::vector<value> args = { { var->pointer, type::STRUCT }, { size, type::INT64 }, { std::to_string(decl.sizes.size()), type::INT32 } };
		for (uint32_t dim = 0; dim < 4; dim++) {
			if (dim < decl.sizes.size()) {
				args.push_back(convert(gen(decl.sizes[dim].get()), type::INT32, decl.sizes[dim]->where, true, std::string(), &decl.sizes[dim]->covers));
			} else {
				args.push_back({ "0", type::INT32 });
			}
		}
		if (var->type == type::STRING) {
			// What the strings of the old array owned is freed before it is made again.
			call_runtime("bb_dim_free_strings", type::UNKNOWN, { { var->pointer, type::STRUCT } });
		}
		call_runtime("bb_dim", type::UNKNOWN, args);
	}
}

////////////////////////////////////////////////////////////////////////////////
// Data
////////////////////////////////////////////////////////////////////////////////
void blitz::compiler::collect_data(std::string const& scope, ast::block const& block)
{
	for (auto const& stmt : block) {
		if (auto data = dynamic_cast<ast::data_statement const*>(stmt.get())) {
			for (auto const& item : data->items) {
				// Only constants are allowed, optionally negative.
				bool                  negative = false;
				ast::expression const* expr     = item.get();
				if (auto u = dynamic_cast<ast::unary const*>(expr)) {
					if ((u->kind == ast::unary::op::NEGATE) || (u->kind == ast::unary::op::PLUS)) {
						negative = (u->kind == ast::unary::op::NEGATE);
						expr     = u->operand.get();
					}
				}
				auto lit = dynamic_cast<ast::literal const*>(expr);
				if (!lit) {
					throw err(item->where, "Data can only contain constants.");
				}
				switch (lit->kind) {
				case ast::literal::variant::INTEGER:
					_data_items.push_back("{ i32 0, i64 " + std::to_string(negative ? -lit->i : lit->i) + " }");
					break;
				case ast::literal::variant::UNSIGNED_INTEGER:
					_data_items.push_back("{ i32 0, i64 " + std::to_string((long long)(negative ? -int64_t(lit->u) : int64_t(lit->u))) + " }");
					break;
				case ast::literal::variant::REAL: {
					double   d = negative ? -lit->f : lit->f;
					uint64_t bits;
					memcpy(&bits, &d, sizeof(bits));
					_data_items.push_back("{ i32 1, i64 " + std::to_string((long long)bits) + " }");
					break;
				}
				case ast::literal::variant::STRING:
					if (negative) {
						throw err(item->where, "Strings can't be negative.");
					}
					_data_items.push_back("{ i32 2, i64 ptrtoint (ptr " + string_constant(lit->text) + " to i64) }");
					break;
				default:
					throw err(item->where, "Data can only contain numbers and strings.");
				}
			}
		} else if (auto label = dynamic_cast<ast::label_statement const*>(stmt.get())) {
			_data_labels[scope + ":" + lower(label->name)] = _data_items.size();
		} else if (auto i = dynamic_cast<ast::if_statement const*>(stmt.get())) {
			for (auto const& b : i->branches) {
				collect_data(scope, b.body);
			}
		} else if (auto w = dynamic_cast<ast::while_statement const*>(stmt.get())) {
			collect_data(scope, w->body);
		} else if (auto r = dynamic_cast<ast::repeat_statement const*>(stmt.get())) {
			collect_data(scope, r->body);
		} else if (auto f = dynamic_cast<ast::for_statement const*>(stmt.get())) {
			collect_data(scope, f->body);
		} else if (auto sel = dynamic_cast<ast::select_statement const*>(stmt.get())) {
			for (auto const& c : sel->cases) {
				collect_data(scope, c.body);
			}
		}
	}
}

void blitz::compiler::gen_read(ast::read_statement const* node)
{
	std::string count = std::to_string(_data_items.size());
	for (auto const& target : node->targets) {
		auto addr = gen_address(target.get(), true);
		if (addr.count || (addr.type == type::STRUCT)) {
			throw err(target->where, "Read can only read numbers and strings.");
		}
		std::vector<value> args = { { "@bb.data", type::STRUCT }, { count, type::INT32 }, { "@bb.data.pos", type::STRUCT } };
		value              v;
		if (addr.type == type::STRING) {
			v = call_runtime("bb_data_string", type::STRING, args);
		} else if (blitz::types::is_real(addr.type)) {
			v = convert(call_runtime("bb_data_float", type::FLOAT32, args), addr.type, node->where, false);
		} else {
			v = convert(call_runtime("bb_data_int", type::INT32, args), addr.type, node->where, false);
		}
		store_value(addr, v);
	}
}

void blitz::compiler::gen_restore(ast::restore_statement const* node)
{
	size_t index = 0;
	if (!node->label.empty()) {
		auto it = _data_labels.find(_scope + ":" + lower(node->label));
		if (it == _data_labels.end()) {
			throw err(node->where, "Label '" + node->label + "' does not exist in this function.");
		}
		index = it->second;
	}
	emit("store i32 " + std::to_string(index) + ", ptr @bb.data.pos");
}
