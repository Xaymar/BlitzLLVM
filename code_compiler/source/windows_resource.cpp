	std::string windows_manifest()
	{
		// The programs draw their own pixels, so Windows must not scale them: per monitor v2 (Windows 10 1703 and later), with
		// "true/pm" as what older systems understand. The compatibility entries keep Windows from applying the shims of old
		// programs. Not set is the UTF-8 code page, which would change how the file names of the program are read.
		return "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\r\n"
			   "<assembly xmlns=\"urn:schemas-microsoft-com:asm.v1\" manifestVersion=\"1.0\">\r\n"
			   "  <compatibility xmlns=\"urn:schemas-microsoft-com:compatibility.v1\">\r\n"
			   "    <application>\r\n"
			   "      <supportedOS Id=\"{35138b9a-5d96-4fbd-8e2d-a2440225f93a}\"/>\r\n" // Windows 7
			   "      <supportedOS Id=\"{4a2f28e3-53b9-4441-ba9c-d69d4a4a6e38}\"/>\r\n" // Windows 8
			   "      <supportedOS Id=\"{1f676c76-80e1-4239-95bb-83d0f6d0da78}\"/>\r\n" // Windows 8.1
			   "      <supportedOS Id=\"{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}\"/>\r\n" // Windows 10 and 11
			   "    </application>\r\n"
			   "  </compatibility>\r\n"
			   "  <application xmlns=\"urn:schemas-microsoft-com:asm.v3\">\r\n"
			   "    <windowsSettings>\r\n"
			   "      <dpiAware xmlns=\"http://schemas.microsoft.com/SMI/2005/WindowsSettings\">true/pm</dpiAware>\r\n"
			   "      <dpiAwareness xmlns=\"http://schemas.microsoft.com/SMI/2016/WindowsSettings\">PerMonitorV2,PerMonitor</dpiAwareness>\r\n"
			   "      <longPathAware xmlns=\"http://schemas.microsoft.com/SMI/2016/WindowsSettings\">true</longPathAware>\r\n"
			   "    </windowsSettings>\r\n"
			   "  </application>\r\n"
			   "</assembly>\r\n";
	}

	namespace {
		void put32(std::string& out, uint32_t value)
		{
			for (int i = 0; i < 4; i++) {
				out.push_back(char((value >> (8 * i)) & 0xFF));
			}
		}

		void put16(std::string& out, uint16_t value)
		{
			out.push_back(char(value & 0xFF));
			out.push_back(char(value >> 8));
		}

		// One entry of a .res file with a numeric type and name, in the language neutral.
		void put_resource(std::string& out, uint16_t type, uint16_t name, std::string const& data, uint16_t flags)
		{
			put32(out, uint32_t(data.size()));
			put32(out, 32); // Size of this header.
			put16(out, 0xFFFF);
			put16(out, type);
			put16(out, 0xFFFF);
			put16(out, name);
			put32(out, 0);      // Data version
			put16(out, flags);  // Memory flags
			put16(out, 0);      // Language: neutral
			put32(out, 0);      // Version
			put32(out, 0);      // Characteristics
			out += data;
			while (out.size() % 4) {
				out.push_back('\0');
			}
		}
	} // namespace

	std::string windows_manifest_resource()
	{
		std::string out;
		put_resource(out, 0, 0, std::string(), 0); // The empty entry that marks the file as a 32-bit resource file.
		put_resource(out, 24, 1, windows_manifest(), 0x1030); // RT_MANIFEST, CREATEPROCESS_MANIFEST_RESOURCE_ID, moveable, pure, discardable
		return out;
	}
