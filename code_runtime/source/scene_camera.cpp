// Cameras, lights and fog.

#include "scene_internal.hpp"

using namespace bb;
using namespace bb::scene;

extern "C" {

// Cameras
void bb_camera_cls_color(int32_t handle, float r, float g, float b)
{
	entity* e = need_kind(handle, CAMERA, "CameraClsColor");
	e->cam_color[0] = clamp255(r);
	e->cam_color[1] = clamp255(g);
	e->cam_color[2] = clamp255(b);
}

void bb_camera_cls_mode(int32_t handle, int32_t color, int32_t depth)
{
	entity* e = need_kind(handle, CAMERA, "CameraClsMode");
	e->cam_clear_color = color != 0;
	e->cam_clear_depth = depth != 0;
}

void bb_camera_range(int32_t handle, float near_plane, float far_plane)
{
	entity* e = need_kind(handle, CAMERA, "CameraRange");
	if ((near_plane <= 0) || (far_plane <= near_plane)) {
		bb_runtime_error("CameraRange: needs 0 < near < far.");
		exit(1);
	}
	e->cam_near = near_plane;
	e->cam_far  = far_plane;
}

void bb_camera_viewport(int32_t handle, int32_t x, int32_t y, int32_t w, int32_t h)
{
	entity* e = need_kind(handle, CAMERA, "CameraViewport");
	e->cam_viewport[0] = x;
	e->cam_viewport[1] = y;
	e->cam_viewport[2] = w;
	e->cam_viewport[3] = h;
}

void bb_camera_zoom(int32_t handle, float zoom)
{
	entity* e = need_kind(handle, CAMERA, "CameraZoom");
	e->cam_zoom = zoom > 0.001f ? zoom : 0.001f;
}

void bb_camera_proj_mode(int32_t handle, int32_t mode)
{
	need_kind(handle, CAMERA, "CameraProjMode")->cam_projection = mode == 0 ? 0 : (mode == 2 ? 2 : 1);
}

// Lights
void bb_light_color(int32_t handle, float r, float g, float b)
{
	entity* e = need_kind(handle, LIGHT, "LightColor");
	// Not limited to 0..255: a light with a negative color takes light away.
	e->light_color[0] = r / 255.0f;
	e->light_color[1] = g / 255.0f;
	e->light_color[2] = b / 255.0f;
}

void bb_light_range(int32_t handle, float range)
{
	need_kind(handle, LIGHT, "LightRange")->light_range = range;
}

// Camera fog.
void bb_camera_fog_mode(int32_t handle, int32_t mode)
{
	need_kind(handle, CAMERA, "CameraFogMode")->fog_mode = mode ? 1 : 0;
}

void bb_camera_fog_range(int32_t handle, float near_distance, float far_distance)
{
	entity* e   = need_kind(handle, CAMERA, "CameraFogRange");
	e->fog_near = near_distance;
	e->fog_far  = far_distance;
}

void bb_camera_fog_color(int32_t handle, float r, float g, float b)
{
	entity* e = need_kind(handle, CAMERA, "CameraFogColor");
	e->fog_color[0] = clamp255(r);
	e->fog_color[1] = clamp255(g);
	e->fog_color[2] = clamp255(b);
}

// The cone of a spot light, which is stored: lights are drawn in all directions.
void bb_light_cone_angles(int32_t handle, float inner, float outer)
{
	entity* e = need_kind(handle, LIGHT, "LightConeAngles");
	inner     = inner < 0 ? 0 : (inner > 180 ? 180 : inner);
	outer     = outer < inner ? inner : (outer > 180 ? 180 : outer);
	e->light_cone[0] = inner;
	e->light_cone[1] = outer;
}
}
