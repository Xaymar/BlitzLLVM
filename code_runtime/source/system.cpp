namespace {
	// Without a window to show it in (and a person to answer) nothing is asked: the question is written to the error
	// output and answered with what is safe.
	bool can_ask()
	{
		return getenv("BLITZ_HEADLESS") == nullptr;
	}

	// Shows a message with buttons, and says which was pressed: the index in the list, or -1 for none.
	int ask(const char* title, const char* text, bool serious, const char* const* labels, int count)
	{
		// BLITZ_DIALOG_ANSWER=<n> presses the n-th button (counting from 0) without showing anything, for automated runs.
		if (const char* answer = getenv("BLITZ_DIALOG_ANSWER")) {
			fprintf(stderr, "%s: %s\n", title, text ? text : "");
			int pressed = atoi(answer);
			return ((pressed >= 0) && (pressed < count)) ? pressed : -1;
		}
		if (!can_ask()) {
			fprintf(stderr, "%s: %s\n", title, text ? text : "");
			return -1;
		}
		SDL_MessageBoxButtonData buttons[3] = {};
		for (int i = 0; i < count; i++) {
			buttons[i].buttonID = i;
			buttons[i].text     = labels[i];
			buttons[i].flags    = (i == 0 ? SDL_MESSAGEBOX_BUTTON_RETURNKEY_DEFAULT : 0) | (i == count - 1 ? SDL_MESSAGEBOX_BUTTON_ESCAPEKEY_DEFAULT : 0);
		}
		SDL_MessageBoxData box = {};
		box.flags              = serious ? SDL_MESSAGEBOX_ERROR : SDL_MESSAGEBOX_INFORMATION;
		box.title              = title;
		box.message            = text ? text : "";
		box.numbuttons         = count;
		box.buttons            = buttons;
		int pressed            = -1;
		if (!SDL_ShowMessageBox(&box, &pressed)) {
			return -1;
		}
		return pressed;
	}
} // namespace

