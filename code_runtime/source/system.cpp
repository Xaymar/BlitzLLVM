// Tells something, with one button to close it.
void bb_notify(const char* text, int32_t serious)
{
	static const char* const labels[] = { "OK" };
	ask(serious ? "Error" : "Notice", text, serious != 0, labels, 1);
}

// Asks to go on or not. Gives 1 for going on, and 0 for stopping, which is also what it gives without a window.
int32_t bb_confirm(const char* text, int32_t serious)
{
	static const char* const labels[] = { "OK", "Cancel" };
	return ask(serious ? "Error" : "Confirm", text, serious != 0, labels, 2) == 0 ? 1 : 0;
}

// Asks yes or no, and can be cancelled: 1 for yes, 0 for no and -1 for cancelling, which is also what it gives without
// a window.
int32_t bb_proceed(const char* text, int32_t serious)
{
	static const char* const labels[] = { "Yes", "No", "Cancel" };
	int                      pressed  = ask(serious ? "Error" : "Proceed", text, serious != 0, labels, 3);
	return pressed == 0 ? 1 : (pressed == 1 ? 0 : -1);
}

// Host (2), join (1) or neither (0), for StartNetGame.
int32_t bb_ask_net_game(void)
{
	static const char* const labels[] = { "Host", "Join", "Cancel" };
	int                      pressed  = ask("Multiplayer", "Host a game, or join one?", false, labels, 3);
	return pressed == 0 ? 2 : (pressed == 1 ? 1 : 0);
}

// Starts another program with the command, without waiting for it. Gives 1 if it started.
int32_t bb_create_process(const char* command)
{
	if (!command || !*command) {
		return 0;
	}
#if defined(_WIN32)
	char* line = static_cast<char*>(malloc(strlen(command) + 1));
	strcpy(line, command);
	STARTUPINFOA        startup = { sizeof(startup) };
	PROCESS_INFORMATION process = {};
	BOOL                started = CreateProcessA(nullptr, line, nullptr, nullptr, FALSE, 0, nullptr, nullptr, &startup, &process);
	free(line);
	if (!started) {
		return 0;
	}
	CloseHandle(process.hThread);
	CloseHandle(process.hProcess);
	return 1;
#else
	pid_t child = fork();
	if (child < 0) {
		return 0;
	}
	if (child == 0) {
		// Twice, so that nobody has to wait for the program to be done with.
		if (fork() == 0) {
			execl("/bin/sh", "sh", "-c", command, static_cast<char*>(nullptr));
		}
		_exit(0);
	}
	int status;
	waitpid(child, &status, 0);
	return 1;
#endif
}

// How many things the program has made that it has not freed yet: banks, streams, images, textures, fonts, sounds,
// timers and objects of its own types.
int32_t bb_active_objects(void)
{
	return bb_live_banks() + bb_live_streams() + bb_live_sounds() + bb_live_images() + bb_live_textures() + bb_live_fonts()
	     + bb_live_timers() + bb_live_objects();
}

// Writes how many of each there are to the debug log.
void bb_debug_objects(void)
{
	struct row {
		const char* name;
		int32_t     count;
	} rows[] = {
		{ "Banks", bb_live_banks() },
		{ "Streams", bb_live_streams() },
		{ "Sounds", bb_live_sounds() },
		{ "Images", bb_live_images() },
		{ "Textures", bb_live_textures() },
		{ "Fonts", bb_live_fonts() },
		{ "Timers", bb_live_timers() },
		{ "Objects", bb_live_objects() },
	};
	bb_debug_log("Object type                   Count");
	for (const row& r : rows) {
		char line[96];
		snprintf(line, sizeof(line), "%-28s %d", r.name, int(r.count));
		bb_debug_log(line);
	}
}

