void bb_name_entity(int32_t handle, const char* name)
{
	entity* e = need(handle, "NameEntity");
	bb_free(e->name);
	size_t length = name ? strlen(name) : 0;
	e->name       = static_cast<char*>(bb_malloc(length + 1));
	memcpy(e->name, name ? name : "", length + 1);
}

const char* bb_entity_name(int32_t handle)
{
	entity*     e      = need(handle, "EntityName");
	const char* name   = e->name ? e->name : "";
	size_t      length = strlen(name);
	return bb_copy(name, length); // A copy: the name can be changed while the program has this.
}

// Looks for a child (or a child of a child, and so on) with the name.
int32_t bb_find_child(int32_t parent, const char* name)
{
	need(parent, "FindChild");
	for (int child = get_entity_raw(parent)->first_child; child; child = get_entity_raw(child)->next_sibling) {
		entity* e = get_entity_raw(child);
		if (e->name && name && same_name(e->name, name)) {
			return child;
		}
		int32_t found = bb_find_child(child, name);
		if (found) {
			return found;
		}
	}
	return 0;
}

