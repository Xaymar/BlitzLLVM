void bb_entity_texture(int32_t handle, int32_t texture, int32_t frame, int32_t index)
{
	entity* e = need(handle, "EntityTexture");
	if (texture && !bb_texture_exists(texture)) { // A 0 takes the texture off.
		BB_DEBUG_HANDLE_MISSING("EntityTexture", "texture", texture);
	}
	if (texture && (frame > 0)) {
		texture |= frame << texture_frame_shift;
	}
	if (index == 0) {
		e->texture = texture;
	} else if ((index > 0) && (index < 8)) {
		e->layers[index - 1] = texture;
	}
}

float bb_entity_distance(int32_t a, int32_t b)
{
	need(a, "EntityDistance");
	need(b, "EntityDistance");
	float ma[16], mb[16];
	world_matrix(a, ma);
	world_matrix(b, mb);
	float dx = ma[12] - mb[12], dy = ma[13] - mb[13], dz = ma[14] - mb[14];
	return sqrtf(dx * dx + dy * dy + dz * dz);
}

void bb_point_entity(int32_t handle, int32_t target, float roll)
{
	entity* e = need_moving(handle, "PointEntity");
	need(target, "PointEntity");
	float me[16], mt[16];
	world_matrix(handle, me);
	world_matrix(target, mt);
	float d[3] = { mt[12] - me[12], mt[13] - me[13], mt[14] - me[14] };
	float len  = sqrtf(d[0] * d[0] + d[1] * d[1] + d[2] * d[2]);
	if (len < 1e-9f) {
		return;
	}
	float pitch = deg(asinf(-d[1] / len)), yaw = deg(atan2f(-d[0], d[2]));
	(void)e;
	bb_rotate_entity(handle, pitch, yaw, roll, 1);
}

