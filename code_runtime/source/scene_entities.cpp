	[[noreturn]] void fail(const char* what, int handle)
	{
		char buffer[128];
		snprintf(buffer, sizeof(buffer), "%s: entity or surface %d does not exist.", what, handle);
		bb_runtime_error(buffer);
		exit(1);
	}

	entity* need(int handle, const char* what)
	{
		entity* e = get_entity(handle);
		if (!e) {
			fail(what, handle);
		}
		entity_moved(handle); // Whatever asks for an entity may change it, and the grid must look at it again.
		return e;
	}

	entity* need_moving(int handle, const char* what)
	{
		entity* e = need(handle, what);
		if (e->static_mode > 0) {
			e->static_mode = 0; // It was not static after all.
		}
		return e;
	}

	entity* need_kind(int handle, int kind, const char* what)
	{
		entity* e = need(handle, what);
		if (e->kind != kind) {
			char buffer[128];
			snprintf(buffer, sizeof(buffer), "%s: entity %d is not the right kind of entity.", what, handle);
			bb_runtime_error(buffer);
			exit(1);
		}
		return e;
	}

	surface* need_surface(int handle, const char* what)
	{
		if ((handle < 1) || (uint32_t(handle) > surface_table.size) || !surface_table[uint32_t(handle) - 1]) {
			fail(what, handle);
		}
		return surface_table[uint32_t(handle) - 1];
	}

	int add_entity(int kind, int parent)
	{
		entity* e = new entity();
		e->kind   = kind;
		if (parent) {
			need(parent, "CreateEntity");
			e->parent = parent;
		}
		int handle = 0;
		// Every slot below first_free is taken, so a program that makes a million entities does not walk over them all each time.
		for (uint32_t i = first_free; i < entities.size; i++) {
			if (!entities[i]) {
				entities[i]     = e;
				entity_kinds[i] = uint8_t(kind + 1);
				cull_records[i].epoch = 0;
				first_free      = i + 1;
				grid_entity_added(int(i) + 1, kind);
				handle = int(i) + 1;
				break;
			}
		}
		if (!handle) {
			first_free = entities.size + 1;
			entities.push(e);
			entity_kinds.push(uint8_t(kind + 1));
			cull_records.push(cull_record{});
			grid_entity_added(int(entities.size), kind);
			handle = int(entities.size);
		}
		if (parent) {
			link_child(handle);
		}
		return handle;
	}

	// An entity lets go of a surface: it is gone once the last entity that has it is.
	static void release_surface(surface* s)
	{
		if (--s->refs > 0) {
			return;
		}
		for (uint32_t i = 0; i < surface_table.size; i++) {
			if (surface_table[i] == s) {
				surface_table[i] = nullptr;
			}
		}
		bb_release_surface_gpu(s->gpu);
		if (s->skin) {
			destroy_skin(s->skin);
		}
		s->vertices.release();
		s->indices.release();
		delete s;
	}

	int surface_handle(surface* s)
	{
		for (uint32_t i = 0; i < surface_table.size; i++) {
			if (surface_table[i] == s) {
				return int(i) + 1;
			}
		}
		surface_table.push(s);
		return int(surface_table.size);
	}

	static void destroy_entity(int handle)
	{
		entity* e = get_entity_raw(handle); // A model that is still being parsed is dropped, not waited for.
		if (!e) {
			return;
		}
		// Children go with their parent, and each one takes itself out of the list.
		while (e->first_child) {
			destroy_entity(e->first_child);
		}
		if (e->parent) {
			unlink_child(handle);
		}
		for (uint32_t i = 0; i < e->surfaces.size; i++) {
			release_surface(e->surfaces[i]);
		}
		e->surfaces.release();
		if (e->plane_draw) {
			release_surface(e->plane_draw);
		}
		if (e->loading) {
			destroy_model_load(e->loading, handle);
		}
		if (e->anim) {
			destroy_animation(e->anim);
		}
		if (e->md2) {
			destroy_md2(e->md2);
		}
		if (e->pending_keys) {
			destroy_pending_keys(e->pending_keys);
		}
		if (e->terrain) {
			bb_free(e->terrain->heights);
			delete e->terrain;
		}
		bb_free(e->name);
		grid_entity_removed(handle, e->kind);
		delete e;
		entities[uint32_t(handle) - 1]     = nullptr;
		entity_kinds[uint32_t(handle) - 1] = 0;
		cull_records[uint32_t(handle) - 1].epoch = 0;
		if (uint32_t(handle) - 1 < first_free) {
			first_free = uint32_t(handle) - 1;
		}
	}
	float clamp255(float v)
	{
		return (v < 0 ? 0 : (v > 255 ? 255 : v)) / 255.0f;
	}

	static float entity_axis(int32_t handle, int axis, int32_t global, const char* what)
	{
		entity* e = need(handle, what);
		if (!global) {
			return e->position[axis];
		}
		float world[16];
		world_matrix(handle, world);
		return world[12 + axis];
	}

	static float entity_angle(int32_t handle, int axis, int32_t global, const char* what)
	{
		entity* e = need(handle, what);
		if (!global) {
			return e->rotation[axis];
		}
		float world[16], angles[3];
		world_matrix(handle, world);
		euler_from_matrix_impl(world, angles);
		return angles[axis];
	}

	static bool same_name(const char* a, const char* b)
	{
		for (; *a && *b; a++, b++) {
			char x = (*a >= 'A' && *a <= 'Z') ? char(*a + 32) : *a, y = (*b >= 'A' && *b <= 'Z') ? char(*b + 32) : *b;
			if (x != y) {
				return false;
			}
		}
		return !*a && !*b;
	}

	static buffer<int> copy_was, copy_now;

	static int copy_entity(int source, int parent)
	{
		entity* from = get_entity(source);
		// The original has no copy of a camera, a light or a terrain: what it makes of them is a pivot in the same place.
		bool    plain  = from->kind == CAMERA || from->kind == LIGHT || from->terrain;
		int     handle = add_entity(plain ? PIVOT : from->kind, parent);
		entity* to     = get_entity(handle);
		copy_was.push(source);
		copy_now.push(handle);

		// Everything is copied over, except what owns memory.
		entity copy = *from;
		copy.kind   = plain ? PIVOT : from->kind;
		copy.parent = parent;
		copy.children = 0; // The children are copied below, which counts them.
		copy.first_child = copy.last_child = 0;
		copy.prev_sibling = to->prev_sibling; // Where add_entity put it in the children of its parent.
		copy.next_sibling = to->next_sibling;
		copy.name   = nullptr;
		copy.anim   = nullptr;
		copy.md2    = nullptr;
		copy.pending_keys = nullptr;
		copy.loading      = nullptr; // The copy of a model that came from a loader thread owns no part of that.
		copy.unresolved   = false;
		if (copy_was.size == 1) {
			copy.hidden = false; // The copy of a hidden model, which is how programs keep their templates, can be seen.
		}
		copy.plane_draw = nullptr; // Made again when it is drawn.
		copy.terrain = nullptr;
		copy.surfaces.data = nullptr;
		copy.surfaces.size = copy.surfaces.cap = 0;
		*to = copy;
		to->captured = false;
		reset_movement(handle); // It starts where it is, not where the original was at the last UpdateWorld.
		for (uint32_t i = 0; !plain && i < from->surfaces.size; i++) {
			surface* original = from->surfaces[i];
			if (original->skin || from->md2) {
				// The vertices of a skinned mesh follow the bones of this copy, and those of an .md2 model its frames, so
				// they can not be shared.
				surface* own = create_surface(handle);
				own->vertices.reserve(original->vertices.size);
				memcpy(own->vertices.data, original->vertices.data, original->vertices.size * sizeof(vertex3d));
				own->vertices.size = original->vertices.size;
				own->indices.reserve(original->indices.size);
				memcpy(own->indices.data, original->indices.data, original->indices.size * sizeof(uint32_t));
				own->indices.size = original->indices.size;
				own->painted = original->painted;
				own->paint   = original->paint;
				bb::surface_epoch++;
				own->skin    = original->skin ? clone_skin(*original->skin) : nullptr;
			} else {
				original->refs++; // Shares the geometry.
				to->surfaces.push(original);
			}
		}
		if (from->name) {
			size_t length = strlen(from->name);
			to->name      = static_cast<char*>(bb_malloc(length + 1));
			memcpy(to->name, from->name, length + 1);
		}

		// An entity without children is the common case, and finding children reads every entity: copying a million of them would read a million squared.
		buffer<int> kids;
		if (from->children > 0) {
			children_of(source, kids);
		}
		for (uint32_t i = 0; i < kids.size; i++) {
			if (kids[i] != handle) {
				copy_entity(kids[i], handle);
			}
		}
		kids.release();
		if (from->anim) {
			to->anim = clone_animation(*from->anim, copy_was, copy_now);
		}
		if (from->md2) {
			to->md2 = clone_md2(*from->md2);
		}
		return handle;
	}
