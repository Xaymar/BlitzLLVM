void bb_entity_parent(int32_t handle, int32_t parent, int32_t global)
{
	entity* e = need_moving(handle, "EntityParent");
	if (parent) {
		need(parent, "EntityParent");
		for (int p = parent; p; p = get_entity(p)->parent) {
			if (p == handle) {
				bb_runtime_error("EntityParent: an entity can't be the child of its own child.");
				exit(1);
			}
		}
	}
	float world[16];
	world_matrix(handle, world);
	if (e->parent != parent) {
		if (e->parent) {
			unlink_child(handle);
		}
		e->parent = parent;
		if (parent) {
			link_child(handle);
		}
	}
	if (global) {
		// Keep the position in the world.
		float p[3] = { world[12], world[13], world[14] };
		world_to_local_point(*e, p, e->position);
	}
}

