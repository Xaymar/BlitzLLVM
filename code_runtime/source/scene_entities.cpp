void bb_translate_entity(int32_t handle, float x, float y, float z, int32_t global)
{
	entity* e = need_moving(handle, "TranslateEntity");
	if (global) {
		float world[16];
		world_matrix(handle, world);
		float p[3] = { world[12] + x, world[13] + y, world[14] + z };
		world_to_local_point(*e, p, e->position);
	} else {
		e->position[0] += x;
		e->position[1] += y;
		e->position[2] += z;
	}
}

// Moves relative to where the entity is facing.
void bb_move_entity(int32_t handle, float x, float y, float z)
{
	entity* e = need_moving(handle, "MoveEntity");
	float   r[9];
	rotation_matrix(r, e->rotation);
	for (int row = 0; row < 3; row++) {
		e->position[row] += r[0 + row] * x + r[3 + row] * y + r[6 + row] * z;
	}
}

void bb_rotate_entity(int32_t handle, float pitch, float yaw, float roll, int32_t global)
{
	entity* e = need_moving(handle, "RotateEntity");
	if (global && e->parent) {
		// Rotation of the entity in the world: remove the parent's rotation.
		float pm[16], inv[16], local[16], r[9];
		parent_matrix(*e, pm);
		affine_inverse(pm, inv);
		float target[3] = { pitch, yaw, roll };
		rotation_matrix(r, target);
		float rot[16];
		mat_identity(rot);
		for (int c = 0; c < 3; c++) {
			for (int row = 0; row < 3; row++) {
				rot[c * 4 + row] = r[c * 3 + row];
			}
		}
		mat_multiply(local, inv, rot);
		euler_from_matrix_impl(local, e->rotation);
		return;
	}
	e->rotation[0] = pitch;
	e->rotation[1] = yaw;
	e->rotation[2] = roll;
}

void bb_turn_entity(int32_t handle, float pitch, float yaw, float roll, int32_t global)
{
	entity* e = need_moving(handle, "TurnEntity");
	if (global) {
		float world[16];
		world_matrix(handle, world);
		float current[3];
		euler_from_matrix_impl(world, current);
		bb_rotate_entity(handle, current[0] + pitch, current[1] + yaw, current[2] + roll, 1);
		return;
	}
	e->rotation[0] += pitch;
	e->rotation[1] += yaw;
	e->rotation[2] += roll;
}

void bb_scale_entity(int32_t handle, float x, float y, float z, int32_t global)
{
	entity* e = need_moving(handle, "ScaleEntity");
	if (e->terrain) {
		e->terrain->dirty = true; // Its normals depend on the scale.
	}
	float target[3] = { x, y, z };
	if (global) {
		// The scale in the world is that of all the parents multiplied with its own, so the entity has what is left.
		for (int p = e->parent; p;) {
			entity* parent = get_entity(p);
			if (!parent) {
				break;
			}
			for (int axis = 0; axis < 3; axis++) {
				target[axis] /= parent->scale[axis];
			}
			p = parent->parent;
		}
	}
	e->scale[0] = target[0];
	e->scale[1] = target[1];
	e->scale[2] = target[2];
}

