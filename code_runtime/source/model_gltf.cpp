	// glTF to Blitz3D
	////////////////////////////////////////////////////////////////////////////
	// A quaternion of glTF (x, y, z, w) as the model has it (w, x, y, z).
	void quaternion_in(const float* q, float* out)
	{
		out[0] = q[3];
		out[1] = -q[0];
		out[2] = q[1];
		out[3] = q[2];
	}

	// The position, scale and rotation of a node, from its matrix or its parts.
	void node_transform(const cgltf_node& node, float* pos, float* scale, float* rot)
	{
		float t[3] = { 0, 0, 0 }, s[3] = { 1, 1, 1 }, q[4] = { 0, 0, 0, 1 };
		if (node.has_matrix) {
			const float* m = node.matrix;
			t[0] = m[12];
			t[1] = m[13];
			t[2] = m[14];
			float col[3][3];
			for (int c = 0; c < 3; c++) {
				float len = sqrtf(m[c * 4] * m[c * 4] + m[c * 4 + 1] * m[c * 4 + 1] + m[c * 4 + 2] * m[c * 4 + 2]);
				s[c]      = len;
				for (int r = 0; r < 3; r++) {
					col[c][r] = len > 1e-12f ? m[c * 4 + r] / len : (c == r ? 1.0f : 0.0f);
				}
			}
			float det = col[0][0] * (col[1][1] * col[2][2] - col[1][2] * col[2][1]) - col[1][0] * (col[0][1] * col[2][2] - col[0][2] * col[2][1]) + col[2][0] * (col[0][1] * col[1][2] - col[0][2] * col[1][1]);
			if (det < 0) {
				s[0] = -s[0];
				for (int r = 0; r < 3; r++) {
					col[0][r] = -col[0][r];
				}
			}
			float r00 = col[0][0], r10 = col[0][1], r20 = col[0][2];
			float r01 = col[1][0], r11 = col[1][1], r21 = col[1][2];
			float r02 = col[2][0], r12 = col[2][1], r22 = col[2][2];
			float trace = r00 + r11 + r22;
			if (trace > 0) {
				float S = sqrtf(trace + 1) * 2;
				q[3] = 0.25f * S;
				q[0] = (r21 - r12) / S;
				q[1] = (r02 - r20) / S;
				q[2] = (r10 - r01) / S;
			} else if ((r00 > r11) && (r00 > r22)) {
				float S = sqrtf(1 + r00 - r11 - r22) * 2;
				q[3] = (r21 - r12) / S;
				q[0] = 0.25f * S;
				q[1] = (r01 + r10) / S;
				q[2] = (r02 + r20) / S;
			} else if (r11 > r22) {
				float S = sqrtf(1 + r11 - r00 - r22) * 2;
				q[3] = (r02 - r20) / S;
				q[0] = (r01 + r10) / S;
				q[1] = 0.25f * S;
				q[2] = (r12 + r21) / S;
			} else {
				float S = sqrtf(1 + r22 - r00 - r11) * 2;
				q[3] = (r10 - r01) / S;
				q[0] = (r02 + r20) / S;
				q[1] = (r12 + r21) / S;
				q[2] = 0.25f * S;
			}
		} else {
			if (node.has_translation) memcpy(t, node.translation, sizeof(t));
			if (node.has_scale) memcpy(s, node.scale, sizeof(s));
			if (node.has_rotation) memcpy(q, node.rotation, sizeof(q));
		}
		float len = sqrtf(q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]);
		if (len > 1e-12f) {
			for (float& c : q) c /= len;
		} else {
			q[0] = q[1] = q[2] = 0;
			q[3]               = 1;
		}
		pos[0] = -t[0];
		pos[1] = t[1];
		pos[2] = t[2];
		memcpy(scale, s, sizeof(s));
		quaternion_in(q, rot);
	}

