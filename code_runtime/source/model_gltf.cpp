	struct jv {
		enum kind_t : uint8_t { none, boolean, number, string, array, object };
		kind_t                                 kind   = none;
		bool                                   flag   = false;
		double                                 value  = 0;
		std::string                            text;
		std::vector<jv>                        items;
		std::vector<std::pair<std::string, jv>> members;

		const jv* get(const char* key) const
		{
			if (kind != object) {
				return nullptr;
			}
			for (auto const& m : members) {
				if (m.first == key) {
					return &m.second;
				}
			}
			return nullptr;
		}

		const jv* at(size_t index) const
		{
			return (kind == array && index < items.size()) ? &items[index] : nullptr;
		}

		size_t count() const
		{
			return kind == array ? items.size() : 0;
		}
	};

	struct json_reader {
		const char* p;
		const char* end;

		void space()
		{
			while ((p < end) && ((*p == ' ') || (*p == '\t') || (*p == '\n') || (*p == '\r'))) {
				p++;
			}
		}

		static void utf8(std::string& out, uint32_t c)
		{
			if (c < 0x80) {
				out += char(c);
			} else if (c < 0x800) {
				out += char(0xC0 | (c >> 6));
				out += char(0x80 | (c & 63));
			} else if (c < 0x10000) {
				out += char(0xE0 | (c >> 12));
				out += char(0x80 | ((c >> 6) & 63));
				out += char(0x80 | (c & 63));
			} else {
				out += char(0xF0 | (c >> 18));
				out += char(0x80 | ((c >> 12) & 63));
				out += char(0x80 | ((c >> 6) & 63));
				out += char(0x80 | (c & 63));
			}
		}

		bool hex4(uint32_t& out)
		{
			if (end - p < 4) {
				return false;
			}
			out = 0;
			for (int i = 0; i < 4; i++) {
				char c = *p++;
				out <<= 4;
				if ((c >= '0') && (c <= '9')) {
					out |= uint32_t(c - '0');
				} else if ((c >= 'a') && (c <= 'f')) {
					out |= uint32_t(c - 'a' + 10);
				} else if ((c >= 'A') && (c <= 'F')) {
					out |= uint32_t(c - 'A' + 10);
				} else {
					return false;
				}
			}
			return true;
		}

		bool string_value(std::string& out)
		{
			if ((p >= end) || (*p != '"')) {
				return false;
			}
			p++;
			while (p < end) {
				char c = *p++;
				if (c == '"') {
					return true;
				}
				if (c != '\\') {
					out += c;
					continue;
				}
				if (p >= end) {
					return false;
				}
				c = *p++;
				switch (c) {
				case 'n': out += '\n'; break;
				case 't': out += '\t'; break;
				case 'r': out += '\r'; break;
				case 'b': out += '\b'; break;
				case 'f': out += '\f'; break;
				case 'u': {
					uint32_t u;
					if (!hex4(u)) {
						return false;
					}
					if ((u >= 0xD800) && (u < 0xDC00) && (end - p >= 6) && (p[0] == '\\') && (p[1] == 'u')) {
						p += 2;
						uint32_t low;
						if (!hex4(low)) {
							return false;
						}
						u = 0x10000 + ((u - 0xD800) << 10) + (low - 0xDC00);
					}
					utf8(out, u);
					break;
				}
				default: out += c; break;
				}
			}
			return false;
		}

		bool value(jv& out, int depth)
		{
			if (depth > 64) {
				return false;
			}
			space();
			if (p >= end) {
				return false;
			}
			char c = *p;
			if (c == '{') {
				p++;
				out.kind = jv::object;
				space();
				if ((p < end) && (*p == '}')) {
					p++;
					return true;
				}
				for (;;) {
					space();
					std::string key;
					if (!string_value(key)) {
						return false;
					}
					space();
					if ((p >= end) || (*p != ':')) {
						return false;
					}
					p++;
					out.members.emplace_back(std::move(key), jv());
					if (!value(out.members.back().second, depth + 1)) {
						return false;
					}
					space();
					if (p >= end) {
						return false;
					}
					if (*p == ',') {
						p++;
						continue;
					}
					if (*p == '}') {
						p++;
						return true;
					}
					return false;
				}
			}
			if (c == '[') {
				p++;
				out.kind = jv::array;
				space();
				if ((p < end) && (*p == ']')) {
					p++;
					return true;
				}
				for (;;) {
					out.items.emplace_back();
					if (!value(out.items.back(), depth + 1)) {
						return false;
					}
					space();
					if (p >= end) {
						return false;
					}
					if (*p == ',') {
						p++;
						continue;
					}
					if (*p == ']') {
						p++;
						return true;
					}
					return false;
				}
			}
			if (c == '"') {
				out.kind = jv::string;
				return string_value(out.text);
			}
			if ((end - p >= 4) && !memcmp(p, "true", 4)) {
				p += 4;
				out.kind = jv::boolean;
				out.flag = true;
				return true;
			}
			if ((end - p >= 5) && !memcmp(p, "false", 5)) {
				p += 5;
				out.kind = jv::boolean;
				return true;
			}
			if ((end - p >= 4) && !memcmp(p, "null", 4)) {
				p += 4;
				return true;
			}
			// A number. strtod needs a string that ends, and so does this copy of the characters that can be in one.
			const char* start = p;
			while ((p < end) && (((*p >= '0') && (*p <= '9')) || (*p == '-') || (*p == '+') || (*p == '.') || (*p == 'e') || (*p == 'E'))) {
				p++;
			}
			if (p == start) {
				return false;
			}
			std::string digits(start, p);
			char*       stop = nullptr;
			out.kind         = jv::number;
			out.value        = strtod(digits.c_str(), &stop);
			return stop && (*stop == 0);
		}
	};

	double num(const jv* v, double fallback)
	{
		return (v && (v->kind == jv::number)) ? v->value : fallback;
	}

	int integer(const jv* object, const char* key, int fallback)
	{
		if (!object) {
			return fallback;
		}
		const jv* v = object->get(key);
		return (v && (v->kind == jv::number) && (v->value >= -2147483648.0) && (v->value <= 2147483647.0)) ? int(v->value) : fallback;
	}

	float real(const jv* object, const char* key, float fallback)
	{
		return object ? float(num(object->get(key), fallback)) : fallback;
	}

	std::string text_of(const jv* object, const char* key)
	{
		const jv* v = object ? object->get(key) : nullptr;
		return (v && (v->kind == jv::string)) ? v->text : std::string();
	}

