// What b3d.cpp and model_3ds.cpp share: a model that was read from a file, as a tree of nodes with meshes, brushes and keys.
// The loaders of each file type fill it, and b3d.cpp builds the entities of it.
#pragma once
#include "animation_internal.hpp"
#include "memory.h"

namespace bb::models {
	struct reader {
		const uint8_t* data;
		size_t         size;
		size_t         pos;
		bool           failed;

		bool have(size_t count)
		{
			if (pos + count > size) {
				failed = true;
				return false;
			}
			return true;
		}

		int32_t read_int()
		{
			int32_t v = 0;
			if (have(4)) {
				memcpy(&v, data + pos, 4);
				pos += 4;
			}
			return v;
		}

		float read_float()
		{
			float v = 0;
			if (have(4)) {
				memcpy(&v, data + pos, 4);
				pos += 4;
			}
			return v;
		}

		// A string that ends with a zero byte.
		char* read_string()
		{
			size_t start = pos;
			while ((pos < size) && data[pos]) {
				pos++;
			}
			if (pos >= size) {
				failed = true;
				return nullptr;
			}
			size_t length = pos - start;
			char*  out    = static_cast<char*>(bb_malloc(length + 1));
			memcpy(out, data + start, length);
			out[length] = 0;
			pos++;
			return out;
		}
	};

	struct tex_info {
		char* name  = nullptr;
		int   flags = 0;
		int   handle = -1; // Loaded when it is first needed, 0 if that failed.
	};

	struct brush_info {
		float color[4]  = { 1, 1, 1, 1 };
		float shininess = 0;
		int   blend = 1, fx = 0;
		int   texture = -1;
	};

	struct vertex_info {
		float pos[3] = { 0, 0, 0 };
		float normal[3] = { 0, 0, 0 };
		float color[4]  = { 1, 1, 1, 1 };
		float uv[2]     = { 0, 0 };
		float uv2[2]    = { 0, 0 }; // The second set, the first if there is none.
	};

	struct triangle_group {
		int              brush = -1;
		buffer<uint32_t> indices;
	};

	struct node_info {
		char*  name = nullptr;
		int    parent = -1;
		float  pos[3] = { 0, 0, 0 }, scale[3] = { 1, 1, 1 }, rot[4] = { 1, 0, 0, 0 };
		bool   has_mesh = false, has_normals = true, is_bone = false;
		bool   hidden = false;
		int    light = 0;                   // 0 = not a light, otherwise the light type: 1 = directional, 2 = point, 3 = spot
		float  light_color[3] = { 1, 1, 1 };
		float  light_range    = 1000;
		float  light_cone[2]  = { 0, 90 };
		int    mesh_brush = -1;
		buffer<vertex_info>    vertices;
		buffer<triangle_group*> groups;
		buffer<int>            bone_vertex; // What a bone pulls on, and how hard.
		buffer<float>          bone_weight;
		buffer<key3>           pos_keys, scale_keys;
		buffer<key4>           rot_keys;
	};

	struct model {
		buffer<tex_info>   textures;
		buffer<brush_info> brushes;
		buffer<node_info*> nodes; // Parents before children.
		float              frames = 0, fps = 60;
		char*              directory = nullptr;

		~model() {}

		void release()
		{
			for (uint32_t i = 0; i < textures.size; i++) {
				bb_free(textures[i].name);
			}
			for (uint32_t i = 0; i < nodes.size; i++) {
				node_info* n = nodes[i];
				bb_free(n->name);
				n->vertices.release();
				for (uint32_t g = 0; g < n->groups.size; g++) {
					n->groups[g]->indices.release();
					delete n->groups[g];
				}
				n->groups.release();
				n->bone_vertex.release();
				n->bone_weight.release();
				n->pos_keys.release();
				n->scale_keys.release();
				n->rot_keys.release();
				delete n;
			}
			textures.release();
			brushes.release();
			nodes.release();
			bb_free(directory);
		}
	};
	/** Reads the 3D Studio model in the data into the model. False if it is not one. */
	bool read_3ds(const uint8_t* data, size_t size, model& m);
} // namespace bb::models
