// The direction of the hat in degrees, 0 is up, or -1 if it is in the middle or there is none.
int32_t bb_joy_hat(int32_t port)
{
	joystick* j = port_of(port);
	if (!j) {
		return 0;
	}
	if (SDL_GetNumJoystickHats(j->handle) < 1) {
		return -1;
	}
	Uint8 hat   = SDL_GetJoystickHat(j->handle, 0);
	bool  up    = hat & SDL_HAT_UP;
	bool  right = hat & SDL_HAT_RIGHT;
	bool  down  = hat & SDL_HAT_DOWN;
	bool  left  = hat & SDL_HAT_LEFT;
	if (up) {
		return right ? 45 : (left ? 315 : 0);
	} else if (down) {
		return right ? 135 : (left ? 225 : 180);
	}
	return right ? 90 : (left ? 270 : -1);
}

