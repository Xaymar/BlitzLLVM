static inline const char* bb_s(const char* s)
{
	return s ? s : "";
}

static inline char* bb_copy(const char* data, size_t length)
{
	char* mem = (char*)malloc(length + 1);
	if (!mem) {
		bb_runtime_error("Out of memory.");
	}
	memcpy(mem, data, length);
	mem[length] = 0;
	return mem;
}

