// Multiplayer games, with the functions of Blitz3D: one program hosts a game, the others join it, every program makes
// players, and messages go from a player to one player or to all of them.
//
// The original talks DirectPlay, which can not be used any more. Here the programs that join connect to the one that
// hosts with TCP, which passes the messages on. Games made here can only play with each other.
//
// The port is 40500, or what the environment variable BLITZLLVM_NETGAME_PORT says.

#include <stdint.h>
#include "memory.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "streams.h"
#include "runtime_internal.h"
#include "environment.h"

extern void    bb_runtime_error(const char* message);
extern int32_t bb_open_tcp_stream(const char* server, int32_t port, int32_t local_port);
extern void    bb_close_tcp_stream(int32_t handle);
extern int32_t bb_create_tcp_server(int32_t port);
extern void    bb_close_tcp_server(int32_t handle);
extern int32_t bb_accept_tcp_stream(int32_t server);
extern int32_t bb_millisecs(void);
extern void    bb_delay(int32_t ms);
extern int32_t bb_ask_net_game(void);

enum {
	FRAME_HELLO = 1,
	FRAME_CREATE,
	FRAME_DELETE,
	FRAME_MESSAGE,
	FRAME_WELCOME = 10,
	FRAME_REFUSED,
	FRAME_PLAYER_NEW,
	FRAME_CREATED,
	FRAME_PLAYER_GONE,
	FRAME_FORWARD,
};

enum {
	MESSAGE_NEW_PLAYER   = 100,
	MESSAGE_PLAYER_GONE  = 101,
	MESSAGE_SESSION_LOST = 200,
};

#define MAX_FRAME (16 * 1024 * 1024)

// What a program that has not said hello yet may send: the hello is only the name of the game. Anything bigger is not one of us, and the host
// would otherwise hold on to up to MAX_FRAME for each of the connections that are not even in the game.
#define MAX_FRAME_BEFORE_HELLO 4096

typedef struct bb_player {
	int32_t id;
	char*   name;
	int     remote;
	int     connection; // Which connection a remote player is behind, -1 for the players of this program.
} bb_player;

typedef struct bb_connection {
	int32_t  stream; // 0 if not used
	uint8_t* buffer;
	size_t   size, capacity;
	int      greeted;
} bb_connection;

typedef struct bb_message {
	int     type;
	int32_t from, to;
	char*   data;
	size_t  length;
} bb_message;

#define MAX_CONNECTIONS 32

static int           bb_net_started = 0, bb_net_host = 0;
static int32_t       bb_net_server = 0;
static char*         bb_net_game   = NULL;
static bb_connection bb_net_connections[MAX_CONNECTIONS];
static bb_player*    bb_net_players      = NULL;
static int           bb_net_player_count = 0;
static int32_t       bb_net_next_id      = 1;
static int32_t*      bb_net_new          = NULL; // Players that appeared, which RecvNetMsg tells about.
static int           bb_net_new_count    = 0;
static bb_message*   bb_net_inbox        = NULL;
static int           bb_net_inbox_count  = 0;
static int           bb_net_lost         = 0;
static int32_t       bb_net_created      = -1; // The reply to CreateNetPlayer.
static int32_t       bb_net_refused      = 0;

static int          bb_msg_type = 0;
static int32_t      bb_msg_from = 0, bb_msg_to = 0;
static char*        bb_msg_data = NULL;

static char* bb_net_copy(const char* data, size_t length)
{
	char* copy = (char*)bb_malloc(length + 1);
	if (!copy) {
		bb_runtime_error("Out of memory.");
	}
	memcpy(copy, data, length);
	copy[length] = 0;
	return copy;
}

static void bb_net_check(void)
{
	if (!bb_net_started) {
		bb_runtime_error("Multiplayer game not started");
	}
}

static bb_player* bb_net_find(int32_t id)
{
	for (int i = 0; i < bb_net_player_count; i++) {
		if (bb_net_players[i].id == id) {
			return &bb_net_players[i];
		}
	}
	return NULL;
}

static bb_player* bb_net_add_player(int32_t id, const char* name, size_t length, int remote, int connection)
{
	bb_net_players = (bb_player*)bb_realloc(bb_net_players, (size_t)(bb_net_player_count + 1) * sizeof(bb_player));
	bb_player* p   = &bb_net_players[bb_net_player_count++];
	p->id          = id;
	p->name        = bb_net_copy(name, length);
	p->remote      = remote;
	p->connection  = connection;
	if (remote) {
		bb_net_new = (int32_t*)bb_realloc(bb_net_new, (size_t)(bb_net_new_count + 1) * sizeof(int32_t));
		bb_net_new[bb_net_new_count++] = id;
	}
	return p;
}

static void bb_net_remove_player(int32_t id)
{
	for (int i = 0; i < bb_net_player_count; i++) {
		if (bb_net_players[i].id == id) {
			bb_free(bb_net_players[i].name);
			bb_net_players[i] = bb_net_players[--bb_net_player_count];
			break;
		}
	}
	// A player that nobody was told about has no news to tell.
	for (int i = 0; i < bb_net_new_count; i++) {
		if (bb_net_new[i] == id) {
			bb_net_new[i] = bb_net_new[--bb_net_new_count];
			break;
		}
	}
}

static void bb_net_push(int type, int32_t from, int32_t to, const char* data, size_t length)
{
	bb_net_inbox = (bb_message*)bb_realloc(bb_net_inbox, (size_t)(bb_net_inbox_count + 1) * sizeof(bb_message));
	bb_message* m = &bb_net_inbox[bb_net_inbox_count++];
	m->type       = type;
	m->from       = from;
	m->to         = to;
	m->data       = bb_net_copy(data ? data : "", length);
	m->length     = length;
}

static void put32(uint8_t* at, int32_t value)
{
	at[0] = (uint8_t)value;
	at[1] = (uint8_t)(value >> 8);
	at[2] = (uint8_t)(value >> 16);
	at[3] = (uint8_t)(value >> 24);
}

static int32_t get32(const uint8_t* at)
{
	return (int32_t)((uint32_t)at[0] | ((uint32_t)at[1] << 8) | ((uint32_t)at[2] << 16) | ((uint32_t)at[3] << 24));
}

static void bb_net_send(int connection, uint8_t kind, const uint8_t* payload, size_t length)
{
	bb_connection* c = &bb_net_connections[connection];
	if (!c->stream) {
		return;
	}
	uint8_t* frame = (uint8_t*)bb_malloc(length + 5);
	put32(frame, (int32_t)(length + 1));
	frame[4] = kind;
	if (length) {
		memcpy(frame + 5, payload, length);
	}
	bb_stream_write(bb_stream_get(c->stream, "SendNetMsg"), frame, length + 5);
	bb_free(frame);
}

static void bb_net_close_connection(int connection)
{
	bb_connection* c = &bb_net_connections[connection];
	if (c->stream) {
		bb_close_tcp_stream(c->stream);
	}
	bb_free(c->buffer);
	memset(c, 0, sizeof(*c));
}

static void bb_net_send_player(int connection, bb_player const* p)
{
	size_t   length = strlen(p->name);
	uint8_t* frame  = (uint8_t*)bb_malloc(length + 4);
	put32(frame, p->id);
	memcpy(frame + 4, p->name, length);
	bb_net_send(connection, FRAME_PLAYER_NEW, frame, length + 4);
	bb_free(frame);
}

// Frames go to every connection that has said hello, except the one that is named.
static void bb_net_broadcast(int except, uint8_t kind, const uint8_t* payload, size_t length)
{
	for (int i = 0; i < MAX_CONNECTIONS; i++) {
		if ((i != except) && bb_net_connections[i].stream && bb_net_connections[i].greeted) {
			bb_net_send(i, kind, payload, length);
		}
	}
}

static void bb_net_gone(int32_t id, int except)
{
	uint8_t frame[4];
	put32(frame, id);
	bb_net_remove_player(id);
	bb_net_broadcast(except, FRAME_PLAYER_GONE, frame, 4);
	bb_net_push(MESSAGE_PLAYER_GONE, id, 0, NULL, 0);
}

// A message that came from a player behind a connection, which goes on to who it is for.
static void bb_net_route(int from_connection, const uint8_t* payload, size_t length)
{
	if (length < 9) {
		return;
	}
	int32_t     from = get32(payload), to = get32(payload + 4);
	bb_player*  sender = bb_net_find(from);
	if (!sender || (sender->connection != from_connection)) {
		return;
	}
	if (to == 0) {
		bb_net_push(payload[8], from, to, (const char*)payload + 9, length - 9);
		for (int i = 0; i < MAX_CONNECTIONS; i++) {
			if ((i != from_connection) && bb_net_connections[i].stream && bb_net_connections[i].greeted) {
				bb_net_send(i, FRAME_FORWARD, payload, length);
			}
		}
		return;
	}
	bb_player* target = bb_net_find(to);
	if (!target) {
		return;
	}
	if (target->connection < 0) {
		bb_net_push(payload[8], from, to, (const char*)payload + 9, length - 9);
	} else if (target->connection != from_connection) {
		bb_net_send(target->connection, FRAME_FORWARD, payload, length);
	}
}

// What the host does with a frame from one of the programs that joined.
static void bb_net_host_frame(int connection, uint8_t kind, const uint8_t* payload, size_t length)
{
	bb_connection* c = &bb_net_connections[connection];
	if (!c->greeted) {
		if ((kind == FRAME_HELLO) && bb_net_game && (length == strlen(bb_net_game)) && !memcmp(payload, bb_net_game, length)) {
			c->greeted = 1;
			bb_net_send(connection, FRAME_WELCOME, NULL, 0);
			for (int i = 0; i < bb_net_player_count; i++) {
				bb_net_send_player(connection, &bb_net_players[i]);
			}
		} else {
			bb_net_send(connection, FRAME_REFUSED, NULL, 0);
			bb_net_close_connection(connection);
		}
		return;
	}
	switch (kind) {
	case FRAME_CREATE: {
		int32_t    id = bb_net_next_id++;
		bb_player* p  = bb_net_add_player(id, (const char*)payload, length, 1, connection);
		uint8_t    reply[4];
		put32(reply, id);
		bb_net_send(connection, FRAME_CREATED, reply, 4);
		for (int i = 0; i < MAX_CONNECTIONS; i++) {
			if ((i != connection) && bb_net_connections[i].stream && bb_net_connections[i].greeted) {
				bb_net_send_player(i, p);
			}
		}
		break;
	}
	case FRAME_DELETE: {
		if (length >= 4) {
			bb_player* p = bb_net_find(get32(payload));
			if (p && (p->connection == connection)) {
				bb_net_gone(p->id, connection);
			}
		}
		break;
	}
	case FRAME_MESSAGE:
		bb_net_route(connection, payload, length);
		break;
	default:
		break;
	}
}

// What a program that joined does with a frame from the host.
static void bb_net_client_frame(uint8_t kind, const uint8_t* payload, size_t length)
{
	switch (kind) {
	case FRAME_WELCOME:
		bb_net_connections[0].greeted = 1;
		break;
	case FRAME_REFUSED:
		bb_net_refused = 1;
		break;
	case FRAME_PLAYER_NEW:
		if ((length >= 4) && !bb_net_find(get32(payload))) {
			bb_net_add_player(get32(payload), (const char*)payload + 4, length - 4, 1, 0);
		}
		break;
	case FRAME_CREATED:
		if (length >= 4) {
			bb_net_created = get32(payload);
		}
		break;
	case FRAME_PLAYER_GONE:
		if ((length >= 4) && bb_net_find(get32(payload))) {
			int32_t id = get32(payload);
			bb_net_remove_player(id);
			bb_net_push(MESSAGE_PLAYER_GONE, id, 0, NULL, 0);
		}
		break;
	case FRAME_FORWARD:
		if (length >= 9) {
			bb_net_push(payload[8], get32(payload), get32(payload + 4), (const char*)payload + 9, length - 9);
		}
		break;
	default:
		break;
	}
}

// Takes in what arrived, and does something about it. Gives 0 if the connection was closed.
static int bb_net_read(int connection)
{
	bb_connection* c      = &bb_net_connections[connection];
	bb_stream*     stream = bb_stream_get(c->stream, "RecvNetMsg");
	int            alive  = 1;
	for (;;) {
		int32_t available = bb_stream_available(stream);
		if (available <= 0) {
			if (bb_stream_eof(stream)) {
				alive = 0;
			}
			break;
		}
		if (bb_net_host && !c->greeted && (c->size + (size_t)available > MAX_FRAME_BEFORE_HELLO + 4)) {
			alive = 0; // That is not a hello.
			break;
		}
		if (c->size + (size_t)available > c->capacity) {
			c->capacity = (c->size + (size_t)available) * 2;
			c->buffer   = (uint8_t*)bb_realloc(c->buffer, c->capacity);
		}
		size_t got = bb_stream_read(stream, c->buffer + c->size, (size_t)available);
		if (got == 0) {
			alive = 0;
			break;
		}
		c->size += got;
	}
	// Whole frames only.
	size_t used = 0;
	while (c->size - used >= 5) {
		int32_t length = get32(c->buffer + used);
		if ((length < 1) || (length > MAX_FRAME) || (bb_net_host && !c->greeted && (length > MAX_FRAME_BEFORE_HELLO))) {
			alive = 0; // That is not one of us.
			break;
		}
		if (c->size - used < (size_t)length + 4) {
			break;
		}
		uint8_t kind = c->buffer[used + 4];
		// The frame is copied: handling it can close the connection and its buffer.
		size_t   payload_length = (size_t)length - 1;
		uint8_t* payload        = (uint8_t*)bb_malloc(payload_length + 1);
		memcpy(payload, c->buffer + used + 5, payload_length);
		used += (size_t)length + 4;
		if (bb_net_host) {
			bb_net_host_frame(connection, kind, payload, payload_length);
		} else {
			bb_net_client_frame(kind, payload, payload_length);
		}
		bb_free(payload);
		if (!c->stream) {
			return 1; // Closed while it was handled.
		}
	}
	if (used) {
		memmove(c->buffer, c->buffer + used, c->size - used);
		c->size -= used;
	}
	return alive;
}

// Everything that can happen without the program asking: new programs, frames, and programs that are gone.
static void bb_net_poll(void)
{
	if (!bb_net_started) {
		return;
	}
	if (bb_net_host) {
		int32_t stream;
		while ((stream = bb_accept_tcp_stream(bb_net_server)) != 0) {
			int slot = -1;
			for (int i = 0; i < MAX_CONNECTIONS; i++) {
				if (!bb_net_connections[i].stream) {
					slot = i;
					break;
				}
			}
			if (slot < 0) {
				bb_close_tcp_stream(stream);
			} else {
				memset(&bb_net_connections[slot], 0, sizeof(bb_connection));
				bb_net_connections[slot].stream = stream;
			}
		}
	}
	for (int i = 0; i < MAX_CONNECTIONS; i++) {
		if (!bb_net_connections[i].stream) {
			continue;
		}
		if (!bb_net_read(i)) {
			if (bb_net_host) {
				// Its players are gone with it.
				for (int p = bb_net_player_count - 1; p >= 0; p--) {
					if (bb_net_players[p].connection == i) {
						bb_net_gone(bb_net_players[p].id, i);
					}
				}
			} else {
				bb_net_lost = 1;
			}
			bb_net_close_connection(i);
		}
	}
}

static void bb_net_reset(void)
{
	for (int i = 0; i < MAX_CONNECTIONS; i++) {
		if (bb_net_connections[i].stream) {
			bb_net_close_connection(i);
		}
	}
	if (bb_net_server) {
		bb_close_tcp_server(bb_net_server);
	}
	for (int i = 0; i < bb_net_player_count; i++) {
		bb_free(bb_net_players[i].name);
	}
	for (int i = 0; i < bb_net_inbox_count; i++) {
		bb_free(bb_net_inbox[i].data);
	}
	bb_free(bb_net_players);
	bb_free(bb_net_new);
	bb_free(bb_net_inbox);
	bb_free(bb_net_game);
	bb_net_players = NULL;
	bb_net_new     = NULL;
	bb_net_inbox   = NULL;
	bb_net_game    = NULL;
	bb_net_player_count = bb_net_new_count = bb_net_inbox_count = 0;
	bb_net_server  = 0;
	bb_net_started = bb_net_host = 0;
	bb_net_lost    = 0;
	bb_net_next_id = 1;
	bb_str_free(bb_msg_data);
	bb_msg_data = NULL;
	bb_msg_type = 0;
}

static int32_t bb_net_port(void)
{
	int32_t port = bb_env_int("BLITZLLVM_NETGAME_PORT", 0);
	return (port > 0 && port < 65536) ? port : 40500;
}

// Starts a game as the one that hosts it. Gives 2 if that worked and 0 if not.
int32_t bb_host_net_game(const char* name)
{
	if (bb_net_started) {
		bb_runtime_error("Multiplayer game already started");
	}
	bb_net_server = bb_create_tcp_server(bb_net_port());
	if (!bb_net_server) {
		return 0;
	}
	bb_net_game    = bb_net_copy(name ? name : "", name ? strlen(name) : 0);
	bb_net_started = 1;
	bb_net_host    = 1;
	return 2;
}

// Joins a game that is hosted by the program at an address. Gives 1 if that worked and 0 if not.
int32_t bb_join_net_game(const char* name, const char* address)
{
	if (bb_net_started) {
		bb_runtime_error("Multiplayer game already started");
	}
	int32_t stream = bb_open_tcp_stream((address && *address) ? address : "127.0.0.1", bb_net_port(), 0);
	if (!stream) {
		return 0;
	}
	memset(&bb_net_connections[0], 0, sizeof(bb_connection));
	bb_net_connections[0].stream = stream;
	bb_net_started               = 1;
	bb_net_host                  = 0;
	bb_net_refused               = 0;
	bb_net_game                  = bb_net_copy(name ? name : "", name ? strlen(name) : 0);
	bb_net_send(0, FRAME_HELLO, (const uint8_t*)bb_net_game, strlen(bb_net_game));

	int32_t start = bb_millisecs();
	while (!bb_net_connections[0].greeted && !bb_net_refused && bb_net_connections[0].stream && (bb_millisecs() - start < 5000)) {
		bb_net_poll();
		if (!bb_net_connections[0].greeted && !bb_net_refused) {
			bb_delay(5);
		}
	}
	if (!bb_net_connections[0].greeted) {
		bb_net_reset();
		return 0;
	}
	return 1;
}

// Asks whether to host or to join, and does it. 0 if nothing was started.
int32_t bb_start_net_game(void)
{
	if (bb_net_started) {
		bb_runtime_error("Multiplayer game already started");
	}
	int32_t choice = bb_ask_net_game();
	if (choice == 2) {
		return bb_host_net_game("BlitzLLVM game");
	}
	if (choice == 1) {
		char address[128] = "";
		fputs("Address of the game to join: ", stdout);
		fflush(stdout);
		if (!fgets(address, sizeof(address), stdin)) {
			return 0;
		}
		address[strcspn(address, "\r\n")] = 0;
		return bb_join_net_game("BlitzLLVM game", address);
	}
	return 0;
}

void bb_stop_net_game(void)
{
	bb_net_reset();
}

// A player of this program: it is told to the others, who find out about it with RecvNetMsg. Gives its number, or 0.
int32_t bb_create_net_player(const char* name)
{
	bb_net_check();
	const char* text   = name ? name : "";
	size_t      length = strlen(text);
	if (bb_net_host) {
		int32_t id = bb_net_next_id++;
		bb_player* p = bb_net_add_player(id, text, length, 0, -1);
		for (int i = 0; i < MAX_CONNECTIONS; i++) {
			if (bb_net_connections[i].stream && bb_net_connections[i].greeted) {
				bb_net_send_player(i, p);
			}
		}
		return id;
	}
	bb_net_created = -1;
	bb_net_send(0, FRAME_CREATE, (const uint8_t*)text, length);
	int32_t start = bb_millisecs();
	while ((bb_net_created < 0) && bb_net_connections[0].stream && (bb_millisecs() - start < 5000)) {
		bb_net_poll();
		if (bb_net_created < 0) {
			bb_delay(5);
		}
	}
	if (bb_net_created <= 0) {
		return 0;
	}
	bb_net_add_player(bb_net_created, text, length, 0, -1);
	return bb_net_created;
}

void bb_delete_net_player(int32_t id)
{
	bb_net_check();
	bb_player* p = bb_net_find(id);
	if (!p || p->remote) {
		return;
	}
	if (bb_net_host) {
		uint8_t frame[4];
		put32(frame, id);
		bb_net_remove_player(id);
		bb_net_broadcast(-1, FRAME_PLAYER_GONE, frame, 4);
	} else {
		uint8_t frame[4];
		put32(frame, id);
		bb_net_send(0, FRAME_DELETE, frame, 4);
		bb_net_remove_player(id);
	}
}

const char* bb_net_player_name(int32_t id)
{
	const char* text = "<all>";
	if (id) {
		bb_player* p = bb_net_find(id);
		text         = p ? p->name : "<unknown>";
	}
	return bb_copy(text, strlen(text));
}

int32_t bb_net_player_local(int32_t id)
{
	bb_player* p = bb_net_find(id);
	return (p && !p->remote) ? 1 : 0;
}

// Sends a message from a player of this program to another player, or to all of them with 0. Reliable or not, it arrives.
int32_t bb_send_net_msg(int32_t type, const char* data, int32_t from, int32_t to, int32_t reliable)
{
	(void)reliable;
	bb_net_check();
	bb_player* sender = bb_net_find(from);
	if (!sender || sender->remote) {
		return 0;
	}
	size_t   length = bb_slen(data);
	uint8_t* frame  = (uint8_t*)bb_malloc(length + 9);
	put32(frame, from);
	put32(frame + 4, to);
	frame[8] = (uint8_t)type;
	if (length) {
		memcpy(frame + 9, data, length);
	}
	if (bb_net_host) {
		bb_player* target = to ? bb_net_find(to) : NULL;
		if (to == 0) {
			bb_net_broadcast(-1, FRAME_FORWARD, frame, length + 9);
		} else if (target && (target->connection >= 0)) {
			bb_net_send(target->connection, FRAME_FORWARD, frame, length + 9);
		}
	} else {
		bb_net_send(0, FRAME_MESSAGE, frame, length + 9);
	}
	bb_free(frame);
	return 1;
}

// Takes the next message: players that appeared (100) or went (101), the game being lost (200), or what players sent.
int32_t bb_recv_net_msg(void)
{
	bb_net_check();
	bb_str_free(bb_msg_data);
	bb_msg_data = NULL;
	bb_msg_type = 0;
	bb_msg_from = 0;
	bb_msg_to   = 0;
	bb_net_poll();

	if (bb_net_new_count) {
		bb_msg_from = bb_net_new[0];
		memmove(bb_net_new, bb_net_new + 1, (size_t)(--bb_net_new_count) * sizeof(int32_t));
		bb_msg_type = MESSAGE_NEW_PLAYER;
		return 1;
	}
	if (bb_net_inbox_count) {
		bb_message m = bb_net_inbox[0];
		memmove(bb_net_inbox, bb_net_inbox + 1, (size_t)(--bb_net_inbox_count) * sizeof(bb_message));
		bb_msg_type = m.type;
		bb_msg_from = m.from;
		bb_msg_to   = m.to;
		bb_str_free(bb_msg_data);
		bb_msg_data = bb_copy(m.data, m.length); // Messages can contain NUL.
		bb_free(m.data);
		return 1;
	}
	if (bb_net_lost) {
		bb_net_lost = 0;
		bb_msg_type = MESSAGE_SESSION_LOST;
		return 1;
	}
	return 0;
}

int32_t bb_net_msg_type(void)
{
	return bb_msg_type;
}

int32_t bb_net_msg_from(void)
{
	return bb_msg_from;
}

