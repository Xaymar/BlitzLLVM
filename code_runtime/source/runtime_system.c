extern int32_t bb_screen_print(const char* s, int32_t newline);
extern const char* bb_screen_input(const char* prompt);

void bb_print(const char* s)
{
	if (bb_screen_print(s, 1)) {
		return;
	}
	fwrite(bb_s(s), 1, bb_slen(s), stdout); // NUL is written as it is.
	fputc('\n', stdout);
}

void bb_write(const char* s)
{
	if (bb_screen_print(s, 0)) {
		return;
	}
	fwrite(bb_s(s), 1, bb_slen(s), stdout);
}

const char* bb_input(const char* prompt)
{
	const char* typed = bb_screen_input(prompt);
	if (typed) {
		return typed;
	}
	fputs(bb_s(prompt), stdout);
	fflush(stdout);
	char   buf[4096];
	if (!fgets(buf, sizeof(buf), stdin)) {
		return bb_copy("", 0);
	}
	size_t len = strlen(buf);
	while (len && (buf[len - 1] == '\n' || buf[len - 1] == '\r')) {
		len--;
	}
	return bb_copy(buf, len);
}

