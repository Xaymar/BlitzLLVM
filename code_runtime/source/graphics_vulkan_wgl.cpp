// Windows: the pictures that Vulkan draws are shown by OpenGL (the default on NVIDIA; BLITZLLVM_VULKAN_PRESENT picks another way).
//
// A Vulkan or DXGI flip model swapchain (graphics_vulkan_dxgi.cpp) is held up by the system while its window is dragged, gains
// the focus or gets other window messages: Present, and even the Direct3D 11 copies before it, waited 30 to 90 ms each on NVIDIA.
// That is Windows moving the window on and off a plane of its own (multiplane overlays): with them turned off, both were smooth.
// The OpenGL renderer stays smooth with them on, with every Flip mode, so this shows the pictures the way it does. Each window gets an OpenGL context of its own, and the images that Vulkan draws
// into are Vulkan memory that OpenGL imports (VK_KHR_external_memory_win32, GL_EXT_memory_object_win32):
//
//   acquire: the next of the three images, once OpenGL is done copying it (the GPU waits for the semaphore that OpenGL signals).
//   present: Vulkan signals a semaphore once the image is drawn; OpenGL waits for it (GL_EXT_semaphore_win32), copies the image
//            into the window with glBlitFramebuffer, signals the other semaphore and swaps the buffers. Flip 1 swaps with an
//            interval of 1, Flip 0, Flip 2 and the windows that a thread of their own shows with 0.
//
// The context is current only during a present, on the thread that presents, so any thread can present the window and it can
// be destroyed from the program's thread. Where anything is missing, the window gets a DXGI or a Vulkan swapchain instead.
