void bb_lock_buffer(int32_t buffer)
{
	if (!active()) {
		return;
	}
	buffer = buffer_or_current(buffer);
	if (find_lock(buffer)) {
		return;
	}
	target_ref target = resolve_target(buffer);
	if (!target.image) {
		bb_runtime_error("LockBuffer: the buffer does not exist.");
	}
	locked_buffer* slot = nullptr;
	for (locked_buffer& l : locked) {
		if (!l.used) {
			slot = &l;
			break;
		}
	}
	if (!slot) {
		bb_runtime_error("LockBuffer: too many buffers are locked.");
	}
	flush();
	slot->used    = true;
	slot->buffer  = buffer;
	slot->region  = target;
	slot->format  = is_deep(target.image->format) ? target.image->format : VK_FORMAT_R8G8B8A8_UNORM;
	slot->pixels  = read_pixels(*target.image, target.x, target.y, target.w, target.h, is_deep(slot->format), target.layer);
	slot->changed = false;
}

void bb_unlock_buffer(int32_t buffer)
{
	buffer           = buffer_or_current(buffer);
	locked_buffer* l = find_lock(buffer);
	if (!l) {
		return;
	}
	if (l->bank) {
		// What the program did to the bank is what the buffer gets.
		int32_t  size;
		uint8_t* data   = bb_bank_data(l->bank, &size);
		size_t   count  = size_t(l->region.w) * size_t(l->region.h);
		size_t   bytes  = pixel_bytes(l->format);
		for (size_t i = 0; i < count && ((i + 1) * bytes <= size_t(size)); i++) {
			if (is_deep(l->format)) {
				uint64_t canonical;
				if (l->format == VK_FORMAT_R16G16B16A16_SFLOAT) {
					// The half floats are what the buffer stores, so the bank is the memory of the buffer (R, G, B, A).
					uint8_t* pixel = l->pixels + i * bytes;
					memcpy(pixel, data + i * 8, 8);
					if (!buffer_has_alpha(buffer)) {
						memcpy(pixel + 6, &bb::half_one, 2);
					}
					continue;
				} else {
					int32_t word;
					memcpy(&word, data + i * 4, 4);
					canonical = int_to_canonical(l->format, word);
				}
				if (!buffer_has_alpha(buffer)) {
					canonical |= canonical_opaque;
				}
				canonical_to_raw(l->format, l->pixels + i * bytes, canonical);
				continue;
			}
			l->pixels[i * 4 + 0] = data[i * 4 + 2];
			l->pixels[i * 4 + 1] = data[i * 4 + 1];
			l->pixels[i * 4 + 2] = data[i * 4 + 0];
			l->pixels[i * 4 + 3] = buffer_has_alpha(buffer) ? data[i * 4 + 3] : 255;
		}
		bb_free_bank(l->bank);
		l->changed = true;
	}
	if (l->changed) {
		flush();
		target_ref target = resolve_target(buffer);
		if (target.image) {
			write_pixels(*target.image, target.x, target.y, target.w, target.h, l->pixels, is_deep(l->format), true, target.layer);
		}
	}
	if (buffer >= texture_buffer_base) {
		// The program knows what is in the whole texture now, which is what sprites need to be cut to size.
		texture_entry* t = texture_of((buffer - texture_buffer_base) >> 10);
		if (t && t->frames == 1 && t->frame_w == 0 && !t->cube && l->region.x == 0 && l->region.y == 0 && l->region.w == t->width && l->region.h == t->height) {
			sprite_hull_compute(t->hull, l->pixels, l->region.w, l->region.h, size_t(l->region.w), t->flags);
		}
	}
	bb_free(l->pixels);
	*l = locked_buffer();
}

// The fast commands read and write the memory of a lock, so without one there is nothing to work on. A debug build stops with an error, as the
// program does not do what it says, and any other build does nothing.
// Gives 0 for the ones that return a pixel.
static int32_t fast_without_lock(const char* command)
{
	if (bb_is_debug()) {
		char message[96];
		snprintf(message, sizeof(message), "%s: the buffer has to be locked with LockBuffer.", command);
		bb_runtime_error(message);
	}
	return 0;
}

// The pixel as the canonical 16 bits per channel value, from a locked buffer or a buffer that is not locked. Not there is 0.
static bool fetch_canonical(int32_t x, int32_t y, int32_t buffer, uint64_t& out, VkFormat& format)
{
	out    = 0;
	buffer = buffer_or_current(buffer);
	if (locked_buffer* l = find_lock(buffer)) {
		format = l->format;
		if ((x < 0) || (y < 0) || (x >= l->region.w) || (y >= l->region.h)) {
			return false;
		}
		out = raw_to_canonical(format, l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * pixel_bytes(format));
		return true;
	}
	target_ref target = resolve_target(buffer);
	if (!target.image) {
		return false;
	}
	format = is_deep(target.image->format) ? target.image->format : VK_FORMAT_R8G8B8A8_UNORM;
	if ((x < 0) || (y < 0) || (x >= target.w) || (y >= target.h)) {
		return false;
	}
	flush();
	uint8_t* pixel = read_pixels(*target.image, target.x + x, target.y + y, 1, 1, is_deep(format), target.layer);
	out            = raw_to_canonical(format, pixel);
	bb_free(pixel);
	return true;
}

static void store_canonical(int32_t x, int32_t y, int32_t buffer, uint64_t canonical)
{
	buffer = buffer_or_current(buffer);
	if (!buffer_has_alpha(buffer)) {
		canonical |= canonical_opaque;
	}
	if (locked_buffer* l = find_lock(buffer)) {
		if ((x < 0) || (y < 0) || (x >= l->region.w) || (y >= l->region.h)) {
			return;
		}
		canonical_to_raw(l->format, l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * pixel_bytes(l->format), canonical);
		l->changed = true;
		return;
	}
	target_ref target = resolve_target(buffer);
	if (!target.image || (x < 0) || (y < 0) || (x >= target.w) || (y >= target.h)) {
		return;
	}
	flush();
	VkFormat format = is_deep(target.image->format) ? target.image->format : VK_FORMAT_R8G8B8A8_UNORM;
	uint8_t  pixel[8];
	canonical_to_raw(format, pixel, canonical);
	write_pixels(*target.image, target.x + x, target.y + y, 1, 1, pixel, is_deep(format), true, target.layer);
}

// The color of the pixel with 8 bits for each of A, R, G and B, or A2R10G10B10 for a buffer that has 30 bits.
int32_t bb_read_pixel_fast(int32_t x, int32_t y, int32_t buffer)
{
	if (!active()) {
		return 0;
	}
	locked_buffer* l = find_lock(buffer_or_current(buffer));
	if (!l) {
		return fast_without_lock("ReadPixelFast");
	}
	if ((x < 0) || (y < 0) || (x >= l->region.w) || (y >= l->region.h)) {
		return 0;
	}
	if (l->format == VK_FORMAT_A2B10G10R10_UNORM_PACK32) {
		uint32_t word;
		memcpy(&word, l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * 4, 4);
		return int32_t(swap_red_blue10(word));
	}
	if (is_deep(l->format)) {
		return canonical_to_int(l->format, raw_to_canonical(l->format, l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * pixel_bytes(l->format)));
	}
	return pack_pixel(l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * 4);
}

void bb_write_pixel_fast(int32_t x, int32_t y, int32_t argb, int32_t buffer)
{
	if (!active()) {
		return;
	}
	locked_buffer* l = find_lock(buffer_or_current(buffer));
	if (!l) {
		fast_without_lock("WritePixelFast");
		return;
	}
	if ((x < 0) || (y < 0) || (x >= l->region.w) || (y >= l->region.h)) {
		return;
	}
	if (l->format == VK_FORMAT_A2B10G10R10_UNORM_PACK32) {
		uint32_t word = swap_red_blue10(uint32_t(argb));
		if (!buffer_has_alpha(l->buffer)) {
			word |= 3u << 30;
		}
		memcpy(l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * 4, &word, 4);
		l->changed = true;
		return;
	}
	if (is_deep(l->format)) {
		store_canonical(x, y, buffer, int_to_canonical(l->format, argb));
		return;
	}
	uint8_t* pixel = l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * 4;
	unpack_pixel(argb, pixel);
	if (!buffer_has_alpha(l->buffer)) {
		pixel[3] = 255;
	}
	l->changed = true;
}

// Without a lock this is slow, as the buffer has to be asked for every time.
int32_t bb_read_pixel(int32_t x, int32_t y, int32_t buffer)
{
	if (!active()) {
		return 0;
	}
	uint64_t canonical;
	VkFormat format;
	if (!fetch_canonical(x, y, buffer, canonical, format)) {
		return 0;
	}
	return canonical_to_int(format, canonical);
}

void bb_write_pixel(int32_t x, int32_t y, int32_t argb, int32_t buffer)
{
	if (!active()) {
		return;
	}
	buffer = buffer_or_current(buffer);
	if (!find_lock(buffer)) {
		target_ref target = resolve_target(buffer);
		if (target.image && !is_deep(target.image->format)) {
			if ((x < 0) || (y < 0) || (x >= target.w) || (y >= target.h)) {
				return;
			}
			flush();
			uint8_t pixel[4];
			unpack_pixel(argb, pixel);
			if (!buffer_has_alpha(buffer)) {
				pixel[3] = 255;
			}
			write_pixels(*target.image, target.x + x, target.y + y, 1, 1, pixel, false, true, target.layer);
			return;
		}
		if (!target.image) {
			return;
		}
		store_canonical(x, y, buffer, int_to_canonical(target.image->format, argb));
		return;
	}
	bb_write_pixel_fast(x, y, argb, buffer);
}

// ReadPixel64 and the others work with the pixel as the buffer stores it. The Long that ReadPixel64 and ReadPixelFast64 give is the memory of
// the pixel (R in the lowest bits), and the channels are half precision floats: for the depth 64 exactly what is stored, for the other depths the
// value from 0 to 1 that the stored bits mean. WritePixel64 and WritePixelFast64 take the channels, which are clamped to 0 to 1 for the depths
// that are not made of floats.
static bool fetch_raw(int32_t x, int32_t y, int32_t buffer, uint8_t (&raw)[8], VkFormat& format)
{
	memset(raw, 0, sizeof(raw));
	buffer = buffer_or_current(buffer);
	if (locked_buffer* l = find_lock(buffer)) {
		format = l->format;
		if ((x < 0) || (y < 0) || (x >= l->region.w) || (y >= l->region.h)) {
			return false;
		}
		memcpy(raw, l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * pixel_bytes(format), pixel_bytes(format));
		return true;
	}
	target_ref target = resolve_target(buffer);
	if (!target.image) {
		return false;
	}
	format = is_deep(target.image->format) ? target.image->format : VK_FORMAT_R8G8B8A8_UNORM;
	if ((x < 0) || (y < 0) || (x >= target.w) || (y >= target.h)) {
		return false;
	}
	flush();
	uint8_t* pixel = read_pixels(*target.image, target.x + x, target.y + y, 1, 1, is_deep(format), target.layer);
	memcpy(raw, pixel, pixel_bytes(format));
	bb_free(pixel);
	return true;
}

static void raw_to_halves(VkFormat format, const uint8_t* raw, uint16_t (&halves)[4])
{
	if (format == VK_FORMAT_R16G16B16A16_SFLOAT) {
		memcpy(halves, raw, 8);
		return;
	}
	uint64_t canonical = raw_to_canonical(format, raw);
	halves[0]          = unorm16_to_half(uint16_t(canonical >> 32));
	halves[1]          = unorm16_to_half(uint16_t(canonical >> 16));
	halves[2]          = unorm16_to_half(uint16_t(canonical));
	halves[3]          = unorm16_to_half(uint16_t(canonical >> 48));
}

static void halves_to_raw(VkFormat format, uint8_t* raw, const uint16_t (&halves)[4])
{
	if (format == VK_FORMAT_R16G16B16A16_SFLOAT) {
		memcpy(raw, halves, 8);
		return;
	}
	uint64_t canonical = make_canonical(half_to_unorm16(halves[3]), half_to_unorm16(halves[0]), half_to_unorm16(halves[1]), half_to_unorm16(halves[2]));
	canonical_to_raw(format, raw, canonical);
}

static void store_halves(int32_t x, int32_t y, int32_t buffer, uint16_t (&halves)[4])
{
	buffer = buffer_or_current(buffer);
	if (!buffer_has_alpha(buffer)) {
		halves[3] = bb::half_one;
	}
	if (locked_buffer* l = find_lock(buffer)) {
		if ((x < 0) || (y < 0) || (x >= l->region.w) || (y >= l->region.h)) {
			return;
		}
		halves_to_raw(l->format, l->pixels + (size_t(y) * size_t(l->region.w) + size_t(x)) * pixel_bytes(l->format), halves);
		l->changed = true;
		return;
	}
	target_ref target = resolve_target(buffer);
	if (!target.image || (x < 0) || (y < 0) || (x >= target.w) || (y >= target.h)) {
		return;
	}
	flush();
	VkFormat format = is_deep(target.image->format) ? target.image->format : VK_FORMAT_R8G8B8A8_UNORM;
	uint8_t  pixel[8];
	halves_to_raw(format, pixel, halves);
	write_pixels(*target.image, target.x + x, target.y + y, 1, 1, pixel, is_deep(format), true, target.layer);
}

static int64_t read_halves(int32_t x, int32_t y, int32_t buffer, uint16_t* red, uint16_t* green, uint16_t* blue, uint16_t* alpha)
{
	uint8_t  raw[8];
	VkFormat format;
	if (!fetch_raw(x, y, buffer, raw, format)) {
		return 0;
	}
	uint16_t halves[4];
	raw_to_halves(format, raw, halves);
	if (red) {
		*red = halves[0];
	}
	if (green) {
		*green = halves[1];
	}
	if (blue) {
		*blue = halves[2];
	}
	if (alpha) {
		*alpha = halves[3];
	}
	int64_t value;
	memcpy(&value, raw, sizeof(value));
	return value;
}

int64_t bb_read_pixel64(int32_t x, int32_t y, int32_t buffer, uint16_t* red, uint16_t* green, uint16_t* blue, uint16_t* alpha)
{
	if (!active()) {
		return 0;
	}
	return read_halves(x, y, buffer, red, green, blue, alpha);
}

void bb_write_pixel64(int32_t x, int32_t y, int32_t buffer, uint32_t red, uint32_t green, uint32_t blue, uint32_t alpha)
{
	if (active()) {
		uint16_t halves[4] = { uint16_t(red), uint16_t(green), uint16_t(blue), uint16_t(alpha) };
		store_halves(x, y, buffer, halves);
	}
}

int64_t bb_read_pixel_fast64(int32_t x, int32_t y, int32_t buffer, uint16_t* red, uint16_t* green, uint16_t* blue, uint16_t* alpha)
{
	if (!active()) {
		return 0;
	}
	if (!find_lock(buffer_or_current(buffer))) {
		return fast_without_lock("ReadPixelFast64");
	}
	return read_halves(x, y, buffer, red, green, blue, alpha);
}

void bb_write_pixel_fast64(int32_t x, int32_t y, int32_t buffer, uint32_t red, uint32_t green, uint32_t blue, uint32_t alpha)
{
	if (!active()) {
		return;
	}
	if (!find_lock(buffer_or_current(buffer))) {
		fast_without_lock("WritePixelFast64");
		return;
	}
	uint16_t halves[4] = { uint16_t(red), uint16_t(green), uint16_t(blue), uint16_t(alpha) };
	store_halves(x, y, buffer, halves);
}

// Through half floats, which keeps everything that a buffer with the depth 64 has (values above 1 included) and what any depth can show.
static void copy_one_pixel(int32_t sx, int32_t sy, int32_t source, int32_t dx, int32_t dy, int32_t destination)
{
	uint8_t  raw[8];
	VkFormat format;
	if (fetch_raw(sx, sy, source, raw, format)) {
		uint16_t halves[4];
		raw_to_halves(format, raw, halves);
		store_halves(dx, dy, destination, halves);
	}
}

// Copies at the depth that both buffers have: a buffer with 64 bits does not lose anything on the way.
void bb_copy_pixel_fast(int32_t sx, int32_t sy, int32_t source, int32_t dx, int32_t dy, int32_t destination)
{
	if (!active()) {
		return;
	}
	if (!find_lock(buffer_or_current(source)) || !find_lock(buffer_or_current(destination))) {
		fast_without_lock("CopyPixelFast");
		return;
	}
	copy_one_pixel(sx, sy, source, dx, dy, destination);
}

void bb_copy_pixel(int32_t sx, int32_t sy, int32_t source, int32_t dx, int32_t dy, int32_t destination)
{
	if (!active()) {
		return;
	}
	copy_one_pixel(sx, sy, source, dx, dy, destination);
}

// CopyRect source_x, source_y, width, height, destination_x, destination_y [, source buffer] [, destination buffer]
void bb_copy_rect(int32_t sx, int32_t sy, int32_t w, int32_t h, int32_t dx, int32_t dy, int32_t source, int32_t destination)
{
	bb::profile_scope timer(bb::PROFILE_COPY_RECT);
	if (!active()) {
		return;
	}
	target_ref from = resolve_target(buffer_or_current(source)), to = resolve_target(buffer_or_current(destination));
	if (!from.image || !to.image) {
		bb_runtime_error("CopyRect: the buffer does not exist.");
	}
	// Clip against both buffers. The numbers are the ones of the program, and the sums of them are not always numbers that fit in 32 bits.
	int64_t x0 = sx, y0 = sy, x1 = dx, y1 = dy, cw = w, ch = h;
	if (x0 < 0) { x1 -= x0; cw += x0; x0 = 0; }
	if (y0 < 0) { y1 -= y0; ch += y0; y0 = 0; }
	if (x1 < 0) { x0 -= x1; cw += x1; x1 = 0; }
	if (y1 < 0) { y0 -= y1; ch += y1; y1 = 0; }
	if (x0 + cw > from.w) { cw = from.w - x0; }
	if (y0 + ch > from.h) { ch = from.h - y0; }
	if (x1 + cw > to.w) { cw = to.w - x1; }
	if (y1 + ch > to.h) { ch = to.h - y1; }
	if ((cw <= 0) || (ch <= 0)) {
		return;
	}
	sx = int32_t(x0);
	sy = int32_t(y0);
	dx = int32_t(x1);
	dy = int32_t(y1);
	w  = int32_t(cw);
	h  = int32_t(ch);

	// The detour for parts of the same image goes through a buffer that is big enough.
	if (from.image->image == to.image->image) {
		VkDeviceSize size = VkDeviceSize(w) * VkDeviceSize(h) * 4;
		if (size > scratch_size) {
			flush(); // What was recorded may use the old one.
			gpu_idle();
			destroy_buffer(scratch, scratch_allocation);
			scratch_size = size > (1u << 20) ? size : (1u << 20);
			create_buffer(scratch_size, VK_BUFFER_USAGE_TRANSFER_SRC_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT, false, scratch, scratch_allocation);
		}
	}
	copies.push({ buffer_or_current(source), buffer_or_current(destination), sx, sy, w, h, dx, dy });
	operation& op = add_operation(OP_COPY, 0, 0);
	op.first      = copies.size - 1;
}

// Makes the pixel the color that is drawn with.
void bb_get_color(int32_t x, int32_t y)
{
	uint64_t canonical;
	VkFormat format;
	if (!active() || !fetch_canonical(x, y, 0, canonical, format)) {
		return;
	}
	g.color[0] = uint8_t(narrow(canonical, 32, 255));
	g.color[1] = uint8_t(narrow(canonical, 16, 255));
	g.color[2] = uint8_t(narrow(canonical, 0, 255));
}

int32_t bb_color_red(void)
{
	return g.color[0];
}

int32_t bb_color_green(void)
{
	return g.color[1];
}

int32_t bb_color_blue(void)
{
	return g.color[2];
}

// BlitzPlus gives the pixels of a locked buffer as a bank: 4 bytes for each pixel, blue first, one row after the other.
// What is done to the bank is written to the buffer when it is unlocked.
int32_t bb_locked_pixels(int32_t buffer)
{
	if (!active()) {
		return 0;
	}
	locked_buffer* l = find_lock(buffer_or_current(buffer));
	if (!l) {
		bb_runtime_error("Buffer is not locked");
	}
	if (!l->bank) {
		size_t  count = size_t(l->region.w) * size_t(l->region.h);
		size_t  bytes = pixel_bytes(l->format);
		int32_t bank  = bb_create_bank(int32_t(count * bytes));
		int32_t size;
		uint8_t* data = bb_bank_data(bank, &size);
		for (size_t i = 0; is_deep(l->format) && (i < count); i++) {
			// What a program reads is the Int of the pixel for 30 bits, and the 64 bits (A, R, G, B from the top) for 64.
			uint64_t canonical = raw_to_canonical(l->format, l->pixels + i * bytes);
			if (l->format == VK_FORMAT_R16G16B16A16_SFLOAT) {
				memcpy(data + i * 8, l->pixels + i * bytes, 8); // The memory of the buffer: R, G, B, A as half floats.
			} else {
				int32_t word = canonical_to_int(l->format, canonical);
				memcpy(data + i * 4, &word, 4);
			}
		}
		for (size_t i = 0; !is_deep(l->format) && (i < count); i++) {
			data[i * 4 + 0] = l->pixels[i * 4 + 2];
			data[i * 4 + 1] = l->pixels[i * 4 + 1];
			data[i * 4 + 2] = l->pixels[i * 4 + 0];
			data[i * 4 + 3] = 255;
		}
		l->bank = bank;
	}
	return l->bank;
}

int32_t bb_locked_pitch(int32_t buffer)
{
	if (!active()) {
		return 0;
	}
	locked_buffer* l = find_lock(buffer_or_current(buffer));
	if (!l) {
		bb_runtime_error("Buffer is not locked");
	}
	return l->region.w * int32_t(pixel_bytes(l->format));
}

// 4 is what BlitzPlus calls 32 bits with nothing in the last byte. 5 (A2R10G10B10) and 6 (R16G16B16A16 as half precision floats, the memory of the buffer) are for the buffers that
// Graphics3D made with the depth 30 and 64.
int32_t bb_locked_format(int32_t buffer)
{
	if (!active()) {
		return 0;
	}
	locked_buffer* l = find_lock(buffer_or_current(buffer));
	if (!l) {
		bb_runtime_error("Buffer is not locked");
	}
	return l->format == VK_FORMAT_A2B10G10R10_UNORM_PACK32 ? 5 : (l->format == VK_FORMAT_R16G16B16A16_SFLOAT ? 6 : 4);
}
