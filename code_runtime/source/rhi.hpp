// The rendering hardware interface: what the graphics code asks of the GPU API, so that Vulkan, Direct3D 11 and OpenGL can each answer it.
// Only the Vulkan answer exists so far, and it is built into the rest of the graphics code: the handles below still show their Vulkan objects
// (vk, allocation) until the code that records commands has moved behind the interface too. Code outside the backend must not make or free
// those objects itself, only through the functions here.
#pragma once
#define VK_NO_PROTOTYPES
#include <vulkan/vulkan.h>
