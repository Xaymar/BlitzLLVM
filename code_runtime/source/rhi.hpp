// The rendering hardware interface: what the graphics code asks of the GPU API, so that Vulkan, Direct3D 11 and OpenGL can each answer it.
// Only the Vulkan answer exists so far, and it is built into the rest of the graphics code: the handles below still show their Vulkan objects
// (vk, allocation) until the code that records commands has moved behind the interface too. Code outside the backend must not make or free
// those objects itself, only through the functions here.
#pragma once
#define VK_NO_PROTOTYPES
#include <vulkan/vulkan.h>
#include <vk_mem_alloc.h>

#include <stdint.h>

namespace bb::rhi {
	/** What a buffer is used for, any of them together. */
	enum buffer_usage : uint32_t {
		vertex_data          = 1u << 0,
		index_data           = 1u << 1,
		uniform_data         = 1u << 2,
		storage_data         = 1u << 3,
		indirect_data        = 1u << 6, // Holds the commands of indirect draws.
		transfer_source      = 1u << 4, // The GPU copies from it (upload).
		transfer_destination = 1u << 5, // The GPU copies to it (readback).
	};

	constexpr buffer_usage operator|(buffer_usage a, buffer_usage b)
	{
		return buffer_usage(uint32_t(a) | uint32_t(b));
	}

	/** Where a buffer lives. */
	enum class memory {
		device, // Only the GPU reaches it (video memory), or system memory over the bus when video memory is full.
		mapped, // The CPU keeps it mapped, reads and writes it at random, no flush needed: staging, readback, uniforms and storage written every frame.
		mesh,   // The CPU only writes it in order (resizable BAR memory if there is some), for the vertices and indices of surfaces.
	};

	/** A buffer. The Vulkan objects are visible for now, see the top of the file. If creating it failed because the device is lost, vk is null and
	    mapped points to memory that is no buffer, so that the code that goes on writing has somewhere to write. */
	struct gpu_buffer {
		VkBuffer      vk         = VK_NULL_HANDLE;
		VmaAllocation allocation = VK_NULL_HANDLE;
		void*         mapped     = nullptr; // For memory::mapped and memory::mesh: where the CPU reads and writes.
		uint64_t      size       = 0;

		explicit operator bool() const { return vk != VK_NULL_HANDLE; }
	};

	/** Makes the buffer; what it held before is forgotten, not freed (the caller has handed it to the graveyard, or it was empty). Fails with a runtime error if memory is out; the buffer is empty (but mapped points to dummy memory) if the device is lost. */
	void create_buffer(gpu_buffer& buffer, uint64_t size, buffer_usage usage, memory where);

	/** Frees the buffer, if there is one, and leaves it empty. */
	void destroy_buffer(gpu_buffer& buffer);

	/** The same for any thread (the loaders of models), for memory::mesh buffers only. False if the device is gone or there is no memory left, with nothing made. These wait
	    for each other and for close_prebuild, which the thread of the program calls before the device goes. */
	bool create_buffer_any_thread(gpu_buffer& buffer, uint64_t size, buffer_usage usage, memory where);
	void destroy_buffer_any_thread(gpu_buffer& buffer);

	/** How much video memory is in use and how much there is for this program, in bytes (0 and 0 without a device). On Vulkan this is the memory budget of the driver, or the pretended size of BLITZLLVM_VRAM_LIMIT_MB; Direct3D 11 answers from DXGI,
	    OpenGL can't and says 0 and 0. */
	void memory_budget(uint64_t& used, uint64_t& total);
} // namespace bb::rhi
