// Which mice and keyboards there are. SDL says which device an event came from, and tells when a device is plugged in or
// removed. Devices get a number counted from 0 in the order they were seen, and keep it for as long as the program runs: a
// device that is removed keeps its number and reports as not connected, a new device gets a new number.

#include "graphics_internal.hpp"
#include "memory.h"
#include "runtime_internal.h"

using namespace bb::gfx;

namespace {
	constexpr int max_devices = 16;

	struct device {
		SDL_MouseID id        = 0; // Mouse and keyboard IDs are both Uint32 in SDL.
		bool        connected = false;
		char        name[128] = {};
	};

	struct device_list {
		device list[max_devices];
		int    count    = 0;
		bool   scanned  = false;
		bool   implicit = false; // The only device is the one the system has when SDL can't tell.
	};

	device_list mice;
	device_list keyboards;

	const char* name_of(bool mouse, Uint32 id)
	{
		return mouse ? SDL_GetMouseNameForID(id) : SDL_GetKeyboardNameForID(id);
	}

	device* find(device_list& l, Uint32 id)
	{
		for (int i = 0; i < l.count; i++) {
			if (l.list[i].id == id) {
				return &l.list[i];
			}
		}
		return nullptr;
	}

	void add(device_list& l, bool mouse, Uint32 id)
	{
		if (device* d = find(l, id)) {
			d->connected = true;
			return;
		}
		if (l.implicit) { // The first real device takes the place of the made up one.
			l.implicit = false;
			l.count    = 0;
		}
		if (l.count >= max_devices) {
			return;
		}
		device& d   = l.list[l.count++];
		d.id        = id;
		d.connected = true;
		const char* name = name_of(mouse, id);
		if (name && *name) {
			SDL_strlcpy(d.name, name, sizeof(d.name));
		} else {
			SDL_snprintf(d.name, sizeof(d.name), "%s %u", mouse ? "Mouse" : "Keyboard", id);
		}
	}

	void scan(device_list& l, bool mouse)
	{
		if (l.scanned) {
			return;
		}
		l.scanned = true;
		int count = 0;
		if (bb_input_active()) {
			if (mouse) {
				SDL_MouseID* ids = SDL_GetMice(&count);
				for (int i = 0; ids && i < count; i++) {
					add(l, true, ids[i]);
				}
				SDL_free(ids);
			} else {
				SDL_KeyboardID* ids = SDL_GetKeyboards(&count);
				for (int i = 0; ids && i < count; i++) {
					add(l, false, ids[i]);
				}
				SDL_free(ids);
			}
		}
		if (l.count == 0) { // Without a window or a window system that tells, the system has one mouse and one keyboard.
			l.implicit = true;
			l.count    = 1;
			device& d  = l.list[0];
			d.id       = 0;
			d.connected = true;
			SDL_strlcpy(d.name, mouse ? "System mouse" : "System keyboard", sizeof(d.name));
		}
	}

	device* get(device_list& l, bool mouse, int32_t index)
	{
		scan(l, mouse);
		bb_input_pump();
		return ((index >= 0) && (index < l.count)) ? &l.list[index] : nullptr;
	}

	const char* name_copy(const device* d)
	{
		const char* name = d ? d->name : "";
		return bb_copy(name, strlen(name));
	}
} // namespace

namespace bb::gfx {
	// Called for every SDL event while the program looks at what happened in the window.
	void device_event(const SDL_Event& event)
	{
		switch (event.type) {
		case SDL_EVENT_MOUSE_ADDED:
			scan(mice, true);
			add(mice, true, event.mdevice.which);
			break;
		case SDL_EVENT_MOUSE_REMOVED:
			scan(mice, true);
			if (device* d = find(mice, event.mdevice.which)) {
				d->connected = false;
			}
			break;
		case SDL_EVENT_KEYBOARD_ADDED:
			scan(keyboards, false);
			add(keyboards, false, event.kdevice.which);
			break;
		case SDL_EVENT_KEYBOARD_REMOVED:
			scan(keyboards, false);
			if (device* d = find(keyboards, event.kdevice.which)) {
				d->connected = false;
			}
			break;
		default:
			break;
		}
	}
} // namespace bb::gfx

extern "C" {
// How many mice there are, including the ones that were removed again. At least 1.
int32_t bb_mouse_device_count(void)
{
	get(mice, true, 0);
	return mice.count;
}

int32_t bb_keyboard_device_count(void)
{
	get(keyboards, false, 0);
	return keyboards.count;
}

const char* bb_mouse_device_name(int32_t device_index)
{
	return name_copy(get(mice, true, device_index));
}

const char* bb_keyboard_device_name(int32_t device_index)
{
	return name_copy(get(keyboards, false, device_index));
}

int32_t bb_mouse_device_connected(int32_t device_index)
{
	device* d = get(mice, true, device_index);
	return (d && d->connected) ? 1 : 0;
}

int32_t bb_keyboard_device_connected(int32_t device_index)
{
	device* d = get(keyboards, false, device_index);
	return (d && d->connected) ? 1 : 0;
}
}
