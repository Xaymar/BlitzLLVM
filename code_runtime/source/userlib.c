// Banks: blocks of memory that programs read and write like files.

// Userlibs: the libraries that .decls files name are loaded when the program calls one of their functions, with LoadLibrary
// or dlopen like the original does, and the functions are looked up with GetProcAddress or dlsym.

#include "runtime_internal.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#if defined(_WIN32)
#include <windows.h>
#else
#include <dlfcn.h>
#include <unistd.h>
#if defined(__APPLE__)
#include <mach-o/dyld.h>
#endif
#endif

#define BB_USERLIB_MAX 64

typedef struct bb_userlib {
	char* name;
	void* handle;
} bb_userlib;

static bb_userlib bb_userlibs[BB_USERLIB_MAX];
static int        bb_userlib_count = 0;

static void* bb_userlib_open(const char* path)
{
#if defined(_WIN32)
	return (void*)LoadLibraryA(path);
#else
	return dlopen(path, RTLD_NOW | RTLD_GLOBAL);
#endif
}

static int bb_userlib_exists(const char* path)
{
#if defined(_WIN32)
	return GetFileAttributesA(path) != INVALID_FILE_ATTRIBUTES;
#else
	return access(path, R_OK) == 0;
#endif
}

// The directory of the program that is running, without a slash at the end. Empty if it is not known.
static void bb_userlib_program_dir(char* out, size_t size)
{
	out[0] = 0;
#if defined(_WIN32)
	DWORD length = GetModuleFileNameA(NULL, out, (DWORD)size);
	if (length == 0 || length >= size) {
		out[0] = 0;
		return;
	}
#elif defined(__APPLE__)
	uint32_t length = (uint32_t)size;
	if (_NSGetExecutablePath(out, &length) != 0) {
		out[0] = 0;
		return;
	}
#else
	ssize_t length = readlink("/proc/self/exe", out, size - 1);
	if (length <= 0) {
		return;
	}
	out[length] = 0;
#endif
	char* slash = strrchr(out, '/');
#if defined(_WIN32)
	char* backslash = strrchr(out, '\\');
	if (backslash && (!slash || backslash > slash)) {
		slash = backslash;
	}
#endif
	if (slash) {
		*slash = 0;
	} else {
		out[0] = 0;
	}
}

// Open the library in one directory. The name is tried as it is written, which is a .dll for the original, and with the
// extension and the prefix of the platform, so that one .decls file works everywhere.
static void* bb_userlib_open_in(const char* dir, const char* name)
{
	char        stem[256];
	const char* base  = name;
	for (const char* c = name; *c; c++) {
		if (*c == '/' || *c == '\\') {
			base = c + 1;
		}
	}
	snprintf(stem, sizeof(stem), "%s", base);
	char* dot = strrchr(stem, '.');
	if (dot) {
		*dot = 0;
	}
#if defined(_WIN32)
	const char* extensions[] = { ".dll" };
#elif defined(__APPLE__)
	const char* extensions[] = { ".dylib", ".so", ".dll" };
#else
	const char* extensions[] = { ".so", ".dll" };
#endif
	char path[1024];
	for (int variant = 0; variant < 1 + 2 * (int)(sizeof(extensions) / sizeof(extensions[0])); variant++) {
		if (variant == 0) {
			snprintf(path, sizeof(path), "%s%s%s", dir, *dir ? "/" : "", name);
		} else {
			snprintf(path, sizeof(path), "%s%s%s%s%s", dir, *dir ? "/" : "", (variant % 2) ? "" : "lib", stem, extensions[(variant - 1) / 2]);
		}
		// Without a directory the system searches for it, and says no if it does not have it.
		if ((*dir == 0) || bb_userlib_exists(path)) {
			void* handle = bb_userlib_open(path);
			if (handle) {
				return handle;
			}
		}
	}
	return NULL;
}

static void* bb_userlib_load(const char* name, const char* userlibs_dir, const char* source_dir)
{
	for (int idx = 0; idx < bb_userlib_count; idx++) {
		if (strcmp(bb_userlibs[idx].name, name) == 0) {
			return bb_userlibs[idx].handle;
		}
	}

	// The userlibs directory, where the program is, where the source is, and then what the system finds.
	char program_dir[1024];
	bb_userlib_program_dir(program_dir, sizeof(program_dir));
	const char* directories[] = { userlibs_dir, program_dir, source_dir, "" };
	void*       handle        = NULL;
	for (size_t idx = 0; !handle && idx < sizeof(directories) / sizeof(directories[0]); idx++) {
		if (directories[idx] && (idx == 3 || *directories[idx])) {
			handle = bb_userlib_open_in(directories[idx], name);
		}
	}
	if (!handle) {
		char message[512];
		snprintf(message, sizeof(message), "Userlib: the library '%s' could not be loaded.", name);
		bb_runtime_error(message);
	}
	if (bb_userlib_count < BB_USERLIB_MAX) {
		bb_userlibs[bb_userlib_count].name   = strdup(name);
		bb_userlibs[bb_userlib_count].handle = handle;
		bb_userlib_count++;
	}
	return handle;
}

static void* bb_userlib_symbol(void* handle, const char* symbol)
{
#if defined(_WIN32)
	return (void*)GetProcAddress((HMODULE)handle, symbol);
#else
	return dlsym(handle, symbol);
#endif
}

// The function of a library, loaded on the first call. The slot is where the program keeps it. A decorated stdcall name (_Name@8) is
// looked for as it is written, and then as the undecorated name that the C calling convention exports.
void* bb_userlib_function(void** slot, const char* lib, const char* symbol, const char* userlibs_dir, const char* source_dir)
{
	if (*slot) {
		return *slot;
	}
	void* handle = bb_userlib_load(lib, userlibs_dir, source_dir);
	void* found  = bb_userlib_symbol(handle, symbol);
	if (!found) {
		char        plain[256];
		const char* start = (symbol[0] == '_') ? symbol + 1 : symbol;
		snprintf(plain, sizeof(plain), "%s", start);
		char* at = strrchr(plain, '@');
		if (at) {
			*at = 0;
		}
		found = bb_userlib_symbol(handle, plain);
	}
	if (!found) {
		char message[512];
		snprintf(message, sizeof(message), "Userlib: the function '%s' was not found in '%s'.", symbol, lib);
		bb_runtime_error(message);
	}
	*slot = found;
	return found;
}
