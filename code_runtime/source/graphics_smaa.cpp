// AntiAlias. 1 smooths what 3D drew with SMAA (Subpixel Morphological Antialiasing, https://github.com/iryoku/smaa) at
// its ultra preset, 2 also does it with SMAA T2x: the picture of a camera is shifted by a quarter pixel every other
// RenderWorld and blended with the one before it, where everything was found from the depth and the matrices of
// both pictures. That needs the picture of the one before, so it only works for the BackBuffer, other targets get 1.
//
// It runs right after the camera is drawn and only on the part of the target that the camera draws to, so 2D drawing,
// before or after, is not touched. Where the camera did not clear the picture, only what 3D drew (it has a depth) and
// its neighbors are smoothed.

