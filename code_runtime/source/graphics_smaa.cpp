	int antialias_mode()
	{
		return setting;
	}

	void antialias_new_frame()
	{
		frame_serial++;
	}

	antialias_plan antialias_begin(int camera, int target_handle, target_ref const& target, int vx, int vy, int vw, int vh)
	{
		antialias_plan plan;
		if ((setting == 0) || palette_mode() || (vw < 4) || (vh < 4) || !target.image || (target.image->block != block_format::none)) {
			return plan;
		}
		plan.mode = 1;
		int index = find_slot(camera);
		slot& s   = slots[index];
		if (s.camera != camera) {
			s.camera   = camera;
			s.has_last = false;
			s.phase    = 1;
		}
		slot_used[index] = ++use_counter;
		plan.slot        = index;
		if ((setting == 2) && (target_handle == back_buffer)) {
			plan.mode = 2;
			// Every picture takes the other of the two places a quarter pixel from the middle (the table of the SMAA
			// documentation, with the rows of the picture going down): the sample moves right and down for the first,
			// so the picture moves left and up. Unless the one before is not there to blend with.
			plan.phase     = continues(s, vw, vh) ? (s.phase ^ 1) : 0;
			float shift    = plan.phase ? 0.25f : -0.25f;
			plan.jitter[0] = shift * 2.0f / float(vw);
			plan.jitter[1] = shift * 2.0f / float(vh);
		}
		(void)vx;
		(void)vy;
		return plan;
	}

	void antialias_end(antialias_plan const& plan, int camera, int target_handle, target_ref const& target, int vx, int vy, int vw, int vh, const float* vp, const double* origin, bool masked)
	{
		(void)target_handle;
		antialias_record record = {};
		record.camera           = camera;
		record.slot             = plan.slot;
		record.x                = target.x + vx;
		record.y                = target.y + vy;
		record.w                = vw;
		record.h                = vh;
		record.layer            = target.layer;
		record.temporal         = plan.mode == 2;
		record.masked           = masked;
		record.phase            = plan.phase;
		if (record.temporal) {
			slot& s = slots[plan.slot];
			if (continues(s, vw, vh) && reprojection(s, vp, origin, record.reproject)) {
				record.history_weight = 0.5f;
			}
			memcpy(s.vp, vp, sizeof(s.vp));
			memcpy(s.origin, origin, sizeof(s.origin));
			s.phase     = plan.phase;
			s.serial    = frame_serial;
			s.has_last  = true;
			s.last_width  = uint32_t(vw);
			s.last_height = uint32_t(vh);
		}
		antialiases.push(record);
		operation& op = add_operation(OP_ANTIALIAS, 0, 0);
		op.first      = antialiases.size - 1;
	}

	void record_antialias(uint32_t index, int target_handle)
	{
		antialias_record& r = antialiases[index];
		target_ref target   = resolve_target(target_handle);
		if (!target.image) {
			return;
		}
		if (!ready) {
			create_resources();
		}
		gpu_image& depth = depth_for(target.image->width, target.image->height);
		slot& s          = slots[r.slot];
		prepare_slot(s, r.camera, uint32_t(r.w), uint32_t(r.h), target.image->format, r.temporal, depth);
		float weight = (r.temporal && s.history) ? r.history_weight : 0.0f;

		// The part of the target that the camera drew.
		transition(*target.image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL);
		transition(s.src, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
		VkImageCopy copy       = {};
		copy.srcSubresource    = { VK_IMAGE_ASPECT_COLOR_BIT, 0, r.layer, 1 };
		copy.srcOffset         = { r.x, r.y, 0 };
		copy.dstSubresource    = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 };
		copy.extent            = { uint32_t(r.w), uint32_t(r.h), 1 };
		vkCmdCopyImage(g.cmd, target.image->image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, s.src.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &copy);
		transition(s.src, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);

		constants c = {};
		c.metrics[0] = 1.0f / float(r.w);
		c.metrics[1] = 1.0f / float(r.h);
		c.metrics[2] = float(r.w);
		c.metrics[3] = float(r.h);
		c.resolve[0] = weight;
		c.resolve[1] = r.masked ? 1.0f : 0.0f;
		c.depthmap[0] = float(r.x) / float(depth.width);
		c.depthmap[1] = float(r.y) / float(depth.height);
		c.depthmap[2] = float(r.w) / float(depth.width);
		c.depthmap[3] = float(r.h) / float(depth.height);
		if (r.temporal) {
			c.subsample[0] = c.subsample[1] = c.subsample[2] = r.phase ? 2.0f : 1.0f;
			memcpy(c.reproject, r.reproject, sizeof(c.reproject));
		}
		VkRect2D whole = { { 0, 0 }, { uint32_t(r.w), uint32_t(r.h) } };

		// Edges, then the weights of the blend along them.
		transition(s.edges, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL);
		begin_pass(s.edges, whole, true);
		draw_pass(edges_pipeline, s.edges_set, c);
		transition(s.edges, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
		transition(s.blend, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL);
		begin_pass(s.blend, whole, true);
		draw_pass(weights_pipeline, s.weights_set, c);
		transition(s.blend, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);

		// The blend itself reads the depth, to leave alone what 3D did not draw.
		bool reads_depth = r.masked || r.temporal;

		// What 3D drew was dithered before it was smoothed, and smoothing makes colors between the steps of 8 bits that rounding would flatten
		// again, so the last pass dithers what it makes (only a target of 8 bits per channel, the others are dithered when they are shown).
		// The blend of T2x only makes the picture that the resolve then mixes, so that one is not rounded with noise.
		float dither_for_pass = (target.image->format == VK_FORMAT_R8G8B8A8_UNORM) ? dither_code() : 0.0f;
		float steps[3]        = { 0, 0, 0 };
		dither_steps(steps);
		c.subsample[0] = steps[0];
		c.subsample[1] = steps[1];
		c.subsample[2] = steps[2];
		c.subsample[3] = float(bayer_levels());
		c.resolve[2]   = r.temporal ? 0.0f : dither_for_pass;
		if (reads_depth) {
			barrier(depth.image, VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_DEPTH_STENCIL_READ_ONLY_OPTIMAL, VK_IMAGE_ASPECT_DEPTH_BIT);
		}
		format_pipelines& p = pipelines_for(target.image->format);
		VkRect2D          area = { { r.x, r.y }, { uint32_t(r.w), uint32_t(r.h) } };
		if (!r.temporal) {
			transition(*target.image, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL);
			VkRenderingAttachmentInfo attachment = { VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO };
			attachment.imageView                 = target_view_of(*target.image, r.layer);
			attachment.imageLayout               = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
			attachment.loadOp                    = VK_ATTACHMENT_LOAD_OP_LOAD;
			attachment.storeOp                   = VK_ATTACHMENT_STORE_OP_STORE;
			VkRenderingInfo info                 = { VK_STRUCTURE_TYPE_RENDERING_INFO };
			info.renderArea                      = { { 0, 0 }, { target.image->width, target.image->height } };
			info.layerCount                      = 1;
			info.colorAttachmentCount            = 1;
			info.pColorAttachments               = &attachment;
			vkCmdBeginRendering(g.cmd, &info);
			VkViewport viewport = { float(r.x), float(r.y), float(r.w), float(r.h), 0, 1 };
			vkCmdSetViewport(g.cmd, 0, 1, &viewport);
			vkCmdSetScissor(g.cmd, 0, 1, &area);
			draw_pass(p.blend, s.blend_set, c);
		} else {
			gpu_image& now     = s.out[s.current];
			gpu_image& before  = s.out[1 - s.current];
			transition(now, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL);
			transition(before, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
			c.resolve[2] = 0.0f;
			begin_pass(now, whole, false);
			draw_pass(p.blend, s.blend_set, c);
			transition(now, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
			transition(*target.image, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL);
			VkRenderingAttachmentInfo attachment = { VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO };
			attachment.imageView                 = target_view_of(*target.image, r.layer);
			attachment.imageLayout               = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
			attachment.loadOp                    = VK_ATTACHMENT_LOAD_OP_LOAD;
			attachment.storeOp                   = VK_ATTACHMENT_STORE_OP_STORE;
			VkRenderingInfo info                 = { VK_STRUCTURE_TYPE_RENDERING_INFO };
			info.renderArea                      = { { 0, 0 }, { target.image->width, target.image->height } };
			info.layerCount                      = 1;
			info.colorAttachmentCount            = 1;
			info.pColorAttachments               = &attachment;
			vkCmdBeginRendering(g.cmd, &info);
			VkViewport viewport = { float(r.x), float(r.y), float(r.w), float(r.h), 0, 1 };
			vkCmdSetViewport(g.cmd, 0, 1, &viewport);
			vkCmdSetScissor(g.cmd, 0, 1, &area);
			c.resolve[2] = dither_for_pass;
			draw_pass(p.resolve, s.resolve_set[s.current], c);
			s.current = 1 - s.current;
			s.history = true;
		}
		if (reads_depth) {
			barrier(depth.image, VK_IMAGE_LAYOUT_DEPTH_STENCIL_READ_ONLY_OPTIMAL, VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL, VK_IMAGE_ASPECT_DEPTH_BIT);
		}
		target.image->mips_stale = target.image->mips > 1;
	}

	void destroy_antialias()
	{
		if (!ready) {
			return;
		}
		wait_gpu();
		for (slot& s : slots) {
			release_slot(s);
			s.camera = 0;
			s.has_last = false;
		}
		for (format_pipelines& p : pipelines) {
			if (p.blend) {
				vkDestroyPipeline(g.device, p.blend, nullptr);
				vkDestroyPipeline(g.device, p.resolve, nullptr);
			}
			p = format_pipelines();
		}
		vkDestroyPipeline(g.device, edges_pipeline, nullptr);
		vkDestroyPipeline(g.device, weights_pipeline, nullptr);
		for (int i = 0; i < 4; i++) {
			vkDestroyShaderModule(g.device, vertex_modules[i], nullptr);
			vkDestroyShaderModule(g.device, fragment_modules[i], nullptr);
		}
		vkDestroySampler(g.device, linear, nullptr);
		vkDestroySampler(g.device, nearest, nullptr);
		vkDestroyDescriptorPool(g.device, pool, nullptr);
		vkDestroyPipelineLayout(g.device, layout, nullptr);
		vkDestroyDescriptorSetLayout(g.device, set_layout, nullptr);
		destroy_image(area_texture);
		destroy_image(search_texture);
		destroy_buffer(area_staging, area_allocation);
		destroy_buffer(search_staging, search_allocation);
		ready = false;
	}
