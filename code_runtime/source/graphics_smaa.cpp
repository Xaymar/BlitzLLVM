	// Matrices are in the order of the rest of the runtime: columns first.
	void multiply(const double* a, const double* b, double* out)
	{
		double r[16];
		for (int c = 0; c < 4; c++) {
			for (int row = 0; row < 4; row++) {
				double sum = 0;
				for (int k = 0; k < 4; k++) {
					sum += a[k * 4 + row] * b[c * 4 + k];
				}
				r[c * 4 + row] = sum;
			}
		}
		memcpy(out, r, sizeof(r));
	}

	bool invert(const double* m, double* out)
	{
		double inv[16];
		inv[0]  = m[5] * m[10] * m[15] - m[5] * m[11] * m[14] - m[9] * m[6] * m[15] + m[9] * m[7] * m[14] + m[13] * m[6] * m[11] - m[13] * m[7] * m[10];
		inv[4]  = -m[4] * m[10] * m[15] + m[4] * m[11] * m[14] + m[8] * m[6] * m[15] - m[8] * m[7] * m[14] - m[12] * m[6] * m[11] + m[12] * m[7] * m[10];
		inv[8]  = m[4] * m[9] * m[15] - m[4] * m[11] * m[13] - m[8] * m[5] * m[15] + m[8] * m[7] * m[13] + m[12] * m[5] * m[11] - m[12] * m[7] * m[9];
		inv[12] = -m[4] * m[9] * m[14] + m[4] * m[10] * m[13] + m[8] * m[5] * m[14] - m[8] * m[6] * m[13] - m[12] * m[5] * m[10] + m[12] * m[6] * m[9];
		inv[1]  = -m[1] * m[10] * m[15] + m[1] * m[11] * m[14] + m[9] * m[2] * m[15] - m[9] * m[3] * m[14] - m[13] * m[2] * m[11] + m[13] * m[3] * m[10];
		inv[5]  = m[0] * m[10] * m[15] - m[0] * m[11] * m[14] - m[8] * m[2] * m[15] + m[8] * m[3] * m[14] + m[12] * m[2] * m[11] - m[12] * m[3] * m[10];
		inv[9]  = -m[0] * m[9] * m[15] + m[0] * m[11] * m[13] + m[8] * m[1] * m[15] - m[8] * m[3] * m[13] - m[12] * m[1] * m[11] + m[12] * m[3] * m[9];
		inv[13] = m[0] * m[9] * m[14] - m[0] * m[10] * m[13] - m[8] * m[1] * m[14] + m[8] * m[2] * m[13] + m[12] * m[1] * m[10] - m[12] * m[2] * m[9];
		inv[2]  = m[1] * m[6] * m[15] - m[1] * m[7] * m[14] - m[5] * m[2] * m[15] + m[5] * m[3] * m[14] + m[13] * m[2] * m[7] - m[13] * m[3] * m[6];
		inv[6]  = -m[0] * m[6] * m[15] + m[0] * m[7] * m[14] + m[4] * m[2] * m[15] - m[4] * m[3] * m[14] - m[12] * m[2] * m[7] + m[12] * m[3] * m[6];
		inv[10] = m[0] * m[5] * m[15] - m[0] * m[7] * m[13] - m[4] * m[1] * m[15] + m[4] * m[3] * m[13] + m[12] * m[1] * m[7] - m[12] * m[3] * m[5];
		inv[14] = -m[0] * m[5] * m[14] + m[0] * m[6] * m[13] + m[4] * m[1] * m[14] - m[4] * m[2] * m[13] - m[12] * m[1] * m[6] + m[12] * m[2] * m[5];
		inv[3]  = -m[1] * m[6] * m[11] + m[1] * m[7] * m[10] + m[5] * m[2] * m[11] - m[5] * m[3] * m[10] - m[9] * m[2] * m[7] + m[9] * m[3] * m[6];
		inv[7]  = m[0] * m[6] * m[11] - m[0] * m[7] * m[10] - m[4] * m[2] * m[11] + m[4] * m[3] * m[10] + m[8] * m[2] * m[7] - m[8] * m[3] * m[6];
		inv[11] = -m[0] * m[5] * m[11] + m[0] * m[7] * m[9] + m[4] * m[1] * m[11] - m[4] * m[3] * m[9] - m[8] * m[1] * m[7] + m[8] * m[3] * m[5];
		inv[15] = m[0] * m[5] * m[10] - m[0] * m[6] * m[9] - m[4] * m[1] * m[10] + m[4] * m[2] * m[9] + m[8] * m[1] * m[6] - m[8] * m[2] * m[5];
		double det = m[0] * inv[0] + m[1] * inv[4] + m[2] * inv[8] + m[3] * inv[12];
		if (det == 0.0) {
			return false;
		}
		for (int i = 0; i < 16; i++) {
			out[i] = inv[i] / det;
		}
		return true;
	}

	void identity(double* m)
	{
		memset(m, 0, sizeof(double) * 16);
		m[0] = m[5] = m[10] = m[15] = 1;
	}

	// Where a point of the picture of this time was in the one before: from (x, y, depth, 1) of the clip space of this
	// picture to the clip space of the one before. The shift of the two pictures is left in on purpose: the same pixel
	// of both looks at two different places in it, which is what the second sample is. Returns false if the matrix can
	// not be inverted.
	bool reprojection(slot const& s, const float* vp, const double* origin, float* out)
	{
		double now[16], before[16], inverse[16], move[16], a[16], b[16];
		for (int i = 0; i < 16; i++) {
			now[i]    = vp[i];
			before[i] = s.vp[i];
		}
		if (!invert(now, inverse)) {
			return false;
		}
		identity(move); // Positions are relative to the camera: from the origin of this time to the one before.
		for (int k = 0; k < 3; k++) {
			move[12 + k] = origin[k] - s.origin[k];
		}
		multiply(move, inverse, a);
		multiply(before, a, b);
		for (int i = 0; i < 16; i++) {
			out[i] = float(b[i]);
		}
		return true;
	}

	// Whether the picture of the one before is the one that this blends with.
	bool continues(slot const& s, int width, int height)
	{
		return s.has_last && (s.serial + 1 == frame_serial) && (s.last_width == uint32_t(width)) && (s.last_height == uint32_t(height));
	}

	int find_slot(int camera)
	{
		int oldest = 0;
		for (int i = 0; i < max_slots; i++) {
			if (slots[i].camera == camera) {
				return i;
			}
			if (slot_used[i] < slot_used[oldest]) {
				oldest = i;
			}
		}
		return oldest;
	}

	VkSampler make_sampler(VkFilter filter)
	{
		VkSamplerCreateInfo info = { VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO };
		info.magFilter           = filter;
		info.minFilter           = filter;
		info.mipmapMode          = VK_SAMPLER_MIPMAP_MODE_NEAREST;
		info.addressModeU = info.addressModeV = info.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
		VkSampler sampler;
		check(vkCreateSampler(g.device, &info, nullptr, &sampler), "vkCreateSampler");
		return sampler;
	}

	gpu_image upload_lookup(VkFormat format, uint32_t width, uint32_t height, const unsigned char* data, size_t size, VkBuffer& staging, VmaAllocation& allocation)
	{
		void* mapped;
		create_buffer(size, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, true, staging, allocation, &mapped);
		memcpy(mapped, data, size);
		gpu_image image = create_image(width, height, VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT, format);
		transition(image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
		VkBufferImageCopy copy = {};
		copy.imageSubresource  = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 };
		copy.imageExtent       = { width, height, 1 };
		vkCmdCopyBufferToImage(g.cmd, staging, image.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &copy);
		transition(image, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL);
		return image;
	}

	void create_resources()
	{
		VkDescriptorSetLayoutBinding bindings[3] = {};
		for (uint32_t i = 0; i < 3; i++) {
			bindings[i].binding         = i;
			bindings[i].descriptorType  = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
			bindings[i].descriptorCount = 1;
			bindings[i].stageFlags      = VK_SHADER_STAGE_FRAGMENT_BIT;
		}
		VkDescriptorSetLayoutCreateInfo set_info = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
		set_info.bindingCount                    = 3;
		set_info.pBindings                       = bindings;
		check(vkCreateDescriptorSetLayout(g.device, &set_info, nullptr, &set_layout), "vkCreateDescriptorSetLayout");

		VkPushConstantRange range = { VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(constants) };
		VkPipelineLayoutCreateInfo layout_info = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
		layout_info.setLayoutCount             = 1;
		layout_info.pSetLayouts                = &set_layout;
		layout_info.pushConstantRangeCount     = 1;
		layout_info.pPushConstantRanges        = &range;
		check(vkCreatePipelineLayout(g.device, &layout_info, nullptr, &layout), "vkCreatePipelineLayout");

		VkDescriptorPoolSize size = { VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, max_slots * 5 * 3 };
		VkDescriptorPoolCreateInfo pool_info = { VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO };
		pool_info.maxSets                    = max_slots * 5;
		pool_info.poolSizeCount              = 1;
		pool_info.pPoolSizes                 = &size;
		check(vkCreateDescriptorPool(g.device, &pool_info, nullptr, &pool), "vkCreateDescriptorPool");

		linear  = make_sampler(VK_FILTER_LINEAR);
		nearest = make_sampler(VK_FILTER_NEAREST);

		vertex_modules[0]   = create_shader(bb_shader_smaa_vertex_edges, sizeof(bb_shader_smaa_vertex_edges));
		vertex_modules[1]   = create_shader(bb_shader_smaa_vertex_weights, sizeof(bb_shader_smaa_vertex_weights));
		vertex_modules[2]   = create_shader(bb_shader_smaa_vertex_blend, sizeof(bb_shader_smaa_vertex_blend));
		vertex_modules[3]   = create_shader(bb_shader_smaa_vertex_resolve, sizeof(bb_shader_smaa_vertex_resolve));
		fragment_modules[0] = create_shader(bb_shader_smaa_fragment_edges, sizeof(bb_shader_smaa_fragment_edges));
		fragment_modules[1] = create_shader(bb_shader_smaa_fragment_weights, sizeof(bb_shader_smaa_fragment_weights));
		fragment_modules[2] = create_shader(bb_shader_smaa_fragment_blend, sizeof(bb_shader_smaa_fragment_blend));
		fragment_modules[3] = create_shader(bb_shader_smaa_fragment_resolve, sizeof(bb_shader_smaa_fragment_resolve));
		edges_pipeline      = create_fullscreen_pipeline(vertex_modules[0], fragment_modules[0], layout, VK_FORMAT_R8G8_UNORM);
		weights_pipeline    = create_fullscreen_pipeline(vertex_modules[1], fragment_modules[1], layout, VK_FORMAT_R8G8B8A8_UNORM);

		area_texture   = upload_lookup(VK_FORMAT_R8G8_UNORM, 160, 560, bb_smaa_area_texture, sizeof(bb_smaa_area_texture), area_staging, area_allocation);
		search_texture = upload_lookup(VK_FORMAT_R8_UNORM, 64, 16, bb_smaa_search_texture, sizeof(bb_smaa_search_texture), search_staging, search_allocation);
		ready          = true;
	}

	format_pipelines& pipelines_for(VkFormat format)
	{
		int free_index = -1;
		for (int i = 0; i < 8; i++) {
			if (pipelines[i].format == format) {
				return pipelines[i];
			}
			if ((free_index < 0) && (pipelines[i].format == VK_FORMAT_UNDEFINED)) {
				free_index = i;
			}
		}
		if (free_index < 0) {
			free_index = 0; // More formats than there can be: not reached, the targets of 3D have a few.
			vkDeviceWaitIdle(g.device);
			vkDestroyPipeline(g.device, pipelines[0].blend, nullptr);
			vkDestroyPipeline(g.device, pipelines[0].resolve, nullptr);
		}
		format_pipelines& p = pipelines[free_index];
		p.format            = format;
		p.blend             = create_fullscreen_pipeline(vertex_modules[2], fragment_modules[2], layout, format);
		p.resolve           = create_fullscreen_pipeline(vertex_modules[3], fragment_modules[3], layout, format);
		return p;
	}

	void write_set(VkDescriptorSet set, gpu_image const* a, VkSampler sa, gpu_image const* b, VkSampler sb, VkImageView c, VkSampler sc)
	{
		VkDescriptorImageInfo infos[3] = {
			{ sa, a->view, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL },
			{ sb, b->view, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL },
			{ sc, c, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL },
		};
		VkWriteDescriptorSet writes[3] = {};
		for (uint32_t i = 0; i < 3; i++) {
			writes[i].sType           = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
			writes[i].dstSet          = set;
			writes[i].dstBinding      = i;
			writes[i].descriptorCount = 1;
			writes[i].descriptorType  = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
			writes[i].pImageInfo      = &infos[i];
		}
		vkUpdateDescriptorSets(g.device, 3, writes, 0, nullptr);
	}

	void allocate_set(VkDescriptorSet& set)
	{
		VkDescriptorSetAllocateInfo alloc = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO };
		alloc.descriptorPool              = pool;
		alloc.descriptorSetCount          = 1;
		alloc.pSetLayouts                 = &set_layout;
		check(vkAllocateDescriptorSets(g.device, &alloc, &set), "vkAllocateDescriptorSets");
	}

	void release_slot(slot& s)
	{
		destroy_image(s.src);
		destroy_image(s.edges);
		destroy_image(s.blend);
		destroy_image(s.out[0]);
		destroy_image(s.out[1]);
		if (s.edges_set) {
			VkDescriptorSet sets[5] = { s.edges_set, s.weights_set, s.blend_set, s.resolve_set[0], s.resolve_set[1] };
			vkFreeDescriptorSets(g.device, pool, 5, sets);
		}
		s.edges_set = s.weights_set = s.blend_set = s.resolve_set[0] = s.resolve_set[1] = VK_NULL_HANDLE;
		s.owner = 0;
		s.width = s.height = 0;
		s.depth_view = VK_NULL_HANDLE;
		s.history = false;
	}

	// Makes what a camera needs on the GPU, if it has not got it or has the wrong size.
	void prepare_slot(slot& s, int camera, uint32_t width, uint32_t height, VkFormat format, bool temporal, gpu_image& depth)
	{
		if ((s.owner != camera) || (s.width != width) || (s.height != height) || (s.format != format) || (s.temporal != temporal)) {
			wait_gpu(); // The frame before may still use them.
			release_slot(s);
			VkImageUsageFlags attachment = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_SAMPLED_BIT;
			s.src   = create_image(width, height, VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_SAMPLED_BIT, format);
			s.edges = create_image(width, height, attachment, VK_FORMAT_R8G8_UNORM);
			s.blend = create_image(width, height, attachment, VK_FORMAT_R8G8B8A8_UNORM);
			if (temporal) {
				s.out[0] = create_image(width, height, attachment, format);
				s.out[1] = create_image(width, height, attachment, format);
			}
			allocate_set(s.edges_set);
			allocate_set(s.weights_set);
			allocate_set(s.blend_set);
			write_set(s.edges_set, &s.src, linear, &s.src, linear, s.src.view, linear);
			write_set(s.weights_set, &s.edges, linear, &area_texture, linear, search_texture.view, nearest);
			if (temporal) {
				allocate_set(s.resolve_set[0]);
				allocate_set(s.resolve_set[1]);
			}
			s.owner = camera, s.width = width, s.height = height, s.format = format, s.temporal = temporal;
			s.depth_view = VK_NULL_HANDLE;
		}
		if (s.depth_view != depth.view) {
			wait_gpu();
			s.depth_view = depth.view;
			write_set(s.blend_set, &s.src, linear, &s.blend, linear, depth.view, nearest);
			if (temporal) {
				write_set(s.resolve_set[0], &s.out[0], linear, &s.out[1], linear, depth.view, nearest);
				write_set(s.resolve_set[1], &s.out[1], linear, &s.out[0], linear, depth.view, nearest);
			}
		}
	}

	void begin_pass(gpu_image& image, VkRect2D area, bool clear, bool load = false)
	{
		VkRenderingAttachmentInfo attachment = { VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO };
		attachment.imageView                 = image.view;
		attachment.imageLayout               = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
		attachment.loadOp                    = clear ? VK_ATTACHMENT_LOAD_OP_CLEAR : (load ? VK_ATTACHMENT_LOAD_OP_LOAD : VK_ATTACHMENT_LOAD_OP_DONT_CARE);
		attachment.storeOp                   = VK_ATTACHMENT_STORE_OP_STORE;
		VkRenderingInfo info                 = { VK_STRUCTURE_TYPE_RENDERING_INFO };
		info.renderArea                      = { { 0, 0 }, { image.width, image.height } };
		info.layerCount                      = 1;
		info.colorAttachmentCount            = 1;
		info.pColorAttachments               = &attachment;
		vkCmdBeginRendering(g.cmd, &info);
		VkViewport viewport = { float(area.offset.x), float(area.offset.y), float(area.extent.width), float(area.extent.height), 0, 1 };
		vkCmdSetViewport(g.cmd, 0, 1, &viewport);
		vkCmdSetScissor(g.cmd, 0, 1, &area);
	}

	void draw_pass(VkPipeline pipeline, VkDescriptorSet set, constants const& c)
	{
		vkCmdBindPipeline(g.cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, pipeline);
		vkCmdBindDescriptorSets(g.cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, layout, 0, 1, &set, 0, nullptr);
		vkCmdPushConstants(g.cmd, layout, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(c), &c);
		vkCmdDraw(g.cmd, 3, 1, 0, 0);
		vkCmdEndRendering(g.cmd);
	}
