void bb_cls(void)
{
	if (!active()) {
		return;
	}
	operation& op = add_operation(OP_CLEAR, 0, 0);
	op.color[0]   = g.clscolor[0] / 255.0f;
	op.color[1]   = g.clscolor[1] / 255.0f;
	op.color[2]   = g.clscolor[2] / 255.0f;
	op.color[3]   = 1.0f;
}

void bb_color(int32_t r, int32_t g_, int32_t b)
{
	g.color[0] = uint8_t(r < 0 ? 0 : (r > 255 ? 255 : r));
	g.color[1] = uint8_t(g_ < 0 ? 0 : (g_ > 255 ? 255 : g_));
	g.color[2] = uint8_t(b < 0 ? 0 : (b > 255 ? 255 : b));
}

void bb_clscolor(int32_t r, int32_t g_, int32_t b)
{
	g.clscolor[0] = uint8_t(r < 0 ? 0 : (r > 255 ? 255 : r));
	g.clscolor[1] = uint8_t(g_ < 0 ? 0 : (g_ > 255 ? 255 : g_));
	g.clscolor[2] = uint8_t(b < 0 ? 0 : (b > 255 ? 255 : b));
}

