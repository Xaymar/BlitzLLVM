namespace bb::gfx {
	// Fonts that are loaded are a TrueType font of the system if there is one with that name, and otherwise the built-in
	// bitmap font in the size that was asked for.
	struct font_entry {
		bool      used   = false;
		char*     name   = nullptr;
		int       height = 8;
		int       style  = 0; // 1 bold, 2 italic, 4 underline
		ttf_font* ttf    = nullptr;
	};
	static bb::buffer<font_entry> font_table;

	static font_entry* font_of(int handle)
	{
		if ((handle < 1) || (uint32_t(handle) > font_table.size) || !font_table[uint32_t(handle) - 1].used) {
			return nullptr;
		}
		return &font_table[uint32_t(handle) - 1];
	}

	static float font_scale()
	{
		font_entry* f = font_of(g.font);
		return f ? float(f->height) / 8.0f : 1.0f;
	}

	// The height of a line of the font that text is drawn with, and the width of its widest character.
	static int current_height()
	{
		font_entry* f = font_of(g.font);
		return (f && f->ttf) ? ttf_height(f->ttf) : int(8 * font_scale() + 0.5f);
	}

	static int current_width()
	{
		font_entry* f = font_of(g.font);
		return (f && f->ttf) ? ttf_width(f->ttf) : int(8 * font_scale() + 0.5f);
	}

	static void glyph_vertices(vertex* v, float x, float y, int c, float scale)
	{
		int index;
		if ((c <= 32) || ((c >= 127) && (c <= 160))) {
			index = -1;
		} else if (c >= BB_FONT_GLYPHS) {
			index = BB_FONT_GLYPHS - 1;
		} else if (c < 127) {
			index = c - 33;
		} else {
			index = c - 67;
		}
		float atlas_w = float(font_columns * 8), atlas_h = float(font_rows * 8);
		float u0 = 0, v0 = 0, u1 = 0, v1 = 0;
		if (index >= 0) {
			u0 = float((index % font_columns) * 8) / atlas_w;
			v0 = float((index / font_columns) * 8) / atlas_h;
			u1 = u0 + 8.0f / atlas_w;
			v1 = v0 + 8.0f / atlas_h;
		}
		float size = 8 * scale;
		set_vertex(v[0], x, y, u0, v0);
		set_vertex(v[1], x + size, y, u1, v0);
		set_vertex(v[2], x, y + size, u0, v1);
		set_vertex(v[3], x + size, y, u1, v0);
		set_vertex(v[4], x + size, y + size, u1, v1);
		set_vertex(v[5], x, y + size, u0, v1);
	}
} // namespace bb::gfx

