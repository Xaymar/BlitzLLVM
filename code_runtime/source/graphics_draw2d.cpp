void bb_line(int32_t x1, int32_t y1, int32_t x2, int32_t y2)
{
	if (!active()) {
		return;
	}
	// Lines are made of whole pixels with both ends included, the way the original draws them, which the GPU does not
	// do for lines. The part of the line outside the buffer is cut off first.
	target_ref target = resolve_target(g.target);
	if (!target.image) {
		return;
	}
	int cx1 = target.w - 1, cy1 = target.h - 1;
	for (;;) {
		int clip0 = 0, clip1 = 0;
		if (y1 > cy1) clip0 |= 1; else if (y1 < 0) clip0 |= 2;
		if (x1 > cx1) clip0 |= 4; else if (x1 < 0) clip0 |= 8;
		if (y2 > cy1) clip1 |= 1; else if (y2 < 0) clip1 |= 2;
		if (x2 > cx1) clip1 |= 4; else if (x2 < 0) clip1 |= 8;
		if ((clip0 | clip1) == 0) break;
		if ((clip0 & clip1) != 0) return;
		if (clip0 & 1) { x1 = x1 + int(int64_t(x2 - x1) * (cy1 - y1) / (y2 - y1)); y1 = cy1; continue; }
		if (clip0 & 2) { x1 = x1 + int(int64_t(x2 - x1) * (0 - y1) / (y2 - y1)); y1 = 0; continue; }
		if (clip0 & 4) { y1 = y1 + int(int64_t(y2 - y1) * (cx1 - x1) / (x2 - x1)); x1 = cx1; continue; }
		if (clip0 & 8) { y1 = y1 + int(int64_t(y2 - y1) * (0 - x1) / (x2 - x1)); x1 = 0; continue; }
		if (clip1 & 1) { x2 = x1 + int(int64_t(x2 - x1) * (cy1 - y1) / (y2 - y1)); y2 = cy1; continue; }
		if (clip1 & 2) { x2 = x1 + int(int64_t(x2 - x1) * (0 - y1) / (y2 - y1)); y2 = 0; continue; }
		if (clip1 & 4) { y2 = y1 + int(int64_t(y2 - y1) * (cx1 - x1) / (x2 - x1)); x2 = cx1; continue; }
		if (clip1 & 8) { y2 = y1 + int(int64_t(y2 - y1) * (0 - x1) / (x2 - x1)); x2 = 0; continue; }
	}
	int dx = x2 - x1, dy = y2 - y1;
	if ((dx | dy) == 0) {
		add_rect(float(x1), float(y1), 1, 1);
		return;
	}
	int sx = dx >= 0 ? 1 : -1, ax = dx >= 0 ? dx : -dx;
	int sy = dy >= 0 ? 1 : -1, ay = dy >= 0 ? dy : -dy;
	if (ax > ay) {
		int ddf = -ax, sadj = ax + ax, padj = ay + ay;
		while (ax-- >= 0) {
			add_rect(float(x1), float(y1), 1, 1);
			x1 += sx;
			ddf += padj;
			if (ddf >= 0) { y1 += sy; ddf -= sadj; }
		}
	} else {
		int ddf = -ay, sadj = ay + ay, padj = ax + ax;
		while (ay-- >= 0) {
			add_rect(float(x1), float(y1), 1, 1);
			y1 += sy;
			ddf += padj;
			if (ddf >= 0) { x1 += sx; ddf -= sadj; }
		}
	}
}

void bb_rect(int32_t x, int32_t y, int32_t w, int32_t h, int32_t solid)
{
	if (!active() || (w <= 0) || (h <= 0)) {
		return;
	}
	if (solid) {
		add_rect(float(x), float(y), float(w), float(h));
	} else if ((w <= 2) || (h <= 2)) {
		add_rect(float(x), float(y), float(w), float(h));
	} else {
		add_rect(float(x), float(y), float(w), 1);
		add_rect(float(x), float(y + h - 1), float(w), 1);
		add_rect(float(x), float(y + 1), 1, float(h - 2));
		add_rect(float(x + w - 1), float(y + 1), 1, float(h - 2));
	}
}

void bb_oval(int32_t x, int32_t y, int32_t w, int32_t h, int32_t solid)
{
	if (!active() || (w <= 0) || (h <= 0)) {
		return;
	}
	float cx = float(x) + float(w) / 2, cy = float(y) + float(h) / 2;
	float rx = float(w) / 2, ry = float(h) / 2;
	int   segments = int(ceilf((rx + ry) * 1.5f));
	if (segments < 12) {
		segments = 12;
	}
	const float tau = 6.28318530717958647692f;
	if (solid) {
		vertex* v = add_vertices(OP_TRIANGLES, TEXTURE_WHITE, uint32_t(segments) * 3);
		for (int i = 0; i < segments; i++) {
			float a0 = tau * float(i) / float(segments), a1 = tau * float(i + 1) / float(segments);
			set_vertex(v[i * 3 + 0], cx, cy, 0.5f, 0.5f);
			set_vertex(v[i * 3 + 1], cx + cosf(a0) * rx, cy + sinf(a0) * ry, 0.5f, 0.5f);
			set_vertex(v[i * 3 + 2], cx + cosf(a1) * rx, cy + sinf(a1) * ry, 0.5f, 0.5f);
		}
	} else {
		vertex* v = add_vertices(OP_LINES, TEXTURE_WHITE, uint32_t(segments) * 2);
		for (int i = 0; i < segments; i++) {
			float a0 = tau * float(i) / float(segments), a1 = tau * float(i + 1) / float(segments);
			set_vertex(v[i * 2 + 0], cx + cosf(a0) * (rx - 0.5f), cy + sinf(a0) * (ry - 0.5f), 0.5f, 0.5f);
			set_vertex(v[i * 2 + 1], cx + cosf(a1) * (rx - 0.5f), cy + sinf(a1) * (ry - 0.5f), 0.5f, 0.5f);
		}
	}
}

int32_t bb_string_width(const char* s)
{
	if (font_entry* f = font_of(g.font); f && f->ttf) {
		return ttf_string_width(f->ttf, s);
	}
	return s ? int32_t(float(strlen(s)) * 8 * font_scale() + 0.5f) : 0;
}

int32_t bb_string_height(const char* s)
{
	(void)s;
	return current_height();
}

// Text x, y, string [, center x] [, center y]
void bb_text(int32_t x, int32_t y, const char* s, int32_t center_x, int32_t center_y)
{
	if (!active() || !s || !*s) {
		return;
	}
	size_t length = strlen(s);
	float  scale  = font_scale();
	float  px = float(x), py = float(y);
	if (font_entry* f = font_of(g.font); f && f->ttf) {
		if (center_x) {
			px -= float(ttf_string_width(f->ttf, s)) / 2;
		}
		if (center_y) {
			py -= float(ttf_height(f->ttf)) / 2;
		}
		ttf_draw(f->ttf, floorf(px), floorf(py), s);
		return;
	}
	if (center_x) {
		px -= float(length) * 8 * scale / 2;
	}
	if (center_y) {
		py -= 4 * scale;
	}
	px = floorf(px);
	py = floorf(py);

	vertex* v = add_vertices(OP_TRIANGLES, TEXTURE_FONT, uint32_t(length) * 6);
	for (size_t i = 0; i < length; i++) {
		glyph_vertices(v + i * 6, px + float(i) * 8 * scale, py, int(static_cast<unsigned char>(s[i])), scale);
	}
}

// For the GUI: text in a size of its own, so that gadgets don't change the font that programs draw with. The size is
// the height of a character, which is also how wide it is.
void bb_gui_text(int32_t x, int32_t y, const char* s, int32_t size)
{
	if (!active() || !s || !*s || (size < 1)) {
		return;
	}
	size_t length = strlen(s);
	float  scale  = float(size) / 8.0f;
	vertex* v     = add_vertices(OP_TRIANGLES, TEXTURE_FONT, uint32_t(length) * 6);
	for (size_t i = 0; i < length; i++) {
		glyph_vertices(v + i * 6, float(x) + float(i) * float(size), float(y), int(static_cast<unsigned char>(s[i])), scale);
	}
}

// What size a font was loaded in, 0 for the one that is built in.
int32_t bb_gui_font_size(int32_t font)
{
	font_entry* f = font_of(font);
	return f ? f->height : 0;
}

// Fonts. The name and the style are only remembered: text is always drawn with the built-in font, in the height
// that was asked for.
int32_t bb_load_font(const char* name, int32_t height, int32_t bold, int32_t italic, int32_t underline)
{
	font_entry entry;
	entry.used   = true;
	entry.height = height < 1 ? 1 : height;
	entry.style  = (bold ? 1 : 0) | (italic ? 2 : 0) | (underline ? 4 : 0);
	entry.ttf    = ttf_open(name, entry.height, entry.style);
	if (name) {
		entry.name = static_cast<char*>(malloc(strlen(name) + 1));
		strcpy(entry.name, name);
	}
	for (uint32_t i = 0; i < font_table.size; i++) {
		if (!font_table[i].used) {
			font_table[i] = entry;
			return int32_t(i) + 1;
		}
	}
	font_table.push(entry);
	return int32_t(font_table.size);
}

void bb_set_font(int32_t handle)
{
	if (handle && !font_of(handle)) {
		bb_runtime_error("SetFont: the font does not exist.");
	}
	g.font = handle;
}

void bb_free_font(int32_t handle)
{
	if (!handle) {
		return;
	}
	font_entry* f = font_of(handle);
	if (!f) {
		bb_runtime_error("FreeFont: the font does not exist.");
	}
	free(f->name);
	ttf_free(f->ttf);
	*f = font_entry();
	if (g.font == handle) {
		g.font = 0;
	}
}

// The bitmap font is scaled, so all its characters are as wide as it is high.
int32_t bb_font_width(void)
{
	return current_width();
}

int32_t bb_font_height(void)
{
	return current_height();
}

static font_entry* need_font(int32_t handle, const char* what)
{
	font_entry* f = font_of(handle);
	if (!f) {
		char message[96];
		snprintf(message, sizeof(message), "%s: the font does not exist.", what);
		bb_runtime_error(message);
	}
	return f;
}

const char* bb_font_name(int32_t handle)
{
	const char* name = need_font(handle, "FontName")->name;
	char*       copy = static_cast<char*>(malloc(strlen(name ? name : "") + 1));
	strcpy(copy, name ? name : "");
	return copy;
}

int32_t bb_font_size(int32_t handle)
{
	return need_font(handle, "FontSize")->height;
}

int32_t bb_font_style(int32_t handle)
{
	return need_font(handle, "FontStyle")->style;
}

int32_t bb_font_ascent(int32_t handle)
{
	font_entry* f = need_font(handle, "FontAscent");
	return f->ttf ? ttf_ascent(f->ttf) : f->height * 3 / 4;
}

int32_t bb_font_descent(int32_t handle)
{
	font_entry* f = need_font(handle, "FontDescent");
	return f->ttf ? ttf_descent(f->ttf) : f->height - f->height * 3 / 4;
}

// Origin x, y: where 0, 0 is for what is drawn after.
void bb_origin(int32_t x, int32_t y)
{
	g.origin_x = x;
	g.origin_y = y;
}

// Viewport x, y, width, height: drawing is limited to this part of the buffer.
void bb_viewport(int32_t x, int32_t y, int32_t w, int32_t h)
{
	if (!active()) {
		return;
	}
	target_ref target = resolve_target(g.target);
	int        x1     = x + w, y1 = y + h;
	x                 = x < 0 ? 0 : x;
	y                 = y < 0 ? 0 : y;
	x1                = x1 > target.w ? target.w : x1;
	y1                = y1 > target.h ? target.h : y1;
	g.view_x          = x;
	g.view_y          = y;
	g.view_w          = x1 > x ? x1 - x : 0;
	g.view_h          = y1 > y ? y1 - y : 0;
}

// Locate x, y: where Print and Write continue, in the window.
void bb_locate(int32_t x, int32_t y)
{
	if (!g.created) {
		return;
	}
	gpu_image& front = g.buffers[0];
	int        w = front.width ? int(front.width) : int(g.width), h = front.height ? int(front.height) : int(g.height);
	g.cursor_x = x < 0 ? 0 : (x > w ? w : x);
	g.cursor_y = y < 0 ? 0 : (y > h ? h : y);
}

extern "C" char* bb_copy(const char* data, size_t length);

namespace {
	// Print, Write and Input draw on the front buffer from the top left, whatever the program set up, and put all of
	// it back when they are done.
	struct front_drawing {
		int     target, ox, oy, vx, vy, vw, vh;
		uint8_t color[3];

		front_drawing() : target(g.target), ox(g.origin_x), oy(g.origin_y), vx(g.view_x), vy(g.view_y), vw(g.view_w), vh(g.view_h)
		{
			memcpy(color, g.color, 3);
			g.target   = front_buffer;
			g.origin_x = g.origin_y = g.view_x = g.view_y = 0;
			g.view_w = g.view_h = -1;
		}

		~front_drawing()
		{
			g.target   = target;
			g.origin_x = ox;
			g.origin_y = oy;
			g.view_x   = vx;
			g.view_y   = vy;
			g.view_w   = vw;
			g.view_h   = vh;
			memcpy(g.color, color, 3);
		}
	};
} // namespace

// Print and Write show their text in the window, from where Locate put the cursor, on the front buffer. Returns 0 if
// there is no window to show it in.
int32_t bb_screen_print(const char* s, int32_t newline)
{
	if (!active()) {
		return 0;
	}
	int        height = current_height();
	gpu_image& front  = g.buffers[0];
	int        width = int(front.width), screen = int(front.height);

	front_drawing drawing;
	int           scroll = g.cursor_y + height - screen;
	if (scroll > 0) {
		g.cursor_y = screen - height;
		bb_copy_rect(0, scroll, width, screen - scroll, 0, 0, front_buffer, front_buffer);
		memcpy(g.color, g.clscolor, 3);
		add_rect(0, float(screen - scroll), float(width), float(scroll));
		memcpy(g.color, drawing.color, 3);
	}
	if (s && *s) {
		bb_text(g.cursor_x, g.cursor_y, s, 0, 0);
	}
	if (newline) {
		g.cursor_x = 0;
		g.cursor_y += height;
	} else {
		g.cursor_x += bb_string_width(s);
	}
	return 1;
}

// Input shows its prompt and what is typed in the window like Print does, with a blinking block as the cursor, and gives
// back the line once Return is pressed. Escape clears it, and the cursor keys, Home, End, Backspace and Delete edit it.
// Returns null if there is no window to do it in.
const char* bb_screen_input(const char* prompt)
{
	if (!active()) {
		return nullptr;
	}
	bb_screen_print(prompt, 0);

	constexpr int capacity = 1024;
	int           height   = current_height();
	int           width    = int(g.buffers[0].width);
	int           x        = g.cursor_x, y = g.cursor_y;

	// What is behind the line is kept, so that it can be put back whenever the line changes.
	int behind = bb_create_image(width, height, 1);
	bb_copy_rect(0, y, width, height, 0, 0, front_buffer, bb_image_buffer(behind, 0));

	char          line[capacity + 1] = {};
	int           length = 0, cursor = 0, phase = -1;
	Uint64        start   = SDL_GetTicks();
	bool          changed = true, done = false;
	front_drawing drawing;

	while (!done) {
		bb_graphics_idle();
		Uint64 now = SDL_GetTicks();

		// The codes are the ones GetKey gives: 1 Home, 2 End, 4 Delete, 30 Right and 31 Left, the rest edits as typed.
		while (int key = bb_get_key()) {
			changed = true;
			if (key == 13) {
				done = true;
				break;
			} else if (key == 8) {
				if (cursor) {
					memmove(line + cursor - 1, line + cursor, size_t(length - cursor + 1));
					cursor--, length--;
				}
			} else if (key == 27) {
				line[0] = 0;
				cursor = length = 0;
			} else if (key == 4) {
				if (cursor < length) {
					memmove(line + cursor, line + cursor + 1, size_t(length - cursor));
					length--;
				}
			} else if (key == 1) {
				cursor = 0;
			} else if (key == 2) {
				cursor = length;
			} else if (key == 31) {
				cursor -= cursor ? 1 : 0;
			} else if (key == 30) {
				cursor += (cursor < length) ? 1 : 0;
			} else if ((key >= 32) && (length < capacity)) {
				memmove(line + cursor + 1, line + cursor, size_t(length - cursor + 1));
				line[cursor++] = char(key);
				length++;
			}
		}

		int blink = int(((now - start) / 320) & 1);
		if (!changed && (blink == phase)) {
			SDL_Delay(5);
			continue;
		}
		changed = false;
		phase   = blink;

		bb_copy_rect(0, 0, width, height, 0, y, bb_image_buffer(behind, 0), front_buffer);
		bb_text(x, y, line, 0, 0);
		if (!blink && !done) {
			char under   = line[cursor];
			line[cursor] = 0;
			int cx       = x + bb_string_width(line);
			line[cursor] = under;
			for (int c = 0; c < 3; c++) {
				g.color[c] = uint8_t(g.clscolor[c] ^ 0xFF);
			}
			bb_rect(cx, y, current_width(), height, 1);
			if (under) {
				char shown[2] = { under, 0 };
				memcpy(g.color, g.clscolor, 3);
				bb_text(cx, y, shown, 0, 0);
			}
			memcpy(g.color, drawing.color, 3);
		}
	}

	bb_free_image(behind);
	g.cursor_x = 0;
	g.cursor_y = y + height;
	return bb_copy(line, size_t(length));
}

int32_t bb_live_fonts(void)
{
	int32_t count = 0;
	for (uint32_t i = 0; i < font_table.size; i++) {
		count += font_table[i].used ? 1 : 0;
	}
	return count;
}
