void bb_cls(void)
{
	if (!active()) {
		return;
	}
	operation& op = add_operation(OP_CLEAR, 0, 0);
	op.color[0]   = g.clscolor[0] / 255.0f;
	op.color[1]   = g.clscolor[1] / 255.0f;
	op.color[2]   = g.clscolor[2] / 255.0f;
	op.color[3]   = 1.0f;
}

