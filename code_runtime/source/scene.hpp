	/** Asks for the cache line at an address to be loaded, which is a hint and changes nothing else. */
	inline void prefetch(const void* address)
	{
#if defined(_MSC_VER) && (defined(_M_X64) || defined(_M_IX86))
		_mm_prefetch(static_cast<const char*>(address), _MM_HINT_T0);
#elif defined(__GNUC__) || defined(__clang__)
		__builtin_prefetch(address);
#else
		(void)address;
#endif
	}

	// A growable array for plain data, which avoids needing the C++ standard library in programs.
	template<typename T>
	struct buffer {
		T*       data = nullptr;
		uint32_t size = 0;
		uint32_t cap  = 0;

		T& operator[](uint32_t index) { return data[index]; }
		T const& operator[](uint32_t index) const { return data[index]; }

		void reserve(uint32_t count)
		{
			if (count > cap) {
				// In 64 bits: the doubling and the size in bytes can be more than 32 bits, and a failed allocation is not a buffer to write to.
				uint64_t grown = cap ? uint64_t(cap) * 2 : 16;
				grown          = grown > count ? grown : count;
				grown          = grown > UINT32_MAX ? uint64_t(UINT32_MAX) : grown;
				uint64_t bytes = grown * sizeof(T);
				void*    made  = (bytes > SIZE_MAX) ? nullptr : bb_realloc(data, size_t(bytes));
				if (!made) {
					bb_runtime_error("Out of memory.");
				}
				cap  = uint32_t(grown);
				data = static_cast<T*>(made);
			}
		}

		void push(T const& value)
		{
			reserve(size + 1);
			data[size++] = value;
		}

		void clear() { size = 0; }

		void release()
		{
			bb_free(data);
			data = nullptr;
			size = cap = 0;
		}
	};

