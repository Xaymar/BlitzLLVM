#pragma once
// A few threads that split work over ranges, for work that is the same for every element: BLITZLLVM_THREADS is how many threads work (the one
// that asks included, 1 turns it off), by default half of the cores, at most 8. Only the thread that renders asks for work.

#include <algorithm>
#include <condition_variable>
#include <cstdint>
#include <mutex>
#include <thread>

#include "environment.h"

namespace bb {
	class work_pool {
	public:
		work_pool()
		{
			uint32_t cores = std::thread::hardware_concurrency();
			int32_t  total = bb_env_int("BLITZLLVM_THREADS", int32_t(cores / 2 < 8 ? cores / 2 : 8));
			count_         = total < 1 ? 1 : (total > 16 ? 16 : uint32_t(total));
			for (uint32_t i = 1; i < count_; i++) {
				// They wait for work for as long as the program lives and are not joined: the pool is never destroyed.
				std::thread([this, i] { loop(i); }).detach();
			}
		}

		uint32_t count() const { return count_; }

		/** How many parts a range of that many elements is worth splitting into, with at least grain elements in each: 1 means do it yourself. */
		uint32_t parts(uint32_t elements, uint32_t grain) const
		{
			uint32_t most = grain ? elements / grain : elements;
			return std::max(1u, std::min(count_, most));
		}

		/** Calls work(part, first, last) for every one of the parts of [0, elements), on all threads, and returns when all are done. */
		template <class F> void split(uint32_t parts, uint32_t elements, F&& work)
		{
			if (parts <= 1) {
				work(0u, 0u, elements);
				return;
			}
			auto each = [&](uint32_t thread) {
				for (uint32_t part = thread; part < parts; part += count_) {
					work(part, uint32_t(uint64_t(elements) * part / parts), uint32_t(uint64_t(elements) * (part + 1) / parts));
				}
			};
			run(&call<decltype(each)>, &each);
		}

	private:
		template <class F> static void call(uint32_t thread, void* user) { (*static_cast<F*>(user))(thread); }

		void run(void (*job)(uint32_t, void*), void* user)
		{
			std::lock_guard<std::mutex> only(run_lock_);
			{
				std::lock_guard<std::mutex> lock(mutex_);
				job_       = job;
				user_      = user;
				remaining_ = count_ - 1;
				generation_++;
			}
			start_.notify_all();
			job(0, user);
			std::unique_lock<std::mutex> lock(mutex_);
			done_.wait(lock, [this] { return remaining_ == 0; });
		}

		void loop(uint32_t thread)
		{
			uint64_t seen = 0;
			for (;;) {
				void (*job)(uint32_t, void*);
				void* user;
				{
					std::unique_lock<std::mutex> lock(mutex_);
					start_.wait(lock, [&] { return generation_ != seen; });
					seen = generation_;
					job  = job_;
					user = user_;
				}
				job(thread, user);
				{
					std::lock_guard<std::mutex> lock(mutex_);
					remaining_--;
				}
				done_.notify_all();
			}
		}

		uint32_t                count_ = 1;
		std::mutex              run_lock_, mutex_;
		std::condition_variable start_, done_;
		uint64_t                generation_ = 0;
		uint32_t                remaining_  = 0;
		void (*job_)(uint32_t, void*)       = nullptr;
		void* user_                         = nullptr;
	};

	inline work_pool& pool()
	{
		static work_pool* made = new work_pool();
		return *made;
	}
} // namespace bb
