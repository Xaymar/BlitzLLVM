// Which backend of the rendering hardware interface draws: BLITZLLVM_RENDERER asks for one, and without it (or with "auto") the first
// one that this build has is taken. Only Vulkan is built so far, so asking for another one ends the program with a message.
#include "graphics_internal.hpp"
#include "environment.h"

namespace bb::rhi {
	namespace {
		const char* name_of(backend which)
		{
			switch (which) {
			case backend::vulkan: return "vulkan";
			case backend::d3d11: return "d3d11";
			case backend::opengl: return "opengl";
			default: return "";
			}
		}

		// What the name of BLITZLLVM_RENDERER stands for; none for "auto", for nothing and for a name that is not known.
		backend asked_backend()
		{
			const char* wanted = bb_env("BLITZLLVM_RENDERER");
			if (!wanted || !wanted[0] || !SDL_strcasecmp(wanted, "auto")) {
				return backend::none;
			}
			for (backend which : { backend::vulkan, backend::d3d11, backend::opengl }) {
				if (!SDL_strcasecmp(wanted, name_of(which))) {
					return which;
				}
			}
			fprintf(stderr, "warning: BLITZLLVM_RENDERER=%s is not a renderer (auto, vulkan, d3d11, opengl); the renderer is picked as for auto.\n", wanted);
			return backend::none;
		}
	} // namespace

	bool backend_built(backend which)
	{
		return which == backend::vulkan;
	}

	backend selected_backend()
	{
		static const backend selected = [] {
			backend asked = asked_backend();
			if (asked == backend::none) {
				return backend::vulkan; // The order of auto, as far as it goes yet.
			}
			if (!backend_built(asked)) {
				char message[160];
				snprintf(message, sizeof(message), "BLITZLLVM_RENDERER=%s: this build of the runtime has no %s renderer.", name_of(asked), name_of(asked));
				bb::gfx::fail(message);
			}
			return asked;
		}();
		return selected;
	}

	uint64_t window_flags()
	{
		switch (selected_backend()) {
		case backend::vulkan: return SDL_WINDOW_VULKAN;
		default: return 0;
		}
	}

	const char* backend_name()
	{
		return name_of(selected_backend());
	}
} // namespace bb::rhi

extern "C" const char* bb_renderer_name(void)
{
	return bb::rhi::backend_name();
}
