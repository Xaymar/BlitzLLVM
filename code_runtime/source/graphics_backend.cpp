// Which backend of the rendering hardware interface draws: BLITZLLVM_RENDERER asks for one, and without it (or with "auto") the first
// one that this build has is taken, which is Vulkan. Asking for one that this build does not have ends the program with a message.
// The calls of the backends go through a table (rhi_backend.hpp); the functions at the end of this file call through it.
#include "rhi_backend.hpp"
#include "environment.h"

namespace bb::rhi {
	namespace {
		const char* name_of(backend which)
		{
			switch (which) {
			case backend::vulkan: return "vulkan";
			case backend::d3d11: return "d3d11";
			case backend::opengl: return "opengl";
			default: return "";
			}
		}

		// What the name of BLITZLLVM_RENDERER stands for; none for "auto", for nothing and for a name that is not known.
		backend asked_backend()
		{
			const char* wanted = bb_env("BLITZLLVM_RENDERER");
			if (!wanted || !wanted[0] || !SDL_strcasecmp(wanted, "auto")) {
				return backend::none;
			}
			for (backend which : { backend::vulkan, backend::d3d11, backend::opengl }) {
				if (!SDL_strcasecmp(wanted, name_of(which))) {
					return which;
				}
			}
			fprintf(stderr, "warning: BLITZLLVM_RENDERER=%s is not a renderer (auto, vulkan, d3d11, opengl); the renderer is picked as for auto.\n", wanted);
			return backend::none;
		}
	} // namespace

	namespace {
		// The table of a backend, null for one that this build does not have.
		const backend_table* table_of(backend which)
		{
			switch (which) {
			case backend::vulkan: return &vulkan_backend;
#ifdef BB_OPENGL
			case backend::opengl: return &opengl_backend;
#endif
#ifdef BB_D3D11_SHADERS
			case backend::d3d11: return &d3d11_backend;
#endif
			default: return nullptr;
			}
		}
	} // namespace

	bool backend_built(backend which)
	{
		return table_of(which) != nullptr;
	}

	backend selected_backend()
	{
		static const backend selected = [] {
			backend asked = asked_backend();
			if (asked == backend::none) {
				asked = backend::vulkan; // The order of auto, as far as it goes yet.
			}
			if (!backend_built(asked)) {
				char message[160];
				snprintf(message, sizeof(message), "BLITZLLVM_RENDERER=%s: this build of the runtime has no %s renderer.", name_of(asked), name_of(asked));
				bb::gfx::fail(message);
			}
			active_backend = table_of(asked); // From here on every call of rhi_backend.inc goes to it.
			return asked;
		}();
		return selected;
	}

	uint64_t window_flags()
	{
		switch (selected_backend()) {
		case backend::vulkan: return SDL_WINDOW_VULKAN;
		case backend::opengl:
			// The context that the backend makes has to fit the windows, so what it asks for is set before any window is made.
			SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
			SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 4);
			SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 3);
			SDL_GL_SetAttribute(SDL_GL_CONTEXT_FLAGS, bb_env_bool("BLITZLLVM_DEBUG_OPENGL", 0) ? SDL_GL_CONTEXT_DEBUG_FLAG : 0);
			SDL_GL_SetAttribute(SDL_GL_DEPTH_SIZE, 0);
			SDL_GL_SetAttribute(SDL_GL_DOUBLEBUFFER, 1);
			return SDL_WINDOW_OPENGL;
		default: return 0;
		}
	}

	const char* backend_name()
	{
		return name_of(selected_backend());
	}
} // namespace bb::rhi

extern "C" const char* bb_renderer_name(void)
{
	return bb::rhi::backend_name();
}

