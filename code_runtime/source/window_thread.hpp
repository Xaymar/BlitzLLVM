// The thread of the window system. On Windows, grabbing the title bar of a window starts a loop inside the call that handles the messages of
// the window, and that call only returns once the mouse is let go. When the program's own thread handles them (it does, in pump), the program
// stops for as long as a window is dragged or resized. So the windows belong to a thread of their own: it starts SDL's video and event systems,
// makes and destroys every window, and handles their messages, and the program's thread takes the events it put in SDL's queue. What the
// program asks of a window (size, title, grab) goes straight to the window and Windows passes it on. Only what has to be done by the thread
// of the window system (starting and quitting video, making and destroying a window) is handed over with run and waited for; such a call
// waits while a window is being dragged, which a program rarely does at that moment.
//
// On by default on Windows, where the loop exists. BLITZLLVM_WINDOW_THREAD=1 turns it on elsewhere (the tests do, to keep it working), and
// =0 turns it off on Windows.

#pragma once

#include <SDL3/SDL.h>
#include <utility>

namespace bb::wnd {
	// True if the windows belong to the thread of the window system.
	bool enabled();

	// Runs the function on the thread of the window system and returns when it is done; where there is no such thread, or on it, it is
	// called right here.
	void run(void (*function)(void*), void* data);

	template<typename F>
	void run(F&& function)
	{
		run([](void* f) { (*static_cast<std::remove_reference_t<F>*>(f))(); }, &function);
	}

	// SDL_InitSubSystem and SDL_QuitSubSystem, on the thread that has to own what they start.
	bool init(SDL_InitFlags flags);
	void quit(SDL_InitFlags flags);

	// SDL_CreateWindow and SDL_DestroyWindow, likewise: a window handles its messages on the thread that made it.
	SDL_Window* create_window(const char* title, int width, int height, SDL_WindowFlags flags);
	void        destroy_window(SDL_Window* window);

	// SDL_SetWindowSize and SDL_SyncWindow: on the window system's thread, where the size is applied and the events it makes are queued
	// before the call returns, as they were when the program's thread did the window system's work itself.
	void set_window_size(SDL_Window* window, int width, int height);
	void sync_window(SDL_Window* window);

	// SDL_ShowCursor/SDL_HideCursor, SDL_SetCursor and SDL_SetWindowRelativeMouseMode, on the thread that owns the windows. Windows
	// keeps the pointer of each thread apart: a SetCursor from the program's thread does not change the pointer over a window of
	// another thread, which only changes when the window is asked again, on the next movement of the mouse (and not at all while the
	// mouse is held in the middle of the window, as MoveMouse and the mouse speeds do).
	void set_cursor_visible(bool visible);
	void set_cursor(SDL_Cursor* cursor);
	void set_relative_mouse_mode(SDL_Window* window, bool enabled);

	// The next event the thread of the window system has queued, like SDL_PollEvent, and a wait of up to the milliseconds for one to come.
	bool poll_event(SDL_Event* event);
	void wait_event(int milliseconds);
} // namespace bb::wnd
