int32_t bb_create_cube(int32_t parent)
{
	int mesh = new_mesh(parent);
	make_cube(surface_of(new_surface(mesh)));
	return mesh;
}

int32_t bb_create_sphere(int32_t segments, int32_t parent)
{
	int mesh = new_mesh(parent);
	make_sphere(surface_of(new_surface(mesh)), clamp_segments(segments));
	return mesh;
}

int32_t bb_create_cylinder(int32_t segments, int32_t solid, int32_t parent)
{
	int mesh = new_mesh(parent);
	make_round(surface_of(new_surface(mesh)), clamp_segments(segments), solid != 0, false);
	return mesh;
}

int32_t bb_create_cone(int32_t segments, int32_t solid, int32_t parent)
{
	int mesh = new_mesh(parent);
	make_round(surface_of(new_surface(mesh)), clamp_segments(segments), solid != 0, true);
	return mesh;
}

int32_t bb_create_mesh(int32_t parent)
{
	return new_mesh(parent);
}

int32_t bb_create_surface(int32_t mesh, int32_t brush)
{
	int32_t handle = new_surface(mesh);
	if (brush) {
		bb_paint_surface(handle, brush);
	}
	return handle;
}

int32_t bb_add_vertex(int32_t handle, float x, float y, float z, float u, float v, float w)
{
	(void)w;
	return int32_t(add_vertex(need_surface(handle, "AddVertex"), x, y, z, 0, 0, 0, u, v));
}

int32_t bb_add_triangle(int32_t handle, int32_t a, int32_t b, int32_t c)
{
	surface* s = need_surface(handle, "AddTriangle");
	uint32_t n = s->vertices.size;
	if ((a < 0) || (b < 0) || (c < 0) || (uint32_t(a) >= n) || (uint32_t(b) >= n) || (uint32_t(c) >= n)) {
		bb_runtime_error("AddTriangle: vertex index out of range.");
		exit(1);
	}
	s->indices.push(uint32_t(a));
	s->indices.push(uint32_t(b));
	s->indices.push(uint32_t(c));
	s->dirty = true;
	return int32_t(s->indices.size / 3) - 1;
}

void bb_vertex_color(int32_t handle, int32_t index, float r, float g, float b, float a)
{
	vertex3d& v = vertex_of(handle, index, "VertexColor");
	v.r = uint8_t(clamp255(r) * 255 + 0.5f);
	v.g = uint8_t(clamp255(g) * 255 + 0.5f);
	v.b = uint8_t(clamp255(b) * 255 + 0.5f);
	v.a = uint8_t((a < 0 ? 0 : (a > 1 ? 1 : a)) * 255 + 0.5f);
}

void bb_vertex_normal(int32_t handle, int32_t index, float x, float y, float z)
{
	vertex3d& v = vertex_of(handle, index, "VertexNormal");
	v.nx = x;
	v.ny = y;
	v.nz = z;
}

void bb_vertex_tex_coords(int32_t handle, int32_t index, float u, float v, float w, int32_t set)
{
	(void)w;
	(void)set;
	vertex3d& vert = vertex_of(handle, index, "VertexTexCoords");
	vert.u = u;
	vert.v = v;
}

void bb_update_normals(int32_t mesh)
{
	entity* e = need_kind(mesh, MESH, "UpdateNormals");
	for (uint32_t i = 0; i < e->surfaces.size; i++) {
		update_normals(e->surfaces[i]);
	}
}

void bb_flip_mesh(int32_t mesh)
{
	entity* e = need_kind(mesh, MESH, "FlipMesh");
	for (uint32_t i = 0; i < e->surfaces.size; i++) {
		surface* s = e->surfaces[i];
		for (uint32_t t = 0; t + 2 < s->indices.size; t += 3) {
			uint32_t tmp       = s->indices[t + 1];
			s->indices[t + 1]  = s->indices[t + 2];
			s->indices[t + 2]  = tmp;
		}
		for (uint32_t v = 0; v < s->vertices.size; v++) {
			s->vertices[v].nx = -s->vertices[v].nx;
			s->vertices[v].ny = -s->vertices[v].ny;
			s->vertices[v].nz = -s->vertices[v].nz;
		}
		s->dirty = true;
	}
}

void bb_scale_mesh(int32_t mesh, float x, float y, float z)
{
	float arg[3] = { x, y, z };
	transform_mesh(mesh, "ScaleMesh", [](float* p, const float* a) { p[0] *= a[0]; p[1] *= a[1]; p[2] *= a[2]; }, arg);
}

void bb_position_mesh(int32_t mesh, float x, float y, float z)
{
	float arg[3] = { x, y, z };
	transform_mesh(mesh, "PositionMesh", [](float* p, const float* a) { p[0] += a[0]; p[1] += a[1]; p[2] += a[2]; }, arg);
}

void bb_rotate_mesh(int32_t mesh, float pitch, float yaw, float roll)
{
	float angles[3] = { pitch, yaw, roll };
	entity* e       = need_kind(mesh, MESH, "RotateMesh");
	float   r[9];
	rotation_matrix(r, angles);
	for (uint32_t i = 0; i < e->surfaces.size; i++) {
		surface* s = e->surfaces[i];
		for (uint32_t v = 0; v < s->vertices.size; v++) {
			vertex3d& vert = s->vertices[v];
			float     p[3] = { vert.x, vert.y, vert.z }, n[3] = { vert.nx, vert.ny, vert.nz };
			for (int row = 0; row < 3; row++) {
				(&vert.x)[row]  = r[0 + row] * p[0] + r[3 + row] * p[1] + r[6 + row] * p[2];
				(&vert.nx)[row] = r[0 + row] * n[0] + r[3 + row] * n[1] + r[6 + row] * n[2];
			}
		}
		s->dirty = true;
	}
}

