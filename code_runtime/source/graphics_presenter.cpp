// More windows than the one of Graphics. Each has its own SDL window, Vulkan surface and swapchain (a surface_state), while the
// device, the queue and everything the GPU draws with stay shared. Nothing in the program makes one yet: BlitzPlus windows

// A presenter: the thread of a window that shows the newest finished picture of the window whenever there is one, or the window
// asks for it (it was uncovered or resized), at the pace of the display the window is on. The program never waits for it, and it
// never waits for the program: the pictures are three (a triple buffer). The program draws into one, the newest finished one
// waits to be shown, and the thread shows one; a handover makes the drawn one the newest and takes the free one to draw into
// next, so a program that draws faster than the display only has its newest picture shown, and one that draws slower has its
// last picture shown again whenever the window needs it. The thread only ever touches the pictures, the swapchain and the queue:
// it knows nothing of gadgets or the drawing state (which belongs to the thread of the program), so nothing there needs a lock.
// This is what the windows of BlitzPlus and their canvases show with (see BLITZLLVM_TEST_PRESENTERS). The thread makes the swapchain
// again itself when the window changed its size, so the window shows its last picture, stretched, at once, and not only once the
// program looks at its events again: until then, the new part of a window that grows would stay black.
//
// The pictures are images, so the program draws into one with SetBuffer and the 2D commands, as it does into the BackBuffer. A
// handover sends what was drawn with a timeline semaphore signal of its number, which the blit of the thread waits for on the GPU,
// so neither thread waits for the other.
//
// A present of one window must never hold up another window or Graphics. So the thread has a queue of its own where the device
// has more than one (else it shares queue 0 under its lock), its swapchain never waits for the display (MAILBOX, or IMMEDIATE),
// and it paces itself to the display outside of any lock: with vkWaitForPresentKHR where the driver has it, otherwise with a
// timer at the refresh rate of the display the window is on.

