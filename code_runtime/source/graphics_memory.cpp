// The memory of every buffer and image comes from VulkanMemoryAllocator, which lives in this file: its implementation is
// compiled here and nowhere else. The Vulkan functions are not linked (SDL loads the loader at runtime), so VMA gets the two
// functions it needs to look up the rest.
