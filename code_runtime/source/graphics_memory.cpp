// The memory of every buffer and image comes from VulkanMemoryAllocator, which lives in this file: its implementation is
// compiled here and nowhere else. The Vulkan functions are not linked (SDL loads the loader at runtime), so VMA gets the two
// functions it needs to look up the rest.
#define VMA_IMPLEMENTATION
#define VMA_STATIC_VULKAN_FUNCTIONS 0
#define VMA_DYNAMIC_VULKAN_FUNCTIONS 1
#define VMA_VULKAN_VERSION 1003000
// A program must not stop because of what the allocator checks: allocations that were not freed are reported when profiling (see
// destroy_allocator), and the checks of its own use of Vulkan are for its developers.
#define VMA_ASSERT(expr)
#include "graphics_internal.hpp"

namespace bb::gfx {
	void create_allocator(PFN_vkGetInstanceProcAddr get_instance_proc)
	{
		VmaVulkanFunctions functions    = {};
		functions.vkGetInstanceProcAddr = get_instance_proc;
		functions.vkGetDeviceProcAddr   = vkGetDeviceProcAddr;

		VmaAllocatorCreateInfo info = {};
		info.vulkanApiVersion       = VK_API_VERSION_1_3;
		info.instance               = g.instance;
		info.physicalDevice         = g.physical;
		info.device                 = g.device;
		info.pVulkanFunctions       = &functions;
		check(vmaCreateAllocator(&info, &g.allocator), "vmaCreateAllocator");
	}

	void destroy_allocator()
	{
		if (!g.allocator) {
			return;
		}
		if (profile_enabled) {
			// Everything is destroyed by now, so what is left was never given back.
			VmaTotalStatistics stats;
			vmaCalculateStatistics(g.allocator, &stats);
			if (stats.total.statistics.allocationCount) {
				fprintf(stderr, "GPU memory leak: %u allocations (%llu bytes) were not freed.\n", unsigned(stats.total.statistics.allocationCount), static_cast<unsigned long long>(stats.total.statistics.allocationBytes));
			}
		}
		vmaDestroyAllocator(g.allocator);
		g.allocator = VK_NULL_HANDLE;
	}

	void create_buffer(VkDeviceSize size, VkBufferUsageFlags usage, bool host, VkBuffer& buffer, VmaAllocation& allocation, void** mapped)
	{
		VkBufferCreateInfo info = { VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO };
		info.size               = size;
		info.usage              = usage;
		info.sharingMode        = VK_SHARING_MODE_EXCLUSIVE;

		VmaAllocationCreateInfo alloc = {};
		alloc.usage                   = VMA_MEMORY_USAGE_AUTO;
		if (host) {
			// Mapped for as long as the buffer lives, and coherent so that writes and reads need no flush or invalidate.
			alloc.flags         = VMA_ALLOCATION_CREATE_HOST_ACCESS_RANDOM_BIT | VMA_ALLOCATION_CREATE_MAPPED_BIT;
			alloc.requiredFlags = VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
		} else {
			alloc.requiredFlags = VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT;
		}
		VmaAllocationInfo result;
		check(vmaCreateBuffer(g.allocator, &info, &alloc, &buffer, &allocation, &result), "vmaCreateBuffer");
		if (mapped) {
			*mapped = result.pMappedData;
		}
	}

	void destroy_buffer(VkBuffer& buffer, VmaAllocation& allocation)
	{
		if (buffer) {
			vmaDestroyBuffer(g.allocator, buffer, allocation);
		}
		buffer     = VK_NULL_HANDLE;
		allocation = VK_NULL_HANDLE;
	}
} // namespace bb::gfx
