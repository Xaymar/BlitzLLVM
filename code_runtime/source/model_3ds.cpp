	uint32_t u8(reader& r)
	{
		uint32_t v = 0;
		if (r.have(1)) {
			v = r.data[r.pos++];
		}
		return v;
	}

	uint32_t u16(reader& r)
	{
		uint32_t v = 0;
		if (r.have(2)) {
			v = r.data[r.pos] | (r.data[r.pos + 1] << 8);
			r.pos += 2;
		}
		return v;
	}

	uint32_t u32(reader& r)
	{
		uint32_t v = 0;
		if (r.have(4)) {
			v = uint32_t(r.data[r.pos]) | (uint32_t(r.data[r.pos + 1]) << 8) | (uint32_t(r.data[r.pos + 2]) << 16) | (uint32_t(r.data[r.pos + 3]) << 24);
			r.pos += 4;
		}
		return v;
	}

	// Calls the function with the id of each chunk from here to the end, and the reader at the start of its contents.
	template<typename F>
	void each_chunk(reader& r, size_t end, F&& function)
	{
		while ((r.pos + 6 <= end) && !r.failed) {
			size_t   start = r.pos;
			uint32_t id    = u16(r);
			uint32_t size  = u32(r);
			if ((size < 6) || (start + size > end)) {
				r.failed = true;
				return;
			}
			function(id, start + size);
			r.pos = start + size;
		}
	}

	// A value over time: for each key its frame and then the numbers of the key.
	struct track {
		int           width = 0;
		buffer<float> data;
		uint32_t      count() const { return width ? data.size / uint32_t(width + 1) : 0; }
		const float*  at(uint32_t key) const { return data.data + size_t(key) * size_t(width + 1); }
	};

	struct material3ds {
		char* name = nullptr;
		float diffuse[3] = { 0.8f, 0.8f, 0.8f };
		float shininess = 0, strength = 1;
		float transparency = 0, self_illum = 0;
		bool  two_sided = false, additive = false, flat = false;
		char* map = nullptr;
		int   map_flags = 0;
		float tile[2] = { 1, 1 }, offset[2] = { 0, 0 }, angle = 0;
	};

	struct mesh3ds {
		buffer<float>    vertices; // 3 per vertex
		buffer<float>    uvs;      // 2 per vertex, or none
		buffer<uint16_t> faces;    // 3 per face
		buffer<uint32_t> smoothing;
		buffer<int>      face_material;
	};

	struct object3ds {
		char*   name = nullptr;
		int     kind = 0; // 0 = mesh, 1 = light, 2 = camera
		mesh3ds mesh;
		// Lights and cameras
		float   position[3] = { 0, 0, 0 }, target[3] = { 0, 0, 0 };
		bool    has_target = false, off = false;
		float   color[3] = { 1, 1, 1 }, multiplier = 1, range = 0, hotspot = 0, falloff = 0, bank = 0;
	};

	struct node3ds {
		uint32_t tag = 0;
		int      id = -1, parent = -1; // The id of another node, or -1
		uint32_t flags = 0;
		char*    name = nullptr;
		char*    instance = nullptr;
		track    pos, rot, scale, roll, color, hot, fall;
		int      object = -1;
		int      target = -1; // The node that a light or camera looks at
		int      made = -1;   // The node of the model
		float    world[16];   // Where it is in the first frame.
		bool     placed = false;
	};

	struct scene3ds {
		buffer<material3ds*> materials;
		buffer<object3ds*>   objects;
		buffer<node3ds*>     nodes;
		float                first = 0, last = 0;
		bool                 has_range = false;

		~scene3ds() {}

		void release()
		{
			for (uint32_t i = 0; i < materials.size; i++) {
				bb_free(materials[i]->name);
				bb_free(materials[i]->map);
				delete materials[i];
			}
			for (uint32_t i = 0; i < objects.size; i++) {
				object3ds* o = objects[i];
				bb_free(o->name);
				o->mesh.vertices.release();
				o->mesh.uvs.release();
				o->mesh.faces.release();
				o->mesh.smoothing.release();
				o->mesh.face_material.release();
				delete o;
			}
			for (uint32_t i = 0; i < nodes.size; i++) {
				node3ds* n = nodes[i];
				bb_free(n->name);
				bb_free(n->instance);
				n->pos.data.release();
				n->rot.data.release();
				n->scale.data.release();
				n->roll.data.release();
				n->color.data.release();
				n->hot.data.release();
				n->fall.data.release();
				delete n;
			}
			materials.release();
			objects.release();
			nodes.release();
		}
	};

