// Loading .3ds files of 3D Studio into a model (see model_internal.hpp), which b3d.cpp turns into entities.
//
// A .3ds file is a tree of chunks, each with an id and a length. The meshes, materials, lights and cameras are in the 0x3D3D
// chunk, and what moves is in the 0xB000 chunk, which has a tag for each object, light and camera that says where it is over
// time, how it is turned and how big it is, and which tag it hangs from.
//
// 3D Studio is right-handed with z up, Blitz3D is left-handed with y up: swapping y and z is the whole conversion, as that
// turns the space around once. A face keeps its look, but its front is where its corners go around the other way, so two corners
// of each face change places. Rotations are conjugated by the same swap.
// Meshes are stored in the world, so each is moved back by where its tag puts it at the first frame, and then the tag moves it.

