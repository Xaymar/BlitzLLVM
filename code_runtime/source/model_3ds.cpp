	bool read_color(reader& r, uint32_t id, float* out)
	{
		if ((id == 0x0010) || (id == 0x0013)) {
			for (int i = 0; i < 3; i++) {
				out[i] = r.read_float();
			}
			return true;
		}
		if ((id == 0x0011) || (id == 0x0012)) {
			for (int i = 0; i < 3; i++) {
				out[i] = float(u8(r)) / 255.0f;
			}
			return true;
		}
		return false;
	}

	// A percentage, as a whole number or a float.
	float read_percent(reader& r, size_t end)
	{
		float value = 0;
		each_chunk(r, end, [&](uint32_t id, size_t) {
			if (id == 0x0030) {
				value = float(u16(r));
			} else if (id == 0x0031) {
				value = r.read_float();
			}
		});
		return value;
	}

	void read_material(reader& r, size_t end, material3ds& m)
	{
		each_chunk(r, end, [&](uint32_t id, size_t stop) {
			switch (id) {
			case 0xA000:
				bb_free(m.name);
				m.name = r.read_string();
				break;
			case 0xA020:
				each_chunk(r, stop, [&](uint32_t sub, size_t) { read_color(r, sub, m.diffuse); });
				break;
			case 0xA040:
				m.shininess = read_percent(r, stop) / 100.0f;
				break;
			case 0xA041:
				m.strength = read_percent(r, stop) / 100.0f;
				break;
			case 0xA050:
				m.transparency = read_percent(r, stop) / 100.0f;
				break;
			case 0xA081:
				m.two_sided = true;
				break;
			case 0xA083:
				m.additive = true;
				break;
			case 0xA084:
				m.self_illum = read_percent(r, stop) / 100.0f;
				break;
			case 0xA100:
				m.flat = u16(r) == 1;
				break;
			case 0xA200: // The first texture map
				each_chunk(r, stop, [&](uint32_t sub, size_t sub_stop) {
					switch (sub) {
					case 0xA300:
						bb_free(m.map);
						m.map = r.read_string();
						break;
					case 0xA351:
						m.map_flags = int(u16(r));
						break;
					case 0xA354:
						m.tile[0] = r.read_float();
						break;
					case 0xA356:
						m.tile[1] = r.read_float();
						break;
					case 0xA358:
						m.offset[0] = r.read_float();
						break;
					case 0xA35A:
						m.offset[1] = r.read_float();
						break;
					case 0xA35C:
						m.angle = r.read_float();
						break;
					}
					(void)sub_stop;
				});
				break;
			}
		});
	}

	void read_mesh(reader& r, size_t end, scene3ds& scene, mesh3ds& mesh)
	{
		each_chunk(r, end, [&](uint32_t id, size_t stop) {
			if (id == 0x4110) {
				uint32_t count = u16(r);
				for (uint32_t i = 0; (i < count * 3) && !r.failed; i++) {
					mesh.vertices.push(r.read_float());
				}
			} else if (id == 0x4120) {
				uint32_t count = u16(r);
				for (uint32_t i = 0; (i < count) && !r.failed; i++) {
					for (int c = 0; c < 3; c++) {
						mesh.faces.push(uint16_t(u16(r)));
					}
					u16(r); // The flags of the edges
				}
				mesh.face_material.reserve(count);
				for (uint32_t i = 0; i < count; i++) {
					mesh.face_material.push(-1);
					mesh.smoothing.push(0);
				}
				// A face chunk holds the materials of the faces and their smoothing groups.
				each_chunk(r, stop, [&](uint32_t sub, size_t) {
					if (sub == 0x4130) {
						char*    name = r.read_string();
						uint32_t used = u16(r);
						int      found = -1;
						for (uint32_t m = 0; name && (m < scene.materials.size); m++) {
							if (scene.materials[m]->name && !strcmp(scene.materials[m]->name, name)) {
								found = int(m);
								break;
							}
						}
						for (uint32_t i = 0; (i < used) && !r.failed; i++) {
							uint32_t face = u16(r);
							if ((face < count) && (mesh.face_material[face] < 0)) {
								mesh.face_material[face] = found;
							}
						}
						bb_free(name);
					} else if (sub == 0x4150) {
						for (uint32_t i = 0; (i < count) && !r.failed; i++) {
							mesh.smoothing[i] = u32(r);
						}
					}
				});
			} else if (id == 0x4140) {
				uint32_t count = u16(r);
				for (uint32_t i = 0; (i < count * 2) && !r.failed; i++) {
					mesh.uvs.push(r.read_float());
				}
			}
		});
	}

	void read_object(reader& r, size_t end, scene3ds& scene, object3ds& o)
	{
		each_chunk(r, end, [&](uint32_t id, size_t stop) {
			if (id == 0x4100) {
				o.kind = 0;
				read_mesh(r, stop, scene, o.mesh);
			} else if (id == 0x4600) {
				o.kind = 1;
				for (int i = 0; i < 3; i++) {
					o.position[i] = r.read_float();
				}
				each_chunk(r, stop, [&](uint32_t sub, size_t sub_stop) {
					if (read_color(r, sub, o.color)) {
						return;
					}
					switch (sub) {
					case 0x4610:
						for (int i = 0; i < 3; i++) {
							o.target[i] = r.read_float();
						}
						o.has_target = true;
						o.hotspot    = r.read_float();
						o.falloff    = r.read_float();
						break;
					case 0x4620:
						o.off = true;
						break;
					case 0x465A:
						o.range = r.read_float();
						break;
					case 0x465B:
						o.multiplier = r.read_float();
						break;
					}
					(void)sub_stop;
				});
			} else if (id == 0x4700) {
				o.kind = 2;
				for (int i = 0; i < 3; i++) {
					o.position[i] = r.read_float();
				}
				for (int i = 0; i < 3; i++) {
					o.target[i] = r.read_float();
				}
				o.has_target = true;
				o.bank       = r.read_float();
			}
		});
	}

	// A track of numbers for each key, after the frame and the settings of the spline that is ignored.
	void read_track(reader& r, size_t end, track& t, int width)
	{
		t.width = width;
		u16(r);
		u32(r);
		u32(r);
		uint32_t keys = u32(r);
		for (uint32_t k = 0; (k < keys) && (r.pos + 6 <= end) && !r.failed; k++) {
			float frame = float(u32(r));
			uint32_t flags = u16(r);
			for (int bit = 0; bit < 5; bit++) {
				if (flags & (1u << bit)) {
					r.read_float(); // Tension, continuity, bias, ease in and ease out
				}
			}
			t.data.push(frame);
			for (int i = 0; i < width; i++) {
				t.data.push(r.read_float());
			}
		}
	}

	void read_node(reader& r, size_t end, uint32_t tag, scene3ds& scene)
	{
		node3ds* n = new node3ds();
		n->tag     = tag;
		n->id      = int(scene.nodes.size);
		each_chunk(r, end, [&](uint32_t id, size_t stop) {
			switch (id) {
			case 0xB010: {
				bb_free(n->name);
				n->name         = r.read_string();
				n->flags        = u16(r);
				u16(r);
				uint32_t parent = u16(r);
				n->parent       = parent == 0xFFFF ? -1 : int(parent);
				break;
			}
			case 0xB011:
				bb_free(n->instance);
				n->instance = r.read_string();
				break;
			case 0xB020:
				read_track(r, stop, n->pos, 3);
				break;
			case 0xB021:
				read_track(r, stop, n->rot, 4);
				break;
			case 0xB022:
				read_track(r, stop, n->scale, 3);
				break;
			case 0xB024:
				read_track(r, stop, n->roll, 1);
				break;
			case 0xB025:
				read_track(r, stop, n->color, 3);
				break;
			case 0xB027:
				read_track(r, stop, n->hot, 1);
				break;
			case 0xB028:
				read_track(r, stop, n->fall, 1);
				break;
			case 0xB030:
				n->id = int(u16(r));
				break;
			}
		});
		scene.nodes.push(n);
	}

	void read_scene(reader& r, size_t end, scene3ds& scene)
	{
		each_chunk(r, end, [&](uint32_t id, size_t stop) {
			if (id == 0x3D3D) {
				// Materials come before the objects that use them.
				each_chunk(r, stop, [&](uint32_t sub, size_t sub_stop) {
					if (sub == 0xAFFF) {
						material3ds* m = new material3ds();
						read_material(r, sub_stop, *m);
						scene.materials.push(m);
					} else if (sub == 0x4000) {
						object3ds* o = new object3ds();
						o->name      = r.read_string();
						read_object(r, sub_stop, scene, *o);
						scene.objects.push(o);
					}
				});
			} else if (id == 0xB000) {
				each_chunk(r, stop, [&](uint32_t sub, size_t sub_stop) {
					if (sub == 0xB008) {
						scene.first     = float(u32(r));
						scene.last      = float(u32(r));
						scene.has_range = true;
					} else if ((sub >= 0xB002) && (sub <= 0xB007)) {
						read_node(r, sub_stop, sub, scene);
					}
				});
			}
		});
	}

	////////////////////////////////////////////////////////////////////////////
	// Math: 3x3 matrices are columns, 4x4 matrices are columns, both for column vectors
	////////////////////////////////////////////////////////////////////////////
	int swapped(int axis)
	{
		return axis == 0 ? 0 : 3 - axis;
	}

	void axis_angle(const float* axis, float angle, float* r)
	{
		float length = sqrtf(axis[0] * axis[0] + axis[1] * axis[1] + axis[2] * axis[2]);
		float x = 0, y = 0, z = 1;
		if (length > 1e-12f) {
			x = axis[0] / length;
			y = axis[1] / length;
			z = axis[2] / length;
		} else {
			angle = 0;
		}
		float c = cosf(angle), s = sinf(angle), t = 1 - c;
		r[0] = t * x * x + c;
		r[1] = t * x * y + s * z;
		r[2] = t * x * z - s * y;
		r[3] = t * x * y - s * z;
		r[4] = t * y * y + c;
		r[5] = t * y * z + s * x;
		r[6] = t * x * z + s * y;
		r[7] = t * y * z - s * x;
		r[8] = t * z * z + c;
	}

	void multiply3(const float* a, const float* b, float* out)
	{
		float result[9];
		for (int col = 0; col < 3; col++) {
			for (int row = 0; row < 3; row++) {
				result[col * 3 + row] = a[0 * 3 + row] * b[col * 3 + 0] + a[1 * 3 + row] * b[col * 3 + 1] + a[2 * 3 + row] * b[col * 3 + 2];
			}
		}
		memcpy(out, result, sizeof(result));
	}

	// The value of a track at a frame, between the two keys around it and the closest key outside of them.
	void evaluate(track const& t, float frame, float* out)
	{
		uint32_t count = t.count();
		if (count == 0) {
			return;
		}
		uint32_t next = 0;
		while ((next < count) && (t.at(next)[0] < frame)) {
			next++;
		}
		if (next == 0) {
			memcpy(out, t.at(0) + 1, size_t(t.width) * sizeof(float));
		} else if (next >= count) {
			memcpy(out, t.at(count - 1) + 1, size_t(t.width) * sizeof(float));
		} else {
			const float* a = t.at(next - 1);
			const float* b = t.at(next);
			float        f = (b[0] > a[0]) ? (frame - a[0]) / (b[0] - a[0]) : 0;
			for (int i = 0; i < t.width; i++) {
				out[i] = a[1 + i] + (b[1 + i] - a[1 + i]) * f;
			}
		}
	}

	// The turns of the keys of a rotation track, each of which is a turn on top of the key before it.
	// out gets a matrix for each key.
	void rotations(track const& t, buffer<float>& out)
	{
		float total[9] = { 1, 0, 0, 0, 1, 0, 0, 0, 1 };
		for (uint32_t k = 0; k < t.count(); k++) {
			const float* key = t.at(k);
			float        turn[9];
			axis_angle(key + 2, key[1], turn);
			multiply3(total, turn, total);
			for (int i = 0; i < 9; i++) {
				out.push(total[i]);
			}
		}
	}

	// The rotation matrix of 3D Studio as the quaternion of the keys in Blitz3D.
	void quaternion_of(const float* r, float* q)
	{
		float turned[9];
		for (int col = 0; col < 3; col++) {
			for (int row = 0; row < 3; row++) {
				turned[col * 3 + row] = r[swapped(col) * 3 + swapped(row)];
			}
		}
		rotation_to_quaternion(turned, q);
	}

	void matrix_of(const float* pos, const float* scale, const float* r, float* m)
	{
		memset(m, 0, 16 * sizeof(float));
		for (int col = 0; col < 3; col++) {
			for (int row = 0; row < 3; row++) {
				m[col * 4 + row] = r[col * 3 + row] * scale[col];
			}
		}
		m[12] = pos[0];
		m[13] = pos[1];
		m[14] = pos[2];
		m[15] = 1;
	}

