// Rounded to what the picture can show only when it is shown, so that the tables keep what was set. The values are
// the 0 to 255 of a color, but fractions count.
void bb_set_gamma(int32_t source_red, int32_t source_green, int32_t source_blue, float red, float green, float blue)
{
	need_gamma();
	working[0][source_red & 255]   = clamp_gamma(red);
	working[1][source_green & 255] = clamp_gamma(green);
	working[2][source_blue & 255]  = clamp_gamma(blue);
}

// Dither: the picture of the window gets temporal Interleaved Gradient Noise of half a step of 8 bits when it is shown, so that
// what the gamma tables and rounding do to a gradient is not seen as bands. 3D drawing gets it before its colors are rounded
// to the buffer, and with 2 also after blending, if the GPU can blend in the shader (HWDither). Without that 2 is 1. Takes
// effect with the next picture that is shown.
void bb_dither(int32_t enable)
{
	int level = (enable == 0) ? 0 : ((enable >= 2) ? 2 : 1); // Every other value is on, as it was.
	if (level != dither) {
		int before = dither_level();
		dither     = level;
		changed    = true;
		if (g.created && !g.headless && (dither_level() != before)) {
			rebuild_pipelines_3d();
		}
	}
}

// A BlitzLLVM extension: whether the noise of Dither moves from picture to picture (the default), which averages out over time,
// or is the same pattern every time, which does not flicker when a picture is looked at on its own (a screenshot, a still scene).
// It applies to the shown picture and 3D drawing, and takes effect with the next picture.
void bb_dither_temporal(int32_t enable)
{
	dither_moves = (enable != 0) ? 1 : 0;
}

// GraphicsPalette imagefile: the 256 colors that a Graphics with a depth of 8 shows. The file is a picture of 16 by 16 pixels, read from the
// top left to the right and then down, so that the pixel at x,y is the color with the number y * 16 + x. Without a file (an empty name)
// the palette is the one of all colors with 3 bits of red and green and 2 of blue, from 0,0,0 to 255,255,255. It can be set before
// Graphics, and takes effect with the next picture that is shown.
void bb_graphics_palette(const char* file)
{
	palette_ready = true;
	if (!file || !file[0]) {
		default_palette();
	} else {
		SDL_Surface* loaded = load_surface(file);
		if (!loaded) {
			bb_runtime_error("GraphicsPalette: the picture could not be loaded.");
			return;
		}
		SDL_Surface* rgba = SDL_ConvertSurface(loaded, SDL_PIXELFORMAT_RGBA32);
		SDL_DestroySurface(loaded);
		if (!rgba) {
			bb_runtime_error("GraphicsPalette: the picture could not be read.");
			return;
		}
		if ((rgba->w != 16) || (rgba->h != 16)) {
			SDL_DestroySurface(rgba);
			bb_runtime_error("GraphicsPalette: the picture has to be 16 by 16 pixels.");
			return;
		}
		for (int y = 0; y < 16; y++) {
			const uint8_t* row = static_cast<const uint8_t*>(rgba->pixels) + size_t(y) * size_t(rgba->pitch);
			for (int x = 0; x < 16; x++) {
				memcpy(palette[y * 16 + x], row + x * 4, 3);
			}
		}
		SDL_DestroySurface(rgba);
	}
	palette_prepare();
	palette_changed = true;
	changed         = true;
	if (g.created && !g.headless && palette_mode()) {
		wait_gpu();
		g.front_touched = true;
		flush();
	}
}

// Makes the tables count. The original also had them corrected for the calibration of the display, which a window
// has no say in.
void bb_update_gamma(int32_t calibrate)
{
	(void)calibrate;
	need_gamma();
	memcpy(applied, working, sizeof(applied));
	changed = true;
	if (g.created && !g.headless) {
		// The window shows it at once, also if the program only draws to the front buffer.
		wait_gpu();
		g.front_touched = true;
		flush();
	}
}

float bb_gamma_red(int32_t index)
{
	need_gamma();
	return working[0][index & 255];
}

float bb_gamma_green(int32_t index)
{
	need_gamma();
	return working[1][index & 255];
}

float bb_gamma_blue(int32_t index)
{
	need_gamma();
	return working[2][index & 255];
}
