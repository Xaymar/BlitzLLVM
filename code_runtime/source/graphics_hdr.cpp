	constexpr float scrgb_white_nits = 80.0f; // 1.0 in scRGB.

	int   mode         = -1;    // AutoHDR: -1 until BLITZLLVM_AUTOHDR was read (2 if it is not set).
	float white_nits   = -1.0f; // AutoHDRWhite: 0 for the SDR white level of the system. -1 until BLITZLLVM_AUTOHDR_WHITE was read.
	float peak_nits    = -1.0f; // AutoHDRPeak: 0 for the peak of the display.
	float expand       = -1.0f; // AutoHDRExpand: how far the highlights are stretched toward the peak with AutoHDR 2, 0 to 1.
	float meta_min     = 0.0f;  // AutoHDRMetadata: what the system is told about the picture, 0 for the default of each.
	float meta_average = 0.0f;
	float meta_max     = 0.0f;
	bool  meta_dirty   = true;

	VkPipelineLayout layout   = VK_NULL_HANDLE;
	VkPipeline       pipeline = VK_NULL_HANDLE;
	VkDescriptorSet  set      = VK_NULL_HANDLE;
	VkImageView      set_view = VK_NULL_HANDLE; // What set samples.
	gpu_image        scrgb;                     // The picture in scRGB, which is what is blitted to the swapchain.

	VkBuffer      dump_buffer     = VK_NULL_HANDLE;
	VmaAllocation dump_allocation = VK_NULL_HANDLE;
	uint8_t*      dump_mapped     = nullptr;
	uint32_t      dump_size       = 0;
	bool          dumped          = false; // The picture of this present was copied to the buffer.

	const char* test_path()
	{
		static const char* path = bb_env("BLITZLLVM_TEST_HDR");
		return (path && path[0]) ? path : nullptr;
	}

	float half_to_float(uint16_t h)
	{
		uint32_t sign     = uint32_t(h >> 15) << 31;
		uint32_t exponent = (h >> 10) & 31;
		uint32_t fraction = h & 1023;
		uint32_t bits;
		if (exponent == 0) {
			if (fraction == 0) {
				bits = sign;
			} else { // A subnormal half is a normal float.
				exponent = 127 - 15 + 1;
				while (!(fraction & 1024)) {
					fraction <<= 1;
					exponent--;
				}
				bits = sign | (exponent << 23) | ((fraction & 1023) << 13);
			}
		} else if (exponent == 31) {
			bits = sign | 0x7F800000u | (fraction << 13);
		} else {
			bits = sign | ((exponent + 127 - 15) << 23) | (fraction << 13);
		}
		float value;
		memcpy(&value, &bits, sizeof(value));
		return value;
	}

	void read_environment()
	{
		if (mode < 0) {
			mode = std::clamp(bb_env_int("BLITZLLVM_AUTOHDR", 2), 0, 2);
		}
		if (white_nits < 0.0f) {
			white_nits = std::clamp(float(bb_env_double("BLITZLLVM_AUTOHDR_WHITE", 0.0)), 0.0f, 10000.0f);
		}
		if (peak_nits < 0.0f) {
			peak_nits = std::clamp(float(bb_env_double("BLITZLLVM_AUTOHDR_PEAK", 0.0)), 0.0f, 10000.0f);
		}
		if (expand < 0.0f) {
			expand = std::clamp(float(bb_env_double("BLITZLLVM_AUTOHDR_EXPAND", 1.0)), 0.0f, 1.0f);
		}
	}

	// What the system says about the window: the SDR white level in nits (0 if it does not say) and the room above it (1 for none).
	struct system_levels {
		bool  hdr      = false; // The window is on a display that has HDR switched on.
		float white    = 0.0f;
		float headroom = 1.0f;
	};

#ifdef _WIN32
	// SDL says a display has HDR only when its own query through DXGI finds the monitor, and on some machines (two GPUs, for one) it does not.
	// Windows can be asked directly: the display configuration says if "advanced color" (HDR) is on for the monitor a window is on, the SDR white
	// level of its slider, and DXGI the peak luminance. The answer is kept for half a second as the questions are not cheap.
	struct advanced_color_info {
		DISPLAYCONFIG_DEVICE_INFO_HEADER header;
		UINT32                           value; // Bit 0 supported, bit 1 enabled.
		UINT32                           color_encoding;
		UINT32                           bits_per_channel;
	};
	struct sdr_white_info {
		DISPLAYCONFIG_DEVICE_INFO_HEADER header;
		ULONG                            level; // 1000 is 80 nits.
	};

	bool windows_hdr(HWND hwnd, bool& hdr, float& white_nits_out, float& peak_nits_out)
	{
		hdr             = false;
		white_nits_out  = 0.0f;
		peak_nits_out   = 0.0f;
		HMONITOR monitor = MonitorFromWindow(hwnd, MONITOR_DEFAULTTONEAREST);
		MONITORINFOEXW info = {};
		info.cbSize         = sizeof(info);
		if (!monitor || !GetMonitorInfoW(monitor, reinterpret_cast<MONITORINFO*>(&info))) {
			return false;
		}

		UINT32                  path_count = 0, mode_count = 0;
		std::vector<DISPLAYCONFIG_PATH_INFO> paths;
		std::vector<DISPLAYCONFIG_MODE_INFO> modes;
		LONG                    result;
		do {
			if (GetDisplayConfigBufferSizes(QDC_ONLY_ACTIVE_PATHS, &path_count, &mode_count) != ERROR_SUCCESS) {
				return false;
			}
			paths.resize(path_count);
			modes.resize(mode_count);
			result = QueryDisplayConfig(QDC_ONLY_ACTIVE_PATHS, &path_count, paths.data(), &mode_count, modes.data(), nullptr);
		} while (result == ERROR_INSUFFICIENT_BUFFER);
		if (result != ERROR_SUCCESS) {
			return false;
		}

		for (UINT32 i = 0; i < path_count; i++) {
			DISPLAYCONFIG_SOURCE_DEVICE_NAME name = {};
			name.header.type                      = DISPLAYCONFIG_DEVICE_INFO_GET_SOURCE_NAME;
			name.header.size                      = sizeof(name);
			name.header.adapterId                 = paths[i].sourceInfo.adapterId;
			name.header.id                        = paths[i].sourceInfo.id;
			if ((DisplayConfigGetDeviceInfo(&name.header) != ERROR_SUCCESS) || (wcscmp(name.viewGdiDeviceName, info.szDevice) != 0)) {
				continue;
			}
			advanced_color_info color = {};
			color.header.type         = static_cast<DISPLAYCONFIG_DEVICE_INFO_TYPE>(9); // DISPLAYCONFIG_DEVICE_INFO_GET_ADVANCED_COLOR_INFO
			color.header.size         = sizeof(color);
			color.header.adapterId    = paths[i].targetInfo.adapterId;
			color.header.id           = paths[i].targetInfo.id;
			if (DisplayConfigGetDeviceInfo(&color.header) == ERROR_SUCCESS) {
				hdr = (color.value & 2u) != 0;
			}
			sdr_white_info level = {};
			level.header.type    = static_cast<DISPLAYCONFIG_DEVICE_INFO_TYPE>(11); // DISPLAYCONFIG_DEVICE_INFO_GET_SDR_WHITE_LEVEL
			level.header.size    = sizeof(level);
			level.header.adapterId = paths[i].targetInfo.adapterId;
			level.header.id        = paths[i].targetInfo.id;
			if (DisplayConfigGetDeviceInfo(&level.header) == ERROR_SUCCESS && level.level > 0) {
				white_nits_out = float(level.level) / 1000.0f * scrgb_white_nits;
			}
			break;
		}

#ifdef BB_HAVE_DXGI16
		if (hdr) {
			using create_factory = HRESULT(WINAPI*)(REFIID, void**);
			HMODULE dxgi = LoadLibraryW(L"dxgi.dll");
			auto    make = dxgi ? reinterpret_cast<create_factory>(GetProcAddress(dxgi, "CreateDXGIFactory1")) : nullptr;
			IDXGIFactory1* factory = nullptr;
			if (make && SUCCEEDED(make(__uuidof(IDXGIFactory1), reinterpret_cast<void**>(&factory)))) {
				IDXGIAdapter1* adapter = nullptr;
				for (UINT a = 0; (peak_nits_out == 0.0f) && SUCCEEDED(factory->EnumAdapters1(a, &adapter)); a++) {
					IDXGIOutput* output = nullptr;
					for (UINT o = 0; (peak_nits_out == 0.0f) && SUCCEEDED(adapter->EnumOutputs(o, &output)); o++) {
						IDXGIOutput6* output6 = nullptr;
						if (SUCCEEDED(output->QueryInterface(__uuidof(IDXGIOutput6), reinterpret_cast<void**>(&output6)))) {
							DXGI_OUTPUT_DESC1 desc = {};
							if (SUCCEEDED(output6->GetDesc1(&desc)) && (desc.Monitor == monitor)) {
								// The desktop of ordinary color management ("advanced color" without HDR) is not in the HDR colorspace.
								hdr            = (desc.ColorSpace == DXGI_COLOR_SPACE_RGB_FULL_G2084_NONE_P2020);
								peak_nits_out = hdr ? desc.MaxLuminance : 0.0f;
							}
							output6->Release();
						}
						output->Release();
					}
					adapter->Release();
				}
				factory->Release();
			}
			if (dxgi) {
				FreeLibrary(dxgi);
			}
		}
#endif
		return true;
	}

	// What windows_hdr said, kept for half a second.
	bool windows_levels(SDL_Window* window, system_levels& levels)
	{
		static Uint64 asked = 0;
		static bool   hdr   = false;
		static float  white = 0.0f, peak = 0.0f;
		Uint64        now   = SDL_GetTicks();
		if (!asked || (now - asked > 500)) {
			asked = now ? now : 1;
			HWND hwnd = static_cast<HWND>(SDL_GetPointerProperty(SDL_GetWindowProperties(window), SDL_PROP_WINDOW_WIN32_HWND_POINTER, nullptr));
			if (!hwnd || !windows_hdr(hwnd, hdr, white, peak)) {
				hdr = false;
			}
		}
		if (hdr) {
			levels.hdr   = true;
			levels.white = white; // 0 when Windows does not say, which is the usual 203 nits then.
			if (peak > 0.0f && levels.white > 0.0f) {
				levels.headroom = std::max(1.0f, peak / levels.white);
			}
		}
		return hdr;
	}
#endif

	system_levels ask_system()
	{
		system_levels levels;
		if (!g.headless && surface().window) {
			SDL_PropertiesID props = SDL_GetWindowProperties(surface().window);
			levels.hdr             = SDL_GetBooleanProperty(props, SDL_PROP_WINDOW_HDR_ENABLED_BOOLEAN, false);
			levels.white           = SDL_GetFloatProperty(props, SDL_PROP_WINDOW_SDR_WHITE_LEVEL_FLOAT, 0.0f) * scrgb_white_nits;
			levels.headroom        = std::max(1.0f, SDL_GetFloatProperty(props, SDL_PROP_WINDOW_HDR_HEADROOM_FLOAT, 1.0f));
			if (!levels.hdr) {
				// SDL sets what the window knows once, where the window was made, and does not follow the window to another display. Ask the display it is on now.
				SDL_DisplayID display = SDL_GetDisplayForWindow(surface().window);
				levels.hdr            = display && SDL_GetBooleanProperty(SDL_GetDisplayProperties(display), SDL_PROP_DISPLAY_HDR_ENABLED_BOOLEAN, false);
			}
#ifdef _WIN32
			if (!levels.hdr) {
				windows_levels(surface().window, levels); // SDL does not see the HDR of this display, ask Windows.
			}
#endif
		} else if (!bb_env_bool("BLITZLLVM_HEADLESS", 0) && !g.headless && SDL_InitSubSystem(SDL_INIT_VIDEO)) {
			SDL_DisplayID display = SDL_GetPrimaryDisplay();
			if (display) {
				levels.hdr = SDL_GetBooleanProperty(SDL_GetDisplayProperties(display), SDL_PROP_DISPLAY_HDR_ENABLED_BOOLEAN, false);
			}
		}
		return levels;
	}

	// SDR white in nits: asked for, else what the system has (it follows the slider of the system), else the usual 203.
	float effective_white(const system_levels& levels)
	{
		return (white_nits > 0.0f) ? white_nits : ((levels.white > 0.0f) ? levels.white : 203.0f);
	}

	// The brightest the display shows in nits: asked for, else what the system says, else 1000.
	float effective_peak(const system_levels& levels, float white)
	{
		float peak = (peak_nits > 0.0f) ? peak_nits : ((levels.hdr && (levels.headroom > 1.0f) && (levels.white > 0.0f)) ? levels.white * levels.headroom : 1000.0f);
		return std::max(peak, white);
	}

	void create_resources()
	{
		VkDescriptorSetLayout layouts[1] = { g.set_layout };
		VkPushConstantRange   range      = { VK_SHADER_STAGE_FRAGMENT_BIT, 0, 2 * sizeof(float) }; // The SDR white, and how far the highlights go beyond it.
		VkPipelineLayoutCreateInfo info  = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
		info.setLayoutCount              = 1;
		info.pSetLayouts                 = layouts;
		info.pushConstantRangeCount      = 1;
		info.pPushConstantRanges         = &range;
		check(vkCreatePipelineLayout(g.device, &info, nullptr, &layout), "vkCreatePipelineLayout");

		VkShaderModule vs = create_shader(bb_shader_vertex_fullscreen, sizeof(bb_shader_vertex_fullscreen));
		VkShaderModule fs = create_shader(bb_shader_fragment_hdr, sizeof(bb_shader_fragment_hdr));
		pipeline          = create_fullscreen_pipeline(vs, fs, layout, VK_FORMAT_R16G16B16A16_SFLOAT);
		vkDestroyShaderModule(g.device, vs, nullptr);
		vkDestroyShaderModule(g.device, fs, nullptr);
		allocate_descriptor(set);
	}

	// Primaries of sRGB and BT.709, with the D65 white point: scRGB shares them.
	void tell_system(surface_state& s)
	{
		if (!g.can_hdr_metadata || !vkSetHdrMetadataEXT || !s.swapchain) {
			return;
		}
		system_levels levels = ask_system();
		float         white  = effective_white(levels);
		float         peak   = effective_peak(levels, white);
		VkHdrMetadataEXT metadata       = { VK_STRUCTURE_TYPE_HDR_METADATA_EXT };
		metadata.displayPrimaryRed      = { 0.640f, 0.330f };
		metadata.displayPrimaryGreen    = { 0.300f, 0.600f };
		metadata.displayPrimaryBlue     = { 0.150f, 0.060f };
		metadata.whitePoint             = { 0.3127f, 0.3290f };
		metadata.maxLuminance           = (meta_max > 0.0f) ? meta_max : peak;
		metadata.minLuminance           = meta_min;
		metadata.maxContentLightLevel   = (meta_max > 0.0f) ? meta_max : peak;
		metadata.maxFrameAverageLightLevel = (meta_average > 0.0f) ? meta_average : white;
		vkSetHdrMetadataEXT(g.device, 1, &s.swapchain, &metadata);
	}
