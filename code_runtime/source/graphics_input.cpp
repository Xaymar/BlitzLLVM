int32_t bb_key_down(int32_t key)
{
	if (!active()) {
		return 0;
	}
	pump();
	return ((key > 0) && (key < 256) && g.keys[key]) ? 1 : 0;
}

int32_t bb_key_hit(int32_t key)
{
	if (!active()) {
		return 0;
	}
	pump();
	if ((key > 0) && (key < 256)) {
		int hits        = g.key_hits[key];
		g.key_hits[key] = 0;
		return hits;
	}
	return 0;
}

// MouseX [canvas]: in the window, or in a canvas if one is given.
