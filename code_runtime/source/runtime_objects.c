////////////////////////////////////////////////////////////////////////////////
// Objects (Types)
//
// Every object starts with this header, which the compiler knows about (see register_types). Objects of a type are
// in a doubly linked list. Delete takes the object out of the list, flags it and frees its memory. Two things hold the
// memory back for a while: a For Each loop over the type that is running (its next object is found through the deleted
// one), a variable that still points at it, and a program compiled with -d, which keeps the last BB_OBJECT_DELAY
// deleted objects of each type as a second safety net.
//
// Variables, fields and array elements that hold an object count it: flags has the deleted bit in bit 0, a bit that says its
// memory was given up (-d keeps it for a while) and the number of holders from bit 2 on. Only an object that was deleted is ever freed, once nothing holds it any more, so a
// variable that still points at a deleted object finds the flag and reports 'Object does not exist.', in every build.
// A holder that is missed leaves the object where it is, a count that is too low frees it a little early, as a
// Delete did before holders were counted.
////////////////////////////////////////////////////////////////////////////////
#define BB_OBJECT_DELETED 1
#define BB_OBJECT_RETIRED 2
#define BB_OBJECT_HOLDER  4

extern int32_t bb_is_debug(void);

typedef struct bb_object {
	struct bb_object* next;
	struct bb_object* prev;
	int32_t           handle;
	int32_t           flags;
} bb_object;

#define BB_OBJECT_DELAY 65536

typedef struct bb_dead {
	bb_object** ring;    // With -d: the deleted objects of this type, oldest first, starting at head.
	int32_t     cap;
	int32_t     head;
	int32_t     count;
	bb_object** pending; // Deleted while a For Each loop was running, freed when the last one ends.
	int32_t     pending_cap;
	int32_t     pending_count;
} bb_dead;

struct bb_list;

// A field of a type (or an array of them) that holds objects: where it is, how many there are and the type they have.
typedef struct bb_objfield {
	int32_t         offset;
	int32_t         count; // 0 for a single field.
	struct bb_list* list;  // NULL ends the table.
} bb_objfield;

typedef struct bb_list {
	bb_object*         first;
	bb_object*         last;
	const int32_t*     strings; // How many fields (or arrays of them) are strings, then the offset and the count of each.
	bb_dead*           dead;
	int64_t            iterating; // How many For Each loops over this type are running.
	const bb_objfield* objects;   // The fields that hold objects.
} bb_list;

// Handles are numbers that stand in for objects. Index 0 is never used.
static bb_object** bb_handles     = NULL;
static int32_t     bb_handle_count = 1;
static int32_t     bb_handle_cap   = 0;
static const bb_list** bb_handle_lists = NULL; // The list of the type of each handle.

static void bb_list_append(bb_list* list, bb_object* object)
{
	object->prev = list->last;
	object->next = NULL;
	if (list->last) {
		list->last->next = object;
	} else {
		list->first = object;
	}
	list->last = object;
}

static void bb_list_unlink(bb_list* list, bb_object* object)
{
	// The object keeps its own next and previous pointers, so that a loop standing on it can continue.
	if (object->prev) {
		object->prev->next = object->next;
	} else {
		list->first = object->next;
	}
	if (object->next) {
		object->next->prev = object->prev;
	} else {
		list->last = object->prev;
	}
}

static int32_t bb_objects_live    = 0; // Objects that were made and not deleted.
static int32_t bb_objects_deleted = 0; // Objects that were deleted, but whose memory stays because programs may still hold them.

void* bb_object_new(int64_t size, bb_list* list)
{
	bb_object* object = (bb_object*)bb_calloc(1, (size_t)size);
	if (!object) {
		bb_runtime_error("Out of memory.");
	}
	bb_list_append(list, object);
	bb_objects_live++;
	return object;
}

void bb_check_object(void* pointer)
{
	bb_object* object = (bb_object*)pointer;
	if (!object || (object->flags & BB_OBJECT_DELETED)) {
		bb_runtime_error("Object does not exist.");
	}
}

static bb_dead* bb_list_dead(bb_list* list)
{
	if (!list->dead) {
		list->dead = (bb_dead*)bb_calloc(1, sizeof(bb_dead));
	}
	return list->dead;
}

static void bb_object_release(bb_object* object)
{
	bb_objects_deleted--;
	bb_free(object);
}

static void bb_array_push(bb_object*** array, int32_t* count, int32_t* cap, bb_object* object)
{
	if (*count == *cap) {
		int32_t      grown = *cap ? *cap * 2 : 64;
		bb_object** items = (bb_object**)bb_realloc(*array, (size_t)grown * sizeof(bb_object*));
		if (!items) {
			bb_runtime_error("Out of memory.");
		}
		*array = items;
		*cap   = grown;
	}
	(*array)[(*count)++] = object;
}

// The object has been unlinked, flagged and had its strings freed. Free its memory unless something still needs it.
static void bb_object_retire(bb_object* object, bb_list* list)
{
	object->flags |= BB_OBJECT_RETIRED;
	bb_dead* dead = bb_list_dead(list);
	if (!dead) {
		return; // The object simply stays deleted.
	}
	if (bb_is_debug()) {
		// Keep it for a while, so that variables that still point at it are caught.
		if (dead->count == dead->cap) {
			// Grow the ring, and unroll it so that head is 0 again.
			int32_t      cap  = dead->cap ? dead->cap * 2 : 64;
			bb_object** ring = (bb_object**)bb_calloc((size_t)cap, sizeof(bb_object*));
			if (!ring) {
				return;
			}
			for (int32_t i = 0; i < dead->count; i++) {
				ring[i] = dead->ring[(dead->head + i) % dead->cap];
			}
			bb_free(dead->ring);
			dead->ring = ring;
			dead->cap  = cap;
			dead->head = 0;
		}
		dead->ring[(dead->head + dead->count) % dead->cap] = object;
		dead->count++;
		// The oldest are old enough now, unless a loop might still stand on them.
		while (!list->iterating && (dead->count > BB_OBJECT_DELAY)) {
			bb_object_release(dead->ring[dead->head]);
			dead->head = (dead->head + 1) % dead->cap;
			dead->count--;
		}
		return;
	}
	if (list->iterating) {
		bb_array_push(&dead->pending, &dead->pending_count, &dead->pending_cap, object);
		return;
	}
	bb_object_release(object);
}

// A For Each loop over the type starts. The flag says if this loop already counts (a Goto can jump back into it).
void bb_loop_enter(bb_list* list, char* flag)
{
	if (!*flag) {
		*flag = 1;
		list->iterating++;
	}
}

void bb_loop_leave(bb_list* list, char* flag)
{
	if (!*flag) {
		return;
	}
	*flag = 0;
	if (--list->iterating) {
		return;
	}
	bb_dead* dead = list->dead;
	if (dead) {
		for (int32_t i = 0; i < dead->pending_count; i++) {
			bb_object_release(dead->pending[i]);
		}
		dead->pending_count = 0;
		while (dead->count > BB_OBJECT_DELAY) {
			bb_object_release(dead->ring[dead->head]);
			dead->head = (dead->head + 1) % dead->cap;
			dead->count--;
		}
	}
}

// A variable, field or element starts holding the object.
void bb_object_hold(bb_object* object)
{
	if (object) {
		object->flags += BB_OBJECT_HOLDER;
	}
}

// It stops holding it. A deleted object that nobody holds is freed now.
void bb_object_drop(bb_object* object, bb_list* list)
{
	if (!object || (object->flags < BB_OBJECT_HOLDER)) {
		return;
	}
	object->flags -= BB_OBJECT_HOLDER;
	if (object->flags == BB_OBJECT_DELETED) {
		bb_object_retire(object, list);
	}
}

// The generated code lets go of an object itself and calls this when the last holder of a deleted object went.
void bb_object_unheld(bb_object* object, bb_list* list)
{
	bb_object_retire(object, list);
}

// What a variable, field or element does when it is given an object: the new one is held, the old one let go.
bb_object* bb_object_assign(bb_object* old, bb_object* object, bb_list* list)
{
	if (old != object) {
		bb_object_hold(object);
		bb_object_drop(old, list);
	}
	return object;
}

// The elements of an array of objects stop holding them, as the array goes away or is made again.
void bb_object_drop_array(bb_object** elements, int64_t count, bb_list* list)
{
	for (int64_t i = 0; i < count; i++) {
		bb_object* held = elements[i];
		elements[i]     = NULL;
		bb_object_drop(held, list);
	}
}

void bb_object_delete(bb_object* object, bb_list* list)
{
	if (!object || (object->flags & BB_OBJECT_DELETED)) {
		return;
	}
	bb_list_unlink(list, object);
	object->flags |= BB_OBJECT_DELETED;
	bb_objects_live--;
	bb_objects_deleted++;
	if (list->strings) {
		// The object stays readable after it is deleted, with empty strings.
		for (int32_t i = 0; i < list->strings[0]; i++) {
			char** slot  = (char**)((char*)object + list->strings[1 + 2 * i]);
			int32_t count = list->strings[2 + 2 * i];
			for (int32_t k = 0; k < (count ? count : 1); k++) {
				bb_str_free(slot[k]);
				slot[k] = NULL;
			}
		}
	}
	if (list->objects) {
		// The objects it held are let go, a chain of deleted objects follows.
		for (const bb_objfield* field = list->objects; field->list; field++) {
			bb_object** slot = (bb_object**)((char*)object + field->offset);
			bb_object_drop_array(slot, field->count ? field->count : 1, field->list);
		}
	}
	if (object->handle > 0) {
		bb_handles[object->handle] = NULL;
	}
	if (object->flags == BB_OBJECT_DELETED) {
		bb_object_retire(object, list);
	}
}

void bb_list_clear(bb_list* list)
{
	while (list->first) {
		bb_object_delete(list->first, list);
	}
}

bb_object* bb_list_first(bb_list* list)
{
	return list->first;
}

bb_object* bb_list_last(bb_list* list)
{
	return list->last;
}

bb_object* bb_object_next(bb_object* object)
{
	if (!object) {
		return NULL;
	}
	bb_object* next = object->next;
	while (next && (next->flags & BB_OBJECT_DELETED)) {
		next = next->next;
	}
	return next;
}

bb_object* bb_object_prev(bb_object* object)
{
	if (!object) {
		return NULL;
	}
	bb_object* prev = object->prev;
	while (prev && (prev->flags & BB_OBJECT_DELETED)) {
		prev = prev->prev;
	}
	return prev;
}

// Insert object Before/After other: moves the object within its list.
void bb_object_insert(bb_object* object, bb_object* other, int32_t after, bb_list* list)
{
	bb_check_object(object);
	bb_check_object(other);
	if (object == other) {
		return;
	}
	bb_list_unlink(list, object);
	if (after) {
		object->prev = other;
		object->next = other->next;
		if (other->next) {
			other->next->prev = object;
		} else {
			list->last = object;
		}
		other->next = object;
	} else {
		object->next = other;
		object->prev = other->prev;
		if (other->prev) {
			other->prev->next = object;
		} else {
			list->first = object;
		}
		other->prev = object;
	}
}

// The list that a handle was made for says which type its object is. Object.Type(handle) with the handle of an object of another type
// would give the program an object whose fields it reads as the ones of a different type: numbers as pointers, and pointers as strings.
int32_t bb_handle(bb_object* object, const bb_list* list)
{
	if (!object || (object->flags & BB_OBJECT_DELETED)) {
		return 0;
	}
	if (object->handle == 0) {
		if (bb_handle_count >= bb_handle_cap) {
			int32_t cap = bb_handle_cap ? bb_handle_cap * 2 : 1024;
			void*   handles = bb_realloc(bb_handles, (size_t)cap * sizeof(bb_object*));
			if (!handles) {
				bb_runtime_error("Out of memory.");
			}
			bb_handles = (bb_object**)handles;
			void* lists = bb_realloc(bb_handle_lists, (size_t)cap * sizeof(bb_list*));
			if (!lists) {
				bb_runtime_error("Out of memory.");
			}
			bb_handle_lists = (const bb_list**)lists;
			bb_handle_cap   = cap;
		}
		object->handle                   = bb_handle_count;
		bb_handles[bb_handle_count]      = object;
		bb_handle_lists[bb_handle_count] = list;
		bb_handle_count++;
	}
	return object->handle;
}

bb_object* bb_object_from_handle(int32_t handle, const bb_list* list)
{
	if ((handle <= 0) || (handle >= bb_handle_count) || (bb_handle_lists[handle] != list)) {
		return NULL;
	}
	return bb_handles[handle];
}

void bb_check_index(int32_t index, int32_t count)
{
	if ((index < 0) || (index >= count)) {
		bb_runtime_error("Array index out of bounds.");
	}
}

// Dim: describes an array, see gen_dim_address in the compiler. The upper bounds are given, and each dimension has one
// element more than that. Dimensioning again discards what was in the array.
typedef struct bb_array {
	void*   data;
	int32_t size[4];
	int32_t pitch; // Elements from one row to the next, which is size[0] plus some padding.
} bb_array;

// Frees the strings in an array that is about to be made again, which is what the elements of a string array own.
void bb_dim_free_strings(bb_array* array)
{
	if (!array->data) {
		return;
	}
	int64_t total = array->pitch;
	for (int32_t i = 1; i < 4; i++) {
		if (array->size[i]) {
			total *= array->size[i];
		}
	}
	char** elements = (char**)array->data;
	for (int64_t i = 0; i < total; i++) {
		bb_str_free(elements[i]);
		elements[i] = NULL;
	}
}

// The same for an array of objects, which let go of them.
void bb_dim_drop_objects(bb_array* array, bb_list* list)
{
	if (!array->data) {
		return;
	}
	int64_t total = array->pitch;
	for (int32_t i = 1; i < 4; i++) {
		if (array->size[i]) {
			total *= array->size[i];
		}
	}
	bb_object_drop_array((bb_object**)array->data, total, list);
}

void bb_dim(bb_array* array, int64_t element_size, int32_t dimensions, int32_t b0, int32_t b1, int32_t b2, int32_t b3)
{
	int32_t bounds[4] = { b0, b1, b2, b3 };
	int64_t total     = 1;
	for (int32_t i = 0; i < 4; i++) {
		if (i < dimensions) {
			if (bounds[i] < 0) {
				bb_runtime_error("Array sizes can't be negative.");
			}
			// The compiler checks each index against the size of its own dimension, not against the whole, so the product of the sizes
			// has to be what is in memory. It overflows for sizes that a file can say, such as 65536 in each of 4 dimensions.
			int64_t limit = ((int64_t)1 << 40) / (element_size > 0 ? element_size : 1);
			if ((bounds[i] == INT32_MAX) || (total > limit / ((int64_t)bounds[i] + 1))) {
				bb_runtime_error("The array is too big.");
			}
			array->size[i] = bounds[i] + 1;
			total *= array->size[i];
		} else {
			array->size[i] = 0;
		}
	}
	// Rows that are a multiple of 1 KiB apart all land in a few sets of the cache, which makes walking down a column slow (and
	// slower still when the rows are 4 KiB apart), so such rows get a cache line of padding.
	array->pitch = array->size[0];
	if ((dimensions > 1) && (element_size > 0) && (element_size <= 64) && ((((int64_t)array->size[0]) * element_size) % 1024 == 0)) {
		array->pitch += (int32_t)(64 / element_size);
		total = total / array->size[0] * array->pitch;
	}
	bb_free(array->data);
	array->data = bb_calloc((size_t)total, (size_t)element_size);
	if (!array->data) {
		bb_runtime_error("Out of memory.");
	}
}

// Data, Read and Restore. The compiler collects the items of all Data statements into a table.
typedef struct bb_data_item {
	int32_t tag; // 0 = integer, 1 = real (the bits of a double), 2 = string (a pointer)
	int64_t value;
} bb_data_item;

static const bb_data_item* bb_data_take(const bb_data_item* table, int32_t count, int32_t* position)
{
	if (*position >= count) {
		bb_runtime_error("Out of data.");
	}
	return &table[(*position)++];
}

const char* bb_str_from_i64(int64_t v);
const char* bb_str_from_f64(double v);
int32_t     bb_str_to_i32(const char* s);
double      bb_str_to_f64(const char* s);

static double bb_data_double(const bb_data_item* item)
{
	double d;
	memcpy(&d, &item->value, sizeof(d));
	return d;
}

int32_t bb_data_int(const bb_data_item* table, int32_t count, int32_t* position)
{
	const bb_data_item* item = bb_data_take(table, count, position);
	switch (item->tag) {
	case 1:
		return (int32_t)bb_data_double(item);
	case 2:
		return bb_str_to_i32((const char*)(intptr_t)item->value);
	default:
		return (int32_t)item->value;
	}
}

float bb_data_float(const bb_data_item* table, int32_t count, int32_t* position)
{
	const bb_data_item* item = bb_data_take(table, count, position);
	switch (item->tag) {
	case 1:
		return (float)bb_data_double(item);
	case 2:
		return (float)bb_str_to_f64((const char*)(intptr_t)item->value);
	default:
		return (float)item->value;
	}
}

const char* bb_data_string(const bb_data_item* table, int32_t count, int32_t* position)
{
	const bb_data_item* item = bb_data_take(table, count, position);
	switch (item->tag) {
	case 1:
		return bb_str_from_f64(bb_data_double(item));
	case 2:
		return (const char*)(intptr_t)item->value;
	default:
		return bb_str_from_i64(item->value);
	}
}



// Says in the debug log how many objects there are. Strings are not counted, as many of them belong to the library.
void bb_runtime_stats(void)
{
	char line[96];
	snprintf(line, sizeof(line), "Active objects :%d", (int)bb_objects_live);
	bb_log_text(line);
	snprintf(line, sizeof(line), "Unreleased objs:%d", (int)bb_objects_deleted);
	bb_log_text(line);
}

