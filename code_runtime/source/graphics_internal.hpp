	struct texture_entry {
		bool            used = false;
		int             flags = 0;
		int             width = 0, height = 0;
		float           uv[4] = { 1, 1, 0, 0 }; // Scale (ScaleTexture) and offset (PositionTexture) of the coordinates.
		int             blend = 2;              // What a texture on a later layer does with what is below: 1 alpha, 2 multiply, 3 add, 5 twice multiply.
		int             frames = 1;             // More than one for a texture that is a sheet of frames, see LoadAnimTexture.
		int             frame_w = 0, frame_h = 0; // The size of a frame, if there are frames.
		int             first_frame = 0;        // The cell of the sheet that is the first frame.
		char*           file = nullptr;         // Where it was loaded from, for TextureName.
		gpu_image       image;
		VkDescriptorSet set = VK_NULL_HANDLE;
	};


	// Images are what 2D drawing uses. They can have frames, which are cells of one sheet.
	struct image_entry {
		bool            used = false;
		int             frames = 1, frame_w = 0, frame_h = 0;
		int             sheet_w = 0, sheet_h = 0;
		int             first = 0; // Index of the first frame in the sheet.
		int             handle_x = 0, handle_y = 0;
		uint8_t         mask[3] = { 0, 0, 0 };
		bool            masked  = true;
		gpu_image       image;
		VkDescriptorSet set = VK_NULL_HANDLE;
		uint8_t*        solid = nullptr;        // For collisions: one byte per pixel of the sheet, 1 where it is not the mask color.
		uint32_t        solid_generation = 0;   // What image_generation was when solid was made.
	};

	// Counts changes to images, so that collision data that was made from them is made again.
	extern uint32_t image_generation;


