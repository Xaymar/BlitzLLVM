	/** What the Vulkan backend keeps of the device. Like the graphics state it belongs to the thread that runs the program. */
	struct vk_state {
		VkInstance       instance = VK_NULL_HANDLE;
		VkPhysicalDevice physical = VK_NULL_HANDLE;
		VkDevice         device   = VK_NULL_HANDLE;
		VmaAllocator     allocator = VK_NULL_HANDLE; // Where all the memory of buffers and images comes from. Destroyed before the device.
		VkQueue          queue    = VK_NULL_HANDLE; // queues[0]: the one of Graphics, the program's thread and the submission thread.
		VkQueue          queues[8] = {};
		VkPhysicalDeviceMemoryProperties memory = {};

		VkCommandPool   pool  = VK_NULL_HANDLE;
		VkCommandBuffer cmd   = VK_NULL_HANDLE;
		VkFence         fence = VK_NULL_HANDLE;

		VkDescriptorSetLayout set_layout = VK_NULL_HANDLE;
		VkDescriptorPool      set_pool   = VK_NULL_HANDLE;
	};
	extern constinit thread_local vk_state vkd;

	/** The parts of a recipe that are kept in the backend's own terms (see image_recipe). */
	static_assert(sizeof(VkImageCreateInfo) <= sizeof(image_recipe::native_info));
	static_assert(sizeof(VkComponentMapping) == sizeof(image_recipe::mapping));
	inline VkImageCreateInfo vk_create_info(const image_recipe& recipe)
	{
		VkImageCreateInfo info;
		memcpy(&info, recipe.native_info, sizeof(info));
		return info;
	}
	inline void set_vk_create_info(image_recipe& recipe, const VkImageCreateInfo& info)
	{
		memcpy(recipe.native_info, &info, sizeof(info));
	}
	inline VkComponentMapping vk_mapping(const image_recipe& recipe)
	{
		VkComponentMapping mapping;
		memcpy(&mapping, recipe.mapping, sizeof(mapping));
		return mapping;
	}

	/** Lets a Vulkan call write a handle into a field that keeps it as a number: vkCreateX(..., vk_out<VkX>{ field }). The field has the handle once the statement is over. */
	template<typename T>
	struct vk_out {
		uint64_t& field;
		T         handle;
		explicit vk_out(uint64_t& f) : field(f), handle(T(f)) {}
		vk_out(const vk_out&) = delete;
		~vk_out() { field = uint64_t(handle); }
		operator T*() { return &handle; }
		operator T&() { return handle; }
	};

	/** The Vulkan layout that an image is in while it has the use. */
	inline VkImageLayout vk_layout_of(bb::rhi::image_state usage)
	{
		switch (usage) {
		case bb::rhi::image_state::sampled: return VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
		case bb::rhi::image_state::color_target: return VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
		case bb::rhi::image_state::depth_target: return VK_IMAGE_LAYOUT_DEPTH_ATTACHMENT_OPTIMAL;
		case bb::rhi::image_state::depth_read: return VK_IMAGE_LAYOUT_DEPTH_STENCIL_READ_ONLY_OPTIMAL;
		case bb::rhi::image_state::copy_src: return VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
		case bb::rhi::image_state::copy_dst: return VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
		case bb::rhi::image_state::present: return VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
		default: return VK_IMAGE_LAYOUT_UNDEFINED;
		}
	}
