#include "window_thread.hpp"
#include "environment.h"
#include <atomic>
#include <chrono>
#include <deque>
#include <condition_variable>
#include <mutex>

namespace bb::wnd {
	namespace {
		struct job {
			void (*function)(void*);
			void* data;
			bool  done = false;
		};

		std::mutex              lock;
		std::condition_variable wake; // The thread has a job to do.
		std::condition_variable finished; // A job is done.
		std::deque<job*>        jobs;
		SDL_Thread*             thread = nullptr;
		std::atomic<SDL_ThreadID> thread_id{ 0 };
		bool                    started = false;
		std::atomic<bool>       cursor_owned{ true }; // The last change of the pointer was made on the thread that owns the windows.

		int thread_main(void*)
		{
			std::unique_lock<std::mutex> guard(lock);
			thread_id = SDL_GetCurrentThreadID();
			for (;;) {
				while (!jobs.empty()) {
					job* next = jobs.front();
					jobs.pop_front();
					guard.unlock();
					next->function(next->data);
					guard.lock();
					next->done = true;
					finished.notify_all();
				}
				guard.unlock();
				// The messages of the windows are handled here, and the events they make wait in the queue of SDL for the program.
				if (SDL_WasInit(SDL_INIT_VIDEO | SDL_INIT_EVENTS)) {
					SDL_PumpEvents();
				}
				guard.lock();
				if (jobs.empty()) {
					wake.wait_for(guard, std::chrono::milliseconds(1));
				}
			}
			return 0;
		}

		bool on_thread()
		{
			return thread_id.load() && (SDL_GetCurrentThreadID() == thread_id.load());
		}
	} // namespace

	bool enabled()
	{
#if defined(_WIN32)
		return bb_env_bool("BLITZLLVM_WINDOW_THREAD", 1) != 0;
#else
		return bb_env_bool("BLITZLLVM_WINDOW_THREAD", 0) != 0;
#endif
	}

	void run(void (*function)(void*), void* data)
	{
		if (!enabled() || on_thread()) {
			function(data);
			return;
		}
		job                          todo{ function, data };
		std::unique_lock<std::mutex> guard(lock);
		if (!started) {
			started = true;
			thread  = SDL_CreateThread(thread_main, "BlitzLLVM windows", nullptr);
			if (!thread) {
				started = false;
				guard.unlock();
				function(data); // No thread to give it to: the program's own does it, as before.
				return;
			}
			SDL_DetachThread(thread); // It lives as long as the program does.
		}
		jobs.push_back(&todo);
		wake.notify_all();
		finished.wait(guard, [&] { return todo.done; });
	}

	bool init(SDL_InitFlags flags)
	{
		// The click that brings a window to the front is a click like any other, as it was on Win32 in the original: a canvas in a window
		// that is not in front gets its $201 (and MouseHit counts it), so a program can start dragging or pressing at once. SDL drops that
		// click unless this is set. A value in the environment still wins, since a hint set here does not override it.
		SDL_SetHint(SDL_HINT_MOUSE_FOCUS_CLICKTHROUGH, "1");
		bool ok = false;
		run([&] { ok = SDL_InitSubSystem(flags); });
		return ok;
	}

	void quit(SDL_InitFlags flags)
	{
		run([&] { SDL_QuitSubSystem(flags); });
	}

	SDL_Window* create_window(const char* title, int width, int height, SDL_WindowFlags flags)
	{
		SDL_Window* window = nullptr;
		run([&] { window = SDL_CreateWindow(title, width, height, flags); });
		return window;
	}

	void destroy_window(SDL_Window* window)
	{
		run([&] { SDL_DestroyWindow(window); });
	}

	void set_window_size(SDL_Window* window, int width, int height)
	{
		run([&] {
			SDL_SetWindowSize(window, width, height);
			SDL_SyncWindow(window);
		});
	}

	void sync_window(SDL_Window* window)
	{
		run([&] { SDL_SyncWindow(window); });
	}

	bool owns_windows()
	{
		return !thread_id.load() || on_thread();
	}

	void set_cursor_visible(bool visible)
	{
		run([&] {
			if (visible) {
				SDL_ShowCursor();
			} else {
				SDL_HideCursor();
			}
			cursor_owned = owns_windows();
		});
	}

	bool cursor_changed_by_owner()
	{
		return cursor_owned;
	}

	void set_cursor(SDL_Cursor* cursor)
	{
		run([&] { SDL_SetCursor(cursor); });
	}

	void set_relative_mouse_mode(SDL_Window* window, bool enabled)
	{
		run([&] { SDL_SetWindowRelativeMouseMode(window, enabled); });
	}

	bool poll_event(SDL_Event* event)
	{
		if (!thread_id.load()) {
			return SDL_PollEvent(event);
		}
		// Not SDL_PollEvent: it would ask the window system for events from this thread, which has no windows.
		return SDL_PeepEvents(event, 1, SDL_GETEVENT, SDL_EVENT_FIRST, SDL_EVENT_LAST) > 0;
	}

	void wait_event(int milliseconds)
	{
		if (!thread_id.load()) {
			SDL_WaitEventTimeout(nullptr, milliseconds);
			return;
		}
		SDL_Delay(milliseconds < 5 ? milliseconds : 5);
	}
} // namespace bb::wnd
