static uint64_t architecture_mask(void)
{
#if defined(BB_CPU_X86)
	return X86_ALL;
#elif defined(BB_CPU_ARM64)
	return 0x7FFull << 32; // BB_CPU_NEON to BB_CPU_SVE2
#else
	return 0;
#endif
}

static int equal_nocase(const char* a, const char* b, size_t length)
{
	for (size_t i = 0; i < length; i++) {
		char x = a[i], y = b[i];
		x = (x >= 'A' && x <= 'Z') ? (char)(x + 32) : x;
		y = (y >= 'A' && y <= 'Z') ? (char)(y + 32) : y;
		if (x != y || !y) {
			return 0;
		}
	}
	return b[length] == 0;
}

uint64_t bb_cpu_apply_override(uint64_t detected, const char* setting, int* unknown)
{
	uint64_t mask = drop_unsatisfied(detected & architecture_mask());
	if (unknown) {
		*unknown = 0;
	}
	if (!setting) {
		return mask;
	}
	const char* p = setting;
	while (*p) {
		while (*p == ',' || *p == ' ') {
			p++;
		}
		const char* end = p;
		while (*end && *end != ',' && *end != ' ') {
			end++;
		}
		size_t length = (size_t)(end - p);
		int    known  = 0;
		if (length == 0) {
			break;
		}
		if (equal_nocase(p, "native", length) || equal_nocase(p, "auto", length)) {
			known = 1;
		} else if (equal_nocase(p, "baseline", length)) {
			mask &= BB_CPU_NEON; // The generic code only: x86-64 has no optional features, arm64 has NEON.
			known = 1;
		} else if (equal_nocase(p, "v2", length) || equal_nocase(p, "v3", length) || equal_nocase(p, "v4", length)) {
#if defined(BB_CPU_X86)
			uint64_t cap = (p[1] == '2') ? X86_V2 : (p[1] == '3') ? X86_V3 : X86_V4;
			// The crypto helpers are no part of the levels, they stay from v3 on only.
			cap |= (p[1] != '2') ? (BB_CPU_PCLMUL | BB_CPU_AES) : 0;
			mask &= cap;
			known = 1;
#endif
		} else if (*p == '-') {
			for (size_t i = 0; i < FEATURE_COUNT; i++) {
				if ((features[i].bit & architecture_mask()) && equal_nocase(p + 1, features[i].name, length - 1)) {
					mask &= ~features[i].bit;
					known = 1;
				}
			}
		}
		if (!known && unknown) {
			(*unknown)++;
		}
		p = end;
	}
	return drop_unsatisfied(mask);
}

// The result is cached in one 64-bit word, with the top bit set once it is known. Detection is cheap and gives the same answer on every
// thread, so two threads racing to fill it is harmless; the atomic accesses only keep a half written word from being read.
#define STATE_READY (1ull << 63)
static volatile uint64_t cached = 0;

static uint64_t load_cached(void)
{
#if defined(BB_CPU_MSVC)
	return (uint64_t)_InterlockedCompareExchange64((volatile __int64*)&cached, 0, 0);
#else
	return __atomic_load_n(&cached, __ATOMIC_ACQUIRE);
#endif
}

static void store_cached(uint64_t value)
{
#if defined(BB_CPU_MSVC)
	_InterlockedExchange64((volatile __int64*)&cached, (__int64)value);
#else
	__atomic_store_n(&cached, value, __ATOMIC_RELEASE);
#endif
}

uint64_t bb_cpu_features(void)
{
	uint64_t value = load_cached();
	if (!(value & STATE_READY)) {
		const char* setting = getenv("BLITZLLVM_CPU");
		int         unknown = 0;
		uint64_t    mask    = bb_cpu_apply_override(detect(), setting, &unknown);
		if (unknown) {
			fprintf(stderr, "BLITZLLVM_CPU=%s: not understood, it is baseline, v2, v3, v4, native or -<feature>, separated by commas.\n", setting);
		}
		value = mask | STATE_READY;
		store_cached(value);
	}
	return value & ~STATE_READY;
}

int bb_cpu_has(uint64_t mask)
{
	return (bb_cpu_features() & mask) == mask;
}

const char* bb_cpu_architecture(void)
{
	return BB_CPU_ARCH;
}

const char* bb_cpu_level(void)
{
#if defined(BB_CPU_X86)
	uint64_t f = bb_cpu_features();
	if ((f & X86_V4) == X86_V4) {
		return "v4";
	}
	if ((f & X86_V3) == X86_V3) {
		return "v3";
	}
	if ((f & X86_V2) == X86_V2) {
		return "v2";
	}
#endif
	return "baseline";
}

size_t bb_cpu_describe(char* buffer, size_t size)
{
	uint64_t f = bb_cpu_features();
	char     text[512];
	int      length = snprintf(text, sizeof(text), "%s %s", bb_cpu_architecture(), bb_cpu_level());
	if (f) {
		length += snprintf(text + length, sizeof(text) - (size_t)length, ":");
	}
	for (size_t i = 0; i < FEATURE_COUNT && length > 0 && (size_t)length < sizeof(text); i++) {
		if (f & features[i].bit) {
			length += snprintf(text + length, sizeof(text) - (size_t)length, " %s", features[i].name);
		}
	}
	if (length < 0) {
		length = 0;
	}
	if (length >= (int)sizeof(text)) {
		length = (int)sizeof(text) - 1;
	}
	if (buffer && size) {
		size_t copy = ((size_t)length < size - 1) ? (size_t)length : size - 1;
		memcpy(buffer, text, copy);
		buffer[copy] = 0;
	}
	return (size_t)length + 1;
}
