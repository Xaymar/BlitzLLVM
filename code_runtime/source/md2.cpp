	// What is in the file, and is the same for all copies of the model.
	struct md2_data {
		int           refs   = 1;
		int           frames = 0, verts = 0, tris = 0;
		buffer<float> positions; // For every frame, for every vertex: x, y, z.
		buffer<float> normals;   // The same.
		buffer<float> uvs;       // For every vertex: u, v.
		buffer<uint32_t> indices;
	};

	// What one copy of the model is doing.
	struct md2_state {
		md2_data*     data = nullptr;
		int           mode = 0; // 0 for none, 1 loop, 2 back and forth, 3 once, and 0x8000 on top while changing from one to the next.
		float         time = 0, speed = 0;
		int           first = 0, last = 0, length = 0;
		int           frame_a = 0, frame_b = 0;
		float         blend = 0;
		float         transition_time = 0, transition_speed = 0;
		buffer<float> from_positions, from_normals; // How it looked when the animation was changed.
	};

	static void release_data(md2_data* d)
	{
		if (--d->refs > 0) {
			return;
		}
		d->positions.release();
		d->normals.release();
		d->uvs.release();
		d->indices.release();
		delete d;
	}

	void destroy_md2(md2_state* s)
	{
		s->from_positions.release();
		s->from_normals.release();
		release_data(s->data);
		delete s;
	}

	md2_state* clone_md2(md2_state const& from)
	{
		md2_state* copy = new md2_state();
		copy->data      = from.data;
		copy->data->refs++;
		return copy; // It stands still, whatever the original is doing.
	}

	static void normalize(float* v)
	{
		float length = sqrtf(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
		if (length > 1e-12f) {
			v[0] /= length;
			v[1] /= length;
			v[2] /= length;
		}
	}

	// How the model looks, between two frames, as positions and normals for the vertices.
	static void pose(md2_data const& d, int frame_a, int frame_b, float blend, float* positions, float* normals)
	{
		const float* pa = d.positions.data + size_t(frame_a) * size_t(d.verts) * 3;
		const float* pb = d.positions.data + size_t(frame_b) * size_t(d.verts) * 3;
		const float* na = d.normals.data + size_t(frame_a) * size_t(d.verts) * 3;
		const float* nb = d.normals.data + size_t(frame_b) * size_t(d.verts) * 3;
		for (size_t i = 0; i < size_t(d.verts) * 3; i++) {
			positions[i] = (pb[i] - pa[i]) * blend + pa[i];
			normals[i]   = (nb[i] - na[i]) * blend + na[i];
		}
	}

	// Where the vertices are now, which is what a change of animation starts from.
	static void current_pose(md2_state const& s, float* positions, float* normals)
	{
		md2_data const& d = *s.data;
		if (s.mode & 0x8000) {
			// On the way from the old pose to the first frame of the new one.
			int          frame = int(s.time);
			frame              = frame < 0 ? 0 : (frame >= d.frames ? d.frames - 1 : frame);
			const float* pf    = d.positions.data + size_t(frame) * size_t(d.verts) * 3;
			const float* nf    = d.normals.data + size_t(frame) * size_t(d.verts) * 3;
			for (size_t i = 0; i < size_t(d.verts) * 3; i++) {
				positions[i] = (pf[i] - s.from_positions[uint32_t(i)]) * s.transition_time + s.from_positions[uint32_t(i)];
				normals[i]   = (nf[i] - s.from_normals[uint32_t(i)]) * s.transition_time + s.from_normals[uint32_t(i)];
			}
		} else {
			pose(d, s.frame_a, s.frame_b, s.blend, positions, normals);
		}
	}

	// Writes how the model looks into its surface.
	static void show(entity& e)
	{
		md2_state& s = *e.md2;
		if (e.surfaces.size == 0) {
			return;
		}
		md2_data const& d = *s.data;
		surface&        surf = *e.surfaces[0];
		buffer<float>   positions, normals;
		positions.reserve(uint32_t(d.verts) * 3);
		normals.reserve(uint32_t(d.verts) * 3);
		current_pose(s, positions.data, normals.data);
		for (int i = 0; i < d.verts && uint32_t(i) < surf.vertices.size; i++) {
			vertex3d& v = surf.vertices[uint32_t(i)];
			v.x         = positions.data[i * 3 + 0];
			v.y         = positions.data[i * 3 + 1];
			v.z         = positions.data[i * 3 + 2];
			float n[3]  = { normals.data[i * 3 + 0], normals.data[i * 3 + 1], normals.data[i * 3 + 2] };
			normalize(n);
			v.nx = n[0];
			v.ny = n[1];
			v.nz = n[2];
		}
		positions.release();
		normals.release();
		surf.dirty       = true;
		surf.bound_valid = false;
	}

	// Moves the animation of a model on by some frames.
	void md2_animate(int handle, float elapsed)
	{
		entity* e = get_entity(handle);
		if (!e || !e->md2 || !e->md2->mode) {
			return;
		}
		md2_state& s = *e->md2;
		if (s.mode & 0x8000) {
			s.transition_time += s.transition_speed;
			if (s.transition_time < 1) {
				show(*e);
				return;
			}
			s.mode &= ~0x8000;
			if (!s.mode) {
				show(*e);
				return;
			}
		}
		s.time += s.speed * elapsed;
		// Past the end of the frames, whatever the mode says happens as often as it takes.
		for (int guard = 0; guard < 64; guard++) {
			if (s.time < float(s.first)) {
				if (s.mode == 1) {
					s.time += float(s.length);
				} else if (s.mode == 2) {
					s.time  = float(s.first) + (float(s.first) - s.time);
					s.speed = -s.speed;
				} else {
					s.time = float(s.first);
					s.mode = 0;
					break;
				}
			} else if (s.time >= float(s.last)) {
				if (s.mode == 1) {
					s.time -= float(s.length);
				} else if (s.mode == 2) {
					s.time  = float(s.last) - (s.time - float(s.last));
					s.speed = -s.speed;
				} else {
					s.time = float(s.last);
					s.mode = 0;
					break;
				}
			} else {
				break;
			}
		}
		s.frame_a = int(floorf(s.time));
		s.frame_b = s.frame_a + 1;
		if (s.mode == 1 && s.frame_b == s.last) {
			s.frame_b = s.first;
		}
		s.frame_a = s.frame_a >= s.data->frames ? s.data->frames - 1 : s.frame_a;
		s.frame_b = s.frame_b >= s.data->frames ? s.data->frames - 1 : s.frame_b;
		s.blend   = s.time - floorf(s.time);
		show(*e);
	}
