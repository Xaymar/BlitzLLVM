// A model from a file, standing in its first frame. 0 if the file is not one.
int32_t bb_load_md2(const char* file, int32_t parent)
{
	if (parent && !get_entity(parent)) {
		bb_runtime_error("LoadMD2: the parent does not exist.");
	}
	md2_data* d = file ? read_md2(file) : nullptr;
	if (!d) {
		return 0;
	}
	int      handle = create_entity(MESH, parent);
	entity*  e      = get_entity(handle);
	e->cls          = "MD2";
	e->md2          = new md2_state();
	e->md2->data    = d;
	e->md2->frame_a = e->md2->frame_b = 0;

	surface* s = create_surface(handle);
	for (int i = 0; i < d->verts; i++) {
		vertex3d v = {};
		v.u        = d->uvs[uint32_t(i) * 2];
		v.v        = d->uvs[uint32_t(i) * 2 + 1];
		v.u2       = v.u;
		v.v2       = v.v;
		v.r = v.g = v.b = v.a = half_one;
		s->vertices.push(v);
	}
	for (uint32_t i = 0; i < d->indices.size; i++) {
		s->indices.push(d->indices[i]);
	}
	show(*e);
	return handle;
}

// AnimateMD2 model, mode, speed, first frame, last frame, transition: mode 0 stops, 1 loops, 2 goes back and forth and
// 3 plays once. With a transition the model changes into the first frame over that many frames.
void bb_animate_md2(int32_t handle, int32_t mode, float speed, int32_t first, int32_t last, float transition)
{
	md2_state& s = need_md2(handle, "AnimateMD2");
	int        frames = s.data->frames;
	if (last < first) {
		int t = first;
		first = last;
		last  = t;
	}
	first = first < 0 ? 0 : (first >= frames ? frames - 1 : first);
	last  = last < 0 ? 0 : (last >= frames ? frames - 1 : last);

	if (transition > 0) {
		uint32_t count = uint32_t(s.data->verts) * 3;
		buffer<float> positions, normals;
		positions.reserve(count);
		normals.reserve(count);
		current_pose(s, positions.data, normals.data);
		s.from_positions.release();
		s.from_normals.release();
		s.from_positions = positions;
		s.from_normals   = normals;
		s.from_positions.size = s.from_normals.size = count;
		s.transition_speed = 1.0f / transition;
		s.transition_time  = 0;
		mode |= 0x8000;
	}

	s.first  = first;
	s.last   = last;
	s.length = last - first;
	s.speed  = speed;
	s.time   = (((mode & 0x7fff) == 1) || (speed >= 0)) ? float(first) : float(last);
	s.mode   = mode;
	if ((speed == 0) || (s.length == 0)) {
		s.frame_a = s.frame_b = int(s.time);
		s.blend   = 0;
		s.mode &= 0x8000;
	}
}

float bb_md2_anim_time(int32_t handle)
{
	return need_md2(handle, "MD2AnimTime").time;
}

int32_t bb_md2_anim_length(int32_t handle)
{
	return need_md2(handle, "MD2AnimLength").data->frames;
}

int32_t bb_md2_animating(int32_t handle)
{
	return need_md2(handle, "MD2Animating").mode ? 1 : 0;
}
