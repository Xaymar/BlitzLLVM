// How much higher a sound is heard than it is made, for a source that moves away from a listener at speed_away and a listener
// that moves toward the source at speed_toward (in meters per second, negative for the other way). The doppler scale makes the
// shift stronger or weaker, and none of it is there for a scale of 0.
float bb_doppler_ratio(float speed_toward, float speed_away, float scale, float sound_speed)
{
	if ((scale <= 0.0f) || (sound_speed <= 0.0f)) {
		return 1.0f;
	}
	// Nothing moves faster than the sound does, which would turn the shift around or make it infinite.
	float limit = sound_speed * 0.9f;
	speed_toward = bb_clamp(speed_toward, -limit, limit);
	speed_away   = bb_clamp(speed_away, -limit, limit);
	float ratio  = (sound_speed + speed_toward) / (sound_speed + speed_away);
	ratio        = 1.0f + (ratio - 1.0f) * scale;
	return bb_clamp(ratio, 0.25f, 4.0f);
}

// Programs move things in steps, and this is called more often than that (every time that Delay waits), so the speed is the
// distance of the last step over the time that it took. Something that stays where it is for a while has stopped.
static void bb_motion_update(bb_motion* motion, const float* position, Uint64 now)
{
	if (!motion->known) {
		memcpy(motion->position, position, sizeof(motion->position));
		memset(motion->speed, 0, sizeof(motion->speed));
		motion->time  = now;
		motion->known = 1;
		return;
	}
	float dx = position[0] - motion->position[0], dy = position[1] - motion->position[1], dz = position[2] - motion->position[2];
	float seconds = (float)(now - motion->time) / 1e9f;
	if (dx * dx + dy * dy + dz * dz > 1e-12f) {
		if (seconds > 0.001f) {
			motion->speed[0] = dx / seconds;
			motion->speed[1] = dy / seconds;
			motion->speed[2] = dz / seconds;
		}
		memcpy(motion->position, position, sizeof(motion->position));
		motion->time = now;
	} else if (seconds > 0.25f) {
		memset(motion->speed, 0, sizeof(motion->speed));
	}
}

// The curves of volume by distance. 0 is the curve of this runtime, 1 the curve of the original and 2 the one of SoLoud.
enum { BB_FALLOFF_NEW = 0, BB_FALLOFF_LEGACY = 1, BB_FALLOFF_SOLOUD = 2 };

// What new channels start with: SetFalloff if it was called, else BLITZLLVM_VOLUME_FALLOFF ("new" or unset, "legacy", "soloud").
static int bb_falloff_default(void)
{
	if (!bb_audio.falloff_known) {
		const char* text = bb_env("BLITZLLVM_VOLUME_FALLOFF");
		int model        = BB_FALLOFF_NEW;
		if (text && !SDL_strcasecmp(text, "soloud")) {
			model = BB_FALLOFF_SOLOUD;
		} else if (text && !SDL_strcasecmp(text, "legacy")) {
			model = BB_FALLOFF_LEGACY;
		}
		bb_audio.falloff_default = model;
		bb_audio.falloff_known   = 1;
	}
	return bb_audio.falloff_default;
}

static int bb_falloff_check(int32_t mode, const char* message)
{
	if (mode < BB_FALLOFF_NEW || mode > BB_FALLOFF_SOLOUD) {
		bb_runtime_error(message);
	}
	return (int)mode;
}

void bb_set_falloff(int32_t mode)
{
	bb_audio.falloff_default = bb_falloff_check(mode, "SetFalloff: the mode has to be 0 (new), 1 (legacy) or 2 (soloud)");
	bb_audio.falloff_known   = 1;
}

int32_t bb_get_falloff(void)
{
	return bb_falloff_default();
}

void bb_set_channel_falloff(int32_t handle, int32_t mode)
{
	int         checked = bb_falloff_check(mode, "SetChannelFalloff: the mode has to be 0 (new), 1 (legacy) or 2 (soloud)");
	bb_channel* channel = bb_channel_get(handle, "SetChannelFalloff");
	if (channel) {
		channel->falloff = checked; // Heard from the next update of the sounds.
	}
}

int32_t bb_get_channel_falloff(int32_t handle)
{
	bb_channel* channel = bb_channel_get(handle, "GetChannelFalloff");
	return channel ? channel->falloff : bb_falloff_default();
}

// How loud a sound is at a distance (in meters) from the listener, by the curve of its channel: "new" is the curve of this runtime,
// "soloud" is the inverse distance model of SoLoud (minimum distance of a meter), and "legacy" is the curve of the original, which FMOD 3
// mixed like DirectSound3D does: full volume up to a meter, then the rolloff is the exponent of the inverse of the distance.
static float bb_distance_gain(float meters, float rolloff, int model)
{
	if (model == BB_FALLOFF_SOLOUD) {
		return meters <= 1.0f ? 1.0f : 1.0f / (1.0f + rolloff * (meters - 1.0f));
	}
	if (model == BB_FALLOFF_LEGACY) {
		return meters <= 1.0f ? 1.0f : powf(meters, -rolloff);
	}
	return 1.0f / (1.0f + rolloff * meters * 0.05f);
}

// What a setting of the listener is at the time `now`.
static float bb_fade_value(const bb_fade* fade, Uint64 now)
{
	if ((fade->length == 0) || (now >= fade->start + fade->length)) {
		return fade->to;
	}
	float t = (float)(now - fade->start) / (float)fade->length;
	return fade->from + (fade->to - fade->from) * t;
}

// Lets a setting glide from what it is now to `value` over `milliseconds` (0 changes it at once).
static void bb_fade_to(bb_fade* fade, float value, int32_t milliseconds)
{
	Uint64 now   = SDL_GetTicksNS();
	fade->from   = bb_fade_value(fade, now);
	fade->to     = value;
	fade->start  = now;
	fade->length = milliseconds > 0 ? (Uint64)milliseconds * 1000000ull : 0;
}

static void bb_fade_set(bb_fade* fade, float value)
{
	fade->from = fade->to = value;
	fade->start = fade->length = 0;
}

static int32_t bb_fade_check(int32_t milliseconds, const char* message)
{
	if (milliseconds < 0) {
		bb_runtime_error(message);
	}
	return milliseconds;
}

