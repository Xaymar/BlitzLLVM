void bb_stop_channel(int32_t handle)
{
	bb_channel* channel = bb_channel_get(handle);
	if (channel) {
		MIX_StopTrack(channel->track, 0);
		MIX_DestroyTrack(channel->track);
		memset(channel, 0, sizeof(*channel));
	}
}

void bb_pause_channel(int32_t handle)
{
	bb_channel* channel = bb_channel_get(handle);
	if (channel) {
		MIX_PauseTrack(channel->track);
	}
}

void bb_resume_channel(int32_t handle)
{
	bb_channel* channel = bb_channel_get(handle);
	if (channel) {
		MIX_ResumeTrack(channel->track);
	}
}

int32_t bb_channel_playing(int32_t handle)
{
	bb_channel* channel = bb_channel_get(handle);
	return (channel && (MIX_TrackPlaying(channel->track) || MIX_TrackPaused(channel->track))) ? 1 : 0;
}

void bb_channel_volume(int32_t handle, float volume)
{
	bb_channel* channel = bb_channel_get(handle);
	if (channel) {
		channel->volume = bb_clamp(volume, 0.0f, 1.0f);
		bb_channel_apply(channel, channel->volume, channel->pan);
	}
}

void bb_channel_pan(int32_t handle, float pan)
{
	bb_channel* channel = bb_channel_get(handle);
	if (channel) {
		channel->pan = bb_clamp(pan, -1.0f, 1.0f);
		bb_channel_apply(channel, channel->volume, channel->pan);
	}
}

void bb_channel_pitch(int32_t handle, int32_t hertz)
{
	bb_channel* channel = bb_channel_get(handle);
	if (channel && (hertz > 0)) {
		bb_sound* sound = &bb_sounds[channel->sound];
		if (sound->frequency > 0) {
			channel->ratio = (float)hertz / (float)sound->frequency;
			MIX_SetTrackFrequencyRatio(channel->track, channel->ratio);
		}
	}
}

