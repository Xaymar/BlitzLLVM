// Takes the sound device down before the program ends, as its thread would run on while the libraries unwind.
static void bb_audio_shutdown(void)
{
	for (int32_t i = 1; i < bb_audio.channel_count; i++) {
		if (bb_audio.channels[i].used) {
			MIX_DestroyTrack(bb_audio.channels[i].track);
		}
	}
	for (int32_t i = 1; i < bb_audio.sound_count; i++) {
		if (bb_audio.sounds[i].audio) {
			MIX_DestroyAudio(bb_audio.sounds[i].audio);
		}
	}
	if (bb_audio.mixer) {
		MIX_DestroyMixer(bb_audio.mixer);
		bb_audio.mixer = NULL;
	}
	MIX_Quit();
	SDL_QuitSubSystem(SDL_INIT_AUDIO);
}

static int bb_audio_ready(void)
{
	if (bb_audio.tried) {
		return bb_audio.mixer != NULL;
	}
	bb_audio.tried = 1;
	if (bb_env_bool("BLITZLLVM_HEADLESS", 0)) {
		return 0;
	}
	bb_open_audio_codecs();
	if (!SDL_InitSubSystem(SDL_INIT_AUDIO) || !MIX_Init()) {
		return 0;
	}
	bb_audio.mixer = MIX_CreateMixerDevice(SDL_AUDIO_DEVICE_DEFAULT_PLAYBACK, NULL);
	bb_on_exit(bb_audio_shutdown);
	return bb_audio.mixer != NULL;
}

// The original plays sounds through FMOD, which brings them to the speakers' rate by linear interpolation. That adds a lot of high frequencies
// (the mirror images of the sound above its own rate) and rolls off the top a little, which is what people remember. SDL_mixer resamples cleanly
// instead, so sounds with a low rate seem muffled next to the original. Setting BLITZLLVM_LEGACY_AUDIO_RESAMPLING does the original's resampling here, once,
// when the sound is loaded.
static MIX_Audio* bb_classic_audio(const char* path, const SDL_AudioSpec* file)
{
	SDL_AudioSpec device;
	if (!MIX_GetMixerFormat(bb_audio.mixer, &device) || (device.freq <= 0) || (file->channels <= 0) || (file->freq <= 0)) {
		return NULL;
	}
	MIX_AudioDecoder* decoder = MIX_CreateAudioDecoder(path, 0);
	if (!decoder) {
		return NULL;
	}
	SDL_AudioSpec spec;
	spec.format   = SDL_AUDIO_F32;
	spec.channels = file->channels;
	spec.freq     = file->freq;

	size_t capacity = 1 << 16, used = 0;
	char*  data     = (char*)bb_malloc_or_fail(capacity);
	for (;;) {
		if (used + 8192 > capacity) {
			capacity *= 2;
			data = (char*)bb_realloc_or_fail(data, capacity);
		}
		int got = MIX_DecodeAudio(decoder, data + used, 8192, &spec);
		if (got <= 0) {
			break;
		}
		used += (size_t)got;
	}
	MIX_DestroyAudioDecoder(decoder);

	int      channels = file->channels;
	size_t   frames   = used / (sizeof(float) * (size_t)channels);
	size_t   out      = (size_t)((double)frames * device.freq / file->freq);
	MIX_Audio* audio  = NULL;
	if (frames > 1 && out > 1) {
		float* in  = (float*)data;
		float* res = (float*)bb_malloc_or_fail(out * (size_t)channels * sizeof(float));
		double step = (double)file->freq / device.freq;
		for (size_t i = 0; i < out; i++) {
			double  at = (double)i * step;
			size_t  a  = (size_t)at;
			size_t  b  = (a + 1 < frames) ? a + 1 : a;
			float   t  = (float)(at - (double)a);
			for (int c = 0; c < channels; c++) {
				res[i * channels + c] = in[a * channels + c] * (1.0f - t) + in[b * channels + c] * t;
			}
		}
		SDL_AudioSpec result;
		result.format   = SDL_AUDIO_F32;
		result.channels = channels;
		result.freq     = device.freq;
		audio = MIX_LoadRawAudio(bb_audio.mixer, res, out * (size_t)channels * sizeof(float), &result);
		bb_free(res);
	}
	bb_free(data);
	return audio;
}

static float bb_clamp(float v, float lo, float hi)
{
	return v < lo ? lo : (v > hi ? hi : v);
}

static bb_sound* bb_sound_get(int32_t handle, const char* what)
{
	static bb_sound none; // Programs pass the 0 of a sound that failed to load, which Blitz ignores (also in a debug build).
	if (handle == 0) {
		memset(&none, 0, sizeof(none));
		return &none;
	}
	if ((handle < 0) || (handle >= bb_audio.sound_count) || !bb_audio.sounds[handle].used) {
		bb_handle_error(what, "sound", handle);
	}
	return &bb_audio.sounds[handle];
}

static bb_channel* bb_channel_get(int32_t handle, const char* what)
{
	if (((handle < 0) || (handle >= bb_audio.channel_count)) && bb_audio.channel_count > 0) {
		BB_DEBUG_HANDLE_MISSING(what, "channel", handle); // A channel that was never given out. The ones that are over are fine to ask about.
	}
	if ((handle <= 0) || (handle >= bb_audio.channel_count) || !bb_audio.channels[handle].used) {
		return NULL; // Channels end by themselves, programs can still hold on to them.
	}
	return &bb_audio.channels[handle];
}

static int32_t bb_load(const char* path, int is_3d)
{
	if (!path) {
		return 0;
	}
	char* real = bb_path(path);

	bb_sound sound;
	memset(&sound, 0, sizeof(sound));
	sound.used   = 1;
	sound.volume = 1.0f;
	sound.is_3d  = is_3d;

	if (bb_audio_ready()) {
		sound.audio = MIX_LoadAudio(bb_audio.mixer, real, true);
		if (!sound.audio) {
			if (SDL_GetPathInfo(real, NULL)) {
				bb_report_missing_audio_codec(real); // Only for files that are there, so that a missing library is what is reported.
			}
			bb_free(real);
			return 0; // Missing or unusable files give 0, like in Blitz.
		}
		SDL_AudioSpec spec;
		if (MIX_GetAudioFormat(sound.audio, &spec)) {
			sound.frequency = spec.freq;
			if (bb_env_bool("BLITZLLVM_LEGACY_AUDIO_RESAMPLING", 0)) {
				MIX_Audio* classic = bb_classic_audio(real, &spec);
				if (classic) {
					MIX_DestroyAudio(sound.audio);
					sound.audio = classic;
				}
			}
		}
	} else {
		// No sound device: just remember that the file is there.
		FILE* file = fopen(real, "rb");
		if (!file) {
			bb_free(real);
			return 0;
		}
		fclose(file);
	}
	bb_free(real);

	for (int32_t i = 1; i < bb_audio.sound_count; i++) {
		if (!bb_audio.sounds[i].used) {
			bb_audio.sounds[i] = sound;
			return i;
		}
	}
	if (bb_audio.sound_count >= bb_audio.sound_cap) {
		bb_audio.sound_cap = bb_audio.sound_cap ? bb_audio.sound_cap * 2 : 64;
		bb_audio.sounds    = (bb_sound*)bb_realloc_or_fail(bb_audio.sounds, (size_t)bb_audio.sound_cap * sizeof(bb_sound));
	}
	bb_audio.sounds[bb_audio.sound_count] = sound;
	return bb_audio.sound_count++;
}

