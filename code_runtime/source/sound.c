// Sets the track to what the channel says. Gains are 0 to 1, and the pan from left (-1) to right (1).
// ChannelVolume and ChannelPan set what the program wants, the position of the entity is on top of that.
static void bb_channel_apply(bb_channel* channel)
{
	float volume = channel->volume * channel->gain3d;
	float pan    = bb_clamp(channel->pan + channel->pan3d, -1.0f, 1.0f);
	MIX_SetTrackGain(channel->track, bb_clamp(volume, 0.0f, 1.0f));
	MIX_StereoGains gains;
	gains.left  = pan > 0 ? 1.0f - pan : 1.0f;
	gains.right = pan < 0 ? 1.0f + pan : 1.0f;
	MIX_SetTrackStereo(channel->track, &gains);
}

static int32_t bb_play(int32_t handle, int32_t entity, const char* what)
{
	bb_sound* sound = bb_sound_get(handle, what);
	if (!bb_audio.mixer || !sound->audio) {
		return 0;
	}

	// Reuse the slot of a channel that is over.
	int32_t slot = 0;
	for (int32_t i = 1; i < bb_audio.channel_count; i++) {
		if (bb_audio.channels[i].used && !MIX_TrackPlaying(bb_audio.channels[i].track) && !MIX_TrackPaused(bb_audio.channels[i].track)) {
			MIX_DestroyTrack(bb_audio.channels[i].track);
			memset(&bb_audio.channels[i], 0, sizeof(bb_channel));
		}
		if (!slot && !bb_audio.channels[i].used) {
			slot = i;
		}
	}
	if (!slot) {
		if (bb_audio.channel_count >= bb_audio.channel_cap) {
			bb_audio.channel_cap = bb_audio.channel_cap ? bb_audio.channel_cap * 2 : 64;
			bb_audio.channels    = (bb_channel*)bb_realloc(bb_audio.channels, (size_t)bb_audio.channel_cap * sizeof(bb_channel));
		}
		slot = bb_audio.channel_count++;
	}

	bb_channel* channel = &bb_audio.channels[slot];
	memset(channel, 0, sizeof(*channel));
	channel->track = MIX_CreateTrack(bb_audio.mixer);
	if (!channel->track) {
		return 0;
	}
	channel->used      = 1;
	channel->sound     = handle;
	channel->entity    = entity;
	channel->volume    = sound->volume;
	channel->pan       = sound->pan;
	channel->frequency = sound->pitch;
	channel->ratio     = 1.0f;
	channel->gain3d    = 1.0f;

	MIX_SetTrackAudio(channel->track, sound->audio);
	if (sound->pitch > 0 && sound->frequency > 0) {
		channel->ratio = (float)sound->pitch / (float)sound->frequency;
		MIX_SetTrackFrequencyRatio(channel->track, channel->ratio);
	}
	bb_channel_apply(channel);
	// The loop count has to be given while starting, MIX_SetTrackLoops does nothing for a track that is not playing yet.
	SDL_PropertiesID options = SDL_CreateProperties();
	SDL_SetNumberProperty(options, MIX_PROP_PLAY_LOOPS_NUMBER, sound->loop ? -1 : 0);
	MIX_PlayTrack(channel->track, options);
	SDL_DestroyProperties(options);
	return slot;
}

int32_t bb_play_sound(int32_t handle)
{
	return bb_play(handle, 0, "PlaySound");
}

