	size_t block_bytes(block_format format, int width, int height)
	{
		size_t per_block = (format == block_format::bc1 || format == block_format::bc4) ? 8 : 16;
		return size_t((width + 3) / 4) * size_t((height + 3) / 4) * per_block;
	}

	void decode_blocks(block_format format, int width, int height, const uint8_t* data, uint8_t* out)
	{
		size_t per_block = block_bytes(format, 4, 4);
		bool   unused    = false;
		rgba   tile[16];
		for (int by = 0; by < (height + 3) / 4; by++) {
			for (int bx = 0; bx < (width + 3) / 4; bx++) {
				const uint8_t* src = data + (size_t(by) * size_t((width + 3) / 4) + size_t(bx)) * per_block;
				switch (format) {
				case block_format::bc1: decode_bc1_block(src, tile, unused); break;
				case block_format::bc2: decode_bc23_block(src, tile, false); break;
				case block_format::bc3: decode_bc23_block(src, tile, true); break;
				case block_format::bc4: decode_bc4_block_grey(src, tile); break;
				case block_format::bc5: decode_bc5_block(src, tile); break;
				default: decode_bc7_block(src, tile); break;
				}
				for (int i = 0; i < 16; i++) {
					int x = bx * 4 + (i & 3), y = by * 4 + (i >> 2);
					if ((x < width) && (y < height)) {
						memcpy(out + (size_t(y) * size_t(width) + size_t(x)) * 4, &tile[i], 4);
					}
				}
			}
		}
	}

	namespace {
		// Makes the surface of RGBA pixels, without alpha if there is none.
		SDL_Surface* make_surface(const uint8_t* pixels, int width, int height, bool has_alpha)
		{
			SDL_Surface* surface = SDL_CreateSurface(width, height, has_alpha ? SDL_PIXELFORMAT_RGBA32 : SDL_PIXELFORMAT_RGBX32);
			if (!surface) {
				return nullptr;
			}
			for (int y = 0; y < height; y++) {
				uint8_t* row = static_cast<uint8_t*>(surface->pixels) + size_t(y) * size_t(surface->pitch);
				memcpy(row, pixels + size_t(y) * size_t(width) * 4, size_t(width) * 4);
				if (!has_alpha) {
					for (int x = 0; x < width; x++) {
						row[x * 4 + 3] = 255;
					}
				}
			}
			return surface;
		}

		// Reads the header, and then either keeps the blocks or decodes the pixels of an uncompressed picture.
		bool parse_dds(const uint8_t* file, size_t size, picture& out)
		{
			if ((size < 128) || (read32(file) != fourcc('D', 'D', 'S', ' ')) || (read32(file + 4) != 124)) {
				return false;
			}
			const uint8_t* header = file + 4;
			uint32_t       height = read32(header + 8), width = read32(header + 12);
			if ((width < 1) || (height < 1) || (width > max_size) || (height > max_size)) {
				return false;
			}
			format f;
			size_t offset;
			if (!describe(header, f, offset) || (size < offset + 4)) {
				return false;
			}
			// The offset counts from after the magic.
			const uint8_t* data      = file + 4 + offset;
			size_t         available = size - (4 + offset);

			if (f.type != block_format::none) {
				// The levels of the first face follow each other, from the biggest to the smallest. A file that ends early
				// keeps the ones that are whole.
				uint32_t stored = (read32(header + 4) & 0x20000) ? read32(header + 24) : 1, levels = 1; // DDSD_MIPMAPCOUNT
				stored          = stored > 1 ? stored : 1;
				size_t bytes    = block_bytes(f.type, int(width), int(height));
				if (available < bytes) {
					return false;
				}
				for (uint32_t level = 1; level < stored && level < mip_count(width, height); level++) {
					size_t more = block_bytes(f.type, int(std::max(width >> level, 1u)), int(std::max(height >> level, 1u)));
					if (available < bytes + more) {
						break;
					}
					bytes += more;
					levels++;
				}
				out.block  = f.type;
				out.width  = int(width);
				out.height = int(height);
				out.size   = bytes;
				out.mips   = int(levels);
				out.blocks = static_cast<uint8_t*>(malloc(bytes));
				if (!out.blocks) {
					return false;
				}
				memcpy(out.blocks, data, bytes);
				// BC2 and BC3 always count as having alpha. For BC1 and BC7 it depends on what is in the blocks.
				if ((f.type == block_format::bc2) || (f.type == block_format::bc3)) {
					out.has_alpha = true;
				} else if ((f.type == block_format::bc1) || (f.type == block_format::bc7)) {
					uint8_t* pixels = static_cast<uint8_t*>(malloc(size_t(width) * height * 4));
					if (pixels) {
						decode_blocks(f.type, int(width), int(height), data, pixels);
						for (size_t i = 0; i < size_t(width) * height; i++) {
							if (pixels[i * 4 + 3] != 255) {
								out.has_alpha = true;
								break;
							}
						}
						free(pixels);
					}
				}
				return true;
			}
			if (available < size_t(width) * height * (f.bits / 8)) {
				return false;
			}

			uint8_t* pixels = static_cast<uint8_t*>(malloc(size_t(width) * height * 4));
			if (!pixels) {
				return false;
			}
			int bytes = int(f.bits / 8);
			int shift[4], count[4];
			for (int c = 0; c < 4; c++) {
				shift[c] = mask_shift(f.mask[c]);
				count[c] = mask_bits(f.mask[c]);
			}
			bool has_alpha = f.mask[3] != 0;
			for (uint32_t y = 0; y < height; y++) {
				for (uint32_t x = 0; x < width; x++) {
					const uint8_t* src = data + (size_t(y) * width + x) * size_t(bytes);
					uint32_t       v   = 0;
					for (int i = 0; i < bytes; i++) {
						v |= uint32_t(src[i]) << (8 * i);
					}
					uint8_t* dst = pixels + (size_t(y) * width + x) * 4;
					for (int c = 0; c < 4; c++) {
						if (f.mask[c]) {
							dst[c] = expand((v & f.mask[c]) >> shift[c], count[c]);
						} else {
							dst[c] = (c == 3 || f.alpha_only) ? 255 : 0;
						}
					}
					if (f.alpha_only) {
						dst[0] = dst[1] = dst[2] = 255;
					}
				}
			}
			out.surface   = make_surface(pixels, int(width), int(height), has_alpha);
			out.width     = int(width);
			out.height    = int(height);
			out.has_alpha = has_alpha;
			free(pixels);
			return out.surface != nullptr;
		}
	} // namespace

	void free_picture(picture& p)
	{
		if (p.surface) {
			SDL_DestroySurface(p.surface);
		}
		free(p.blocks);
		p = picture();
	}

	SDL_Surface* picture_surface(picture& p)
	{
		SDL_Surface* surface = p.surface;
		if (!surface && p.blocks) {
			uint8_t* pixels = static_cast<uint8_t*>(malloc(size_t(p.width) * size_t(p.height) * 4));
			if (pixels) {
				decode_blocks(p.block, p.width, p.height, p.blocks, pixels);
				surface = make_surface(pixels, p.width, p.height, p.has_alpha);
				free(pixels);
			}
		}
		p.surface = nullptr;
		free_picture(p);
		return surface;
	}

	// Finds the hull of sprites for blocks that stay compressed on the GPU: the first level is decoded on the side for its alpha.
	void picture_sprite_hull(picture const& p, int flags, sprite_hull& hull)
	{
		if (!p.blocks || p.width <= 0 || p.height <= 0) {
			return;
		}
		uint8_t* pixels = static_cast<uint8_t*>(malloc(size_t(p.width) * size_t(p.height) * 4));
		if (pixels) {
			decode_blocks(p.block, p.width, p.height, p.blocks, pixels);
			sprite_hull_compute(hull, pixels, p.width, p.height, size_t(p.width), flags);
			free(pixels);
		}
	}

	// The codecs for AVIF, JPEG XL and WebP are shared libraries next to the program (blitzcc copies them there from the runtime directory). SDL_image
	// opens them by their name, which only finds them next to the program on Windows. So they are opened here by their path first, which makes the
	// system find them by the name that they are loaded under. A format whose library is missing is reported once instead of silently not loading.
	struct codec_family {
		const char* name;       // In the file name of the library.
		const char* extensions; // Of the files that need it, each in lower case and between spaces.
		bool        found;
	};
	codec_family codec_families[] = { { "avif", " avif ", false }, { "jxl", " jxl ", false }, { "webp", " webp ", false } };

	void open_codec_libraries()
	{
		static bool opened = false;
		if (opened) {
			return;
		}
		opened            = true;
		const char* base = SDL_GetBasePath();
		int         count = 0;
		char**      names = base ? SDL_GlobDirectory(base, nullptr, 0, &count) : nullptr;
		for (int i = 0; i < count; i++) {
			std::string name = names[i];
			bool        shared = (name.find(".dll") != std::string::npos) || (name.find(".dylib") != std::string::npos) || (name.find(".so.") != std::string::npos);
			for (auto family : { "avcodec", "avformat", "avutil", "swscale", "swresample" }) {
				shared = shared && (name.find(family) == std::string::npos);
			}
			if (!shared) {
				continue;
			}
			bool opened_library = SDL_LoadObject((std::string(base) + name).c_str()) != nullptr;
			for (auto& family : codec_families) {
				family.found = family.found || (opened_library && (name.find(family.name) != std::string::npos));
			}
		}
		SDL_free(names);
	}

	void report_missing_codec(const char* file)
	{
		const char* dot = strrchr(file, '.');
		if (!dot) {
			return;
		}
		std::string extension = std::string(" ") + (dot + 1) + " ";
		for (auto& c : extension) {
			c = char(tolower(static_cast<unsigned char>(c)));
		}
		for (auto& family : codec_families) {
			if (!family.found && (strstr(family.extensions, extension.c_str()) != nullptr)) {
				family.found = true; // Only once.
				fprintf(stderr, "warning: Can't load '%s': the %s library that opens these files was not found next to the program. Copy it from the runtime directory of BlitzLLVM next to the program.\n", file, family.name);
			}
		}
	}

	bool load_picture_memory(const char* name, const void* data, size_t size, picture& out)
	{
		if ((size >= 4) && (read32(static_cast<const uint8_t*>(data)) == fourcc('D', 'D', 'S', ' '))) {
			bool done = parse_dds(static_cast<const uint8_t*>(data), size, out);
			if (!done) {
				free_picture(out);
			}
			return done;
		}
		SDL_IOStream* io = SDL_IOFromConstMem(data, size);
		if (!io) {
			return false;
		}
		open_codec_libraries();
		// TGA files have no marker at the start that tells them from other files, so SDL_image only reads them when it is told by the
		// extension that the file is one.
		const char* dot = strrchr(name, '.');
		out.surface     = IMG_LoadTyped_IO(io, true, dot ? dot + 1 : nullptr);
		if (!out.surface) {
			report_missing_codec(name);
			return false;
		}
		out.width     = out.surface->w;
		out.height    = out.surface->h;
		out.has_alpha = SDL_ISPIXELFORMAT_ALPHA(out.surface->format);
		return true;
	}

	bool load_picture(const char* file, picture& out)
	{
		size_t size = 0;
		void*  data = SDL_LoadFile(bb_native_path(file), &size);
		if (!data) {
			return false;
		}
		bool done = load_picture_memory(file, data, size, out);
		SDL_free(data);
		return done;
	}

	// The formats that SDL_image and the DDS reader open, by the first bytes. Anything else is decoded by the caller, so that
	// a file that is no picture still gives 0 from the Load command.
	bool picture_recognized(const uint8_t* d, size_t n)
	{
		if (n < 12) {
			return false;
		}
		return !memcmp(d, "\x89PNG", 4) || ((d[0] == 0xFF) && (d[1] == 0xD8)) || !memcmp(d, "GIF8", 4) || !memcmp(d, "DDS ", 4) || ((d[0] == 'B') && (d[1] == 'M')) || (!memcmp(d, "RIFF", 4) && !memcmp(d + 8, "WEBP", 4)) || !memcmp(d + 4, "ftypavif", 8) || ((d[0] == 0xFF) && (d[1] == 0x0A)) || !memcmp(d, "\x00\x00\x00\x0cJXL ", 8);
	}

	SDL_Surface* load_surface(const char* file)
	{
		picture p;
		if (!load_picture(file, p)) {
			return nullptr;
		}
		return picture_surface(p);
	}

