	constexpr uint32_t fourcc(char a, char b, char c, char d)
	{
		return uint32_t(uint8_t(a)) | (uint32_t(uint8_t(b)) << 8) | (uint32_t(uint8_t(c)) << 16) | (uint32_t(uint8_t(d)) << 24);
	}

	constexpr uint32_t PF_ALPHAPIXELS = 0x1, PF_ALPHA = 0x2, PF_FOURCC = 0x4, PF_RGB = 0x40, PF_LUMINANCE = 0x20000;
	constexpr int      max_size       = 16384;

	uint32_t read32(const uint8_t* p)
	{
		return uint32_t(p[0]) | (uint32_t(p[1]) << 8) | (uint32_t(p[2]) << 16) | (uint32_t(p[3]) << 24);
	}

	struct format {
		block_format type  = block_format::none;
		uint32_t bits      = 0; // Bits per pixel, for masks.
		uint32_t mask[4]   = { 0, 0, 0, 0 }; // Red, green, blue, alpha.
		bool     luminance = false;
		bool     alpha_only = false;
	};

	// Converts a value of some bits to 8 bits by repeating its top bits.
	uint8_t expand(uint32_t value, int bits)
	{
		if (bits >= 8) {
			return uint8_t(value >> (bits - 8));
		}
		if (bits <= 0) {
			return 0;
		}
		uint32_t out = value << (8 - bits);
		for (int shift = bits; shift < 8; shift <<= 1) {
			out |= out >> shift;
		}
		return uint8_t(out);
	}

	struct rgba {
		uint8_t r, g, b, a;
	};

	// The colors of a block. With transparency (DXT1) the block has 4 colors when the first is bigger than the second and 3 and
	// see-through black otherwise. BC2 and BC3 blocks always have 4.
	void decode_bc1_colors(const uint8_t* src, rgba* palette, bool transparency)
	{
		uint32_t c0 = src[0] | (src[1] << 8), c1 = src[2] | (src[3] << 8);
		auto     unpack = [](uint32_t c) { return rgba{ expand((c >> 11) & 31, 5), expand((c >> 5) & 63, 6), expand(c & 31, 5), 255 }; };
		palette[0] = unpack(c0);
		palette[1] = unpack(c1);
		if (!transparency || (c0 > c1)) {
			palette[2] = { uint8_t((2 * palette[0].r + palette[1].r) / 3), uint8_t((2 * palette[0].g + palette[1].g) / 3), uint8_t((2 * palette[0].b + palette[1].b) / 3), 255 };
			palette[3] = { uint8_t((palette[0].r + 2 * palette[1].r) / 3), uint8_t((palette[0].g + 2 * palette[1].g) / 3), uint8_t((palette[0].b + 2 * palette[1].b) / 3), 255 };
		} else {
			palette[2] = { uint8_t((palette[0].r + palette[1].r) / 2), uint8_t((palette[0].g + palette[1].g) / 2), uint8_t((palette[0].b + palette[1].b) / 2), 255 };
			palette[3] = { 0, 0, 0, 0 };
		}
	}

	// The 16 values of a BC4 block, which is the alpha of a DXT5 block.
	void decode_bc4_block(const uint8_t* src, uint8_t* out)
	{
		uint8_t v[8];
		v[0] = src[0];
		v[1] = src[1];
		if (v[0] > v[1]) {
			for (int i = 1; i < 7; i++) {
				v[i + 1] = uint8_t(((7 - i) * v[0] + i * v[1]) / 7);
			}
		} else {
			for (int i = 1; i < 5; i++) {
				v[i + 1] = uint8_t(((5 - i) * v[0] + i * v[1]) / 5);
			}
			v[6] = 0;
			v[7] = 255;
		}
		uint64_t bits = 0;
		for (int i = 0; i < 6; i++) {
			bits |= uint64_t(src[2 + i]) << (8 * i);
		}
		for (int i = 0; i < 16; i++) {
			out[i] = v[(bits >> (3 * i)) & 7];
		}
	}

	void decode_bc1_block(const uint8_t* src, rgba* out, bool& has_alpha)
	{
		rgba palette[4];
		decode_bc1_colors(src, palette, true);
		uint32_t bits = read32(src + 4);
		for (int i = 0; i < 16; i++) {
			out[i] = palette[(bits >> (2 * i)) & 3];
			if (out[i].a != 255) {
				has_alpha = true;
			}
		}
	}

	// A BC2 or BC3 block has the colors of a BC1 block, after 8 bytes of alpha.
	void decode_bc23_block(const uint8_t* src, rgba* out, bool bc3)
	{
		rgba palette[4];
		decode_bc1_colors(src + 8, palette, false);
		uint32_t bits = read32(src + 12);
		for (int i = 0; i < 16; i++) {
			out[i] = palette[(bits >> (2 * i)) & 3];
		}
		if (bc3) {
			uint8_t alpha[16];
			decode_bc4_block(src, alpha);
			for (int i = 0; i < 16; i++) {
				out[i].a = alpha[i];
			}
		} else {
			for (int i = 0; i < 16; i++) {
				out[i].a = uint8_t(((src[i / 2] >> (4 * (i & 1))) & 15) * 17);
			}
		}
	}

	// BC4 is one channel, which is shown as grey.
	void decode_bc4_block_grey(const uint8_t* src, rgba* out)
	{
		uint8_t v[16];
		decode_bc4_block(src, v);
		for (int i = 0; i < 16; i++) {
			out[i] = { v[i], v[i], v[i], 255 };
		}
	}

	// BC5 is two channels, and is used for normal maps: the third channel is rebuilt from the first two.
	void decode_bc5_block(const uint8_t* src, rgba* out)
	{
		uint8_t x[16], y[16];
		decode_bc4_block(src, x);
		decode_bc4_block(src + 8, y);
		for (int i = 0; i < 16; i++) {
			float nx = float(x[i]) / 127.5f - 1.0f, ny = float(y[i]) / 127.5f - 1.0f;
			float nz = 1.0f - nx * nx - ny * ny;
			nz       = (nz > 0.0f) ? sqrtf(nz) : 0.0f;
			out[i]   = { x[i], y[i], uint8_t(nz * 127.5f + 127.5f + 0.5f), 255 };
		}
	}

