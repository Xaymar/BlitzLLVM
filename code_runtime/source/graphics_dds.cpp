	const uint8_t* bc7_weights(int bits)
	{
		return (bits == 2) ? bc7_weights2 : (bits == 3) ? bc7_weights3 : bc7_weights4;
	}

	struct bit_reader {
		const uint8_t* data;
		int            position = 0;
		uint32_t read(int count)
		{
			uint32_t out = 0;
			for (int i = 0; i < count; i++, position++) {
				out |= uint32_t((data[position >> 3] >> (position & 7)) & 1) << i;
			}
			return out;
		}
	};

	void decode_bc7_block(const uint8_t* src, rgba* out)
	{
		int mode = 0;
		while ((mode < 8) && !((src[0] >> mode) & 1)) {
			mode++;
		}
		if (mode >= 8) {
			// Not a mode: transparent black.
			for (int i = 0; i < 16; i++) {
				out[i] = { 0, 0, 0, 0 };
			}
			return;
		}
		const bc7_mode& m = bc7_modes[mode];
		bit_reader      in{ src, mode + 1 };
		uint32_t        partition = in.read(m.partition_bits);
		uint32_t        rotation  = in.read(m.rotation_bits);
		uint32_t        select    = in.read(m.index_select_bits);

		int     endpoints = m.subsets * 2;
		uint8_t color[6][4]; // Endpoint, then red, green, blue, alpha.
		int     bits[4] = { m.color_bits, m.color_bits, m.color_bits, m.alpha_bits };
		for (int channel = 0; channel < 4; channel++) {
			for (int e = 0; e < endpoints; e++) {
				color[e][channel] = uint8_t(in.read(bits[channel]));
			}
		}
		int pbits = m.endpoint_pbits ? endpoints : (m.shared_pbits ? m.subsets : 0);
		uint8_t pbit[6] = { 0, 0, 0, 0, 0, 0 };
		for (int p = 0; p < pbits; p++) {
			pbit[p] = uint8_t(in.read(1));
		}
		for (int e = 0; e < endpoints; e++) {
			for (int channel = 0; channel < 4; channel++) {
				int n = bits[channel];
				if (n == 0) {
					color[e][channel] = 255;
					continue;
				}
				uint32_t v = color[e][channel];
				if (pbits && (channel < 3 || m.alpha_bits)) {
					v = (v << 1) | pbit[m.endpoint_pbits ? e : e / 2];
					n++;
				}
				color[e][channel] = expand(v, n);
			}
		}

		auto subset_of = [&](int pixel) -> int {
			if (m.subsets == 2) {
				return (bc7_subsets2[partition] >> pixel) & 1;
			}
			if (m.subsets == 3) {
				return (bc7_subsets3[partition] >> (2 * pixel)) & 3;
			}
			return 0;
		};
		auto is_anchor = [&](int pixel) -> bool {
			if (pixel == 0) {
				return true;
			}
			if (m.subsets == 2) {
				return pixel == bc7_anchor2[partition];
			}
			if (m.subsets == 3) {
				return (pixel == bc7_anchor3a[partition]) || (pixel == bc7_anchor3b[partition]);
			}
			return false;
		};

		uint8_t index[16], index2[16];
		for (int i = 0; i < 16; i++) {
			index[i] = uint8_t(in.read(m.index_bits - (is_anchor(i) ? 1 : 0)));
		}
		if (m.index2_bits) {
			for (int i = 0; i < 16; i++) {
				index2[i] = uint8_t(in.read(m.index2_bits - (i == 0 ? 1 : 0)));
			}
		}

		for (int i = 0; i < 16; i++) {
			int            s  = subset_of(i);
			const uint8_t* a  = color[s * 2];
			const uint8_t* b  = color[s * 2 + 1];
			int            ci = index[i], ai = index[i];
			int            cb = m.index_bits, ab = m.index_bits;
			if (m.index2_bits) {
				// Either the color or the alpha uses the second set of indices.
				if (select) {
					ci = index2[i];
					cb = m.index2_bits;
					ai = index[i];
					ab = m.index_bits;
				} else {
					ci = index[i];
					cb = m.index_bits;
					ai = index2[i];
					ab = m.index2_bits;
				}
			}
			int wc = bc7_weights(cb)[ci], wa = bc7_weights(ab)[ai];
			uint8_t px[4];
			for (int channel = 0; channel < 3; channel++) {
				px[channel] = uint8_t((a[channel] * (64 - wc) + b[channel] * wc + 32) >> 6);
			}
			px[3] = uint8_t((a[3] * (64 - wa) + b[3] * wa + 32) >> 6);
			if (rotation) {
				uint8_t t = px[3];
				px[3] = px[rotation - 1];
				px[rotation - 1] = t;
			}
			out[i] = { px[0], px[1], px[2], px[3] };
		}
	}

	bool describe(const uint8_t* header, format& f, size_t& offset)
	{
		const uint8_t* pf     = header + 72; // The pixel format starts at offset 76 of the file, 72 after the magic.
		uint32_t       flags  = read32(pf + 4);
		uint32_t       code   = read32(pf + 8);
		offset                = 124;
		if (read32(pf) != 32) {
			return false;
		}
		if (flags & PF_FOURCC) {
			switch (code) {
			case fourcc('D', 'X', 'T', '1'): f.type = block_format::bc1; return true;
			case fourcc('D', 'X', 'T', '2'):
			case fourcc('D', 'X', 'T', '3'): f.type = block_format::bc2; return true;
			case fourcc('D', 'X', 'T', '4'):
			case fourcc('D', 'X', 'T', '5'): f.type = block_format::bc3; return true;
			case fourcc('A', 'T', 'I', '1'):
			case fourcc('B', 'C', '4', 'U'): f.type = block_format::bc4; return true;
			case fourcc('A', 'T', 'I', '2'):
			case fourcc('B', 'C', '5', 'U'): f.type = block_format::bc5; return true;
			case fourcc('D', 'X', '1', '0'): break;
			default: return false;
			}
			// The DX10 header follows the normal one.
			offset = 144;
			uint32_t dxgi = read32(header + 124);
			auto     set  = [&](uint32_t bits, uint32_t r, uint32_t g, uint32_t b, uint32_t a) {
                f.type = block_format::none;
                f.bits = bits;
                f.mask[0] = r; f.mask[1] = g; f.mask[2] = b; f.mask[3] = a;
			};
			switch (dxgi) {
			case 70: case 71: case 72: f.type = block_format::bc1; return true;
			case 73: case 74: case 75: f.type = block_format::bc2; return true;
			case 76: case 77: case 78: f.type = block_format::bc3; return true;
			case 79: case 80: case 81: f.type = block_format::bc4; return true;
			case 82: case 83: case 84: f.type = block_format::bc5; return true;
			case 97: case 98: case 99: f.type = block_format::bc7; return true;
			case 27: case 28: case 29: set(32, 0xff, 0xff00, 0xff0000, 0xff000000); return true;   // R8G8B8A8
			case 87: case 91: set(32, 0xff0000, 0xff00, 0xff, 0xff000000); return true;             // B8G8R8A8
			case 88: case 93: set(32, 0xff0000, 0xff00, 0xff, 0); return true;                     // B8G8R8X8
			case 85: set(16, 0xf800, 0x7e0, 0x1f, 0); return true;                                 // B5G6R5
			case 86: set(16, 0x7c00, 0x3e0, 0x1f, 0x8000); return true;                            // B5G5R5A1
			case 115: set(16, 0xf00, 0xf0, 0xf, 0xf000); return true;                              // B4G4R4A4
			case 49: set(16, 0xff, 0xff00, 0, 0); return true;                                     // R8G8
			case 61: set(8, 0xff, 0xff, 0xff, 0); return true;                                     // R8, shown as grey
			case 65: set(8, 0, 0, 0, 0xff); f.alpha_only = true; return true;                      // A8
			default: return false;
			}
		}
		if (flags & (PF_RGB | PF_LUMINANCE | PF_ALPHA)) {
			f.type = block_format::none;
			f.bits = read32(pf + 12);
			for (int i = 0; i < 4; i++) {
				f.mask[i] = read32(pf + 16 + 4 * i);
			}
			if (!(flags & PF_ALPHAPIXELS)) {
				f.mask[3] = 0;
			}
			if (flags & PF_LUMINANCE) {
				f.luminance = true;
				f.mask[1] = f.mask[2] = f.mask[0];
			}
			if (flags & PF_ALPHA) {
				f.alpha_only = true;
				f.mask[3]    = f.mask[3] ? f.mask[3] : f.mask[0];
				f.mask[0]    = 0;
			}
			return (f.bits == 8) || (f.bits == 16) || (f.bits == 24) || (f.bits == 32);
		}
		return false;
	}

	int mask_bits(uint32_t mask)
	{
		int n = 0;
		for (; mask; mask >>= 1) {
			n += int(mask & 1);
		}
		return n;
	}

	int mask_shift(uint32_t mask)
	{
		int n = 0;
		while (mask && !(mask & 1)) {
			mask >>= 1;
			n++;
		}
		return n;
	}

