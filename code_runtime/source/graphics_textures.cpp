	// What a tile of an atlas reads through. With a gutter of g pixels the levels up to log2(g) only reach into the gutter (they are
	// only used if the atlas has mip maps); without one it stays on the first level.
	static VkSampler view_sampler(texture_entry const& t)
	{
		int lod = 0;
		if (t.gutter > 1 && t.image.mips > 1) {
			while ((2 << lod) <= t.gutter) {
				lod++;
			}
		}
		return lod > 0 ? atlas_sampler((t.flags & TEXTURE_POINT) != 0, lod) : texture_sampler(t.flags & ~TEXTURE_MIPMAPS);
	}

	texture_entry* texture_of(int reference)
	{
		int handle = reference & bb::texture_handle_mask;
		if ((handle < 1) || (uint32_t(handle) > texture_table.size) || !texture_table[uint32_t(handle) - 1].used) {
			return nullptr;
		}
		texture_entry* t = &texture_table[uint32_t(handle) - 1];
		if (t->alias) {
			// A handle that GetBrushTexture made is the same texture, with the same scale, blend and pixels.
			t = &texture_table[uint32_t(t->alias) - 1];
		}
		if (t->pending) {
			resolve_texture(*t);
		}
		if (t->atlas) {
			// A view samples the image of its atlas, which may have been loaded, or turned into another format, since the view was made.
			texture_entry& a = texture_table[uint32_t(t->atlas) - 1];
			if (a.pending) {
				resolve_texture(a);
			}
			if (a.image.view != t->image.view) {
				t->image = a.image;
				if (g.device && t->set) {
					set_descriptor_sampler(t->image, t->set, view_sampler(*t));
				}
			}
		}
		return t;
	}

	texture_entry* live_texture_of(int reference)
	{
		int handle = reference & bb::texture_handle_mask;
		if ((handle < 1) || (uint32_t(handle) > texture_table.size) || !texture_table[uint32_t(handle) - 1].used || texture_table[uint32_t(handle) - 1].freed) {
			return nullptr;
		}
		return texture_of(reference);
	}

	// With frames the texture coordinates only cover the cell of a frame in the sheet.
	void texture_uv(texture_entry const* t, int reference, float* uv)
	{
		uv[0] = t ? t->uv[0] : 1.0f;
		uv[1] = t ? t->uv[1] : 1.0f;
		uv[2] = t ? t->uv[2] : 0.0f;
		uv[3] = t ? t->uv[3] : 0.0f;
		if (t && (t->frame_w > 0) && (t->frame_h > 0)) {
			int frame = reference >> bb::texture_frame_shift;
			frame     = frame >= t->frames ? t->frames - 1 : frame;
			int cols  = t->width / t->frame_w;
			cols      = cols > 0 ? cols : 1;
			int cell  = t->first_frame + frame;
			float fx  = float(t->frame_w) / float(t->width), fy = float(t->frame_h) / float(t->height);
			uv[0] *= fx;
			uv[1] *= fy;
			uv[2] = uv[2] * fx + float(cell % cols) * fx;
			uv[3] = uv[3] * fy + float(cell / cols) * fy;
		}
		if (t && t->atlas) {
			// The rectangle of an atlas view. Linear filtering reads half a texel past what it is given, so the edge of the rectangle
			// is half a texel in, which keeps the neighbouring tiles out; the nearest texel (flag 1024) has nothing to bleed.
			float inset = ((t->flags & TEXTURE_POINT) || t->gutter > 0) ? 0.0f : 0.5f;
			float aw = float(t->width), ah = float(t->height);
			float w = float(t->rect[2]) - 2.0f * inset, h = float(t->rect[3]) - 2.0f * inset;
			w       = w < 0.0f ? 0.0f : w;
			h       = h < 0.0f ? 0.0f : h;
			uv[0] *= w / aw;
			uv[1] *= h / ah;
			uv[2] = uv[2] * w / aw + (float(t->rect[0]) + inset) / aw;
			uv[3] = uv[3] * h / ah + (float(t->rect[1]) + inset) / ah;
		}
	}

	// RotateTexture turns the coordinates before they are scaled; the cosine is kept minus one so that zeros mean no rotation.
	void texture_rotation(texture_entry const* t, float* extra)
	{
		extra[1] = t ? sinf(t->rotation) : 0.0f;
		extra[2] = t ? cosf(t->rotation) - 1.0f : 0.0f;
	}

	// Sphere maps (flag 64) and cube maps (flag 128) make their coordinates from the view, like the original does. A texture
	// that has both is drawn as a plain one.
	void texture_texgen(texture_entry const* t, float* texgen)
	{
		texgen[0] = texgen[1] = texgen[2] = texgen[3] = 0;
		if (!t) {
			return;
		}
		bool sphere = (t->flags & 64) != 0, cube = (t->flags & 128) != 0;
		if (sphere && !cube) {
			texgen[0] = 1;
		} else if (cube && !sphere && t->cube) {
			int mode  = t->cube_mode & 3;
			texgen[0] = 2;
			texgen[1] = (mode == 2 || mode == 3) ? float(mode) : 1.0f;
			texgen[2] = (t->cube_mode & 4) ? 1.0f : 0.0f;
			texgen[3] = 0.5f / float(t->width);
		}
	}

	void free_image(image_entry& e)
	{
		if (e.pending) {
			async_discard(e.pending);
			e.pending = nullptr;
		}
		if (g.device && e.set) {
			flush(); // What was asked to be drawn with it comes first.
			gpu_idle();
			vkFreeDescriptorSets(g.device, g.set_pool, 1, &e.set);
			destroy_image(e.image);
		}
		bb_free(e.solid);
		bb_free(e.delays);
		e = image_entry();
	}

	void free_texture(texture_entry& t)
	{
		if (t.pending) {
			async_discard(t.pending);
			t.pending = nullptr;
		}
		if (g.device && t.set) {
			flush(); // What was asked to be drawn with it comes first.
			gpu_idle();
			vkFreeDescriptorSets(g.device, g.set_pool, 1, &t.set);
			if (t.atlas) {
				// The image belongs to the atlas.
			} else if (t.cube) {
				cube_store(t);
				for (gpu_image& face : t.cube->faces) {
					destroy_image(face);
				}
				destroy_image(t.cube->sheet);
			} else {
				destroy_image(t.image);
			}
		}
		sprite_hull_drop(t.hull);
		delete t.cube;
		bb_free(t.file);
		bb_free(t.delays);
		t = texture_entry();
	}

	void cube_store(texture_entry& t)
	{
		if (t.cube) {
			t.cube->faces[t.cube->face] = t.image;
		}
	}

	// Gives a texture the pictures of a cube map: six faces of the size of the texture, from a strip of faces next to each
	// other if there is one (the pixels are then strip_width wide), and the sheet that 3D samples.
	static void make_cube(texture_entry& entry, const uint8_t* strip, int strip_width)
	{
		int      w = entry.width, h = entry.height;
		uint8_t* face_pixels = static_cast<uint8_t*>(bb_calloc(size_t(w) * size_t(h), 4));
		entry.cube           = new cube_data();
		for (int face = 0; face < 6; face++) {
			for (int y = 0; y < h; y++) {
				for (int x = 0; x < w; x++) {
					uint8_t* px = face_pixels + (size_t(y) * size_t(w) + size_t(x)) * 4;
					if (strip) {
						memcpy(px, strip + (size_t(y) * size_t(strip_width) + size_t(face * w + x)) * 4, 4);
					} else {
						px[0] = px[1] = px[2] = 0;
						px[3] = 255;
					}
				}
			}
			create_pixel_image(entry.cube->faces[face], uint32_t(w), uint32_t(h), face_pixels);
		}
		bb_free(face_pixels);
		uint8_t* blank = static_cast<uint8_t*>(bb_calloc(size_t(w) * 3 * size_t(h) * 2, 4));
		entry.cube->sheet.array_sets = true;
		upload_texture(entry.cube->sheet, entry.set, uint32_t(w * 3), uint32_t(h * 2), blank, g.sampler_clamp);
		bb_free(blank);
		entry.image = entry.cube->faces[entry.cube->face];
	}
