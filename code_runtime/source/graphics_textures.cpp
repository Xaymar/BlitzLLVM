	texture_entry* texture_of(int reference)
	{
		int handle = reference & bb::texture_handle_mask;
		if ((handle < 1) || (uint32_t(handle) > texture_table.size) || !texture_table[uint32_t(handle) - 1].used) {
			return nullptr;
		}
		texture_entry* t = &texture_table[uint32_t(handle) - 1];
		if (t->alias) {
			// A handle that GetBrushTexture made is the same texture, with the same scale, blend and pixels.
			t = &texture_table[uint32_t(t->alias) - 1];
		}
		return t;
	}

	texture_entry* live_texture_of(int reference)
	{
		int handle = reference & bb::texture_handle_mask;
		if ((handle < 1) || (uint32_t(handle) > texture_table.size) || !texture_table[uint32_t(handle) - 1].used || texture_table[uint32_t(handle) - 1].freed) {
			return nullptr;
		}
		return texture_of(reference);
	}

	// With frames the texture coordinates only cover the cell of a frame in the sheet.
	void texture_uv(texture_entry const* t, int reference, float* uv)
	{
		uv[0] = t ? t->uv[0] : 1.0f;
		uv[1] = t ? t->uv[1] : 1.0f;
		uv[2] = t ? t->uv[2] : 0.0f;
		uv[3] = t ? t->uv[3] : 0.0f;
		if (t && (t->frame_w > 0) && (t->frame_h > 0)) {
			int frame = reference >> bb::texture_frame_shift;
			frame     = frame >= t->frames ? t->frames - 1 : frame;
			int cols  = t->width / t->frame_w;
			cols      = cols > 0 ? cols : 1;
			int cell  = t->first_frame + frame;
			float fx  = float(t->frame_w) / float(t->width), fy = float(t->frame_h) / float(t->height);
			uv[0] *= fx;
			uv[1] *= fy;
			uv[2] = uv[2] * fx + float(cell % cols) * fx;
			uv[3] = uv[3] * fy + float(cell / cols) * fy;
		}
	}

	void free_image(image_entry& e)
	{
		if (g.device && e.set) {
			flush(); // What was asked to be drawn with it comes first.
			vkDeviceWaitIdle(g.device);
			vkFreeDescriptorSets(g.device, g.set_pool, 1, &e.set);
			destroy_image(e.image);
		}
		free(e.solid);
		e = image_entry();
	}

	void free_texture(texture_entry& t)
	{
		if (g.device && t.set) {
			flush(); // What was asked to be drawn with it comes first.
			vkDeviceWaitIdle(g.device);
			vkFreeDescriptorSets(g.device, g.set_pool, 1, &t.set);
			destroy_image(t.image);
		}
		free(t.file);
		t = texture_entry();
	}
	static bb::buffer<texture_filter> texture_filters;

