	static texture_entry* need_texture(int32_t handle, const char* what)
	{
		texture_entry* t = live_texture_of(handle);
		if (!t) {
			char message[96];
			snprintf(message, sizeof(message), "%s: the texture does not exist.", what);
			bb_runtime_error(message);
		}
		return t;
	}

	float texture_layer(texture_entry const* t, int reference)
	{
		if (!t || (t->image.layers < 2)) {
			return 0.0f;
		}
		int frame = reference >> bb::texture_frame_shift;
		return float(frame >= int(t->image.layers) ? int(t->image.layers) - 1 : frame);
	}

	// Puts the frames of a texture that is a sheet into the layers of one image, each with its own mip levels, so that filtering and wrapping
	// stay inside a frame like they do in the original, where every frame is a texture of its own. What can not be split stays a sheet:
	// compressed pictures and the ones with more than 8 bits.
	void texture_into_layers(texture_entry& t)
	{
		if (!g.device || !t.set || t.pending || t.cube || t.atlas || (t.frames < 2) || (t.frame_w <= 0) || (t.frame_h <= 0) || !t.image.image) {
			return;
		}
		if ((t.image.block != block_format::none) || t.image.ten || (t.image.format != VK_FORMAT_R8G8B8A8_UNORM && t.image.format != VK_FORMAT_R8G8B8A8_SRGB)) {
			return;
		}
		flush();
		uint8_t*             sheet = read_pixels(t.image, 0, 0, t.width, t.height);
		size_t               row = size_t(t.frame_w) * 4, layer_bytes = row * size_t(t.frame_h);
		int                  cols = t.width / t.frame_w;
		std::vector<uint8_t> stack(layer_bytes * size_t(t.frames));
		for (int frame = 0; frame < t.frames; frame++) {
			int cell = t.first_frame + frame;
			for (int y = 0; y < t.frame_h; y++) {
				memcpy(stack.data() + layer_bytes * size_t(frame) + row * size_t(y), sheet + (size_t(cell / cols) * size_t(t.frame_h) + size_t(y)) * size_t(t.width) * 4 + size_t(cell % cols) * row, row);
			}
		}
		bb_free(sheet);

		gpu_image       fresh;
		VkDescriptorSet set     = VK_NULL_HANDLE;
		VkSampler       sampler = t.image.sampler;
		fresh.array_sets        = true;
		upload_texture(fresh, set, uint32_t(t.frame_w), uint32_t(t.frame_h), stack.data(), sampler, t.image.mips > 1, t.image.srgb, false, uint32_t(t.frames));
		gpu_idle();
		vkFreeDescriptorSets(g.device, g.set_pool, 1, &t.set);
		destroy_image(t.image);
		t.image       = fresh;
		t.set         = set;
		t.width       = t.frame_w;
		t.height      = t.frame_h;
		t.frame_w     = t.frame_h = 0;
		t.first_frame = 0;
		sprite_hull_drop(t.hull);
	}

	// Where a frame of the texture is: in its sheet, or the layer of its image. False if there is no such frame.
	bool texture_frame_rect(texture_entry const& t, int frame, int& x, int& y, int& w, int& h, uint32_t* layer)
	{
		if ((frame < 0) || (frame >= t.frames)) {
			return false;
		}
		x = y = 0;
		w     = t.width;
		h     = t.height;
		if (layer) {
			*layer = t.image.layers > 1 ? uint32_t(frame) : 0;
		}
		if ((t.frame_w > 0) && (t.frame_h > 0)) {
			int cols = t.width / t.frame_w;
			cols     = cols > 0 ? cols : 1;
			int cell = t.first_frame + frame;
			x        = (cell % cols) * t.frame_w;
			y        = (cell / cols) * t.frame_h;
			w        = t.frame_w;
			h        = t.frame_h;
		}
		return true;
	}

	// The path as an absolute one without . and .. in it, which is what TextureName tells.
	static char* full_path(const char* file)
	{
#ifdef _WIN32
		const char separator = '\\';
#else
		const char separator = '/';
#endif
		bool        absolute = (file[0] == '/') || (file[0] == '\\') || (file[0] && (file[1] == ':'));
		const char* cwd      = absolute ? nullptr : SDL_GetCurrentDirectory();
		size_t      length   = strlen(file) + (cwd ? strlen(cwd) : 0) + 2;
		char*       joined   = static_cast<char*>(bb_malloc(length));
		snprintf(joined, length, "%s%s%s", cwd ? cwd : "", (cwd && cwd[0] && (cwd[strlen(cwd) - 1] != '/') && (cwd[strlen(cwd) - 1] != '\\')) ? "/" : "", file);
		SDL_free(const_cast<char*>(cwd));

		size_t prefix = 0;
		if ((joined[0] == '/') || (joined[0] == '\\')) {
			prefix = 1;
		} else if (joined[0] && (joined[1] == ':')) {
			prefix = ((joined[2] == '/') || (joined[2] == '\\')) ? 3 : 2;
		}
		char* out = static_cast<char*>(bb_malloc(length + 1));
		memcpy(out, joined, prefix);
		size_t used = prefix, base = prefix;
		for (char* part = joined + prefix; *part;) {
			char* end = part;
			while (*end && (*end != '/') && (*end != '\\')) {
				end++;
			}
			size_t size = size_t(end - part);
			if ((size == 2) && (part[0] == '.') && (part[1] == '.')) {
				// Back to the separator before the last part, but not past the start.
				if (used > base) {
					used--;
					while ((used > base) && (out[used - 1] != separator)) {
						used--;
					}
				}
			} else if ((size > 0) && !((size == 1) && (part[0] == '.'))) {
				memcpy(out + used, part, size);
				used += size;
				if (*end) {
					out[used++] = separator;
				}
			}
			part = *end ? end + 1 : end;
		}
		out[used] = 0;
		bb_free(joined);
		return out;
	}
