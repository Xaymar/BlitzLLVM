// CreateTexture(width, height, flags, frames): an empty texture to draw on, with TextureBuffer.
int32_t bb_create_texture(int32_t width, int32_t height, int32_t flags, int32_t frames)
{
	if ((width <= 0) || (height <= 0)) {
		bb_runtime_error("CreateTexture: needs a size.");
	}
	if (frames <= 0) {
		bb_runtime_error("CreateTexture: Illegal number of texture frames.");
	}
	// Frames are the cells of one column in a sheet, as big as the frames put on top of each other.
	texture_entry entry;
	entry.used   = true;
	entry.flags  = flags;
	entry.width  = width;
	entry.height = height * frames;
	if (frames > 1) {
		entry.frames  = frames;
		entry.frame_w = width;
		entry.frame_h = height;
	}
	if (active() && (flags & 128) && !(flags & 64)) {
		entry.frames = 1;
		make_cube(entry, nullptr, 0);
	} else if (active()) {
		uint8_t* pixels = static_cast<uint8_t*>(calloc(size_t(entry.width) * size_t(entry.height), 4));
		for (size_t i = 0; i < size_t(entry.width) * size_t(entry.height); i++) {
			pixels[i * 4 + 3] = 255;
		}
		upload_texture(entry.image, entry.set, uint32_t(entry.width), uint32_t(entry.height), pixels, texture_sampler(flags), (flags & TEXTURE_MIPMAPS) != 0);
		free(pixels);
	}
	for (uint32_t i = 0; i < texture_table.size; i++) {
		if (!texture_table[i].used) {
			texture_table[i] = entry;
			return int32_t(i) + 1;
		}
	}
	texture_table.push(entry);
	return int32_t(texture_table.size);
}

// A texture from pixels that are already in memory (4 bytes each, red first), for what the runtime builds itself, such as the
// lightmaps of a level. The flags are the ones of CreateTexture, and blend is what it does on a later layer.
int32_t bb_texture_from_rgba(int32_t width, int32_t height, int32_t flags, int32_t blend, const uint8_t* pixels)
{
	texture_entry entry;
	entry.used   = true;
	entry.flags  = flags;
	entry.blend  = blend;
	entry.width  = width;
	entry.height = height;
	if (active()) {
		upload_texture(entry.image, entry.set, uint32_t(width), uint32_t(height), pixels, texture_sampler(flags), (flags & TEXTURE_MIPMAPS) != 0);
	}
	for (uint32_t i = 0; i < texture_table.size; i++) {
		if (!texture_table[i].used) {
			texture_table[i] = entry;
			return int32_t(i) + 1;
		}
	}
	texture_table.push(entry);
	return int32_t(texture_table.size);
}

int32_t bb_filter_texture_flags(const char* file, int32_t flags)
{
	if (!file) {
		return flags;
	}
	size_t length = strlen(file);
	char*  lower  = static_cast<char*>(malloc(length + 1));
	for (size_t i = 0; i <= length; i++) {
		char c   = file[i];
		lower[i] = (c >= 'A' && c <= 'Z') ? char(c + 32) : c;
	}
	for (uint32_t i = 0; i < texture_filters.size; i++) {
		if (strstr(lower, texture_filters[i].match)) {
			flags |= texture_filters[i].flags;
		}
	}
	free(lower);
	return flags;
}

static int32_t add_texture(texture_entry const& entry)
{
	for (uint32_t i = 0; i < texture_table.size; i++) {
		if (!texture_table[i].used) {
			texture_table[i] = entry;
			return int32_t(i) + 1;
		}
	}
	texture_table.push(entry);
	return int32_t(texture_table.size);
}

