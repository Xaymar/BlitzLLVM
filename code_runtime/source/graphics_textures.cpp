void bb_clear_texture_filters(void)
{
	for (uint32_t i = 0; i < texture_filters.size; i++) {
		free(texture_filters[i].match);
	}
	texture_filters.clear();
}

// What Graphics3D starts with: every texture has color (1) and mipmaps (8).
void bb_reset_texture_filters(void)
{
	bb_clear_texture_filters();
	bb_texture_filter("", 1 | 8);
}

// ClearWorld takes all textures away.
void bb_clear_textures(void)
{
	for (uint32_t i = 0; i < texture_table.size; i++) {
		if (texture_table[i].used) {
			free_texture(texture_table[i]);
		}
	}
}

// ScaleTexture makes the texture bigger for numbers above 1: the coordinates are divided.
void bb_scale_texture(int32_t handle, float u, float v)
{
	texture_entry* t = need_texture(handle, "ScaleTexture");
	t->uv[0]         = (u != 0) ? 1.0f / u : 1.0f;
	t->uv[1]         = (v != 0) ? 1.0f / v : 1.0f;
}

void bb_position_texture(int32_t handle, float u, float v)
{
	texture_entry* t = need_texture(handle, "PositionTexture");
	t->uv[2]         = u;
	t->uv[3]         = v;
}

// Rotating textures is not supported, the call is accepted so programs that do it still run.
void bb_rotate_texture(int32_t handle, float angle)
{
	(void)angle;
	need_texture(handle, "RotateTexture");
}

void bb_texture_blend(int32_t handle, int32_t mode)
{
	need_texture(handle, "TextureBlend")->blend = mode;
}

void bb_texture_filter(const char* match, int32_t flags)
{
	const char* text   = match ? match : "";
	size_t      length = strlen(text);
	char*       lower  = static_cast<char*>(malloc(length + 1));
	for (size_t i = 0; i <= length; i++) {
		char c   = text[i];
		lower[i] = (c >= 'A' && c <= 'Z') ? char(c + 32) : c;
	}
	texture_filters.push({ lower, flags });
}

void bb_set_cube_face(int32_t handle, int32_t face)
{
	(void)face;
	need_texture(handle, "SetCubeFace"); // Cube maps are not supported.
}

int32_t bb_live_textures(void)
{
	int32_t count = 0;
	for (uint32_t i = 0; i < texture_table.size; i++) {
		count += (texture_table[i].used && !texture_table[i].alias) ? 1 : 0;
	}
	return count;
}
