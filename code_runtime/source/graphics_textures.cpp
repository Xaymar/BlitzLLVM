// Loads a texture with exactly these flags. Where alpha comes from is what the original does: nothing, if the flag is
// not there, and with it the alpha channel of the image if it has one, and otherwise how bright each pixel is.
int32_t bb_load_texture_flags(const char* file, int32_t flags)
{
	if (!file) {
		return 0;
	}
	if (flags & TEXTURE_MASKED) {
		flags |= 1 | TEXTURE_ALPHA;
	}

	if (async_loading() && active() && !(flags & 128)) {
		// The file is read now, so it can be deleted or replaced right after, and so a missing file or one that is no picture
		// gives 0 as ever. The decoding is what goes on another thread.
		size_t size = 0;
		void*  data = SDL_LoadFile(bb_native_path(file), &size);
		if (!data) {
			return 0;
		}
		if (picture_recognized(static_cast<const uint8_t*>(data), size)) {
			texture_job* job = new texture_job();
			job->data        = data;
			job->size        = size;
			job->name        = file;
			job->flags       = flags;
			memcpy(job->block_ok, async_block_support(), sizeof(job->block_ok));
			texture_entry entry;
			entry.used    = true;
			entry.flags   = flags;
			entry.file    = full_path(file);
			entry.pending = job;
			async_submit(job);
			return add_texture(entry);
		}
		SDL_free(data);
	}

	picture source;
	if (!load_picture(file, source)) {
		return 0; // Blitz gives 0 for missing files.
	}
	prepared_texture prepared;
	if (!prepare_texture(source, flags, active(), active() && compressed_supported(source.block), prepared)) {
		free_picture(source);
		return 0;
	}

	texture_entry entry;
	entry.used   = true;
	entry.flags  = flags;
	entry.file   = full_path(file);
	if (prepared.compressed) {
		finish_texture(entry, prepared, flags);
		return add_texture(entry);
	}

	SDL_Surface* rgba = prepared.rgba;
	entry.width  = rgba->w;
	entry.height = rgba->h;
	if (active() && (flags & 128) && !(flags & 64)) {
		// Six faces next to each other.
		if (rgba->w % 6) {
			SDL_DestroySurface(rgba);
			free(entry.file);
			return 0;
		}
		entry.width = rgba->w / 6;
		make_cube(entry, static_cast<const uint8_t*>(rgba->pixels), rgba->pitch / 4);
		SDL_DestroySurface(rgba);
	} else if (active()) {
		finish_texture(entry, prepared, flags);
	} else {
		SDL_DestroySurface(rgba);
	}

	return add_texture(entry);
}

// TextureReady(texture): 1 once the texture is loaded, without waiting for it.
int32_t bb_texture_ready(int32_t handle)
{
	return texture_is_ready(handle) ? 1 : 0;
}

// AsyncLoading(enabled): whether LoadTexture and LoadImage decode on other threads and let the program go on.
void bb_async_loading(int32_t enabled)
{
	async_set_loading(enabled != 0);
}

int32_t bb_load_texture(const char* file, int32_t flags)
{
	return bb_load_texture_flags(file, bb_filter_texture_flags(file, flags));
}

// A new handle for the texture of this one. Both have the same pixels, scale and blend, and each is freed on its own.
int32_t bb_texture_alias(int32_t handle)
{
	int index = handle & bb::texture_handle_mask;
	if ((index < 1) || (uint32_t(index) > texture_table.size) || !texture_table[uint32_t(index) - 1].used) {
		return 0;
	}
	texture_entry entry;
	entry.used  = true;
	entry.alias = texture_table[uint32_t(index) - 1].alias ? texture_table[uint32_t(index) - 1].alias : index;
	for (uint32_t i = 0; i < texture_table.size; i++) {
		if (!texture_table[i].used) {
			texture_table[i] = entry;
			return int32_t(i) + 1;
		}
	}
	texture_table.push(entry);
	return int32_t(texture_table.size);
}

// FreeTexture while entities or brushes still use the texture only takes the handle away, what uses it keeps it until it
// does not need it any more, like the original which counts how often it is used.
void bb_collect_textures(void)
{
	bool changed = true;
	while (changed) {
		changed = false;
		for (uint32_t i = 0; i < texture_table.size; i++) {
			texture_entry& t = texture_table[i];
			if (!t.used || !t.freed || bb_texture_in_use(int32_t(i) + 1)) {
				continue;
			}
			bool shared = false;
			for (uint32_t k = 0; k < texture_table.size; k++) {
				shared |= texture_table[k].used && (texture_table[k].alias == int(i) + 1);
			}
			if (!shared) {
				free_texture(t);
				changed = true;
			}
		}
	}
}

void bb_free_texture(int32_t handle)
{
	if (!live_texture_of(handle)) {
		return;
	}
	texture_entry& t = texture_table[uint32_t(handle & bb::texture_handle_mask) - 1];
	t.freed          = true;
	bb_collect_textures();
}

// A texture with frames is as big as one of them.
int32_t bb_texture_width(int32_t handle)
{
	texture_entry* t = live_texture_of(handle);
	return t ? (t->frame_w > 0 ? t->frame_w : t->width) : 0;
}

int32_t bb_texture_height(int32_t handle)
{
	texture_entry* t = live_texture_of(handle);
	return t ? (t->frame_h > 0 ? t->frame_h : t->height) : 0;
}

// LoadAnimTexture(file, flags, width, height, first, count): a picture that is a sheet of frames of this size, with
// count of them from the first. 0 if there are not that many frames in the picture. Where the coordinates wrap around, they do so over the whole sheet.
int32_t bb_load_anim_texture(const char* file, int32_t flags, int32_t width, int32_t height, int32_t first, int32_t count)
{
	int32_t handle = bb_load_texture(file, flags);
	if (!handle) {
		return 0;
	}
	texture_entry* t = texture_of(handle);
	if ((width < 1) || (height < 1) || (count < 1) || (first < 0)) {
		return handle; // Like the original, this is the whole picture as one frame.
	}
	int cells = (t->width / width) * (t->height / height);
	if (first + count > cells) {
		bb_free_texture(handle);
		return 0; // The frames don't fit in the picture.
	}
	t->frames      = count;
	t->frame_w     = width;
	t->frame_h     = height;
	t->first_frame = first;
	return handle;
}

// The full path of the file a texture was loaded from, and nothing for one that was made.
const char* bb_texture_name(int32_t handle)
{
	texture_entry* t    = need_texture(handle, "TextureName");
	const char*    name = t->file ? t->file : "";
	char*          copy = static_cast<char*>(malloc(strlen(name) + 1));
	strcpy(copy, name);
	return copy;
}

// Which set of texture coordinates the texture uses. There is only one set.
void bb_texture_coords(int32_t handle, int32_t coords)
{
	// Like flag 65536 of LoadTexture, a 1 makes the texture read the second set of coordinates.
	texture_entry* t = need_texture(handle, "TextureCoords");
	t->flags         = coords ? (t->flags | 0x10000) : (t->flags & ~0x10000);
}

