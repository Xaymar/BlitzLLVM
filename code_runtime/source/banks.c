// Banks: blocks of memory that programs read and write like files.

#include "files_internal.h"

// Banks
////////////////////////////////////////////////////////////////////////////////
typedef struct bb_bank {
	uint8_t* data;
	int32_t  size;
} bb_bank;

// Not static: the compiler reads these from the program (as { ptr, i32 } entries) to check and access the bank of Peek and Poke inline.
bb_bank* bb_banks      = NULL;
int32_t  bb_bank_count = 1;
static int32_t  bb_bank_cap   = 0;

static bb_bank* bb_bank_get(int32_t handle, const char* what)
{
	if ((handle <= 0) || (handle >= bb_bank_count) || !bb_banks[handle].data) {
		char message[96];
		snprintf(message, sizeof(message), "%s: the bank does not exist.", what);
		bb_runtime_error(message);
	}
	return &bb_banks[handle];
}

static uint8_t* bb_bank_at(int32_t handle, int32_t offset, int32_t size, const char* what)
{
	bb_bank* bank = bb_bank_get(handle, what);
	if ((offset < 0) || (size < 0) || ((int64_t)offset + size > bank->size)) {
		char message[96];
		snprintf(message, sizeof(message), "%s: the offset is outside of the bank.", what);
		bb_runtime_error(message);
	}
	return bank->data + offset;
}

int32_t bb_create_bank(int32_t size)
{
	if (size < 0) {
		bb_runtime_error("CreateBank: the size can't be negative.");
	}
	uint8_t* data = (uint8_t*)calloc(1, (size_t)size + 1); // At least one byte, so that an empty bank still exists.
	if (!data) {
		bb_runtime_error("Out of memory.");
	}
	int32_t handle = 0;
	for (int32_t i = 1; i < bb_bank_count; i++) {
		if (!bb_banks[i].data) {
			handle = i;
			break;
		}
	}
	if (!handle) {
		if (bb_bank_count >= bb_bank_cap) {
			bb_bank_cap = bb_bank_cap ? bb_bank_cap * 2 : 64;
			bb_banks    = (bb_bank*)realloc(bb_banks, (size_t)bb_bank_cap * sizeof(bb_bank));
		}
		handle = bb_bank_count++;
	}
	bb_banks[handle].data = data;
	bb_banks[handle].size = size;
	return handle;
}

int32_t bb_live_banks(void)
{
	int32_t count = 0;
	for (int32_t i = 1; i < bb_bank_count; i++) {
		count += bb_banks[i].data ? 1 : 0;
	}
	return count;
}

// For the code that gives access to the memory of a bank, like the pixels of a buffer that is locked.
uint8_t* bb_bank_data(int32_t handle, int32_t* size)
{
	bb_bank* bank = bb_bank_get(handle, "Bank");
	*size         = bank->size;
	return bank->data;
}

// The address of the memory of a bank, for the functions of userlibs. Zero is no bank, and gives NULL.
uint8_t* bb_bank_pointer(int32_t handle)
{
	return handle ? bb_bank_get(handle, "Userlib function")->data : NULL;
}

void bb_free_bank(int32_t handle)
{
	bb_bank* bank = bb_bank_get(handle, "FreeBank");
	free(bank->data);
	bank->data = NULL;
	bank->size = 0;
}

// Reads from a stream into a bank, and returns how many bytes there were.
int32_t bb_read_bank_bytes(int32_t bank, int32_t file, int32_t offset, int32_t count)
{
	uint8_t* at = bb_bank_at(bank, offset, count, "ReadBytes");
	return (int32_t)bb_read_bytes(file, at, (size_t)count, "ReadBytes");
}

// Writes a part of a bank to a stream.
int32_t bb_write_bank_bytes(int32_t bank, int32_t file, int32_t offset, int32_t count)
{
	uint8_t* at = bb_bank_at(bank, offset, count, "WriteBytes");
	bb_write_bytes(file, at, (size_t)count, "WriteBytes");
	return count;
}

// Calls a function of a library, which gets the two banks as (in, in size, out, out size) and gives back a number.
int32_t bb_call_dll(const char* library, const char* function, int32_t in_bank, int32_t out_bank)
{
	typedef int32_t (*bb_dll_function)(const void*, int32_t, void*, int32_t);
	bb_dll_function call = NULL;
#if defined(_WIN32)
	HMODULE module = GetModuleHandleA(library);
	if (!module) {
		module = LoadLibraryA(library);
	}
	if (module) {
		call = (bb_dll_function)(void*)GetProcAddress(module, function);
	}
#else
	void* module = dlopen(library, RTLD_NOW);
	if (module) {
		call = (bb_dll_function)dlsym(module, function);
	}
#endif
	if (!call) {
		return 0;
	}
	bb_bank* in  = in_bank ? bb_bank_get(in_bank, "CallDLL") : NULL;
	bb_bank* out = out_bank ? bb_bank_get(out_bank, "CallDLL") : NULL;
	return call(in ? in->data : NULL, in ? in->size : 0, out ? out->data : NULL, out ? out->size : 0);
}

int32_t bb_bank_size(int32_t handle)
{
	return bb_bank_get(handle, "BankSize")->size;
}

void bb_resize_bank(int32_t handle, int32_t size)
{
	bb_bank* bank = bb_bank_get(handle, "ResizeBank");
	if (size < 0) {
		bb_runtime_error("ResizeBank: the size can't be negative.");
	}
	uint8_t* data = (uint8_t*)realloc(bank->data, (size_t)size + 1);
	if (!data) {
		bb_runtime_error("Out of memory.");
	}
	if (size > bank->size) {
		memset(data + bank->size, 0, (size_t)(size - bank->size));
	}
	bank->data = data;
	bank->size = size;
}

void bb_copy_bank(int32_t from, int32_t from_offset, int32_t to, int32_t to_offset, int32_t count)
{
	memmove(bb_bank_at(to, to_offset, count, "CopyBank"), bb_bank_at(from, from_offset, count, "CopyBank"), (size_t)count);
}

int32_t bb_peek_byte(int32_t bank, int32_t offset)
{
	return *bb_bank_at(bank, offset, 1, "PeekByte");
}

int32_t bb_peek_short(int32_t bank, int32_t offset)
{
	uint16_t v;
	memcpy(&v, bb_bank_at(bank, offset, 2, "PeekShort"), 2);
	return v;
}

int32_t bb_peek_int(int32_t bank, int32_t offset)
{
	int32_t v;
	memcpy(&v, bb_bank_at(bank, offset, 4, "PeekInt"), 4);
	return v;
}

float bb_peek_float(int32_t bank, int32_t offset)
{
	float v;
	memcpy(&v, bb_bank_at(bank, offset, 4, "PeekFloat"), 4);
	return v;
}

void bb_poke_byte(int32_t bank, int32_t offset, int32_t value)
{
	*bb_bank_at(bank, offset, 1, "PokeByte") = (uint8_t)value;
}

void bb_poke_short(int32_t bank, int32_t offset, int32_t value)
{
	uint16_t v = (uint16_t)value;
	memcpy(bb_bank_at(bank, offset, 2, "PokeShort"), &v, 2);
}

void bb_poke_int(int32_t bank, int32_t offset, int32_t value)
{
	memcpy(bb_bank_at(bank, offset, 4, "PokeInt"), &value, 4);
}

void bb_poke_float(int32_t bank, int32_t offset, float value)
{
	memcpy(bb_bank_at(bank, offset, 4, "PokeFloat"), &value, 4);
}

