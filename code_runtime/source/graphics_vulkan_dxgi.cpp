		void release_device()
		{
			if (d3d.context) {
				d3d.context->ClearState();
				d3d.context->Flush();
			}
			release(d3d.context);
			release(d3d.device);
			release(d3d.factory);
			d3d.tearing = false;
		}

		// The Direct3D 11 device on the GPU that Vulkan uses (found by its LUID). Called with d3d_lock held.
		bool ensure_device(VkDevice vk_device)
		{
			if (d3d.made_for == vk_device) {
				return d3d.device != nullptr;
			}
			release_device();
			d3d.made_for = vk_device;
			d3d.failed   = true;
			if (!device_luid_valid) {
				return false;
			}
			if (!d3d.d3d11_library) {
				d3d.d3d11_library = LoadLibraryA("d3d11.dll");
				d3d.dxgi_library  = LoadLibraryA("dxgi.dll");
			}
			auto create_device  = d3d.d3d11_library ? reinterpret_cast<PFN_D3D11_CREATE_DEVICE>(GetProcAddress(d3d.d3d11_library, "D3D11CreateDevice")) : nullptr;
			auto create_factory = d3d.dxgi_library ? reinterpret_cast<HRESULT(WINAPI*)(REFIID, void**)>(GetProcAddress(d3d.dxgi_library, "CreateDXGIFactory1")) : nullptr;
			if (!create_device || !create_factory) {
				return false;
			}
			IDXGIFactory1* factory1 = nullptr;
			HRESULT        result   = create_factory(__uuidof(IDXGIFactory1), reinterpret_cast<void**>(&factory1));
			if (FAILED(result)) {
				warn("CreateDXGIFactory1", result);
				return false;
			}
			result = factory1->QueryInterface(__uuidof(IDXGIFactory2), reinterpret_cast<void**>(&d3d.factory));
			IDXGIAdapter1* adapter = nullptr;
			for (UINT i = 0; SUCCEEDED(result) && (factory1->EnumAdapters1(i, &adapter) != DXGI_ERROR_NOT_FOUND); i++) {
				DXGI_ADAPTER_DESC1 desc = {};
				adapter->GetDesc1(&desc);
				if (memcmp(&desc.AdapterLuid, device_luid, sizeof(desc.AdapterLuid)) == 0) {
					break;
				}
				release(adapter);
			}
			if (IDXGIFactory5* factory5 = nullptr; SUCCEEDED(factory1->QueryInterface(__uuidof(IDXGIFactory5), reinterpret_cast<void**>(&factory5)))) {
				BOOL allow = FALSE;
				d3d.tearing = SUCCEEDED(factory5->CheckFeatureSupport(DXGI_FEATURE_PRESENT_ALLOW_TEARING, &allow, sizeof(allow))) && allow;
				factory5->Release();
			}
			release(factory1);
			if (FAILED(result) || !adapter) {
				warn(adapter ? "IDXGIFactory2" : "no DXGI adapter has the LUID of the Vulkan device", result);
				release(adapter);
				release_device();
				return false;
			}

			const D3D_FEATURE_LEVEL levels[] = { D3D_FEATURE_LEVEL_11_1, D3D_FEATURE_LEVEL_11_0 };
			ID3D11Device*           device   = nullptr;
			ID3D11DeviceContext*    context  = nullptr;
			result = create_device(adapter, D3D_DRIVER_TYPE_UNKNOWN, nullptr, D3D11_CREATE_DEVICE_BGRA_SUPPORT, levels, UINT(std::size(levels)), D3D11_SDK_VERSION, &device, nullptr, &context);
			release(adapter);
			if (SUCCEEDED(result)) {
				result = device->QueryInterface(__uuidof(ID3D11Device5), reinterpret_cast<void**>(&d3d.device));
			}
			if (SUCCEEDED(result)) {
				result = context->QueryInterface(__uuidof(ID3D11DeviceContext4), reinterpret_cast<void**>(&d3d.context));
			}
			if (SUCCEEDED(result)) {
				// The submission thread and the threads of windows present with the one device.
				ID3D11Multithread* multithread = nullptr;
				result = context->QueryInterface(__uuidof(ID3D11Multithread), reinterpret_cast<void**>(&multithread));
				if (SUCCEEDED(result)) {
					multithread->SetMultithreadProtected(TRUE);
					multithread->Release();
				}
			}
			release(context);
			release(device);
			if (FAILED(result)) {
				warn("D3D11CreateDevice", result);
				release_device();
				return false;
			}
			d3d.failed = false;
			return true;
		}

		// The image was drawn and is in the layout of a present; it goes to Direct3D 11, which reads it as it is.
		void record_release(VkCommandBuffer cmd, VkImage image, uint32_t family)
		{
			VkCommandBufferBeginInfo begin = { VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO };
			begin.flags                    = VK_COMMAND_BUFFER_USAGE_SIMULTANEOUS_USE_BIT; // It is submitted again for every present of the image.
			vkBeginCommandBuffer(cmd, &begin);
			VkImageMemoryBarrier2 b       = { VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2 };
			b.srcStageMask                = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
			b.srcAccessMask               = VK_ACCESS_2_MEMORY_WRITE_BIT;
			b.dstStageMask                = VK_PIPELINE_STAGE_2_NONE;
			b.dstAccessMask               = VK_ACCESS_2_NONE;
			b.oldLayout                   = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR; // Where the drawing leaves it, as for a swapchain image.
			b.newLayout                   = VK_IMAGE_LAYOUT_GENERAL;
			b.srcQueueFamilyIndex         = family;
			b.dstQueueFamilyIndex         = VK_QUEUE_FAMILY_EXTERNAL;
			b.image                       = image;
			b.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
			b.subresourceRange.levelCount = 1;
			b.subresourceRange.layerCount = 1;
			VkDependencyInfo info         = { VK_STRUCTURE_TYPE_DEPENDENCY_INFO };
			info.imageMemoryBarrierCount  = 1;
			info.pImageMemoryBarriers     = &b;
			vkCmdPipelineBarrier2(cmd, &info);
			vkEndCommandBuffer(cmd);
		}

		// One of the images: a Direct3D 11 texture that Vulkan draws into.
		bool make_image(chain& c, uint32_t i, uint32_t width, uint32_t height, const VkPhysicalDeviceMemoryProperties& memory_types)
		{
			D3D11_TEXTURE2D_DESC desc = {};
			desc.Width                = width;
			desc.Height               = height;
			desc.MipLevels            = 1;
			desc.ArraySize            = 1;
			desc.Format               = DXGI_FORMAT_B8G8R8A8_UNORM;
			desc.SampleDesc.Count     = 1;
			desc.Usage                = D3D11_USAGE_DEFAULT;
			desc.BindFlags            = D3D11_BIND_RENDER_TARGET | D3D11_BIND_SHADER_RESOURCE;
			desc.MiscFlags            = D3D11_RESOURCE_MISC_SHARED | D3D11_RESOURCE_MISC_SHARED_NTHANDLE;
			HRESULT result            = d3d.device->CreateTexture2D(&desc, nullptr, &c.textures[i]);
			if (FAILED(result)) {
				warn("ID3D11Device::CreateTexture2D", result);
				return false;
			}
			IDXGIResource1* resource = nullptr;
			HANDLE          handle   = nullptr;
			result = c.textures[i]->QueryInterface(__uuidof(IDXGIResource1), reinterpret_cast<void**>(&resource));
			if (SUCCEEDED(result)) {
				result = resource->CreateSharedHandle(nullptr, DXGI_SHARED_RESOURCE_READ | DXGI_SHARED_RESOURCE_WRITE, nullptr, &handle);
				resource->Release();
			}
			if (FAILED(result)) {
				warn("IDXGIResource1::CreateSharedHandle", result);
				return false;
			}

			VkExternalMemoryImageCreateInfo external = { VK_STRUCTURE_TYPE_EXTERNAL_MEMORY_IMAGE_CREATE_INFO };
			external.handleTypes                     = VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT;
			VkImageCreateInfo image                  = { VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO };
			image.pNext                              = &external;
			image.imageType                          = VK_IMAGE_TYPE_2D;
			image.format                             = VK_FORMAT_B8G8R8A8_UNORM;
			image.extent                             = { width, height, 1 };
			image.mipLevels                          = 1;
			image.arrayLayers                        = 1;
			image.samples                            = VK_SAMPLE_COUNT_1_BIT;
			image.tiling                             = VK_IMAGE_TILING_OPTIMAL;
			image.usage                              = VK_IMAGE_USAGE_TRANSFER_DST_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT | VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT;
			image.sharingMode                        = VK_SHARING_MODE_EXCLUSIVE;
			image.initialLayout                      = VK_IMAGE_LAYOUT_UNDEFINED;
			VkResult made                            = vkCreateImage(c.device, &image, nullptr, &c.images[i]);
			uint32_t type                            = UINT32_MAX;
			VkMemoryRequirements needs               = {};
			if (made == VK_SUCCESS) {
				get_image_memory_requirements(c.device, c.images[i], &needs);
				VkMemoryWin32HandlePropertiesKHR properties = { VK_STRUCTURE_TYPE_MEMORY_WIN32_HANDLE_PROPERTIES_KHR };
				uint32_t                         allowed    = needs.memoryTypeBits;
				if ((get_memory_win32_handle_properties(c.device, VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT, handle, &properties) == VK_SUCCESS) && (properties.memoryTypeBits & allowed)) {
					allowed &= properties.memoryTypeBits;
				}
				for (uint32_t t = 0; t < memory_types.memoryTypeCount; t++) { // Video memory where it can be.
					if ((allowed & (1u << t)) && ((type == UINT32_MAX) || (memory_types.memoryTypes[t].propertyFlags & VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT))) {
						bool better = (type == UINT32_MAX) || !(memory_types.memoryTypes[type].propertyFlags & VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
						type        = better ? t : type;
					}
				}
			}
			if ((made == VK_SUCCESS) && (type != UINT32_MAX)) {
				VkMemoryDedicatedAllocateInfo dedicated = { VK_STRUCTURE_TYPE_MEMORY_DEDICATED_ALLOCATE_INFO };
				dedicated.image                         = c.images[i];
				VkImportMemoryWin32HandleInfoKHR import  = { VK_STRUCTURE_TYPE_IMPORT_MEMORY_WIN32_HANDLE_INFO_KHR };
				import.pNext                            = &dedicated;
				import.handleType                       = VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT;
				import.handle                           = handle;
				VkMemoryAllocateInfo allocate           = { VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO };
				allocate.pNext                          = &import;
				allocate.allocationSize                 = needs.size;
				allocate.memoryTypeIndex                = type;
				made                                    = allocate_memory(c.device, &allocate, nullptr, &c.memory[i]);
				if (made == VK_SUCCESS) {
					made = bind_image_memory(c.device, c.images[i], c.memory[i], 0);
				}
			}
			CloseHandle(handle); // Importing a handle of this type does not take it over.
			if ((made != VK_SUCCESS) || (type == UINT32_MAX)) {
				warn("importing a Direct3D 11 texture into Vulkan", HRESULT(made));
				return false;
			}
			return true;
		}

		void destroy_chain(chain* c)
		{
			// Direct3D 11 is done with the images once the fence has its last value.
			if (c->fence && c->counter && (c->fence->GetCompletedValue() < c->counter)) {
				if (HANDLE done = CreateEventW(nullptr, FALSE, FALSE, nullptr)) {
					if (SUCCEEDED(c->fence->SetEventOnCompletion(c->counter, done))) {
						WaitForSingleObject(done, 1000);
					}
					CloseHandle(done);
				}
			}
			for (uint32_t i = 0; i < image_count; i++) {
				if (c->images[i]) {
					vkDestroyImage(c->device, c->images[i], nullptr);
				}
				if (c->memory[i]) {
					free_memory(c->device, c->memory[i], nullptr);
				}
				release(c->textures[i]);
			}
			if (c->pool) {
				vkDestroyCommandPool(c->device, c->pool, nullptr);
			}
			if (c->timeline) {
				vkDestroySemaphore(c->device, c->timeline, nullptr);
			}
			release(c->fence);
			release(c->back);
			if (c->latency) {
				CloseHandle(c->latency);
			}
			release(c->swap);
			{
				// The swapchain is let go of at once, so the window can have a new one.
				std::lock_guard<std::mutex> guard(d3d_lock);
				if (d3d.context) {
					d3d.context->Flush();
				}
			}
			delete c;
		}
