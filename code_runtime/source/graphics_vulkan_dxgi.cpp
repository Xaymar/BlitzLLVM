// Windows: the pictures that Vulkan draws are shown through a DXGI swapchain instead of a Vulkan one.
//
// A Vulkan swapchain of a window on Windows is shown by the driver in its own way, and NVIDIA's holds on to its images for 30 to
// 140 ms at a time while a window is dragged or changes focus, which made every program stutter then (with FIFO and IMMEDIATE alike).
// A DXGI flip model swapchain, which Direct3D programs use, does not. So each window gets one, made with a Direct3D 11 device on the
// same GPU, and the images that Vulkan draws into are Direct3D 11 textures that both share (VK_KHR_external_memory_win32):
//
//   acquire: the next of the three images, once Direct3D 11 is done copying it (the GPU waits for that on the shared fence).
//   present: Vulkan signals the shared fence once the image is drawn; Direct3D 11 waits for that, copies the image into the back
//            buffer of the DXGI swapchain, signals the fence again and presents. Flip 1 presents with a sync interval of 1, which
//            waits for the display like FIFO; Flip 0 with 0 and tearing where the system allows it; Flip 2 and the windows that a
//            thread of their own shows (graphics_presenter.cpp) with 0 and no tearing, which shows the newest picture like MAILBOX.
//
// The fence is a Direct3D 11 fence that Vulkan imports as a timeline semaphore (VK_KHR_external_semaphore_win32). The images and the
// fence belong to one swapchain; the Direct3D 11 device is shared by all of them, with its multithread protection on, as the
// submission thread presents the window of Graphics and the thread of each other window presents that one.
//
// Where any of it is missing (an older Windows, a driver without the extensions, a GPU that Direct3D 11 can't find, or
// BLITZLLVM_DXGI_PRESENT=0) the window gets a Vulkan swapchain as before.
