		constexpr uint32_t image_count = 3;

		// The Direct3D 11 device that every swapchain presents with, made for the Vulkan device that is in use.
		struct d3d_device {
			HMODULE               d3d11_library = nullptr;
			HMODULE               dxgi_library  = nullptr;
			IDXGIFactory2*        factory       = nullptr;
			ID3D11Device5*        device        = nullptr;
			ID3D11DeviceContext4* context       = nullptr;
			bool                  tearing       = false; // DXGI_FEATURE_PRESENT_ALLOW_TEARING: Flip 0 can show at once.
			VkDevice              made_for      = VK_NULL_HANDLE;
			bool                  failed        = false; // Tried for made_for and it can't be done: Vulkan swapchains then.
		};
		std::mutex d3d_lock;
		d3d_device d3d;

		// What the Vulkan device was made with, set when it is made (on the program's thread).
		bool    extensions_on = false;
		uint8_t device_luid[VK_LUID_SIZE] = {};
		bool    device_luid_valid = false;
		PFN_vkGetMemoryWin32HandlePropertiesKHR get_memory_win32_handle_properties = nullptr;
		PFN_vkImportSemaphoreWin32HandleKHR     import_semaphore_win32_handle      = nullptr;
		PFN_vkAllocateMemory                    allocate_memory                    = nullptr;
		PFN_vkFreeMemory                        free_memory                        = nullptr;
		PFN_vkBindImageMemory                   bind_image_memory                  = nullptr;
		PFN_vkGetImageMemoryRequirements        get_image_memory_requirements      = nullptr;

		struct chain {
			VkDevice         device = VK_NULL_HANDLE;
			IDXGISwapChain1* swap   = nullptr;
			ID3D11Texture2D* back   = nullptr; // Buffer 0, which Direct3D 11 keeps as the one to draw into next.
			ID3D11Fence*     fence  = nullptr;
			VkSemaphore      timeline = VK_NULL_HANDLE; // The same fence, as Vulkan sees it.
			ID3D11Texture2D* textures[image_count] = {};
			VkImage          images[image_count]   = {};
			VkDeviceMemory   memory[image_count]   = {};
			VkCommandPool    pool = VK_NULL_HANDLE;
			VkCommandBuffer  release[image_count] = {}; // Hands an image that was drawn over to Direct3D 11 (see record_release).
			UINT             interval = 1, flags = 0;   // Of Present.
			HANDLE           latency  = nullptr;        // Signalled while the swapchain can take another picture without Present waiting.

			uint64_t              counter = 0;           // The last value the fence was given; only the thread that presents changes it.
			std::atomic<uint64_t> copied[image_count] = {}; // The value at which Direct3D 11 is done copying the image, 0 before.

			// An image is acquired again only once its last acquire was presented: until then the value of copied is not yet the one to wait for.
			std::mutex              lock;
			std::condition_variable presented;
			uint64_t                acquires[image_count] = {};
			uint64_t                presents[image_count] = {};
			uint32_t                next = 0;
		};
		std::mutex          chains_lock;
		std::vector<chain*> chains;

		chain* find(uint64_t handle)
		{
			if (!handle) {
				return nullptr;
			}
			std::lock_guard<std::mutex> guard(chains_lock);
			for (chain* c : chains) {
				if (uint64_t(uintptr_t(c)) == handle) {
					return c;
				}
			}
			return nullptr;
		}

