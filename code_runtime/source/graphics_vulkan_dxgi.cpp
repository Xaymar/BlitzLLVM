	void choose_extensions(const VkExtensionProperties* available, uint32_t available_count, const char** extensions, uint32_t& count)
	{
		extensions_on = false;
		if (!enabled()) {
			return;
		}
		bool memory = false, semaphore = false;
		for (uint32_t i = 0; i < available_count; i++) {
			memory |= strcmp(available[i].extensionName, VK_KHR_EXTERNAL_MEMORY_WIN32_EXTENSION_NAME) == 0;
			semaphore |= strcmp(available[i].extensionName, VK_KHR_EXTERNAL_SEMAPHORE_WIN32_EXTENSION_NAME) == 0;
		}
		if (memory && semaphore) {
			extensions[count++] = VK_KHR_EXTERNAL_MEMORY_WIN32_EXTENSION_NAME;
			extensions[count++] = VK_KHR_EXTERNAL_SEMAPHORE_WIN32_EXTENSION_NAME;
			extensions_on       = true;
		}
	}

	void device_made(VkInstance instance, VkPhysicalDevice physical, VkDevice device)
	{
		device_luid_valid = false;
		if (!extensions_on) {
			return;
		}
		auto get_instance_proc = reinterpret_cast<PFN_vkGetInstanceProcAddr>(SDL_Vulkan_GetVkGetInstanceProcAddr());
		auto get_properties2   = get_instance_proc ? reinterpret_cast<PFN_vkGetPhysicalDeviceProperties2>(get_instance_proc(instance, "vkGetPhysicalDeviceProperties2")) : nullptr;
		get_memory_win32_handle_properties = reinterpret_cast<PFN_vkGetMemoryWin32HandlePropertiesKHR>(vkGetDeviceProcAddr(device, "vkGetMemoryWin32HandlePropertiesKHR"));
		import_semaphore_win32_handle      = reinterpret_cast<PFN_vkImportSemaphoreWin32HandleKHR>(vkGetDeviceProcAddr(device, "vkImportSemaphoreWin32HandleKHR"));
		allocate_memory                    = reinterpret_cast<PFN_vkAllocateMemory>(vkGetDeviceProcAddr(device, "vkAllocateMemory"));
		free_memory                        = reinterpret_cast<PFN_vkFreeMemory>(vkGetDeviceProcAddr(device, "vkFreeMemory"));
		bind_image_memory                  = reinterpret_cast<PFN_vkBindImageMemory>(vkGetDeviceProcAddr(device, "vkBindImageMemory"));
		get_image_memory_requirements      = reinterpret_cast<PFN_vkGetImageMemoryRequirements>(vkGetDeviceProcAddr(device, "vkGetImageMemoryRequirements"));
		if (!get_properties2 || !get_memory_win32_handle_properties || !import_semaphore_win32_handle || !allocate_memory || !free_memory || !bind_image_memory || !get_image_memory_requirements) {
			return;
		}
		VkPhysicalDeviceIDProperties id = { VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_ID_PROPERTIES };
		VkPhysicalDeviceProperties2  properties = { VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2 };
		properties.pNext                        = &id;
		get_properties2(physical, &properties);
		if (id.deviceLUIDValid) {
			memcpy(device_luid, id.deviceLUID, sizeof(device_luid));
			device_luid_valid = true;
		}
	}

	bool create(swapchain& sc, const swapchain_desc& d)
	{
		using namespace gfx;
		HWND window = HWND(d.native_window);
		if (!enabled() || !extensions_on || !device_luid_valid || !window) {
			return false;
		}
		if ((d.width == 0) || (d.height == 0)) {
			sc.width = sc.height = 0;
			return true; // Minimized, try again later.
		}
		std::unique_lock<std::mutex> guard(d3d_lock);
		if (!ensure_device(vkd.device)) {
			return false;
		}

		chain* c  = new chain();
		c->device = vkd.device;
		c->interval = ((d.vsync == 1) && !d.own_thread) ? 1 : 0;
		c->flags    = ((d.vsync == 0) && !d.own_thread && d3d.tearing) ? DXGI_PRESENT_ALLOW_TEARING : 0;

		DXGI_SWAP_CHAIN_DESC1 desc = {};
		desc.Width                 = d.width;
		desc.Height                = d.height;
		desc.Format                = DXGI_FORMAT_B8G8R8A8_UNORM;
		desc.SampleDesc.Count      = 1;
		desc.BufferUsage           = DXGI_USAGE_RENDER_TARGET_OUTPUT;
		desc.BufferCount           = image_count;
		desc.Scaling               = DXGI_SCALING_STRETCH;
		desc.SwapEffect            = DXGI_SWAP_EFFECT_FLIP_DISCARD;
		desc.AlphaMode             = DXGI_ALPHA_MODE_IGNORE;
		desc.Flags                 = DXGI_SWAP_CHAIN_FLAG_FRAME_LATENCY_WAITABLE_OBJECT | (d3d.tearing ? DXGI_SWAP_CHAIN_FLAG_ALLOW_TEARING : 0);
		HRESULT result             = d3d.factory->CreateSwapChainForHwnd(d3d.device, window, &desc, nullptr, nullptr, &c->swap);
		if (SUCCEEDED(result)) {
			d3d.factory->MakeWindowAssociation(window, DXGI_MWA_NO_ALT_ENTER | DXGI_MWA_NO_WINDOW_CHANGES); // Fullscreen is the program's business.
			result = c->swap->GetBuffer(0, __uuidof(ID3D11Texture2D), reinterpret_cast<void**>(&c->back));
		}
		if (SUCCEEDED(result)) {
			// The wait for the display happens on this object and not in Present: Present holds the lock of the device, which every
			// window presents with.
			IDXGISwapChain2* swap2 = nullptr;
			result = c->swap->QueryInterface(__uuidof(IDXGISwapChain2), reinterpret_cast<void**>(&swap2));
			if (SUCCEEDED(result)) {
				swap2->SetMaximumFrameLatency(2);
				c->latency = swap2->GetFrameLatencyWaitableObject();
				swap2->Release();
			}
		}
		HANDLE fence_handle = nullptr;
		if (SUCCEEDED(result)) {
			result = d3d.device->CreateFence(0, D3D11_FENCE_FLAG_SHARED, __uuidof(ID3D11Fence), reinterpret_cast<void**>(&c->fence));
		}
		if (SUCCEEDED(result)) {
			result = c->fence->CreateSharedHandle(nullptr, GENERIC_ALL, nullptr, &fence_handle);
		}
		bool ok = SUCCEEDED(result);
		if (!ok) {
			warn("making the DXGI swapchain", result);
		}
		for (uint32_t i = 0; ok && (i < image_count); i++) {
			ok = make_image(*c, i, d.width, d.height, vkd.memory);
		}
		guard.unlock();

		if (ok) {
			VkSemaphoreTypeCreateInfo timeline_info = { VK_STRUCTURE_TYPE_SEMAPHORE_TYPE_CREATE_INFO };
			timeline_info.semaphoreType             = VK_SEMAPHORE_TYPE_TIMELINE;
			VkSemaphoreCreateInfo semaphore_info    = { VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO };
			semaphore_info.pNext                    = &timeline_info;
			ok                                      = vkCreateSemaphore(c->device, &semaphore_info, nullptr, &c->timeline) == VK_SUCCESS;
			if (ok) {
				VkImportSemaphoreWin32HandleInfoKHR import = { VK_STRUCTURE_TYPE_IMPORT_SEMAPHORE_WIN32_HANDLE_INFO_KHR };
				import.semaphore                           = c->timeline;
				import.handleType                          = VK_EXTERNAL_SEMAPHORE_HANDLE_TYPE_D3D12_FENCE_BIT; // Direct3D 11 fences are of the same kind.
				import.handle                              = fence_handle;
				VkResult imported                          = import_semaphore_win32_handle(c->device, &import);
				ok                                         = imported == VK_SUCCESS;
				if (!ok) {
					warn("vkImportSemaphoreWin32HandleKHR", HRESULT(imported));
				}
			}
		}
		if (fence_handle) {
			CloseHandle(fence_handle);
		}
		if (ok) {
			VkCommandPoolCreateInfo pool_info = { VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO };
			pool_info.queueFamilyIndex        = g.family;
			ok                                = vkCreateCommandPool(c->device, &pool_info, nullptr, &c->pool) == VK_SUCCESS;
			VkCommandBufferAllocateInfo cmd_info = { VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO };
			cmd_info.commandPool                 = c->pool;
			cmd_info.level                       = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
			cmd_info.commandBufferCount          = image_count;
			ok = ok && (vkAllocateCommandBuffers(c->device, &cmd_info, c->release) == VK_SUCCESS);
			for (uint32_t i = 0; ok && (i < image_count); i++) {
				record_release(c->release[i], c->images[i], g.family);
			}
		}
		if (!ok) {
			destroy_chain(c);
			return false;
		}

		sc.handle = uint64_t(uintptr_t(c));
		sc.count  = image_count;
		sc.width  = d.width;
		sc.height = d.height;
		for (uint32_t i = 0; i < image_count; i++) {
			sc.images[i]                = uint64_t(c->images[i]);
			VkSemaphoreCreateInfo sem   = { VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO };
			VkSemaphore           done  = VK_NULL_HANDLE;
			check(vkCreateSemaphore(c->device, &sem, nullptr, &done), "vkCreateSemaphore");
			sc.done[i] = uint64_t(done);
		}
		std::lock_guard<std::mutex> list_guard(chains_lock);
		chains.push_back(c);
		return true;
	}

	bool owns(uint64_t handle)
	{
		return find(handle) != nullptr;
	}

	void destroy(swapchain& sc)
	{
		chain* c = find(sc.handle);
		if (!c) {
			return;
		}
		{
			std::lock_guard<std::mutex> guard(chains_lock);
			for (size_t i = 0; i < chains.size(); i++) {
				if (chains[i] == c) {
					chains.erase(chains.begin() + ptrdiff_t(i));
					break;
				}
			}
		}
		for (uint32_t i = 0; i < sc.count; i++) {
			vkDestroySemaphore(c->device, VkSemaphore(sc.done[i]), nullptr);
			sc.images[i] = 0;
			sc.done[i]   = 0;
		}
		sc.count  = 0;
		sc.handle = 0;
		destroy_chain(c);
	}

	present_result acquire(uint64_t handle, VkSemaphore signal, VkQueue queue, uint32_t queue_index, uint64_t timeout_ns, uint32_t& index)
	{
		chain* c = find(handle);
		if (!c) {
			return { present_status::out_of_date, int32_t(VK_ERROR_OUT_OF_DATE_KHR) };
		}
		uint32_t i = 0;
		{
			std::unique_lock<std::mutex> guard(c->lock);
			i          = c->next;
			auto ready = [&] { return c->presents[i] == c->acquires[i]; };
			if (timeout_ns == UINT64_MAX) {
				c->presented.wait(guard, ready);
			} else if (!c->presented.wait_for(guard, std::chrono::nanoseconds(timeout_ns), ready)) {
				return { present_status::not_ready, int32_t(VK_TIMEOUT) };
			}
			c->acquires[i]++;
			c->next = (i + 1) % image_count;
		}

		// The image is ready to be drawn into once Direct3D 11 copied it the last time; the GPU waits for that, not this thread.
		uint64_t                      wait_value = c->copied[i].load();
		uint64_t                      no_value   = 0;
		VkPipelineStageFlags          stage      = VK_PIPELINE_STAGE_ALL_COMMANDS_BIT;
		VkTimelineSemaphoreSubmitInfo values     = { VK_STRUCTURE_TYPE_TIMELINE_SEMAPHORE_SUBMIT_INFO };
		values.waitSemaphoreValueCount           = wait_value ? 1 : 0;
		values.pWaitSemaphoreValues              = &wait_value;
		values.signalSemaphoreValueCount         = 1;
		values.pSignalSemaphoreValues            = &no_value; // A binary semaphore: the value is not looked at.
		VkSubmitInfo info                        = { VK_STRUCTURE_TYPE_SUBMIT_INFO };
		info.pNext                               = &values;
		info.waitSemaphoreCount                  = wait_value ? 1 : 0;
		info.pWaitSemaphores                     = &c->timeline;
		info.pWaitDstStageMask                   = &stage;
		info.signalSemaphoreCount                = 1;
		info.pSignalSemaphores                   = &signal;
		gfx::queue_lock(queue_index);
		VkResult result = vkQueueSubmit(queue, 1, &info, VK_NULL_HANDLE);
		gfx::queue_unlock(queue_index);
		index = i;
		if (result != VK_SUCCESS) {
			return { present_status::error, int32_t(result) };
		}
		return { present_status::ok, int32_t(VK_SUCCESS) };
	}

	present_result present(uint64_t handle, VkQueue queue, uint32_t queue_index, VkSemaphore wait, uint32_t index, bool wait_queue)
	{
		chain* c = find(handle);
		if (!c || (index >= image_count)) {
			return { present_status::out_of_date, int32_t(VK_ERROR_OUT_OF_DATE_KHR) };
		}
		uint64_t                      drawn  = ++c->counter;
		uint64_t                      none   = 0;
		VkPipelineStageFlags          stage  = VK_PIPELINE_STAGE_ALL_COMMANDS_BIT;
		VkTimelineSemaphoreSubmitInfo values = { VK_STRUCTURE_TYPE_TIMELINE_SEMAPHORE_SUBMIT_INFO };
		values.waitSemaphoreValueCount       = 1;
		values.pWaitSemaphoreValues          = &none; // The binary semaphore of the drawing.
		values.signalSemaphoreValueCount     = 1;
		values.pSignalSemaphoreValues        = &drawn;
		VkSubmitInfo info                    = { VK_STRUCTURE_TYPE_SUBMIT_INFO };
		info.pNext                           = &values;
		info.waitSemaphoreCount              = 1;
		info.pWaitSemaphores                 = &wait;
		info.pWaitDstStageMask               = &stage;
		info.commandBufferCount              = 1;
		info.pCommandBuffers                 = &c->release[index];
		info.signalSemaphoreCount            = 1;
		info.pSignalSemaphores               = &c->timeline;
		gfx::queue_lock(queue_index);
		VkResult result = vkQueueSubmit(queue, 1, &info, VK_NULL_HANDLE);
		if (wait_queue && (result == VK_SUCCESS)) {
			vkQueueWaitIdle(queue);
		}
		gfx::queue_unlock(queue_index);

		HRESULT shown = S_OK;
		if (result == VK_SUCCESS) {
			uint64_t copied = ++c->counter;
			{
				std::lock_guard<std::mutex> guard(d3d_lock);
				d3d.context->Wait(c->fence, drawn);
				d3d.context->CopyResource(c->back, c->textures[index]);
				d3d.context->Signal(c->fence, copied);
			}
			c->copied[index].store(copied);
		}
		{
			std::lock_guard<std::mutex> guard(c->lock);
			c->presents[index]++; // Even when the submit failed: the image is not held up by it.
		}
		c->presented.notify_all();
		if (result != VK_SUCCESS) {
			return { present_status::error, int32_t(result) };
		}
		// Not under d3d_lock, and only once the swapchain can take the picture: with a sync interval of 1 that waits for the
		// display, which the other windows must not wait for. A second at most, for a window that is hidden.
		if (c->latency) {
			WaitForSingleObjectEx(c->latency, 1000, TRUE);
		}
		shown = c->swap->Present(c->interval, c->flags);
		if ((shown == DXGI_ERROR_DEVICE_REMOVED) || (shown == DXGI_ERROR_DEVICE_RESET) || (shown == DXGI_ERROR_INVALID_CALL)) {
			warn("IDXGISwapChain::Present", shown);
			return { present_status::out_of_date, int32_t(VK_ERROR_OUT_OF_DATE_KHR) }; // Made again, as a Vulkan swapchain if DXGI keeps failing.
		}
		return { present_status::ok, int32_t(VK_SUCCESS) };
	}
