// Sprites are a square that normally turns towards the camera, which the renderer takes care of.
int32_t bb_create_sprite(int32_t parent)
{
	int      mesh = new_mesh(parent);
	surface* s    = surface_of(new_surface(mesh));
	static const float corners[4][2] = { { -1, -1 }, { 1, -1 }, { 1, 1 }, { -1, 1 } };
	for (int i = 0; i < 4; i++) {
		add_vertex(s, corners[i][0], corners[i][1], 0, 0, 0, -1, (corners[i][0] + 1) / 2, 1 - (corners[i][1] + 1) / 2);
	}
	add_oriented_triangle(s, 0, 1, 2);
	add_oriented_triangle(s, 0, 2, 3);
	entity* e      = get_entity(mesh);
	e->sprite_mode = 1;
	return mesh;
}

void bb_scale_sprite(int32_t handle, float x, float y)
{
	entity* e = need_kind(handle, MESH, "ScaleSprite");
	e->sprite_scale[0] = x;
	e->sprite_scale[1] = y;
}

void bb_rotate_sprite(int32_t handle, float angle)
{
	need_kind(handle, MESH, "RotateSprite")->sprite_angle = angle;
}

void bb_sprite_view_mode(int32_t handle, int32_t mode)
{
	entity* e = need_kind(handle, MESH, "SpriteViewMode");
	if (e->sprite_mode) {
		e->sprite_mode = (mode < 1 || mode > 4) ? 1 : mode;
	}
}

// A plane that has no end in Blitz. The renderer makes the part of it that the camera can see out of squares, as many
// per side as the segments say, which is also why lights show on it. The large square here is for collisions and picking.
int32_t bb_create_plane(int32_t divisions, int32_t parent)
{
	int      mesh = new_mesh(parent);
	surface* s    = surface_of(new_surface(mesh));
	const float size = 10000.0f;
	static const float corners[4][2] = { { -1, -1 }, { 1, -1 }, { 1, 1 }, { -1, 1 } };
	for (int i = 0; i < 4; i++) {
		add_vertex(s, corners[i][0] * size, 0, corners[i][1] * size, 0, 1, 0, corners[i][0] * size, corners[i][1] * size);
	}
	add_oriented_triangle(s, 0, 1, 2);
	add_oriented_triangle(s, 0, 2, 3);
	entity* e     = get_entity(mesh);
	e->cls        = "Plane";
	e->plane_divs = divisions < 1 ? 1 : (divisions > 20 ? 20 : divisions);
	return mesh;
}

// Where a sprite is held, in half the size of it: the middle is 0, 0. It turns and scales around there.
void bb_handle_sprite(int32_t handle, float x, float y)
{
	entity* e = need_kind(handle, MESH, "HandleSprite");
	if (!e->sprite_mode) {
		bb_runtime_error("HandleSprite: the entity is not a sprite.");
	}
	e->sprite_handle[0] = x;
	e->sprite_handle[1] = y;
}

// A sprite with a texture from a file: lit by nothing, and see-through the way the flags say. 0 if the file can't be loaded.
int32_t bb_load_sprite(const char* file, int32_t flags, int32_t parent)
{
	if (parent) {
		need(parent, "LoadSprite");
	}
	int32_t texture = bb_load_texture(file, flags);
	if (!texture) {
		return 0;
	}
	int32_t sprite = bb_create_sprite(parent);
	bb_entity_texture(sprite, texture, 0, 0);
	bb_entity_fx(sprite, 1);
	bb_entity_blend(sprite, ((flags & 4) || (flags & 2)) ? 1 : 3);
	return sprite;
}
