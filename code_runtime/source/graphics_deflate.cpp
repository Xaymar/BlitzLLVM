	unsigned char* zlib_compress(const unsigned char* data, int size_in, int* out_size, int level)
	{
		if (level < 0) {
			level = 0;
		}
		if (level > 9) {
			level = 9;
		}
		size_t               size = size_t(size_in);
		std::vector<uint8_t> out;
		out.reserve(size / 2 + 64);
		out.push_back(0x78);
		int     flevel = (level < 2) ? 0 : (level < 6 ? 1 : (level == 6 ? 2 : 3));
		uint8_t flags  = uint8_t(flevel << 6);
		flags         = uint8_t(flags + (31 - ((0x7800 + flags) % 31)) % 31);
		out.push_back(flags);
		bits_out bits(out);

		if (level == 0 || size == 0) {
			size_t pos = 0;
			do {
				size_t n = std::min<size_t>(size - pos, 65535);
				bool   last = (pos + n >= size);
				bits.put(last ? 1 : 0, 1);
				bits.put(0, 2);
				bits.align();
				bits.put(uint32_t(n), 16);
				bits.put(~uint32_t(n) & 0xffff, 16);
				for (size_t i = 0; i < n; i++) {
					bits.put(data[pos + i], 8);
				}
				pos += n;
			} while (pos < size);
		} else {
			const level_config& cfg     = levels[level];
			const bool          lazy    = level >= 4;
			const size_t        window  = 32768;
			std::vector<int32_t> head(1 << 15, -1), previous(window, -1);
			std::vector<token>   tokens;
			tokens.reserve(1 << 15);
			size_t block_start = 0;

			auto hash = [&](size_t i) -> uint32_t { return ((uint32_t(data[i]) | (uint32_t(data[i + 1]) << 8) | (uint32_t(data[i + 2]) << 16)) * 2654435761u) >> 17; };
			auto insert = [&](size_t i) {
				if (i + 2 < size) {
					uint32_t h = hash(i);
					previous[i & (window - 1)] = head[h];
					head[h]                    = int32_t(i);
				}
			};
			// The longest match at i that is longer than `best`, found by following the chain of positions with the same hash.
			auto find = [&](size_t i, int best, int& distance) -> int {
				if (i + 2 >= size) {
					return 0;
				}
				int    max_len = int(std::min<size_t>(258, size - i));
				if (best >= max_len) {
					return 0;
				}
				int    chain   = (best >= cfg.good) ? cfg.chain >> 2 : cfg.chain;
				int    found   = 0;
				int32_t cand   = head[hash(i)];
				while (cand >= 0 && chain-- > 0 && (i - size_t(cand)) <= window - 1) {
					const uint8_t* a = data + cand;
					const uint8_t* b = data + i;
					int probe = best >= found ? best : found; // The byte after the longest match so far has to match for this one to beat it.
					if (a[probe] == b[probe]) {
						int len = 0;
						while (len < max_len && a[len] == b[len]) {
							len++;
						}
						if (len > best && len > found) {
							found    = len;
							distance = int(i - size_t(cand));
							if (len >= cfg.nice || len >= max_len) {
								break;
							}
						}
					}
					int32_t next = previous[size_t(cand) & (window - 1)];
					if (next >= cand) {
						break;
					}
					cand = next;
				}
				return found;
			};
			auto flush = [&](size_t end, bool last) {
				write_block(bits, tokens, data + block_start, end - block_start, last);
				tokens.clear();
				block_start = end;
			};
			auto emit_literal = [&](size_t i) { tokens.push_back({ data[i], 0 }); };
			auto emit_match   = [&](int len, int dist) { tokens.push_back({ uint16_t(len), uint16_t(dist) }); };

			size_t i = 0;
			int    prev_len = 0, prev_dist = 0;
			bool   have_prev = false;
			while (i < size) {
				int len = 0, dist = 0;
				if (i + 2 < size && (!have_prev || prev_len < cfg.lazy)) {
					len = find(i, have_prev ? std::max(prev_len, 2) : 2, dist);
					if (len == 3 && dist > 4096) {
						len = 0; // Not worth it, a literal is shorter.
					}
				}
				insert(i);
				if (!lazy) {
					if (len >= 3) {
						emit_match(len, dist);
						for (int k = 1; k < len; k++) {
							insert(i + size_t(k));
						}
						i += size_t(len);
					} else {
						emit_literal(i);
						i++;
					}
				} else if (have_prev && prev_len >= 3 && len <= prev_len) {
					emit_match(prev_len, prev_dist);
					for (size_t k = i + 1; k < i - 1 + size_t(prev_len); k++) {
						insert(k);
					}
					i         = i - 1 + size_t(prev_len);
					have_prev = false;
					prev_len  = 0;
				} else {
					if (have_prev) {
						emit_literal(i - 1);
					}
					have_prev = true;
					prev_len  = len;
					prev_dist = dist;
					i++;
				}
				if (tokens.size() >= (1 << 15) - 2) {
					flush(have_prev ? i - 1 : i, false); // A pending match starts at i - 1 and is not in the tokens yet.
				}
			}
			if (have_prev) {
				emit_literal(size - 1);
			}
			flush(size, true);
		}
		bits.align();
		uint32_t adler = adler32(data, size);
		out.push_back(uint8_t(adler >> 24));
		out.push_back(uint8_t(adler >> 16));
		out.push_back(uint8_t(adler >> 8));
		out.push_back(uint8_t(adler));
		auto* result = static_cast<unsigned char*>(bb_malloc(out.size()));
		if (!result) {
			return nullptr;
		}
		memcpy(result, out.data(), out.size());
		*out_size = int(out.size());
		return result;
	}

