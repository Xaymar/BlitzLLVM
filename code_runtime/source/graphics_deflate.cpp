// A zlib (RFC 1950) compressor for the PNG files of the save commands. The one in stb_image_write only has fixed Huffman codes and no lazy matching, so
// a higher compression level did not make files smaller. This one searches the previous 32 KiB with hash chains, with lazy matching on the levels from 4,
// and picks for every block whichever of stored, fixed and dynamic Huffman codes is smallest. The levels are those of zlib: 0 stores the data as it is,
// 1 is the fastest and 9 searches the longest.

