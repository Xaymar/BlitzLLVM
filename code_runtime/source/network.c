typedef struct bb_tcp {
	bb_socket sock;
	int32_t   ip; // The IPv4 address as a number, 0 for an IPv6 one.
	int32_t   port;
	int       server;
	int       dual;        // Whether the socket takes IPv4 and IPv6.
	char      address[64]; // The address as text, IPv4 or IPv6.
} bb_tcp;

static size_t bb_tcp_read(bb_stream* stream, void* data, size_t size)
{
	bb_tcp* tcp  = (bb_tcp*)stream->user;
	size_t  got  = 0;
	char*   dest = (char*)data;
	while (got < size) {
		if (!bb_available(tcp->sock) && !bb_wait_readable(tcp->sock, bb_net.read_timeout)) {
			break;
		}
		int n = recv(tcp->sock, dest + got, (int)(size - got), 0);
		if (n <= 0) {
			break;
		}
		got += (size_t)n;
	}
	return got;
}

static size_t bb_tcp_write(bb_stream* stream, const void* data, size_t size)
{
	bb_tcp*     tcp  = (bb_tcp*)stream->user;
	size_t      sent = 0;
	const char* src  = (const char*)data;
	while (sent < size) {
		int n = send(tcp->sock, src + sent, (int)(size - sent), BB_SEND_FLAGS);
		if (n <= 0) {
			break;
		}
		sent += (size_t)n;
	}
	return sent;
}

static int32_t bb_tcp_available(bb_stream* stream)
{
	return bb_available(((bb_tcp*)stream->user)->sock);
}

// Done when the other side closed the connection, and everything was read.
static int32_t bb_tcp_at_end(bb_stream* stream)
{
	bb_tcp* tcp = (bb_tcp*)stream->user;
	if (bb_available(tcp->sock)) {
		return 0;
	}
	if (!bb_wait_readable(tcp->sock, 0)) {
		return 0;
	}
	char c;
	return recv(tcp->sock, &c, 1, MSG_PEEK) <= 0;
}

static void bb_tcp_close(bb_stream* stream)
{
	bb_tcp* tcp = (bb_tcp*)stream->user;
	bb_close_socket(tcp->sock);
	bb_free(tcp);
}

static int32_t bb_tcp_add(bb_socket sock, const struct sockaddr* peer, int32_t port, int server, int dual)
{
#if defined(SO_NOSIGPIPE)
	int no_signal = 1;
	setsockopt(sock, SOL_SOCKET, SO_NOSIGPIPE, (const char*)&no_signal, sizeof(no_signal));
#endif
	bb_tcp* tcp = (bb_tcp*)bb_calloc_or_fail(1, sizeof(bb_tcp));
	tcp->sock   = sock;
	tcp->port   = port;
	tcp->server = server;
	tcp->dual   = dual;
	if (peer) {
		tcp->ip = bb_sockaddr_ip(peer);
		bb_sockaddr_text(peer, tcp->address, sizeof(tcp->address));
	}

	bb_stream stream;
	memset(&stream, 0, sizeof(stream));
	stream.kind      = BB_STREAM_NET;
	stream.user      = tcp;
	stream.read      = bb_tcp_read;
	stream.write     = bb_tcp_write;
	stream.available = bb_tcp_available;
	stream.at_end    = bb_tcp_at_end;
	stream.close     = bb_tcp_close;
	return bb_stream_add(stream);
}

static bb_tcp* bb_tcp_get(int32_t handle, const char* what, int server)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if ((stream->kind != BB_STREAM_NET) || (stream->close != bb_tcp_close) || (((bb_tcp*)stream->user)->server != server)) {
		char message[96];
		snprintf(message, sizeof(message), "%s: this is not a TCP %s.", what, server ? "server" : "stream");
		bb_runtime_error(message);
	}
	return (bb_tcp*)stream->user;
}

void bb_tcp_timeouts(int32_t read, int32_t accept)
{
	bb_net.read_timeout   = read;
	bb_net.accept_timeout = accept;
}

int32_t bb_open_tcp_stream(const char* server, int32_t port, int32_t local_port)
{
	bb_network_init();
	if (!server) {
		return 0;
	}
	// The system sorts the addresses of a name by what is likely to work (IPv6 first where there is a route for it), and the first
	// one that connects is the one used.
	struct addrinfo* list = bb_resolve_all(server, SOCK_STREAM);
	struct addrinfo* entry;
	for (entry = list; entry; entry = entry->ai_next) {
		if (entry->ai_family != AF_INET && entry->ai_family != AF_INET6) {
			continue;
		}
		bb_socket sock = socket(entry->ai_family, SOCK_STREAM, 0);
		if (sock == BB_INVALID_SOCKET) {
			continue;
		}
		if (local_port) {
			bb_addr local;
			memset(&local, 0, sizeof(local));
			if (entry->ai_family == AF_INET6) {
				struct sockaddr_in6* v6 = (struct sockaddr_in6*)&local.storage;
				v6->sin6_family         = AF_INET6;
				v6->sin6_addr           = in6addr_any;
				v6->sin6_port           = htons((unsigned short)local_port);
				local.length            = sizeof(*v6);
			} else {
				struct sockaddr_in* v4 = (struct sockaddr_in*)&local.storage;
				v4->sin_family         = AF_INET;
				v4->sin_addr.s_addr    = htonl(INADDR_ANY);
				v4->sin_port           = htons((unsigned short)local_port);
				local.length           = sizeof(*v4);
			}
			bind(sock, (struct sockaddr*)&local.storage, local.length);
		}
		bb_addr remote;
		memset(&remote, 0, sizeof(remote));
		memcpy(&remote.storage, entry->ai_addr, entry->ai_addrlen);
		remote.length = (socklen_t)entry->ai_addrlen;
		if (remote.storage.ss_family == AF_INET6) {
			((struct sockaddr_in6*)&remote.storage)->sin6_port = htons((unsigned short)port);
		} else {
			((struct sockaddr_in*)&remote.storage)->sin_port = htons((unsigned short)port);
		}
		if (connect(sock, (struct sockaddr*)&remote.storage, remote.length) != 0) {
			bb_close_socket(sock);
			continue;
		}
		int32_t handle = bb_tcp_add(sock, (struct sockaddr*)&remote.storage, port, 0, 0);
		freeaddrinfo(list);
		return handle;
	}
	if (list) {
		freeaddrinfo(list);
	}
	return 0;
}

void bb_close_tcp_stream(int32_t handle)
{
	bb_tcp_get(handle, "CloseTCPStream", 0);
	bb_stream* stream = bb_stream_get(handle, "CloseTCPStream");
	stream->close(stream);
	bb_stream_remove(handle);
}

