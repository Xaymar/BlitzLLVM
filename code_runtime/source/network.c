// UDP
////////////////////////////////////////////////////////////////////////////////
// The most a message may have. Every stream has one buffer of this size for what it receives, made with the stream, and a message that has
// more is dropped (the sender can not make the program use more memory by sending more). A UDP datagram is 64 KiB at most on Windows and
// Linux, so this takes every message a peer can send over IPv4 and the drop is only a guard.
#define BB_UDP_MAX_MESSAGE 65536

typedef struct bb_udp {
	bb_socket sock;
	int32_t   port;
	uint8_t*  in; // BB_UDP_MAX_MESSAGE + 1 bytes: the one more tells a message that is too big from one that just fits.
	size_t    in_size, in_pos;
	uint8_t*  out;
	size_t    out_size, out_cap;
	int32_t   from_ip, from_port;
	int       dual;           // Whether the socket takes IPv4 and IPv6.
	char      from_text[64];  // Where the last message came from, as text.
} bb_udp;

static size_t bb_udp_read(bb_stream* stream, void* data, size_t size)
{
	bb_udp* udp   = (bb_udp*)stream->user;
	size_t  avail = udp->in_size - udp->in_pos;
	size_t  take  = size < avail ? size : avail;
	memcpy(data, udp->in + udp->in_pos, take);
	udp->in_pos += take;
	return take;
}

static size_t bb_udp_write(bb_stream* stream, const void* data, size_t size)
{
	bb_udp* udp = (bb_udp*)stream->user;
	if (udp->out_size + size > udp->out_cap) {
		udp->out_cap = (udp->out_size + size) * 2;
		udp->out     = (uint8_t*)bb_realloc_or_fail(udp->out, udp->out_cap);
	}
	memcpy(udp->out + udp->out_size, data, size);
	udp->out_size += size;
	return size;
}

static int32_t bb_udp_available(bb_stream* stream)
{
	bb_udp* udp = (bb_udp*)stream->user;
	return (int32_t)(udp->in_size - udp->in_pos);
}

static int32_t bb_udp_at_end(bb_stream* stream)
{
	bb_udp* udp = (bb_udp*)stream->user;
	return udp->in_pos >= udp->in_size;
}

static void bb_udp_close(bb_stream* stream)
{
	bb_udp* udp = (bb_udp*)stream->user;
	bb_close_socket(udp->sock);
	bb_free(udp->in);
	bb_free(udp->out);
	bb_free(udp);
}

static bb_udp* bb_udp_get(int32_t handle, const char* what)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if ((stream->kind != BB_STREAM_NET) || (stream->close != bb_udp_close)) {
		char message[96];
		snprintf(message, sizeof(message), "%s: this is not a UDP stream.", what);
		bb_runtime_error(message);
	}
	return (bb_udp*)stream->user;
}

int32_t bb_create_udp_stream(int32_t port)
{
	bb_network_init();
	int       dual = 0;
	bb_socket sock = bb_socket_dual(SOCK_DGRAM, &dual);
	if (sock == BB_INVALID_SOCKET) {
		return 0;
	}
	bb_addr local;
	memset(&local, 0, sizeof(local));
	if (dual) {
		struct sockaddr_in6* v6 = (struct sockaddr_in6*)&local.storage;
		v6->sin6_family         = AF_INET6;
		v6->sin6_addr           = in6addr_any;
		v6->sin6_port           = htons((unsigned short)port);
		local.length            = sizeof(*v6);
	} else {
		struct sockaddr_in* v4 = (struct sockaddr_in*)&local.storage;
		v4->sin_family         = AF_INET;
		v4->sin_addr.s_addr    = htonl(INADDR_ANY);
		v4->sin_port           = htons((unsigned short)port);
		local.length           = sizeof(*v4);
	}
	if (bind(sock, (struct sockaddr*)&local.storage, local.length) != 0) {
		bb_close_socket(sock);
		return 0;
	}
	// With port 0 the system picks one.
	local.length = (socklen_t)sizeof(local.storage);
	getsockname(sock, (struct sockaddr*)&local.storage, &local.length);

	bb_udp* udp = (bb_udp*)bb_calloc_or_fail(1, sizeof(bb_udp));
	udp->sock   = sock;
	udp->in     = (uint8_t*)bb_malloc_or_fail(BB_UDP_MAX_MESSAGE + 1);
	udp->port   = bb_sockaddr_port((struct sockaddr*)&local.storage);
	udp->dual   = dual;

	bb_stream stream;
	memset(&stream, 0, sizeof(stream));
	stream.kind      = BB_STREAM_NET;
	stream.user      = udp;
	stream.read      = bb_udp_read;
	stream.write     = bb_udp_write;
	stream.available = bb_udp_available;
	stream.at_end    = bb_udp_at_end;
	stream.close     = bb_udp_close;
	return bb_stream_add(stream);
}

void bb_close_udp_stream(int32_t handle)
{
	bb_udp_get(handle, "CloseUDPStream");
	bb_stream* stream = bb_stream_get(handle, "CloseUDPStream");
	stream->close(stream);
	bb_stream_remove(handle);
}

static void bb_udp_send(bb_udp* udp, const bb_addr* remote)
{
	sendto(udp->sock, (const char*)udp->out, (int)udp->out_size, 0, (const struct sockaddr*)&remote->storage, remote->length);
	udp->out_size = 0;
}

// Sends what was written to the stream. Without a port, it goes to the port of the stream.
void bb_send_udp_msg(int32_t handle, int32_t ip, int32_t port)
{
	bb_udp* udp = bb_udp_get(handle, "SendUDPMsg");
	bb_addr remote;
	bb_addr_from_ip(&remote, udp->dual, ip, port ? port : udp->port);
	bb_udp_send(udp, &remote);
}

// Sends what was written to the stream to an address given as text, IPv4 or IPv6 (or a name). The message is dropped if the address
// can not be found, or if it is an IPv6 address and the stream only takes IPv4.
void bb_send_udp_msg_to(int32_t handle, const char* address, int32_t port)
{
	bb_udp* udp = bb_udp_get(handle, "SendUDPMsgTo");
	if (!address) {
		udp->out_size = 0;
		return;
	}
	struct addrinfo* list = bb_resolve_all(address, SOCK_DGRAM);
	struct addrinfo* entry;
	int              sent = 0;
	for (entry = list; entry && !sent; entry = entry->ai_next) {
		bb_addr remote;
		memset(&remote, 0, sizeof(remote));
		if (entry->ai_family == AF_INET) {
			bb_addr_from_ip(&remote, udp->dual, bb_ip_to_int(((struct sockaddr_in*)entry->ai_addr)->sin_addr), port ? port : udp->port);
		} else if (entry->ai_family == AF_INET6 && udp->dual) {
			memcpy(&remote.storage, entry->ai_addr, entry->ai_addrlen);
			remote.length = (socklen_t)entry->ai_addrlen;
			((struct sockaddr_in6*)&remote.storage)->sin6_port = htons((unsigned short)(port ? port : udp->port));
		} else {
			continue;
		}
		bb_udp_send(udp, &remote);
		sent = 1;
	}
	if (list) {
		freeaddrinfo(list);
	}
	udp->out_size = 0;
}

// Takes in the next message, if there is one. Returns how big it is, and 0 if there is none.
int32_t bb_recv_udp_msg(int32_t handle)
{
	bb_udp* udp = bb_udp_get(handle, "RecvUDPMsg");
	if (!bb_wait_readable(udp->sock, bb_net.udp_timeout)) {
		return 0;
	}
	bb_addr remote;
	memset(&remote, 0, sizeof(remote));
	remote.length = (socklen_t)sizeof(remote.storage);
	int n         = recvfrom(udp->sock, (char*)udp->in, BB_UDP_MAX_MESSAGE + 1, 0, (struct sockaddr*)&remote.storage, &remote.length);
	if ((n < 0) || (n > BB_UDP_MAX_MESSAGE)) {
		udp->in_size = udp->in_pos = 0;
		return 0;
	}
	udp->in_size   = (size_t)n;
	udp->in_pos    = 0;
	udp->from_ip   = bb_sockaddr_ip((struct sockaddr*)&remote.storage);
	udp->from_port = bb_sockaddr_port((struct sockaddr*)&remote.storage);
	bb_sockaddr_text((struct sockaddr*)&remote.storage, udp->from_text, sizeof(udp->from_text));
	return n;
}

void bb_udp_timeouts(int32_t receive)
{
	bb_net.udp_timeout = receive < 0 ? 0 : receive;
}

