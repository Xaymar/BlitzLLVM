// TCP and UDP streams, which are handles like files are, and can be read from and written to in the same way.
//
// TCP: OpenTCPStream connects, CreateTCPServer and AcceptTCPStream accept. Reading waits for data, until the read
// timeout set with TCPTimeouts is over.
// UDP: Writing to a stream builds a message, SendUDPMsg sends it. RecvUDPMsg receives the next message, which can
// then be read from the stream.

