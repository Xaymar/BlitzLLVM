static void bb_network_init(void)
{
#if defined(_WIN32)
	static int started = 0;
	if (!started) {
		WSADATA data;
		WSAStartup(MAKEWORD(2, 2), &data);
		started = 1;
	}
#endif
}

// Waits until the socket can be read, for up to the given time. Returns whether it can.
//
// select() can't be used where file descriptors are numbered like they are on Linux and macOS: FD_SET writes into an fd_set that has
// room for FD_SETSIZE (1024) of them, and a connection or file with a higher number than that, which a server that is busy has,
// would overwrite the stack.
static int bb_wait_readable(bb_socket sock, int32_t milliseconds)
{
#if defined(_WIN32)
	fd_set set;
	FD_ZERO(&set);
	FD_SET(sock, &set);
	struct timeval timeout;
	timeout.tv_sec  = milliseconds / 1000;
	timeout.tv_usec = (milliseconds % 1000) * 1000;
	return select((int)sock + 1, &set, NULL, NULL, &timeout) > 0;
#else
	struct pollfd entry;
	entry.fd      = sock;
	entry.events  = POLLIN;
	entry.revents = 0;
	return poll(&entry, 1, milliseconds < 0 ? 0 : milliseconds) > 0;
#endif
}

static int32_t bb_available(bb_socket sock)
{
#if defined(_WIN32)
	u_long count = 0;
	ioctlsocket(sock, FIONREAD, &count);
#else
	int count = 0;
	ioctl(sock, FIONREAD, &count);
#endif
	return (int32_t)count;
}

static int32_t bb_ip_to_int(struct in_addr address)
{
	uint32_t ip;
	memcpy(&ip, &address, sizeof(ip));
	return (int32_t)ntohl(ip); // The first part of the address is the highest byte, as in the original.
}

static struct in_addr bb_int_to_ip(int32_t ip)
{
	struct in_addr address;
	uint32_t       network = htonl((uint32_t)ip);
	memcpy(&address, &network, sizeof(network));
	return address;
}

// Whether IPv6 is used. On by default, BLITZLLVM_NET_IPV6=0 makes every command use IPv4 only. Read once, like all the BLITZLLVM_ variables.
static int bb_ipv6_enabled(void)
{
	static int enabled = -1;
	if (enabled < 0) {
		enabled = bb_env_int("BLITZLLVM_NET_IPV6", 1) != 0;
	}
	return enabled;
}

// An address of either kind, with the length that goes with it.
typedef struct bb_addr {
	struct sockaddr_storage storage;
	socklen_t               length;
} bb_addr;

// The IPv4 address a socket address holds as a number, or 0 if it is an IPv6 address that is not an IPv4 one in disguise.
// A socket that listens for both kinds sees IPv4 peers as ::ffff:a.b.c.d, which is what makes programs that only know IPv4 keep working.
static int32_t bb_sockaddr_ip(const struct sockaddr* address)
{
	if (address->sa_family == AF_INET) {
		return bb_ip_to_int(((const struct sockaddr_in*)address)->sin_addr);
	}
	if (address->sa_family == AF_INET6) {
		const struct in6_addr* v6 = &((const struct sockaddr_in6*)address)->sin6_addr;
		if (IN6_IS_ADDR_V4MAPPED(v6)) {
			struct in_addr v4;
			memcpy(&v4, v6->s6_addr + 12, sizeof(v4));
			return bb_ip_to_int(v4);
		}
	}
	return 0;
}

static int bb_sockaddr_port(const struct sockaddr* address)
{
	if (address->sa_family == AF_INET) {
		return ntohs(((const struct sockaddr_in*)address)->sin_port);
	}
	if (address->sa_family == AF_INET6) {
		return ntohs(((const struct sockaddr_in6*)address)->sin6_port);
	}
	return 0;
}

// Writes the address as text: 127.0.0.1 for IPv4 (also in disguise), ::1 for IPv6.
static void bb_sockaddr_text(const struct sockaddr* address, char* out, size_t size)
{
	out[0] = 0;
	if (address->sa_family == AF_INET6 && IN6_IS_ADDR_V4MAPPED(&((const struct sockaddr_in6*)address)->sin6_addr)) {
		struct sockaddr_in v4;
		memset(&v4, 0, sizeof(v4));
		v4.sin_family = AF_INET;
		v4.sin_addr   = bb_int_to_ip(bb_sockaddr_ip(address));
		getnameinfo((struct sockaddr*)&v4, sizeof(v4), out, (socklen_t)size, NULL, 0, NI_NUMERICHOST);
		return;
	}
	if (address->sa_family != AF_INET && address->sa_family != AF_INET6) {
		return;
	}
	getnameinfo(address, address->sa_family == AF_INET ? sizeof(struct sockaddr_in) : sizeof(struct sockaddr_in6), out, (socklen_t)size, NULL, 0, NI_NUMERICHOST);
}

// Makes a socket for the kind of connection, for both IPv4 and IPv6 if the system can. *dual says whether it can.
static bb_socket bb_socket_dual(int type, int* dual)
{
	*dual = 0;
	if (bb_ipv6_enabled()) {
		bb_socket sock = socket(AF_INET6, type, 0);
		if (sock != BB_INVALID_SOCKET) {
			int only = 0; // IPV6_V6ONLY is on by default on Windows and off on Linux.
			if (setsockopt(sock, IPPROTO_IPV6, IPV6_V6ONLY, (const char*)&only, sizeof(only)) == 0) {
				*dual = 1;
				return sock;
			}
			bb_close_socket(sock);
		}
	}
	return socket(AF_INET, type, 0);
}

// Gives an IPv4 number as a socket address for a socket, which wraps it as ::ffff:a.b.c.d if the socket is a dual one.
static void bb_addr_from_ip(bb_addr* out, int dual, int32_t ip, int port)
{
	memset(out, 0, sizeof(*out));
	if (dual) {
		struct sockaddr_in6* v6 = (struct sockaddr_in6*)&out->storage;
		v6->sin6_family         = AF_INET6;
		v6->sin6_port           = htons((unsigned short)port);
		v6->sin6_addr.s6_addr[10] = 0xFF;
		v6->sin6_addr.s6_addr[11] = 0xFF;
		struct in_addr v4         = bb_int_to_ip(ip);
		memcpy(v6->sin6_addr.s6_addr + 12, &v4, sizeof(v4));
		out->length = sizeof(struct sockaddr_in6);
	} else {
		struct sockaddr_in* v4 = (struct sockaddr_in*)&out->storage;
		v4->sin_family         = AF_INET;
		v4->sin_addr           = bb_int_to_ip(ip);
		v4->sin_port           = htons((unsigned short)port);
		out->length            = sizeof(struct sockaddr_in);
	}
}

// Resolves a name or a number, with [] around IPv6 allowed, to the addresses it has. The result must be freed with freeaddrinfo.
static struct addrinfo* bb_resolve_all(const char* name, int socktype)
{
	char        stripped[256];
	size_t      length = strlen(name);
	if (length >= 2 && name[0] == '[' && name[length - 1] == ']' && length - 2 < sizeof(stripped)) {
		memcpy(stripped, name + 1, length - 2);
		stripped[length - 2] = 0;
		name                 = stripped;
	}
	struct addrinfo hints, *result = NULL;
	memset(&hints, 0, sizeof(hints));
	hints.ai_family   = bb_ipv6_enabled() ? AF_UNSPEC : AF_INET;
	hints.ai_socktype = socktype;
	if (getaddrinfo(name, NULL, &hints, &result) != 0) {
		return NULL;
	}
	return result;
}

// Resolves a name or number to one IPv4 address, for the commands that only know them.
static int bb_resolve(const char* name, struct in_addr* out)
{
	struct addrinfo hints, *result = NULL;
	memset(&hints, 0, sizeof(hints));
	hints.ai_family   = AF_INET;
	hints.ai_socktype = SOCK_STREAM;
	if (getaddrinfo(name, NULL, &hints, &result) != 0 || !result) {
		return 0;
	}
	*out = ((struct sockaddr_in*)result->ai_addr)->sin_addr;
	freeaddrinfo(result);
	return 1;
}

const char* bb_dotted_ip(int32_t ip)
{
	char          buffer[32];
	int n = snprintf(buffer, sizeof(buffer), "%u.%u.%u.%u", ((unsigned)ip >> 24) & 255, ((unsigned)ip >> 16) & 255, ((unsigned)ip >> 8) & 255, (unsigned)ip & 255);
	return bb_copy(buffer, (size_t)n);
}

