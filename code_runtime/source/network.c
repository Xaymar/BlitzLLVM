typedef struct bb_tcp {
	bb_socket sock;
	int32_t   ip;
	int32_t   port;
	int       server;
} bb_tcp;

static size_t bb_tcp_read(bb_stream* stream, void* data, size_t size)
{
	bb_tcp* tcp  = (bb_tcp*)stream->user;
	size_t  got  = 0;
	char*   dest = (char*)data;
	while (got < size) {
		if (!bb_available(tcp->sock) && !bb_wait_readable(tcp->sock, bb_read_timeout)) {
			break;
		}
		int n = recv(tcp->sock, dest + got, (int)(size - got), 0);
		if (n <= 0) {
			break;
		}
		got += (size_t)n;
	}
	return got;
}

static size_t bb_tcp_write(bb_stream* stream, const void* data, size_t size)
{
	bb_tcp*     tcp  = (bb_tcp*)stream->user;
	size_t      sent = 0;
	const char* src  = (const char*)data;
	while (sent < size) {
		int n = send(tcp->sock, src + sent, (int)(size - sent), 0);
		if (n <= 0) {
			break;
		}
		sent += (size_t)n;
	}
	return sent;
}

static int32_t bb_tcp_available(bb_stream* stream)
{
	return bb_available(((bb_tcp*)stream->user)->sock);
}

// Done when the other side closed the connection, and everything was read.
static int32_t bb_tcp_at_end(bb_stream* stream)
{
	bb_tcp* tcp = (bb_tcp*)stream->user;
	if (bb_available(tcp->sock)) {
		return 0;
	}
	if (!bb_wait_readable(tcp->sock, 0)) {
		return 0;
	}
	char c;
	return recv(tcp->sock, &c, 1, MSG_PEEK) <= 0;
}

static void bb_tcp_close(bb_stream* stream)
{
	bb_tcp* tcp = (bb_tcp*)stream->user;
	bb_close_socket(tcp->sock);
	free(tcp);
}

static int32_t bb_tcp_add(bb_socket sock, int32_t ip, int32_t port, int server)
{
	bb_tcp* tcp = (bb_tcp*)calloc(1, sizeof(bb_tcp));
	tcp->sock   = sock;
	tcp->ip     = ip;
	tcp->port   = port;
	tcp->server = server;

	bb_stream stream;
	memset(&stream, 0, sizeof(stream));
	stream.kind      = BB_STREAM_NET;
	stream.user      = tcp;
	stream.read      = bb_tcp_read;
	stream.write     = bb_tcp_write;
	stream.available = bb_tcp_available;
	stream.at_end    = bb_tcp_at_end;
	stream.close     = bb_tcp_close;
	return bb_stream_add(stream);
}

static bb_tcp* bb_tcp_get(int32_t handle, const char* what, int server)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if ((stream->kind != BB_STREAM_NET) || (stream->close != bb_tcp_close) || (((bb_tcp*)stream->user)->server != server)) {
		char message[96];
		snprintf(message, sizeof(message), "%s: this is not a TCP %s.", what, server ? "server" : "stream");
		bb_runtime_error(message);
	}
	return (bb_tcp*)stream->user;
}

void bb_tcp_timeouts(int32_t read, int32_t accept)
{
	bb_read_timeout   = read;
	bb_accept_timeout = accept;
}

int32_t bb_open_tcp_stream(const char* server, int32_t port, int32_t local_port)
{
	bb_network_init();
	struct in_addr address;
	if (!server || !bb_resolve(server, &address)) {
		return 0;
	}
	bb_socket sock = socket(AF_INET, SOCK_STREAM, 0);
	if (sock == BB_INVALID_SOCKET) {
		return 0;
	}
	if (local_port) {
		struct sockaddr_in local;
		memset(&local, 0, sizeof(local));
		local.sin_family      = AF_INET;
		local.sin_addr.s_addr = htonl(INADDR_ANY);
		local.sin_port        = htons((unsigned short)local_port);
		bind(sock, (struct sockaddr*)&local, sizeof(local));
	}
	struct sockaddr_in remote;
	memset(&remote, 0, sizeof(remote));
	remote.sin_family = AF_INET;
	remote.sin_addr   = address;
	remote.sin_port   = htons((unsigned short)port);
	if (connect(sock, (struct sockaddr*)&remote, sizeof(remote)) != 0) {
		bb_close_socket(sock);
		return 0;
	}
	return bb_tcp_add(sock, bb_ip_to_int(address), port, 0);
}

void bb_close_tcp_stream(int32_t handle)
{
	bb_tcp_get(handle, "CloseTCPStream", 0);
	bb_stream* stream = bb_stream_get(handle, "CloseTCPStream");
	stream->close(stream);
	bb_stream_remove(handle);
}

int32_t bb_tcp_stream_ip(int32_t handle)
{
	return bb_tcp_get(handle, "TCPStreamIP", 0)->ip;
}

int32_t bb_tcp_stream_port(int32_t handle)
{
	return bb_tcp_get(handle, "TCPStreamPort", 0)->port;
}

int32_t bb_create_tcp_server(int32_t port)
{
	bb_network_init();
	bb_socket sock = socket(AF_INET, SOCK_STREAM, 0);
	if (sock == BB_INVALID_SOCKET) {
		return 0;
	}
	int reuse = 1;
	setsockopt(sock, SOL_SOCKET, SO_REUSEADDR, (const char*)&reuse, sizeof(reuse));
	struct sockaddr_in local;
	memset(&local, 0, sizeof(local));
	local.sin_family      = AF_INET;
	local.sin_addr.s_addr = htonl(INADDR_ANY);
	local.sin_port        = htons((unsigned short)port);
	if ((bind(sock, (struct sockaddr*)&local, sizeof(local)) != 0) || (listen(sock, 16) != 0)) {
		bb_close_socket(sock);
		return 0;
	}
	return bb_tcp_add(sock, 0, port, 1);
}

void bb_close_tcp_server(int32_t handle)
{
	bb_tcp_get(handle, "CloseTCPServer", 1);
	bb_stream* stream = bb_stream_get(handle, "CloseTCPServer");
	stream->close(stream);
	bb_stream_remove(handle);
}

// Returns the new stream, or 0 if nobody connected in time.
int32_t bb_accept_tcp_stream(int32_t server)
{
	bb_tcp* tcp = bb_tcp_get(server, "AcceptTCPStream", 1);
	if (!bb_wait_readable(tcp->sock, bb_accept_timeout)) {
		return 0;
	}
	struct sockaddr_in remote;
	int                length = (int)sizeof(remote);
	bb_socket          client = accept(tcp->sock, (struct sockaddr*)&remote, (void*)&length);
	if (client == BB_INVALID_SOCKET) {
		return 0;
	}
	return bb_tcp_add(client, bb_ip_to_int(remote.sin_addr), ntohs(remote.sin_port), 0);
}

#define BB_MAX_HOST_IPS 64

static int32_t bb_host_ips[BB_MAX_HOST_IPS];
static int32_t bb_host_ip_count = 0;
static int     bb_host_looked_up = 0; // Whether CountHostIPs was called, so that HostIP does not guess.

static void bb_host_ip_add(int32_t* list, int32_t* count, int32_t ip)
{
	for (int32_t i = 0; i < *count; i++) {
		if (list[i] == ip) {
			return;
		}
	}
	if (*count < BB_MAX_HOST_IPS) {
		list[(*count)++] = ip;
	}
}

// The IPv4 addresses of this computer, with the ones that other computers can reach first and 127.0.0.1 last.
static int32_t bb_local_ips(int32_t* list)
{
	int32_t count = 0;
#if !defined(_WIN32)
	struct ifaddrs *interfaces = NULL, *entry;
	if (getifaddrs(&interfaces) == 0) {
		for (int pass = 0; pass < 2; pass++) {
			for (entry = interfaces; entry; entry = entry->ifa_next) {
				if (!entry->ifa_addr || (entry->ifa_addr->sa_family != AF_INET) || !(entry->ifa_flags & IFF_UP)) {
					continue;
				}
				int32_t ip = bb_ip_to_int(((struct sockaddr_in*)entry->ifa_addr)->sin_addr);
				if ((((uint32_t)ip >> 24) == 127) == (pass == 1)) {
					bb_host_ip_add(list, &count, ip);
				}
			}
		}
		freeifaddrs(interfaces);
	}
#else
	char name[256];
	if (gethostname(name, sizeof(name)) == 0) {
		struct addrinfo hints, *result = NULL, *entry;
		memset(&hints, 0, sizeof(hints));
		hints.ai_family = AF_INET;
		if (getaddrinfo(name, NULL, &hints, &result) == 0) {
			for (entry = result; entry; entry = entry->ai_next) {
				bb_host_ip_add(list, &count, bb_ip_to_int(((struct sockaddr_in*)entry->ai_addr)->sin_addr));
			}
			freeaddrinfo(result);
		}
	}
#endif
	if (count == 0) {
		list[count++] = 0x7F000001; // Nothing can be found out, but this computer can always be reached as itself.
	}
	return count;
}

// CountHostIPs(host$): looks the host up and remembers its addresses for HostIP. An empty name is this computer, which
// has the address of every network interface that is up.
int32_t bb_count_host_ips(const char* host)
{
	bb_network_init();
	const char* name = host ? host : "";
	bb_host_ip_count = 0;
	bb_host_looked_up = 1;
	if (!*name) {
		bb_host_ip_count = bb_local_ips(bb_host_ips);
		return bb_host_ip_count;
	}
	struct addrinfo hints, *result = NULL, *entry;
	memset(&hints, 0, sizeof(hints));
	hints.ai_family   = AF_INET;
	hints.ai_socktype = SOCK_STREAM;
	if (getaddrinfo(name, NULL, &hints, &result) != 0) {
		return 0;
	}
	for (entry = result; entry; entry = entry->ai_next) {
		bb_host_ip_add(bb_host_ips, &bb_host_ip_count, bb_ip_to_int(((struct sockaddr_in*)entry->ai_addr)->sin_addr));
	}
	freeaddrinfo(result);
	return bb_host_ip_count;
}

// HostIP(index): an address found by the last CountHostIPs, counting from 1. Without one, the addresses of this computer.
int32_t bb_host_ip(int32_t index)
{
	bb_network_init();
	if (!bb_host_looked_up) {
		bb_host_looked_up = 1;
		bb_host_ip_count  = bb_local_ips(bb_host_ips);
	}
	return ((index >= 1) && (index <= bb_host_ip_count)) ? bb_host_ips[index - 1] : 0;
}

////////////////////////////////////////////////////////////////////////////////
// UDP
////////////////////////////////////////////////////////////////////////////////
typedef struct bb_udp {
	bb_socket sock;
	int32_t   port;
	uint8_t*  in;
	size_t    in_size, in_pos;
	uint8_t*  out;
	size_t    out_size, out_cap;
	int32_t   from_ip, from_port;
} bb_udp;

static size_t bb_udp_read(bb_stream* stream, void* data, size_t size)
{
	bb_udp* udp   = (bb_udp*)stream->user;
	size_t  avail = udp->in_size - udp->in_pos;
	size_t  take  = size < avail ? size : avail;
	memcpy(data, udp->in + udp->in_pos, take);
	udp->in_pos += take;
	return take;
}

static size_t bb_udp_write(bb_stream* stream, const void* data, size_t size)
{
	bb_udp* udp = (bb_udp*)stream->user;
	if (udp->out_size + size > udp->out_cap) {
		udp->out_cap = (udp->out_size + size) * 2;
		udp->out     = (uint8_t*)realloc(udp->out, udp->out_cap);
	}
	memcpy(udp->out + udp->out_size, data, size);
	udp->out_size += size;
	return size;
}

static int32_t bb_udp_available(bb_stream* stream)
{
	bb_udp* udp = (bb_udp*)stream->user;
	return (int32_t)(udp->in_size - udp->in_pos);
}

static int32_t bb_udp_at_end(bb_stream* stream)
{
	bb_udp* udp = (bb_udp*)stream->user;
	return udp->in_pos >= udp->in_size;
}

static void bb_udp_close(bb_stream* stream)
{
	bb_udp* udp = (bb_udp*)stream->user;
	bb_close_socket(udp->sock);
	free(udp->in);
	free(udp->out);
	free(udp);
}

static bb_udp* bb_udp_get(int32_t handle, const char* what)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if ((stream->kind != BB_STREAM_NET) || (stream->close != bb_udp_close)) {
		char message[96];
		snprintf(message, sizeof(message), "%s: this is not a UDP stream.", what);
		bb_runtime_error(message);
	}
	return (bb_udp*)stream->user;
}

int32_t bb_create_udp_stream(int32_t port)
{
	bb_network_init();
	bb_socket sock = socket(AF_INET, SOCK_DGRAM, 0);
	if (sock == BB_INVALID_SOCKET) {
		return 0;
	}
	struct sockaddr_in local;
	memset(&local, 0, sizeof(local));
	local.sin_family      = AF_INET;
	local.sin_addr.s_addr = htonl(INADDR_ANY);
	local.sin_port        = htons((unsigned short)port);
	if (bind(sock, (struct sockaddr*)&local, sizeof(local)) != 0) {
		bb_close_socket(sock);
		return 0;
	}
	// With port 0 the system picks one.
	int length = (int)sizeof(local);
	getsockname(sock, (struct sockaddr*)&local, (void*)&length);

	bb_udp* udp = (bb_udp*)calloc(1, sizeof(bb_udp));
	udp->sock   = sock;
	udp->port   = ntohs(local.sin_port);

	bb_stream stream;
	memset(&stream, 0, sizeof(stream));
	stream.kind      = BB_STREAM_NET;
	stream.user      = udp;
	stream.read      = bb_udp_read;
	stream.write     = bb_udp_write;
	stream.available = bb_udp_available;
	stream.at_end    = bb_udp_at_end;
	stream.close     = bb_udp_close;
	return bb_stream_add(stream);
}

void bb_close_udp_stream(int32_t handle)
{
	bb_udp_get(handle, "CloseUDPStream");
	bb_stream* stream = bb_stream_get(handle, "CloseUDPStream");
	stream->close(stream);
	bb_stream_remove(handle);
}

// Sends what was written to the stream. Without a port, it goes to the port of the stream.
void bb_send_udp_msg(int32_t handle, int32_t ip, int32_t port)
{
	bb_udp* udp = bb_udp_get(handle, "SendUDPMsg");
	struct sockaddr_in remote;
	memset(&remote, 0, sizeof(remote));
	remote.sin_family = AF_INET;
	remote.sin_addr   = bb_int_to_ip(ip);
	remote.sin_port   = htons((unsigned short)(port ? port : udp->port));
	sendto(udp->sock, (const char*)udp->out, (int)udp->out_size, 0, (struct sockaddr*)&remote, sizeof(remote));
	udp->out_size = 0;
}

// Takes in the next message, if there is one. Returns how big it is, and 0 if there is none.
int32_t bb_recv_udp_msg(int32_t handle)
{
	bb_udp* udp = bb_udp_get(handle, "RecvUDPMsg");
	if (!bb_wait_readable(udp->sock, bb_udp_timeout)) {
		return 0;
	}
	free(udp->in);
	udp->in = (uint8_t*)malloc(65536);
	struct sockaddr_in remote;
	int                length = (int)sizeof(remote);
	int                n      = recvfrom(udp->sock, (char*)udp->in, 65536, 0, (struct sockaddr*)&remote, (void*)&length);
	if (n < 0) {
		udp->in_size = udp->in_pos = 0;
		return 0;
	}
	udp->in_size   = (size_t)n;
	udp->in_pos    = 0;
	udp->from_ip   = bb_ip_to_int(remote.sin_addr);
	udp->from_port = ntohs(remote.sin_port);
	return n;
}

void bb_udp_timeouts(int32_t receive)
{
	bb_udp_timeout = receive < 0 ? 0 : receive;
}

// The address of this computer, which is where the stream receives.
int32_t bb_udp_stream_ip(int32_t handle)
{
	bb_udp_get(handle, "UDPStreamIP");
	int32_t list[BB_MAX_HOST_IPS];
	bb_network_init();
	return bb_local_ips(list) ? list[0] : 0;
}

int32_t bb_udp_msg_ip(int32_t handle)
{
	return bb_udp_get(handle, "UDPMsgIP")->from_ip;
}

int32_t bb_udp_msg_port(int32_t handle)
{
	return bb_udp_get(handle, "UDPMsgPort")->from_port;
}

int32_t bb_udp_stream_port(int32_t handle)
{
	return bb_udp_get(handle, "UDPStreamPort")->port;
}
