int32_t bb_create_tcp_server(int32_t port)
{
	bb_network_init();
	int       dual = 0;
	bb_socket sock = bb_socket_dual(SOCK_STREAM, &dual);
	if (sock == BB_INVALID_SOCKET) {
		return 0;
	}
	int reuse = 1;
	setsockopt(sock, SOL_SOCKET, SO_REUSEADDR, (const char*)&reuse, sizeof(reuse));
	bb_addr local;
	memset(&local, 0, sizeof(local));
	if (dual) {
		struct sockaddr_in6* v6 = (struct sockaddr_in6*)&local.storage;
		v6->sin6_family         = AF_INET6;
		v6->sin6_addr           = in6addr_any;
		v6->sin6_port           = htons((unsigned short)port);
		local.length            = sizeof(*v6);
	} else {
		struct sockaddr_in* v4 = (struct sockaddr_in*)&local.storage;
		v4->sin_family         = AF_INET;
		v4->sin_addr.s_addr    = htonl(INADDR_ANY);
		v4->sin_port           = htons((unsigned short)port);
		local.length           = sizeof(*v4);
	}
	if ((bind(sock, (struct sockaddr*)&local.storage, local.length) != 0) || (listen(sock, 16) != 0)) {
		bb_close_socket(sock);
		return 0;
	}
	return bb_tcp_add(sock, NULL, port, 1, dual);
}

void bb_close_tcp_server(int32_t handle)
{
	bb_tcp_get(handle, "CloseTCPServer", 1);
	bb_stream* stream = bb_stream_get(handle, "CloseTCPServer");
	stream->close(stream);
	bb_stream_remove(handle);
}

// Returns the new stream, or 0 if nobody connected in time.
int32_t bb_accept_tcp_stream(int32_t server)
{
	bb_tcp* tcp = bb_tcp_get(server, "AcceptTCPStream", 1);
	if (!bb_wait_readable(tcp->sock, bb_net.accept_timeout)) {
		return 0;
	}
	bb_addr   remote;
	memset(&remote, 0, sizeof(remote));
	remote.length    = (socklen_t)sizeof(remote.storage);
	bb_socket client = accept(tcp->sock, (struct sockaddr*)&remote.storage, &remote.length);
	if (client == BB_INVALID_SOCKET) {
		return 0;
	}
	return bb_tcp_add(client, (struct sockaddr*)&remote.storage, bb_sockaddr_port((struct sockaddr*)&remote.storage), 0, tcp->dual);
}

static void bb_host_ip_add(int32_t* list, int32_t* count, int32_t ip)
{
	for (int32_t i = 0; i < *count; i++) {
		if (list[i] == ip) {
			return;
		}
	}
	if (*count < BB_MAX_HOST_IPS) {
		list[(*count)++] = ip;
	}
}

// The IPv4 addresses of this computer, with the ones that other computers can reach first and 127.0.0.1 last.
static int32_t bb_local_ips(int32_t* list)
{
	int32_t count = 0;
#if !defined(_WIN32)
	struct ifaddrs *interfaces = NULL, *entry;
	if (getifaddrs(&interfaces) == 0) {
		for (int pass = 0; pass < 2; pass++) {
			for (entry = interfaces; entry; entry = entry->ifa_next) {
				if (!entry->ifa_addr || (entry->ifa_addr->sa_family != AF_INET) || !(entry->ifa_flags & IFF_UP)) {
					continue;
				}
				int32_t ip = bb_ip_to_int(((struct sockaddr_in*)entry->ifa_addr)->sin_addr);
				if ((((uint32_t)ip >> 24) == 127) == (pass == 1)) {
					bb_host_ip_add(list, &count, ip);
				}
			}
		}
		freeifaddrs(interfaces);
	}
#else
	char name[256];
	if (gethostname(name, sizeof(name)) == 0) {
		struct addrinfo hints, *result = NULL, *entry;
		memset(&hints, 0, sizeof(hints));
		hints.ai_family = AF_INET;
		if (getaddrinfo(name, NULL, &hints, &result) == 0) {
			for (entry = result; entry; entry = entry->ai_next) {
				bb_host_ip_add(list, &count, bb_ip_to_int(((struct sockaddr_in*)entry->ai_addr)->sin_addr));
			}
			freeaddrinfo(result);
		}
	}
#endif
	if (count == 0) {
		list[count++] = 0x7F000001; // Nothing can be found out, but this computer can always be reached as itself.
	}
	return count;
}

// CountHostIPs(host$): looks the host up and remembers its addresses for HostIP. An empty name is this computer, which
// has the address of every network interface that is up.
int32_t bb_count_host_ips(const char* host)
{
	bb_network_init();
	const char* name = host ? host : "";
	bb_net.host_ip_count = 0;
	bb_net.host_looked_up = 1;
	if (!*name) {
		bb_net.host_ip_count = bb_local_ips(bb_net.host_ips);
		return bb_net.host_ip_count;
	}
	struct addrinfo hints, *result = NULL, *entry;
	memset(&hints, 0, sizeof(hints));
	hints.ai_family   = AF_INET;
	hints.ai_socktype = SOCK_STREAM;
	if (getaddrinfo(name, NULL, &hints, &result) != 0) {
		return 0;
	}
	for (entry = result; entry; entry = entry->ai_next) {
		bb_host_ip_add(bb_net.host_ips, &bb_net.host_ip_count, bb_ip_to_int(((struct sockaddr_in*)entry->ai_addr)->sin_addr));
	}
	freeaddrinfo(result);
	return bb_net.host_ip_count;
}

// HostIP(index): an address found by the last CountHostIPs, counting from 1. Without one, the addresses of this computer.
int32_t bb_host_ip(int32_t index)
{
	bb_network_init();
	if (!bb_net.host_looked_up) {
		bb_net.host_looked_up = 1;
		bb_net.host_ip_count  = bb_local_ips(bb_net.host_ips);
	}
	return ((index >= 1) && (index <= bb_net.host_ip_count)) ? bb_net.host_ips[index - 1] : 0;
}

static void bb_host_addr_add(char (*list)[64], int32_t* count, const struct sockaddr* address)
{
	char text[64];
	bb_sockaddr_text(address, text, sizeof(text));
	if (!text[0]) {
		return;
	}
	for (int32_t i = 0; i < *count; i++) {
		if (strcmp(list[i], text) == 0) {
			return;
		}
	}
	if (*count < BB_MAX_HOST_IPS) {
		memcpy(list[(*count)++], text, strlen(text) + 1);
	}
}

// The IPv4 and IPv6 addresses of this computer: the ones other computers can reach first, then the ones that only work on the same
// network link (fe80::), and the loopback addresses last.
static int32_t bb_local_addresses(char (*list)[64])
{
	int32_t count = 0;
#if !defined(_WIN32)
	struct ifaddrs *interfaces = NULL, *entry;
	if (getifaddrs(&interfaces) == 0) {
		for (int pass = 0; pass < 3; pass++) {
			for (entry = interfaces; entry; entry = entry->ifa_next) {
				if (!entry->ifa_addr || !(entry->ifa_flags & IFF_UP)) {
					continue;
				}
				int family = entry->ifa_addr->sa_family;
				if (family != AF_INET && !(family == AF_INET6 && bb_ipv6_enabled())) {
					continue;
				}
				int loopback = 0, link_local = 0;
				if (family == AF_INET) {
					loopback = ((uint32_t)bb_sockaddr_ip(entry->ifa_addr) >> 24) == 127;
				} else {
					const struct in6_addr* v6 = &((struct sockaddr_in6*)entry->ifa_addr)->sin6_addr;
					loopback                  = IN6_IS_ADDR_LOOPBACK(v6);
					link_local                = IN6_IS_ADDR_LINKLOCAL(v6);
				}
				if ((loopback ? 2 : (link_local ? 1 : 0)) == pass) {
					bb_host_addr_add(list, &count, entry->ifa_addr);
				}
			}
		}
		freeifaddrs(interfaces);
	}
#else
	char name[256];
	if (gethostname(name, sizeof(name)) == 0) {
		struct addrinfo* result = bb_resolve_all(name, SOCK_STREAM);
		struct addrinfo* entry;
		for (entry = result; entry; entry = entry->ai_next) {
			bb_host_addr_add(list, &count, entry->ai_addr);
		}
		if (result) {
			freeaddrinfo(result);
		}
	}
#endif
	if (count == 0) {
		memcpy(list[count++], "127.0.0.1", 10); // Nothing can be found out, but this computer can always be reached as itself.
	}
	return count;
}

// CountHostAddresses(host$): like CountHostIPs, but with the IPv6 addresses too, for GetHostAddress$.
int32_t bb_count_host_addresses(const char* host)
{
	bb_network_init();
	const char* name = host ? host : "";
	bb_net.host_addr_count     = 0;
	bb_net.host_addr_looked_up = 1;
	if (!*name) {
		bb_net.host_addr_count = bb_local_addresses(bb_net.host_addrs);
		return bb_net.host_addr_count;
	}
	struct addrinfo* result = bb_resolve_all(name, SOCK_STREAM);
	struct addrinfo* entry;
	for (entry = result; entry; entry = entry->ai_next) {
		bb_host_addr_add(bb_net.host_addrs, &bb_net.host_addr_count, entry->ai_addr);
	}
	if (result) {
		freeaddrinfo(result);
	}
	return bb_net.host_addr_count;
}

// GetHostAddress$(index): an address found by the last CountHostAddresses, counting from 1, as text. Empty if there is none.
const char* bb_get_host_address(int32_t index)
{
	bb_network_init();
	if (!bb_net.host_addr_looked_up) {
		bb_net.host_addr_looked_up = 1;
		bb_net.host_addr_count     = bb_local_addresses(bb_net.host_addrs);
	}
	if ((index < 1) || (index > bb_net.host_addr_count)) {
		return bb_copy("", 0);
	}
	return bb_copy(bb_net.host_addrs[index - 1], strlen(bb_net.host_addrs[index - 1]));
}

// The address on the other end of a TCP stream, as text. For a stream that was made by OpenTCPStream, the address that connected.
const char* bb_get_tcp_stream_address(int32_t handle)
{
	const char* text = bb_tcp_get(handle, "GetTCPStreamAddress", 0)->address;
	return bb_copy(text, strlen(text));
}

