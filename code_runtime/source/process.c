// DebugLog text$: a line on the standard error output, which is the console the program was started from. On Windows it also
// goes to the debugger, where the originals showed it.
// For the runtime itself: a plain C string, which has no length in front of it.
void bb_log_text(const char* text)
{
	fprintf(stderr, "%s\n", text);
	fflush(stderr);
#if defined(_WIN32)
	OutputDebugStringA(text);
	OutputDebugStringA("\n");
#endif
}

// DebugLog: a string of the program, which can contain NUL.
void bb_debug_log(const char* text)
{
	fwrite(bb_s(text), 1, bb_slen(text), stderr);
	fputc('\n', stderr);
	fflush(stderr);
#if defined(_WIN32)
	OutputDebugStringA(bb_s(text)); // The system takes C strings.
	OutputDebugStringA("\n");
#endif
}

const char* bb_current_date(void)
{
	static const char* months[] = { "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec" };
	time_t             now      = time(NULL);
	struct tm*         local    = localtime(&now);
	char               buffer[32];
	int                n = snprintf(buffer, sizeof(buffer), "%02d %s %d", local->tm_mday, months[local->tm_mon], local->tm_year + 1900);
	return bb_copy(buffer, (size_t)n);
}

const char* bb_current_time(void)
{
	time_t     now   = time(NULL);
	struct tm* local = localtime(&now);
	char       buffer[16];
	int        n = snprintf(buffer, sizeof(buffer), "%02d:%02d:%02d", local->tm_hour, local->tm_min, local->tm_sec);
	return bb_copy(buffer, (size_t)n);
}

int32_t bb_exec_file(const char* command)
{
	fflush(stdout);
	return system(bb_s(command)) == 0 ? 1 : 0;
}

// LSet$(text, width): text padded with spaces on the right, or cut short, to be exactly this wide.
const char* bb_lset(const char* text, int32_t width)
{
	size_t len = bb_slen(text);
	if (width < 0) {
		width = 0;
	}
	char* out = bb_alloc((size_t)width);
	for (int32_t i = 0; i < width; i++) {
		out[i] = ((size_t)i < len) ? text[i] : ' ';
	}
	return out;
}

const char* bb_rset(const char* text, int32_t width)
{
	size_t len = bb_slen(text);
	if (width < 0) {
		width = 0;
	}
	char* out = bb_alloc((size_t)width);
	for (int32_t i = 0; i < width; i++) {
		int64_t source = (int64_t)i - ((int64_t)width - (int64_t)len);
		out[i]         = ((source >= 0) && ((size_t)source < len)) ? text[source] : ' ';
	}
	return out;
}
