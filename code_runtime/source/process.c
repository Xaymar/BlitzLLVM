static int    bb_argc = 0;
static char** bb_argv = NULL;

void bb_set_arguments(int32_t argc, char** argv)
{
	bb_argc = argc;
	bb_argv = argv;
}

// Everything after the program name.
const char* bb_command_line(void)
{
	size_t length = 0;
	for (int i = 1; i < bb_argc; i++) {
		length += strlen(bb_argv[i]) + 1;
	}
	char* out = (char*)malloc(length + 1);
	out[0]    = 0;
	for (int i = 1; i < bb_argc; i++) {
		if (i > 1) {
			strcat(out, " ");
		}
		strcat(out, bb_argv[i]);
	}
	return out;
}

// The folder that the program is in, with a separator at the end.
static const char* bb_app_dir(void)
{
	char buffer[4096];
	size_t length = 0;
#if defined(_WIN32)
	length = GetModuleFileNameA(NULL, buffer, sizeof(buffer));
	if (length >= sizeof(buffer)) {
		length = 0;
	}
#else
	ssize_t n = readlink("/proc/self/exe", buffer, sizeof(buffer) - 1);
	if (n > 0) {
		length = (size_t)n;
	} else if (bb_argc > 0 && bb_argv[0]) {
		char* resolved = realpath(bb_argv[0], NULL); // Where the system has no /proc (macOS, BSD) and the program was started by path.
		if (resolved && (strlen(resolved) < sizeof(buffer))) {
			strcpy(buffer, resolved);
			length = strlen(buffer);
		}
		free(resolved);
	}
#endif
	buffer[length] = 0;
	while (length && (buffer[length - 1] != '/') && (buffer[length - 1] != '\\')) {
		buffer[--length] = 0;
	}
	if (!length) {
		return bb_current_dir(); // Nothing is known about where the program is, so this is the best guess.
	}
	return bb_copy(buffer, length);
}

// SystemProperty$(name): tempdir, appdir, windowsdir and systemdir. Off Windows there is no such thing as the Windows
// folder, so windowsdir is where the system keeps its configuration (/etc/ or /System/ on macOS) and systemdir is
// where it keeps its libraries (/usr/lib/ or /System/Library/ on macOS). Anything else is an empty string.
const char* bb_system_property(const char* name)
{
	const char* wanted = bb_s(name);
	const char* value  = NULL;
	if (!strcmp(wanted, "tempdir") || !strcmp(wanted, "TEMPDIR")) {
		value = getenv("TEMP");
		if (!value) {
			value = getenv("TMPDIR");
		}
		if (!value) {
			value = "/tmp";
		}
	} else if (!strcmp(wanted, "appdir") || !strcmp(wanted, "APPDIR")) {
		return bb_app_dir();
	} else if (!strcmp(wanted, "windowsdir") || !strcmp(wanted, "WINDOWSDIR")) {
#if defined(_WIN32)
		value = getenv("SystemRoot");
#elif defined(__APPLE__)
		value = "/System/";
#else
		value = "/etc/";
#endif
	} else if (!strcmp(wanted, "systemdir") || !strcmp(wanted, "SYSTEMDIR")) {
#if defined(_WIN32)
		char system[MAX_PATH];
		UINT length = GetSystemDirectoryA(system, sizeof(system));
		if (length && (length < sizeof(system))) {
			return bb_copy(system, length);
		}
		value = getenv("SystemRoot");
#elif defined(__APPLE__)
		value = "/System/Library/";
#else
		value = "/usr/lib/";
#endif
	}
	return bb_copy(value ? value : "", value ? strlen(value) : 0);
}

// GetEnv$(name): the value of an environment variable, empty if there is none.
const char* bb_get_env(const char* name)
{
	const char* value = getenv(bb_s(name));
	return bb_copy(value ? value : "", value ? strlen(value) : 0);
}

// SetEnv name, value: sets an environment variable for this program and what it starts.
void bb_set_env(const char* name, const char* value)
{
#if defined(_WIN32)
	_putenv_s(bb_s(name), bb_s(value));
#else
	setenv(bb_s(name), bb_s(value), 1);
#endif
}

void bb_debug_log(const char* text)
{
	fprintf(stderr, "%s\n", bb_s(text));
}

const char* bb_current_date(void)
{
	static const char* months[] = { "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec" };
	time_t             now      = time(NULL);
	struct tm*         local    = localtime(&now);
	char               buffer[32];
	int                n = snprintf(buffer, sizeof(buffer), "%d %s %d", local->tm_mday, months[local->tm_mon], local->tm_year + 1900);
	return bb_copy(buffer, (size_t)n);
}

const char* bb_current_time(void)
{
	time_t     now   = time(NULL);
	struct tm* local = localtime(&now);
	char       buffer[16];
	int        n = snprintf(buffer, sizeof(buffer), "%02d:%02d:%02d", local->tm_hour, local->tm_min, local->tm_sec);
	return bb_copy(buffer, (size_t)n);
}

int32_t bb_exec_file(const char* command)
{
	fflush(stdout);
	return system(bb_s(command)) == 0 ? 1 : 0;
}

// LSet$(text, width): text padded with spaces on the right, or cut short, to be exactly this wide.
const char* bb_lset(const char* text, int32_t width)
{
	size_t len = strlen(bb_s(text));
	if (width < 0) {
		width = 0;
	}
	char* out = (char*)malloc((size_t)width + 1);
	for (int32_t i = 0; i < width; i++) {
		out[i] = ((size_t)i < len) ? text[i] : ' ';
	}
	out[width] = 0;
	return out;
}

const char* bb_rset(const char* text, int32_t width)
{
	size_t len = strlen(bb_s(text));
	if (width < 0) {
		width = 0;
	}
	char* out = (char*)malloc((size_t)width + 1);
	for (int32_t i = 0; i < width; i++) {
		int64_t source = (int64_t)i - ((int64_t)width - (int64_t)len);
		out[i]         = ((source >= 0) && ((size_t)source < len)) ? text[source] : ' ';
	}
	out[width] = 0;
	return out;
}
