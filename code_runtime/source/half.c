// The Windows link has no compiler-rt, so the conversions between Float and Half that the compiler emits (__truncsfhf2 and __extendhfsf2) were
// missing. They are done here with integer math, as compiler-rt does (round to nearest even).
// BLITZ_HALF_TEST builds them on any system under other names, to compare them with the compiler's own conversion.

#include <stdint.h>

#ifdef BLITZ_HALF_TEST
#define HALF_TRUNC blitz_truncsfhf2
#define HALF_EXTEND blitz_extendhfsf2
#define HALF_ENABLED 1
#elif defined(_WIN32) && defined(__clang__)
#define HALF_TRUNC __truncsfhf2
#define HALF_EXTEND __extendhfsf2
#define HALF_ENABLED 1
#endif

#ifdef HALF_ENABLED

static uint16_t half_bits_from_float(float value)
{
	uint32_t bits;
	__builtin_memcpy(&bits, &value, 4);
	uint32_t sign = (bits >> 16) & 0x8000u;
	uint32_t abs  = bits & 0x7FFFFFFFu;
	if (abs > 0x7F800000u) { // NaN keeps the top of its payload and stays a NaN.
		return (uint16_t)(sign | 0x7E00u | ((abs >> 13) & 0x1FFu));
	}
	if (abs >= 0x47800000u) { // 65536 or more, and infinity, are infinity (65520 up rounds there below).
		return (uint16_t)(sign | 0x7C00u);
	}
	if (abs < 0x33000000u) { // Below 2^-25 rounds to zero.
		return (uint16_t)sign;
	}
	if (abs < 0x38800000u) { // Subnormal half.
		uint32_t exponent = abs >> 23;
		uint32_t mantissa = (abs & 0x7FFFFFu) | 0x800000u;
		uint32_t shift    = 126u - exponent; // 14 to 24
		uint32_t result   = mantissa >> shift;
		uint32_t rest     = mantissa & ((1u << shift) - 1u);
		uint32_t halfway  = 1u << (shift - 1u);
		if (rest > halfway || (rest == halfway && (result & 1u))) {
			result++;
		}
		return (uint16_t)(sign | result);
	}
	// Normal half: rebias the exponent, round the 13 dropped bits to nearest even. A carry may run into the exponent, which is right.
	uint32_t result = ((abs - 0x38000000u) >> 13);
	uint32_t rest   = abs & 0x1FFFu;
	if (rest > 0x1000u || (rest == 0x1000u && (result & 1u))) {
		result++;
	}
	return (uint16_t)(sign | result);
}

static float float_from_half_bits(uint16_t half)
{
	uint32_t sign     = ((uint32_t)half & 0x8000u) << 16;
	uint32_t exponent = (half >> 10) & 0x1Fu;
	uint32_t mantissa = half & 0x3FFu;
	uint32_t bits;
	if (exponent == 0x1Fu) {
		bits = sign | 0x7F800000u | (mantissa << 13);
	} else if (exponent != 0) {
		bits = sign | ((exponent + 112u) << 23) | (mantissa << 13);
	} else if (mantissa == 0) {
		bits = sign;
	} else { // Subnormal half is a normal float.
		uint32_t e = 113u;
		while (!(mantissa & 0x400u)) {
			mantissa <<= 1;
			e--;
		}
		bits = sign | (e << 23) | ((mantissa & 0x3FFu) << 13);
	}
	float result;
	__builtin_memcpy(&result, &bits, 4);
	return result;
}

#ifdef BLITZ_HALF_TEST
uint16_t HALF_TRUNC(float value)
{
	return half_bits_from_float(value);
}
float HALF_EXTEND(uint16_t half)
{
	return float_from_half_bits(half);
}
#else
_Float16 HALF_TRUNC(float value)
{
	uint16_t bits = half_bits_from_float(value);
	_Float16 result;
	__builtin_memcpy(&result, &bits, 2);
	return result;
}
float HALF_EXTEND(_Float16 half)
{
	uint16_t bits;
	__builtin_memcpy(&bits, &half, 2);
	return float_from_half_bits(bits);
}
#endif

#endif
