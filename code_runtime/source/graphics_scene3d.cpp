// Whether any part of the entity is in the picture of the camera. Meshes count with a sphere around them.
int32_t bb_entity_in_view(int32_t entity, int32_t camera)
{
	bb::profile_scope timer(bb::PROFILE_IN_VIEW);
	bb::entity* e = bb::get_entity(entity);
	if (!e) {
		bb_runtime_error("EntityInView: the entity does not exist.");
	}
	bb::entity* cam = need_camera(camera, "EntityInView");
	int vx, vy, vw, vh;
	if (!camera_viewport(*cam, int(g.width), int(g.height), vx, vy, vw, vh)) {
		return 0;
	}

	// The box around the surfaces, in the space of the entity. Like in the original, what is not a mesh is a point.
	float lo[3] = { 0, 0, 0 }, hi[3] = { 0, 0, 0 };
	if (e->kind == bb::MESH) {
		bb::update_terrain(*e);
		float mesh_lo[3], mesh_hi[3];
		bool  any = bb::mesh_bounds(*e, mesh_lo, mesh_hi);
		if (e->has_cull_box) {
			// MeshCullBox says what box decides.
			for (int k = 0; k < 3; k++) {
				mesh_lo[k] = e->cull_box[k];
				mesh_hi[k] = e->cull_box[k] + e->cull_box[3 + k];
			}
			any = true;
		}
		if (any) {
			memcpy(lo, mesh_lo, sizeof(lo));
			memcpy(hi, mesh_hi, sizeof(hi));
		}
	}

	float m[16];
	bb::world_matrix(entity, m);
	float corners[8][3];
	for (int corner = 0; corner < 8; corner++) {
		float local[3] = { (corner & 1) ? hi[0] : lo[0], (corner & 2) ? hi[1] : lo[1], (corner & 4) ? hi[2] : lo[2] };
		for (int row = 0; row < 3; row++) {
			corners[corner][row] = m[0 + row] * local[0] + m[4 + row] * local[1] + m[8 + row] * local[2] + m[12 + row];
		}
	}

	float world[16], view[16], proj[16], vp[16];
	bb::world_matrix(camera, world);
	bb::mat_affine_inverse(world, view);
	projection(proj, *cam, float(vw), float(vh));
	bb::mat_multiply(vp, proj, view);

	// The planes of the view, from the rows of the matrix: left, right, bottom, top, far and near (the depth is reversed).
	float row[4][4];
	for (int r = 0; r < 4; r++) {
		for (int c = 0; c < 4; c++) {
			row[r][c] = vp[c * 4 + r];
		}
	}
	float planes[6][4];
	for (int c = 0; c < 4; c++) {
		planes[0][c] = row[3][c] + row[0][c];
		planes[1][c] = row[3][c] - row[0][c];
		planes[2][c] = row[3][c] + row[1][c];
		planes[3][c] = row[3][c] - row[1][c];
		planes[4][c] = row[2][c];
		planes[5][c] = row[3][c] - row[2][c];
	}
	// It is seen unless all of the corners of the box are on the outside of one of the planes.
	for (int i = 0; i < 6; i++) {
		int outside = 0;
		for (int corner = 0; corner < 8; corner++) {
			float distance = planes[i][0] * corners[corner][0] + planes[i][1] * corners[corner][1] + planes[i][2] * corners[corner][2] + planes[i][3];
			outside += distance < 0 ? 1 : 0;
		}
		if (outside == 8) {
			return 0;
		}
	}
	return 1;
}

// Stats3D 1000 to 1003: draw calls, pipeline binds, texture binds and buffer binds of what RenderWorld drew since it began.
int32_t bb_draw_stats(int32_t which)
{
	if (!active()) {
		return 0;
	}
	flush(); // What waits to be drawn counts too.
	switch (which) {
	case 0: return int32_t(stats3d.draws);
	case 1: return int32_t(stats3d.pipelines);
	case 2: return int32_t(stats3d.textures);
	case 3: return int32_t(stats3d.buffers);
	}
	return 0;
}

