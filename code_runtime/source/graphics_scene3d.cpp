// Whether any part of the entity is in the picture of the camera. Meshes count with a sphere around them.
int32_t bb_entity_in_view(int32_t entity, int32_t camera)
{
	bb::profile_scope timer(bb::PROFILE_IN_VIEW);
	bb::entity* e = bb::get_entity(entity);
	if (!e) {
		bb_runtime_error("EntityInView: the entity does not exist.");
	}
	bb::entity* cam = need_camera(camera, "EntityInView");
	int vx, vy, vw, vh;
	if (!camera_viewport(*cam, int(g.width), int(g.height), vx, vy, vw, vh)) {
		return 0;
	}

	// The box around the surfaces, in the space of the entity. Like in the original, what is not a mesh is a point.
	float lo[3] = { 0, 0, 0 }, hi[3] = { 0, 0, 0 };
	if (e->kind == bb::MESH) {
		bb::update_terrain(*e);
		float mesh_lo[3], mesh_hi[3];
		bool  any = bb::mesh_bounds(*e, mesh_lo, mesh_hi);
		if (e->has_cull_box) {
			// MeshCullBox says what box decides.
			for (int k = 0; k < 3; k++) {
				mesh_lo[k] = e->cull_box[k];
				mesh_hi[k] = e->cull_box[k] + e->cull_box[3 + k];
			}
			any = true;
		}
		if (any) {
			memcpy(lo, mesh_lo, sizeof(lo));
			memcpy(hi, mesh_hi, sizeof(hi));
		}
	}

	float m[16];
	bb::world_matrix(entity, m);
	float corners[8][3];
	for (int corner = 0; corner < 8; corner++) {
		float local[3] = { (corner & 1) ? hi[0] : lo[0], (corner & 2) ? hi[1] : lo[1], (corner & 4) ? hi[2] : lo[2] };
		for (int row = 0; row < 3; row++) {
			corners[corner][row] = m[0 + row] * local[0] + m[4 + row] * local[1] + m[8 + row] * local[2] + m[12 + row];
		}
	}

	float world[16], view[16], proj[16], vp[16];
	bb::world_matrix(camera, world);
	bb::mat_affine_inverse(world, view);
	projection(proj, *cam, float(vw), float(vh));
	bb::mat_multiply(vp, proj, view);

	// The planes of the view, from the rows of the matrix: left, right, bottom, top, far and near (the depth is reversed).
	float row[4][4];
	for (int r = 0; r < 4; r++) {
		for (int c = 0; c < 4; c++) {
			row[r][c] = vp[c * 4 + r];
		}
	}
	float planes[6][4];
	for (int c = 0; c < 4; c++) {
		planes[0][c] = row[3][c] + row[0][c];
		planes[1][c] = row[3][c] - row[0][c];
		planes[2][c] = row[3][c] + row[1][c];
		planes[3][c] = row[3][c] - row[1][c];
		planes[4][c] = row[2][c];
		planes[5][c] = row[3][c] - row[2][c];
	}
	// It is seen unless all of the corners of the box are on the outside of one of the planes.
	for (int i = 0; i < 6; i++) {
		int outside = 0;
		for (int corner = 0; corner < 8; corner++) {
			float distance = planes[i][0] * corners[corner][0] + planes[i][1] * corners[corner][1] + planes[i][2] * corners[corner][2] + planes[i][3];
			outside += distance < 0 ? 1 : 0;
		}
		if (outside == 8) {
			return 0;
		}
	}
	return 1;
}

// Stats3D 1000 to 1003: draw calls, pipeline binds, texture binds and buffer binds of what RenderWorld drew since it began.
int32_t bb_draw_stats(int32_t which)
{
	if (!active()) {
		return 0;
	}
	flush(); // What waits to be drawn counts too.
	switch (which) {
	case 0: return int32_t(stats3d.draws);
	case 1: return int32_t(stats3d.pipelines);
	case 2: return int32_t(stats3d.textures);
	case 3: return int32_t(stats3d.buffers);
	case 4: return int32_t(stats3d.clusters);
	}
	return 0;
}

// Draw only the edges of everything, if the GPU can.
// A BlitzLLVM extension: how see-through draws are ordered: along the view axis of the camera (the distance in front of it, as the
// depth buffer sees it) and not by the distance in space like the original does. Mode 0 is the default, mode 1 the view distance. It applies from the next
// RenderWorld, and does not change fading with EntityAutoFade, which keeps going by the distance in space.
void bb_transparency_distance_sort_mode(int32_t mode)
{
	sort_view = (mode == 1) ? 1 : 0;
}

void bb_wire_frame(int32_t on)
{
	g.wireframe = (on != 0) && g.can_wireframe;
}

// Picks what is under a pixel of the camera's view.
int32_t bb_camera_pick(int32_t camera, float x, float y)
{
	bb::entity* cam = need_camera(camera, "CameraPick");
	int         vx, vy, vw, vh;
	if (!camera_viewport(*cam, int(g.width), int(g.height), vx, vy, vw, vh)) {
		return 0;
	}
	float sx = cam->cam_zoom, sy = cam->cam_zoom * (float(vw) / float(vh));
	float ndc_x = (x - float(vx)) / float(vw) * 2 - 1, ndc_y = (y - float(vy)) / float(vh) * 2 - 1;
	float local[3] = { ndc_x / sx, -ndc_y / sy, 1 };
	float m[16];
	bb::world_matrix(camera, m);
	// Like the original the line ends as far along the view direction as the far plane, so its time is the depth over the far plane.
	float range = cam->cam_far;
	float dx = (m[0] * local[0] + m[4] * local[1] + m[8] * local[2]) * range;
	float dy = (m[1] * local[0] + m[5] * local[1] + m[9] * local[2]) * range;
	float dz = (m[2] * local[0] + m[6] * local[1] + m[10] * local[2]) * range;
	return bb_line_pick(m[12], m[13], m[14], dx, dy, dz, 0);
}

// RenderWorld: draws everything the cameras see into the current buffer.
void bb_render_world(float tween)
{
	bb::profile_scope timer(bb::PROFILE_RENDER_WORLD);
	if (!active()) {
		return;
	}
	{
		static const bool wanted = bb_env_bool("BLITZLLVM_GPU_DRAWS", false);
		gpu_static::enabled      = wanted && g.can_gpu_cull && g.static_pipeline;
		bb::gpu_static_active    = gpu_static::enabled;
		gpu_static::frame++;
	}
	bb_movie_update(); // The textures of movies are up to date for this frame.
	bb_sound_update(); // Programs that render every frame never wait with Delay, the sounds of entities follow them here.
	if (resolve_target(g.target).image && (g.target >= image_buffer_base) && (g.target < texture_buffer_base)) {
		fail("RenderWorld can not draw to an image, use a texture.");
	}
	acquire_frame(); // The buffers that the scene is written to are not read by the frame before any more.
	antialias_new_frame();
	g.triangles_drawn = 0;
	stats3d           = {};

	scene_data data = {};
	data.ambient[0] = bb::ambient_light[0];
	data.ambient[1] = bb::ambient_light[1];
	data.ambient[2] = bb::ambient_light[2];
	data.ambient[3] = 1;
	// Things captured by CaptureWorld are drawn between where they were and where they are.
	bb::render_tween = tween < 0 ? 0 : (tween > 1 ? 1 : tween);
	bb::grid_begin_frame();
	light_collector lights = { &data, 0 };
	camera_collector cameras;
	camera_collector mirrors;
	{
		bb::profile_scope scan(bb::PROFILE_SCAN);
		bb::for_each_visible(bb::LIGHT, collect_light, &lights);
		current_light_count = lights.count;
		channel_answer_count = 0;
	{
		// FNV-1a over what decides how much each light does (not the cones, they are not part of that).
		uint32_t hash = 2166136261u;
		for (uint32_t i = 0; i < lights.count; i++) {
			const unsigned char* bytes[2] = { reinterpret_cast<const unsigned char*>(data.light_position[i]), reinterpret_cast<const unsigned char*>(data.light_color[i]) };
			for (const unsigned char* b : bytes) {
				for (size_t k = 0; k < sizeof(float) * 4; k++) {
					hash = (hash ^ b[k]) * 16777619u;
				}
			}
			for (int k = 0; k < 8; k++) {
				hash = (hash ^ uint32_t((light_channels[i] >> (8 * k)) & 255u)) * 16777619u;
			}
		}
		current_light_hash = hash | 1u;
	}
		bb::for_each_visible(bb::CAMERA, collect_camera, &cameras);
		bb::for_each_visible(bb::PIVOT, collect_mirror, &mirrors);
	}
	// The cameras draw from the highest EntityOrder to the lowest, so the one with the lowest is drawn last and on top. Cameras that
	// have the same order keep the order they were made in.
	std::stable_sort(cameras.handles.data, cameras.handles.data + cameras.handles.size, [](int a, int b) {
		bb::entity* ea = bb::get_entity(a);
		bb::entity* eb = bb::get_entity(b);
		return (ea ? ea->order : 0) > (eb ? eb->order : 0);
	});
	for (uint32_t i = 0; i < cameras.handles.size; i++) {
		bb::entity* cam = bb::get_entity(cameras.handles[i]);
		if (cam) {
			render_camera(cameras.handles[i], *cam, data, mirrors.handles);
		}
	}
	cameras.handles.release();
	mirrors.handles.release();
	bb::grid_end_frame();
	bb::render_tween = 1.0f;
}

// The scene lets go of a surface: its GPU buffers go with it.
void bb_release_surface_gpu(void* gpu)
{
	if (gpu && g.device) {
		release_surface_gpu(static_cast<surface_gpu*>(gpu));
	}
}

// Called by Delay, so programs that wait keep their window alive and showing what they drew.
void bb_graphics_idle(void)
{
	bb_mem_tick(); // Gives back the allocator's spans that stayed empty for a second.
	bb_sound_update();
	bb_movie_update();
	if (active()) {
		flush();
		pump();
		bb_gui_idle(); // Gadgets that changed are drawn.
	}
}
