// Called by Delay, so programs that wait keep their window alive and showing what they drew.
void bb_graphics_idle(void)
{
	bb_sound_update();
	bb_movie_update();
	if (active()) {
		flush();
		pump();
		bb_gui_idle(); // Gadgets that changed are drawn.
	}
}
