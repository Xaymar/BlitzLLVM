// Picks what is under a pixel of the camera's view.
int32_t bb_camera_pick(int32_t camera, float x, float y)
{
	bb::entity* cam = need_camera(camera, "CameraPick");
	int         vx, vy, vw, vh;
	if (!camera_viewport(*cam, int(g.width), int(g.height), vx, vy, vw, vh)) {
		return 0;
	}
	float sx = cam->cam_zoom, sy = cam->cam_zoom * (float(vw) / float(vh));
	float ndc_x = (x - float(vx)) / float(vw) * 2 - 1, ndc_y = (y - float(vy)) / float(vh) * 2 - 1;
	float local[3] = { ndc_x / sx, -ndc_y / sy, 1 };
	float len      = sqrtf(local[0] * local[0] + local[1] * local[1] + 1);
	float m[16];
	bb::world_matrix(camera, m);
	float range = cam->cam_far;
	float dx = (m[0] * local[0] + m[4] * local[1] + m[8] * local[2]) / len * range;
	float dy = (m[1] * local[0] + m[5] * local[1] + m[9] * local[2]) / len * range;
	float dz = (m[2] * local[0] + m[6] * local[1] + m[10] * local[2]) / len * range;
	return bb_line_pick(m[12], m[13], m[14], dx, dy, dz, 0);
}

// RenderWorld: draws everything the cameras see into the current buffer.
void bb_render_world(float tween)
{
	bb::profile_scope timer(bb::PROFILE_RENDER_WORLD);
	if (!active()) {
		return;
	}
	if (resolve_target(g.target).image && (g.target >= image_buffer_base) && (g.target < texture_buffer_base)) {
		fail("RenderWorld can not draw to an image, use a texture.");
	}
	g.triangles_drawn = 0;

	scene_data data = {};
	data.ambient[0] = bb::ambient_light[0];
	data.ambient[1] = bb::ambient_light[1];
	data.ambient[2] = bb::ambient_light[2];
	data.ambient[3] = 1;
	// Things captured by CaptureWorld are drawn between where they were and where they are.
	bb::render_tween = tween < 0 ? 0 : (tween > 1 ? 1 : tween);
	light_collector lights = { &data, 0 };
	bb::for_each_visible(bb::LIGHT, collect_light, &lights);

	camera_collector cameras;
	bb::for_each_visible(bb::CAMERA, collect_camera, &cameras);
	for (uint32_t i = 0; i < cameras.handles.size; i++) {
		bb::entity* cam = bb::get_entity(cameras.handles[i]);
		if (cam) {
			render_camera(cameras.handles[i], *cam, data);
		}
	}
	cameras.handles.release();
	bb::render_tween = 1.0f;
}

