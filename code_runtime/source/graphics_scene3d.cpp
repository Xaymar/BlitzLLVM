	uint32_t flush_number = 0;

	static surface_gpu* surface_list = nullptr;

	static void release_surface_gpu(surface_gpu* gpu)
	{
		if (!gpu) {
			return;
		}
		if (gpu->previous) {
			gpu->previous->next = gpu->next;
		} else {
			surface_list = gpu->next;
		}
		if (gpu->next) {
			gpu->next->previous = gpu->previous;
		}
		// Things that were asked to be drawn can still use it, so it is only destroyed once they have been drawn.
		if (gpu->vertex_buffer) {
			graveyard.push({ gpu->vertex_buffer, gpu->vertex_allocation });
		}
		if (gpu->index_buffer) {
			graveyard.push({ gpu->index_buffer, gpu->index_allocation });
		}
		delete gpu;
	}

	void destroy_surface_buffers()
	{
		for (surface_gpu* gpu = surface_list; gpu; gpu = gpu->next) {
			destroy_buffer(gpu->vertex_buffer, gpu->vertex_allocation);
			destroy_buffer(gpu->index_buffer, gpu->index_allocation);
		}
	}

	// Makes sure the GPU has the current geometry of the surface.
	static surface_gpu* upload_surface(bb::surface& s)
	{
		if (!s.dirty && s.gpu) {
			return static_cast<surface_gpu*>(s.gpu);
		}
		s.dirty       = false;
		s.bound_valid = false;
		surface_gpu* gpu = static_cast<surface_gpu*>(s.gpu);
		if ((s.vertices.size == 0) || (s.indices.size == 0)) {
			release_surface_gpu(gpu);
			s.gpu = nullptr;
			return nullptr;
		}

		// Changing the contents is only fine if nothing that waits to be drawn looks at the buffers, and they are big enough.
		VkDeviceSize vsize = VkDeviceSize(s.vertices.size) * sizeof(bb::vertex3d);
		VkDeviceSize isize = VkDeviceSize(s.indices.size) * sizeof(uint32_t);
		// The GPU may still read it for the flushes that were sent and are not done, and the draws that wait use it as well.
		bool unused = gpu && ((gpu->used_by_flush == 0xFFFFFFFFu) || ((gpu->used_by_flush != flush_number) && flush_is_done(gpu->used_by_flush)));
		if (unused && (s.vertices.size <= gpu->vertex_capacity) && (s.indices.size <= gpu->index_capacity)) {
			memcpy(gpu->vertex_mapped, s.vertices.data, size_t(vsize));
			memcpy(gpu->index_mapped, s.indices.data, size_t(isize));
			gpu->index_count = s.indices.size;
			return gpu;
		}
		release_surface_gpu(gpu);

		gpu = new surface_gpu();
		gpu->next = surface_list;
		if (surface_list) {
			surface_list->previous = gpu;
		}
		surface_list = gpu;

		// A bit of room, so that surfaces that grow and shrink do not need new buffers all the time.
		gpu->vertex_capacity = s.vertices.size + s.vertices.size / 4 + 16;
		gpu->index_capacity  = s.indices.size + s.indices.size / 4 + 48;
		create_buffer(VkDeviceSize(gpu->vertex_capacity) * sizeof(bb::vertex3d), VK_BUFFER_USAGE_VERTEX_BUFFER_BIT, true, gpu->vertex_buffer, gpu->vertex_allocation, &gpu->vertex_mapped);
		memcpy(gpu->vertex_mapped, s.vertices.data, size_t(vsize));

		create_buffer(VkDeviceSize(gpu->index_capacity) * sizeof(uint32_t), VK_BUFFER_USAGE_INDEX_BUFFER_BIT, true, gpu->index_buffer, gpu->index_allocation, &gpu->index_mapped);
		memcpy(gpu->index_mapped, s.indices.data, size_t(isize));

		gpu->index_count = s.indices.size;
		s.gpu            = gpu;
		return gpu;
	}

	static VkPipeline create_pipeline_3d(VkShaderModule vs, VkShaderModule fs, int mode, bool wire = false)
	{
		VkPipelineShaderStageCreateInfo stages[2] = { { VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO }, { VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO } };
		stages[0].stage                           = VK_SHADER_STAGE_VERTEX_BIT;
		stages[0].module                          = vs;
		stages[0].pName                           = "main";
		stages[1].stage                           = VK_SHADER_STAGE_FRAGMENT_BIT;
		stages[1].module                          = fs;
		stages[1].pName                           = "main";

		VkVertexInputBindingDescription   binding       = { 0, sizeof(bb::vertex3d), VK_VERTEX_INPUT_RATE_VERTEX };
		VkVertexInputAttributeDescription attributes[5] = {
			{ 0, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(bb::vertex3d, x) },
			{ 1, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(bb::vertex3d, nx) },
			{ 2, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(bb::vertex3d, u) },
			{ 3, 0, VK_FORMAT_R16G16B16A16_SFLOAT, offsetof(bb::vertex3d, r) },
			{ 4, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(bb::vertex3d, u2) },
		};
		VkPipelineVertexInputStateCreateInfo input = { VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO };
		input.vertexBindingDescriptionCount        = 1;
		input.pVertexBindingDescriptions           = &binding;
		input.vertexAttributeDescriptionCount      = 5;
		input.pVertexAttributeDescriptions         = attributes;

		VkPipelineInputAssemblyStateCreateInfo assembly = { VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO };
		assembly.topology                               = VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

		VkPipelineViewportStateCreateInfo viewport = { VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO };
		viewport.viewportCount                     = 1;
		viewport.scissorCount                      = 1;

		// Blitz3D's front faces are clockwise as seen from the front. The projection flips Y, which flips this once more.
		VkPipelineRasterizationStateCreateInfo raster = { VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO };
		raster.polygonMode                            = wire ? VK_POLYGON_MODE_LINE : VK_POLYGON_MODE_FILL;
		raster.cullMode                               = VK_CULL_MODE_BACK_BIT;
		raster.frontFace                              = VK_FRONT_FACE_CLOCKWISE;
		raster.lineWidth                              = 1.0f;

		VkPipelineMultisampleStateCreateInfo multisample = { VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO };
		multisample.rasterizationSamples                 = VK_SAMPLE_COUNT_1_BIT;

		VkPipelineDepthStencilStateCreateInfo depth = { VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO };
		depth.depthTestEnable                       = VK_TRUE;
		depth.depthWriteEnable                      = VK_TRUE;
		// The depth is reversed: 1 at the near plane and 0 at the far plane, so closer is greater.
		depth.depthCompareOp                        = VK_COMPARE_OP_GREATER_OR_EQUAL;

		VkPipelineColorBlendAttachmentState blend = {};
		blend.blendEnable                         = (mode != 0) ? VK_TRUE : VK_FALSE;
		blend.srcColorBlendFactor                 = VK_BLEND_FACTOR_SRC_ALPHA;
		blend.dstColorBlendFactor                 = VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA;
		blend.colorBlendOp                        = VK_BLEND_OP_ADD;
		blend.srcAlphaBlendFactor                 = VK_BLEND_FACTOR_ONE;
		blend.dstAlphaBlendFactor                 = VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA;
		blend.alphaBlendOp                        = VK_BLEND_OP_ADD;
		blend.colorWriteMask                      = VK_COLOR_COMPONENT_R_BIT | VK_COLOR_COMPONENT_G_BIT | VK_COLOR_COMPONENT_B_BIT | VK_COLOR_COMPONENT_A_BIT;
		VkPipelineColorBlendStateCreateInfo blending = { VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO };
		blending.attachmentCount                     = 1;
		blending.pAttachments                        = &blend;

		// Modes: 0 = no blending, 1 = by alpha, 2 = multiply with what is there, 3 = add to what is there.
		if (mode == 2) {
			blend.srcColorBlendFactor = VK_BLEND_FACTOR_DST_COLOR;
			blend.dstColorBlendFactor = VK_BLEND_FACTOR_ZERO;
		} else if (mode == 3) {
			blend.srcColorBlendFactor = VK_BLEND_FACTOR_SRC_ALPHA;
			blend.dstColorBlendFactor = VK_BLEND_FACTOR_ONE;
		} else if (mode == 4) {
			blend.srcColorBlendFactor = VK_BLEND_FACTOR_DST_COLOR; // What is there times what is drawn, twice.
			blend.dstColorBlendFactor = VK_BLEND_FACTOR_SRC_COLOR;
		}

		VkDynamicState dynamic_states[5] = { VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR, VK_DYNAMIC_STATE_CULL_MODE, VK_DYNAMIC_STATE_DEPTH_WRITE_ENABLE, VK_DYNAMIC_STATE_DEPTH_TEST_ENABLE };
		VkPipelineDynamicStateCreateInfo dynamic = { VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO };
		dynamic.dynamicStateCount                = 5;
		dynamic.pDynamicStates                   = dynamic_states;

		VkFormat                      format    = VK_FORMAT_R8G8B8A8_UNORM;
		VkPipelineRenderingCreateInfo rendering = { VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO };
		rendering.colorAttachmentCount          = 1;
		rendering.pColorAttachmentFormats       = &format;
		rendering.depthAttachmentFormat         = depth_format;

		VkGraphicsPipelineCreateInfo info = { VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO };
		info.pNext                        = &rendering;
		info.stageCount                   = 2;
		info.pStages                      = stages;
		info.pVertexInputState            = &input;
		info.pInputAssemblyState          = &assembly;
		info.pViewportState               = &viewport;
		info.pRasterizationState          = &raster;
		info.pMultisampleState            = &multisample;
		info.pDepthStencilState           = &depth;
		info.pColorBlendState             = &blending;
		info.pDynamicState                = &dynamic;
		info.layout                       = g.layout3d;

		VkPipeline pipeline;
		check(vkCreateGraphicsPipelines(g.device, VK_NULL_HANDLE, 1, &info, nullptr, &pipeline), "vkCreateGraphicsPipelines (3D)");
		return pipeline;
	}

	// Makes room in the buffer of draw data for that many draws. This is only done while nothing is being recorded, and
	// what was drawn before has been waited for, so the old buffer can go. It is filled when the draws are recorded.
	static void ensure_entities(uint32_t count)
	{
		acquire_frame(); // The frame before in this slot may still read the descriptor set and the buffer.
		if (count <= g.entity_capacity) {
			return;
		}
		uint32_t capacity = g.entity_capacity ? g.entity_capacity : 1024;
		while (capacity < count) {
			capacity *= 2;
		}
		if (g.entity_buffer) {
			graveyard.push({ g.entity_buffer, g.entity_allocation });
		}
		create_buffer(VkDeviceSize(capacity) * sizeof(entity_push), VK_BUFFER_USAGE_STORAGE_BUFFER_BIT, true, g.entity_buffer, g.entity_allocation, &g.entity_mapped);
		g.entity_capacity = capacity;

		VkDescriptorBufferInfo buffer_info = { g.entity_buffer, 0, VK_WHOLE_SIZE };
		VkWriteDescriptorSet   write       = { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET };
		write.dstSet                       = g.entity_set;
		write.descriptorCount              = 1;
		write.descriptorType               = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
		write.pBufferInfo                  = &buffer_info;
		vkUpdateDescriptorSets(g.device, 1, &write, 0, nullptr);
	}

	void create_3d()
	{
		// Scene uniform buffer, with its descriptor set.
		VkDescriptorSetLayoutBinding binding = { 0, VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, nullptr };
		VkDescriptorSetLayoutCreateInfo set_info = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
		set_info.bindingCount                    = 1;
		set_info.pBindings                       = &binding;
		check(vkCreateDescriptorSetLayout(g.device, &set_info, nullptr, &g.scene_layout), "vkCreateDescriptorSetLayout");

		// The data of each draw is in a buffer, so that draws of the same thing can be a single call.
		VkDescriptorSetLayoutBinding entity_binding = { 0, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, nullptr };
		set_info.pBindings                          = &entity_binding;
		check(vkCreateDescriptorSetLayout(g.device, &set_info, nullptr, &g.entity_layout), "vkCreateDescriptorSetLayout");

		// Each of the frames that can be in flight has its own, as the program writes them while the GPU reads the other.
		for (uint32_t slot = 0; slot < frame_slots; slot++) {
			select_frame_slot(slot);
			VkDescriptorSetAllocateInfo alloc = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO };
			alloc.descriptorPool              = g.set_pool;
			alloc.descriptorSetCount          = 1;
			alloc.pSetLayouts                 = &g.scene_layout;
			check(vkAllocateDescriptorSets(g.device, &alloc, &g.scene_set), "vkAllocateDescriptorSets");

			create_buffer(VkDeviceSize(scene_stride) * max_scenes, VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT, true, g.scene_buffer, g.scene_allocation, &g.scene_mapped);

			VkDescriptorBufferInfo buffer_info = { g.scene_buffer, 0, sizeof(scene_data) };
			VkWriteDescriptorSet   write       = { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET };
			write.dstSet                       = g.scene_set;
			write.descriptorCount              = 1;
			write.descriptorType               = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC;
			write.pBufferInfo                  = &buffer_info;
			vkUpdateDescriptorSets(g.device, 1, &write, 0, nullptr);

			alloc.pSetLayouts = &g.entity_layout;
			check(vkAllocateDescriptorSets(g.device, &alloc, &g.entity_set), "vkAllocateDescriptorSets");
			ensure_entities(1024);
		}
		select_frame_slot(0);

		VkDescriptorSetLayout layouts[3]   = { g.set_layout, g.scene_layout, g.entity_layout };
		VkPipelineLayoutCreateInfo layout_info = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
		layout_info.setLayoutCount         = 3;
		layout_info.pSetLayouts            = layouts;
		check(vkCreatePipelineLayout(g.device, &layout_info, nullptr, &g.layout3d), "vkCreatePipelineLayout");

		VkShaderModule vs = create_shader(bb_shader_vertex_3d, sizeof(bb_shader_vertex_3d));
		VkShaderModule fs = create_shader(bb_shader_fragment_3d, sizeof(bb_shader_fragment_3d));
		g.opaque3d        = create_pipeline_3d(vs, fs, 0);
		g.blend3d         = create_pipeline_3d(vs, fs, 1);
		g.mul3d           = create_pipeline_3d(vs, fs, 2);
		g.add3d           = create_pipeline_3d(vs, fs, 3);
		g.mul2x3d         = create_pipeline_3d(vs, fs, 4);
		if (g.can_wireframe) {
			for (int mode = 0; mode < 4; mode++) {
				g.wire3d[mode] = create_pipeline_3d(vs, fs, mode, true);
			}
		}
		vkDestroyShaderModule(g.device, vs, nullptr);
		vkDestroyShaderModule(g.device, fs, nullptr);
	}
	gpu_image          depth_cache[max_depths];

	static gpu_image& depth_for(uint32_t width, uint32_t height)
	{
		for (uint32_t i = 0; i < max_depths; i++) {
			if (depth_cache[i].image && (depth_cache[i].width == width) && (depth_cache[i].height == height)) {
				return depth_cache[i];
			}
		}
		for (uint32_t i = 0; i < max_depths; i++) {
			if (!depth_cache[i].image) {
				depth_cache[i] = create_image(width, height, VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT, depth_format, VK_IMAGE_ASPECT_DEPTH_BIT);
				return depth_cache[i];
			}
		}
		fail("Too many different sizes of things are drawn to in 3D.");
	}

