	void create_3d()
	{
		// Scene uniform buffer, with its descriptor set.
		VkDescriptorSetLayoutBinding binding = { 0, VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, nullptr };
		VkDescriptorSetLayoutCreateInfo set_info = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
		set_info.bindingCount                    = 1;
		set_info.pBindings                       = &binding;
		check(vkCreateDescriptorSetLayout(g.device, &set_info, nullptr, &g.scene_layout), "vkCreateDescriptorSetLayout");

		// The data of each draw is in a buffer, so that draws of the same thing can be a single call.
		VkDescriptorSetLayoutBinding entity_binding = { 0, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT | VK_SHADER_STAGE_COMPUTE_BIT, nullptr };
		set_info.pBindings                          = &entity_binding;
		check(vkCreateDescriptorSetLayout(g.device, &set_info, nullptr, &g.entity_layout), "vkCreateDescriptorSetLayout");

		if (g.can_gpu_cull) {
			// The clusters, the runs of them for each draw and the commands that come out: see compute_shader_cull in generate_shaders.py.
			VkDescriptorSetLayoutBinding cull_bindings[3] = {
				{ 0, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
				{ 1, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
				{ 2, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
			};
			VkDescriptorSetLayoutCreateInfo cull_info = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
			cull_info.bindingCount                    = 3;
			cull_info.pBindings                       = cull_bindings;
			check(vkCreateDescriptorSetLayout(g.device, &cull_info, nullptr, &g.cull_layout), "vkCreateDescriptorSetLayout");
		}

		// Each of the frames that can be in flight has its own, as the program writes them while the GPU reads the other.
		for (uint32_t slot = 0; slot < frame_slots; slot++) {
			select_frame_slot(slot);
			VkDescriptorSetAllocateInfo alloc = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO };
			alloc.descriptorPool              = g.set_pool;
			alloc.descriptorSetCount          = 1;
			alloc.pSetLayouts                 = &g.scene_layout;
			check(vkAllocateDescriptorSets(g.device, &alloc, &g.scene_set), "vkAllocateDescriptorSets");

			create_buffer(VkDeviceSize(scene_stride) * max_scenes, VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT, true, g.scene_buffer, g.scene_allocation, &g.scene_mapped);

			VkDescriptorBufferInfo buffer_info = { g.scene_buffer, 0, sizeof(scene_data) };
			VkWriteDescriptorSet   write       = { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET };
			write.dstSet                       = g.scene_set;
			write.descriptorCount              = 1;
			write.descriptorType               = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC;
			write.pBufferInfo                  = &buffer_info;
			vkUpdateDescriptorSets(g.device, 1, &write, 0, nullptr);

			alloc.pSetLayouts = &g.entity_layout;
			check(vkAllocateDescriptorSets(g.device, &alloc, &g.entity_set), "vkAllocateDescriptorSets");
			ensure_entities(1024);
			if (g.can_gpu_cull) {
				alloc.pSetLayouts = &g.cull_layout;
				check(vkAllocateDescriptorSets(g.device, &alloc, &g.cull.set), "vkAllocateDescriptorSets");
			}
		}
		select_frame_slot(0);

		// Set 3 is the depth of what was drawn before the blended sprites, for SpriteDepthFade. Set 4, if the GPU can blend in the shader, is the target.
		if (g.can_blend_dither || blend_interlock()) {
			VkDescriptorSetLayoutBinding input_binding = { 0, blend_interlock() ? VK_DESCRIPTOR_TYPE_STORAGE_IMAGE : VK_DESCRIPTOR_TYPE_INPUT_ATTACHMENT, 1, VK_SHADER_STAGE_FRAGMENT_BIT, nullptr };
			set_info.pBindings                         = &input_binding;
			check(vkCreateDescriptorSetLayout(g.device, &set_info, nullptr, &g.input_layout), "vkCreateDescriptorSetLayout");
		}
		VkDescriptorSetLayout layouts[5]   = { g.set_layout, g.scene_layout, g.entity_layout, g.set_layout, (g.can_blend_dither || blend_interlock()) ? g.input_layout : g.set_layout };
		VkPipelineLayoutCreateInfo layout_info = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
		layout_info.setLayoutCount         = (g.can_blend_dither || blend_interlock()) ? 5 : 4;
		layout_info.pSetLayouts            = layouts;
		check(vkCreatePipelineLayout(g.device, &layout_info, nullptr, &g.layout3d), "vkCreatePipelineLayout");

		if (g.can_gpu_cull) {
			VkDescriptorSetLayout cull_layouts[2] = { g.entity_layout, g.cull_layout };
			VkPushConstantRange   cull_push       = { VK_SHADER_STAGE_COMPUTE_BIT, 0, 6 * 16 + 16 }; // The planes of the view and the first group.
			VkPipelineLayoutCreateInfo cull_layout_info = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
			cull_layout_info.setLayoutCount             = 2;
			cull_layout_info.pSetLayouts                = cull_layouts;
			cull_layout_info.pushConstantRangeCount     = 1;
			cull_layout_info.pPushConstantRanges        = &cull_push;
			check(vkCreatePipelineLayout(g.device, &cull_layout_info, nullptr, &g.cull_pipeline_layout), "vkCreatePipelineLayout");
			VkShaderModule cs = create_shader(bb_shader_compute_cull, sizeof(bb_shader_compute_cull));
			VkComputePipelineCreateInfo cull_pipeline = { VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO };
			cull_pipeline.stage.sType                 = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
			cull_pipeline.stage.stage                 = VK_SHADER_STAGE_COMPUTE_BIT;
			cull_pipeline.stage.module                = cs;
			cull_pipeline.stage.pName                 = "main";
			cull_pipeline.layout                      = g.cull_pipeline_layout;
			check(vkCreateComputePipelines(g.device, VK_NULL_HANDLE, 1, &cull_pipeline, nullptr, &g.cull_pipeline), "vkCreateComputePipelines");
			vkDestroyShaderModule(g.device, cs, nullptr);
		}

		build_pipelines_3d();
	}

	void build_pipelines_3d()
	{
		VkShaderModule vs = create_shader(bb_shader_vertex_3d, sizeof(bb_shader_vertex_3d));
		VkShaderModule fs = create_shader(bb_shader_fragment_3d, sizeof(bb_shader_fragment_3d));
		VkShaderModule fs_solid = create_shader(bb_shader_fragment_3d_solid, sizeof(bb_shader_fragment_3d_solid));
		// With Dither 2 the blended things are drawn by the shader that blends itself.
		bool           shader_blend = dither_level() == 2;
		VkShaderModule fs_blend     = shader_blend ? (blend_interlock() ? create_shader(bb_shader_fragment_3d_blend_interlock, sizeof(bb_shader_fragment_3d_blend_interlock)) : create_shader(bb_shader_fragment_3d_blend, sizeof(bb_shader_fragment_3d_blend))) : fs;
		g.opaque3d        = create_pipeline_3d(vs, fs, 0);
		g.solid3d         = create_pipeline_3d(vs, fs_solid, 0);
		g.blend3d         = create_pipeline_3d(vs, fs_blend, 1, false, shader_blend, fs);
		g.mul3d           = create_pipeline_3d(vs, fs_blend, 2, false, shader_blend, fs);
		g.add3d           = create_pipeline_3d(vs, fs_blend, 3, false, shader_blend, fs);
		g.mul2x3d         = create_pipeline_3d(vs, fs_blend, 4, false, shader_blend, fs);
		if (g.can_wireframe) {
			for (int mode = 0; mode < 4; mode++) {
				g.wire3d[mode] = create_pipeline_3d(vs, (mode != 0) ? fs_blend : fs, mode, true, shader_blend && (mode != 0), fs);
			}
		}
		vkDestroyShaderModule(g.device, vs, nullptr);
		vkDestroyShaderModule(g.device, fs, nullptr);
		vkDestroyShaderModule(g.device, fs_solid, nullptr);
		if (shader_blend) {
			vkDestroyShaderModule(g.device, fs_blend, nullptr);
		}
	}

	void destroy_pipelines_3d()
	{
		vkDestroyPipeline(g.device, g.opaque3d, nullptr);
		vkDestroyPipeline(g.device, g.solid3d, nullptr);
		vkDestroyPipeline(g.device, g.blend3d, nullptr);
		vkDestroyPipeline(g.device, g.mul3d, nullptr);
		vkDestroyPipeline(g.device, g.mul2x3d, nullptr);
		vkDestroyPipeline(g.device, g.add3d, nullptr);
		for (VkPipeline& pipeline : g.wire3d) {
			if (pipeline) {
				vkDestroyPipeline(g.device, pipeline, nullptr);
				pipeline = VK_NULL_HANDLE;
			}
		}
	}

	void rebuild_pipelines_3d()
	{
		if (!g.layout3d) {
			return;
		}
		flush(); // What was recorded still uses the old ones.
		wait_gpu();
		destroy_pipelines_3d();
		build_pipelines_3d();
	}
