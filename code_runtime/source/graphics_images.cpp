	// The bytes a pixel takes in an image that programs read and write as RGBA8: the buffers can be deeper than that.
	uint32_t pixel_bytes(VkFormat format)
	{
		return (format == VK_FORMAT_R16G16B16A16_UNORM) ? 8 : 4;
	}

	// Copies the pixels of a rectangle of an image into new memory, as RGBA.
	uint8_t* read_pixels(gpu_image& img, int x, int y, int w, int h, bool native)
	{
		VkDeviceSize   size = VkDeviceSize(w) * VkDeviceSize(h) * pixel_bytes(img.format);
		VkBuffer       staging;
		VmaAllocation staging_allocation;
		void*          mapped;
		create_buffer(size, VK_BUFFER_USAGE_TRANSFER_DST_BIT, true, staging, staging_allocation, &mapped);

		begin_commands();
		VkImageLayout previous = img.layout;
		transition(img, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL);
		VkBufferImageCopy copy = {};
		copy.imageSubresource  = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 };
		copy.imageOffset       = { x, y, 0 };
		copy.imageExtent       = { uint32_t(w), uint32_t(h), 1 };
		vkCmdCopyImageToBuffer(g.cmd, img.image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, staging, 1, &copy);
		transition(img, previous);
		submit_commands();

		size_t   count = size_t(w) * size_t(h);
		uint8_t* out   = static_cast<uint8_t*>(malloc(count * (native ? pixel_bytes(img.format) : 4)));
		if (native) {
			memcpy(out, mapped, count * pixel_bytes(img.format));
		} else if (img.format == VK_FORMAT_A2B10G10R10_UNORM_PACK32) {
			const uint32_t* packed = static_cast<const uint32_t*>(mapped);
			for (size_t i = 0; i < count; i++) {
				uint32_t v     = packed[i];
				out[i * 4 + 0] = uint8_t(((v & 1023) * 255 + 511) / 1023);
				out[i * 4 + 1] = uint8_t((((v >> 10) & 1023) * 255 + 511) / 1023);
				out[i * 4 + 2] = uint8_t((((v >> 20) & 1023) * 255 + 511) / 1023);
				out[i * 4 + 3] = uint8_t((v >> 30) * 85);
			}
		} else if (img.format == VK_FORMAT_R16G16B16A16_UNORM) {
			const uint16_t* wide = static_cast<const uint16_t*>(mapped);
			for (size_t i = 0; i < count * 4; i++) {
				out[i] = uint8_t((uint32_t(wide[i]) * 255 + 32767) / 65535);
			}
		} else {
			memcpy(out, mapped, count * 4);
		}
		destroy_buffer(staging, staging_allocation);
		return out;
	}

	// The other way around.
	void write_pixels(gpu_image& img, int x, int y, int w, int h, const uint8_t* rgba, bool native)
	{
		image_generation++;
		img.mips_stale = img.mips > 1;
		VkDeviceSize   size = VkDeviceSize(w) * VkDeviceSize(h) * pixel_bytes(img.format);
		VkBuffer       staging;
		VmaAllocation staging_allocation;
		void*          mapped;
		create_buffer(size, VK_BUFFER_USAGE_TRANSFER_SRC_BIT, true, staging, staging_allocation, &mapped);
		size_t count = size_t(w) * size_t(h);
		if (native) {
			memcpy(mapped, rgba, count * pixel_bytes(img.format));
		} else if (img.format == VK_FORMAT_A2B10G10R10_UNORM_PACK32) {
			uint32_t* packed = static_cast<uint32_t*>(mapped);
			for (size_t i = 0; i < count; i++) {
				uint32_t a = (uint32_t(rgba[i * 4 + 3]) + 42) / 85;
				packed[i]  = ((uint32_t(rgba[i * 4 + 0]) * 1023 + 127) / 255) | (((uint32_t(rgba[i * 4 + 1]) * 1023 + 127) / 255) << 10) | (((uint32_t(rgba[i * 4 + 2]) * 1023 + 127) / 255) << 20) | ((a > 3 ? 3 : a) << 30);
			}
		} else if (img.format == VK_FORMAT_R16G16B16A16_UNORM) {
			uint16_t* wide = static_cast<uint16_t*>(mapped);
			for (size_t i = 0; i < count * 4; i++) {
				wide[i] = uint16_t(rgba[i] * 257); // 255 * 257 = 65535.
			}
		} else {
			memcpy(mapped, rgba, count * 4);
		}

		begin_commands();
		VkImageLayout previous = img.layout;
		transition(img, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL);
		VkBufferImageCopy copy = {};
		copy.imageSubresource  = { VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1 };
		copy.imageOffset       = { x, y, 0 };
		copy.imageExtent       = { uint32_t(w), uint32_t(h), 1 };
		vkCmdCopyBufferToImage(g.cmd, staging, img.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &copy);
		transition(img, previous);
		submit_commands();

		destroy_buffer(staging, staging_allocation);
	}

	static int32_t add_image(image_entry const& entry)
	{
		for (uint32_t i = 0; i < image_table.size; i++) {
			if (!image_table[i].used) {
				image_table[i] = entry;
				return int32_t(i) + 1;
			}
		}
		image_table.push(entry);
		return int32_t(image_table.size);
	}

	int make_internal_image(int width, int height, const uint8_t* rgba)
	{
		image_entry entry;
		entry.used     = true;
		entry.internal = true;
		entry.frame_w = entry.sheet_w = width;
		entry.frame_h = entry.sheet_h = height;
		upload_texture(entry.image, entry.set, uint32_t(width), uint32_t(height), rgba, g.sampler);
		return add_image(entry);
	}

	void free_internal_image(int handle)
	{
		if (image_entry* e = image_of(handle)) {
			free_image(*e);
		}
	}

	static image_entry* need_image(int32_t handle, const char* what)
	{
		image_entry* e = image_of(handle);
		if (!e) {
			char message[96];
			snprintf(message, sizeof(message), "%s: the image does not exist.", what);
			bb_runtime_error(message);
		}
		return e;
	}

	// Uploads the pixels (RGBA, the whole sheet) as a new image with the given frames.
	static int32_t make_image(int sheet_w, int sheet_h, int frame_w, int frame_h, int frames, int first, const uint8_t* pixels, picture const* compressed = nullptr)
	{
		image_entry entry;
		entry.used    = true;
		entry.frames  = frames;
		entry.frame_w = frame_w;
		entry.frame_h = frame_h;
		entry.sheet_w = sheet_w;
		entry.sheet_h = sheet_h;
		entry.first   = first;
		if (auto_mid_handle) {
			entry.handle_x = frame_w / 2;
			entry.handle_y = frame_h / 2;
		}
		if (active()) {
			if (compressed) {
				upload_compressed(entry.image, entry.set, *compressed, g.sampler, false, false);
			} else {
				upload_texture(entry.image, entry.set, uint32_t(sheet_w), uint32_t(sheet_h), pixels, g.sampler);
			}
		}
		return add_image(entry);
	}

	static uint8_t* picture_pixels(picture& source, int& width, int& height)
	{
		SDL_Surface* loaded = picture_surface(source);
		if (!loaded) {
			return nullptr;
		}
		SDL_Surface* rgba = SDL_ConvertSurface(loaded, SDL_PIXELFORMAT_RGBA32);
		SDL_DestroySurface(loaded);
		if (!rgba) {
			return nullptr;
		}
		width        = rgba->w;
		height       = rgba->h;
		uint8_t* out = static_cast<uint8_t*>(malloc(size_t(width) * size_t(height) * 4));
		for (int y = 0; y < height; y++) {
			memcpy(out + size_t(y) * size_t(width) * 4, static_cast<uint8_t*>(rgba->pixels) + size_t(y) * size_t(rgba->pitch), size_t(width) * 4);
		}
		SDL_DestroySurface(rgba);
		return out;
	}

	static uint8_t* load_pixels(const char* file, int& width, int& height)
	{
		picture source;
		if (!file || !load_picture(file, source)) {
			return nullptr;
		}
		return picture_pixels(source, width, height);
	}

	// Whether a picture can go to the GPU as the blocks it has, which saves the memory of the pixels. BC5 has to be decoded as its third
	// channel is rebuilt.
	static bool keeps_blocks(picture const& source)
	{
		return source.blocks && active() && (source.block != block_format::bc5) && compressed_supported(source.block);
	}

	// LoadImage on a loader thread: the decoded pixels, or the blocks of a compressed picture that go to the GPU as they are.
	struct image_job : load_job {
		void*       data = nullptr;
		size_t      size = 0;
		std::string name;
		bool        mid  = false; // AutoMidHandle when the image was loaded.
		bool        block_ok[7] = {};
		picture     blocks;
		uint8_t*    pixels = nullptr;
		int         w = 0, h = 0;

		~image_job() override
		{
			SDL_free(data);
			free_picture(blocks);
			free(pixels);
		}

		void run() override
		{
			picture source;
			if (!load_picture_memory(name.c_str(), data, size, source)) {
				return;
			}
			SDL_free(data);
			data = nullptr;
			if (source.blocks && (source.block != block_format::bc5) && block_ok[int(source.block)]) {
				w      = source.width;
				h      = source.height;
				blocks = source;
				ok     = true;
				return;
			}
			pixels = picture_pixels(source, w, h);
			ok     = pixels != nullptr;
			free_picture(source);
		}
	};

	void resolve_image(image_entry& e)
	{
		image_job* job = static_cast<image_job*>(e.pending);
		e.pending      = nullptr;
		async_wait(job);
		if (!job->ok) {
			char message[400];
			snprintf(message, sizeof(message), "Can't load image '%s': the picture can't be decoded.", job->name.c_str());
			delete job;
			bb_runtime_error(message);
			return;
		}
		e.frames  = 1;
		e.frame_w = e.sheet_w = job->w;
		e.frame_h = e.sheet_h = job->h;
		if (job->mid) {
			e.handle_x = job->w / 2;
			e.handle_y = job->h / 2;
		}
		if (job->blocks.blocks) {
			upload_compressed(e.image, e.set, job->blocks, g.sampler, false, false);
		} else {
			upload_texture(e.image, e.set, uint32_t(job->w), uint32_t(job->h), job->pixels, g.sampler);
		}
		delete job;
	}

	bool image_is_ready(int handle)
	{
		if ((handle < 1) || (uint32_t(handle) > image_table.size) || !image_table[uint32_t(handle) - 1].used) {
			return false;
		}
		image_entry* e = &image_table[uint32_t(handle) - 1];
		if (e->pending) {
			if (!async_finished(e->pending)) {
				return false;
			}
			resolve_image(*e);
		}
		return true;
	}

	// Draws a part of a frame, with its top left corner at the destination.
	static void draw_part(image_entry* e, int32_t handle, int dx, int dy, int rx, int ry, int rw, int rh, int frame, bool masked)
	{
		if (!active()) {
			return;
		}
		if ((frame < 0) || (frame >= e->frames)) {
			bb_runtime_error("DrawImage: the frame does not exist.");
		}
		// Only what is in the frame can be drawn.
		if (rx < 0) {
			dx -= rx;
			rw += rx;
			rx = 0;
		}
		if (ry < 0) {
			dy -= ry;
			rh += ry;
			ry = 0;
		}
		rw = (rx + rw > e->frame_w) ? e->frame_w - rx : rw;
		rh = (ry + rh > e->frame_h) ? e->frame_h - ry : rh;
		if ((rw <= 0) || (rh <= 0)) {
			return;
		}

		int cx, cy;
		frame_position(*e, frame, cx, cy);
		float u0 = float(cx + rx) / float(e->sheet_w), v0 = float(cy + ry) / float(e->sheet_h);
		float u1 = float(cx + rx + rw) / float(e->sheet_w), v1 = float(cy + ry + rh) / float(e->sheet_h);
		float x0 = float(dx + g.origin_x), y0 = float(dy + g.origin_y), x1 = float(dx + rw + g.origin_x), y1 = float(dy + rh + g.origin_y);

		float mask[4] = { 0, 0, 0, 0 };
		if (masked && e->masked) {
			mask[0] = float(e->mask[0]) / 255.0f;
			mask[1] = float(e->mask[1]) / 255.0f;
			mask[2] = float(e->mask[2]) / 255.0f;
			mask[3] = 1.0f;
		}
		vertex* v = add_vertices(OP_TRIANGLES, TEXTURE_WHITE, 6, handle, mask);
		v[0]      = { x0, y0, u0, v0, 255, 255, 255, 255 };
		v[1]      = { x1, y0, u1, v0, 255, 255, 255, 255 };
		v[2]      = { x0, y1, u0, v1, 255, 255, 255, 255 };
		v[3]      = { x1, y0, u1, v0, 255, 255, 255, 255 };
		v[4]      = { x1, y1, u1, v1, 255, 255, 255, 255 };
		v[5]      = { x0, y1, u0, v1, 255, 255, 255, 255 };
	}

	// DrawMovie: the picture of a movie, which is an image, stretched to a rectangle of the screen. Nothing of it is see-through.
	void draw_stretched(int32_t handle, int x, int y, int w, int h)
	{
		image_entry* e = image_of(handle);
		if (!e || !active() || (w <= 0) || (h <= 0)) {
			return;
		}
		float x0 = float(x), y0 = float(y), x1 = float(x + w), y1 = float(y + h);
		float u1 = float(e->frame_w) / float(e->sheet_w), v1 = float(e->frame_h) / float(e->sheet_h);
		float mask[4] = { 0, 0, 0, 0 };
		vertex* v = add_vertices(OP_TRIANGLES, TEXTURE_WHITE, 6, handle, mask);
		v[0]      = { x0, y0, 0, 0, 255, 255, 255, 255 };
		v[1]      = { x1, y0, u1, 0, 255, 255, 255, 255 };
		v[2]      = { x0, y1, 0, v1, 255, 255, 255, 255 };
		v[3]      = { x1, y0, u1, 0, 255, 255, 255, 255 };
		v[4]      = { x1, y1, u1, v1, 255, 255, 255, 255 };
		v[5]      = { x0, y1, 0, v1, 255, 255, 255, 255 };
	}

	// Puts the RGBA pixels of a picture that is as big as the image into it.
	void replace_pixels(int32_t handle, const uint8_t* rgba)
	{
		image_entry* e = image_of(handle);
		if (e && active()) {
			write_pixels(e->image, 0, 0, e->frame_w, e->frame_h, rgba);
		}
	}
