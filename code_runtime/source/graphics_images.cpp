// IMAGE_READY: 1 once the image is loaded, without waiting for it.
int32_t bb_image_ready(int32_t handle)
{
	return image_is_ready(handle) ? 1 : 0;
}

int32_t bb_load_image(const char* file)
{
	if (async_loading() && active() && file) {
		// Like LoadTexture: the file is read now and the decoding goes on another thread.
		size_t size = 0;
		void*  data = SDL_LoadFile(bb_native_path(file), &size);
		if (!data) {
			return 0;
		}
		if (picture_recognized(static_cast<const uint8_t*>(data), size)) {
			image_job* job = new image_job();
			job->data      = data;
			job->size      = size;
			job->name      = file;
			job->mid       = auto_mid_handle;
			memcpy(job->block_ok, async_block_support(), sizeof(job->block_ok));
			image_entry entry;
			entry.used    = true;
			entry.pending = job;
			async_submit(job);
			return add_image(entry);
		}
		SDL_free(data);
	}
	picture source;
	if (!file || !load_picture(file, source)) {
		return 0;
	}
	if (keeps_blocks(source)) {
		int32_t handle = make_image(source.width, source.height, source.width, source.height, 1, 0, nullptr, &source);
		free_picture(source);
		return handle;
	}
	int      w = 0, h = 0;
	uint8_t* pixels = picture_pixels(source, w, h);
	if (!pixels) {
		return 0;
	}
	int32_t handle = make_image(w, h, w, h, 1, 0, pixels);
	free(pixels);
	return handle;
}

// LoadAnimImage(file, width, height, first, count): a sheet of frames that are width x height.
int32_t bb_load_anim_image(const char* file, int32_t frame_w, int32_t frame_h, int32_t first, int32_t count)
{
	picture source;
	if (!file || !load_picture(file, source)) {
		return 0;
	}
	if (keeps_blocks(source)) {
		int32_t handle = 0;
		if ((frame_w > 0) && (frame_h > 0) && (count > 0) && (frame_w <= source.width) && (frame_h <= source.height) && (first >= 0)) {
			handle = make_image(source.width, source.height, frame_w, frame_h, count, first, nullptr, &source);
		}
		free_picture(source);
		return handle;
	}
	int      w = 0, h = 0;
	uint8_t* pixels = picture_pixels(source, w, h);
	if (!pixels) {
		return 0;
	}
	if ((frame_w <= 0) || (frame_h <= 0) || (count <= 0) || (frame_w > w) || (frame_h > h) || (first < 0)) {
		free(pixels);
		return 0;
	}
	int32_t handle = make_image(w, h, frame_w, frame_h, count, first, pixels);
	free(pixels);
	return handle;
}

// For the GUI: a file of square icons next to each other, whose background is the color of the first pixel. Says how
// many icons there are and how big they are, and which of them are blank, which is how toolbars have spaces.
int32_t bb_gui_load_strip(const char* file, int32_t* size, int32_t* count, char* blank, int32_t max)
{
	int      w = 0, h = 0;
	uint8_t* pixels = load_pixels(file, w, h);
	if (!pixels) {
		return 0;
	}
	int sz = h, n = w / sz;
	if ((sz < 1) || (n < 1)) {
		free(pixels);
		return 0;
	}
	uint8_t trans[3] = { pixels[0], pixels[1], pixels[2] };
	for (int i = 0; (i < n) && (i < max); i++) {
		bool same = true;
		for (int y = 0; same && (y < sz); y++) {
			for (int x = i * sz; same && (x < (i + 1) * sz); x++) {
				const uint8_t* p = pixels + (size_t(y) * size_t(w) + size_t(x)) * 4;
				same             = (p[0] == trans[0]) && (p[1] == trans[1]) && (p[2] == trans[2]);
			}
		}
		blank[i] = same ? 1 : 0;
	}
	int32_t handle = make_image(w, h, w, h, 1, 0, pixels);
	free(pixels);
	if (image_entry* e = image_of(handle)) {
		e->mask[0] = trans[0];
		e->mask[1] = trans[1];
		e->mask[2] = trans[2];
		e->masked  = true;
	}
	*size  = sz;
	*count = n;
	return handle;
}

int32_t bb_create_image(int32_t width, int32_t height, int32_t frames)
{
	if ((width <= 0) || (height <= 0) || (frames <= 0)) {
		bb_runtime_error("CreateImage: needs a size and at least one frame.");
	}
	size_t   sheet_w = size_t(width) * size_t(frames);
	uint8_t* pixels  = static_cast<uint8_t*>(calloc(sheet_w * size_t(height), 4));
	for (size_t i = 0; i < sheet_w * size_t(height); i++) {
		pixels[i * 4 + 3] = 255; // Black, which is what is masked by default.
	}
	int32_t handle = make_image(int(sheet_w), height, width, height, frames, 0, pixels);
	free(pixels);
	return handle;
}

void bb_free_image(int32_t handle)
{
	// Freeing what is already gone (or never was) does nothing, as programs rely on.
	image_entry* e = image_of(handle);
	if (e) {
		free_image(*e);
	}
}

int32_t bb_image_width(int32_t handle)
{
	return need_image(handle, "ImageWidth")->frame_w;
}

int32_t bb_image_height(int32_t handle)
{
	return need_image(handle, "ImageHeight")->frame_h;
}

void bb_handle_image(int32_t handle, int32_t x, int32_t y)
{
	image_entry* e = need_image(handle, "HandleImage");
	e->handle_x    = x;
	e->handle_y    = y;
}

void bb_mid_handle(int32_t handle)
{
	image_entry* e = need_image(handle, "MidHandle");
	e->handle_x    = e->frame_w / 2;
	e->handle_y    = e->frame_h / 2;
}

void bb_auto_mid_handle(int32_t on)
{
	auto_mid_handle = on != 0;
}

void bb_mask_image(int32_t handle, int32_t r, int32_t green, int32_t b)
{
	image_entry* e = need_image(handle, "MaskImage");
	e->mask[0]     = uint8_t(r < 0 ? 0 : (r > 255 ? 255 : r));
	e->mask[1]     = uint8_t(green < 0 ? 0 : (green > 255 ? 255 : green));
	e->mask[2]     = uint8_t(b < 0 ? 0 : (b > 255 ? 255 : b));
	e->masked      = true;
	image_generation++;
}

