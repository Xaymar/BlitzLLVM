	////////////////////////////////////////////////////////////////////////////
	// Matrices and quaternions
	////////////////////////////////////////////////////////////////////////////
	// Matrix for a position, a scale and a quaternion (w, x, y, z).
	void compose(float* m, const float* pos, const float* scale, const float* q)
	{
		float w = q[0], x = q[1], y = q[2], z = q[3];
		float len = sqrtf(w * w + x * x + y * y + z * z);
		if (len > 1e-12f) {
			w /= len;
			x /= len;
			y /= len;
			z /= len;
		}
		float xx = x * x, yy = y * y, zz = z * z, xy = x * y, xz = x * z, yz = y * z, wx = w * x, wy = w * y, wz = w * z;
		float r[3][3] = {
			// The quaternions of the original turn the other way round than the usual ones.
			{ 1 - 2 * (yy + zz), 2 * (xy - wz), 2 * (xz + wy) },
			{ 2 * (xy + wz), 1 - 2 * (xx + zz), 2 * (yz - wx) },
			{ 2 * (xz - wy), 2 * (yz + wx), 1 - 2 * (xx + yy) },
		};
		memset(m, 0, sizeof(float) * 16);
		for (int col = 0; col < 3; col++) {
			for (int row = 0; row < 3; row++) {
				m[col * 4 + row] = r[row][col] * scale[col];
			}
		}
		m[12] = pos[0];
		m[13] = pos[1];
		m[14] = pos[2];
		m[15] = 1;
	}

	void transform_point(const float* m, const float* p, float* out)
	{
		for (int row = 0; row < 3; row++) {
			out[row] = m[0 + row] * p[0] + m[4 + row] * p[1] + m[8 + row] * p[2] + m[12 + row];
		}
	}

	void transform_direction(const float* m, const float* p, float* out)
	{
		for (int row = 0; row < 3; row++) {
			out[row] = m[0 + row] * p[0] + m[4 + row] * p[1] + m[8 + row] * p[2];
		}
	}

	////////////////////////////////////////////////////////////////////////////
	// Where a node is at a time
	////////////////////////////////////////////////////////////////////////////
	template<typename K>
	void find_keys(buffer<K> const& keys, float frame, uint32_t& before, uint32_t& after, float& blend)
	{
		if (frame <= keys[0].frame) {
			before = after = 0;
			blend          = 0;
			return;
		}
		for (uint32_t i = 1; i < keys.size; i++) {
			if (frame <= keys[i].frame) {
				before = i - 1;
				after  = i;
				float span = keys[i].frame - keys[i - 1].frame;
				blend      = span > 1e-6f ? (frame - keys[i - 1].frame) / span : 0;
				return;
			}
		}
		before = after = keys.size - 1;
		blend          = 0;
	}

	void sample_vector(buffer<key3> const& keys, float frame, float* out)
	{
		if (keys.size == 0) {
			return;
		}
		uint32_t a, b;
		float    t;
		find_keys(keys, frame, a, b, t);
		for (int i = 0; i < 3; i++) {
			out[i] = keys[a].v[i] + (keys[b].v[i] - keys[a].v[i]) * t;
		}
	}

	void sample_rotation(buffer<key4> const& keys, float frame, float* out)
	{
		if (keys.size == 0) {
			return;
		}
		uint32_t a, b;
		float    t;
		find_keys(keys, frame, a, b, t);
		float sign = 1;
		float d    = keys[a].q[0] * keys[b].q[0] + keys[a].q[1] * keys[b].q[1] + keys[a].q[2] * keys[b].q[2] + keys[a].q[3] * keys[b].q[3];
		if (d < 0) {
			sign = -1; // The short way around.
		}
		for (int i = 0; i < 4; i++) {
			out[i] = keys[a].q[i] + (keys[b].q[i] * sign - keys[a].q[i]) * t;
		}
	}

	// The pose of one node at a frame: position, scale and rotation.
	void node_pose(anim_node const& n, float frame, float* pos, float* scale, float* rot)
	{
		memcpy(pos, n.pos, sizeof(n.pos));
		memcpy(scale, n.scale, sizeof(n.scale));
		memcpy(rot, n.rot, sizeof(n.rot));
		sample_vector(n.pos_keys, frame, pos);
		sample_vector(n.scale_keys, frame, scale);
		sample_rotation(n.rot_keys, frame, rot);
	}

	// Puts everything in a model where it belongs at a frame, which includes moving the vertices of skinned meshes.
	void apply_pose(animation& a, float frame)
	{
		uint32_t count = a.nodes.size;
		float*   models = static_cast<float*>(malloc(size_t(count) * 16 * sizeof(float)));
		bool     any_bones = false;
		for (uint32_t i = 0; i < count; i++) {
			anim_node& n = *a.nodes[i];
			float      pos[3], scale[3], rot[4], local[16];
			node_pose(n, frame, pos, scale, rot);
			compose(local, pos, scale, rot);
			if (n.parent >= 0) {
				mat_multiply(models + i * 16, models + size_t(n.parent) * 16, local);
			} else {
				memcpy(models + i * 16, local, sizeof(local));
			}
			any_bones = any_bones || n.is_bone;

			// The first node is where the whole model is placed, which belongs to the program and not to the animation.
			if (((i > 0) || n.user_keys) && get_entity(n.handle)) {
				entity* e = get_entity(n.handle);
				if (n.pos_keys.size) {
					memcpy(e->position, pos, sizeof(pos));
				}
				if (n.scale_keys.size) {
					memcpy(e->scale, scale, sizeof(scale));
				}
				if (n.rot_keys.size) {
					float rotation_matrix[16];
					float unit[3] = { 1, 1, 1 };
					compose(rotation_matrix, pos, unit, rot);
					euler_from_matrix(rotation_matrix, e->rotation);
				}
			}
		}

		if (any_bones) {
			// Bone matrices: from the bind pose to now.
			float* skin = static_cast<float*>(malloc(size_t(count) * 16 * sizeof(float)));
			for (uint32_t i = 0; i < count; i++) {
				mat_multiply(skin + i * 16, models + i * 16, a.nodes[i]->inverse_bind);
			}
			for (uint32_t i = 0; i < count; i++) {
				anim_node& n = *a.nodes[i];
				entity*    e = n.has_mesh ? get_entity(n.handle) : nullptr;
				if (!e) {
					continue;
				}
				float pose_inverse[16];
				mat_affine_inverse(models + i * 16, pose_inverse);
				for (uint32_t s = 0; s < e->surfaces.size; s++) {
					surface*   surf = e->surfaces[s];
					skin_data* sk   = surf->skin;
					if (!sk) {
						continue;
					}
					const float* bind = a.nodes[sk->mesh_node]->bind_model;
					for (uint32_t v = 0; v < surf->vertices.size; v++) {
						float p[3], n3[3];
						transform_point(bind, &sk->bind_position[v * 3], p);
						transform_direction(bind, &sk->bind_normal[v * 3], n3);
						float moved[3] = { 0, 0, 0 }, moved_normal[3] = { 0, 0, 0 };
						float total = 0;
						for (uint32_t w = sk->start[v]; w < sk->start[v + 1]; w++) {
							const float* m = skin + size_t(sk->bone[w]) * 16;
							float        q[3], qn[3];
							transform_point(m, p, q);
							transform_direction(m, n3, qn);
							for (int k = 0; k < 3; k++) {
								moved[k] += q[k] * sk->weight[w];
								moved_normal[k] += qn[k] * sk->weight[w];
							}
							total += sk->weight[w];
						}
						if (total < 1e-6f) {
							memcpy(moved, p, sizeof(p));
							memcpy(moved_normal, n3, sizeof(n3));
						}
						float local[3], local_normal[3];
						transform_point(pose_inverse, moved, local);
						transform_direction(pose_inverse, moved_normal, local_normal);
						float length = sqrtf(local_normal[0] * local_normal[0] + local_normal[1] * local_normal[1] + local_normal[2] * local_normal[2]);
						if (length > 1e-9f) {
							local_normal[0] /= length;
							local_normal[1] /= length;
							local_normal[2] /= length;
						}
						vertex3d& vert = surf->vertices[v];
						vert.x = local[0];
						vert.y = local[1];
						vert.z = local[2];
						vert.nx = local_normal[0];
						vert.ny = local_normal[1];
						vert.nz = local_normal[2];
					}
					surf->dirty = true;
				}
			}
			free(skin);
		}
		free(models);
	}

	// The model that an entity is part of: the closest entity above that has an animation.
	animation* animation_of(int handle)
	{
		for (int h = handle; h; ) {
			entity* e = get_entity(h);
			if (!e) {
				return nullptr;
			}
			if (e->anim) {
				return e->anim;
			}
			h = e->parent;
		}
		return nullptr;
	}

