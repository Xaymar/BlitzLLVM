		struct pixel {
			uint8_t c[4];
		};

		void put32(std::vector<uint8_t>& v, uint32_t x)
		{
			for (int i = 0; i < 4; i++) {
				v.push_back(uint8_t(x >> (8 * i)));
			}
		}

		// The 4x4 block at (bx, by) of a picture, the edge repeated where the picture ends.
		void fetch_block(const uint8_t* rgba, int w, int h, int bx, int by, pixel* out)
		{
			for (int i = 0; i < 16; i++) {
				int x = std::min(bx * 4 + (i & 3), w - 1), y = std::min(by * 4 + (i >> 2), h - 1);
				memcpy(out[i].c, rgba + (size_t(y) * w + x) * 4, 4);
			}
		}

		uint16_t to565(const int* c)
		{
			return uint16_t(((c[0] * 31 + 127) / 255) << 11 | ((c[1] * 63 + 127) / 255) << 5 | ((c[2] * 31 + 127) / 255));
		}

		void from565(uint16_t v, int* c)
		{
			int r = (v >> 11) & 31, g = (v >> 5) & 63, b = v & 31;
			c[0] = (r << 3) | (r >> 2);
			c[1] = (g << 2) | (g >> 4);
			c[2] = (b << 3) | (b >> 2);
		}

		// The two colors of the block that are the furthest apart along the direction the colors vary in the most (found with a few steps
		// of the power method on the covariance), as lo and hi. Channels from `channels` on are not looked at. Skipped pixels are ignored.
		bool line_ends(const pixel* px, int channels, bool skip_see_through, int* lo, int* hi)
		{
			double mean[4] = { 0, 0, 0, 0 };
			int    count   = 0;
			for (int i = 0; i < 16; i++) {
				if (skip_see_through && px[i].c[3] < 128) {
					continue;
				}
				count++;
				for (int k = 0; k < channels; k++) {
					mean[k] += px[i].c[k];
				}
			}
			if (!count) {
				return false;
			}
			for (int k = 0; k < channels; k++) {
				mean[k] /= count;
			}
			double cov[4][4] = {};
			for (int i = 0; i < 16; i++) {
				if (skip_see_through && px[i].c[3] < 128) {
					continue;
				}
				for (int a = 0; a < channels; a++) {
					for (int b = 0; b < channels; b++) {
						cov[a][b] += (px[i].c[a] - mean[a]) * (px[i].c[b] - mean[b]);
					}
				}
			}
			double axis[4] = { 1, 1, 1, 1 };
			for (int step = 0; step < 6; step++) {
				double next[4] = {}, length = 0;
				for (int a = 0; a < channels; a++) {
					for (int b = 0; b < channels; b++) {
						next[a] += cov[a][b] * axis[b];
					}
					length += next[a] * next[a];
				}
				if (length < 1e-9) {
					break;
				}
				length = std::sqrt(length);
				for (int a = 0; a < channels; a++) {
					axis[a] = next[a] / length;
				}
			}
			double best_lo = 1e30, best_hi = -1e30;
			int    at_lo = -1, at_hi = -1;
			for (int i = 0; i < 16; i++) {
				if (skip_see_through && px[i].c[3] < 128) {
					continue;
				}
				double t = 0;
				for (int k = 0; k < channels; k++) {
					t += px[i].c[k] * axis[k];
				}
				if (t < best_lo) {
					best_lo = t;
					at_lo   = i;
				}
				if (t > best_hi) {
					best_hi = t;
					at_hi   = i;
				}
			}
			for (int k = 0; k < channels; k++) {
				lo[k] = px[at_lo].c[k];
				hi[k] = px[at_hi].c[k];
			}
			return true;
		}

		// Puts the colors lo and hi (the ends of the BC1 line) in a block, picks the closest of the colors between them for every pixel, and
		// returns how far the result is from the pixels (squared, over red, green and blue).
		int bc1_try(const pixel* px, bool punch, const int* lo, const int* hi, uint8_t* out)
		{
			uint16_t c0 = to565(hi), c1 = to565(lo);
			bool     four = !punch;
			if (four ? (c0 < c1) : (c0 > c1)) {
				std::swap(c0, c1);
			}
			int pal[4][3];
			from565(c0, pal[0]);
			from565(c1, pal[1]);
			for (int k = 0; k < 3; k++) {
				if (four) {
					pal[2][k] = (2 * pal[0][k] + pal[1][k]) / 3;
					pal[3][k] = (pal[0][k] + 2 * pal[1][k]) / 3;
				} else {
					pal[2][k] = (pal[0][k] + pal[1][k]) / 2;
					pal[3][k] = 0;
				}
			}
			out[0] = uint8_t(c0);
			out[1] = uint8_t(c0 >> 8);
			out[2] = uint8_t(c1);
			out[3] = uint8_t(c1 >> 8);
			uint32_t bits  = 0;
			int      total = 0;
			for (int i = 0; i < 16; i++) {
				int best = 0;
				if (punch && px[i].c[3] < 128) {
					best = 3;
				} else {
					int best_error = 1 << 30;
					for (int q = 0; q < (four ? 4 : 3); q++) {
						int e = 0;
						for (int k = 0; k < 3; k++) {
							int d = int(px[i].c[k]) - pal[q][k];
							e += d * d;
						}
						if (e < best_error) {
							best_error = e;
							best       = q;
						}
					}
					total += best_error;
				}
				bits |= uint32_t(best) << (2 * i);
			}
			for (int i = 0; i < 4; i++) {
				out[4 + i] = uint8_t(bits >> (8 * i));
			}
			return total;
		}

		// Eight bytes of BC1 color: the two ends of the line the colors lie along (pulled in a little) and 2 bits for each pixel of where
		// between. The ends are then fitted again a few times to the pixels that picked them (least squares), as long as that gets closer.
		void encode_bc1_color(const pixel* px, bool punch, uint8_t* out)
		{
			int lo[3], hi[3];
			if (!line_ends(px, 3, punch, lo, hi)) {
				memset(out, 0, 8);
				memset(out + 4, 0xff, 4); // every pixel is transparent (index 3)
				return;
			}
			for (int k = 0; k < 3; k++) {
				int inset = (hi[k] - lo[k]) / 16;
				lo[k] += inset;
				hi[k] -= inset;
			}
			int best = bc1_try(px, punch, lo, hi, out);
			for (int round = 0; round < 3 && best > 0; round++) {
				// The weight of the first end for each of the four indices.
				static const double weight4[4] = { 1.0, 0.0, 2.0 / 3.0, 1.0 / 3.0 };
				static const double weight3[4] = { 1.0, 0.0, 0.5, 0.0 };
				const double*       weight = punch ? weight3 : weight4;
				uint32_t            bits   = uint32_t(out[4]) | uint32_t(out[5]) << 8 | uint32_t(out[6]) << 16 | uint32_t(out[7]) << 24;
				double              aa = 0, ab = 0, bb = 0, ax[3] = {}, bx[3] = {};
				for (int i = 0; i < 16; i++) {
					int q = (bits >> (2 * i)) & 3;
					if (punch && px[i].c[3] < 128) {
						continue;
					}
					double a = weight[q], b = 1.0 - a;
					aa += a * a;
					ab += a * b;
					bb += b * b;
					for (int k = 0; k < 3; k++) {
						ax[k] += a * px[i].c[k];
						bx[k] += b * px[i].c[k];
					}
				}
				double det = aa * bb - ab * ab;
				if (det < 1e-6) {
					break;
				}
				int nlo[3], nhi[3];
				for (int k = 0; k < 3; k++) {
					nhi[k] = std::clamp(int(std::lround((ax[k] * bb - bx[k] * ab) / det)), 0, 255);
					nlo[k] = std::clamp(int(std::lround((bx[k] * aa - ax[k] * ab) / det)), 0, 255);
				}
				uint8_t trial[8];
				int     e = bc1_try(px, punch, nlo, nhi, trial);
				if (e >= best) {
					break;
				}
				best = e;
				memcpy(out, trial, 8);
			}
		}

		// Eight bytes of a BC4 channel (also the alpha of BC3): the smallest and biggest value, and 3 bits for each pixel of where between.
		void encode_bc4_channel(const pixel* px, int channel, uint8_t* out)
		{
			int lo = 255, hi = 0;
			for (int i = 0; i < 16; i++) {
				lo = std::min<int>(lo, px[i].c[channel]);
				hi = std::max<int>(hi, px[i].c[channel]);
			}
			int pal[8];
			pal[0] = hi;
			pal[1] = lo;
			for (int k = 1; k < 7; k++) {
				pal[1 + k] = ((7 - k) * hi + k * lo + 3) / 7;
			}
			uint64_t bits = uint64_t(uint8_t(hi)) | (uint64_t(uint8_t(lo)) << 8);
			for (int i = 0; i < 16; i++) {
				int best = 0, best_error = 1 << 30;
				for (int p = 0; p < 8; p++) {
					int d = int(px[i].c[channel]) - pal[p];
					if (d * d < best_error) {
						best_error = d * d;
						best       = p;
					}
				}
				bits |= uint64_t(best) << (16 + 3 * i);
			}
			for (int i = 0; i < 8; i++) {
				out[i] = uint8_t(bits >> (8 * i));
			}
		}

		// BC2: 4 bits of alpha for each pixel.
		void encode_bc2_alpha(const pixel* px, uint8_t* out)
		{
			for (int i = 0; i < 8; i++) {
				int a = (px[2 * i].c[3] * 15 + 127) / 255, b = (px[2 * i + 1].c[3] * 15 + 127) / 255;
				out[i] = uint8_t(a | (b << 4));
			}
		}

		struct bit_writer {
			uint8_t* out;
			int      position = 0;
			void     put(uint32_t value, int count)
			{
				for (int i = 0; i < count; i++) {
					if ((value >> i) & 1) {
						out[position >> 3] |= uint8_t(1 << (position & 7));
					}
					position++;
				}
			}
		};

