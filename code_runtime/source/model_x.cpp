// Loading DirectX .x files into a model (see model_internal.hpp), which b3d.cpp turns into entities.
//
// A .x file has three kinds: text, binary, and compressed (text or binary, in MSZip blocks). All three are a list of tokens, so one
// reader gives the same tokens for each of them, and the rest does not care which one it is. The tokens make up templates (what an
// object looks like) and objects (data that fills a template, and the objects below it). The templates of Direct3D are known
// from the start, and the ones in the file are added to them.
//
// The model is made as the original Blitz3D does it: each frame is a node, the meshes of a frame are put into the node as they are,
// triangles with the same material share a surface, and only the animation keys of the frames are used (there are no bones, a mesh
// moves with its frame). LoaderMatrix is applied to the vertices, normals, frames and keys.

