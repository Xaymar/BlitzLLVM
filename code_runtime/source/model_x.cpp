	struct parser {
		lexer                 lex;
		buffer<template_info*> templates;
		buffer<object*>       roots;

		~parser()
		{
			for (uint32_t i = 0; i < templates.size; i++) {
				template_info* t = templates[i];
				free(t->name);
				for (uint32_t j = 0; j < t->members.size; j++) {
					free(t->members[j].type);
					free(t->members[j].name);
					for (int k = 0; k < t->members[j].dims; k++) {
						free(t->members[j].dim[k].name);
					}
				}
				t->members.release();
				delete t;
			}
			templates.release();
			for (uint32_t i = 0; i < roots.size; i++) {
				release_object(roots[i]);
			}
			roots.release();
		}

		template_info* find_template(const char* name)
		{
			for (uint32_t i = templates.size; i > 0; i--) {
				if (same_name(templates[i - 1]->name, name)) {
					return templates[i - 1];
				}
			}
			return nullptr;
		}

		// After the word template: the name, and everything between the braces.
		bool read_template()
		{
			token name = lex.next();
			if ((name.type != t_name) || !is_punct(lex.next(), '{')) {
				return false;
			}
			if (lex.peek().type == t_guid) {
				lex.next();
			}
			template_info* t = new template_info();
			t->name          = copy_token(name);
			for (;;) {
				token w = lex.next();
				if (is_punct(w, '}')) {
					break;
				}
				if (is_punct(w, '[')) { // Which objects can be below this one, which does not matter here.
					for (token s = lex.next(); !is_punct(s, ']'); s = lex.next()) {
						if (s.type == t_end) {
							templates.push(t);
							return false;
						}
					}
					continue;
				}
				if (w.type != t_name) {
					templates.push(t);
					return false;
				}
				member m;
				bool   array = same(w, "array");
				if (array) {
					w = lex.next();
					if (w.type != t_name) {
						templates.push(t);
						return false;
					}
				}
				if (same(w, "STRING") || same(w, "LPSTR") || same(w, "CSTRING") || same(w, "UNICODE")) {
					m.kind = k_string;
				} else if (same(w, "WORD") || same(w, "DWORD") || same(w, "FLOAT") || same(w, "DOUBLE") || same(w, "CHAR") || same(w, "UCHAR") || same(w, "BYTE") || same(w, "SWORD") || same(w, "SDWORD")) {
					m.kind = k_number;
				} else {
					m.kind = k_template;
					m.type = copy_token(w);
				}
				token field = lex.next();
				if (field.type != t_name) {
					free(m.type);
					templates.push(t);
					return false;
				}
				m.name = copy_token(field);
				t->members.push(m); // From here the template owns the member, also if the rest of the file is damaged.
				member& added = t->members[t->members.size - 1];
				while (array && lex.bracket_follows() && (added.dims < 4)) {
					lex.next(); // The bracket
					token size = lex.next();
					if (size.type == t_int) {
						added.dim[added.dims].fixed = int(size.number);
					} else if (size.type == t_name) {
						added.dim[added.dims].name = copy_token(size);
					} else {
						templates.push(t);
						return false;
					}
					added.dims++;
					if (!is_punct(lex.next(), ']')) {
						templates.push(t);
						return false;
					}
				}
			}
			templates.push(t);
			return !lex.failed;
		}

		bool read_members(template_info* t, object& o, int depth)
		{
			if (depth > 16) {
				return false;
			}
			buffer<double> values; // The last number of each member, for the ones that say how many there are.
			for (uint32_t i = 0; i < t->members.size; i++) {
				values.push(0);
			}
			bool ok = true;
			for (uint32_t i = 0; ok && (i < t->members.size); i++) {
				member const& m     = t->members[i];
				double        total = 1;
				for (int d = 0; d < m.dims; d++) {
					double count = m.dim[d].fixed;
					if (m.dim[d].name) {
						count = -1;
						for (uint32_t j = 0; j < i; j++) {
							if (!strcmp(t->members[j].name, m.dim[d].name)) {
								count = values[j];
							}
						}
					}
					if ((count < 0) || (count > double(lex.n))) {
						ok = false;
						break;
					}
					total *= count;
				}
				if (!ok || (total > double(lex.n))) {
					ok = false;
					break;
				}
				for (uint32_t e = 0; ok && (e < uint32_t(total)); e++) {
					if (m.kind == k_number) {
						token v = lex.next();
						if ((v.type != t_int) && (v.type != t_float)) {
							ok = false;
							break;
						}
						o.numbers.push(v.number);
						values[i] = v.number;
					} else if (m.kind == k_string) {
						token v = lex.next();
						if (v.type != t_string) {
							ok = false;
							break;
						}
						o.strings.push(copy_token(v));
					} else {
						template_info* sub = find_template(m.type);
						ok                 = sub && read_members(sub, o, depth + 1);
					}
				}
			}
			values.release();
			return ok && !lex.failed;
		}

		// Skips to the end of the braces that were opened, for objects that have no template.
		bool skip_block()
		{
			for (int depth = 1; depth > 0;) {
				token t = lex.next();
				if (t.type == t_end) {
					return false;
				}
				if (is_punct(t, '{')) {
					depth++;
				} else if (is_punct(t, '}')) {
					depth--;
				}
			}
			return true;
		}

		// An object that starts after its type (which is the token that was given). Null if the file is damaged.
		object* read_object(token const& type, int depth)
		{
			if (depth > 64) {
				return nullptr;
			}
			object* o = new object();
			o->type   = copy_token(type);
			token t   = lex.next();
			if ((t.type == t_name) || (t.type == t_int) || (t.type == t_float)) {
				o->name = copy_token(t);
				t       = lex.next();
			}
			if (!is_punct(t, '{')) {
				release_object(o);
				return nullptr;
			}
			if (lex.peek().type == t_guid) {
				lex.next();
			}
			template_info* info = find_template(o->type);
			if (!info) {
				if (!skip_block()) {
					release_object(o);
					return nullptr;
				}
				free(o->type);
				o->type = nullptr; // Not something that is known.
				return o;
			}
			if (!read_members(info, *o, 0)) {
				release_object(o);
				return nullptr;
			}
			for (;;) {
				token c = lex.next();
				if (is_punct(c, '}')) {
					break;
				}
				object* child = nullptr;
				if (is_punct(c, '{')) {
					token name = lex.next();
					if ((name.type != t_name) && (name.type != t_int) && (name.type != t_float)) {
						release_object(o);
						return nullptr;
					}
					if (lex.peek().type == t_guid) {
						lex.next();
					}
					if (!is_punct(lex.next(), '}')) {
						release_object(o);
						return nullptr;
					}
					child            = new object();
					child->reference = true;
					child->name      = copy_token(name);
				} else if (c.type == t_name) {
					child = read_object(c, depth + 1);
				}
				if (!child) {
					release_object(o);
					return nullptr;
				}
				o->children.push(child);
			}
			return o;
		}

		// Reads everything. False if there was nothing to read; a file that is damaged after some objects keeps those objects.
		bool read_all(bool& damaged)
		{
			damaged = false;
			for (;;) {
				token t = lex.next();
				if (t.type == t_end) {
					break;
				}
				if (is_punct(t, '}')) {
					continue; // Some exporters close one object too many.
				}
				if (t.type != t_name) {
					damaged = true;
					break;
				}
				if (same(t, "template")) {
					if (!read_template()) {
						damaged = true;
						break;
					}
					continue;
				}
				object* o = read_object(t, 0);
				if (!o) {
					damaged = true;
					break;
				}
				if (o->type) {
					roots.push(o);
				} else {
					release_object(o);
				}
			}
			return roots.size > 0;
		}
	};

