	enum member_kind {
		k_number,
		k_string,
		k_template,
	};

	struct dimension {
		int   fixed = 0;
		char* name  = nullptr; // Another member that says how many.
	};

	struct member {
		int       kind = k_number;
		char*     type = nullptr; // Of a member that is a template.
		char*     name = nullptr;
		int       dims = 0;
		dimension dim[4];
	};

	struct template_info {
		char*          name = nullptr;
		buffer<member> members;
	};

	// What an object has: all numbers in order (arrays and templates inside templates are flattened), all strings, and the objects
	// below it. A reference to an object is such an object with only a name.
	struct object {
		char*            type = nullptr;
		char*            name = nullptr;
		bool             reference = false;
		buffer<double>   numbers;
		buffer<char*>    strings;
		buffer<object*>  children;
	};

	void release_object(object* o)
	{
		free(o->type);
		free(o->name);
		o->numbers.release();
		for (uint32_t i = 0; i < o->strings.size; i++) {
			free(o->strings[i]);
		}
		o->strings.release();
		for (uint32_t i = 0; i < o->children.size; i++) {
			release_object(o->children[i]);
		}
		o->children.release();
		delete o;
	}

