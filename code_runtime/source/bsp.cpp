// A level from a file. 0 if the file is not a level of Quake 3. The textures are looked for next to the file, and in
// the folders above it.
int32_t bb_load_bsp(const char* file, float gamma, int32_t parent)
{
	(void)gamma; // It is for the lightmaps, which are not used.
	if (parent && !get_entity(parent)) {
		bb_runtime_error("LoadBSP: the parent does not exist.");
	}
	FILE* f = file ? fopen(file, "rb") : nullptr;
	if (!f) {
		return 0;
	}
	fseek(f, 0, SEEK_END);
	long size = ftell(f);
	fseek(f, 0, SEEK_SET);
	if ((size < long(sizeof(header))) || (size > 512L * 1024 * 1024)) {
		fclose(f);
		return 0;
	}
	uint8_t* data = static_cast<uint8_t*>(malloc(size_t(size)));
	if (fread(data, 1, size_t(size), f) != size_t(size)) {
		free(data);
		fclose(f);
		return 0;
	}
	fclose(f);

	header const& h = *reinterpret_cast<header const*>(data);
	if ((h.magic != 0x50534249u) || (h.version != 46)) {
		free(data);
		return 0;
	}
	for (int i = 0; i < 17; i++) {
		if (!in_file(h.lumps[i], size_t(size))) {
			free(data);
			return 0;
		}
	}
	const texture_info* textures  = reinterpret_cast<const texture_info*>(data + h.lumps[LUMP_TEXTURES].offset);
	const level_vertex* vertices  = reinterpret_cast<const level_vertex*>(data + h.lumps[LUMP_VERTICES].offset);
	const int*          meshverts = reinterpret_cast<const int*>(data + h.lumps[LUMP_MESHVERTS].offset);
	const level_face*   faces     = reinterpret_cast<const level_face*>(data + h.lumps[LUMP_FACES].offset);
	int                 texture_count  = h.lumps[LUMP_TEXTURES].length / int(sizeof(texture_info));
	int                 vertex_count   = h.lumps[LUMP_VERTICES].length / int(sizeof(level_vertex));
	int                 meshvert_count = h.lumps[LUMP_MESHVERTS].length / int(sizeof(int));
	int                 face_count     = h.lumps[LUMP_FACES].length / int(sizeof(level_face));

	// Where the level is, for finding the textures.
	char* directory = static_cast<char*>(malloc(strlen(file) + 1));
	strcpy(directory, file);
	char* slash = strrchr(directory, '/');
	char* back  = strrchr(directory, '\\');
	slash       = (back && (!slash || back > slash)) ? back : slash;
	if (slash) {
		slash[1] = 0;
	} else {
		directory[0] = 0;
	}

	int      handle = create_entity(MESH, parent);
	entity*  e      = get_entity(handle);
	e->cls          = "BSP";
	e->fx           = 1 | 2; // It is lit by the colors of its vertices.
	surface** surface_of_texture = static_cast<surface**>(calloc(size_t(texture_count > 0 ? texture_count : 1) + 1, sizeof(surface*)));
	int*      handle_of_texture  = static_cast<int*>(calloc(size_t(texture_count > 0 ? texture_count : 1) + 1, sizeof(int)));
	bool*     tried              = static_cast<bool*>(calloc(size_t(texture_count > 0 ? texture_count : 1) + 1, sizeof(bool)));
	surface*  untextured         = nullptr;

	for (int k = 0; k < face_count; k++) {
		level_face const& face = faces[k];
		if (face.type == 1 || face.type == 3) {
			if (!face.meshverts || (face.meshverts % 3)) {
				continue;
			}
		} else if (face.type != 2) {
			continue;
		}
		if ((face.vertex < 0) || (face.vertices < 0) || (face.vertex > vertex_count) || (face.vertices > vertex_count - face.vertex)) {
			continue;
		}
		if (face.texture >= texture_count) {
			continue;
		}
		if (face.texture >= 0) {
			texture_info const& tex = textures[face.texture];
			if (!(tex.contents & 1) || (tex.flags & 0x84)) {
				continue; // Not solid, or not drawn (the sky, or hidden).
			}
		}

		surface** slot = face.texture >= 0 ? &surface_of_texture[face.texture] : &untextured;
		if (!*slot) {
			*slot = create_surface(handle);
			if (face.texture >= 0) {
				if (!tried[face.texture]) {
					tried[face.texture] = true;
					char name[65];
					memcpy(name, textures[face.texture].name, 64);
					name[64] = 0;
					handle_of_texture[face.texture] = find_texture(directory, name);
				}
				if (handle_of_texture[face.texture]) {
					(*slot)->painted       = true;
					(*slot)->paint.texture = handle_of_texture[face.texture];
				}
			}
		}
		surface& s    = **slot;
		uint32_t base = s.vertices.size;

		if (face.type == 2) {
			// A curved face: 3x3 control points for every piece, cut into many triangles.
			int px = face.patch_size[0], py = face.patch_size[1];
			if ((px < 3) || (py < 3) || (px > 33) || (py > 33) || (px % 2 == 0) || (py % 2 == 0) || (px * py != face.vertices)) {
				continue;
			}
			int step = 1 << tessellation;
			int sx = (px - 1) * step + 1, sy = (py - 1) * step + 1;
			blend_vertex* grid = static_cast<blend_vertex*>(calloc(size_t(sx) * size_t(sy), sizeof(blend_vertex)));
			const level_vertex* control = vertices + face.vertex;
			for (int y = 0; y < sy; y += step) {
				for (int x = 0; x < sx; x += step) {
					grid[y * sx + x] = to_blend(*control++);
				}
			}
			for (int y = 0; y < sy; y += step) {
				for (int x = 0; x < sx - 1; x += step * 2) {
					subdivide(grid, tessellation, y * sx + x, step);
				}
			}
			for (int x = 0; x < sx; x++) {
				for (int y = 0; y < sy - 1; y += step * 2) {
					subdivide(grid, tessellation, y * sx + x, sx * step);
				}
			}
			for (int i = 0; i < sx * sy; i++) {
				add_vertex(s, grid[i]);
			}
			for (int y = 0; y < sy - 1; y++) {
				uint32_t n = base + uint32_t(y * sx);
				for (int x = 0; x < sx - 1; x++, n++) {
					s.indices.push(n);
					s.indices.push(n + uint32_t(sx));
					s.indices.push(n + 1);
					s.indices.push(n + uint32_t(sx) + 1);
					s.indices.push(n + 1);
					s.indices.push(n + uint32_t(sx));
				}
			}
			free(grid);
		} else {
			if ((face.meshvert < 0) || (face.meshvert > meshvert_count) || (face.meshverts > meshvert_count - face.meshvert)) {
				continue;
			}
			bool valid = true;
			for (int j = 0; j < face.meshverts; j++) {
				if ((meshverts[face.meshvert + j] < 0) || (meshverts[face.meshvert + j] >= face.vertices)) {
					valid = false;
				}
			}
			if (!valid) {
				continue;
			}
			for (int j = 0; j < face.vertices; j++) {
				add_vertex(s, to_blend(vertices[face.vertex + j]));
			}
			for (int j = 0; j < face.meshverts; j++) {
				s.indices.push(base + uint32_t(meshverts[face.meshvert + j]));
			}
		}
		s.dirty       = true;
		s.bound_valid = false;
	}

	free(surface_of_texture);
	free(handle_of_texture);
	free(tried);
	free(directory);
	free(data);
	return handle;
}

static void need_bsp(int32_t handle, const char* what)
{
	entity* e = get_entity(handle);
	if (!e || !e->cls || strcmp(e->cls, "BSP") != 0) {
		char message[96];
		snprintf(message, sizeof(message), "%s: the entity is not a BSP model.", what);
		bb_runtime_error(message);
	}
}

// Whether the lightmaps are used. They never are: the colors of the vertices light the level.
void bb_bsp_lighting(int32_t handle, int32_t lightmaps)
{
	(void)lightmaps;
	need_bsp(handle, "BSPLighting");
}

// How bright the level is without light, as colors of 0 to 255.
void bb_bsp_ambient_light(int32_t handle, float r, float g, float b)
{
	need_bsp(handle, "BSPAmbientLight");
	entity* e = get_entity(handle);
	e->color[0] = (r < 0 ? 0 : (r > 255 ? 255 : r)) / 255.0f;
	e->color[1] = (g < 0 ? 0 : (g > 255 ? 255 : g)) / 255.0f;
	e->color[2] = (b < 0 ? 0 : (b > 255 ? 255 : b)) / 255.0f;
}
