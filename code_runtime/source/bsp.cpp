// Levels of Quake 3 (.bsp): the faces of the level become the surfaces of a mesh, one for each texture and lightmap. Curved
// faces are made of triangles. A face that has a lightmap is drawn with it as a second layer that multiplies the texture
// once, as the original does, and the other faces are lit by the colors of their vertices. The visibility data is not used: all of the level is drawn.

