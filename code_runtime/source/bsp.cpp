#pragma pack(push, 1)
	struct lump {
		int offset, length;
	};
	struct header {
		unsigned magic;
		int      version;
		lump     lumps[17];
	};
	struct texture_info {
		char name[64];
		int  flags, contents;
	};
	struct level_vertex {
		float         coordinates[3];
		float         texture_coordinates[4];
		float         normal[3];
		unsigned char color[4];
	};
	struct level_face {
		int   texture, effect, type, vertex, vertices, meshvert, meshverts, lightmap;
		int   lightmap_start[2], lightmap_size[2];
		float lightmap_origin[3], lightmap_vectors[6], normal[3];
		int   patch_size[2];
	};
#pragma pack(pop)

	enum {
		LUMP_ENTITIES = 0,
		LUMP_TEXTURES = 1,
		LUMP_VERTICES = 10,
		LUMP_MESHVERTS = 11,
		LUMP_FACES = 13,
		LUMP_LIGHTMAPS = 14,
	};

	constexpr int lightmap_size = 128; // Every lightmap of a level is this many pixels wide and high, 3 bytes each.
	constexpr int lightmap_flags = 1 | 16 | 32 | 0x10000; // Color, not repeated, and read with the second texture coordinates.
	constexpr int lightmap_blend = 2;                     // Multiplies, like the original.

	constexpr int tessellation = 2; // How many times a segment of a curved face is cut in two.

	// A vertex, as numbers that can be averaged.
	struct blend_vertex {
		float v[14]; // coordinates 3, texture coordinates 4, normal 3, color 4
	};

	blend_vertex to_blend(level_vertex const& in)
	{
		blend_vertex b;
		memcpy(b.v, in.coordinates, 3 * sizeof(float));
		memcpy(b.v + 3, in.texture_coordinates, 4 * sizeof(float));
		memcpy(b.v + 7, in.normal, 3 * sizeof(float));
		for (int i = 0; i < 4; i++) {
			b.v[10 + i] = float(in.color[i]);
		}
		return b;
	}

	blend_vertex average(blend_vertex const& a, blend_vertex const& b)
	{
		blend_vertex out;
		for (int i = 0; i < 14; i++) {
			out.v[i] = (a.v[i] + b.v[i]) * 0.5f;
		}
		return out;
	}

	// Cuts a row of control points of a curved face into more, along the curve that they make.
	void subdivide(blend_vertex* verts, int level, int index, int step)
	{
		if (!level) {
			blend_vertex t1 = average(verts[index], verts[index + step]);
			blend_vertex t2 = average(verts[index + step], verts[index + step * 2]);
			verts[index + step] = average(t1, t2);
			return;
		}
		verts[index + step / 2]        = average(verts[index], verts[index + step]);
		verts[index + step + step / 2] = average(verts[index + step], verts[index + step * 2]);
		verts[index + step]            = average(verts[index + step / 2], verts[index + step + step / 2]);
		subdivide(verts, level - 1, index, step / 2);
		subdivide(verts, level - 1, index + step, step / 2);
	}

	// The coordinates of the level are the ones of Quake: x forward, y left and z up.
	void convert(float const* in, float* out)
	{
		out[0] = -in[1];
		out[1] = in[2];
		out[2] = in[0];
	}

	void add_vertex(surface& s, blend_vertex const& b)
	{
		vertex3d v = {};
		float    coordinates[3] = { b.v[0], b.v[1], b.v[2] }, normal[3] = { b.v[7], b.v[8], b.v[9] };
		float    c[3], n[3];
		convert(coordinates, c);
		convert(normal, n);
		v.x = c[0];
		v.y = c[1];
		v.z = c[2];
		v.nx = n[0];
		v.ny = n[1];
		v.nz = n[2];
		v.u  = b.v[3];
		v.v  = b.v[4];
		v.u2 = b.v[5]; // Where the lightmap is.
		v.v2 = b.v[6];
		v.r  = float_to_half(b.v[10] / 255.0f);
		v.g  = float_to_half(b.v[11] / 255.0f);
		v.b  = float_to_half(b.v[12] / 255.0f);
		v.a  = half_one;
		s.vertices.push(v);
	}

	// The texture of one lightmap of the level, with the gamma of LoadBSP applied.
	int make_lightmap(const uint8_t* rgb, float gamma)
	{
		uint8_t* pixels = static_cast<uint8_t*>(bb_malloc(size_t(lightmap_size) * lightmap_size * 4));
		uint8_t  curve[256];
		float    power = 1.0f - (gamma < 0 ? 0.0f : (gamma > 1 ? 1.0f : gamma)); // Each value is raised to 1 - gamma, as in the original.
		for (int i = 0; i < 256; i++) {
			curve[i] = uint8_t(255.0f * powf(float(i) / 255.0f, power) + 0.5f);
		}
		for (int i = 0; i < lightmap_size * lightmap_size; i++) {
			pixels[i * 4 + 0] = curve[rgb[i * 3 + 0]];
			pixels[i * 4 + 1] = curve[rgb[i * 3 + 1]];
			pixels[i * 4 + 2] = curve[rgb[i * 3 + 2]];
			pixels[i * 4 + 3] = 255;
		}
		int texture = bb_texture_from_rgba(lightmap_size, lightmap_size, lightmap_flags, lightmap_blend, pixels);
		bb_free(pixels);
		return texture;
	}

	bool in_file(lump const& l, size_t size)
	{
		return (l.offset >= 0) && (l.length >= 0) && (size_t(l.offset) + size_t(l.length) <= size);
	}

	bool exists(const char* path)
	{
		FILE* f = fopen(bb_native_path(path), "rb");
		if (f) {
			fclose(f);
			return true;
		}
		return false;
	}

	// The texture of a name in the level, looked for next to the level and in the folders above it.
	int find_texture(const char* directory, const char* name)
	{
		static const char* extensions[] = { ".tga", ".jpg", ".png", ".dds" };
		size_t             length       = strlen(directory) + strlen(name) + 64;
		char*              path         = static_cast<char*>(bb_malloc(length));
		char*              up           = static_cast<char*>(bb_malloc(length));
		int                texture      = 0;
		strcpy(up, directory);
		for (int depth = 0; depth < 4 && !texture; depth++) {
			for (const char* extension : extensions) {
				snprintf(path, length, "%s%s%s", up, name, extension);
				if (exists(path)) {
					offscreen_hold hold;
					texture = bb_load_texture(path, 1);
					if (texture) {
						break;
					}
				}
			}
			strcat(up, "../");
		}
		bb_free(path);
		bb_free(up);
		return texture;
	}

	// Reads the next quoted string of the entities lump into out. Returns false at the end.
	bool next_quoted(const char*& p, const char* end, char* out, size_t capacity)
	{
		while (p < end && *p != '"') {
			p++;
		}
		if (p >= end) {
			return false;
		}
		p++;
		size_t n = 0;
		while (p < end && *p != '"') {
			if (n + 1 < capacity) {
				out[n++] = *p;
			}
			p++;
		}
		out[n] = 0;
		if (p < end) {
			p++;
		}
		return true;
	}

	// The light entities of a level become point lights that are children of the level, at the place that the map says. The
	// level itself is not lit by them while its lightmaps are used, as the lightmaps already hold their light.
	int make_lights(int level, const char* text, size_t length)
	{
		int         count = 0;
		const char* p     = text;
		const char* end   = text + length;
		char        key[64], value[256];
		float       origin[3] = {}, color[3] = { 1, 1, 1 }, intensity = 300;
		bool        is_light = false, has_origin = false, has_target = false;
		while (p < end) {
			while (p < end && *p != '{' && *p != '}') {
				p++;
			}
			if (p >= end) {
				break;
			}
			if (*p == '}') {
				p++;
				continue;
			}
			p++;
			origin[0] = origin[1] = origin[2] = 0;
			color[0] = color[1] = color[2] = 1;
			intensity  = 300;
			is_light   = has_origin = has_target = false;
			// Pairs of key and value until the closing brace.
			while (true) {
				const char* q = p;
				while (q < end && *q != '"' && *q != '}') {
					q++;
				}
				if (q >= end || *q == '}') {
					p = q;
					break;
				}
				p = q;
				if (!next_quoted(p, end, key, sizeof(key)) || !next_quoted(p, end, value, sizeof(value))) {
					break;
				}
				if (!strcmp(key, "classname")) {
					is_light = !strcmp(value, "light");
				} else if (!strcmp(key, "origin")) {
					has_origin = sscanf(value, "%f %f %f", &origin[0], &origin[1], &origin[2]) == 3;
				} else if (!strcmp(key, "light") || !strcmp(key, "_light")) {
					float f = 0;
					if (sscanf(value, "%f", &f) == 1) {
						intensity = f;
					}
				} else if (!strcmp(key, "_color") || !strcmp(key, "color")) {
					float c[3];
					if (sscanf(value, "%f %f %f", &c[0], &c[1], &c[2]) == 3) {
						// The colors of a map are 0 to 1.
						for (int i = 0; i < 3; i++) {
							color[i] = c[i] < 0 ? 0 : (c[i] > 1 ? 1 : c[i]);
						}
					}
				} else if (!strcmp(key, "target")) {
					has_target = true;
				}
			}
			(void)has_target; // A light with a target is a spot light in the map; it is a point light here.
			if (!is_light || !has_origin || intensity <= 0) {
				continue;
			}
			int light = bb_create_light(2, level);
			float converted[3];
			convert(origin, converted);
			bb_position_entity(light, converted[0], converted[1], converted[2], 0);
			bb_light_color(light, color[0] * 255.0f, color[1] * 255.0f, color[2] * 255.0f);
			bb_light_range(light, intensity);
			count++;
		}
		return count;
	}
