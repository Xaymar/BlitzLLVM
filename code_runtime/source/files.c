#if !defined(_WIN32)
#include <dirent.h>
#include <strings.h>
#include <unistd.h>

// Finds the name in directory that only differs in case, as Windows would. Returns a copy, or NULL.
static char* bb_find_name(const char* directory, const char* name)
{
	DIR* handle = opendir(directory);
	if (!handle) {
		return NULL;
	}
	char* found = NULL;
	for (struct dirent* entry = readdir(handle); entry; entry = readdir(handle)) {
		if (strcasecmp(entry->d_name, name) == 0) {
			found = bb_dup(entry->d_name, strlen(entry->d_name));
			break;
		}
	}
	closedir(handle);
	return found;
}

// Replaces the names in a path that do not exist with the ones that differ only in case, so that LoadImage("Hero.BMP") finds hero.bmp.
// A name that does not exist in any case is kept as it is.
static char* bb_match_case(char* path)
{
	size_t length = strlen(path);
	char*  out    = (char*)bb_malloc(length + 1);
	if (!out) {
		bb_runtime_error("Out of memory.");
	}
	size_t used = 0;
	if (path[0] == '/') {
		out[used++] = '/';
	}
	out[used]  = 0;
	char* next = path;
	while (*next) {
		char* end = strchr(next, '/');
		size_t part = end ? (size_t)(end - next) : strlen(next);
		if (part == 0 || (part == 1 && next[0] == '.')) {
			next += part + (end ? 1 : 0);
			continue; // A doubled separator or ".", which names the same folder.
		}
		char* name = bb_dup(next, part);
		// What is built so far, or the current folder when nothing is.
		char* parent = bb_dup(used ? out : ".", used ? used : 1);
		char* join   = (char*)bb_malloc(used + part + 2);
		if (!join) {
			bb_runtime_error("Out of memory.");
		}
		snprintf(join, used + part + 2, "%s%s%s", out, (used && out[used - 1] != '/') ? "/" : "", name);
		char* replacement = NULL;
		if (!((part == 2) && (name[0] == '.') && (name[1] == '.')) && (access(join, F_OK) != 0)) {
			replacement = bb_find_name(parent, name);
		}
		const char* use = replacement ? replacement : name;
		out = (char*)bb_realloc(out, used + strlen(use) + 2);
		if (!out) {
			bb_runtime_error("Out of memory.");
		}
		if (used && out[used - 1] != '/') {
			out[used++] = '/';
		}
		memcpy(out + used, use, strlen(use) + 1);
		used += strlen(use);
		bb_free(replacement);
		bb_free(join);
		bb_free(parent);
		bb_free(name);
		next += part + (end ? 1 : 0);
		if (end && !*next) {
			out[used++] = '/'; // A folder that was written with a separator at its end.
			out[used]   = 0;
		}
	}
	bb_free(path);
	return out;
}
#endif

// Turns a path from a Blitz program into one for this system. Where names are not found as written, the ones that differ only in case
// are used, as Windows would.
char* bb_path(const char* path)
{
	char* out = bb_dup(bb_s(path), strlen(bb_s(path)));
#if !defined(_WIN32)
	for (char* c = out; *c; c++) {
		if (*c == '\\') {
			*c = '/';
		}
	}
	if (*out && (access(out, F_OK) != 0)) {
		out = bb_match_case(out);
	}
#endif
	return out;
}

////////////////////////////////////////////////////////////////////////////////
// Streams
//
// Files, directories and (see network.c) connections are all handles into this table. Index 0 is never used.
////////////////////////////////////////////////////////////////////////////////
static bb_stream* bb_streams      = NULL;
static int32_t    bb_stream_count = 1;
static int32_t    bb_stream_cap   = 0;

int32_t bb_stream_add(bb_stream stream)
{
	for (int32_t i = 1; i < bb_stream_count; i++) {
		if (bb_streams[i].kind == BB_STREAM_NONE) {
			bb_streams[i] = stream;
			return i;
		}
	}
	if (bb_stream_count >= bb_stream_cap) {
		bb_stream_cap = bb_stream_cap ? bb_stream_cap * 2 : 64;
		bb_streams    = (bb_stream*)bb_realloc(bb_streams, (size_t)bb_stream_cap * sizeof(bb_stream));
		if (!bb_streams) {
			bb_runtime_error("Out of memory.");
		}
	}
	bb_streams[bb_stream_count] = stream;
	return bb_stream_count++;
}

bb_stream* bb_stream_get(int32_t handle, const char* what)
{
	if ((handle <= 0) || (handle >= bb_stream_count) || (bb_streams[handle].kind == BB_STREAM_NONE)) {
		char message[96];
		snprintf(message, sizeof(message), "%s: the file or stream does not exist.", what);
		bb_runtime_error(message);
	}
	return &bb_streams[handle];
}

void bb_stream_remove(int32_t handle)
{
	if ((handle > 0) && (handle < bb_stream_count)) {
		memset(&bb_streams[handle], 0, sizeof(bb_stream));
	}
}

