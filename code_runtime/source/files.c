int32_t bb_open(const char* path, const char* mode)
{
	char* real = bb_path(path);
	FILE* file = fopen(real, mode);
	bb_free(real);
	if (!file) {
		return 0;
	}
	bb_stream stream;
	memset(&stream, 0, sizeof(stream));
	stream.kind = BB_STREAM_FILE;
	stream.file = file;
	return bb_stream_add(stream);
}

int32_t bb_read_file(const char* path)
{
	return bb_open(path, "rb");
}

int32_t bb_write_file(const char* path)
{
	return bb_open(path, "wb");
}

int32_t bb_open_file(const char* path)
{
	return bb_open(path, "r+b"); // Like the original, this does not make a file that is missing.
}

void bb_close_file(int32_t handle)
{
	bb_stream* stream = bb_stream_get(handle, "CloseFile");
	if (stream->kind == BB_STREAM_FILE) {
		fclose(stream->file);
	} else if (stream->close) {
		stream->close(stream);
	}
	bb_stream_remove(handle);
}

FILE* bb_file(int32_t handle, const char* what)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if (stream->kind != BB_STREAM_FILE) {
		char message[96];
		snprintf(message, sizeof(message), "%s: this is not a file.", what);
		bb_runtime_error(message);
	}
	return stream->file;
}

int32_t bb_eof(int32_t handle)
{
	bb_stream* stream = bb_stream_get(handle, "Eof");
	if (stream->kind == BB_STREAM_FILE) {
		int c = fgetc(stream->file);
		if (c == EOF) {
			return 1;
		}
		ungetc(c, stream->file);
		return 0;
	}
	return bb_stream_eof(stream);
}

int32_t bb_file_pos(int32_t handle)
{
	return (int32_t)ftell(bb_file(handle, "FilePos"));
}

int32_t bb_seek_file(int32_t handle, int32_t position)
{
	FILE* file = bb_file(handle, "SeekFile");
	if (fseek(file, position, SEEK_SET) != 0) {
		return -1;
	}
	return (int32_t)ftell(file);
}

// Reads from a stream, returns how many bytes it managed to read.
size_t bb_read_bytes(int32_t handle, void* data, size_t size, const char* what)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if (stream->kind == BB_STREAM_FILE) {
		return fread(data, 1, size, stream->file);
	}
	return bb_stream_read(stream, data, size);
}

void bb_write_bytes(int32_t handle, const void* data, size_t size, const char* what)
{
	bb_stream* stream = bb_stream_get(handle, what);
	if (stream->kind == BB_STREAM_FILE) {
		fwrite(data, 1, size, stream->file);
	} else {
		bb_stream_write(stream, data, size);
	}
}

// Copies from one stream to the other until one of them has nothing more to give or take.
void bb_copy_stream(int32_t source, int32_t destination, int32_t buffer_size)
{
	if ((buffer_size < 1) || (buffer_size > 1024 * 1024)) {
		bb_runtime_error("CopyStream: the buffer size is not valid.");
	}
	bb_stream* target = bb_stream_get(destination, "CopyStream");
	uint8_t*   buffer = (uint8_t*)bb_malloc((size_t)buffer_size);
	if (!buffer) {
		bb_runtime_error("CopyStream: out of memory.");
	}
	// A file that is written to is always "at the end", which does not stop anything. A connection that is gone does.
	while (!bb_eof(source) && ((target->kind == BB_STREAM_FILE) || !bb_eof(destination))) {
		size_t n = bb_read_bytes(source, buffer, (size_t)buffer_size, "CopyStream");
		bb_write_bytes(destination, buffer, n, "CopyStream");
		if (n < (size_t)buffer_size) {
			break;
		}
	}
	bb_free(buffer);
}

int32_t bb_read_byte(int32_t handle)
{
	uint8_t v = 0;
	bb_read_bytes(handle, &v, 1, "ReadByte");
	return v;
}

int32_t bb_read_short(int32_t handle)
{
	uint8_t b[2] = { 0, 0 };
	bb_read_bytes(handle, b, 2, "ReadShort");
	return (int32_t)(b[0] | (b[1] << 8));
}

int32_t bb_read_int(int32_t handle)
{
	uint8_t b[4] = { 0, 0, 0, 0 };
	bb_read_bytes(handle, b, 4, "ReadInt");
	return (int32_t)((uint32_t)b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16) | ((uint32_t)b[3] << 24));
}

float bb_read_float(int32_t handle)
{
	int32_t bits = bb_read_int(handle);
	float   v;
	memcpy(&v, &bits, sizeof(v));
	return v;
}

// A line, without the line break. Both \r\n and \n end a line.
const char* bb_read_line(int32_t handle)
{
	size_t cap = 128, len = 0;
	char*  buffer = (char*)bb_malloc(cap);
	uint8_t c;
	while (bb_read_bytes(handle, &c, 1, "ReadLine") == 1) {
		if (c == '\n') {
			break;
		}
		if (len + 1 >= 16 * 1024 * 1024) {
			break; // A line that never ends, from a stream that never stops.
		}
		if (len + 1 >= cap) {
			cap *= 2;
			buffer = (char*)bb_realloc(buffer, cap);
		}
		buffer[len++] = (char)c;
	}
	if (len && (buffer[len - 1] == '\r')) {
		len--;
	}
	char* result = bb_copy(buffer, len); // A line can contain NUL.
	bb_free(buffer);
	return result;
}

// Strings in files start with their length, as a 32 bit number.
const char* bb_read_string(int32_t handle)
{
	int32_t length = bb_read_int(handle);
	if (length < 0) {
		length = 0;
	}
	// A length that is more than what is there, as in a broken file or from a stranger on the network, is the end.
	bb_stream* stream = bb_stream_get(handle, "ReadString");
	size_t     limit  = 16 * 1024 * 1024;
	if (stream->kind == BB_STREAM_FILE) {
		long here = ftell(stream->file);
		if (here >= 0) {
			fseek(stream->file, 0, SEEK_END);
			long end = ftell(stream->file);
			fseek(stream->file, here, SEEK_SET);
			limit = (end > here) ? (size_t)(end - here) : 0;
		}
	}
	if ((size_t)length > limit) {
		length = (int32_t)limit;
	}
	char*  buffer = bb_alloc((size_t)length);
	size_t got    = bb_read_bytes(handle, buffer, (size_t)length, "ReadString");
	if (got < (size_t)length) {
		char* shorter = bb_copy(buffer, got); // The file ended: what was there is the string.
		bb_str_free(buffer);
		return shorter;
	}
	return buffer;
}

void bb_write_byte(int32_t handle, int32_t value)
{
	uint8_t v = (uint8_t)value;
	bb_write_bytes(handle, &v, 1, "WriteByte");
}

void bb_write_short(int32_t handle, int32_t value)
{
	uint8_t b[2] = { (uint8_t)value, (uint8_t)(value >> 8) };
	bb_write_bytes(handle, b, 2, "WriteShort");
}

void bb_write_int(int32_t handle, int32_t value)
{
	uint8_t b[4] = { (uint8_t)value, (uint8_t)(value >> 8), (uint8_t)(value >> 16), (uint8_t)(value >> 24) };
	bb_write_bytes(handle, b, 4, "WriteInt");
}

void bb_write_float(int32_t handle, float value)
{
	int32_t bits;
	memcpy(&bits, &value, sizeof(bits));
	bb_write_int(handle, bits);
}

void bb_write_line(int32_t handle, const char* text)
{
	bb_write_bytes(handle, bb_s(text), bb_slen(text), "WriteLine");
	bb_write_bytes(handle, "\r\n", 2, "WriteLine");
}

void bb_write_string(int32_t handle, const char* text)
{
	int32_t length = (int32_t)bb_slen(text);
	bb_write_int(handle, length);
	bb_write_bytes(handle, bb_s(text), (size_t)length, "WriteString");
}

int32_t bb_read_avail(int32_t handle)
{
	bb_stream* stream = bb_stream_get(handle, "ReadAvail");
	if (stream->kind == BB_STREAM_FILE) {
		long here = ftell(stream->file);
		fseek(stream->file, 0, SEEK_END);
		long end = ftell(stream->file);
		fseek(stream->file, here, SEEK_SET);
		return (int32_t)(end - here);
	}
	return bb_stream_available(stream);
}

////////////////////////////////////////////////////////////////////////////////

int32_t bb_live_streams(void)
{
	int32_t count = 0;
	for (int32_t i = 1; i < bb_stream_count; i++) {
		count += (bb_streams[i].kind != BB_STREAM_NONE) ? 1 : 0;
	}
	return count;
}
