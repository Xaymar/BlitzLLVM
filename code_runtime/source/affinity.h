// Which CPU the threads of the program prefer. The first CPU the process may use is the one that boosts highest on modern machines, so
// the thread that runs the program (and so the Blitz code, the culling and the recording of the frame) prefers it, and the helper threads
// (the work pool, the loaders, the submission and window threads) prefer the other CPUs, and not the SMT sibling of that CPU.
//
// Windows: a soft hint (SetThreadIdealProcessorEx), the scheduler may still move a thread when its CPU is busy. Default on.
// Linux: there is no soft hint, so the thread is bound with sched_setaffinity. That is inherited by threads made by libraries
// (Jolt, ffmpeg, SDL), which are not told to leave it, so it defaults to off. macOS has no way to ask for a CPU: nothing is done.
// BLITZLLVM_PIN_CORE0=0 turns it off, =1 turns it on. Read once at startup.

/** The thread that runs the program calls this once at startup. */
void bb_affinity_main(void);

/** Every other thread of the runtime calls this first thing: it moves the thread away from the CPU of bb_affinity_main (and its SMT sibling). */
void bb_affinity_helper(unsigned index);

