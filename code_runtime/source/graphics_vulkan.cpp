	void create_device()
	{
		using namespace gfx;
		create_instance();
		if (!create_surface(gfx::surface().window, gfx::surface().surface)) {
			fail(SDL_GetError());
		}
		gfx::create_device(VkSurfaceKHR(gfx::surface().surface));
	}

