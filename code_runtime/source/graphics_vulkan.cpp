	// The layouts that were made, so that equal descriptions share one.
	static std::vector<std::pair<layout_desc, pipeline_layout>> made_layouts;

	pipeline_layout get_layout(layout_desc const& desc)
	{
		for (auto const& entry : made_layouts) {
			if (entry.first == desc) {
				return entry.second;
			}
		}
		VkDescriptorSetLayout sets[5];
		for (uint32_t i = 0; i < desc.set_count; i++) {
			sets[i] = bb::gfx::vk_set_layout(desc.sets[i]);
		}
		VkPushConstantRange range = {};
		range.size                = desc.push_size;
		if (desc.push_stages & stage_vertex) {
			range.stageFlags |= VK_SHADER_STAGE_VERTEX_BIT;
		}
		if (desc.push_stages & stage_fragment) {
			range.stageFlags |= VK_SHADER_STAGE_FRAGMENT_BIT;
		}
		if (desc.push_stages & stage_compute) {
			range.stageFlags |= VK_SHADER_STAGE_COMPUTE_BIT;
		}
		VkPipelineLayoutCreateInfo info = { VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO };
		info.setLayoutCount             = desc.set_count;
		info.pSetLayouts                = sets;
		info.pushConstantRangeCount     = desc.push_size ? 1 : 0;
		info.pPushConstantRanges        = &range;
		VkPipelineLayout layout;
		bb::gfx::check(vkCreatePipelineLayout(bb::gfx::vkd.device, &info, nullptr, &layout), "vkCreatePipelineLayout");
		pipeline_layout made{ uint64_t(layout) };
		made_layouts.push_back({ desc, made });
		return made;
	}

	void destroy_layouts()
	{
		for (auto const& entry : made_layouts) {
			vkDestroyPipelineLayout(bb::gfx::vkd.device, bb::gfx::vk_layout(entry.second), nullptr);
		}
		made_layouts.clear();
		// The layouts of the kinds of group, which vk_set_layout made when they were first asked for.
		for (VkDescriptorSetLayout* layout : { &bb::gfx::kind_layouts.scene, &bb::gfx::kind_layouts.entity, &bb::gfx::kind_layouts.cull, &bb::gfx::kind_layouts.images3, &bb::gfx::kind_layouts.images8 }) {
			if (*layout) {
				vkDestroyDescriptorSetLayout(bb::gfx::vkd.device, *layout, nullptr);
				*layout = VK_NULL_HANDLE;
			}
		}
	}

	void forget_layouts()
	{
		made_layouts.clear();
		bb::gfx::kind_layouts.scene = bb::gfx::kind_layouts.entity = bb::gfx::kind_layouts.cull = bb::gfx::kind_layouts.images3 = bb::gfx::kind_layouts.images8 = VK_NULL_HANDLE;
	}
