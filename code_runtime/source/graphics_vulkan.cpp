	VkFormat vk_format(bb::rhi::format format)
	{
		for (const format_pair& pair : format_pairs) {
			if (pair.neutral == format) {
				return pair.vk;
			}
		}
		return VK_FORMAT_UNDEFINED;
	}

	bb::rhi::format rhi_format(VkFormat format)
	{
		for (const format_pair& pair : format_pairs) {
			if (pair.vk == format) {
				return pair.neutral;
			}
		}
		return bb::rhi::format::undefined;
	}

	static VkComponentSwizzle vk_swizzle(bb::rhi::channel channel)
	{
		switch (channel) {
		case bb::rhi::channel::zero: return VK_COMPONENT_SWIZZLE_ZERO;
		case bb::rhi::channel::one: return VK_COMPONENT_SWIZZLE_ONE;
		case bb::rhi::channel::r: return VK_COMPONENT_SWIZZLE_R;
		case bb::rhi::channel::g: return VK_COMPONENT_SWIZZLE_G;
		case bb::rhi::channel::b: return VK_COMPONENT_SWIZZLE_B;
		case bb::rhi::channel::a: return VK_COMPONENT_SWIZZLE_A;
		default: return VK_COMPONENT_SWIZZLE_IDENTITY;
		}
	}

	gpu_image create_image(uint32_t width, uint32_t height, bb::rhi::image_usage usage, bb::rhi::format format, const bb::rhi::swizzle* components, uint32_t mips, uint32_t layers, uint32_t samples)
	{
		if (vk_format(format) == VK_FORMAT_UNDEFINED) {
			fail("internal error: an image was asked for in a format that is not known");
		}
		VkImageUsageFlags flags = 0;
		flags |= (usage & bb::rhi::image_sampled) ? VK_IMAGE_USAGE_SAMPLED_BIT : 0;
		flags |= (usage & bb::rhi::image_color_target) ? VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT : 0;
		flags |= (usage & bb::rhi::image_depth_target) ? VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT : 0;
		flags |= (usage & bb::rhi::image_copy_source) ? VK_IMAGE_USAGE_TRANSFER_SRC_BIT : 0;
		flags |= (usage & bb::rhi::image_copy_destination) ? VK_IMAGE_USAGE_TRANSFER_DST_BIT : 0;
		VkImageAspectFlags aspect = (format == bb::rhi::format::d32f) ? VK_IMAGE_ASPECT_DEPTH_BIT : VK_IMAGE_ASPECT_COLOR_BIT;
		VkComponentMapping mapping = {};
		if (components) {
			mapping = { vk_swizzle(components->r), vk_swizzle(components->g), vk_swizzle(components->b), vk_swizzle(components->a) };
		}
		return create_image_vk(width, height, flags, vk_format(format), aspect, components ? &mapping : nullptr, mips, layers, samples);
	}

	gpu_image create_image_vk(uint32_t width, uint32_t height, VkImageUsageFlags usage, VkFormat format, VkImageAspectFlags aspect, const VkComponentMapping* components, uint32_t mips, uint32_t layers, uint32_t samples)
	{
		gpu_image img;
		img.format = format;
		img.mips = mips;
		img.layers = layers;
		img.width  = width;
		img.height = height;
		img.recipe         = new image_recipe();
		img.recipe->width  = width;
		img.recipe->height = height;
		img.recipe->mips   = mips;
		img.recipe->layers = layers;
		img.recipe->samples = samples;
		img.recipe->usage  = usage;
		img.recipe->format = format;
		img.recipe->aspect = aspect;
		if (components) {
			img.recipe->mapping     = *components;
			img.recipe->has_mapping = true;
		}

		VkImageCreateInfo info = { VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO };
		info.imageType         = VK_IMAGE_TYPE_2D;
		info.format            = format;
		info.extent            = { width, height, 1 };
		info.mipLevels         = mips;
		info.arrayLayers       = layers;
		info.samples           = VkSampleCountFlagBits(samples);
		info.tiling            = VK_IMAGE_TILING_OPTIMAL;
		info.usage             = usage;
		info.sharingMode       = VK_SHARING_MODE_EXCLUSIVE;
		info.initialLayout     = vk_layout_of(bb::rhi::image_state::undefined);
		// An sRGB image is drawn to and read back through a view that does not convert, so the bytes in it stay as they were written.
		bool srgb_rgba = (format == VK_FORMAT_R8G8B8A8_SRGB);
		if (srgb_rgba) {
			info.flags = VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT;
		}

		img.recipe->may_spill = image_spill_allowed();
		VkResult created = create_image_memory(info, img.image, img.allocation);
		check(created, "vmaCreateImage");
		if (created != VK_SUCCESS) {
			// Only a lost device gets here. The image stays without its GPU objects, and is made again by rebuild_image.
			img.image = VK_NULL_HANDLE;
			img.allocation = VK_NULL_HANDLE;
			return img;
		}

		img.recipe->create_info = info;
		create_views(img, info, aspect, components);
		return img;
	}

	void describe_image(bb::rhi::binding_group set, gpu_image const& img, bb::rhi::sampler sampler)
	{
		write_descriptor(set, img.array_sets && img.array_view ? img.array_view : img.view, sampler);
	}

	VkImageView target_view_of(gpu_image const& img, uint32_t layer)
	{
		if ((layer > 0) && (layer < img.layers) && img.layer_targets) {
			return img.layer_targets[layer];
		}
		return img.target_view ? img.target_view : img.view;
	}

	// Destroys the views of an image, and nothing else.
	static void destroy_views(gpu_image& img)
	{
		for (uint32_t layer = 1; img.layer_targets && (layer < img.layers); layer++) {
			vkDestroyImageView(g.device, img.layer_targets[layer], nullptr);
		}
		bb_free(img.layer_targets);
		img.layer_targets = nullptr;
		if (img.array_view) {
			vkDestroyImageView(g.device, img.array_view, nullptr);
			img.array_view = VK_NULL_HANDLE;
		}
		if (img.view) {
			vkDestroyImageView(g.device, img.view, nullptr);
		}
		if (img.target_view) {
			vkDestroyImageView(g.device, img.target_view, nullptr);
		}
		img.view        = VK_NULL_HANDLE;
		img.target_view = VK_NULL_HANDLE;
	}

	void release_image(gpu_image& img)
	{
		destroy_views(img);
		if (img.image) {
			forget_system_allocation(img.allocation);
			vmaDestroyImage(g.allocator, img.image, img.allocation);
		}
		img.image       = VK_NULL_HANDLE;
		img.allocation  = VK_NULL_HANDLE;
	}

	bool move_image(gpu_image& img, VmaAllocation destination)
	{
		if (!img.image || !img.recipe) {
			return false;
		}
		VkImageCreateInfo info = img.recipe->create_info;
		VkImage           fresh = VK_NULL_HANDLE;
		if ((vkCreateImage(g.device, &info, nullptr, &fresh) != VK_SUCCESS) || (vmaBindImageMemory(g.allocator, destination, fresh) != VK_SUCCESS)) {
			if (fresh) {
				vkDestroyImage(g.device, fresh, nullptr);
			}
			return false;
		}
		if (img.layout != bb::rhi::image_state::undefined) {
			// What the image holds goes over on the GPU: every level and layer.
			begin_commands();
			barrier(img.image, img.layout, bb::rhi::image_state::copy_src, img.recipe->aspect);
			barrier(fresh, bb::rhi::image_state::undefined, bb::rhi::image_state::copy_dst, img.recipe->aspect);
			std::vector<bb::rhi::image_copy> regions(info.mipLevels);
			for (uint32_t level = 0; level < info.mipLevels; level++) {
				regions[level].src.mip    = level;
				regions[level].src.layers = info.arrayLayers;
				regions[level].src.depth  = (img.recipe->aspect & VK_IMAGE_ASPECT_DEPTH_BIT) != 0;
				regions[level].dst        = regions[level].src;
				regions[level].w          = (info.extent.width >> level) ? (info.extent.width >> level) : 1;
				regions[level].h          = (info.extent.height >> level) ? (info.extent.height >> level) : 1;
			}
			bb::rhi::copy_image(uint64_t(img.image), uint64_t(fresh), regions.data(), info.mipLevels);
			barrier(fresh, bb::rhi::image_state::copy_dst, img.layout, img.recipe->aspect);
			submit_commands();
		}
		destroy_views(img);
		vkDestroyImage(g.device, img.image, nullptr); // The allocation stays: the allocator hands the image's handle over to the memory it was moved to.
		img.image = fresh;
		create_views(img, info, img.recipe->aspect, img.recipe->has_mapping ? &img.recipe->mapping : nullptr);
		return true;
	}

	void destroy_image(gpu_image& img)
	{
		release_image(img);
		delete img.recipe;
		img = gpu_image();
	}

