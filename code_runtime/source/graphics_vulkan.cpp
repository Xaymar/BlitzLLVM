	image_entry* image_of(int handle)
	{
		if ((handle < 1) || (uint32_t(handle) > image_table.size) || !image_table[uint32_t(handle) - 1].used) {
			return nullptr;
		}
		return &image_table[uint32_t(handle) - 1];
	}

	// Where the pixels of a frame are in the sheet of its image.
	void frame_position(image_entry const& e, int frame, int& x, int& y)
	{
		int cells = e.sheet_w / (e.frame_w > 0 ? e.frame_w : 1);
		cells     = cells > 0 ? cells : 1;
		int index = e.first + frame;
		x         = (index % cells) * e.frame_w;
		y         = (index / cells) * e.frame_h;
	}

	target_ref resolve_target(int handle)
	{
		target_ref t;
		if ((handle == front_buffer) || (handle == back_buffer)) {
			t.image = &g.buffers[handle == front_buffer ? 0 : 1];
			t.w     = int(t.image->width);
			t.h     = int(t.image->height);
		} else if (handle >= texture_buffer_base) {
			texture_entry* tex = texture_of((handle - texture_buffer_base) >> 10);
			if (tex && tex->set && texture_frame_rect(*tex, (handle - texture_buffer_base) & 1023, t.x, t.y, t.w, t.h)) {
				ensure_color_image(tex->image, tex->set);
				t.image = &tex->image;
			}
		} else if (handle >= image_buffer_base) {
			int          id    = (handle - image_buffer_base) >> 10;
			int          frame = (handle - image_buffer_base) & 1023;
			image_entry* e     = image_of(id);
			if (e && e->set && (frame < e->frames)) {
				ensure_color_image(e->image, e->set);
				t.image = &e->image;
				frame_position(*e, frame, t.x, t.y);
				t.w = e->frame_w;
				t.h = e->frame_h;
			}
		}
		return t;
	}

	[[noreturn]] void fail(const char* what)
	{
		char buffer[256];
		snprintf(buffer, sizeof(buffer), "Graphics: %s", what);
		bb_runtime_error(buffer);
		exit(1);
	}

	void check(VkResult result, const char* what)
	{
		if (result != VK_SUCCESS) {
			char buffer[256];
			snprintf(buffer, sizeof(buffer), "%s failed (VkResult %d).", what, int(result));
			fail(buffer);
		}
	}

	static uint32_t find_memory(uint32_t bits, VkMemoryPropertyFlags wanted)
	{
		for (uint32_t i = 0; i < g.memory.memoryTypeCount; i++) {
			if ((bits & (1u << i)) && ((g.memory.memoryTypes[i].propertyFlags & wanted) == wanted)) {
				return i;
			}
		}
		fail("No suitable GPU memory type found.");
	}

	void create_buffer(VkDeviceSize size, VkBufferUsageFlags usage, VkMemoryPropertyFlags props, VkBuffer& buffer, VkDeviceMemory& memory)
	{
		VkBufferCreateInfo info = { VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO };
		info.size               = size;
		info.usage              = usage;
		info.sharingMode        = VK_SHARING_MODE_EXCLUSIVE;
		check(vkCreateBuffer(g.device, &info, nullptr, &buffer), "vkCreateBuffer");

		VkMemoryRequirements req;
		vkGetBufferMemoryRequirements(g.device, buffer, &req);
		VkMemoryAllocateInfo alloc = { VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO };
		alloc.allocationSize       = req.size;
		alloc.memoryTypeIndex      = find_memory(req.memoryTypeBits, props);
		check(vkAllocateMemory(g.device, &alloc, nullptr, &memory), "vkAllocateMemory");
		check(vkBindBufferMemory(g.device, buffer, memory, 0), "vkBindBufferMemory");
	}

	gpu_image create_image(uint32_t width, uint32_t height, VkImageUsageFlags usage, VkFormat format, VkImageAspectFlags aspect, const VkComponentMapping* components)
	{
		gpu_image img;
		img.width  = width;
		img.height = height;

		VkImageCreateInfo info = { VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO };
		info.imageType         = VK_IMAGE_TYPE_2D;
		info.format            = format;
		info.extent            = { width, height, 1 };
		info.mipLevels         = 1;
		info.arrayLayers       = 1;
		info.samples           = VK_SAMPLE_COUNT_1_BIT;
		info.tiling            = VK_IMAGE_TILING_OPTIMAL;
		info.usage             = usage;
		info.sharingMode       = VK_SHARING_MODE_EXCLUSIVE;
		info.initialLayout     = VK_IMAGE_LAYOUT_UNDEFINED;
		check(vkCreateImage(g.device, &info, nullptr, &img.image), "vkCreateImage");

		VkMemoryRequirements req;
		vkGetImageMemoryRequirements(g.device, img.image, &req);
		VkMemoryAllocateInfo alloc = { VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO };
		alloc.allocationSize       = req.size;
		alloc.memoryTypeIndex      = find_memory(req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
		check(vkAllocateMemory(g.device, &alloc, nullptr, &img.memory), "vkAllocateMemory");
		check(vkBindImageMemory(g.device, img.image, img.memory, 0), "vkBindImageMemory");

		VkImageViewCreateInfo view         = { VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO };
		view.image                         = img.image;
		view.viewType                      = VK_IMAGE_VIEW_TYPE_2D;
		view.format                        = info.format;
		if (components) {
			view.components = *components;
		}
		view.subresourceRange.aspectMask   = aspect;
		view.subresourceRange.levelCount   = 1;
		view.subresourceRange.layerCount   = 1;
		check(vkCreateImageView(g.device, &view, nullptr, &img.view), "vkCreateImageView");
		return img;
	}

	void destroy_image(gpu_image& img)
	{
		if (img.view) {
			vkDestroyImageView(g.device, img.view, nullptr);
		}
		if (img.image) {
			vkDestroyImage(g.device, img.image, nullptr);
		}
		if (img.memory) {
			vkFreeMemory(g.device, img.memory, nullptr);
		}
		img = gpu_image();
	}

