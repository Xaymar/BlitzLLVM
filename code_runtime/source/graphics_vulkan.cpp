	{
		char buffer[256];
		snprintf(buffer, sizeof(buffer), "Graphics: %s", what);
		bb_runtime_error(buffer);
		exit(1);
	}

	void check(VkResult result, const char* what)
	{
		if (result != VK_SUCCESS) {
			char buffer[256];
			snprintf(buffer, sizeof(buffer), "%s failed (VkResult %d).", what, int(result));
			fail(buffer);
		}
	}

	gpu_image create_image(uint32_t width, uint32_t height, VkImageUsageFlags usage, VkFormat format, VkImageAspectFlags aspect, const VkComponentMapping* components, uint32_t mips)
	{
		gpu_image img;
		img.format = format;
		img.mips = mips;
		img.width  = width;
		img.height = height;
		// Dither 2 blends in the shader, which reads what it draws to.
		if (g.can_blend_dither && (usage & VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT)) {
			usage |= VK_IMAGE_USAGE_INPUT_ATTACHMENT_BIT;
		}
		if (g.can_interlock && (usage & VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT) && (format == VK_FORMAT_R8G8B8A8_UNORM)) {
			usage |= VK_IMAGE_USAGE_STORAGE_BIT;
		}

		VkImageCreateInfo info = { VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO };
		info.imageType         = VK_IMAGE_TYPE_2D;
		info.format            = format;
		info.extent            = { width, height, 1 };
		info.mipLevels         = mips;
		info.arrayLayers       = 1;
		info.samples           = VK_SAMPLE_COUNT_1_BIT;
		info.tiling            = VK_IMAGE_TILING_OPTIMAL;
		info.usage             = usage;
		info.sharingMode       = VK_SHARING_MODE_EXCLUSIVE;
		info.initialLayout     = VK_IMAGE_LAYOUT_UNDEFINED;
		// An sRGB image is drawn to and read back through a view that does not convert, so the bytes in it stay as they were written.
		bool srgb_rgba = (format == VK_FORMAT_R8G8B8A8_SRGB);
		if (srgb_rgba) {
			info.flags = VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT;
		}

		VmaAllocationCreateInfo alloc = {};
		alloc.usage                   = VMA_MEMORY_USAGE_AUTO;
		alloc.requiredFlags           = VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT;
		check(vmaCreateImage(g.allocator, &info, &alloc, &img.image, &img.allocation, nullptr), "vmaCreateImage");

		VkImageViewCreateInfo view         = { VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO };
		view.image                         = img.image;
		view.viewType                      = VK_IMAGE_VIEW_TYPE_2D;
		view.format                        = info.format;
		if (components) {
			view.components = *components;
		}
		view.subresourceRange.aspectMask   = aspect;
		view.subresourceRange.levelCount   = mips;
		view.subresourceRange.layerCount   = 1;
		check(vkCreateImageView(g.device, &view, nullptr, &img.view), "vkCreateImageView");
		if ((mips > 1) || srgb_rgba) {
			// An attachment has one level, so drawing to the texture goes through a view of the first.
			view.subresourceRange.levelCount = 1;
			if (srgb_rgba) {
				view.format = VK_FORMAT_R8G8B8A8_UNORM;
			}
			check(vkCreateImageView(g.device, &view, nullptr, &img.target_view), "vkCreateImageView");
		}
		return img;
	}

	void destroy_image(gpu_image& img)
	{
		if (img.view) {
			vkDestroyImageView(g.device, img.view, nullptr);
		}
		if (img.target_view) {
			vkDestroyImageView(g.device, img.target_view, nullptr);
		}
		if (img.image) {
			vmaDestroyImage(g.allocator, img.image, img.allocation);
		}
		img = gpu_image();
	}

