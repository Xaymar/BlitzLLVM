	image_entry* image_of(int handle)
	{
		if ((handle < 1) || (uint32_t(handle) > image_table.size) || !image_table[uint32_t(handle) - 1].used) {
			return nullptr;
		}
		image_entry* e = &image_table[uint32_t(handle) - 1];
		if (e->pending) {
			resolve_image(*e);
		}
		return e;
	}

	// Where the pixels of a frame are in the sheet of its image.
	void frame_position(image_entry const& e, int frame, int& x, int& y)
	{
		int cells = e.sheet_w / (e.frame_w > 0 ? e.frame_w : 1);
		cells     = cells > 0 ? cells : 1;
		int index = e.first + frame;
		x         = (index % cells) * e.frame_w;
		y         = (index / cells) * e.frame_h;
	}

	target_ref resolve_target(int handle)
	{
		target_ref t;
		if ((handle == front_buffer) || (handle == back_buffer)) {
			t.image = &g.buffers[handle == front_buffer ? 0 : 1];
			t.w     = int(t.image->width);
			t.h     = int(t.image->height);
		} else if (handle >= texture_buffer_base) {
			texture_entry* tex = texture_of((handle - texture_buffer_base) >> 10);
			if (tex && tex->set && texture_frame_rect(*tex, (handle - texture_buffer_base) & 1023, t.x, t.y, t.w, t.h, &t.layer)) {
				ensure_color_image(tex->image, tex->set);
				sprite_hull_drop(tex->hull); // Whatever is drawn to it can show outside of the hull; LockBuffer and UnlockBuffer make one again.
				t.image = &tex->image;
			}
		} else if (handle >= image_buffer_base) {
			int          id    = (handle - image_buffer_base) >> 10;
			int          frame = (handle - image_buffer_base) & 1023;
			image_entry* e     = image_of(id);
			if (e && e->set && (frame < e->frames)) {
				ensure_color_image(e->image, e->set);
				t.image = &e->image;
				frame_position(*e, frame, t.x, t.y);
				t.w = e->frame_w;
				t.h = e->frame_h;
			}
		}
		return t;
	}

	[[noreturn]] void fail(const char* what)
	{
		char buffer[256];
		if (restoring_graphics()) {
			snprintf(buffer, sizeof(buffer), "Graphics: the graphics device was lost and could not be made again: %s", what);
		} else {
			snprintf(buffer, sizeof(buffer), "Graphics: %s", what);
		}
		bb_runtime_error(buffer);
		exit(1);
	}

	void check(VkResult result, const char* what)
	{
		if (result != VK_SUCCESS) {
			if (bb::rhi::is_device_loss(int32_t(result)) && recovery_enabled()) {
				note_device_loss(int32_t(result), what); // The graphics are made again where a frame begins.
				return;
			}
			char buffer[256];
			if (bb::rhi::is_device_loss(int32_t(result))) {
				snprintf(buffer, sizeof(buffer), "the graphics device was lost (%s in %s) and making the graphics again is turned off.", bb::rhi::native_result_name(int32_t(result)), what);
			} else {
				snprintf(buffer, sizeof(buffer), "%s failed (VkResult %d).", what, int(result));
			}
			fail(buffer);
		}
	}

	// The views of an image: all levels for sampling, as an array for textures, and the first level (and each layer) for drawing.
	static void create_views(gpu_image& img, const VkImageCreateInfo& info, VkImageAspectFlags aspect, const VkComponentMapping* components)
	{
		uint32_t mips = info.mipLevels, layers = info.arrayLayers;
		bool     srgb_rgba = (info.format == VK_FORMAT_R8G8B8A8_SRGB);
		VkImageViewCreateInfo view         = { VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO };
		view.image                         = img.image;
		view.viewType                      = VK_IMAGE_VIEW_TYPE_2D;
		view.format                        = info.format;
		if (components) {
			view.components = *components;
		}
		view.subresourceRange.aspectMask   = aspect;
		view.subresourceRange.levelCount   = mips;
		view.subresourceRange.layerCount   = 1;
		check(vkCreateImageView(g.device, &view, nullptr, &img.view), "vkCreateImageView");
		// Textures are sampled as arrays, with a layer for each frame of an animated one.
		if ((aspect == VK_IMAGE_ASPECT_COLOR_BIT) && (info.usage & VK_IMAGE_USAGE_SAMPLED_BIT) && (info.samples == VK_SAMPLE_COUNT_1_BIT)) {
			view.viewType                     = VK_IMAGE_VIEW_TYPE_2D_ARRAY;
			view.subresourceRange.layerCount = layers;
			check(vkCreateImageView(g.device, &view, nullptr, &img.array_view), "vkCreateImageView");
			view.viewType                     = VK_IMAGE_VIEW_TYPE_2D;
			view.subresourceRange.layerCount = 1;
		}
		if ((mips > 1) || srgb_rgba || (layers > 1)) {
			// An attachment has one level, so drawing to the texture goes through a view of the first.
			view.subresourceRange.levelCount = 1;
			if (srgb_rgba) {
				view.format = VK_FORMAT_R8G8B8A8_UNORM;
			}
			check(vkCreateImageView(g.device, &view, nullptr, &img.target_view), "vkCreateImageView");
			if (layers > 1) {
				img.layer_targets    = static_cast<VkImageView*>(bb_calloc(layers, sizeof(VkImageView)));
				img.layer_targets[0] = img.target_view;
				for (uint32_t layer = 1; layer < layers; layer++) {
					view.subresourceRange.baseArrayLayer = layer;
					check(vkCreateImageView(g.device, &view, nullptr, &img.layer_targets[layer]), "vkCreateImageView");
				}
			}
		}
	}

