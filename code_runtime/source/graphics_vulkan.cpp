	namespace vulkan {
	bool image_can_move(const gpu_image& img)
	{
		return img.image && img.allocation && img.recipe && img.recipe->aspect == VK_IMAGE_ASPECT_COLOR_BIT && vk_create_info(*img.recipe).samples == VK_SAMPLE_COUNT_1_BIT;
	}
	} // namespace vulkan

	namespace vulkan {
	bool move_image(gpu_image& img, uint64_t destination_handle)
	{
		VmaAllocation destination = VmaAllocation(destination_handle);
		if (!img.image || !img.recipe) {
			return false;
		}
		VkImageCreateInfo info = vk_create_info(*img.recipe);
		VkImage           fresh = VK_NULL_HANDLE;
		if ((vkCreateImage(vkd.device, &info, nullptr, &fresh) != VK_SUCCESS) || (vmaBindImageMemory(vkd.allocator, destination, fresh) != VK_SUCCESS)) {
			if (fresh) {
				vkDestroyImage(vkd.device, fresh, nullptr);
			}
			return false;
		}
		if (img.layout != bb::rhi::image_state::undefined) {
			// What the image holds goes over on the GPU: every level and layer.
			begin_commands();
			barrier(img.image, img.layout, bb::rhi::image_state::copy_src, (img.recipe->aspect & VK_IMAGE_ASPECT_DEPTH_BIT) != 0);
			barrier(uint64_t(fresh), bb::rhi::image_state::undefined, bb::rhi::image_state::copy_dst, (img.recipe->aspect & VK_IMAGE_ASPECT_DEPTH_BIT) != 0);
			std::vector<bb::rhi::image_copy> regions(info.mipLevels);
			for (uint32_t level = 0; level < info.mipLevels; level++) {
				regions[level].src.mip    = level;
				regions[level].src.layers = info.arrayLayers;
				regions[level].src.depth  = (img.recipe->aspect & VK_IMAGE_ASPECT_DEPTH_BIT) != 0;
				regions[level].dst        = regions[level].src;
				regions[level].w          = (info.extent.width >> level) ? (info.extent.width >> level) : 1;
				regions[level].h          = (info.extent.height >> level) ? (info.extent.height >> level) : 1;
			}
			bb::rhi::copy_image(uint64_t(img.image), uint64_t(fresh), regions.data(), info.mipLevels);
			barrier(uint64_t(fresh), bb::rhi::image_state::copy_dst, img.layout, (img.recipe->aspect & VK_IMAGE_ASPECT_DEPTH_BIT) != 0);
			submit_commands();
		}
		destroy_views(img);
		vkDestroyImage(vkd.device, VkImage(img.image), nullptr); // The allocation stays: the allocator hands the image's handle over to the memory it was moved to.
		img.image = uint64_t(fresh);
		VkComponentMapping mapping = vk_mapping(*img.recipe);
		create_views(img, info, img.recipe->aspect, img.recipe->has_mapping ? &mapping : nullptr);
		return true;
	}
	} // namespace vulkan

