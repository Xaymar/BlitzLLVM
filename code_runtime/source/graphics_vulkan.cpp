	// The layouts of the kinds of group, apart from the one of the textures. Null until first asked for.
	static struct {
		VkDescriptorSetLayout scene = VK_NULL_HANDLE, entity = VK_NULL_HANDLE, cull = VK_NULL_HANDLE, images3 = VK_NULL_HANDLE, images8 = VK_NULL_HANDLE;
	} kind_layouts;

	// The layout of a kind of group, made when it is first asked for. (The one of the textures is made with the device.)
	static VkDescriptorSetLayout made_set_layout(VkDescriptorSetLayout& layout, const VkDescriptorSetLayoutBinding* bindings, uint32_t count)
	{
		if (!layout) {
			VkDescriptorSetLayoutCreateInfo info = { VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO };
			info.bindingCount                    = count;
			info.pBindings                       = bindings;
			check(vkCreateDescriptorSetLayout(g.device, &info, nullptr, &layout), "vkCreateDescriptorSetLayout");
		}
		return layout;
	}

	// A group of count sampled images that fragment shaders read.
	static VkDescriptorSetLayout images_layout(VkDescriptorSetLayout& layout, uint32_t count)
	{
		VkDescriptorSetLayoutBinding bindings[8];
		for (uint32_t i = 0; i < count; i++) {
			bindings[i] = { i, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1, VK_SHADER_STAGE_FRAGMENT_BIT, nullptr };
		}
		return made_set_layout(layout, bindings, count);
	}

	VkDescriptorSetLayout vk_set_layout(bb::rhi::group_kind kind)
	{
		switch (kind) {
		case bb::rhi::group_kind::texture:
			return g.set_layout;
		case bb::rhi::group_kind::scene: {
			// The uniform buffer of the scene, and the lookup texture of the palette of a Graphics of depth 8 (the white texture when there is none).
			const VkDescriptorSetLayoutBinding bindings[2] = {
				{ 0, VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER_DYNAMIC, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT, nullptr },
				{ 1, VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, 1, VK_SHADER_STAGE_FRAGMENT_BIT, nullptr },
			};
			return made_set_layout(kind_layouts.scene, bindings, 2);
		}
		case bb::rhi::group_kind::entities: {
			// The data of each draw is in a buffer, so that draws of the same thing can be a single call.
			// Binding 1 holds what the texture layers after the first of the draws need (layer_data), which only the fragment shader reads.
			const VkDescriptorSetLayoutBinding bindings[2] = {
				{ 0, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT | VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
				{ 1, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_FRAGMENT_BIT, nullptr },
			};
			return made_set_layout(kind_layouts.entity, bindings, 2);
		}
		case bb::rhi::group_kind::cull: {
			// The clusters, the runs of them for each draw and the commands that come out: see compute_shader_cull in generate_shaders.py.
			const VkDescriptorSetLayoutBinding bindings[3] = {
				{ 0, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
				{ 1, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
				{ 2, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr },
			};
			return made_set_layout(kind_layouts.cull, bindings, 3);
		}
		case bb::rhi::group_kind::images3:
			return images_layout(kind_layouts.images3, 3);
		case bb::rhi::group_kind::images8:
			return images_layout(kind_layouts.images8, 8);
		}
		return VK_NULL_HANDLE;
	}

	bb::rhi::shader create_shader(const unsigned int* words, size_t size)
	{
		VkShaderModuleCreateInfo info = { VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO };
		info.codeSize                 = size;
		info.pCode                    = words;
		VkShaderModule module;
		check(vkCreateShaderModule(g.device, &info, nullptr, &module), "vkCreateShaderModule");
		return bb::rhi::shader{ uint64_t(module) };
	}

	void destroy_shader(bb::rhi::shader shader)
	{
		vkDestroyShaderModule(g.device, vk_shader(shader), nullptr);
	}

	// An image of RGBA8 stored as sRGB is copied as the bytes it has, so it counts as the same as one stored linear.
	static VkFormat copy_class(VkFormat format)
	{
		return (format == VK_FORMAT_R8G8B8A8_SRGB) ? VK_FORMAT_R8G8B8A8_UNORM : format;
	}

	void copy_region(gpu_image& from, int sx, int sy, gpu_image& to, int dx, int dy, int w, int h, uint32_t from_layer, uint32_t to_layer)
	{
		if (copy_class(from.format) == copy_class(to.format)) {
			bb::rhi::image_copy copy;
			copy.src.layer = from_layer;
			copy.src.x     = sx;
			copy.src.y     = sy;
			copy.dst.layer = to_layer;
			copy.dst.x     = dx;
			copy.dst.y     = dy;
			copy.w         = uint32_t(w);
			copy.h         = uint32_t(h);
			bb::rhi::copy_image(uint64_t(from.image), uint64_t(to.image), &copy, 1);
			return;
		}
		bb::rhi::image_blit blit;
		blit.layer_src = from_layer;
		blit.layer_dst = to_layer;
		blit.src[0]    = sx;
		blit.src[1]    = sy;
		blit.src[2]    = sx + w;
		blit.src[3]    = sy + h;
		blit.dst[0]    = dx;
		blit.dst[1]    = dy;
		blit.dst[2]    = dx + w;
		blit.dst[3]    = dy + h;
		bb::rhi::blit_image(uint64_t(from.image), uint64_t(to.image), &blit, 1, bb::rhi::filter::nearest);
	}

	namespace {
		struct pipeline_object {
			bb::rhi::pipeline_recipe                                 recipe;
			std::unordered_map<bb::rhi::format, VkPipeline>          built;
			bool                                                     alive = false;
			bool                                                     fixed = false; // One description for whatever format it is bound with.
		};
		std::vector<pipeline_object> pipeline_objects;
	} // namespace

	/** The Vulkan pipeline to draw to an image of that format. A target that is not the format of the buffers (when those are not RGBA8) gets the one made for RGBA8. */
	VkPipeline vk_pipeline(bb::rhi::pipeline pipeline, VkFormat format)
	{
		pipeline_object& object = pipeline_objects[pipeline.id - 1];
		bb::rhi::format  key    = object.fixed ? bb::rhi::format::undefined : (((format == g.buffer_format) && (format != VK_FORMAT_R8G8B8A8_UNORM)) ? rhi_format(format) : bb::rhi::format::rgba8);
		auto             found  = object.built.find(key);
		if (found != object.built.end()) {
			return found->second;
		}
		VkPipeline made = build_pipeline(object.recipe(key));
		object.built[key] = made;
		return made;
	}

	static VkBlendFactor vk_blend_factor(bb::rhi::blend_factor f)
	{
		switch (f) {
		case bb::rhi::blend_factor::zero: return VK_BLEND_FACTOR_ZERO;
		case bb::rhi::blend_factor::one: return VK_BLEND_FACTOR_ONE;
		case bb::rhi::blend_factor::src_alpha: return VK_BLEND_FACTOR_SRC_ALPHA;
		case bb::rhi::blend_factor::one_minus_src_alpha: return VK_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA;
		case bb::rhi::blend_factor::src_color: return VK_BLEND_FACTOR_SRC_COLOR;
		case bb::rhi::blend_factor::dst_color: return VK_BLEND_FACTOR_DST_COLOR;
		case bb::rhi::blend_factor::one_minus_src_color: return VK_BLEND_FACTOR_ONE_MINUS_SRC_COLOR;
		}
		return VK_BLEND_FACTOR_ZERO;
	}

	// The one translation of a neutral pipeline description to Vulkan state, for every pipeline of the renderer.
	VkPipeline build_pipeline(const bb::rhi::pipeline_desc& desc)
	{
		VkPipelineShaderStageCreateInfo stages[2] = { { VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO }, { VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO } };
		stages[0].stage                           = VK_SHADER_STAGE_VERTEX_BIT;
		stages[0].module                          = vk_shader(desc.vs);
		stages[0].pName                           = "main";
		stages[1].stage                           = VK_SHADER_STAGE_FRAGMENT_BIT;
		stages[1].module                          = vk_shader(desc.fs);
		stages[1].pName                           = "main";

		// The constants of the 3D shaders.
		struct {
			VkBool32 dither;
			float    factor[5];
			float    limit[2];
			float    scale[3];
			VkBool32 palette;
			float    bayer_levels;
			float    multiply;
			VkBool32 layers;
		} constants = {};
		VkSpecializationMapEntry entries[15];
		VkSpecializationInfo     specialization        = {};
		VkSpecializationMapEntry vertex_entries[2];
		VkSpecializationInfo     vertex_specialization = {};
		if (desc.has_constants) {
			const bb::rhi::shader_constants& k = desc.constants;
			constants.dither                   = k.dither ? VK_TRUE : VK_FALSE;
			memcpy(constants.factor, k.factor, sizeof(constants.factor));
			memcpy(constants.limit, k.limit, sizeof(constants.limit));
			memcpy(constants.scale, k.scale, sizeof(constants.scale));
			constants.palette      = k.palette ? VK_TRUE : VK_FALSE;
			constants.bayer_levels = k.bayer_levels;
			constants.multiply     = k.multiply;
			constants.layers       = k.layers ? VK_TRUE : VK_FALSE;
			entries[0]             = { 0, offsetof(decltype(constants), dither), sizeof(VkBool32) };
			for (uint32_t i = 0; i < 5; i++) {
				entries[1 + i] = { 1 + i, uint32_t(offsetof(decltype(constants), factor) + i * sizeof(float)), sizeof(float) };
			}
			entries[6] = { 6, uint32_t(offsetof(decltype(constants), limit)), sizeof(float) };
			entries[7] = { 7, uint32_t(offsetof(decltype(constants), limit) + sizeof(float)), sizeof(float) };
			for (uint32_t i = 0; i < 3; i++) {
				entries[8 + i] = { 8 + i, uint32_t(offsetof(decltype(constants), scale) + i * sizeof(float)), sizeof(float) };
			}
			entries[11]                   = { 11, uint32_t(offsetof(decltype(constants), palette)), sizeof(VkBool32) };
			entries[12]                   = { 12, uint32_t(offsetof(decltype(constants), bayer_levels)), sizeof(float) };
			entries[13]                   = { 20, uint32_t(offsetof(decltype(constants), multiply)), sizeof(float) };
			entries[14]                   = { 21, uint32_t(offsetof(decltype(constants), layers)), sizeof(VkBool32) };
			specialization                = { 15u, entries, sizeof(constants), &constants };
			stages[1].pSpecializationInfo = &specialization;
			vertex_entries[0]             = { 0, uint32_t(offsetof(decltype(constants), limit)), sizeof(float) };
			vertex_entries[1]             = { 1, uint32_t(offsetof(decltype(constants), limit) + sizeof(float)), sizeof(float) };
			vertex_specialization         = { 2u, vertex_entries, sizeof(constants), &constants };
			stages[0].pSpecializationInfo = &vertex_specialization;
		}

		VkVertexInputBindingDescription   binding       = {};
		VkVertexInputAttributeDescription attributes[5] = {};
		uint32_t                          attribute_count = 0;
		if (desc.vertices == bb::rhi::vertex_layout::flat) {
			binding             = { 0, sizeof(vertex), VK_VERTEX_INPUT_RATE_VERTEX };
			attributes[0]       = { 0, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(vertex, x) };
			attributes[1]       = { 1, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(vertex, u) };
			attributes[2]       = { 2, 0, VK_FORMAT_R8G8B8A8_UNORM, offsetof(vertex, r) };
			attribute_count     = 3;
		} else if (desc.vertices == bb::rhi::vertex_layout::scene3d) {
			binding         = { 0, sizeof(bb::vertex3d), VK_VERTEX_INPUT_RATE_VERTEX };
			attributes[0]   = { 0, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(bb::vertex3d, x) };
			attributes[1]   = { 1, 0, VK_FORMAT_R32G32B32_SFLOAT, offsetof(bb::vertex3d, nx) };
			attributes[2]   = { 2, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(bb::vertex3d, u) };
			attributes[3]   = { 3, 0, VK_FORMAT_R16G16B16A16_SFLOAT, offsetof(bb::vertex3d, r) };
			attributes[4]   = { 4, 0, VK_FORMAT_R32G32_SFLOAT, offsetof(bb::vertex3d, u2) };
			attribute_count = 5;
		}
		VkPipelineVertexInputStateCreateInfo input = { VK_STRUCTURE_TYPE_PIPELINE_VERTEX_INPUT_STATE_CREATE_INFO };
		input.vertexBindingDescriptionCount        = attribute_count ? 1 : 0;
		input.pVertexBindingDescriptions           = &binding;
		input.vertexAttributeDescriptionCount      = attribute_count;
		input.pVertexAttributeDescriptions         = attributes;

		VkPipelineInputAssemblyStateCreateInfo assembly = { VK_STRUCTURE_TYPE_PIPELINE_INPUT_ASSEMBLY_STATE_CREATE_INFO };
		assembly.topology                               = (desc.primitives == bb::rhi::topology::lines) ? VK_PRIMITIVE_TOPOLOGY_LINE_LIST : VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST;

		VkPipelineViewportStateCreateInfo viewport = { VK_STRUCTURE_TYPE_PIPELINE_VIEWPORT_STATE_CREATE_INFO };
		viewport.viewportCount                     = 1;
		viewport.scissorCount                      = 1;

		// Blitz3D's front faces are clockwise as seen from the front. The projection flips Y, which flips this once more.
		VkPipelineRasterizationStateCreateInfo raster = { VK_STRUCTURE_TYPE_PIPELINE_RASTERIZATION_STATE_CREATE_INFO };
		raster.polygonMode                            = desc.wire ? VK_POLYGON_MODE_LINE : VK_POLYGON_MODE_FILL;
		raster.cullMode                               = desc.depth ? VK_CULL_MODE_BACK_BIT : VK_CULL_MODE_NONE;
		raster.frontFace                              = VK_FRONT_FACE_CLOCKWISE;
		raster.lineWidth                              = 1.0f;

		VkPipelineMultisampleStateCreateInfo multisample = { VK_STRUCTURE_TYPE_PIPELINE_MULTISAMPLE_STATE_CREATE_INFO };
		multisample.rasterizationSamples                 = VkSampleCountFlagBits(desc.samples);

		VkPipelineDepthStencilStateCreateInfo depth = { VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO };
		depth.depthTestEnable                       = VK_TRUE;
		depth.depthWriteEnable                      = VK_TRUE;
		// The depth is reversed: 1 at the near plane and 0 at the far plane, so closer is greater.
		depth.depthCompareOp                        = (desc.depth_compare == bb::rhi::compare::less) ? VK_COMPARE_OP_LESS : VK_COMPARE_OP_GREATER_OR_EQUAL;

		VkPipelineColorBlendAttachmentState blend[4]   = {};
		VkFormat                            formats[4] = {};
		for (uint32_t i = 0; i < desc.attachment_count; i++) {
			const bb::rhi::attachment_desc& a = desc.attachments[i];
			formats[i]                        = vk_format(a.fmt);
			blend[i].blendEnable              = a.blend.enable ? VK_TRUE : VK_FALSE;
			blend[i].srcColorBlendFactor      = vk_blend_factor(a.blend.src_color);
			blend[i].dstColorBlendFactor      = vk_blend_factor(a.blend.dst_color);
			blend[i].colorBlendOp             = VK_BLEND_OP_ADD;
			blend[i].srcAlphaBlendFactor      = vk_blend_factor(a.blend.src_alpha);
			blend[i].dstAlphaBlendFactor      = vk_blend_factor(a.blend.dst_alpha);
			blend[i].alphaBlendOp             = VK_BLEND_OP_ADD;
			blend[i].colorWriteMask           = a.blend.write_mask;
		}
		VkPipelineColorBlendStateCreateInfo blending = { VK_STRUCTURE_TYPE_PIPELINE_COLOR_BLEND_STATE_CREATE_INFO };
		blending.attachmentCount                     = desc.attachment_count;
		blending.pAttachments                        = blend;

		VkDynamicState dynamic_states[5]         = { VK_DYNAMIC_STATE_VIEWPORT, VK_DYNAMIC_STATE_SCISSOR, VK_DYNAMIC_STATE_CULL_MODE, VK_DYNAMIC_STATE_DEPTH_WRITE_ENABLE, VK_DYNAMIC_STATE_DEPTH_TEST_ENABLE };
		VkPipelineDynamicStateCreateInfo dynamic = { VK_STRUCTURE_TYPE_PIPELINE_DYNAMIC_STATE_CREATE_INFO };
		dynamic.dynamicStateCount                = desc.depth ? 5 : 2;
		dynamic.pDynamicStates                   = dynamic_states;

		VkPipelineRenderingCreateInfo rendering = { VK_STRUCTURE_TYPE_PIPELINE_RENDERING_CREATE_INFO };
		rendering.colorAttachmentCount          = desc.attachment_count;
		rendering.pColorAttachmentFormats       = formats;
		rendering.depthAttachmentFormat         = (desc.depth || desc.depth_unused) ? vk_format(desc.depth_format) : VK_FORMAT_UNDEFINED;

		VkGraphicsPipelineCreateInfo info = { VK_STRUCTURE_TYPE_GRAPHICS_PIPELINE_CREATE_INFO };
		info.pNext                        = &rendering;
		info.stageCount                   = 2;
		info.pStages                      = stages;
		info.pVertexInputState            = &input;
		info.pInputAssemblyState          = &assembly;
		info.pViewportState               = &viewport;
		info.pRasterizationState          = &raster;
		info.pMultisampleState            = &multisample;
		VkPipelineDepthStencilStateCreateInfo no_depth = { VK_STRUCTURE_TYPE_PIPELINE_DEPTH_STENCIL_STATE_CREATE_INFO }; // Neither tested nor written.
		info.pDepthStencilState           = desc.depth ? &depth : (desc.depth_unused ? &no_depth : nullptr);
		info.pColorBlendState             = &blending;
		info.pDynamicState                = &dynamic;
		info.layout                       = vk_layout(desc.layout);

		VkPipeline pipeline;
		check(vkCreateGraphicsPipelines(g.device, VK_NULL_HANDLE, 1, &info, nullptr, &pipeline), "vkCreateGraphicsPipelines");
		return pipeline;
	}

	static bb::rhi::pipeline_desc flat_desc(bb::rhi::shader vs, bb::rhi::shader fs, bb::rhi::pipeline_layout layout, VkPrimitiveTopology topology, bool vertices, VkFormat format)
	{
		bb::rhi::pipeline_desc desc;
		desc.vs                      = vs;
		desc.fs                      = fs;
		desc.layout                  = layout;
		desc.primitives              = (topology == VK_PRIMITIVE_TOPOLOGY_LINE_LIST) ? bb::rhi::topology::lines : bb::rhi::topology::triangles;
		desc.vertices                = vertices ? bb::rhi::vertex_layout::flat : bb::rhi::vertex_layout::none;
		desc.attachments[0].fmt      = rhi_format(format);
		desc.attachments[0].blend.enable = vertices; // Passes over an image replace it.
		return desc;
	}

	bb::rhi::pipeline create_flat_pipeline(bb::rhi::shader vs, bb::rhi::shader fs, VkPrimitiveTopology topology, bb::rhi::pipeline_layout layout)
	{
		bb::rhi::pipeline pipeline = bb::rhi::create_pipeline([=](bb::rhi::format target) { return flat_desc(vs, fs, layout, topology, true, vk_format(target)); });
		vk_pipeline(pipeline, VK_FORMAT_R8G8B8A8_UNORM); // Both versions are made now, so that nothing is compiled in the middle of a frame.
		if (g.buffer_format != VK_FORMAT_R8G8B8A8_UNORM) {
			vk_pipeline(pipeline, g.buffer_format);
		}
		return pipeline;
	}

	bb::rhi::pipeline create_fullscreen_pipeline(bb::rhi::shader vs, bb::rhi::shader fs, bb::rhi::pipeline_layout layout, bb::rhi::format format)
	{
		return bb::rhi::create_fixed_pipeline(flat_desc(vs, fs, layout, VK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST, false, vk_format(format)));
	}

	void write_descriptor(bb::rhi::binding_group set, VkImageView view, bb::rhi::sampler sampler)
	{
		VkDescriptorImageInfo image_info = { vk_sampler(sampler), view, vk_layout_of(bb::rhi::image_state::sampled) };
		VkWriteDescriptorSet  write      = { VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET };
		write.dstSet                     = vk_set(set);
		write.descriptorCount            = 1;
		write.descriptorType             = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
		write.pImageInfo                 = &image_info;
		vkUpdateDescriptorSets(g.device, 1, &write, 0, nullptr);
	}

	void set_descriptor_sampler(gpu_image& image, bb::rhi::binding_group set, bb::rhi::sampler sampler)
	{
		flush(); // What was recorded may use the old sampler.
		bb::rhi::wait_idle();
		describe_image(set, image, sampler);
		image.sampler = sampler;
	}

	void allocate_descriptor(bb::rhi::binding_group& set)
	{
		set = bb::rhi::create_group(bb::rhi::group_kind::texture);
		// The bindings of the layers hold white (every shader that reads them needs something in them), until the white texture itself is made.
		bb::rhi::binding_group white = g.sets[TEXTURE_WHITE_3D];
		if (white && (white != set)) {
			VkCopyDescriptorSet copy = { VK_STRUCTURE_TYPE_COPY_DESCRIPTOR_SET };
			copy.srcSet              = vk_set(white);
			copy.srcBinding          = 1;
			copy.dstSet              = vk_set(set);
			copy.dstBinding          = 1;
			copy.descriptorCount     = texture_layer_bindings - 1;
			vkUpdateDescriptorSets(g.device, 0, nullptr, 1, &copy);
		}
	}

	uint32_t mip_count(uint32_t width, uint32_t height)
	{
		uint32_t levels = 1;
		for (uint32_t size = width > height ? width : height; size > 1; size >>= 1) {
			levels++;
		}
		return levels;
	}

	static void level_barrier(VkImage image, uint32_t first, uint32_t count, bb::rhi::image_state from, bb::rhi::image_state to)
	{
		VkImageMemoryBarrier2 b       = { VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2 };
		b.srcStageMask                = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
		b.srcAccessMask               = VK_ACCESS_2_MEMORY_WRITE_BIT;
		b.dstStageMask                = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
		b.dstAccessMask               = VK_ACCESS_2_MEMORY_READ_BIT | VK_ACCESS_2_MEMORY_WRITE_BIT;
		b.oldLayout                   = vk_layout_of(from);
		b.newLayout                   = vk_layout_of(to);
		b.srcQueueFamilyIndex         = VK_QUEUE_FAMILY_IGNORED;
		b.dstQueueFamilyIndex         = VK_QUEUE_FAMILY_IGNORED;
		b.image                       = image;
		b.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
		b.subresourceRange.baseMipLevel = first;
		b.subresourceRange.levelCount = count;
		b.subresourceRange.layerCount = VK_REMAINING_ARRAY_LAYERS;
		VkDependencyInfo dep          = { VK_STRUCTURE_TYPE_DEPENDENCY_INFO };
		dep.imageMemoryBarrierCount   = 1;
		dep.pImageMemoryBarriers      = &b;
		vkCmdPipelineBarrier2(g.cmd, &dep);
	}

	// Fills every level below the first by halving the one above it with a linear filter, which averages 2 by 2 pixels. All
	// levels are expected to be in the layout, and are in the shader read layout afterwards. Expects an open command buffer.
	static void generate_mips(gpu_image& image, bb::rhi::image_state from)
	{
		level_barrier(image.image, 0, 1, from, bb::rhi::image_state::copy_src);
		if (from != bb::rhi::image_state::copy_dst) {
			level_barrier(image.image, 1, image.mips - 1, from, bb::rhi::image_state::copy_dst);
		}
		int32_t w = int32_t(image.width), h = int32_t(image.height);
		for (uint32_t level = 1; level < image.mips; level++) {
			int32_t     next_w = w > 1 ? w / 2 : 1, next_h = h > 1 ? h / 2 : 1;
			bb::rhi::image_blit blit;
			blit.mip_src = level - 1;
			blit.mip_dst = level;
			blit.layers  = image.layers;
			blit.src[2]  = w;
			blit.src[3]  = h;
			blit.dst[2]  = next_w;
			blit.dst[3]  = next_h;
			bb::rhi::blit_image(uint64_t(image.image), uint64_t(image.image), &blit, 1, bb::rhi::filter::linear);
			level_barrier(image.image, level, 1, bb::rhi::image_state::copy_dst, bb::rhi::image_state::copy_src);
			w = next_w;
			h = next_h;
		}
		level_barrier(image.image, 0, image.mips, bb::rhi::image_state::copy_src, bb::rhi::image_state::sampled);
		image.layout     = bb::rhi::image_state::sampled;
		image.mips_stale = false;
	}

	void refresh_mips(gpu_image& image)
	{
		if ((image.mips > 1) && image.mips_stale) {
			generate_mips(image, image.layout);
		}
	}

	// Uploads RGBA pixels into a new image that can be sampled and drawn to, with all of its mip levels if asked for.
	// With remember the recipe of the image keeps the pixels, so that the image can be made again (rebuild_image does not want that: it has the pixels).
	static void upload_pixels(gpu_image& image, uint32_t width, uint32_t height, const uint8_t* pixels, bool mipmaps, bool srgb = false, bool ten = false, bool remember = true, uint32_t layers = 1)
	{
		// Pixels of 10 bits hold every mip level one after the other, as the picture was made on the CPU (see mip_chain_ten).
		uint32_t     levels = (ten && mipmaps) ? mip_count(width, height) : 1;
		VkDeviceSize size   = 0;
		for (uint32_t level = 0; level < levels; level++) {
			size += VkDeviceSize((width >> level) ? (width >> level) : 1) * ((height >> level) ? (height >> level) : 1) * 4;
		}
		size *= layers; // The layers one after the other.
		rhi::gpu_buffer staging;
		void* mapped;
		rhi::create_buffer(staging, size, rhi::transfer_source, rhi::memory::mapped);
		mapped = staging.mapped;
		memcpy(mapped, pixels, size_t(size));

		// Pixels of 10 bits per channel are never drawn to as they are, so they are not a color attachment.
		bb::rhi::image_usage usage = bb::rhi::image_sampled | bb::rhi::image_copy_destination | bb::rhi::image_copy_source | (ten ? bb::rhi::image_usage(0) : bb::rhi::image_color_target);
		bool arrays             = image.array_sets;
		image                   = create_image(width, height, usage, ten ? bb::rhi::format::a2bgr10 : (srgb ? bb::rhi::format::rgba8_srgb : bb::rhi::format::rgba8), nullptr, mipmaps ? mip_count(width, height) : 1, layers);
		image.array_sets        = arrays;
		image.ten               = ten;
		image.srgb              = srgb;
		if (remember && recovery_enabled()) {
			image_recipe& recipe = *image.recipe;
			recipe.kind          = image_recipe::content::pixels;
			recipe.mipmaps       = mipmaps;
			recipe.srgb          = srgb;
			recipe.ten           = ten;
			recipe.data.assign(pixels, pixels + size);
		}
		if (!image.image) {
			rhi::destroy_buffer(staging); // The device is lost, the recipe is all there is until it is back.
			return;
		}

		begin_commands();
		barrier(image.image, bb::rhi::image_state::undefined, bb::rhi::image_state::copy_dst);
		bb::rhi::buffer_image_copy copy;
		copy.image.layers = layers;
		copy.w            = width;
		copy.h            = height;
		bb::rhi::copy_buffer_to_image(uint64_t(staging.vk), uint64_t(image.image), &copy, 1);
		if (ten && (image.mips > 1)) {
			std::vector<bb::rhi::buffer_image_copy> copies(levels);
			VkDeviceSize                            offset = 0;
			for (uint32_t level = 0; level < levels; level++) {
				uint32_t w = (width >> level) ? (width >> level) : 1, h = (height >> level) ? (height >> level) : 1;
				copies[level].buffer_offset = offset;
				copies[level].image.mip     = level;
				copies[level].w             = w;
				copies[level].h             = h;
				offset += VkDeviceSize(w) * h * 4;
			}
			// The first copy above only covered level 0; the others come from the rest of the buffer.
			bb::rhi::copy_buffer_to_image(uint64_t(staging.vk), uint64_t(image.image), copies.data() + 1, levels - 1);
			barrier(image.image, bb::rhi::image_state::copy_dst, bb::rhi::image_state::sampled);
			image.layout = bb::rhi::image_state::sampled;
		} else if (image.mips > 1) {
			generate_mips(image, bb::rhi::image_state::copy_dst);
		} else {
			barrier(image.image, bb::rhi::image_state::copy_dst, bb::rhi::image_state::sampled);
			image.layout = bb::rhi::image_state::sampled;
		}
		submit_commands();

		rhi::destroy_buffer(staging);
	}

