// Graphics width, height, depth, mode.
// Modes: 0 = windowed (or fullscreen for 3D), 1 = fullscreen, 2 = windowed, 3 = resizable window,
// 4 = window without a border (a BlitzLLVM extension). The depth picks what the buffers are made of: 24 is R8G8B8X8,
// 30 is R10G10B10A2, 32 (and 0 and 16) is R8G8B8A8 and 64 is R16G16B16A16.
void bb_graphics(int32_t width, int32_t height, int32_t depth, int32_t mode)
{
	if ((width <= 0) || (height <= 0)) {
		fail("Graphics needs a width and height of at least 1.");
	}
	if (g.created) {
		bb_end_graphics();
	}

	bb_reset_texture_filters();
	g.requested_depth = depth;
	g.buffer_depth    = (depth == 24 || depth == 30 || depth == 64) ? depth : 32;
	g.buffer_format   = VK_FORMAT_R8G8B8A8_UNORM;
	g.headless = getenv("BLITZ_HEADLESS") != nullptr;
	g.width    = uint32_t(width);
	g.height   = uint32_t(height);
	g.created  = true;
	g.target   = back_buffer;
	if (g.headless) {
		return;
	}

	if (!SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS)) {
		fail(SDL_GetError());
	}
	SDL_WindowFlags flags = SDL_WINDOW_VULKAN;
	if (mode == 1) {
		// Borderless over the whole display with no change of its video mode; the buffer is shown with its aspect ratio kept.
		flags |= SDL_WINDOW_FULLSCREEN | SDL_WINDOW_BORDERLESS;
	} else if (mode == 3) {
		flags |= SDL_WINDOW_RESIZABLE;
	} else if (mode == 4) {
		flags |= SDL_WINDOW_BORDERLESS;
	}
	// Fullscreen covers the main display, whatever size the buffer is.
	SDL_Rect bounds = { 0, 0, width, height };
	if (mode == 1) {
		SDL_GetDisplayBounds(SDL_GetPrimaryDisplay(), &bounds);
	}
	g.window = SDL_CreateWindow("BlitzLLVM", bounds.w, bounds.h, flags);
	if (!g.window) {
		fail(SDL_GetError());
	}
	if (mode == 1) {
		SDL_SetWindowFullscreenMode(g.window, nullptr); // The desktop mode, not a mode of the size asked for.
		g.fullscreen = true;
		SDL_SetWindowPosition(g.window, bounds.x, bounds.y); // For systems that do not move a fullscreen window.
		SDL_SyncWindow(g.window);
	}
	SDL_StartTextInput(g.window);
	g.auto_suspend = (mode == 1); // Fullscreen programs are suspended when they are not in front, unless they say not.
	if (const char* path = getenv("BLITZ_TEST_WINDOW_FLAGS")) {
		// Test hook: the flags SDL gave the window, as a number in the named file.
		if (FILE* file = fopen(path, "w")) {
			fprintf(file, "%llu", (unsigned long long)SDL_GetWindowFlags(g.window));
			fclose(file);
		}
	}

	create_vulkan();
	create_buffers(uint32_t(width), uint32_t(height));
	create_swapchain();
	if (const char* path = getenv("BLITZ_TEST_LAYOUT")) {
		// Test hook: the size of the window in pixels, where the buffer is shown in it, and the buffer coordinates of
		// the window corners and center, one number per line in the named file.
		if (FILE* file = fopen(path, "w")) {
			buffer_rect area = fit_buffer(float(g.swap_extent.width), float(g.swap_extent.height));
			fprintf(file, "%u\n%u\n%d\n%d\n%d\n%d\n", g.swap_extent.width, g.swap_extent.height, int(area.x), int(area.y), int(area.w), int(area.h));
			int ww = 1, wh = 1;
			SDL_GetWindowSize(g.window, &ww, &wh);
			float points[3][2] = { { 0, 0 }, { float(ww) * 0.5f, float(wh) * 0.5f }, { float(ww - 1), float(wh - 1) } };
			for (auto& point : points) {
				int x, y;
				window_to_buffer(point[0], point[1], &x, &y);
				fprintf(file, "%d\n%d\n", x, y);
			}
			fclose(file);
		}
	}
}

void bb_end_graphics(void)
{
	if (!g.created) {
		return;
	}
	if (!g.headless) {
		flush(); // What was asked for is drawn before it all goes away.
		gpu_idle();
		for (int i = 0; i < 2; i++) {
			destroy_image(g.buffers[i]);
		}
		for (uint32_t i = 0; i < texture_table.size; i++) {
			if (texture_table[i].used) {
				free_texture(texture_table[i]);
			}
		}
		for (uint32_t i = 0; i < image_table.size; i++) {
			if (image_table[i].used) {
				free_image(image_table[i]);
			}
		}
		async_shutdown(); // The pictures that were still loading went with the freed handles.
		for (uint32_t i = 0; i < max_depths; i++) {
			destroy_image(depth_cache[i]);
		}
		if (scratch) {
			destroy_buffer(scratch, scratch_allocation);
			scratch_size = 0;
		}
		empty_graveyard();
		destroy_surface_buffers();
		destroy_gamma();
		destroy_frame_slot_buffers();
		vkDestroyPipeline(g.device, g.opaque3d, nullptr);
	vkDestroyPipeline(g.device, g.solid3d, nullptr);
		vkDestroyPipeline(g.device, g.blend3d, nullptr);
		vkDestroyPipeline(g.device, g.mul3d, nullptr);
		vkDestroyPipeline(g.device, g.mul2x3d, nullptr);
		vkDestroyPipeline(g.device, g.add3d, nullptr);
		for (VkPipeline pipeline : g.wire3d) {
			if (pipeline) {
				vkDestroyPipeline(g.device, pipeline, nullptr);
			}
		}
		vkDestroyPipelineLayout(g.device, g.layout3d, nullptr);
		vkDestroyDescriptorSetLayout(g.device, g.scene_layout, nullptr);
		for (int i = 0; i < TEXTURES; i++) {
			destroy_image(g.textures[i]);
		}
		destroy_swapchain();
		stop_gpu_thread();
		destroy_buffer(g.vertex_buffer, g.vertex_allocation);
		destroy_buffer(g.vertex_buffer_alt, g.vertex_allocation_alt);
		destroy_buffer(g.vertex_buffer_alt2, g.vertex_allocation_alt2);
		destroy_pipeline_twins();
		vkDestroyPipeline(g.device, g.triangles, nullptr);
		vkDestroyPipeline(g.device, g.lines, nullptr);
		vkDestroyPipelineLayout(g.device, g.layout, nullptr);
		vkDestroyDescriptorPool(g.device, g.set_pool, nullptr);
		vkDestroyDescriptorSetLayout(g.device, g.set_layout, nullptr);
		destroy_user_samplers();
		vkDestroySampler(g.device, g.sampler, nullptr);
		vkDestroySampler(g.device, g.sampler_repeat, nullptr);
		vkDestroySampler(g.device, g.sampler_clamp, nullptr);
		vkDestroySampler(g.device, g.sampler_repeat_mips, nullptr);
		vkDestroySampler(g.device, g.sampler_clamp_mips, nullptr);
		vkDestroySampler(g.device, g.sampler_point_repeat, nullptr);
		vkDestroySampler(g.device, g.sampler_point_clamp, nullptr);
		vkDestroySampler(g.device, g.sampler_point_repeat_mips, nullptr);
		vkDestroySampler(g.device, g.sampler_point_clamp_mips, nullptr);
		if (profile_query_pool) {
			vkDestroyQueryPool(g.device, profile_query_pool, nullptr);
			profile_query_pool = VK_NULL_HANDLE;
			profile_mark_state = -1;
		}
		destroy_frame_slots();
		vkDestroyCommandPool(g.device, g.pool, nullptr);
		destroy_allocator();
		vkDestroyDevice(g.device, nullptr);
		SDL_Vulkan_DestroySurface(g.instance, g.surface, nullptr);
		vkDestroyInstance(g.instance, nullptr);
		SDL_DestroyWindow(g.window);
		SDL_Quit();
	}
	free(g.ops);
	forget_recorded();
	g = state();
}

// The window of the program as the system knows it (HWND on Windows, the window number on X11), 0 where there is none.
int32_t bb_native_window(void)
{
	if (!g.window) {
		return 0;
	}
	SDL_PropertiesID properties = SDL_GetWindowProperties(g.window);
#if defined(_WIN32)
	return int32_t(reinterpret_cast<intptr_t>(SDL_GetPointerProperty(properties, SDL_PROP_WINDOW_WIN32_HWND_POINTER, nullptr)));
#else
	return int32_t(SDL_GetNumberProperty(properties, SDL_PROP_WINDOW_X11_WINDOW_NUMBER, 0));
#endif
}

