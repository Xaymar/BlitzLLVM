// Takes down the window of Graphics and the device, also a device that was made without a window (ensure_device).
void bb_end_graphics(void)
{
	if (!g.created && !g.device) {
		return;
	}
	if (!g.headless) {
		flush(); // What was asked for is drawn before it all goes away.
		gpu_idle();
		for (uint32_t i = 0; i < texture_table.size; i++) {
			if (texture_table[i].used) {
				free_texture(texture_table[i]);
			}
		}
		for (uint32_t i = 0; i < image_table.size; i++) {
			if (image_table[i].used) {
				free_image(image_table[i]);
			}
		}
		save_finish_all(); // The pictures that are still being written are written before the program ends.
		async_shutdown(); // The pictures that were still loading went with the freed handles.
		destroy_device_objects();
		if (surface().window) {
			SDL_DestroyWindow(surface().window);
		}
		SDL_Quit();
	}
	bb_free(g.ops);
	forget_recorded();
	g = state();
}

// The window of the program as the system knows it (HWND on Windows, the window number on X11), 0 where there is none.
int32_t bb_native_window(void)
{
	if (!surface().window) {
		return 0;
	}
	SDL_PropertiesID properties = SDL_GetWindowProperties(surface().window);
#if defined(_WIN32)
	return int32_t(reinterpret_cast<intptr_t>(SDL_GetPointerProperty(properties, SDL_PROP_WINDOW_WIN32_HWND_POINTER, nullptr)));
#else
	return int32_t(SDL_GetNumberProperty(properties, SDL_PROP_WINDOW_X11_WINDOW_NUMBER, 0));
#endif
}

