int32_t bb_set_buffer(int32_t buffer)
{
	// A texture is only drawn to if it was made as a render target (flag 4096); reading and writing its pixels needs no flag.
	if (bb_is_debug() && (buffer >= texture_buffer_base)) {
		texture_entry* tex = live_texture_of(int32_t((buffer - texture_buffer_base) >> 10));
		if (tex && !(tex->flags & TEXTURE_TARGET)) {
			bb_runtime_error("SetBuffer: the texture is not a render target, give it flag 4096 when it is made.");
		}
	}
	int32_t previous = g.target;
	if (active() && !resolve_target(buffer).image) {
		fail("SetBuffer: the buffer does not exist.");
	}
	g.target = buffer; // What is drawn to it is only recorded for now, each operation knows its buffer.
	g.origin_x = g.origin_y = 0;
	g.view_x = g.view_y = 0;
	g.view_w = g.view_h = -1;
	g.cursor_x = g.cursor_y = 0;
	return previous;
}

