// Graphics width, height, depth, mode. Graphics3D is this same function: there is no 2D-only mode, so the 3D commands work
// after either of them.
// Modes: 0 = windowed, 1 = fullscreen, 2 = windowed, 3 = resizable window,
// 4 = window without a border (a BlitzLLVM extension). The depth picks what the buffers are made of: 8 is a palette of 256 colors
// (see GraphicsPalette), 12 is R4G4B4A4, 15 is A1R5G5B5, 16 is R5G6B5, 24 is R8G8B8X8, 30 is R10G10B10A2, 32 (and 0) is R8G8B8A8 and
// 64 is R16G16B16A16 as half precision floats.
void bb_graphics(int32_t width, int32_t height, int32_t depth, int32_t mode)
{
	if ((width <= 0) || (height <= 0)) {
		fail("Graphics needs a width and height of at least 1.");
	}
	if (g.created) {
		bb_end_graphics();
	}
	bb_on_exit(bb_end_graphics); // The program ends with the graphics taken down, while the Vulkan driver's threads still have what they need.

	bb_reset_texture_filters();
	if (const char* path = bb_env("BLITZLLVM_TEST_LAZY_DEVICE")) {
		test_lazy_device(path); // Test hook: a device before the window, as a program that opens its own windows first would have (see graphics_surfaces.cpp).
	}
	// A device from before there was a window of Graphics (ensure_device) is kept, if it draws with the depth asked for: the
	// window gets a surface on it. Otherwise the device is made again, for the depth.
	bool keep_device  = g.device != VK_NULL_HANDLE;
	int  actual_depth = 32;
	if (keep_device && (pick_buffer_format(depth, actual_depth) != g.buffer_format)) {
		bb_end_graphics();
		keep_device = false;
	}
	g.requested_depth = depth;
	if (keep_device) {
		g.buffer_depth = actual_depth; // The format stays, create_device would pick the same.
	} else {
		g.buffer_depth  = (depth == 8 || depth == 12 || depth == 15 || depth == 16 || depth == 24 || depth == 30 || depth == 64) ? depth : 32;
		g.buffer_format = VK_FORMAT_R8G8B8A8_UNORM;
	}
	g.headless = bb_env_bool("BLITZLLVM_HEADLESS", 0) != 0;
	g.width    = uint32_t(width);
	g.height   = uint32_t(height);
	g.created  = true;
	g.target   = back_buffer;
	if (g.headless) {
		return;
	}

	if (!SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS)) {
		fail(SDL_GetError());
	}
	SDL_WindowFlags flags = SDL_WINDOW_VULKAN;
	if (mode == 1) {
		// Borderless over the whole display with no change of its video mode; the buffer is shown with its aspect ratio kept.
		flags |= SDL_WINDOW_FULLSCREEN | SDL_WINDOW_BORDERLESS;
	} else if (mode == 3) {
		flags |= SDL_WINDOW_RESIZABLE;
	} else if (mode == 4) {
		flags |= SDL_WINDOW_BORDERLESS;
	}
	// Fullscreen covers the main display, whatever size the buffer is.
	SDL_Rect bounds = { 0, 0, width, height };
	if (mode == 1) {
		SDL_GetDisplayBounds(SDL_GetPrimaryDisplay(), &bounds);
	}
	surface().window = SDL_CreateWindow("BlitzLLVM", bounds.w, bounds.h, flags);
	if (!surface().window) {
		fail(SDL_GetError());
	}
	if (mode == 1) {
		SDL_SetWindowFullscreenMode(surface().window, nullptr); // The desktop mode, not a mode of the size asked for.
		surface().fullscreen = true;
		SDL_SetWindowPosition(surface().window, bounds.x, bounds.y); // For systems that do not move a fullscreen window.
		SDL_SyncWindow(surface().window);
	}
	if (mode != 1) {
		disable_rounded_corners(surface().window);
	}
	SDL_StartTextInput(surface().window);
	g.auto_suspend = (mode == 1); // Fullscreen programs are suspended when they are not in front, unless they say not.
	if (const char* path = bb_env("BLITZLLVM_TEST_WINDOW_FLAGS")) {
		// Test hook: the flags SDL gave the window, as a number in the named file.
		if (FILE* file = fopen(path, "w")) {
			fprintf(file, "%llu", (unsigned long long)SDL_GetWindowFlags(surface().window));
			fclose(file);
		}
	}

	if (keep_device) {
		if (!SDL_Vulkan_CreateSurface(surface().window, g.instance, nullptr, &surface().surface)) {
			fail(SDL_GetError());
		}
		// The queue of the device was picked with another window; the window system does not give one that cannot show pictures
		// in this one, so that is an error of the driver.
		VkBool32 present = VK_FALSE;
		vkGetPhysicalDeviceSurfaceSupportKHR(g.physical, g.family, surface().surface, &present);
		if (!present) {
			fail("The graphics device that was picked before the window cannot show pictures in it.");
		}
	} else {
		create_vulkan();
	}
	create_buffers(uint32_t(width), uint32_t(height));
	create_swapchain();
	if (const char* path = bb_env("BLITZLLVM_TEST_LAZY_DEVICE")) {
		test_lazy_device_finish(path);
	}
	if (const char* path = bb_env("BLITZLLVM_TEST_EXTRA_SURFACES")) {
		test_extra_surfaces(path); // Test hook: see graphics_surfaces.cpp.
	}
	if (const char* path = bb_env("BLITZLLVM_TEST_PRESENTERS")) {
		test_presenters(path); // Test hook: see graphics_presenter.cpp.
	}
	if (const char* path = bb_env("BLITZLLVM_TEST_LAYOUT")) {
		// Test hook: the size of the window in pixels, where the buffer is shown in it, and the buffer coordinates of
		// the window corners and center, one number per line in the named file.
		if (FILE* file = fopen(path, "w")) {
			buffer_rect area = fit_buffer(float(surface().swap_extent.width), float(surface().swap_extent.height));
			fprintf(file, "%u\n%u\n%d\n%d\n%d\n%d\n", surface().swap_extent.width, surface().swap_extent.height, int(area.x), int(area.y), int(area.w), int(area.h));
			int ww = 1, wh = 1;
			SDL_GetWindowSize(surface().window, &ww, &wh);
			float points[3][2] = { { 0, 0 }, { float(ww) * 0.5f, float(wh) * 0.5f }, { float(ww - 1), float(wh - 1) } };
			for (auto& point : points) {
				int x, y;
				window_to_buffer(point[0], point[1], &x, &y);
				fprintf(file, "%d\n%d\n", x, y);
			}
			fclose(file);
		}
	}
}

