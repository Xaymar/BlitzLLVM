// Gives back everything the device made and then the device, the surface and the instance, and not the window. The images of
// textures and images are gone before this (freed, or released if they are made again), so are the buffers.
void bb::gfx::destroy_device_objects()
{
	destroy_extra_surfaces(); // Their swapchains are of this device.
	close_prebuild(); // Before the buffers of the surfaces go: no loader thread makes another one from here on.
	for (int i = 0; i < 2; i++) {
		destroy_image(g.buffers[i]);
	}
	destroy_depth_cache();
	if (scratch) {
		destroy_buffer(scratch, scratch_allocation);
		scratch_size = 0;
	}
	empty_graveyard();
	destroy_surface_buffers();
	destroy_antialias();
	destroy_gamma();
	destroy_frame_slot_buffers();
	destroy_pipelines_3d();
	if (g.cull_pipeline) {
		vkDestroyPipeline(g.device, g.cull_pipeline, nullptr);
	}
	vkDestroyPipelineLayout(g.device, g.cull_pipeline_layout, nullptr);
	if (g.static_pipeline) {
		vkDestroyPipeline(g.device, g.static_pipeline, nullptr);
	}
	vkDestroyPipelineLayout(g.device, g.static_pipeline_layout, nullptr);
	vkDestroyDescriptorSetLayout(g.device, g.cull_layout, nullptr);
	vkDestroyPipelineLayout(g.device, g.layout3d, nullptr);
	vkDestroyDescriptorSetLayout(g.device, g.scene_layout, nullptr);
	if (g.input_layout) {
		vkDestroyDescriptorSetLayout(g.device, g.input_layout, nullptr);
		g.input_layout = VK_NULL_HANDLE;
	}
	for (int i = 0; i < TEXTURES; i++) {
		destroy_image(g.textures[i]);
	}
	destroy_swapchain();
	stop_gpu_thread();
	destroy_buffer(g.vertex_buffer, g.vertex_allocation);
	destroy_buffer(g.vertex_buffer_alt, g.vertex_allocation_alt);
	destroy_buffer(g.vertex_buffer_alt2, g.vertex_allocation_alt2);
	destroy_pipeline_twins();
	vkDestroyPipeline(g.device, g.triangles, nullptr);
	vkDestroyPipeline(g.device, g.lines, nullptr);
	vkDestroyPipelineLayout(g.device, g.layout, nullptr);
	vkDestroyDescriptorPool(g.device, g.set_pool, nullptr);
	vkDestroyDescriptorSetLayout(g.device, g.set_layout, nullptr);
	destroy_user_samplers();
	vkDestroySampler(g.device, g.sampler, nullptr);
	vkDestroySampler(g.device, g.sampler_repeat, nullptr);
	vkDestroySampler(g.device, g.sampler_clamp, nullptr);
	vkDestroySampler(g.device, g.sampler_repeat_mips, nullptr);
	vkDestroySampler(g.device, g.sampler_clamp_mips, nullptr);
	vkDestroySampler(g.device, g.sampler_point_repeat, nullptr);
	vkDestroySampler(g.device, g.sampler_point_clamp, nullptr);
	vkDestroySampler(g.device, g.sampler_point_repeat_mips, nullptr);
	vkDestroySampler(g.device, g.sampler_point_clamp_mips, nullptr);
	if (profile_query_pool) {
		vkDestroyQueryPool(g.device, profile_query_pool, nullptr);
		profile_query_pool = VK_NULL_HANDLE;
		profile_mark_state = -1;
	}
	destroy_frame_slots();
	vkDestroyCommandPool(g.device, g.pool, nullptr);
	destroy_allocator();
	vkDestroyDevice(g.device, nullptr);
	if (surface().surface) {
		SDL_Vulkan_DestroySurface(g.instance, surface().surface, nullptr);
	}
	vkDestroyInstance(g.instance, nullptr);
}

// A device while there is no window of Graphics, for windows of their own (see graphics_surfaces.cpp). The GPU is picked by
// what can show pictures in a window, so a hidden one stands in for the windows to come and goes away again at once. The
// device draws with a depth of 32 until Graphics asks for another one, which makes it again.
bool bb::gfx::ensure_device()
{
	if (g.device) {
		return true;
	}
	if (g.headless || bb_env_bool("BLITZLLVM_HEADLESS", 0)) {
		return false;
	}
	if (!SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS)) {
		fail(SDL_GetError());
	}
	bb_on_exit(bb_end_graphics);
	g.requested_depth = 32;
	g.buffer_depth    = 32;
	g.buffer_format   = VK_FORMAT_R8G8B8A8_UNORM;
	create_instance();
	SDL_Window* probe = SDL_CreateWindow("", 1, 1, SDL_WINDOW_VULKAN | SDL_WINDOW_HIDDEN);
	if (!probe) {
		fail(SDL_GetError());
	}
	VkSurfaceKHR probe_surface = VK_NULL_HANDLE;
	if (!SDL_Vulkan_CreateSurface(probe, g.instance, nullptr, &probe_surface)) {
		fail(SDL_GetError());
	}
	create_device(probe_surface);
	SDL_Vulkan_DestroySurface(g.instance, probe_surface, nullptr);
	SDL_DestroyWindow(probe);
	return true;
}

// Images, textures and their buffers are made on the GPU, so a program that never calls Graphics gets the machinery of Graphics around a window
// that stays hidden, the first time it makes one. The window is only there for the device to be picked with.
static std::atomic<int> offscreen_held{ 0 };

extern "C" void bb_offscreen_hold(int delta)
{
	offscreen_held += delta;
}

bool bb::gfx::ensure_offscreen()
{
	if (g.created) {
		return !g.headless;
	}
	if (offscreen_held > 0) {
		return false; // The runtime making something for itself, such as the picture of a movie.
	}
	if (bb_env_bool("BLITZLLVM_HEADLESS", 0)) {
		return false;
	}
	if (!SDL_Init(SDL_INIT_VIDEO | SDL_INIT_EVENTS)) {
		return false; // No window system, as in a program that runs on a server.
	}
	surface().window = SDL_CreateWindow("BlitzLLVM", offscreen_size, offscreen_size, SDL_WINDOW_VULKAN | SDL_WINDOW_HIDDEN);
	if (!surface().window) {
		SDL_Quit();
		return false;
	}
	bb_on_exit(bb_end_graphics);
	bb_reset_texture_filters();
	const bool keep_device = g.device != VK_NULL_HANDLE; // From ensure_device, which made it for depth 32 as well.
	g.requested_depth      = 32;
	g.buffer_depth         = 32;
	g.buffer_format        = VK_FORMAT_R8G8B8A8_UNORM;
	g.headless             = false;
	g.width                = uint32_t(offscreen_size);
	g.height               = uint32_t(offscreen_size);
	g.created              = true;
	g.offscreen            = true;
	g.target               = back_buffer;
	if (keep_device) {
		if (!SDL_Vulkan_CreateSurface(surface().window, g.instance, nullptr, &surface().surface)) {
			fail(SDL_GetError());
		}
	} else {
		create_vulkan();
	}
	create_buffers(uint32_t(offscreen_size), uint32_t(offscreen_size));
	return true;
}

