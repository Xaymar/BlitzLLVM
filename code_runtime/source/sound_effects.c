static const bb_fx_param_default* bb_fx_find(int type, int param)
{
	if ((type < 1) || (type > BB_FX_TYPES) || (param < 1) || (param > BB_FXP_COUNT)) {
		return NULL;
	}
	for (int i = 0; (i < 7) && bb_fx_params[type][i].param; i++) {
		if (bb_fx_params[type][i].param == param) {
			return &bb_fx_params[type][i];
		}
	}
	return NULL;
}

int bb_fx_has(int type, int param)
{
	return bb_fx_find(type, param) != NULL;
}

float bb_fx_default(int type, int param)
{
	const bb_fx_param_default* known = bb_fx_find(type, param);
	return known ? known->value : 0.0f;
}

const char* bb_fx_type_name(int type)
{
	return ((type >= 1) && (type <= BB_FX_TYPES)) ? bb_fx_type_names[type] : "";
}

const char* bb_fx_param_name(int param)
{
	return ((param >= 1) && (param <= BB_FXP_COUNT)) ? bb_fx_param_names[param] : "";
}

int bb_fx_in_range(int param, float value, float* low, float* high)
{
	if ((param < 1) || (param > BB_FXP_COUNT)) {
		return 0;
	}
	*low  = bb_fx_ranges[param][0];
	*high = bb_fx_ranges[param][1];
	return (value >= *low) && (value <= *high); // NaN is outside.
}

