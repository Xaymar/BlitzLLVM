// The effects of audio buses. The algorithms are the standard, public ones:
// - Filters and EQ: biquads with the coefficients of Robert Bristow-Johnson's Audio EQ Cookbook.
// - Echo: a delay line with feedback, and a one-pole low-pass in the loop that makes each repeat darker.
// - Reverb: the layout of Freeverb (Jezar at Dreampoint, public domain): 8 comb and 4 all-pass filters per side, with a pre-delay line.
// - Compressor and limiter: a peak follower with attack and release, the gain worked out in dB.
// - Distortion: a tanh curve. Lo-fi: sample-and-hold and fewer bits.
//
// Everything runs in chunks of 32 frames. At the start of each chunk the parameters move toward where their fades are at that moment, with
// a smoothing of 5 ms on top, so that even a change without a fade does not click, and the filters work out new coefficients when they
// moved. Within a chunk, the mix and the echo delay move from frame to frame.

#include <math.h>
#include <stdint.h>
#include <string.h>

#include <SDL3/SDL.h>

#include "memory.h"
#include "sound_effects.h"

extern void* bb_malloc_or_fail(size_t size);

#define BB_FX_CHUNK        32
#define BB_FX_CHANNELS     8      // Of the device, that are worked on. More are passed on as they are.
#define BB_FX_SMOOTHING    0.005f // Seconds.
#define BB_FX_ECHO_LONGEST 4      // Seconds, the most that BB_EFFECTPARAM_DELAY can be.
#define BB_FX_PREDELAY     1      // Seconds, the most that BB_EFFECTPARAM_PREDELAY can be.

typedef struct bb_fx_fade {
	float    from;
	float    to;
	uint64_t start;
	uint64_t length;
} bb_fx_fade;

typedef struct bb_fx_comb {
	float* buffer;
	int    length;
	int    at;
	float  store;
} bb_fx_comb;

typedef struct bb_fx_allpass {
	float* buffer;
	int    length;
	int    at;
} bb_fx_allpass;

struct bb_fx {
	bb_fx*     next; // The next effect in the chain of the bus.
	int        type;
	int        bypass;
	bb_fx_fade params[BB_FXP_COUNT + 1];
	// What the audio thread keeps.
	int   rate;
	int   channels;
	int   primed;    // Whether `now` holds values yet.
	int   broken;    // Its memory could not be had, so it lets the sound through.
	float now[BB_FXP_COUNT + 1];
	float before[BB_FXP_COUNT + 1]; // At the start of the chunk, for what moves from frame to frame.
	float active;                   // 1 while it runs, 0 when bypassed, gliding between.
	// Filters.
	// Direct form I: the last two inputs and outputs, which stay right when the coefficients change (the states of the transposed forms
	// would not, and click when a filter moves fast).
	double x1[BB_FX_CHANNELS];
	double x2[BB_FX_CHANNELS];
	double y1[BB_FX_CHANNELS];
	double y2[BB_FX_CHANNELS];
	float  b0, b1, b2, a1, a2;
	float  made[3]; // The frequency, resonance and gain the coefficients were made for.
	int    made_known;
	// Echo and reverb.
	float*        memory;
	int           line_length;
	int           line_at;
	float         damped[BB_FX_CHANNELS];
	bb_fx_comb    comb[2][8];
	bb_fx_allpass allpass[2][4];
	float*        predelay;
	int           predelay_length;
	int           predelay_at;
	// Compressor and limiter.
	float envelope;
	float gain;
	// Lo-fi.
	float hold[BB_FX_CHANNELS];
	float phase;
};

