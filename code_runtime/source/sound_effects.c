static float bb_fx_quiet(float v)
{
	return (fabsf(v) < 1e-20f) ? 0.0f : v; // Denormal numbers would make the tails of the echo and reverb slow.
}

static const int bb_fx_comb_tuning[8]    = { 1116, 1188, 1277, 1356, 1422, 1491, 1557, 1617 };
static const int bb_fx_allpass_tuning[4] = { 556, 441, 341, 225 };
#define BB_FX_STEREO_SPREAD 23

static int bb_fx_scaled(int samples, int rate)
{
	int scaled = (int)((double)samples * (double)rate / 44100.0 + 0.5);
	return scaled > 1 ? scaled : 1;
}

// Makes the memory of the echo and reverb for the rate and channels of the device, and starts every effect over when they changed.
static void bb_fx_prepare(bb_fx* fx, int channels, int rate)
{
	if ((fx->rate == rate) && (fx->channels == channels)) {
		return;
	}
	SDL_free(fx->memory);
	fx->memory = NULL;
	memset(fx->x1, 0, sizeof(fx->x1));
	memset(fx->x2, 0, sizeof(fx->x2));
	memset(fx->y1, 0, sizeof(fx->y1));
	memset(fx->y2, 0, sizeof(fx->y2));
	memset(fx->damped, 0, sizeof(fx->damped));
	memset(fx->hold, 0, sizeof(fx->hold));
	fx->made_known = 0;
	fx->line_at = fx->predelay_at = 0;
	fx->envelope = 0.0f;
	fx->gain     = 1.0f;
	fx->phase    = 1.0f;
	fx->broken   = 0;
	fx->rate     = rate;
	fx->channels = channels;
	if (fx->type == BB_FX_ECHO) {
		fx->line_length = BB_FX_ECHO_LONGEST * rate + 4;
		fx->memory      = (float*)SDL_calloc((size_t)fx->line_length * (size_t)SDL_min(channels, BB_FX_CHANNELS), sizeof(float));
		fx->broken      = fx->memory == NULL;
	} else if (fx->type == BB_FX_REVERB) {
		size_t total = 0;
		for (int side = 0; side < 2; side++) {
			for (int i = 0; i < 8; i++) {
				total += (size_t)bb_fx_scaled(bb_fx_comb_tuning[i] + side * BB_FX_STEREO_SPREAD, rate);
			}
			for (int i = 0; i < 4; i++) {
				total += (size_t)bb_fx_scaled(bb_fx_allpass_tuning[i] + side * BB_FX_STEREO_SPREAD, rate);
			}
		}
		fx->predelay_length = BB_FX_PREDELAY * rate + 2;
		total += (size_t)fx->predelay_length;
		fx->memory = (float*)SDL_calloc(total, sizeof(float));
		fx->broken = fx->memory == NULL;
		if (fx->memory) {
			float* at = fx->memory;
			for (int side = 0; side < 2; side++) {
				for (int i = 0; i < 8; i++) {
					bb_fx_comb* comb = &fx->comb[side][i];
					comb->length     = bb_fx_scaled(bb_fx_comb_tuning[i] + side * BB_FX_STEREO_SPREAD, rate);
					comb->buffer     = at;
					comb->at         = 0;
					comb->store      = 0.0f;
					at += comb->length;
				}
				for (int i = 0; i < 4; i++) {
					bb_fx_allpass* allpass = &fx->allpass[side][i];
					allpass->length        = bb_fx_scaled(bb_fx_allpass_tuning[i] + side * BB_FX_STEREO_SPREAD, rate);
					allpass->buffer        = at;
					allpass->at            = 0;
					at += allpass->length;
				}
			}
			fx->predelay = at;
		}
	}
}

// The biquad of the Audio EQ Cookbook, for the filter and EQ types.
static void bb_fx_coefficients(bb_fx* fx)
{
	float frequency = fx->now[BB_FXP_FREQUENCY];
	float q         = (fx->type == BB_FX_LOWSHELF || fx->type == BB_FX_HIGHSHELF) ? 0.70710678f : fx->now[BB_FXP_RESONANCE];
	float gain      = fx->now[BB_FXP_GAIN];
	if (fx->made_known && (fx->made[0] == frequency) && (fx->made[1] == q) && (fx->made[2] == gain)) {
		return;
	}
	fx->made[0]    = frequency;
	fx->made[1]    = q;
	fx->made[2]    = gain;
	fx->made_known = 1;

	double f     = SDL_min((double)frequency, 0.49 * fx->rate);
	double w0    = 2.0 * SDL_PI_D * f / fx->rate;
	double cw    = cos(w0);
	double sw    = sin(w0);
	double alpha = sw / (2.0 * q);
	double A     = pow(10.0, gain / 40.0);
	double sA    = sqrt(A);
	double b0 = 1, b1 = 0, b2 = 0, a0 = 1, a1 = 0, a2 = 0;
	switch (fx->type) {
	case BB_FX_LOWPASS:
		b0 = (1 - cw) / 2, b1 = 1 - cw, b2 = (1 - cw) / 2;
		a0 = 1 + alpha, a1 = -2 * cw, a2 = 1 - alpha;
		break;
	case BB_FX_HIGHPASS:
		b0 = (1 + cw) / 2, b1 = -(1 + cw), b2 = (1 + cw) / 2;
		a0 = 1 + alpha, a1 = -2 * cw, a2 = 1 - alpha;
		break;
	case BB_FX_BANDPASS: // A peak of 0 dB.
		b0 = alpha, b1 = 0, b2 = -alpha;
		a0 = 1 + alpha, a1 = -2 * cw, a2 = 1 - alpha;
		break;
	case BB_FX_PEAK:
		b0 = 1 + alpha * A, b1 = -2 * cw, b2 = 1 - alpha * A;
		a0 = 1 + alpha / A, a1 = -2 * cw, a2 = 1 - alpha / A;
		break;
	case BB_FX_LOWSHELF:
		b0 = A * ((A + 1) - (A - 1) * cw + 2 * sA * alpha);
		b1 = 2 * A * ((A - 1) - (A + 1) * cw);
		b2 = A * ((A + 1) - (A - 1) * cw - 2 * sA * alpha);
		a0 = (A + 1) + (A - 1) * cw + 2 * sA * alpha;
		a1 = -2 * ((A - 1) + (A + 1) * cw);
		a2 = (A + 1) + (A - 1) * cw - 2 * sA * alpha;
		break;
	case BB_FX_HIGHSHELF:
		b0 = A * ((A + 1) + (A - 1) * cw + 2 * sA * alpha);
		b1 = -2 * A * ((A - 1) + (A + 1) * cw);
		b2 = A * ((A + 1) + (A - 1) * cw - 2 * sA * alpha);
		a0 = (A + 1) - (A - 1) * cw + 2 * sA * alpha;
		a1 = 2 * ((A - 1) - (A + 1) * cw);
		a2 = (A + 1) - (A - 1) * cw - 2 * sA * alpha;
		break;
	}
	fx->b0 = (float)(b0 / a0);
	fx->b1 = (float)(b1 / a0);
	fx->b2 = (float)(b2 / a0);
	fx->a1 = (float)(a1 / a0);
	fx->a2 = (float)(a2 / a0);
}

// Moves the parameters toward where their fades are at `when`.
static void bb_fx_follow(bb_fx* fx, uint64_t when, float pull)
{
	memcpy(fx->before, fx->now, sizeof(fx->now));
	for (int i = 0; (i < 7) && bb_fx_params[fx->type][i].param; i++) {
		int   p      = bb_fx_params[fx->type][i].param;
		float target = bb_fx_fade_value(&fx->params[p], when);
		if (!fx->primed) {
			fx->now[p] = target;
		} else if (p == BB_FXP_FREQUENCY) { // Frequencies glide evenly in octaves.
			fx->now[p] = expf(logf(fx->now[p]) + (logf(target) - logf(fx->now[p])) * pull);
		} else {
			fx->now[p] += (target - fx->now[p]) * pull;
		}
		if (fabsf(target - fx->now[p]) <= 1e-6f * (1.0f + fabsf(target))) {
			fx->now[p] = target;
		}
	}
	if (!fx->primed) {
		memcpy(fx->before, fx->now, sizeof(fx->now));
		fx->primed = 1;
	}
}

// What the effect makes of one chunk, for the effects that replace the sound (all but the echo and the reverb). `out` holds only the
// channels that are worked on.
static void bb_fx_process(bb_fx* fx, const float* in, float* out, int frames, int channels, int used)
{
	switch (fx->type) {
	case BB_FX_LOWPASS:
	case BB_FX_HIGHPASS:
	case BB_FX_BANDPASS:
	case BB_FX_PEAK:
	case BB_FX_LOWSHELF:
	case BB_FX_HIGHSHELF: {
		bb_fx_coefficients(fx);
		for (int c = 0; c < used; c++) {
			double x1 = fx->x1[c], x2 = fx->x2[c], y1 = fx->y1[c], y2 = fx->y2[c];
			for (int f = 0; f < frames; f++) {
				double x          = in[f * channels + c];
				double y          = fx->b0 * x + fx->b1 * x1 + fx->b2 * x2 - fx->a1 * y1 - fx->a2 * y2;
				x2                = x1;
				x1                = x;
				y2                = y1;
				y1                = y;
				out[f * used + c] = (float)y;
			}
			fx->x1[c] = x1;
			fx->x2[c] = x2;
			fx->y1[c] = fabs(y1) < 1e-30 ? 0.0 : y1;
			fx->y2[c] = fabs(y2) < 1e-30 ? 0.0 : y2;
		}
		break;
	}
	case BB_FX_COMPRESSOR: {
		float attack    = fx->now[BB_FXP_ATTACK] > 0.0f ? expf(-1.0f / (fx->now[BB_FXP_ATTACK] * fx->rate)) : 0.0f;
		float release   = fx->now[BB_FXP_RELEASE] > 0.0f ? expf(-1.0f / (fx->now[BB_FXP_RELEASE] * fx->rate)) : 0.0f;
		float threshold = fx->now[BB_FXP_THRESHOLD];
		float slope     = 1.0f - 1.0f / fx->now[BB_FXP_RATIO];
		float makeup    = fx->now[BB_FXP_GAIN];
		for (int f = 0; f < frames; f++) {
			float level = 0.0f;
			for (int c = 0; c < used; c++) {
				level = SDL_max(level, fabsf(in[f * channels + c]));
			}
			float k       = level > fx->envelope ? attack : release;
			fx->envelope  = bb_fx_quiet(k * fx->envelope + (1.0f - k) * level);
			float over    = 20.0f * log10f(fx->envelope + 1e-30f) - threshold;
			float reduced = over > 0.0f ? over * slope : 0.0f;
			float g       = powf(10.0f, (makeup - reduced) / 20.0f);
			for (int c = 0; c < used; c++) {
				out[f * used + c] = in[f * channels + c] * g;
			}
		}
		break;
	}
	case BB_FX_LIMITER: {
		float ceiling = powf(10.0f, fx->now[BB_FXP_CEILING] / 20.0f);
		float release = fx->now[BB_FXP_RELEASE] > 0.0f ? expf(-1.0f / (fx->now[BB_FXP_RELEASE] * fx->rate)) : 0.0f;
		for (int f = 0; f < frames; f++) {
			float peak = 0.0f;
			for (int c = 0; c < used; c++) {
				peak = SDL_max(peak, fabsf(in[f * channels + c]));
			}
			float wanted = peak > ceiling ? ceiling / peak : 1.0f;
			fx->gain     = wanted < fx->gain ? wanted : wanted + (fx->gain - wanted) * release; // Down at once, up with the release.
			for (int c = 0; c < used; c++) {
				out[f * used + c] = in[f * channels + c] * fx->gain;
			}
		}
		break;
	}
	case BB_FX_DISTORTION: {
		float k     = SDL_max(30.0f * fx->now[BB_FXP_DRIVE], 0.001f);
		float scale = 1.0f / tanhf(k); // So that full scale stays full scale.
		for (int f = 0; f < frames; f++) {
			for (int c = 0; c < used; c++) {
				out[f * used + c] = tanhf(k * in[f * channels + c]) * scale;
			}
		}
		break;
	}
	case BB_FX_LOFI: {
		float step  = fx->now[BB_FXP_RATE] / (float)fx->rate;
		float steps = powf(2.0f, fx->now[BB_FXP_BITS] - 1.0f);
		for (int f = 0; f < frames; f++) {
			fx->phase += step;
			int take = fx->phase >= 1.0f;
			if (take) {
				fx->phase -= floorf(fx->phase);
			}
			for (int c = 0; c < used; c++) {
				if (take) {
					fx->hold[c] = in[f * channels + c];
				}
				out[f * used + c] = floorf(fx->hold[c] * steps + 0.5f) / steps;
			}
		}
		break;
	}
	}
}

// The repeats of the echo come on top of the sound: MIX 0 is only the sound, 0.5 the sound and the repeats at full level, 1 only the
// repeats. When it is bypassed, nothing new goes into the delay line, and what is in it rings out.
static void bb_fx_echo(bb_fx* fx, float* pcm, int frames, int channels, int used, float glide)
{
	float target   = fx->bypass ? 0.0f : 1.0f;
	float feedback = fx->now[BB_FXP_FEEDBACK];
	float damping  = fx->now[BB_FXP_DAMPING] * 0.95f;
	int   length   = fx->line_length;
	for (int f = 0; f < frames; f++) {
		float t     = (float)(f + 1) / (float)frames;
		float mix   = fx->before[BB_FXP_MIX] + (fx->now[BB_FXP_MIX] - fx->before[BB_FXP_MIX]) * t;
		float delay = fx->before[BB_FXP_DELAY] + (fx->now[BB_FXP_DELAY] - fx->before[BB_FXP_DELAY]) * t;
		fx->active += SDL_clamp(target - fx->active, -glide, glide);
		float wet = SDL_min(1.0f, 2.0f * mix);
		float dry = 1.0f + (SDL_min(1.0f, 2.0f * (1.0f - mix)) - 1.0f) * fx->active;
		float d   = SDL_clamp(delay * (float)fx->rate, 1.0f, (float)(length - 3));
		int   whole = (int)d;
		float part  = d - (float)whole;
		int   a     = fx->line_at - whole;
		int   b     = a - 1;
		a += a < 0 ? length : 0;
		b += b < 0 ? length : 0;
		for (int c = 0; c < used; c++) {
			float* line   = fx->memory + (size_t)c * (size_t)length;
			float  read   = line[a] + (line[b] - line[a]) * part;
			float  x      = pcm[f * channels + c];
			fx->damped[c] = bb_fx_quiet(read * (1.0f - damping) + fx->damped[c] * damping);
			line[fx->line_at] = bb_fx_quiet(x * fx->active + fx->damped[c] * feedback);
			pcm[f * channels + c] = x * dry + read * wet;
		}
		if (++fx->line_at >= length) {
			fx->line_at = 0;
		}
	}
}

// Freeverb. It hears all channels and plays on the front pair. MIX works as for the echo.
static void bb_fx_reverb(bb_fx* fx, float* pcm, int frames, int channels, int used, float glide)
{
	float target   = fx->bypass ? 0.0f : 1.0f;
	float room     = fx->now[BB_FXP_SIZE] * 0.28f + 0.7f;
	float damp1    = fx->now[BB_FXP_DAMPING] * 0.4f;
	float damp2    = 1.0f - damp1;
	float width    = fx->now[BB_FXP_WIDTH];
	float wet1     = width / 2.0f + 0.5f;
	float wet2     = (1.0f - width) / 2.0f;
	float in_scale = 0.015f * 2.0f / (float)used;
	int   pre      = (int)(fx->now[BB_FXP_PREDELAY] * (float)fx->rate + 0.5f);
	pre            = SDL_clamp(pre, 0, fx->predelay_length - 1);
	for (int f = 0; f < frames; f++) {
		float t   = (float)(f + 1) / (float)frames;
		float mix = fx->before[BB_FXP_MIX] + (fx->now[BB_FXP_MIX] - fx->before[BB_FXP_MIX]) * t;
		fx->active += SDL_clamp(target - fx->active, -glide, glide);
		float wet = SDL_min(1.0f, 2.0f * mix);
		float dry = 1.0f + (SDL_min(1.0f, 2.0f * (1.0f - mix)) - 1.0f) * fx->active;
		float input = 0.0f;
		for (int c = 0; c < used; c++) {
			input += pcm[f * channels + c];
		}
		input *= in_scale * fx->active;
		fx->predelay[fx->predelay_at] = input;
		int from = fx->predelay_at - pre;
		from += from < 0 ? fx->predelay_length : 0;
		input = fx->predelay[from];
		if (++fx->predelay_at >= fx->predelay_length) {
			fx->predelay_at = 0;
		}
		float out[2] = { 0.0f, 0.0f };
		for (int side = 0; side < 2; side++) {
			for (int i = 0; i < 8; i++) {
				bb_fx_comb* comb          = &fx->comb[side][i];
				float       o             = comb->buffer[comb->at];
				comb->store               = bb_fx_quiet(o * damp2 + comb->store * damp1);
				comb->buffer[comb->at]    = bb_fx_quiet(input + comb->store * room);
				comb->at                  = comb->at + 1 >= comb->length ? 0 : comb->at + 1;
				out[side] += o;
			}
			for (int i = 0; i < 4; i++) {
				bb_fx_allpass* allpass          = &fx->allpass[side][i];
				float          o                = allpass->buffer[allpass->at];
				allpass->buffer[allpass->at]    = bb_fx_quiet(out[side] + o * 0.5f);
				allpass->at                     = allpass->at + 1 >= allpass->length ? 0 : allpass->at + 1;
				out[side]                       = o - out[side];
			}
		}
		float left  = (out[0] * wet1 + out[1] * wet2) * wet;
		float right = (out[1] * wet1 + out[0] * wet2) * wet;
		for (int c = 0; c < used; c++) {
			pcm[f * channels + c] *= dry;
		}
		if (used >= 2) {
			pcm[f * channels + 0] += left;
			pcm[f * channels + 1] += right;
		} else {
			pcm[f * channels] += (left + right) * 0.5f;
		}
	}
}

void bb_fx_run(bb_fx* fx, float* pcm, int frames, int channels, int rate, uint64_t now, uint64_t length)
{
	if ((frames <= 0) || (channels <= 0) || (rate <= 0)) {
		return;
	}
	bb_fx_prepare(fx, channels, rate);
	if (fx->broken) {
		return;
	}
	int   used  = SDL_min(channels, BB_FX_CHANNELS);
	float pull  = 1.0f - expf(-(float)BB_FX_CHUNK / (BB_FX_SMOOTHING * (float)rate));
	float glide = 1.0f / (BB_FX_SMOOTHING * (float)rate);
	float out[BB_FX_CHUNK * BB_FX_CHANNELS];
	for (int start = 0; start < frames; start += BB_FX_CHUNK) {
		int    count = SDL_min(BB_FX_CHUNK, frames - start);
		float* at    = pcm + (size_t)start * (size_t)channels;
		bb_fx_follow(fx, now + (uint64_t)((double)length * start / frames), pull);
		if (fx->type == BB_FX_ECHO) {
			bb_fx_echo(fx, at, count, channels, used, glide);
			continue;
		}
		if (fx->type == BB_FX_REVERB) {
			bb_fx_reverb(fx, at, count, channels, used, glide);
			continue;
		}
		float target = fx->bypass ? 0.0f : 1.0f;
		if ((fx->active == 0.0f) && (target == 0.0f)) {
			continue; // Bypassed: the sound goes through as it is.
		}
		bb_fx_process(fx, at, out, count, channels, used);
		for (int f = 0; f < count; f++) {
			float t   = (float)(f + 1) / (float)count;
			float mix = fx->before[BB_FXP_MIX] + (fx->now[BB_FXP_MIX] - fx->before[BB_FXP_MIX]) * t;
			fx->active += SDL_clamp(target - fx->active, -glide, glide);
			float m = mix * fx->active;
			for (int c = 0; c < used; c++) {
				float x = at[f * channels + c];
				at[f * channels + c] = x + (out[f * used + c] - x) * m;
			}
		}
	}
}
