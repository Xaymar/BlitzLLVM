int32_t bb_len(const char* s)
{
	return (int32_t)bb_slen(s);
}

// Strings compare like memcmp on the common part, and the shorter one is less if that part is equal. NUL is a character.
int32_t bb_str_cmp(const char* a, const char* b)
{
	size_t la = bb_slen(a), lb = bb_slen(b);
	int    r  = memcmp(bb_s(a), bb_s(b), (la < lb) ? la : lb);
	if (r == 0) {
		return (la < lb) ? -1 : ((la > lb) ? 1 : 0);
	}
	return (r < 0) ? -1 : 1;
}

const char* bb_str_concat(const char* a, const char* b)
{
	size_t la = bb_slen(a), lb = bb_slen(b);
	char*  r  = bb_alloc(la + lb);
	memcpy(r, bb_s(a), la);
	memcpy(r + la, bb_s(b), lb);
	return r;
}

const char* bb_str_from_i64(int64_t v)
{
	char     buf[32];
	char*    end = buf + sizeof(buf);
	char*    p   = end;
	uint64_t u   = (v < 0) ? (0 - (uint64_t)v) : (uint64_t)v;
	do {
		*--p = (char)('0' + (u % 10));
		u /= 10;
	} while (u);
	if (v < 0) {
		*--p = '-';
	}
	return bb_copy(p, (size_t)(end - p));
}

const char* bb_str_from_u64(uint64_t v)
{
	char buf[32];
	int  n = snprintf(buf, sizeof(buf), "%llu", (unsigned long long)v);
	return bb_copy(buf, (size_t)n);
}

// Reals print with up to 6 significant digits, and always show a fractional part ("1.0", "0.5").
const char* bb_str_from_f64(double v)
{
	char buf[64];
	if (isnan(v)) {
		return bb_copy("NaN", 3);
	} else if (isinf(v)) {
		return v < 0 ? bb_copy("-Infinity", 9) : bb_copy("Infinity", 8);
	}
	int n = snprintf(buf, sizeof(buf), "%.6g", v);
	if (!strpbrk(buf, ".eE")) {
		n += snprintf(buf + n, sizeof(buf) - (size_t)n, ".0");
	}
	return bb_copy(buf, (size_t)n);
}

// Like atoi in the original: optional white space and sign, then digits, and the first other character ends the number.
// That means "1.9" and "1e3" are 1, and "$FF" and "0x10" are 0. Too large numbers stop at the largest one that fits.
int64_t bb_str_to_i64(const char* s)
{
	s = bb_s(s);
	while (isspace((unsigned char)*s)) {
		s++;
	}
	bool negative = false;
	if ((*s == '-') || (*s == '+')) {
		negative = (*s == '-');
		s++;
	}
	uint64_t limit = negative ? (uint64_t)INT64_MAX + 1 : (uint64_t)INT64_MAX, v = 0;
	for (; (*s >= '0') && (*s <= '9'); s++) {
		unsigned digit = (unsigned)(*s - '0');
		if (v > (limit - digit) / 10) {
			v = limit;
			break;
		}
		v = v * 10 + digit;
	}
	return negative ? (int64_t)(0 - v) : (int64_t)v;
}

// The same for 32 bits, which is what Int and the implicit conversion of the original give.
int32_t bb_str_to_i32(const char* s)
{
	int64_t v = bb_str_to_i64(s);
	return (v > INT32_MAX) ? INT32_MAX : ((v < INT32_MIN) ? INT32_MIN : (int32_t)v);
}

double bb_str_to_f64(const char* s)
{
	return strtod(bb_s(s), NULL);
}

const char* bb_left(const char* s, int32_t n)
{
	size_t len = bb_slen(s);
	if (n < 0) {
		n = 0;
	}
	return bb_copy(bb_s(s), ((size_t)n < len) ? (size_t)n : len);
}

const char* bb_right(const char* s, int32_t n)
{
	size_t len = bb_slen(s);
	if (n < 0) {
		n = 0;
	}
	size_t take = ((size_t)n < len) ? (size_t)n : len;
	return bb_copy(bb_s(s) + (len - take), take);
}

// Mid$(s, start[, count]), start is 1-based. A count below zero means "until the end".
const char* bb_mid(const char* s, int32_t start, int32_t count)
{
	size_t len = bb_slen(s);
	if (start < 1) {
		start = 1;
	}
	if ((size_t)(start - 1) >= len) {
		return bb_copy("", 0);
	}
	size_t avail = len - (size_t)(start - 1);
	size_t take  = (count < 0 || (size_t)count > avail) ? avail : (size_t)count;
	return bb_copy(bb_s(s) + (start - 1), take);
}

const char* bb_upper(const char* s)
{
	size_t len = bb_slen(s);
	char*  r   = bb_copy(bb_s(s), len);
	for (size_t i = 0; i < len; i++) {
		r[i] = (char)toupper((unsigned char)r[i]);
	}
	return r;
}

const char* bb_lower(const char* s)
{
	size_t len = bb_slen(s);
	char*  r   = bb_copy(bb_s(s), len);
	for (size_t i = 0; i < len; i++) {
		r[i] = (char)tolower((unsigned char)r[i]);
	}
	return r;
}

const char* bb_trim(const char* s)
{
	const char* b   = bb_s(s);
	size_t      len = bb_slen(s);
	while (len && isspace((unsigned char)*b)) {
		b++;
		len--;
	}
	while (len && isspace((unsigned char)b[len - 1])) {
		len--;
	}
	return bb_copy(b, len);
}

const char* bb_chr(int32_t c)
{
	char buf[1] = { (char)c };
	return bb_copy(buf, 1);
}

int32_t bb_asc(const char* s)
{
	return (int32_t)(unsigned char)bb_s(s)[0]; // The first character, which can be NUL.
}

// Instr(s, find[, start]), 1-based, 0 if not found.
static const char* bb_memmem(const char* s, size_t len, const char* find, size_t find_len)
{
	if (find_len > len) {
		return NULL;
	}
	for (size_t i = 0; i + find_len <= len; i++) {
		if (!memcmp(s + i, find, find_len)) {
			return s + i;
		}
	}
	return NULL;
}

int32_t bb_instr(const char* s, const char* find, int32_t start)
{
	size_t len = bb_slen(s);
	if (start < 1) {
		start = 1;
	}
	if ((size_t)(start - 1) > len) {
		return 0;
	}
	const char* p = bb_memmem(bb_s(s) + (start - 1), len - (size_t)(start - 1), bb_s(find), bb_slen(find));
	return p ? (int32_t)(p - bb_s(s)) + 1 : 0;
}

const char* bb_replace(const char* s, const char* from, const char* to)
{
	size_t ls = bb_slen(s), lf = bb_slen(from), lt = bb_slen(to);
	if (lf == 0) {
		return bb_copy(bb_s(s), ls);
	}
	size_t count = 0;
	const char *p, *rest = bb_s(s);
	size_t left = ls;
	while ((p = bb_memmem(rest, left, bb_s(from), lf))) {
		count++;
		left -= (size_t)(p - rest) + lf;
		rest = p + lf;
	}
	// 64 bits, as the sum is larger than size_t on 32 bit targets and would wrap to a small allocation.
	uint64_t total = (uint64_t)ls + (uint64_t)count * lt - (uint64_t)count * lf;
	if (total > INT32_MAX) {
		bb_runtime_error("String is too long.");
	}
	char* r   = bb_alloc((size_t)total);
	char* out = r;
	rest = bb_s(s);
	left = ls;
	while ((p = bb_memmem(rest, left, bb_s(from), lf))) {
		memcpy(out, rest, (size_t)(p - rest));
		out += p - rest;
		memcpy(out, bb_s(to), lt);
		out += lt;
		left -= (size_t)(p - rest) + lf;
		rest = p + lf;
	}
	memcpy(out, rest, left);
	return r;
}

const char* bb_string_repeat(const char* s, int32_t n)
{
	size_t len = bb_slen(s);
	if (n < 0) {
		n = 0;
	}
	// 64 bits, as the product is larger than size_t on 32 bit targets and would wrap to a small allocation.
	uint64_t total = (uint64_t)len * (uint64_t)n;
	if (total > INT32_MAX) {
		bb_runtime_error("String is too long.");
	}
	char* r = bb_alloc((size_t)total);
	for (int32_t i = 0; i < n; i++) {
		memcpy(r + len * (size_t)i, bb_s(s), len);
	}
	return r;
}

const char* bb_hex(int32_t v)
{
	char buf[16];
	int  n = snprintf(buf, sizeof(buf), "%08X", (unsigned)v);
	return bb_copy(buf, (size_t)n);
}

const char* bb_bin(int32_t v)
{
	char buf[33];
	for (int i = 0; i < 32; i++) {
		buf[i] = ((unsigned)v & (1u << (31 - i))) ? '1' : '0';
	}
	return bb_copy(buf, 32);
}
