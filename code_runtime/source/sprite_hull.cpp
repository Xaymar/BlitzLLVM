// The shape that a sprite is drawn with: not the whole square, but the part of it that a texture is visible in.

#include "graphics_internal.hpp"
#include "scene_internal.hpp"

#include <algorithm>
#include <vector>

namespace bb::gfx {
	namespace {
		struct corner {
			float x, y;
		};

		// Keeps the part of the polygon where a * x + b * y <= c.
		void clip(std::vector<corner>& polygon, float a, float b, float c)
		{
			std::vector<corner> out;
			for (size_t i = 0; i < polygon.size(); i++) {
				corner p = polygon[i], q = polygon[(i + 1) % polygon.size()];
				float  dp = a * p.x + b * p.y - c, dq = a * q.x + b * q.y - c;
				if (dp <= 0) {
					out.push_back(p);
				}
				if ((dp < 0 && dq > 0) || (dp > 0 && dq < 0)) {
					float t = dp / (dp - dq);
					out.push_back({ p.x + (q.x - p.x) * t, p.y + (q.y - p.y) * t });
				}
			}
			polygon = std::move(out);
		}

		float area(std::vector<corner> const& polygon)
		{
			float sum = 0;
			for (size_t i = 0; i < polygon.size(); i++) {
				corner p = polygon[i], q = polygon[(i + 1) % polygon.size()];
				sum += p.x * q.y - q.x * p.y;
			}
			return 0.5f * fabsf(sum);
		}
	} // namespace

	// Finds the smallest octagon (a square with its corners cut off along the 4 diagonal directions) that has all of the
	// visible pixels in it, and makes it a bit bigger so that filtering and mip maps do not show a cut. A round texture such as a
	// flame or a puff of smoke needs 17% less area than the square, and anything that fills the square gets no hull.
	void sprite_hull_compute(sprite_hull& hull, const uint8_t* rgba, int width, int height, size_t pitch, int flags)
	{
		sprite_hull_drop(hull);
		if (!rgba || width <= 0 || height <= 0 || !(flags & (TEXTURE_ALPHA | TEXTURE_MASKED))) {
			return;
		}
		const bool alpha = (flags & TEXTURE_ALPHA) != 0, masked = (flags & TEXTURE_MASKED) != 0;

		// The extent along x, y, x + y and x - y of the pixels that can be seen, in the coordinates of the sprite: -1 to 1, y up.
		float lo[4] = { 1e9f, 1e9f, 1e9f, 1e9f }, hi[4] = { -1e9f, -1e9f, -1e9f, -1e9f };
		bool  any = false;
		for (int j = 0; j < height; j++) {
			const uint8_t* row = rgba + size_t(j) * pitch * 4;
			float          y   = 1.0f - 2.0f * (float(j) + 0.5f) / float(height);
			// Only the first and the last visible pixel of a row count for x, but they all count for the diagonals; the
			// extreme ones are at the ends of the run, so looking at both ends is enough.
			int first = -1, last = -1;
			for (int i = 0; i < width; i++) {
				const uint8_t* px = row + size_t(i) * 4;
				if ((alpha && px[3] == 0) || (masked && !(px[0] | px[1] | px[2]))) {
					continue;
				}
				if (first < 0) {
					first = i;
				}
				last = i;
			}
			if (first < 0) {
				continue;
			}
			any = true;
			for (int i : { first, last }) {
				float x    = 2.0f * (float(i) + 0.5f) / float(width) - 1.0f;
				float v[4] = { x, y, x + y, x - y };
				for (int k = 0; k < 4; k++) {
					lo[k] = std::min(lo[k], v[k]);
					hi[k] = std::max(hi[k], v[k]);
				}
			}
		}
		if (!any) {
			return;
		}

		// A filtered pixel has something in it when a pixel one step away does, which is the exact reach without mip maps. Mip
		// maps are blurred more the smaller the sprite is on the screen, so they get a bit more room that no step can be exact for.
		const bool mips = (flags & TEXTURE_MIPMAPS) != 0;
		float      px = 2.0f / float(width) * (mips ? 2.0f : 1.0f) + (mips ? 0.02f : 0.0f), py = 2.0f / float(height) * (mips ? 2.0f : 1.0f) + (mips ? 0.02f : 0.0f);
		lo[0] -= px;
		hi[0] += px;
		lo[1] -= py;
		hi[1] += py;
		lo[2] -= px + py;
		hi[2] += px + py;
		lo[3] -= px + py;
		hi[3] += px + py;

		std::vector<corner> polygon = { { -1, -1 }, { 1, -1 }, { 1, 1 }, { -1, 1 } };
		clip(polygon, 1, 0, hi[0]);
		clip(polygon, -1, 0, -lo[0]);
		clip(polygon, 0, 1, hi[1]);
		clip(polygon, 0, -1, -lo[1]);
		clip(polygon, 1, 1, hi[2]);
		clip(polygon, -1, -1, -lo[2]);
		clip(polygon, 1, -1, hi[3]);
		clip(polygon, -1, 1, -lo[3]);

		// Not worth more triangles when it hardly cuts anything.
		if (polygon.size() < 3 || polygon.size() > 8 || area(polygon) > 0.9f * 4.0f) {
			return;
		}
		hull.valid = true;
		hull.count = int(polygon.size());
		for (size_t i = 0; i < polygon.size(); i++) {
			hull.point[i][0] = polygon[i].x;
			hull.point[i][1] = polygon[i].y;
		}
	}

	void sprite_hull_drop(sprite_hull& hull)
	{
		if (hull.geometry) {
			bb::surface* s = static_cast<bb::surface*>(hull.geometry);
			bb_release_surface_gpu(s->gpu);
			s->vertices.release();
			s->indices.release();
			delete s;
		}
		hull = sprite_hull();
	}

	// The geometry of the hull, which every sprite of a texture draws instead of the square.
	bb::surface* sprite_hull_surface(sprite_hull& hull)
	{
		if (!hull.valid) {
			return nullptr;
		}
		if (!hull.geometry) {
			bb::surface* s = new bb::surface();
			for (int i = 0; i < hull.count; i++) {
				float x = hull.point[i][0], y = hull.point[i][1];
				bb::scene::add_vertex(s, x, y, 0, 0, 0, -1, (x + 1) / 2, 1 - (y + 1) / 2);
			}
			for (int i = 1; i + 1 < hull.count; i++) {
				bb::scene::add_oriented_triangle(s, 0, uint32_t(i), uint32_t(i + 1));
			}
			hull.geometry = s;
		}
		return static_cast<bb::surface*>(hull.geometry);
	}
} // namespace bb::gfx
