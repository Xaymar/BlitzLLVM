#pragma once
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>

// What Blitz calls files, directories and network streams are all handles to one of these. ReadInt, WriteLine and
// the others work on any stream that can be read or written, so network connections only have to provide callbacks.

enum {
	BB_STREAM_NONE = 0, // A free slot.
	BB_STREAM_FILE,
	BB_STREAM_DIR,
	BB_STREAM_NET,
};

typedef struct bb_stream {
	int   kind;
	FILE* file;

	// Directories
	void* dir_handle;
	void* dir_data;
	int   dir_first;

	// Everything else
	void* user;
	size_t (*read)(struct bb_stream* stream, void* data, size_t size);
	size_t (*write)(struct bb_stream* stream, const void* data, size_t size);
	int32_t (*available)(struct bb_stream* stream);
	int32_t (*at_end)(struct bb_stream* stream);
	void (*close)(struct bb_stream* stream);
} bb_stream;

int32_t    bb_stream_add(bb_stream stream);
bb_stream* bb_stream_get(int32_t handle, const char* what);
void       bb_stream_remove(int32_t handle);

static inline size_t bb_stream_read(bb_stream* stream, void* data, size_t size)
{
	return stream->read ? stream->read(stream, data, size) : 0;
}

static inline size_t bb_stream_write(bb_stream* stream, const void* data, size_t size)
{
	return stream->write ? stream->write(stream, data, size) : 0;
}

static inline int32_t bb_stream_available(bb_stream* stream)
{
	return stream->available ? stream->available(stream) : 0;
}

static inline int32_t bb_stream_eof(bb_stream* stream)
{
	return stream->at_end ? stream->at_end(stream) : 1;
}
