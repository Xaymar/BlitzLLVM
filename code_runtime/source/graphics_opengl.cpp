	// A window with a thread of its own gets a context of its own, which shares the images with the context of the program's thread.
	void create_window_presenter(window_presenter& presenter, uint32_t queue_index)
	{
		gl_presenter* own = new gl_presenter();
		SDL_GL_SetAttribute(SDL_GL_SHARE_WITH_CURRENT_CONTEXT, 1);
		own->context = SDL_GL_CreateContext(glc.helper);
		SDL_GL_SetAttribute(SDL_GL_SHARE_WITH_CURRENT_CONTEXT, 0);
		SDL_GL_MakeCurrent(glc.current, glc.context); // Making a context puts it in the place of this thread's.
		if (!own->context) {
			delete own;
			gfx::fail(SDL_GetError());
		}
		presenter.device       = uint64_t(uintptr_t(own));
		presenter.timeline     = uint64_t(uintptr_t(new gl_timeline()));
		presenter.queue        = 1;
		presenter.queue_index  = queue_index;
		presenter.acquired     = 1;
		presenter.present_wait = false;
	}

	void destroy_window_presenter(window_presenter& presenter)
	{
		if (gl_presenter* own = reinterpret_cast<gl_presenter*>(uintptr_t(presenter.device))) {
			SDL_GL_DestroyContext(own->context); // The thread let go of it after every picture.
			delete own;
		}
		delete reinterpret_cast<gl_timeline*>(uintptr_t(presenter.timeline));
		presenter = window_presenter();
	}

	// Waits until the handover with that number was sent. Whether the GPU is done with its drawing is waited for by show_picture, which has a context.
	wait_status wait_timeline(const window_presenter& presenter, uint64_t value, uint64_t timeout_ns)
	{
		gl_timeline*                 timeline = reinterpret_cast<gl_timeline*>(uintptr_t(presenter.timeline));
		std::unique_lock<std::mutex> guard(timeline->lock);
		bool reached = timeline->changed.wait_for(guard, std::chrono::nanoseconds(timeout_ns), [&] { return timeline->value >= value; });
		return reached ? wait_status::reached : wait_status::timeout;
	}

	show_result show_picture(window_presenter& presenter, swapchain& chain, uint64_t picture, uint32_t w, uint32_t h)
	{
		show_result     shown;
		gl_presenter*   own      = reinterpret_cast<gl_presenter*>(uintptr_t(presenter.device));
		gl_timeline*    timeline = reinterpret_cast<gl_timeline*>(uintptr_t(presenter.timeline));
		const gl_chain* target   = reinterpret_cast<const gl_chain*>(uintptr_t(chain.handle));
		int             now_w = 0, now_h = 0;
		if (!own || !target) {
			return shown;
		}
		SDL_GetWindowSizeInPixels(target->window, &now_w, &now_h);
		if ((uint32_t(now_w) != chain.width) || (uint32_t(now_h) != chain.height) || !SDL_GL_MakeCurrent(target->window, own->context)) {
			return shown; // The swapchain has to be made again.
		}
		SDL_GL_SetSwapInterval(0); // A present of such a window never waits for the display.
		// The drawing of the picture was sent by the other context. It is there for this one once the GPU is done with it.
		gl_fence* fence = nullptr;
		{
			std::lock_guard<std::mutex> guard(timeline->lock);
			fence = timeline->fence;
		}
		for (bool done = (fence == nullptr); !done;) {
			{
				std::lock_guard<std::mutex> guard(fence_lock);
				done = !fence->sync || (gl::ClientWaitSync(fence->sync, 0, 0) != GL_TIMEOUT_EXPIRED);
			}
			if (!done) {
				SDL_DelayNS(200000);
			}
		}
		if (!own->framebuffer) {
			gl::GenFramebuffers(1, &own->framebuffer);
		}
		gl::BindFramebuffer(GL_READ_FRAMEBUFFER, own->framebuffer);
		attach(GL_READ_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, image_of(picture), 0, 0);
		gl::BindFramebuffer(GL_DRAW_FRAMEBUFFER, 0);
		// The picture fills the window, turned over as every picture that goes to a window. Until the program draws one of the new size after a resize, the old one is stretched.
		gl::BlitFramebuffer(0, 0, GLint(w), GLint(h), 0, GLint(chain.height), GLint(chain.width), 0, GL_COLOR_BUFFER_BIT, GL_NEAREST);
		SDL_GL_SwapWindow(target->window);
		gl::Finish(); // The picture may be drawn into again once the copy is done.
		SDL_GL_MakeCurrent(nullptr, nullptr);
		shown.stage     = show_result::stage::submitted;
		shown.presented = present_status::ok;
		return shown;
	}

