		// The calls that wait for the end of the recording: each is a function and what it was called with, one after the other in tape.
		// kept holds copies of the arrays that calls were given, until the calls are done.
		std::vector<uint64_t> tape;
		std::vector<void*>    kept;

		template <class F>
		void record(F&& call)
		{
			using T = std::decay_t<F>;
			static_assert(std::is_trivially_copyable_v<T> && std::is_trivially_destructible_v<T> && (alignof(T) <= alignof(uint64_t)), "a recorded call holds plain values only");
			void (*run)(const void*) = [](const void* what) { (*static_cast<const T*>(what))(); };
			size_t words = 2 + (sizeof(T) + 7) / 8;
			size_t at    = tape.size();
			tape.resize(at + words);
			tape[at]     = uint64_t(reinterpret_cast<uintptr_t>(run));
			tape[at + 1] = words;
			memcpy(&tape[at + 2], &call, sizeof(T));
		}

		template <class T>
		const T* keep(const T* data, size_t count)
		{
			T* copy = static_cast<T*>(bb_malloc(count * sizeof(T) + 1));
			if (!copy) {
				fail("Out of memory.");
			}
			memcpy(static_cast<void*>(copy), data, count * sizeof(T));
			kept.push_back(copy);
			return copy;
		}

		void forget_recorded_calls()
		{
			tape.clear();
			for (void* copy : kept) {
				bb_free(copy);
			}
			kept.clear();
		}

		// Does everything that was recorded, in order.
		void play()
		{
			for (size_t at = 0; at < tape.size(); at += size_t(tape[at + 1])) {
				reinterpret_cast<void (*)(const void*)>(uintptr_t(tape[at]))(&tape[at + 2]);
			}
			forget_recorded_calls();
		}

