	void begin_pass(const pass_desc& desc)
	{
		framebuffer_entry wanted;
		const gl_view*    views[5] = {};
		for (uint32_t i = 0; i < desc.color_count; i++) {
			views[i] = view_of(desc.colors[i].view);
		}
		views[4] = desc.has_depth ? view_of(desc.depth.view) : nullptr;
		for (uint32_t i = 0; i < 5; i++) {
			wanted.textures[i] = views[i] ? views[i]->image->texture : 0;
			wanted.layers[i]   = views[i] ? views[i]->layer : 0;
		}
		GLuint framebuffer = 0;
		for (const framebuffer_entry& entry : glc.framebuffers) {
			if (!memcmp(entry.textures, wanted.textures, sizeof(wanted.textures)) && !memcmp(entry.layers, wanted.layers, sizeof(wanted.layers))) {
				framebuffer = entry.id;
				break;
			}
		}
		if (framebuffer) {
			gl::BindFramebuffer(GL_DRAW_FRAMEBUFFER, framebuffer);
		} else {
			gl::GenFramebuffers(1, &wanted.id);
			gl::BindFramebuffer(GL_DRAW_FRAMEBUFFER, wanted.id);
			GLenum buffers[4] = { GL_COLOR_ATTACHMENT0, GL_COLOR_ATTACHMENT1, GL_COLOR_ATTACHMENT2, GL_COLOR_ATTACHMENT3 };
			for (uint32_t i = 0; i < desc.color_count; i++) {
				attach(GL_DRAW_FRAMEBUFFER, buffers[i], views[i] ? views[i]->image : nullptr, 0, views[i] ? views[i]->layer : 0);
				buffers[i] = views[i] ? buffers[i] : GL_NONE;
			}
			if (views[4]) {
				attach(GL_DRAW_FRAMEBUFFER, bb::rhi::has_stencil(views[4]->image->format) ? GL_DEPTH_STENCIL_ATTACHMENT : GL_DEPTH_ATTACHMENT, views[4]->image, 0, views[4]->layer);
			}
			gl::DrawBuffers(GLsizei(desc.color_count), buffers);
			glc.framebuffers.push_back(wanted);
		}
		glc.pass_depth   = desc.has_depth;
		glc.pass_stencil = views[4] && bb::rhi::has_stencil(views[4]->image->format);
		glc.stencil      = bb::rhi::stencil_state();
		set_viewport(desc.viewport[0], desc.viewport[1], desc.viewport[2], desc.viewport[3]);
		set_scissor(desc.scissor[0], desc.scissor[1], desc.scissor[2], desc.scissor[3]);
		for (uint32_t i = 0; i < desc.color_count; i++) {
			if (views[i] && (desc.colors[i].load == load_op::clear)) {
				clear_attachment(GL_COLOR, GLint(i), desc.colors[i].clear, nullptr);
			}
		}
		if (views[4] && (desc.depth.load == load_op::clear)) {
			clear_attachment(GL_DEPTH, 0, desc.depth.clear, nullptr);
			if (glc.pass_stencil) {
				clear_stencil_attachment(desc.stencil_clear, nullptr);
			}
		}
		apply_state();
	}

