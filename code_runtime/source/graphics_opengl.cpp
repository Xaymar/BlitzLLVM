	binding_group combine_texture_groups(frame_groups& groups, const binding_group* sources, uint32_t count)
	{
		// The pools hold the groups themselves here, and used counts the ones that the frame has taken.
		if (groups.used == groups.pools.size()) {
			groups.pools.push_back(uint64_t(uintptr_t(new gl_group())));
		}
		gl_group* group = reinterpret_cast<gl_group*>(uintptr_t(groups.pools[groups.used++]));
		for (uint32_t k = 0; k < count; k++) {
			group->slots[k] = group_of(sources[k])->slots[0];
		}
		return binding_group{ uint64_t(uintptr_t(group)) };
	}

