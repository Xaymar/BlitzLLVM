// OpenGL 4.3: the device (a context), the pictures of windows, pipelines, and the images and buffers on the GPU.
//
// How it differs from the Vulkan backend:
// - There are no command buffers, so the backend keeps a list of its own: the calls that Vulkan records (passes, draws, copies) are
//   written down and done when the recording ends, on the thread that made the context (the thread of the program). The shared code
//   counts on that order: it may write to a mapped buffer after it recorded the draw that reads it. The submission thread has nothing
//   to send, and a picture is shown where its window image changes to the state present.
// - Pictures are kept the way Vulkan keeps them, with the first row of an image as the top one. OpenGL calls that row the bottom one,
//   so what is drawn into images is upside down in OpenGL's eyes, which changes nothing but the winding of front faces. Only the
//   copy into the window turns the picture over. Depth runs from 0 to 1 as on Vulkan (ARB_clip_control).
// - A shader is GLSL made from the SPIR-V by tools/translate_shaders.py (shaders_opengl.inc), found by the hash of the SPIR-V words.
//   Its specialization constants are #defines, so a program is compiled for each set of constants. What a program reads has a name
//   that says the set and the binding (see opengl_glsl in the tool), from which the texture units and buffer bindings are given out.
// - Buffers that the CPU writes are mapped for good (ARB_buffer_storage), as the shared code expects.
