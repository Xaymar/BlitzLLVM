	// Only the thread of the context can make a buffer. A loader thread is told no, and the surface gets its buffers when it is first drawn.
	bool create_buffer_any_thread(gpu_buffer& buffer, uint64_t size, buffer_usage usage, memory where)
	{
		if (!on_context_thread()) {
			return false;
		}
		opengl::create_buffer(buffer, size, usage, where);
		return true;
	}

	void destroy_buffer_any_thread(gpu_buffer& buffer)
	{
		if (on_context_thread()) {
			opengl::destroy_buffer(buffer);
		} else if (buffer.vk) {
			std::lock_guard<std::mutex> guard(orphan_lock);
			orphans.push_back(GLuint(buffer.vk));
			buffer = gpu_buffer();
		}
	}
