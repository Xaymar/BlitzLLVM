		bb::rhi::shader create_shader(const unsigned int* words, size_t size)
		{
			uint64_t       hash  = 0xCBF29CE484222325ull;
			const uint8_t* bytes = reinterpret_cast<const uint8_t*>(words);
			for (size_t i = 0; i < size; i++) {
				hash = (hash ^ bytes[i]) * 0x100000001B3ull;
			}
			for (size_t i = 0; i < std::size(shader_sources); i++) {
				if ((shader_sources[i].hash == hash) && (size_t(shader_sources[i].words) * 4 == size)) {
					return bb::rhi::shader{ uint64_t(i + 1) };
				}
			}
			fail("internal error: a shader has no GLSL (tools/translate_shaders.py --opengl was not run after the shaders changed).");
		}

