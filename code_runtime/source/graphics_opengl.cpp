	bool read_timestamps(uint32_t first, uint32_t count, double* nanoseconds)
	{
		GLint ready = 0;
		gl::GetQueryObjectiv(glc.queries[first + count - 1], GL_QUERY_RESULT_AVAILABLE, &ready);
		if (!ready) {
			return false;
		}
		for (uint32_t i = 0; i < count; i++) {
			GLuint64 time = 0;
			gl::GetQueryObjectui64v(glc.queries[first + i], GL_QUERY_RESULT, &time);
			nanoseconds[i] = double(time);
		}
		return true;
	}

	static void drop_fence(gl_fence* fence)
	{
		std::lock_guard<std::mutex> guard(fence_lock);
		if (fence && fence->sync) {
			gl::DeleteSync(fence->sync);
			fence->sync = nullptr;
		}
	}

	bool submit_and_wait(uint64_t, uint64_t)
	{
		play();
		drop_fence(glc.fence);
		gl::Finish();
		return true;
	}

	void begin_commands()
	{
		forget_recorded_calls();
		delete_orphans();
	}

	// The end of the recording is where its calls are done, here on the thread of the context. The fence of the slot tells when the GPU is done with them.
	void end_commands()
	{
		play();
		if (glc.fence) {
			drop_fence(glc.fence);
			std::lock_guard<std::mutex> guard(fence_lock);
			glc.fence->sync = gl::FenceSync(GL_SYNC_GPU_COMMANDS_COMPLETE, 0);
		}
		gl::Flush();
	}

