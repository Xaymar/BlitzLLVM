	// The programs stay: they are shared by pipelines and found again by the next pipeline of the same shaders.
	void destroy_pipeline(pipeline p)
	{
		if (!p) {
			return;
		}
		pipeline_object& object = pipeline_objects[p.id - 1];
		for (auto& built : object.built) {
			if (glc.pipeline == &built.second) {
				glc.pipeline = nullptr;
			}
			if (glc.compute == &built.second) {
				glc.compute = nullptr;
			}
		}
		object = pipeline_object();
	}

