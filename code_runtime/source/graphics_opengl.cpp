	// For the submission thread, which has no context: there is nothing to send, see end_commands. A handover of a picture to the thread of a window is told to it here.
	int32_t submit_frame(uint64_t, const frame_sync& sync, const submission& what)
	{
		if (gl_timeline* timeline = reinterpret_cast<gl_timeline*>(uintptr_t(what.timeline))) {
			std::lock_guard<std::mutex> guard(timeline->lock);
			timeline->value = what.timeline_value;
			timeline->fence = reinterpret_cast<gl_fence*>(uintptr_t(sync.fence));
			timeline->changed.notify_all();
		}
		return 0;
	}

	frame_sync create_frame_sync()
	{
		frame_sync sync;
		gl_fence* fence = nullptr;
		{
			std::lock_guard<std::mutex> guard(fence_lock);
			if (!spare_fences.empty()) {
				fence = spare_fences.back();
				spare_fences.pop_back();
			}
		}
		sync.cmd      = 1;
		sync.fence    = uint64_t(uintptr_t(fence ? fence : new gl_fence()));
		sync.acquired = 1;
		return sync;
	}

	void destroy_frame_sync(frame_sync& sync)
	{
		gl_fence* fence = reinterpret_cast<gl_fence*>(uintptr_t(sync.fence));
		drop_fence(fence);
		if (glc.fence == fence) {
			glc.fence = nullptr;
		}
		if (fence) {
			std::lock_guard<std::mutex> guard(fence_lock);
			spare_fences.push_back(fence);
		}
		sync = frame_sync();
	}

	void wait_frame_sync(const frame_sync& sync)
	{
		gl_fence* fence = reinterpret_cast<gl_fence*>(uintptr_t(sync.fence));
		if (fence && fence->sync) {
			while (gl::ClientWaitSync(fence->sync, GL_SYNC_FLUSH_COMMANDS_BIT, 1000000000ull) == GL_TIMEOUT_EXPIRED) {
			}
			drop_fence(fence);
		}
	}

	void wait_idle()
	{
		if (on_context_thread()) {
			gl::Finish();
		}
	}

	// The pictures of a window are its back buffer, which is one image as far as the shared code is concerned. The surface of a window is the window.
	bool create_swapchain(swapchain& sc, const swapchain_desc& d)
	{
		SDL_Window* window = reinterpret_cast<SDL_Window*>(uintptr_t(d.surface));
		int         w = 0, h = 0;
		SDL_GetWindowSizeInPixels(window, &w, &h);
		sc        = swapchain();
		sc.width  = uint32_t(w);
		sc.height = uint32_t(h);
		if ((w <= 0) || (h <= 0)) {
			return true; // Minimized.
		}
		gl_chain* chain      = new gl_chain();
		chain->window        = window;
		chain->interval      = ((d.vsync == 1) && !d.own_thread) ? 1 : 0;
		chain->image         = new gl_image();
		chain->image->window = window;
		chain->image->width  = uint32_t(w);
		chain->image->height = uint32_t(h);
		chain->image->format = format::rgba8;
		SDL_SetPointerProperty(SDL_GetWindowProperties(window), "blitzllvm.opengl.chain", chain);
		sc.handle    = uint64_t(uintptr_t(chain));
		sc.count     = 1;
		sc.images[0] = uint64_t(uintptr_t(chain->image));
		return true;
	}

