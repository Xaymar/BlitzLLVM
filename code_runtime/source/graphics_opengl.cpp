	uint32_t sample_counts()
	{
		GLint color = 1, depth = 1;
		gl::GetIntegerv(GL_MAX_COLOR_TEXTURE_SAMPLES, &color);
		gl::GetIntegerv(GL_MAX_DEPTH_TEXTURE_SAMPLES, &depth);
		uint32_t most = uint32_t(color < depth ? color : depth), counts = 0;
		for (uint32_t count = 1; (count <= most) && (count <= 64); count *= 2) {
			counts |= count;
		}
		return counts;
	}

