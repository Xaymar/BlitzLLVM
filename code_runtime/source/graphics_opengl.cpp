	// OpenGL itself does not say how much video memory there is. Two extensions do, in kilobytes: GL_NVX_gpu_memory_info (NVIDIA, and Mesa for some drivers) and GL_ATI_meminfo (AMD). Without them both numbers are 0, which the shared code reads as "not known".
	static uint64_t video_memory_free()
	{
		static std::atomic<uint64_t> last{0};
		if (on_context_thread()) {
			GLint kb[4] = {0, 0, 0, 0};
			if (glc.memory_nvx) {
				gl::GetIntegerv(0x9049 /* GL_GPU_MEMORY_INFO_CURRENT_AVAILABLE_VIDMEM_NVX */, kb);
			} else if (glc.memory_ati) {
				gl::GetIntegerv(0x87FC /* GL_TEXTURE_FREE_MEMORY_ATI */, kb);
			}
			last = uint64_t(kb[0] > 0 ? kb[0] : 0) * 1024;
		}
		return last;
	}

	uint64_t total_video_memory()
	{
		return glc.memory_total;
	}

	void memory_budget(uint64_t& used, uint64_t& total)
	{
		total = glc.memory_total;
		if (!total) {
			used = 0;
			return;
		}
		uint64_t left = video_memory_free();
		used = total > left ? total - left : 0;
	}

	// A context is not lost the way a Vulkan device is. The code is the one that OpenGL has for it, for the test hook that pretends.
	int32_t device_lost_result()
	{
		return int32_t(GL_CONTEXT_LOST);
	}

	bool is_device_loss(int32_t native)
	{
		return native == int32_t(GL_CONTEXT_LOST);
	}

	const char* native_result_name(int32_t native)
	{
		switch (native) {
		case GL_CONTEXT_LOST: return "GL_CONTEXT_LOST";
		case GL_OUT_OF_MEMORY: return "GL_OUT_OF_MEMORY";
		default: return "an unknown error";
		}
	}

	// Everything that was made with the context goes with it.
	static void drop_context()
	{
		if (glc.context) {
			SDL_GL_MakeCurrent(nullptr, nullptr);
			SDL_GL_DestroyContext(glc.context);
		}
		if (glc.helper) {
			bb::wnd::destroy_window(glc.helper);
		}
		glc = gl_state();
		buffer_sizes.clear();
		forget_recorded_calls();
	}

	void destroy_device()
	{
		gfx::surface().surface = 0;
		drop_context();
	}

	void forget_device()
	{
		drop_programs(false);
		sampler_cache.clear();
		layouts.clear();
		gfx::surface().surface = 0;
		g.cull_pipeline        = {};
		g.static_pipeline      = {};
		drop_context();
	}

	void create_buffer(gpu_buffer& buffer, uint64_t size, buffer_usage, memory where)
	{
		GLuint id = 0;
		gl::GenBuffers(1, &id);
		gl::BindBuffer(GL_COPY_WRITE_BUFFER, id);
		buffer.vk         = id;
		buffer.allocation = 0;
		buffer.mapped     = nullptr;
		buffer.size       = size;
		if (where == memory::device) {
			gl::BufferStorage(GL_COPY_WRITE_BUFFER, GLsizeiptr(size), nullptr, GL_DYNAMIC_STORAGE_BIT);
		} else {
			// Mapped for as long as the buffer lives, and what the CPU writes is there for the GPU without a flush.
			GLbitfield access = GL_MAP_READ_BIT | GL_MAP_WRITE_BIT | GL_MAP_PERSISTENT_BIT | GL_MAP_COHERENT_BIT;
			gl::BufferStorage(GL_COPY_WRITE_BUFFER, GLsizeiptr(size), nullptr, access);
			buffer.mapped = gl::MapBufferRange(GL_COPY_WRITE_BUFFER, 0, GLsizeiptr(size), access);
			if (!buffer.mapped) {
				gfx::fail("Out of memory.");
			}
			// OpenGL 4.2 and later map at GL_MIN_MAP_BUFFER_ALIGNMENT, which is at least 64, so vertices copied here start on a cache line.
			if ((uintptr_t(buffer.mapped) % bb::vertex_alignment) != 0) {
				static bool told = false;
				if (!told) {
					told = true;
					fprintf(stderr, "OpenGL: the driver mapped a buffer at %p, which is not on a %u-byte boundary.\n", buffer.mapped, unsigned(bb::vertex_alignment));
				}
			}
		}
		buffer_sizes[id] = size;
	}

	void destroy_retired_buffer(uint64_t buffer, uint64_t)
	{
		GLuint id = GLuint(buffer);
		if (id) {
			forget_buffer(id);
			gl::DeleteBuffers(1, &id);
		}
	}

	void destroy_buffer(gpu_buffer& buffer)
	{
		destroy_retired_buffer(buffer.vk, buffer.allocation);
		buffer = gpu_buffer();
	}

