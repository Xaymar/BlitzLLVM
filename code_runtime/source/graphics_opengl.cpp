	static pipeline new_pipeline(pipeline_object&& object)
	{
		object.alive = true;
		for (size_t i = 0; i < pipeline_objects.size(); i++) {
			if (!pipeline_objects[i].alive) {
				pipeline_objects[i] = std::move(object);
				return pipeline{ uint64_t(i + 1) };
			}
		}
		pipeline_objects.push_back(std::move(object));
		return pipeline{ uint64_t(pipeline_objects.size()) };
	}

