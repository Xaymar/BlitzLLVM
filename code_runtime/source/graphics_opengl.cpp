		// Makes the context draw into a window (or into nothing that is seen, for null).
		void make_current(SDL_Window* window)
		{
			if (!window) {
				window = glc.helper;
			}
			if (glc.current != window) {
				SDL_GL_MakeCurrent(window, glc.context);
				glc.current = window;
			}
		}

		void bind_unit(uint32_t unit, GLenum target, GLuint texture, GLuint sampler)
		{
			unit_state& state = glc.units[unit];
			if ((state.target != target) || (state.texture != texture)) {
				gl::ActiveTexture(GL_TEXTURE0 + unit);
				gl::BindTexture(target, texture);
				state.target  = target;
				state.texture = texture;
			}
			if (state.sampler != sampler) {
				gl::BindSampler(unit, sampler);
				state.sampler = sampler;
			}
		}

		void forget_texture(GLuint texture)
		{
			for (unit_state& state : glc.units) {
				if (state.texture == texture) {
					state = unit_state();
				}
			}
			for (size_t i = 0; i < glc.framebuffers.size();) {
				framebuffer_entry& entry = glc.framebuffers[i];
				bool               uses  = false;
				for (GLuint used : entry.textures) {
					uses |= (used == texture);
				}
				if (uses) {
					gl::DeleteFramebuffers(1, &entry.id);
					entry = glc.framebuffers.back();
					glc.framebuffers.pop_back();
				} else {
					i++;
				}
			}
		}

		void attach(GLenum framebuffer, GLenum attachment, const gl_image* image, uint32_t mip, uint32_t layer)
		{
			if (!image) {
				gl::FramebufferTexture2D(framebuffer, attachment, GL_TEXTURE_2D, 0, 0);
			} else if (image->target == GL_TEXTURE_2D_ARRAY) {
				gl::FramebufferTextureLayer(framebuffer, attachment, image->texture, GLint(mip), GLint(layer));
			} else {
				gl::FramebufferTexture2D(framebuffer, attachment, image->target, image->texture, GLint(mip));
			}
		}

		// Binds one of the two framebuffers for copies with a level and layer of an image as its colour (or its depth), or the window of the image.
		void bind_copy_framebuffer(GLenum framebuffer, const gl_image* image, uint32_t mip, uint32_t layer)
		{
			if (image->window) {
				make_current(image->window);
				gl::BindFramebuffer(framebuffer, 0);
				return;
			}
			gl::BindFramebuffer(framebuffer, (framebuffer == GL_READ_FRAMEBUFFER) ? glc.read_fbo : glc.draw_fbo);
			attach(framebuffer, GL_COLOR_ATTACHMENT0, image->depth ? nullptr : image, mip, layer);
			attach(framebuffer, GL_DEPTH_STENCIL_ATTACHMENT, nullptr, mip, layer); // Nothing of a depth image with stencil that was attached before.
			attach(framebuffer, (image->depth && bb::rhi::has_stencil(image->format)) ? GL_DEPTH_STENCIL_ATTACHMENT : GL_DEPTH_ATTACHMENT, image->depth ? image : nullptr, mip, layer);
		}

		// The stencil of a 3D draw: the test and the operations in the order of OpenGL (GL_NEVER + the comparison), only in a pass with stencil.
		void apply_stencil()
		{
			const bb::rhi::stencil_state& st = glc.stencil;
			if (!glc.pass_stencil || !st.enable) {
				gl::Disable(GL_STENCIL_TEST);
				return;
			}
			static const GLenum ops[8] = { GL_KEEP, GL_ZERO, GL_REPLACE, GL_INCR, GL_DECR, GL_INVERT, GL_INCR_WRAP, GL_DECR_WRAP };
			gl::Enable(GL_STENCIL_TEST);
			gl::StencilFuncSeparate(GL_FRONT, GLenum(GL_NEVER + int(st.front.compare)), GLint(st.reference), st.read_mask);
			gl::StencilFuncSeparate(GL_BACK, GLenum(GL_NEVER + int(st.back.compare)), GLint(st.reference), st.read_mask);
			gl::StencilOpSeparate(GL_FRONT, ops[int(st.front.fail)], ops[int(st.front.depth_fail)], ops[int(st.front.pass)]);
			gl::StencilOpSeparate(GL_BACK, ops[int(st.back.fail)], ops[int(st.back.depth_fail)], ops[int(st.back.pass)]);
			gl::StencilMask(st.write_mask);
		}

		// The state of the pipeline that is bound, set again after something changed it for a clear or a copy.
		void apply_state()
		{
			gl::Enable(GL_SCISSOR_TEST);
			gl::Scissor(glc.scissor[0], glc.scissor[1], glc.scissor[2], glc.scissor[3]);
			const gl_pipeline* pipeline = glc.pipeline;
			if (!pipeline) {
				return;
			}
			const bb::rhi::pipeline_desc& desc = pipeline->desc;
			for (int i = 0; i < 6; i++) {
				(pipeline->program && (i < pipeline->program->clip_distances) ? gl::Enable : gl::Disable)(GLenum(GL_CLIP_DISTANCE0 + i));
			}
			static const GLenum factors[] = { GL_ZERO, GL_ONE, GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA, GL_SRC_COLOR, GL_DST_COLOR, GL_ONE_MINUS_SRC_COLOR };
			for (uint32_t i = 0; i < desc.attachment_count; i++) {
				const bb::rhi::blend_state& blend = desc.attachments[i].blend;
				if (blend.enable) {
					gl::Enablei(GL_BLEND, i);
					gl::BlendFuncSeparatei(i, factors[int(blend.src_color)], factors[int(blend.dst_color)], factors[int(blend.src_alpha)], factors[int(blend.dst_alpha)]);
				} else {
					gl::Disablei(GL_BLEND, i);
				}
				gl::ColorMaski(i, (blend.write_mask & 1) != 0, (blend.write_mask & 2) != 0, (blend.write_mask & 4) != 0, (blend.write_mask & 8) != 0);
			}
			gl::PolygonMode(GL_FRONT_AND_BACK, desc.wire ? GL_LINE : GL_FILL);
			if (desc.depth) {
				// The depth is reversed: 1 at the near plane and 0 at the far plane, so closer is greater.
				gl::DepthFunc((desc.depth_compare == bb::rhi::compare::less) ? GL_LESS : GL_GEQUAL);
				(glc.depth_test ? gl::Enable : gl::Disable)(GL_DEPTH_TEST);
				gl::DepthMask(glc.depth_write ? GL_TRUE : GL_FALSE);
				if (glc.cull == bb::rhi::cull_mode::none) {
					gl::Disable(GL_CULL_FACE);
				} else {
					gl::Enable(GL_CULL_FACE);
					gl::CullFace((glc.cull == bb::rhi::cull_mode::front) ? GL_FRONT : GL_BACK);
				}
				apply_stencil();
			} else {
				gl::Disable(GL_DEPTH_TEST);
				gl::DepthMask(GL_FALSE);
				gl::Disable(GL_CULL_FACE);
				gl::Disable(GL_STENCIL_TEST);
			}
		}

		// Clears an attachment of the framebuffer that is bound, whatever the state of the pipeline is. rect: x, y, w, h, or null for all of it.
		void clear_attachment(GLenum buffer, GLint index, const float* value, const int32_t* rect)
		{
			if (rect) {
				gl::Scissor(rect[0], rect[1], rect[2], rect[3]);
			} else {
				gl::Disable(GL_SCISSOR_TEST);
			}
			if (buffer == GL_COLOR) {
				gl::ColorMaski(GLuint(index), GL_TRUE, GL_TRUE, GL_TRUE, GL_TRUE);
			} else {
				gl::DepthMask(GL_TRUE);
			}
			gl::ClearBufferfv(buffer, index, value);
			apply_state();
		}

		void clear_stencil_attachment(uint8_t value, const int32_t* rect)
		{
			if (rect) {
				gl::Scissor(rect[0], rect[1], rect[2], rect[3]);
			} else {
				gl::Disable(GL_SCISSOR_TEST);
			}
			gl::StencilMask(0xFF);
			GLint stencil = value;
			gl::ClearBufferiv(GL_STENCIL, 0, &stencil);
			apply_state();
		}

		GLuint compile(const shader_source& source, const std::string& defines)
		{
			GLenum kind   = (source.stage == 'v') ? GL_VERTEX_SHADER : ((source.stage == 'f') ? GL_FRAGMENT_SHADER : GL_COMPUTE_SHADER);
			GLuint shader = gl::CreateShader(kind);
			// The constants go after the line of the version, before the shader sets the ones that nothing has set.
			const char* rest = strchr(source.source, '\n');
			std::string head(source.source, size_t(rest + 1 - source.source));
			const char* parts[3] = { head.c_str(), defines.c_str(), rest + 1 };
			gl::ShaderSource(shader, 3, parts, nullptr);
			gl::CompileShader(shader);
			GLint ok = 0;
			gl::GetShaderiv(shader, GL_COMPILE_STATUS, &ok);
			if (!ok) {
				char log[1024] = "";
				gl::GetShaderInfoLog(shader, sizeof(log), nullptr, log);
				fprintf(stderr, "OpenGL: the shader %s does not compile:\n%s\n", source.name, log);
				fail("internal error: a shader was not accepted by the OpenGL driver.");
			}
			return shader;
		}

		// Reads the names of what the program uses (bb_t<set>_<place>_<stage> and so on) and gives each a texture unit or a binding.
		void assign_bindings(gl_program& program)
		{
			gl::UseProgram(program.id);
			glc.program = program.id;
			GLint  count  = 0;
			char   name[128];
			uint32_t set = 0, place = 0;
			gl::GetProgramiv(program.id, GL_ACTIVE_UNIFORMS, &count);
			for (GLint i = 0; i < count; i++) {
				GLint  size = 0;
				GLenum type = 0;
				gl::GetActiveUniform(program.id, GLuint(i), sizeof(name), nullptr, &size, &type, name);
				if (sscanf(name, "bb_t%u_%u_", &set, &place) == 2) {
					GLenum target = (type == GL_SAMPLER_2D_ARRAY) ? GL_TEXTURE_2D_ARRAY : ((type == GL_SAMPLER_2D_MULTISAMPLE) ? GL_TEXTURE_2D_MULTISAMPLE : GL_TEXTURE_2D);
					uint32_t unit = uint32_t(program.textures.size());
					if (unit >= unit_count) {
						fail("internal error: a shader samples more images than the OpenGL backend has units for.");
					}
					gl::Uniform1i(gl::GetUniformLocation(program.id, name), GLint(unit));
					program.textures.push_back({ set, place, unit, target });
				}
			}
			uint32_t point = 0;
			gl::GetProgramiv(program.id, GL_ACTIVE_UNIFORM_BLOCKS, &count);
			for (GLint i = 0; i < count; i++) {
				gl::GetActiveUniformBlockName(program.id, GLuint(i), sizeof(name), nullptr, name);
				if (sscanf(name, "bb_u%u_%u_", &set, &place) == 2) {
					gl::UniformBlockBinding(program.id, GLuint(i), point);
					program.uniforms.push_back({ set, place, point++, 0 });
				}
			}
			for (GLint i = 0; i < count; i++) {
				gl::GetActiveUniformBlockName(program.id, GLuint(i), sizeof(name), nullptr, name);
				if (strncmp(name, "bb_push_", 8) == 0) { // The blocks of all stages read the one buffer.
					if (program.push_point < 0) {
						program.push_point = int(point++);
					}
					gl::UniformBlockBinding(program.id, GLuint(i), GLuint(program.push_point));
				}
			}
			point = 0;
			gl::GetProgramInterfaceiv(program.id, GL_SHADER_STORAGE_BLOCK, GL_ACTIVE_RESOURCES, &count);
			for (GLint i = 0; i < count; i++) {
				gl::GetProgramResourceName(program.id, GL_SHADER_STORAGE_BLOCK, GLuint(i), sizeof(name), nullptr, name);
				if (sscanf(name, "bb_b%u_%u_", &set, &place) == 2) {
					gl::ShaderStorageBlockBinding(program.id, GLuint(i), point);
					program.storage.push_back({ set, place, point++, 0 });
				}
			}
			program.base_instance = gl::GetUniformLocation(program.id, "SPIRV_Cross_BaseInstance");
		}

		void add_define(std::string& defines, uint32_t id, float value)
		{
			uint32_t bits;
			memcpy(&bits, &value, sizeof(bits));
			char line[96];
			snprintf(line, sizeof(line), "#define SPIRV_CROSS_CONSTANT_ID_%u uintBitsToFloat(0x%08Xu)\n", id, bits); // The exact number, whatever it is.
			defines += line;
		}

		void add_define(std::string& defines, uint32_t id, bool value)
		{
			char line[96];
			snprintf(line, sizeof(line), "#define SPIRV_CROSS_CONSTANT_ID_%u %s\n", id, value ? "true" : "false");
			defines += line;
		}

		// The program of one or two shaders with their constants: made when first asked for, then the same one.
		gl_program* program_of(bb::rhi::shader first, bb::rhi::shader second, const bb::rhi::shader_constants* constants)
		{
			std::string defines[2];
			if (constants) {
				// The numbers of the constants as tools/generate_shaders.py gives them: the vertex shader has the limits, the fragment shader the rest.
				add_define(defines[0], 0, constants->limit[0]);
				add_define(defines[0], 1, constants->limit[1]);
				add_define(defines[1], 0, constants->dither);
				for (uint32_t i = 0; i < 5; i++) {
					add_define(defines[1], 1 + i, constants->factor[i]);
				}
				add_define(defines[1], 6, constants->limit[0]);
				add_define(defines[1], 7, constants->limit[1]);
				for (uint32_t i = 0; i < 3; i++) {
					add_define(defines[1], 8 + i, constants->scale[i]);
				}
				add_define(defines[1], 11, constants->palette);
				add_define(defines[1], 12, constants->bayer_levels);
				add_define(defines[1], 20, constants->multiply);
				add_define(defines[1], 21, constants->layers);
			}
			std::string key = std::to_string(first.id) + "," + std::to_string(second.id) + "\n" + defines[1];
			auto found = programs.find(key);
			if (found != programs.end()) {
				return found->second;
			}
			gl_program* program = new gl_program();
			program->id         = gl::CreateProgram();
			GLuint shaders[2]   = {};
			shaders[0]          = compile(shader_sources[first.id - 1], defines[0]);
			gl::AttachShader(program->id, shaders[0]);
			if (second) {
				shaders[1] = compile(shader_sources[second.id - 1], defines[1]);
				gl::AttachShader(program->id, shaders[1]);
			}
			gl::LinkProgram(program->id);
			GLint ok = 0;
			gl::GetProgramiv(program->id, GL_LINK_STATUS, &ok);
			if (!ok) {
				char log[1024] = "";
				gl::GetProgramInfoLog(program->id, sizeof(log), nullptr, log);
				fprintf(stderr, "OpenGL: the shaders %s and %s do not link:\n%s\n", shader_sources[first.id - 1].name, second ? shader_sources[second.id - 1].name : "(none)", log);
				fail("internal error: a pipeline was not accepted by the OpenGL driver.");
			}
			for (GLuint shader : shaders) {
				if (shader) {
					gl::DeleteShader(shader); // The program keeps what it needs.
				}
			}
			// The 3D vertex shader writes the distances to the clip planes of the camera (gl_ClipDistance[6]); the others write none.
			if (strstr(shader_sources[first.id - 1].source, "gl_ClipDistance")) {
				program->clip_distances = 6;
			}
			assign_bindings(*program);
			programs[key] = program;
			return program;
		}

		gl_pipeline build_pipeline(const bb::rhi::pipeline_desc& desc)
		{
			gl_pipeline pipeline;
			pipeline.desc    = desc;
			pipeline.program = program_of(desc.vs, desc.fs, desc.has_constants ? &desc.constants : nullptr);
			return pipeline;
		}

		const gl_pipeline& pipeline_for(bb::rhi::pipeline pipeline, bb::rhi::format format)
		{
			pipeline_object& object = pipeline_objects[pipeline.id - 1];
			// A target that is not the format of the buffers (when those are not RGBA8) gets the one made for RGBA8, as on Vulkan.
			bb::rhi::format key   = object.fixed ? bb::rhi::format::undefined : (((format == g.buffer_format) && (format != bb::rhi::format::rgba8)) ? format : bb::rhi::format::rgba8);
			auto            found = object.built.find(key);
			if (found != object.built.end()) {
				return found->second;
			}
			return object.built[key] = build_pipeline(object.recipe(key));
		}

		void use_program(const gl_program* program)
		{
			if (glc.program != program->id) {
				gl::UseProgram(program->id);
				glc.program = program->id;
			}
		}

		// Binds what the program reads from the groups: textures with samplers, and buffers.
		void apply_bindings(const gl_program* program, gl_group** groups, const uint32_t* offsets)
		{
			static const gl_slot nothing;
			for (const gl_binding& binding : program->textures) {
				const gl_slot& slot = groups[binding.set] ? groups[binding.set]->slots[binding.place] : nothing;
				bind_unit(binding.point, slot.texture ? slot.target : binding.target, slot.texture, slot.sampler);
			}
			for (const gl_binding& binding : program->uniforms) {
				const gl_slot& slot = groups[binding.set] ? groups[binding.set]->slots[binding.place] : nothing;
				if (slot.buffer) {
					uint64_t offset = offsets ? offsets[binding.set] : 0;
					gl::BindBufferRange(GL_UNIFORM_BUFFER, binding.point, slot.buffer, GLintptr(offset), GLsizeiptr(slot.size ? slot.size : (buffer_sizes[slot.buffer] - offset)));
				}
			}
			for (const gl_binding& binding : program->storage) {
				const gl_slot& slot = groups[binding.set] ? groups[binding.set]->slots[binding.place] : nothing;
				gl::BindBufferBase(GL_SHADER_STORAGE_BUFFER, binding.point, slot.buffer);
			}
			if (program->push_point >= 0) {
				if (glc.push_dirty) {
					gl::BindBuffer(GL_UNIFORM_BUFFER, glc.push_buffer);
					gl::BufferSubData(GL_UNIFORM_BUFFER, 0, push_bytes, glc.push_data);
					glc.push_dirty = false;
				}
				gl::BindBufferBase(GL_UNIFORM_BUFFER, GLuint(program->push_point), glc.push_buffer);
			}
		}

		// Readies everything for a draw of the pipeline that is bound. Answers the kind of primitive.
		GLenum prepare_draw(uint32_t first_instance)
		{
			const gl_pipeline* pipeline = glc.pipeline;
			use_program(pipeline->program);
			apply_bindings(pipeline->program, glc.groups, glc.offsets);
			if (pipeline->program->base_instance >= 0) {
				gl::Uniform1i(pipeline->program->base_instance, GLint(first_instance));
			}
			uint32_t vao = uint32_t(pipeline->desc.vertices);
			gl::BindVertexArray(glc.vaos[vao]);
			bool scene3d = pipeline->desc.vertices == bb::rhi::vertex_layout::scene3d;
			if ((vao != 0) && ((glc.vao_vertices[vao] != glc.vertex_buffer) || (scene3d && (glc.vao_second != glc.vertex_second)))) {
				gl::BindVertexBuffer(0, glc.vertex_buffer, 0, scene3d ? GLsizei(sizeof(bb::vertex3d)) : GLsizei(sizeof(vertex)));
				if (scene3d) { // The second set of texture coordinates: the block of the surface, or the first set.
					uint64_t second = glc.vertex_second;
					gl::BindVertexBuffer(1, glc.vertex_buffer, GLintptr(second ? second : offsetof(bb::vertex3d, u)), second ? GLsizei(sizeof(bb::vertex3d_second)) : GLsizei(sizeof(bb::vertex3d)));
					glc.vao_second = second;
				}
				glc.vao_vertices[vao] = glc.vertex_buffer;
			}
			if (glc.vao_indices[vao] != glc.index_buffer) {
				gl::BindBuffer(GL_ELEMENT_ARRAY_BUFFER, glc.index_buffer);
				glc.vao_indices[vao] = glc.index_buffer;
			}
			return (pipeline->desc.primitives == bb::rhi::topology::lines) ? GL_LINES : GL_TRIANGLES;
		}

		void forget_buffer(GLuint buffer)
		{
			buffer_sizes.erase(buffer);
			for (uint32_t i = 0; i < 3; i++) {
				glc.vao_vertices[i] = (glc.vao_vertices[i] == buffer) ? 0 : glc.vao_vertices[i];
				glc.vao_indices[i]  = (glc.vao_indices[i] == buffer) ? 0 : glc.vao_indices[i];
			}
		}

		void delete_orphans()
		{
			std::lock_guard<std::mutex> guard(orphan_lock);
			for (GLuint buffer : orphans) {
				forget_buffer(buffer);
				gl::DeleteBuffers(1, &buffer);
			}
			orphans.clear();
		}

		bool has_extension(const char* wanted)
		{
			GLint count = 0;
			gl::GetIntegerv(GL_NUM_EXTENSIONS, &count);
			for (GLint i = 0; i < count; i++) {
				const char* name = reinterpret_cast<const char*>(gl::GetStringi(GL_EXTENSIONS, GLuint(i)));
				if (name && (strcmp(name, wanted) == 0)) {
					return true;
				}
			}
			return false;
		}

