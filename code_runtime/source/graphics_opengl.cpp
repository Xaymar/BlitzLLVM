		gpu_image create_image_again(const image_recipe& recipe);

		gpu_image create_image(uint32_t width, uint32_t height, bb::rhi::image_usage usage, bb::rhi::format format, const bb::rhi::swizzle* components, uint32_t mips, uint32_t layers, uint32_t samples)
		{
			const format_info* info = info_of(format);
			if (!info) {
				fail("internal error: an image was asked for in a format that is not known");
			}
			gpu_image img;
			img.format          = format;
			img.mips            = mips;
			img.layers          = layers;
			img.width           = width;
			img.height          = height;
			img.recipe          = new image_recipe();
			img.recipe->width   = width;
			img.recipe->height  = height;
			img.recipe->mips    = mips;
			img.recipe->layers  = layers;
			img.recipe->samples = samples;
			img.recipe->usage   = usage;
			img.recipe->format  = format;
			img.recipe->aspect  = bb::rhi::is_depth(format) ? 2 : 1;
			if (components) {
				const bb::rhi::channel channels[4] = { components->r, components->g, components->b, components->a };
				for (int i = 0; i < 4; i++) {
					img.recipe->mapping[i] = uint32_t(channels[i]);
				}
				img.recipe->has_mapping = true;
			}
			img.recipe->may_spill = image_spill_allowed();

			gl_image* image = new gl_image();
			image->format   = format;
			image->width    = width;
			image->height   = height;
			image->mips     = mips;
			image->layers   = layers;
			image->samples  = samples;
			image->depth    = bb::rhi::is_depth(format);
			image->target   = (samples > 1) ? GL_TEXTURE_2D_MULTISAMPLE : (image->depth ? GL_TEXTURE_2D : GL_TEXTURE_2D_ARRAY);
			gl::GenTextures(1, &image->texture);
			gl::ActiveTexture(GL_TEXTURE0 + scratch_unit);
			gl::BindTexture(image->target, image->texture);
			if (image->target == GL_TEXTURE_2D_MULTISAMPLE) {
				gl::TexStorage2DMultisample(image->target, GLsizei(samples), info->internal, GLsizei(width), GLsizei(height), GL_TRUE);
			} else if (image->target == GL_TEXTURE_2D_ARRAY) {
				gl::TexStorage3D(image->target, GLsizei(mips), info->internal, GLsizei(width), GLsizei(height), GLsizei(layers));
			} else {
				gl::TexStorage2D(image->target, GLsizei(mips), info->internal, GLsizei(width), GLsizei(height));
			}
			GLint swizzle[4] = { GL_RED, GL_GREEN, GL_BLUE, GL_ALPHA };
			if (components) {
				const bb::rhi::channel channels[4] = { components->r, components->g, components->b, components->a };
				for (int i = 0; i < 4; i++) {
					switch (channels[i]) {
					case bb::rhi::channel::zero: swizzle[i] = GL_ZERO; break;
					case bb::rhi::channel::one: swizzle[i] = GL_ONE; break;
					case bb::rhi::channel::r: swizzle[i] = GL_RED; break;
					case bb::rhi::channel::g: swizzle[i] = GL_GREEN; break;
					case bb::rhi::channel::b: swizzle[i] = GL_BLUE; break;
					case bb::rhi::channel::a: swizzle[i] = GL_ALPHA; break;
					default: break;
					}
				}
				gl::TexParameteriv(image->target, GL_TEXTURE_SWIZZLE_RGBA, swizzle);
			}
			img.image = uint64_t(uintptr_t(image));

			// The views as the shared code knows them from Vulkan: one image for sampling, all layers as an array for textures, and the first level (of each layer) for drawing.
			gl_view* whole = new gl_view{ image, image->texture, image->target, 0, false };
			if (image->target == GL_TEXTURE_2D_ARRAY) {
				gl_view* flat = new gl_view{ image, 0, GL_TEXTURE_2D, 0, true };
				gl::GenTextures(1, &flat->texture);
				gl::TextureView(flat->texture, GL_TEXTURE_2D, image->texture, info->internal, 0, mips, 0, 1);
				if (components) {
					gl::BindTexture(GL_TEXTURE_2D, flat->texture);
					gl::TexParameteriv(GL_TEXTURE_2D, GL_TEXTURE_SWIZZLE_RGBA, swizzle);
				}
				img.view = uint64_t(uintptr_t(flat));
				if (usage & bb::rhi::image_sampled) {
					img.array_view = uint64_t(uintptr_t(whole));
				} else {
					delete whole;
				}
			} else {
				img.view = uint64_t(uintptr_t(whole));
			}
			if ((mips > 1) || (format == bb::rhi::format::rgba8_srgb) || (layers > 1)) {
				img.target_view = uint64_t(uintptr_t(new gl_view{ image, image->texture, image->target, 0, false }));
				if (layers > 1) {
					img.layer_targets    = static_cast<uint64_t*>(bb_calloc(layers, sizeof(uint64_t)));
					img.layer_targets[0] = img.target_view;
					for (uint32_t layer = 1; layer < layers; layer++) {
						img.layer_targets[layer] = uint64_t(uintptr_t(new gl_view{ image, image->texture, image->target, layer, false }));
					}
				}
			}
			return img;
		}

		void release_image(gpu_image& img)
		{
			for (uint32_t layer = 1; img.layer_targets && (layer < img.layers); layer++) {
				delete view_of(img.layer_targets[layer]);
			}
			bb_free(img.layer_targets);
			img.layer_targets = nullptr;
			for (uint64_t* handle : { &img.array_view, &img.view, &img.target_view }) {
				if (gl_view* view = view_of(*handle)) {
					if (view->owned) {
						forget_texture(view->texture);
						gl::DeleteTextures(1, &view->texture);
					}
					delete view;
				}
				*handle = 0;
			}
			if (gl_image* image = image_of(img.image)) {
				forget_texture(image->texture);
				gl::DeleteTextures(1, &image->texture);
				delete image;
			}
			img.image      = 0;
			img.allocation = 0;
		}

