// Writing pictures for SaveBuffer, SaveImage and SaveTexture: the formats, their settings and the metadata that is put into the files. The
// encoders run on whatever thread calls them, and with AsyncSaving on that is a loader thread, so nothing in here may use the graphics device.

#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace bb::gfx {

	struct jpeg_options {
		int  quality     = 90;
		int  subsampling = 420; // 444, 422 or 420.
		bool progressive = false;
	};

	/** Encodes RGBA pixels (without row padding; alpha is ignored) to a JPEG file in memory. exif is the TIFF structure of the metadata, or empty. */
	bool jpeg_encode(const uint8_t* rgba, int width, int height, const jpeg_options& options, const std::vector<uint8_t>& exif, std::vector<uint8_t>& out);

	/** A zlib stream of the data, malloc'ed, at a level from 0 (stored) to 9 (smallest) like zlib's. Null if it ran out of memory. */
	unsigned char* zlib_compress(const unsigned char* data, int size, int* out_size, int level);

	/** What the settings string of the save commands says. A value that is -1 (or unset) was not given and the format picks. */
	struct save_settings {
		int   quality     = -1;    // 0 to 100: JPEG, WebP and JPEG XL.
		int   subsampling = 420;   // JPEG: 444, 422 or 420.
		bool  progressive = false; // JPEG.
		int   lossless    = -1;    // WebP and JPEG XL: 1 lossless, 0 lossy.
		float distance    = -1;    // JPEG XL: the distance of lossy compression, 0 is lossless (instead of quality).
		int   effort      = -1;    // JPEG XL: 1 (fast) to 9 (small).
		int   compression = -1;    // PNG: 0 (stored) to 9 (smallest), like zlib.
		bool  rle         = true;  // TGA.
		bool  metadata    = true;  // Whether the file says which program made it.
	};

	/** Reads "key=value, key=value" (separated by commas, semicolons or spaces). Returns the text of the first problem, or an empty string. */
	std::string parse_save_settings(const char* text, save_settings& out);

	enum class save_format { bmp, png, jpeg, webp, jxl, tga, avif };
	/** The format that the extension of a file name says. Every extension that is not known is a BMP, like it was before there were other formats. */
	save_format save_format_of(const char* file);

	/** The metadata of exported pictures: the Exif structure (a TIFF file) that says "Generated by <title>". */
	std::vector<uint8_t> make_exif(const std::string& title);

	/** The title that exported pictures name (AppTitle), BlitzLLVM until the program sets one. */
	void        save_set_title(const char* title);
	std::string save_title();

	/** Encodes and writes. Returns false with a reason in error if it could not. The pixels are RGBA and rows have no padding. */
	bool save_picture_file(const uint8_t* rgba, int width, int height, const std::string& native_path, save_format format, const save_settings& settings, const std::string& title, std::string& error);

	/** Whether saving goes on another thread (AsyncSaving, or BLITZLLVM_ASYNC_SAVE=1). */
	bool save_async_enabled();
	void save_async_set(bool enabled);
	/** Saves a picture, which is taken over (malloc'ed). Returns 0 if it can't be saved, otherwise 1 (1 also when the work only went to another thread). */
	int32_t save_submit(uint8_t* rgba, int width, int height, const char* file, const char* settings);
	/** How many saves are still going on, and how many that went on another thread failed so far. */
	int32_t save_pending_count();
	int32_t save_failed_count();
	/** Waits until every save is done. Called when the graphics end, and before a file that is written again. */
	void save_finish_all();

} // namespace bb::gfx
