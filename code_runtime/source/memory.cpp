namespace {
	void* new_or_die(size_t size)
	{
		void* p = bb_malloc(size);
		if (!p) {
#if defined(__cpp_exceptions)
			throw std::bad_alloc();
#else
			fputs("Out of memory.\n", stderr);
			exit(1);
#endif
		}
		return p;
	}
	void* new_aligned_or_die(size_t size, size_t alignment)
	{
		void* p = bb_aligned_alloc(alignment, size);
		if (!p) {
#if defined(__cpp_exceptions)
			throw std::bad_alloc();
#else
			fputs("Out of memory.\n", stderr);
			exit(1);
#endif
		}
		return p;
	}
} // namespace

