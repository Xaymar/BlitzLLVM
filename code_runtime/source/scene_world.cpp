// The tree that entities are in, what kind of entity something is, and the world as a whole.

#include "scene_internal.hpp"
#include "memory.h"
#include "runtime_internal.h"

using namespace bb;
using namespace bb::scene;

extern "C" {
void bb_clear_brushes(void);
void bb_clear_textures(void);

int32_t bb_count_children(int32_t handle)
{
	return need(handle, "CountChildren")->children;
}

// The children are numbered from 1, in the order they became children.
int32_t bb_get_child(int32_t handle, int32_t index)
{
	need(handle, "GetChild");
	int32_t at = 0, number = 0;
	for (at = get_entity_raw(handle)->first_child, number = 1; at && number < index; number++) {
		at = get_entity_raw(at)->next_sibling;
	}
	return (index >= 1) ? at : 0;
}

int32_t bb_get_parent(int32_t handle)
{
	return need(handle, "GetParent")->parent;
}

const char* bb_entity_class(int32_t handle)
{
	entity*     e    = need(handle, "EntityClass");
	const char* name = "Pivot";
	if (e->cls) {
		name = e->cls;
	} else if (e->kind == LIGHT) {
		name = "Light";
	} else if (e->kind == CAMERA) {
		name = "Camera";
	} else if (e->kind == MESH) {
		name = e->terrain ? "Terrain" : (e->sprite_mode ? "Sprite" : "Mesh");
	}
	return bb_copy(name, strlen(name));
}

int32_t bb_get_entity_type(int32_t handle)
{
	return need(handle, "GetEntityType")->coll_type;
}

// An element of where the entity is in the world: rows 0 to 2 are the way its axes point, row 3 is the position.
float bb_get_mat_element(int32_t handle, int32_t row, int32_t column)
{
	need(handle, "GetMatElement");
	if ((row < 0) || (row > 3) || (column < 0) || (column > 2)) {
		return 0;
	}
	float world[16];
	world_matrix(handle, world);
	return world[row * 4 + column];
}

// A mirror is only an entity: there is no reflection drawn.
int32_t bb_create_mirror(int32_t parent)
{
	int handle = add_entity(PIVOT, parent);
	get_entity(handle)->cls = "Mirror";
	return handle;
}

// Takes away everything that was made. Entities without a parent take their children with them.
void bb_clear_world(int32_t entities, int32_t brushes, int32_t textures)
{
	if (entities) {
		for (int handle = 1; handle <= entity_count(); handle++) {
			entity* e = get_entity(handle);
			if (e && !e->parent) {
				bb_free_entity(handle);
			}
		}
	}
	if (brushes) {
		bb_clear_brushes();
	}
	if (textures) {
		bb_clear_textures();
	}
}
}
