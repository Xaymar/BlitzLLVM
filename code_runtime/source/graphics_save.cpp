		void put16le(std::vector<uint8_t>& v, uint32_t x)
		{
			v.push_back(uint8_t(x));
			v.push_back(uint8_t(x >> 8));
		}

		void put32le(std::vector<uint8_t>& v, uint32_t x)
		{
			put16le(v, x);
			put16le(v, x >> 16);
		}

		void put32be(std::vector<uint8_t>& v, uint32_t x)
		{
			v.push_back(uint8_t(x >> 24));
			v.push_back(uint8_t(x >> 16));
			v.push_back(uint8_t(x >> 8));
			v.push_back(uint8_t(x));
		}

		uint32_t crc32(const uint8_t* data, size_t size, uint32_t crc = 0)
		{
			static uint32_t table[256];
			static bool     made = false;
			if (!made) {
				for (uint32_t i = 0; i < 256; i++) {
					uint32_t c = i;
					for (int k = 0; k < 8; k++) {
						c = (c & 1) ? (0xedb88320u ^ (c >> 1)) : (c >> 1);
					}
					table[i] = c;
				}
				made = true;
			}
			crc = ~crc;
			for (size_t i = 0; i < size; i++) {
				crc = table[(crc ^ data[i]) & 0xff] ^ (crc >> 8);
			}
			return ~crc;
		}

		std::string lower(const char* text)
		{
			std::string out = text ? text : "";
			for (auto& c : out) {
				c = char(tolower(static_cast<unsigned char>(c)));
			}
			return out;
		}

		bool parse_bool(const std::string& value, bool& out)
		{
			if (value.empty() || value == "1" || value == "true" || value == "yes" || value == "on") {
				out = true;
				return true;
			}
			if (value == "0" || value == "false" || value == "no" || value == "off") {
				out = false;
				return true;
			}
			return false;
		}

		bool parse_number(const std::string& value, double& out)
		{
			if (value.empty()) {
				return false;
			}
			char* end = nullptr;
			out       = strtod(value.c_str(), &end);
			return end && !*end && std::isfinite(out);
		}
