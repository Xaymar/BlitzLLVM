		bool encode_bmp(const uint8_t* rgba, int w, int h, std::vector<uint8_t>& out)
		{
			SDL_Surface* surface = SDL_CreateSurfaceFrom(w, h, SDL_PIXELFORMAT_RGBA32, const_cast<uint8_t*>(rgba), w * 4);
			if (!surface) {
				return false;
			}
			SDL_IOStream* io = SDL_IOFromDynamicMem();
			bool          done = io && SDL_SaveBMP_IO(surface, io, false);
			if (done) {
				auto* data = static_cast<uint8_t*>(SDL_GetPointerProperty(SDL_GetIOProperties(io), SDL_PROP_IOSTREAM_DYNAMIC_MEMORY_POINTER, nullptr));
				int64_t size = SDL_TellIO(io);
				done         = data && (size > 0);
				if (done) {
					out.assign(data, data + size);
				}
			}
			if (io) {
				SDL_CloseIO(io);
			}
			SDL_DestroySurface(surface);
			return done;
		}

