// The table of a backend of the rendering hardware interface: one entry for each call of rhi_backend.inc. The functions of bb::rhi (and
// the few of bb::gfx in that list) call through the table of the backend that draws, so that more than one backend can be built into the
// runtime. A backend defines the calls in its own namespace (bb::rhi::vulkan and bb::gfx::vulkan for Vulkan) and fills one table with them.
#pragma once
#include "graphics_internal.hpp"

namespace bb::rhi {
	struct backend_table {
#define BB_RHI_CALL(result, name, parameters, arguments) result (*name) parameters;
#define BB_GFX_CALL(result, name, parameters, arguments) result (*gfx_##name) parameters;
#include "rhi_backend.inc"
#undef BB_RHI_CALL
#undef BB_GFX_CALL
	};

	/** The table of the backend that draws. It is the first backend that was built until a backend is chosen (see selected_backend), so it is never null. */
	extern const backend_table* active_backend;

	/** The tables of the backends that this build has. */
	extern const backend_table vulkan_backend;
#ifdef BB_OPENGL
	extern const backend_table opengl_backend;
#endif
} // namespace bb::rhi
