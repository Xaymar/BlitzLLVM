// BlitzLLVM runtime library.
//
// This file is embedded into the compiler and compiled together with the generated LLVM IR, so that the result is a
// single executable. Everything that Blitz programs can call lives here, prefixed with bb_.
//
// Strings are NUL-terminated UTF-8, where NULL is the empty string. Strings are immutable and currently never freed.

