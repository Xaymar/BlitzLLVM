const char* bb_s(const char* s)
{
	return s ? s : "";
}

size_t bb_slen(const char* s)
{
	uint32_t length = 0;
	if (s) {
		memcpy(&length, s - BB_STRING_HEADER, sizeof(length));
	}
	return length;
}

// A string of the given length (the characters are the caller's to fill in), with the length in front and a NUL after it.
char* bb_alloc(size_t length)
{
	if (length > INT32_MAX) {
		bb_runtime_error("String is too long.");
	}
	char* mem = (char*)bb_malloc(BB_STRING_HEADER + length + 1);
	if (!mem) {
		fputs("Out of memory.\n", stderr);
		exit(1);
	}
	uint32_t stored = (uint32_t)length;
	memcpy(mem, &stored, sizeof(stored));
	mem += BB_STRING_HEADER;
	mem[length] = 0;
	return mem;
}

char* bb_copy(const char* data, size_t length)
{
	char* mem = bb_alloc(length);
	memcpy(mem, data, length);
	return mem;
}

void bb_str_free(const char* s)
{
	if (s) {
		bb_free((char*)s - BB_STRING_HEADER);
	}
}

////////////////////////////////////////////////////////////////////////////////
// Who owns a string
//
// Strings that a function returns are temporaries: they are collected in the pool, and the program frees them when the
// statement that made them is done. Variables, fields and array elements own a copy of what they were given, which is
// freed when they are given something else, or when what they are in goes away.
////////////////////////////////////////////////////////////////////////////////
static char** bb_pool      = NULL;
static size_t bb_pool_size = 0;
static size_t bb_pool_cap  = 0;

char* bb_own(const char* s)
{
	size_t length = bb_slen(s);
	if (!length) {
		return NULL; // The empty string needs no memory.
	}
	return bb_copy(s, length);
}

void bb_pool_push(char* s)
{
	if (bb_pool_size == bb_pool_cap) {
		bb_pool_cap = bb_pool_cap ? bb_pool_cap * 2 : 256;
		bb_pool     = (char**)bb_realloc(bb_pool, bb_pool_cap * sizeof(char*));
		if (!bb_pool) {
			fputs("Out of memory.\n", stderr);
			exit(1);
		}
	}
	bb_pool[bb_pool_size++] = s;
}

// Makes a string that a function returned a temporary.
const char* bb_str_temp(const char* s)
{
	if (s) {
		bb_pool_push((char*)s);
	}
	return s;
}

int32_t bb_str_mark(void)
{
	return (int32_t)bb_pool_size;
}

// Frees the temporaries that were made since the mark.
void bb_str_release(int32_t mark)
{
	while (bb_pool_size > (size_t)mark) {
		bb_str_free(bb_pool[--bb_pool_size]);
	}
}

// For what a variable, field or element gets: its own copy, and the old one is freed.
const char* bb_str_assign(const char* old, const char* value)
{
	// A temporary that was just made (s = s + "x" gives the concatenation) is not copied, the variable takes it over.
	if (bb_slen(value) && bb_pool_size && (bb_pool[bb_pool_size - 1] == value)) {
		bb_pool_size--;
		bb_str_free(old);
		return value;
	}
	char* copy = bb_own(value);
	bb_str_free(old);
	return copy;
}

// For what a userlib gives back: a C string, which is copied into a string of the program.
const char* bb_str_from_c(const char* value)
{
	return (value && *value) ? bb_copy(value, strlen(value)) : NULL;
}

const char* bb_str_dup(const char* value)
{
	return bb_own(value);
}

void bb_str_free_array(const char** elements, int32_t count)
{
	for (int32_t i = 0; i < count; i++) {
		bb_str_free(elements[i]);
		elements[i] = NULL;
	}
}

// What a function gives back: a copy that lives on as a temporary of whoever called, after those of the function are freed.
const char* bb_str_return(const char* value, int32_t mark)
{
	char* copy = bb_own(value);
	bb_str_release(mark);
	if (copy) {
		bb_pool_push(copy);
	}
	return copy;
}

