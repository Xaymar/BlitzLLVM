		struct huffman_table {
			const uint8_t* bits;
			const uint8_t* values;
			int            count;
			uint16_t       code[256];
			uint8_t        length[256];

			void init(const uint8_t* b, const uint8_t* v, int n)
			{
				bits   = b;
				values = v;
				count  = n;
				memset(length, 0, sizeof(length));
				int next = 0, index = 0;
				for (int len = 1; len <= 16; len++) {
					for (int i = 0; i < bits[len - 1]; i++) {
						code[values[index]]   = uint16_t(next++);
						length[values[index]] = uint8_t(len);
						index++;
					}
					next <<= 1;
				}
			}
		};

		struct bit_writer {
			std::vector<uint8_t>& out;
			uint32_t              buffer = 0;
			int                   used   = 0;

			explicit bit_writer(std::vector<uint8_t>& o) : out(o) {}

			void put(uint32_t value, int count)
			{
				if (!count) {
					return;
				}
				buffer = (buffer << count) | (value & ((1u << count) - 1));
				used += count;
				while (used >= 8) {
					uint8_t byte = uint8_t(buffer >> (used - 8));
					out.push_back(byte);
					if (byte == 0xff) {
						out.push_back(0); // A 0xFF in the data is told from a marker by a 0 after it.
					}
					used -= 8;
				}
			}

			void symbol(const huffman_table& table, int value)
			{
				put(table.code[value], table.length[value]);
			}

			// Ends the scan: the last byte is filled up with 1 bits.
			void flush()
			{
				if (used) {
					put(0x7f, 8 - used);
				}
				buffer = 0;
				used   = 0;
			}
		};

		int bit_length(int value)
		{
			int n = 0;
			while (value) {
				n++;
				value >>= 1;
			}
			return n;
		}

		struct component {
			int                  h = 1, v = 1;       // Sampling factors.
			int                  blocks_w = 0, blocks_h = 0; // Blocks in the padded grid (a multiple of the MCU).
			int                  real_w = 0, real_h = 0;     // Blocks that the picture covers, which is what a scan of only this component runs over.
			std::vector<int16_t> coefficients;               // blocks_w * blocks_h blocks of 64, in zigzag order.
		};

		void put16(std::vector<uint8_t>& out, int value)
		{
			out.push_back(uint8_t(value >> 8));
			out.push_back(uint8_t(value));
		}

		void marker(std::vector<uint8_t>& out, int code)
		{
			out.push_back(0xff);
			out.push_back(uint8_t(code));
		}

		void define_huffman(std::vector<uint8_t>& out, int cls_and_id, const huffman_table& table)
		{
			marker(out, 0xc4);
			put16(out, 2 + 1 + 16 + table.count);
			out.push_back(uint8_t(cls_and_id));
			out.insert(out.end(), table.bits, table.bits + 16);
			out.insert(out.end(), table.values, table.values + table.count);
		}

		// The coefficients of one block (in zigzag order) as bits: either the DC difference, or the AC coefficients first..last.
		void put_dc(bit_writer& w, const huffman_table& table, int value, int& previous)
		{
			int diff = value - previous;
			previous = value;
			int size = bit_length(diff < 0 ? -diff : diff);
			w.symbol(table, size);
			w.put(uint32_t(diff < 0 ? diff - 1 : diff), size);
		}

		void put_ac(bit_writer& w, const huffman_table& table, const int16_t* block, int first, int last)
		{
			int run = 0;
			for (int k = first; k <= last; k++) {
				int value = block[k];
				if (!value) {
					run++;
					continue;
				}
				while (run > 15) {
					w.symbol(table, 0xf0);
					run -= 16;
				}
				int size = bit_length(value < 0 ? -value : value);
				w.symbol(table, (run << 4) | size);
				w.put(uint32_t(value < 0 ? value - 1 : value), size);
				run = 0;
			}
			if (run) {
				w.symbol(table, 0x00);
			}
		}

		// Forward DCT of 8x8 samples (already shifted to be around 0), separable and in floating point.
		void forward_dct(const float* in, float* out)
		{
			static float table[8][8];
			static bool  made = false;
			if (!made) {
				for (int u = 0; u < 8; u++) {
					for (int x = 0; x < 8; x++) {
						table[u][x] = float(std::cos((2 * x + 1) * u * 3.14159265358979323846 / 16.0) * (u == 0 ? std::sqrt(0.125) : 0.5));
					}
				}
				made = true;
			}
			float tmp[64];
			for (int y = 0; y < 8; y++) {
				for (int u = 0; u < 8; u++) {
					float sum = 0;
					for (int x = 0; x < 8; x++) {
						sum += in[y * 8 + x] * table[u][x];
					}
					tmp[y * 8 + u] = sum;
				}
			}
			for (int u = 0; u < 8; u++) {
				for (int v = 0; v < 8; v++) {
					float sum = 0;
					for (int y = 0; y < 8; y++) {
						sum += tmp[y * 8 + u] * table[v][y];
					}
					out[v * 8 + u] = sum;
				}
			}
		}
