	bool jpeg_encode(const uint8_t* rgba, int width, int height, const jpeg_options& options, const std::vector<uint8_t>& exif, std::vector<uint8_t>& out)
	{
		if (!rgba || (width <= 0) || (height <= 0) || (width > 65535) || (height > 65535)) {
			return false;
		}
		int quality = options.quality < 1 ? 1 : (options.quality > 100 ? 100 : options.quality);
		int scale   = (quality < 50) ? (5000 / quality) : (200 - quality * 2);
		uint8_t quant[2][64]; // In zigzag order, for luma and chroma.
		for (int i = 0; i < 64; i++) {
			int l = (quant_luma[zigzag[i]] * scale + 50) / 100;
			int c = (quant_chroma[zigzag[i]] * scale + 50) / 100;
			quant[0][i] = uint8_t(l < 1 ? 1 : (l > 255 ? 255 : l));
			quant[1][i] = uint8_t(c < 1 ? 1 : (c > 255 ? 255 : c));
		}

		// Luma is sampled h by v times as often as the chroma; 4:4:4 is 1x1, 4:2:2 is 2x1 and 4:2:0 is 2x2.
		int hmax = (options.subsampling == 444) ? 1 : 2;
		int vmax = (options.subsampling == 420) ? 2 : 1;
		component comps[3];
		comps[0].h = hmax;
		comps[0].v = vmax;
		int mcux = (width + 8 * hmax - 1) / (8 * hmax);
		int mcuy = (height + 8 * vmax - 1) / (8 * vmax);
		for (int c = 0; c < 3; c++) {
			comps[c].blocks_w = mcux * comps[c].h;
			comps[c].blocks_h = mcuy * comps[c].v;
			int plane_w       = (width * comps[c].h + hmax - 1) / hmax;
			int plane_h       = (height * comps[c].v + vmax - 1) / vmax;
			comps[c].real_w   = (plane_w + 7) / 8;
			comps[c].real_h   = (plane_h + 7) / 8;
			comps[c].coefficients.assign(size_t(comps[c].blocks_w) * size_t(comps[c].blocks_h) * 64, 0);
		}

		// The planes at full resolution with the edge repeated to the padded size, then the chroma is averaged down.
		int pw = mcux * 8 * hmax, ph = mcuy * 8 * vmax;
		std::vector<float> plane[3];
		for (auto& p : plane) {
			p.resize(size_t(pw) * size_t(ph));
		}
		for (int y = 0; y < ph; y++) {
			const uint8_t* row = rgba + size_t(y < height ? y : height - 1) * size_t(width) * 4;
			for (int x = 0; x < pw; x++) {
				const uint8_t* px = row + size_t(x < width ? x : width - 1) * 4;
				float r = px[0], g = px[1], b = px[2];
				size_t i = size_t(y) * size_t(pw) + size_t(x);
				plane[0][i] = 0.299f * r + 0.587f * g + 0.114f * b - 128.0f;
				plane[1][i] = -0.168736f * r - 0.331264f * g + 0.5f * b;
				plane[2][i] = 0.5f * r - 0.418688f * g - 0.081312f * b;
			}
		}
		for (int c = 0; c < 3; c++) {
			component& comp = comps[c];
			int fx = hmax / comp.h, fy = vmax / comp.v; // How many full resolution samples make one of this component.
			for (int by = 0; by < comp.blocks_h; by++) {
				for (int bx = 0; bx < comp.blocks_w; bx++) {
					float in[64], coeffs[64];
					for (int y = 0; y < 8; y++) {
						for (int x = 0; x < 8; x++) {
							float sum = 0;
							for (int dy = 0; dy < fy; dy++) {
								for (int dx = 0; dx < fx; dx++) {
									sum += plane[c][size_t((by * 8 + y) * fy + dy) * size_t(pw) + size_t((bx * 8 + x) * fx + dx)];
								}
							}
							in[y * 8 + x] = sum / float(fx * fy);
						}
					}
					forward_dct(in, coeffs);
					int16_t* block = &comp.coefficients[(size_t(by) * size_t(comp.blocks_w) + size_t(bx)) * 64];
					const uint8_t* q = quant[c ? 1 : 0];
					for (int i = 0; i < 64; i++) {
						float v = coeffs[zigzag[i]] / float(q[i]);
						block[i] = int16_t(v < 0 ? -int(-v + 0.5f) : int(v + 0.5f));
					}
				}
			}
		}

		huffman_table dc[2], ac[2];
		dc[0].init(dc_luma_bits, dc_values, 12);
		dc[1].init(dc_chroma_bits, dc_values, 12);
		ac[0].init(ac_luma_bits, ac_luma_values, 162);
		ac[1].init(ac_chroma_bits, ac_chroma_values, 162);

		out.clear();
		marker(out, 0xd8);
		marker(out, 0xe0); // JFIF.
		put16(out, 16);
		static const uint8_t jfif[] = { 'J', 'F', 'I', 'F', 0, 1, 1, 0, 0, 1, 0, 1, 0, 0 };
		out.insert(out.end(), jfif, jfif + sizeof(jfif));
		if (!exif.empty() && (exif.size() + 8 <= 65535)) {
			marker(out, 0xe1);
			put16(out, int(exif.size() + 8));
			static const uint8_t header[] = { 'E', 'x', 'i', 'f', 0, 0 };
			out.insert(out.end(), header, header + sizeof(header));
			out.insert(out.end(), exif.begin(), exif.end());
		}
		for (int t = 0; t < 2; t++) {
			marker(out, 0xdb);
			put16(out, 67);
			out.push_back(uint8_t(t));
			out.insert(out.end(), quant[t], quant[t] + 64);
		}
		marker(out, options.progressive ? 0xc2 : 0xc0);
		put16(out, 17);
		out.push_back(8);
		put16(out, height);
		put16(out, width);
		out.push_back(3);
		for (int c = 0; c < 3; c++) {
			out.push_back(uint8_t(c + 1));
			out.push_back(uint8_t((comps[c].h << 4) | comps[c].v));
			out.push_back(uint8_t(c ? 1 : 0));
		}
		define_huffman(out, 0x00, dc[0]);
		define_huffman(out, 0x10, ac[0]);
		define_huffman(out, 0x01, dc[1]);
		define_huffman(out, 0x11, ac[1]);

		auto start_scan = [&](const int* ids, int count, int ss, int se) {
			marker(out, 0xda);
			put16(out, 6 + 2 * count);
			out.push_back(uint8_t(count));
			for (int i = 0; i < count; i++) {
				out.push_back(uint8_t(ids[i] + 1));
				out.push_back(uint8_t(ids[i] ? 0x11 : 0x00));
			}
			out.push_back(uint8_t(ss));
			out.push_back(uint8_t(se));
			out.push_back(0);
		};
		auto block_of = [&](int c, int bx, int by) { return &comps[c].coefficients[(size_t(by) * size_t(comps[c].blocks_w) + size_t(bx)) * 64]; };

		// The scan of the DC coefficients of all components, which the MCUs of a baseline file carry along with the AC coefficients.
		auto interleaved = [&](bool with_ac) {
			static const int all[3] = { 0, 1, 2 };
			start_scan(all, 3, 0, with_ac ? 63 : 0);
			bit_writer w(out);
			int previous[3] = { 0, 0, 0 };
			for (int my = 0; my < mcuy; my++) {
				for (int mx = 0; mx < mcux; mx++) {
					for (int c = 0; c < 3; c++) {
						for (int v = 0; v < comps[c].v; v++) {
							for (int h = 0; h < comps[c].h; h++) {
								const int16_t* block = block_of(c, mx * comps[c].h + h, my * comps[c].v + v);
								put_dc(w, dc[c ? 1 : 0], block[0], previous[c]);
								if (with_ac) {
									put_ac(w, ac[c ? 1 : 0], block, 1, 63);
								}
							}
						}
					}
				}
			}
			w.flush();
		};
		auto band = [&](int c, int ss, int se) {
			start_scan(&c, 1, ss, se);
			bit_writer w(out);
			for (int by = 0; by < comps[c].real_h; by++) {
				for (int bx = 0; bx < comps[c].real_w; bx++) {
					put_ac(w, ac[c ? 1 : 0], block_of(c, bx, by), ss, se);
				}
			}
			w.flush();
		};

		if (!options.progressive) {
			interleaved(true);
		} else {
			interleaved(false);
			band(0, 1, 5);
			band(2, 1, 63);
			band(1, 1, 63);
			band(0, 6, 63);
		}
		marker(out, 0xd9);
		return true;
	}

