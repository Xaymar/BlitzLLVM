// A JPEG encoder for SaveBuffer, SaveImage and SaveTexture. The stb encoder that is part of the repository can only do baseline files with a fixed
// sub-sampling, so this one exists for the settings of the save commands: quality, chroma sub-sampling (4:4:4, 4:2:2, 4:2:0) and progressive files.
// It uses the standard quantization and Huffman tables of the JPEG specification (Annex K), and the progressive files are made by spectral selection
// (the DC coefficients first, then the AC coefficients in bands), which every decoder reads.

