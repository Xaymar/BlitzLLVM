	void create_buffer(gpu_buffer& buffer, uint64_t size, buffer_usage usage, memory where)
	{
		VkBufferUsageFlags flags = 0;
		flags |= (usage & vertex_data) ? VK_BUFFER_USAGE_VERTEX_BUFFER_BIT : 0;
		flags |= (usage & index_data) ? VK_BUFFER_USAGE_INDEX_BUFFER_BIT : 0;
		flags |= (usage & uniform_data) ? VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT : 0;
		flags |= (usage & storage_data) ? VK_BUFFER_USAGE_STORAGE_BUFFER_BIT : 0;
		flags |= (usage & transfer_source) ? VK_BUFFER_USAGE_TRANSFER_SRC_BIT : 0;
		flags |= (usage & transfer_destination) ? VK_BUFFER_USAGE_TRANSFER_DST_BIT : 0;
		flags |= (usage & indirect_data) ? VK_BUFFER_USAGE_INDIRECT_BUFFER_BIT : 0;
		buffer.mapped = nullptr;
		buffer.size   = size;
		if (where == memory::mesh) {
			bb::gfx::create_vk_mesh_buffer(size, flags, bb::gfx::vk_out<VkBuffer>{ buffer.vk }, bb::gfx::vk_out<VmaAllocation>{ buffer.allocation }, &buffer.mapped);
		} else {
			bb::gfx::create_vk_buffer(size, flags, where == memory::mapped, bb::gfx::vk_out<VkBuffer>{ buffer.vk }, bb::gfx::vk_out<VmaAllocation>{ buffer.allocation }, (where == memory::mapped) ? &buffer.mapped : nullptr);
		}
	}

	void destroy_buffer(gpu_buffer& buffer)
	{
		bb::gfx::destroy_vk_buffer(bb::gfx::vk_out<VkBuffer>{ buffer.vk }, bb::gfx::vk_out<VmaAllocation>{ buffer.allocation });
		buffer.mapped = nullptr;
		buffer.size   = 0;
	}

	bool can_defragment()
	{
		return bb::gfx::vkd.allocator != VK_NULL_HANDLE;
	}

	bool defragment_memory(const std::function<bool(uint64_t allocation, uint64_t destination)>& move_one)
	{
		VmaAllocator              allocator = bb::gfx::vkd.allocator;
		VmaDefragmentationInfo    info      = {};
		VmaDefragmentationContext context;
		if (vmaBeginDefragmentation(allocator, &info, &context) != VK_SUCCESS) {
			return false;
		}
		for (;;) {
			VmaDefragmentationPassMoveInfo pass = {};
			if (vmaBeginDefragmentationPass(allocator, context, &pass) != VK_INCOMPLETE) {
				break;
			}
			for (uint32_t i = 0; i < pass.moveCount; i++) {
				VmaDefragmentationMove& move = pass.pMoves[i];
				if (!move_one(uint64_t(move.srcAllocation), uint64_t(move.dstTmpAllocation))) {
					move.operation = VMA_DEFRAGMENTATION_MOVE_OPERATION_IGNORE;
				}
			}
			if (vmaEndDefragmentationPass(allocator, context, &pass) != VK_INCOMPLETE) {
				break;
			}
		}
		vmaEndDefragmentation(allocator, context, nullptr);
		return true;
	}

	void destroy_retired_buffer(uint64_t buffer, uint64_t allocation)
	{
		vmaDestroyBuffer(bb::gfx::vkd.allocator, VkBuffer(buffer), VmaAllocation(allocation));
	}

	bool create_buffer_any_thread(gpu_buffer& buffer, uint64_t size, buffer_usage usage, memory where)
	{
		// The allocator is the one that the program's thread handed over (see close_prebuild), held for as long as this runs.
		std::shared_lock<std::shared_mutex> gate(bb::gfx::prebuild_gate);
		VmaAllocator allocator = bb::gfx::prebuild_allocator;
		if (!allocator || (where != memory::mesh)) {
			return false;
		}
		VmaAllocationCreateInfo alloc;
		bb::gfx::mesh_allocation_info(alloc);
		VkBufferCreateInfo info = { VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO };
		info.sharingMode        = VK_SHARING_MODE_EXCLUSIVE;
		info.size               = size;
		info.usage              = ((usage & vertex_data) ? VK_BUFFER_USAGE_VERTEX_BUFFER_BIT : 0) | ((usage & index_data) ? VK_BUFFER_USAGE_INDEX_BUFFER_BIT : 0);
		VmaAllocationInfo result;
		if (vmaCreateBuffer(allocator, &info, &alloc, bb::gfx::vk_out<VkBuffer>{ buffer.vk }, bb::gfx::vk_out<VmaAllocation>{ buffer.allocation }, &result) != VK_SUCCESS) {
			buffer.vk         = 0;
			buffer.allocation = 0;
			return false;
		}
		buffer.mapped = result.pMappedData;
		buffer.size   = size;
		return true;
	}

	void destroy_buffer_any_thread(gpu_buffer& buffer)
	{
		std::shared_lock<std::shared_mutex> gate(bb::gfx::prebuild_gate);
		if (buffer.vk && bb::gfx::prebuild_allocator) {
			vmaDestroyBuffer(bb::gfx::prebuild_allocator, VkBuffer(buffer.vk), VmaAllocation(buffer.allocation));
		}
		buffer = gpu_buffer();
	}

