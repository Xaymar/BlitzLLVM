// What animation.cpp and b3d.cpp share: the nodes of a model with their keys, and how they are put into place.
//
// A model is a tree of nodes. Each node is an entity, which can have a mesh. Nodes have keys that say where they are,
// how big they are and how they are turned at certain frames, and nodes can be bones: they pull the vertices of the
// mesh along, each by a weight. Animating moves the bones, and then every vertex is put where its bones say.
