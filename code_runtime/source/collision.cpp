	struct contact_list {
		buffer<contact> contacts;
	};
	buffer<contact_list> contact_lists; // Indexed by entity handle - 1.

	contact_list& contacts_of(int handle)
	{
		while (contact_lists.size < uint32_t(handle)) {
			contact_lists.push(contact_list());
		}
		return contact_lists[uint32_t(handle) - 1];
	}

