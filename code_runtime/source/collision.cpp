// Stats3D: 0 is how many triangles the collisions of the last UpdateWorld looked at. The original also counts the
// vertices and triangles of terrains that were drawn, which are not counted here.
float bb_stats_3d(int32_t type)
{
	return type == 0 ? float(triangles_tested) : 0.0f;
}

// UpdateWorld: collisions, and what is animated.
void bb_update_world(float speed)
{
	triangles_tested = 0;
	{
		bb::profile_scope timer(bb::PROFILE_ANIMATION);
		bb_animation_update(speed);
	}
	bb::profile_scope timer(bb::PROFILE_UPDATE_WORLD);
	update_collisions();
}

// ResetEntity: forgets where it was, so that the way to where it is now is not collided with.
void bb_reset_entity(int32_t handle)
{
	need(handle, "ResetEntity");
	reset_movement(handle);
	if (handle <= int(contact_lists.size)) {
		contact_lists[uint32_t(handle) - 1].contacts.clear();
	}
}

void bb_entity_type(int32_t handle, int32_t type, int32_t recursive)
{
	entity* e = need(handle, "EntityType");
	if ((type < 0) || (type > 999)) {
		fail("EntityType: the type has to be between 0 and 999.");
	}
	e->coll_type = type;
	reset_movement(handle);
	if (recursive) {
		for (int other = 1; other <= entity_count(); other++) {
			entity* child = get_entity(other);
			if (child && (child->parent == handle)) {
				bb_entity_type(other, type, 1);
			}
		}
	}
}

void bb_entity_radius(int32_t handle, float x_radius, float y_radius)
{
	entity* e = need(handle, "EntityRadius");
	e->radius[0] = x_radius;
	e->radius[1] = y_radius > 0 ? y_radius : x_radius;
}

void bb_entity_box(int32_t handle, float x, float y, float z, float w, float h, float d)
{
	entity* e = need(handle, "EntityBox");
	e->has_box = true;
	e->box[0] = x;
	e->box[1] = y;
	e->box[2] = z;
	e->box[3] = w;
	e->box[4] = h;
	e->box[5] = d;
}
// Response: 1 = stop, 2 = slide, 3 = slide, but not down slopes.
void bb_collisions(int32_t source, int32_t destination, int32_t method, int32_t response)
{
	if ((source < 0) || (source > 999) || (destination < 0) || (destination > 999)) {
		fail("Collisions: the types have to be between 0 and 999.");
	}
	if ((method < 1) || (method > 3) || (response < 1) || (response > 3)) {
		fail("Collisions: the method and the response have to be between 1 and 3.");
	}
	for (uint32_t r = 0; r < rules.size; r++) {
		if ((rules[r].source == source) && (rules[r].destination == destination)) {
			return; // A pair of types has one rule, the first one, until ClearCollisions.
		}
	}
	rules.push({ source, destination, method, response });
}

void bb_clear_collisions(void)
{
	rules.clear();
}

int32_t bb_count_collisions(int32_t handle)
{
	need(handle, "CountCollisions");
	return (handle <= int32_t(contact_lists.size)) ? int32_t(contact_lists[uint32_t(handle) - 1].contacts.size) : 0;
}

static contact const& contact_at(int32_t handle, int32_t index, const char* what)
{
	need(handle, what);
	if ((handle > int32_t(contact_lists.size)) || (index < 1) || (uint32_t(index) > contact_lists[uint32_t(handle) - 1].contacts.size)) {
		fail("There is no such collision.");
	}
	return contact_lists[uint32_t(handle) - 1].contacts[uint32_t(index) - 1];
}

int32_t bb_collision_entity(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionEntity").entity; }
float   bb_collision_x(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionX").point.x; }
float   bb_collision_y(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionY").point.y; }
float   bb_collision_z(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionZ").point.z; }
float   bb_collision_nx(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionNX").normal.x; }
float   bb_collision_ny(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionNY").normal.y; }
float   bb_collision_nz(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionNZ").normal.z; }
float   bb_collision_time(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionTime").time; }
int32_t bb_collision_surface(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionSurface").surface; }
int32_t bb_collision_triangle(int32_t handle, int32_t index) { return contact_at(handle, index, "CollisionTriangle").triangle; }

// The entity of the given type that this one collided with, or 0.
int32_t bb_entity_collided(int32_t handle, int32_t type)
{
	need(handle, "EntityCollided");
	if (handle > int32_t(contact_lists.size)) {
		return 0;
	}
	buffer<contact>& list = contact_lists[uint32_t(handle) - 1].contacts;
	for (uint32_t i = 0; i < list.size; i++) {
		entity* other = get_entity(list[i].entity);
		if (other && (other->coll_type == type)) {
			return list[i].entity;
		}
	}
	return 0;
}

