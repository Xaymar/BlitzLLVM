// Collisions and picking.
//
// Collisions: entities get a type (EntityType), and Collisions says which types collide with which, and what
// happens then. UpdateWorld moves every entity that can collide from where it was at the last UpdateWorld to where
// the program put it, and stops or slides it when it hits something on the way. Entities that collide are
// ellipsoids (EntityRadius), what they collide with can be spheres, the polygons of a mesh, or boxes.
//
// This is done with the swept ellipsoid method: the world is squashed so that the ellipsoid becomes a unit sphere,
// then a sphere is moved along a line and tested against triangles.
//
// Picking: finds what is along a line or a ray, for entities that have a pick mode.

