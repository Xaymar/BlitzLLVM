extern "C" int32_t bb_is_debug(void);

namespace {
	struct mode {
		int width, height, depth;
	};
	bb::buffer<mode> modes;
	bool             modes_listed = false;

	void add_mode(int width, int height, int depth)
	{
		for (uint32_t i = 0; i < modes.size; i++) {
			if ((modes[i].width == width) && (modes[i].height == height) && (modes[i].depth == depth)) {
				return;
			}
		}
		modes.push({ width, height, depth });
	}

	// The fullscreen modes of the display. Without one (and without a window, as with BLITZ_HEADLESS, which is looked at
	// here because Graphics may not have been called yet) a few common sizes are listed.
	void list_modes()
	{
		if (modes_listed) {
			return;
		}
		modes_listed = true;
		if (!g.headless && !getenv("BLITZ_HEADLESS") && SDL_InitSubSystem(SDL_INIT_VIDEO)) {
			int                count   = 0;
			SDL_DisplayMode**  display = SDL_GetFullscreenDisplayModes(SDL_GetPrimaryDisplay(), &count);
			for (int i = 0; display && (i < count); i++) {
				// Palette and 16 bit modes are not supported, so every size is listed once with 32 bits.
				add_mode(display[i]->w, display[i]->h, 32);
			}
			SDL_free(display);
		}
		if (modes.size == 0) {
			static const int sizes[][2] = { { 640, 480 },  { 800, 600 },   { 1024, 768 }, { 1152, 864 }, { 1280, 720 }, { 1280, 768 }, { 1280, 800 },
		                                      { 1280, 960 }, { 1280, 1024 }, { 1360, 768 }, { 1366, 768 }, { 1440, 900 }, { 1600, 900 }, { 1600, 1200 },
		                                      { 1680, 1050 }, { 1920, 1080 }, { 1920, 1200 }, { 2560, 1440 }, { 3840, 2160 } };
			for (const auto& size : sizes) {
				add_mode(size[0], size[1], 32);
			}
		}
	}

	mode& mode_at(int32_t index, const char* what)
	{
		list_modes();
		if ((index < 1) || (uint32_t(index) > modes.size)) {
			char message[96];
			snprintf(message, sizeof(message), "%s: the graphics mode does not exist.", what);
			bb_runtime_error(message);
		}
		return modes[uint32_t(index) - 1];
	}

	void need_driver(int32_t driver, const char* what)
	{
		list_gpus();
		if ((driver < 1) || (uint32_t(driver) > gpu_total)) {
			char message[96];
			snprintf(message, sizeof(message), "%s: the graphics driver does not exist.", what);
			bb_runtime_error(message);
		}
	}

	// Whether anything that needs the GPU was made, after which the GPU can not be chosen any more.
	bool gpu_in_use()
	{
		if (g.created) {
			return true;
		}
		for (uint32_t i = 0; i < texture_table.size; i++) {
			if (texture_table[i].used) {
				return true;
			}
		}
		for (uint32_t i = 0; i < image_table.size; i++) {
			if (image_table[i].used) {
				return true;
			}
		}
		return false;
	}
} // namespace

