// What the graphics hardware and the display can do, and the settings of the original that were made for hardware of
// the time: there is one graphics driver, the GPU, and the modes are the ones of the display.

#include "graphics_internal.hpp"

using namespace bb::gfx;

namespace {
	struct mode {
		int width, height, depth;
	};
	bb::buffer<mode> modes;
	bool             modes_listed = false;

	float gamma_ramp[3][256];
	bool  gamma_ready = false;

	void add_mode(int width, int height, int depth)
	{
		for (uint32_t i = 0; i < modes.size; i++) {
			if ((modes[i].width == width) && (modes[i].height == height) && (modes[i].depth == depth)) {
				return;
			}
		}
		modes.push({ width, height, depth });
	}

	// The fullscreen modes of the display. Without one (and without a window) a few common sizes are listed.
	void list_modes()
	{
		if (modes_listed) {
			return;
		}
		modes_listed = true;
		if (!g.headless && SDL_InitSubSystem(SDL_INIT_VIDEO)) {
			int                count   = 0;
			SDL_DisplayMode**  display = SDL_GetFullscreenDisplayModes(SDL_GetPrimaryDisplay(), &count);
			for (int i = 0; display && (i < count); i++) {
				const SDL_PixelFormatDetails* details = SDL_GetPixelFormatDetails(display[i]->format);
				add_mode(display[i]->w, display[i]->h, details ? details->bits_per_pixel : 32);
			}
			SDL_free(display);
		}
		if (modes.size == 0) {
			static const int sizes[][2] = { { 640, 480 }, { 800, 600 }, { 1024, 768 }, { 1280, 720 }, { 1280, 1024 }, { 1920, 1080 } };
			for (const auto& size : sizes) {
				add_mode(size[0], size[1], 32);
			}
		}
	}

	mode& mode_at(int32_t index, const char* what)
	{
		list_modes();
		if ((index < 1) || (uint32_t(index) > modes.size)) {
			char message[96];
			snprintf(message, sizeof(message), "%s: the graphics mode does not exist.", what);
			bb_runtime_error(message);
		}
		return modes[uint32_t(index) - 1];
	}

	void need_driver(int32_t driver, const char* what)
	{
		if (driver != 1) {
			char message[96];
			snprintf(message, sizeof(message), "%s: the graphics driver does not exist.", what);
			bb_runtime_error(message);
		}
	}

	void need_gamma()
	{
		if (!gamma_ready) {
			gamma_ready = true;
			for (int c = 0; c < 3; c++) {
				for (int i = 0; i < 256; i++) {
					gamma_ramp[c][i] = float(i);
				}
			}
		}
	}

	float clamp_gamma(float value)
	{
		return value < 0 ? 0 : (value > 255 ? 255 : value);
	}
} // namespace

