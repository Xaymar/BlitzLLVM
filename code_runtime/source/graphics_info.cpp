const char* bb_gfx_driver_name(int32_t driver)
{
	need_driver(driver, "GfxDriverName");
	const char* name = "Default";
	if (g.physical && vkGetPhysicalDeviceProperties) {
		static VkPhysicalDeviceProperties properties;
		vkGetPhysicalDeviceProperties(g.physical, &properties);
		name = properties.deviceName;
	}
	char* copy = static_cast<char*>(malloc(strlen(name) + 1));
	strcpy(copy, name);
	return copy;
}

