int32_t bb_count_gfx_drivers(void)
{
	list_gpus();
	return int32_t(gpu_total);
}

const char* bb_gfx_driver_name(int32_t driver)
{
	need_driver(driver, "GfxDriverName");
	const char* name = gpus[driver - 1].name;
	char*       copy = static_cast<char*>(bb_malloc(strlen(name) + 1));
	strcpy(copy, name);
	return copy;
}

// The GPU is chosen when the first graphics window is made, so this only works before that. Afterwards a debug build
// stops with an error, because the program does not do what it says, and any other build carries on with the GPU in use.
void bb_set_gfx_driver(int32_t driver)
{
	need_driver(driver, "SetGfxDriver");
	if (gpu_in_use()) {
		if (bb_is_debug()) {
			bb_runtime_error("SetGfxDriver: the graphics driver can only be chosen before the first graphics window, image or texture is made.");
		}
		return;
	}
	driver_choice = driver;
}

// A BlitzLLVM extension: the driver that is in use, or the one that will be used if no graphics window is open yet.
int32_t bb_gfx_driver(void)
{
	list_gpus();
	if (g.created && (g.driver_used > 0)) {
		return g.driver_used;
	}
	return driver_choice > 0 ? driver_choice : 1;
}

// A driver can draw 3D if it does Vulkan 1.3 with a queue that draws, which a GPU of the last years does.
int32_t bb_gfx_driver_3d(int32_t driver)
{
	need_driver(driver, "GfxDriver3D");
	return gpus[driver - 1].usable ? 1 : 0;
}

