int32_t bb_load_anim_mesh(const char* file, int32_t parent)
{
	return load_model(file, parent, true, "LoadAnimMesh: the file is not a model that can be read.");
}

int32_t bb_load_mesh(const char* file, int32_t parent)
{
	return load_model(file, parent, false, "LoadMesh: the file is not a model that can be read.");
}

// EntityReady(entity): 1 once a model from LoadMesh or LoadAnimMesh is built and its textures are loaded, without waiting for it.
// Every other entity is ready all the time.
int32_t bb_entity_ready(int32_t handle)
{
	entity* e = get_entity_raw(handle);
	if (!e) {
		return 0;
	}
	if (!e->loading) {
		return 1;
	}
	if (e->loading->job) {
		if (!gfx::async_finished(e->loading->job)) {
			return 0;
		}
		resolve_model(handle, *e);
	}
	buffer<int>& list = e->loading->textures;
	for (uint32_t i = 0; i < list.size; i++) {
		if (bb_texture_loading(list[i])) {
			return 0;
		}
	}
	return 1;
}

// LoadAnimSeq entity, file: the animation of a model in a file becomes a new sequence of the entity, for the parts that
// have the same names. Gives the number of the new sequence, or -1 if the entity has no animation.
int32_t bb_load_anim_seq(int32_t handle, const char* file)
{
	if (!get_entity(handle)) {
		fail("LoadAnimSeq: the entity does not exist.");
	}
	animation* a = animation_of(handle);
	if (!a) {
		return -1;
	}
	model m;
	if (!file || !read_model(file, m)) {
		m.release();
		return int32_t(a->sequences.size) - 1;
	}
	float length = m.frames > 0 ? m.frames : 1;
	float offset = a->frames;
	for (uint32_t i = 0; i < a->nodes.size; i++) {
		anim_node& n    = *a->nodes[i];
		entity*    e    = get_entity(n.handle);
		const char* own = e ? e->name : nullptr;
		if (!own) {
			continue;
		}
		for (uint32_t k = 0; k < m.nodes.size; k++) {
			node_info& source = *m.nodes[k];
			if (!source.name || strcmp(source.name, own) != 0) {
				continue;
			}
			for (uint32_t j = 0; j < source.pos_keys.size; j++) {
				key3 key = source.pos_keys[j];
				key.frame += offset;
				n.pos_keys.push(key);
			}
			for (uint32_t j = 0; j < source.scale_keys.size; j++) {
				key3 key = source.scale_keys[j];
				key.frame += offset;
				n.scale_keys.push(key);
			}
			for (uint32_t j = 0; j < source.rot_keys.size; j++) {
				key4 key = source.rot_keys[j];
				key.frame += offset;
				n.rot_keys.push(key);
			}
			break;
		}
	}
	a->sequences.push({ offset, offset + length });
	a->frames += length;
	m.release();
	return int32_t(a->sequences.size) - 1;
}

// LoaderMatrix extension, the nine numbers of a matrix: how models of that file type are turned when they are loaded.
// Only the one for .x files is used. 3D Studio models always have y and z swapped, and .b3d files are never turned, as in the original.
void bb_loader_matrix(const char* extension, float xx, float xy, float xz, float yx, float yy, float yz, float zx, float zy, float zz)
{
	if (!extension) {
		return;
	}
	if (extension[0] == '.') {
		extension++;
	}
	if ((extension[0] == 'x' || extension[0] == 'X') && !extension[1]) {
		const float matrix[9] = { xx, xy, xz, yx, yy, yz, zx, zy, zz };
		std::lock_guard<std::mutex> guard(x_matrix_lock);
		memcpy(x_matrix, matrix, sizeof(matrix));
		x_matrix_set = true;
	}
}
