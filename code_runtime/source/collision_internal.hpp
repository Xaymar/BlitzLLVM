	struct vec3 {
		float x = 0, y = 0, z = 0;
	};

	inline vec3  operator+(vec3 a, vec3 b) { return { a.x + b.x, a.y + b.y, a.z + b.z }; }
	inline vec3  operator-(vec3 a, vec3 b) { return { a.x - b.x, a.y - b.y, a.z - b.z }; }
	inline vec3  operator*(vec3 a, float s) { return { a.x * s, a.y * s, a.z * s }; }
	inline float dot(vec3 a, vec3 b) { return a.x * b.x + a.y * b.y + a.z * b.z; }
	inline vec3  cross(vec3 a, vec3 b) { return { a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y - a.y * b.x }; }
	inline float length_squared(vec3 a) { return dot(a, a); }
	inline float length(vec3 a) { return sqrtf(dot(a, a)); }
	inline vec3  normalized(vec3 a)
	{
		float l = length(a);
		return l > 1e-12f ? a * (1.0f / l) : vec3();
	}

	inline vec3 transform(const float* m, vec3 p)
	{
		return { m[0] * p.x + m[4] * p.y + m[8] * p.z + m[12], m[1] * p.x + m[5] * p.y + m[9] * p.z + m[13], m[2] * p.x + m[6] * p.y + m[10] * p.z + m[14] };
	}

	inline vec3 divided(vec3 a, vec3 r) { return { a.x / r.x, a.y / r.y, a.z / r.z }; }
	inline vec3 multiplied(vec3 a, vec3 r) { return { a.x * r.x, a.y * r.y, a.z * r.z }; }

	struct triangle {
		vec3 a, b, c;
		int  surface;
		int  index;
	};

	struct box3 {
		vec3 lo, hi;
		bool empty = true;

		void add(vec3 p)
		{
			if (empty) {
				lo = hi = p;
				empty   = false;
				return;
			}
			// Same as fminf and fmaxf, which do not get inlined and were a tenth of the time of a busy UpdateWorld.
			auto less    = [](float a, float b) { return (a < b) || (b != b); };
			auto greater = [](float a, float b) { return (a > b) || (b != b); };
			lo = { less(p.x, lo.x) ? p.x : lo.x, less(p.y, lo.y) ? p.y : lo.y, less(p.z, lo.z) ? p.z : lo.z };
			hi = { greater(p.x, hi.x) ? p.x : hi.x, greater(p.y, hi.y) ? p.y : hi.y, greater(p.z, hi.z) ? p.z : hi.z };
		}

		bool overlaps(box3 const& o) const
		{
			return !empty && !o.empty && (lo.x <= o.hi.x) && (hi.x >= o.lo.x) && (lo.y <= o.hi.y) && (hi.y >= o.lo.y) && (lo.z <= o.hi.z) && (hi.z >= o.lo.z);
		}
	};


