	// Calls the function for the triangles of the entity that are in the world box, in world coordinates.
	template<typename F>
	void each_triangle_matrix(entity& e, const float* m, box3 const& area, F&& visit)
	{

		if (e.terrain) {
			// Terrains have too many triangles to look at all of them, so only the cells in the area are looked at.
			update_terrain(e);
			float inverse[16];
			mat_affine_inverse(m, inverse);
			box3 local;
			for (int corner = 0; corner < 8; corner++) {
				local.add(transform(inverse, { (corner & 1) ? area.hi.x : area.lo.x, (corner & 2) ? area.hi.y : area.lo.y, (corner & 4) ? area.hi.z : area.lo.z }));
			}
			int n  = e.terrain->size;
			int x0 = int(floorf(local.lo.x)) - 1, x1 = int(ceilf(local.hi.x)) + 1;
			int z0 = int(floorf(local.lo.z)) - 1, z1 = int(ceilf(local.hi.z)) + 1;
			x0 = x0 < 0 ? 0 : x0;
			z0 = z0 < 0 ? 0 : z0;
			x1 = x1 > n - 1 ? n - 1 : x1;
			z1 = z1 > n - 1 ? n - 1 : z1;
			const float* h = e.terrain->heights;
			for (int z = z0; z <= z1; z++) {
				for (int x = x0; x <= x1; x++) {
					vec3 p00 = transform(m, { float(x), h[z * (n + 1) + x], float(z) });
					vec3 p10 = transform(m, { float(x + 1), h[z * (n + 1) + x + 1], float(z) });
					vec3 p01 = transform(m, { float(x), h[(z + 1) * (n + 1) + x], float(z + 1) });
					vec3 p11 = transform(m, { float(x + 1), h[(z + 1) * (n + 1) + x + 1], float(z + 1) });
					// Same winding as the mesh: clockwise seen from above.
					visit(triangle{ p00, p01, p10, 0, (z * n + x) * 2 });
					visit(triangle{ p10, p01, p11, 0, (z * n + x) * 2 + 1 });
				}
			}
			return;
		}

		for (uint32_t s = 0; s < e.surfaces.size; s++) {
			surface& surf = *e.surfaces[s];
			for (uint32_t i = 0; i + 2 < surf.indices.size; i += 3) {
				vertex3d const &a = surf.vertices[surf.indices[i]], &b = surf.vertices[surf.indices[i + 1]], &c = surf.vertices[surf.indices[i + 2]];
				triangle t = { transform(m, { a.x, a.y, a.z }), transform(m, { b.x, b.y, b.z }), transform(m, { c.x, c.y, c.z }), int(s) + 1, int(i / 3) };
				box3 tb;
				tb.add(t.a);
				tb.add(t.b);
				tb.add(t.c);
				if (tb.overlaps(area)) {
					visit(t);
				}
			}
		}
	}

	template<typename F>
	void each_triangle(int handle, entity& e, box3 const& area, F&& visit)
	{
		float m[16];
		world_matrix(handle, m);
		each_triangle_matrix(e, m, area, visit);
	}

	// The 12 triangles of a box, in world coordinates.
	template<typename F>
	void each_box_triangle(entity const& e, const float* m, F&& visit)
	{
		box3 local = local_bounds(e);
		if (local.empty) {
			return;
		}
		vec3 c[8];
		for (int i = 0; i < 8; i++) {
			c[i] = transform(m, { (i & 1) ? local.hi.x : local.lo.x, (i & 2) ? local.hi.y : local.lo.y, (i & 4) ? local.hi.z : local.lo.z });
		}
		static const int faces[12][3] = {
			{ 0, 2, 1 }, { 1, 2, 3 }, { 4, 5, 6 }, { 5, 7, 6 }, { 0, 1, 4 }, { 1, 5, 4 }, { 2, 6, 3 }, { 3, 6, 7 }, { 0, 4, 2 }, { 2, 4, 6 }, { 1, 3, 5 }, { 3, 7, 5 },
		};
		for (int i = 0; i < 12; i++) {
			// Both sides count, so that it does not matter which way the box was turned by a negative scale.
			visit(triangle{ c[faces[i][0]], c[faces[i][1]], c[faces[i][2]], 0, i });
			visit(triangle{ c[faces[i][0]], c[faces[i][2]], c[faces[i][1]], 0, i });
		}
	}

	// The sphere is a point that moves along a line, and what it hits is made bigger by the radius of the sphere.
	const float collision_epsilon = 0.001f;

	struct line3 {
		vec3 o, d;
	};

	inline vec3 at(line3 const& l, float t) { return l.o + l.d * t; }

	struct plane3 {
		vec3  n;
		float d = 0;

		float distance(vec3 p) const { return dot(n, p) + d; }
		float t_intersect(line3 const& l) const { return -distance(l.o) / dot(n, l.d); }
		vec3  nearest(vec3 q) const { return q - n * distance(q); }
	};

	inline plane3 plane_through(vec3 point, vec3 normal) { return { normal, -dot(normal, point) }; }

	inline plane3 plane_of(vec3 v0, vec3 v1, vec3 v2)
	{
		vec3 n = normalized(cross(v1 - v0, v2 - v0));
		return { n, -dot(n, v0) };
	}

	// Where two planes meet.
	inline line3 plane_meeting(plane3 const& a, plane3 const& b)
	{
		vec3   lv        = normalized(cross(a.n, b.n));
		line3  across    = { a.nearest(a.n * -a.d), cross(a.n, lv) };
		vec3   on_b      = at(across, b.t_intersect(across));
		return { on_b, lv };
	}

	inline vec3 nearest_on_line(line3 const& l, vec3 q) { return l.o + l.d * (dot(l.d, q - l.o) / dot(l.d, l.d)); }

