static int failures = 0;
#define CHECK(expr)                                                         \
	do {                                                                    \
		if (!(expr)) {                                                      \
			fprintf(stderr, "%s:%d: check failed: %s\n", __FILE__, __LINE__, #expr); \
			failures++;                                                     \
		}                                                                   \
	} while (0)

static void fill(void* p, size_t n, unsigned seed)
{
	unsigned char* b = static_cast<unsigned char*>(p);
	for (size_t i = 0; i < n; i++) {
		b[i] = static_cast<unsigned char>(seed + i * 7);
	}
}
static bool verify(void* p, size_t n, unsigned seed)
{
	unsigned char* b = static_cast<unsigned char*>(p);
	for (size_t i = 0; i < n; i++) {
		if (b[i] != static_cast<unsigned char>(seed + i * 7)) {
			return false;
		}
	}
	return true;
}

static void test_sizes()
{
	// Every size up to well beyond the small tier: aligned, big enough, not overlapping, content kept.
	std::vector<std::pair<void*, size_t>> blocks;
	for (size_t size = 0; size <= 70000; size += (size < 4200 ? 1 : 97)) {
		void* p = bb_malloc(size);
		CHECK(p != nullptr);
		CHECK((uintptr_t(p) & 15) == 0);
		if (size <= 32768) {
			CHECK(bb_malloc_size(p) >= size);
		} else {
			CHECK(bb_malloc_size(p) == 0); // Normal blocks belong to the system.
		}
		fill(p, size, unsigned(size));
		blocks.emplace_back(p, size);
	}
	for (auto& b : blocks) {
		CHECK(verify(b.first, b.second, unsigned(b.second)));
		bb_free(b.first);
	}
}

static void test_reuse_and_calloc()
{
	for (int round = 0; round < 3; round++) {
		void* a = bb_malloc(100);
		memset(a, 0xAB, 100);
		bb_free(a);
		void* b = bb_calloc(1, 100); // Gets the block back, which must be cleared.
		for (int i = 0; i < 100; i++) {
			CHECK(static_cast<unsigned char*>(b)[i] == 0);
		}
		bb_free(b);
	}
	void* big = bb_calloc(4, 100000);
	CHECK(big && static_cast<unsigned char*>(big)[399999] == 0);
	bb_free(big);
	CHECK(bb_calloc(size_t(-1), 2) == nullptr);
}

static void test_realloc()
{
	size_t sizes[] = { 1, 15, 16, 17, 100, 129, 1000, 2048, 2049, 5000, 32768, 32769, 100000, 50, 8, 0 };
	void*  p       = nullptr;
	size_t old     = 0;
	for (size_t n : sizes) {
		if (n == 0) {
			bb_realloc(p, 0);
			p = nullptr;
			break;
		}
		p = bb_realloc(p, n);
		CHECK(p != nullptr);
		size_t keep = old < n ? old : n;
		CHECK(verify(p, keep, 5));
		fill(p, n, 5);
		old = n;
	}
	bb_free(p);
}

static void test_foreign()
{
	// Blocks of the system allocator (or of another library) must pass through free, realloc and size queries.
	char* p = static_cast<char*>(FOREIGN_MALLOC(64));
	memset(p, 7, 64);
	CHECK(bb_malloc_size(p) == 0);
	p = static_cast<char*>(bb_realloc(p, 4096)); // Stays with the system.
	CHECK(p && p[63] == 7);
	bb_free(p);
	char* q = static_cast<char*>(FOREIGN_MALLOC(32));
	bb_free(q);
	bb_free(nullptr);
}

static void test_aligned_and_new()
{
	for (size_t a : { size_t(16), size_t(32), size_t(64), size_t(4096) }) {
		void* p = bb_aligned_alloc(a, 100);
		CHECK(p && (uintptr_t(p) % a) == 0);
		bb_aligned_free(p);
	}
#if defined(__cpp_aligned_new)
	struct alignas(64) wide {
		char c[64];
	};
	wide* w = new wide;
	CHECK((uintptr_t(w) & 63) == 0);
	delete w;
	wide* ws = new wide[5];
	CHECK((uintptr_t(ws) & 63) == 0);
	delete[] ws;
#endif
	int* i = new int(5);
	CHECK(*i == 5);
	delete i;
	char* nt = new (std::nothrow) char[1000];
	CHECK(nt != nullptr);
	delete[] nt;
	std::vector<std::unique_ptr<int>> v;
	for (int n = 0; n < 1000; n++) {
		v.push_back(std::make_unique<int>(n));
	}
	for (int n = 0; n < 1000; n++) {
		CHECK(*v[n] == n);
	}
}

// Threads that only allocate and threads that only free what the first ones made, in both directions.
static void test_threads()
{
	constexpr int            producers = 4, per_thread = 200000, rounds = 5;
	bb_mem_stats             before;
	bb_mem_get_stats(&before);
	std::atomic<int>         bad{ 0 };
	for (int round = 0; round < rounds; round++) {
		std::vector<std::vector<std::pair<void*, uint32_t>>> made(producers);
		std::vector<std::thread>                             threads;
		for (int t = 0; t < producers; t++) {
			threads.emplace_back([&, t] {
				for (int n = 0; n < per_thread; n++) {
					size_t   size = 16 + size_t((n * 31 + t * 7) % 3000);
					uint32_t seed = uint32_t(n + t);
					void*    p    = bb_malloc(size);
					fill(p, size < 64 ? size : 64, seed);
					made[t].emplace_back(p, seed);
				}
			});
		}
		for (auto& th : threads) {
			th.join();
		}
		threads.clear();
		// Other threads free them (the producers already ended: their caches went back to the pool).
		for (int t = 0; t < producers; t++) {
			threads.emplace_back([&, t] {
				int other = (t + 1) % producers;
				for (auto& b : made[other]) {
					if (!verify(b.first, 16, b.second)) {
						bad++;
					}
					bb_free(b.first);
				}
			});
		}
		for (auto& th : threads) {
			th.join();
		}
	}
	CHECK(bad == 0);
	// Memory must have been reused: 5 rounds of 800000 blocks (about 1.2 GB) may not take 5 times the spans of one.
	bb_mem_stats after;
	bb_mem_get_stats(&after);
	size_t spans = (after.tiny_spans + after.small_spans) - (before.tiny_spans + before.small_spans);
	printf("threads: %zu spans (%zu MiB)\n", spans, (after.tiny_spans * 64 + after.small_spans * 256) / 1024);
	CHECK(spans < 20000);
}

// Resident memory of the process in KiB (0 where it cannot be told).
static size_t resident_kib()
{
#if defined(__linux__)
	FILE* f = fopen("/proc/self/statm", "r");
	if (!f) {
		return 0;
	}
	unsigned long total = 0, resident = 0;
	if (fscanf(f, "%lu %lu", &total, &resident) != 2) {
		resident = 0;
	}
	fclose(f);
	return size_t(resident) * 4;
#else
	return 0;
#endif
}

// Spans that stay empty for a second go back to the system; spans with a block in use stay; a given back span works again.
// The clock is the test's (bb_mem_release_idle), so nothing waits.
static void test_release()
{
	constexpr int count = 400000, size = 100; // About 45 MB of 112 byte blocks.
	// The tests before left empty spans behind: let them go first.
	bb_mem_release_idle(10000);
	bb_mem_release_idle(11500);
	std::vector<void*> blocks(count);
	for (int i = 0; i < count; i++) {
		blocks[i] = bb_malloc(size);
		memset(blocks[i], 0x5A, size);
	}
	// Every 500th block stays (a span holds 585): no span is empty, nothing may go.
	for (int i = 0; i < count; i++) {
		if (i % 500) {
			bb_free(blocks[i]);
		}
	}
	CHECK(bb_mem_release_idle(100000) == 0);
	CHECK(bb_mem_release_idle(120000) == 0);
	for (int i = 0; i < count; i += 500) {
		CHECK(verify(blocks[i], 0, 0) && static_cast<unsigned char*>(blocks[i])[size - 1] == 0x5A);
		bb_free(blocks[i]);
	}
	bb_mem_stats before;
	bb_mem_get_stats(&before);
	size_t rss_before = resident_kib();
	const char* switch_value = getenv("BLITZLLVM_ALLOC_RELEASE");
	if (switch_value && !strcmp(switch_value, "0")) { // Turned off: spans stay where they are.
		CHECK(bb_mem_release_idle(140000) == 0);
		CHECK(bb_mem_release_idle(145000) == 0);
		puts("release: off");
		return;
	}
	// The first looks find the spans that are empty now for the first time, so those stay. A span that was already empty at the
	// sweeps above (the one kept per class) may have been overtaken by a lower one that is empty now and is then due: that depends
	// on where the earlier tests left their blocks, which differs between runs and platforms, so a few are allowed to go.
	size_t early = bb_mem_release_idle(140000); // First seen empty.
	early += bb_mem_release_idle(140500);       // Only half a second.
	CHECK(early <= 8);
	size_t released = early + bb_mem_release_idle(141200);
	CHECK(released > 50);
	bb_mem_stats after;
	bb_mem_get_stats(&after);
	CHECK(after.released_spans - before.released_spans == released);
	CHECK(after.spare_spans >= released);
	size_t rss_after = resident_kib();
	printf("release: %zu spans given back, resident %zu -> %zu MiB\n", released, rss_before / 1024, rss_after / 1024);
	if (rss_before) {
		CHECK(rss_after + 20 * 1024 < rss_before);
	}
	// The spans come back into use: no new address range, memory that is zero, contents that stay.
	bb_mem_stats mid;
	bb_mem_get_stats(&mid);
	for (int i = 0; i < count / 2; i++) {
		unsigned char* p = static_cast<unsigned char*>(bb_calloc(1, size));
		for (int k = 0; k < size; k += 17) {
			CHECK(p[k] == 0);
		}
		fill(p, size, unsigned(i));
		blocks[i] = p;
	}
	bb_mem_stats reuse;
	bb_mem_get_stats(&reuse);
	CHECK(reuse.reused_spans > mid.reused_spans);
	CHECK(reuse.tiny_spans == mid.tiny_spans); // The given back spans were enough.
	for (int i = 0; i < count / 2; i++) {
		CHECK(verify(blocks[i], size, unsigned(i)));
		bb_free(blocks[i]);
	}
	// A full cycle again with the spans that are in use again.
	bb_mem_release_idle(200000);
	bb_mem_release_idle(201100);
}

// Sweeps run on one thread while others allocate, free and hand blocks over: nothing may be damaged or lost.
static void test_release_threads()
{
	std::atomic<bool> stop{ false };
	std::atomic<int>  bad{ 0 };
	std::vector<std::thread> workers;
	for (int t = 0; t < 3; t++) {
		workers.emplace_back([&, t] {
			unsigned seed = unsigned(t) * 977u;
			while (!stop) {
				std::vector<std::pair<void*, unsigned>> mine;
				int n = 20000 + int(seed % 20000);
				for (int i = 0; i < n; i++) {
					seed = seed * 1664525u + 1013904223u;
					size_t sz = 16 + (seed >> 8) % 1500;
					void*  p  = bb_malloc(sz);
					fill(p, sz < 48 ? sz : 48, seed);
					mine.emplace_back(p, seed);
				}
				for (auto& b : mine) {
					if (!verify(b.first, 16, b.second)) {
						bad++;
					}
					bb_free(b.first);
				}
			}
		});
	}
	uint32_t clock = 1000000;
	auto     end   = std::chrono::steady_clock::now() + std::chrono::milliseconds(1500);
	size_t   given = 0;
	while (std::chrono::steady_clock::now() < end) {
		clock += 400; // Every sweep looks as if the last one was a while ago.
		given += bb_mem_release_idle(clock);
		void* p = bb_malloc(200); // The sweeping thread uses the allocator as well.
		bb_free(p);
	}
	stop = true;
	for (auto& w : workers) {
		w.join();
	}
	CHECK(bad == 0);
	printf("release threads: %zu spans given back\n", given);
	const char* switch_value = getenv("BLITZLLVM_ALLOC_RELEASE");
	if (switch_value && !strcmp(switch_value, "0")) {
		CHECK(given == 0);
	}
}

static void benchmark()
{
	using clock = std::chrono::steady_clock;
	constexpr int n = 2000000;
	std::vector<void*> ptrs(1024);
	auto t0 = clock::now();
	for (int i = 0; i < n; i++) {
		size_t k = size_t(i) & 1023;
		if (ptrs[k]) {
			bb_free(ptrs[k]);
		}
		ptrs[k] = bb_malloc(16 + (size_t(i) * 13) % 400);
	}
	auto t1 = clock::now();
	for (void* p : ptrs) {
		bb_free(p);
	}
	std::fill(ptrs.begin(), ptrs.end(), nullptr);
	auto t2 = clock::now();
	for (int i = 0; i < n; i++) {
		size_t k = size_t(i) & 1023;
		if (ptrs[k]) {
			FOREIGN_FREE(ptrs[k]);
		}
		ptrs[k] = FOREIGN_MALLOC(16 + (size_t(i) * 13) % 400);
	}
	auto t3 = clock::now();
	for (void* p : ptrs) {
		FOREIGN_FREE(p);
	}
	printf("benchmark: runtime allocator %.1f ns, system %.1f ns per malloc+free\n", std::chrono::duration<double, std::nano>(t1 - t0).count() / n, std::chrono::duration<double, std::nano>(t3 - t2).count() / n);
}

int main()
{
	test_sizes();
	test_reuse_and_calloc();
	test_realloc();
	test_foreign();
	test_aligned_and_new();
	test_threads();
	test_release();
	test_release_threads();
	benchmark();
	if (failures) {
		fprintf(stderr, "%d checks failed.\n", failures);
		return 1;
	}
	puts("ok");
	return 0;
}
