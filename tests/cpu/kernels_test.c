// Checks that every version of every kernel in code_runtime/source/kernels.c gives the bytes of the scalar one, for all lengths around the vector
// widths, for buffers that start at every offset (the kernels may not assume alignment), and when the destination is the source.
// Run as `kernels_test`; ctest sets BLITZLLVM_CPU, which limits the versions that bb_kernel_tiers reports.
#include "cpu.h"
#include "kernels.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int32_t bb_is_debug(void)
{
	return 0;
}

static int failures = 0;

static void test_swap_rb(int tier)
{
	enum { MAX = 70 };
	static uint8_t source[MAX * 4 + 64], expected[MAX * 4 + 64], actual[MAX * 4 + 64];
	uint32_t       seed = 12345u;
	for (size_t i = 0; i < sizeof(source); i++) {
		seed      = seed * 1664525u + 1013904223u;
		source[i] = (uint8_t)(seed >> 24);
	}
	for (int keep_alpha = 0; keep_alpha <= 1; keep_alpha++) {
		for (size_t offset = 0; offset < 32; offset++) {
			for (size_t count = 0; count <= MAX; count++) {
				memset(expected, 0xA5, sizeof(expected));
				memset(actual, 0xA5, sizeof(actual));
				bb_kernel_swap_rb_with(BB_KERNEL_SCALAR, expected + offset, source + offset, count, keep_alpha);
				bb_kernel_swap_rb_with(tier, actual + offset, source + offset, count, keep_alpha);
				if (memcmp(expected, actual, sizeof(expected)) != 0) {
					fprintf(stderr, "swap_rb tier %d keep_alpha %d offset %zu count %zu differs (or wrote outside of the pixels)\n", tier, keep_alpha, offset, count);
					failures++;
					return;
				}
				// In place.
				memcpy(actual, source, sizeof(actual));
				bb_kernel_swap_rb_with(tier, actual + offset, actual + offset, count, keep_alpha);
				memcpy(expected, source, sizeof(expected));
				bb_kernel_swap_rb_with(BB_KERNEL_SCALAR, expected + offset, source + offset, count, keep_alpha);
				if (memcmp(expected, actual, sizeof(expected)) != 0) {
					fprintf(stderr, "swap_rb tier %d keep_alpha %d offset %zu count %zu differs in place\n", tier, keep_alpha, offset, count);
					failures++;
					return;
				}
			}
		}
	}
}

int main(void)
{
	uint32_t tiers = bb_kernel_tiers();
	char description[256];
	bb_cpu_describe(description, sizeof(description));
	printf("kernel tiers: 0x%x (%s)\n", tiers, description);
	if (!(tiers & 1u)) {
		fprintf(stderr, "the scalar version has to be there\n");
		return 1;
	}
	for (int tier = 0; tier < BB_KERNEL_TIERS; tier++) {
		if (tiers & (1u << tier)) {
			test_swap_rb(tier);
		}
	}
	return failures ? 1 : 0;
}
