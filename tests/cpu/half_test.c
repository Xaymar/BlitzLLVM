// The Float to Half and Half to Float conversions of the runtime (half.c) against the conversions of the compiler.

#define BLITZ_HALF_TEST 1
#include "half.c"

#include <stdio.h>
#include <string.h>

static uint32_t float_bits(float f)
{
	uint32_t b;
	memcpy(&b, &f, 4);
	return b;
}

static float bits_float(uint32_t b)
{
	float f;
	memcpy(&f, &b, 4);
	return f;
}

// The functions of the runtime take and give a float whose lowest 16 bits are the half.
static uint16_t half_of(float f)
{
	return (uint16_t)(float_bits(f) & 0xFFFFu);
}

static float float_of_half(uint16_t h)
{
	return bits_float(h);
}

static int failures = 0;

static void check_trunc(uint32_t bits)
{
	float    f = bits_float(bits);
	_Float16 h = (_Float16)f;
	uint16_t want;
	memcpy(&want, &h, 2);
	uint16_t got = half_of(blitz_truncsfhf2(f));
	int      nan = (bits & 0x7FFFFFFFu) > 0x7F800000u;
	// NaN only has to stay a NaN of the same sign.
	if (nan ? (((got & 0x7C00u) != 0x7C00u) || !(got & 0x3FFu) || ((got ^ want) & 0x8000u)) : (got != want)) {
		if (failures++ < 20) {
			printf("truncate 0x%08x: got 0x%04x, compiler 0x%04x\n", bits, got, want);
		}
	}
}

int main(void)
{
	// Every half, converted up (exact) and back down.
	for (uint32_t h = 0; h < 0x10000u; h++) {
		_Float16 half;
		uint16_t h16 = (uint16_t)h;
		memcpy(&half, &h16, 2);
		float want = (float)half;
		float got  = blitz_extendhfsf2(float_of_half(h16));
		int   nan  = (h & 0x7FFFu) > 0x7C00u;
		if (nan ? (got == got) : (float_bits(got) != float_bits(want))) {
			if (failures++ < 20) {
				printf("extend 0x%04x: got 0x%08x, compiler 0x%08x\n", h, float_bits(got), float_bits(want));
			}
		}
		if (!nan && half_of(blitz_truncsfhf2(got)) != h16) {
			if (failures++ < 20) {
				printf("round trip 0x%04x gave 0x%04x\n", h, half_of(blitz_truncsfhf2(got)));
			}
		}
		// The halfway point to the next half and its neighbours, where rounding to even decides.
		uint32_t mid = float_bits(blitz_extendhfsf2(float_of_half(h16)));
		uint32_t next = float_bits(blitz_extendhfsf2(float_of_half((uint16_t)(h + 1u))));
		if (!nan && ((h + 1u) & 0x7FFFu) <= 0x7C00u && (h & 0x8000u) == ((h + 1u) & 0x8000u)) {
			uint32_t halfway = (uint32_t)(((uint64_t)(mid & 0x7FFFFFFFu) + (uint64_t)(next & 0x7FFFFFFFu)) / 2u) | (mid & 0x80000000u);
			for (int d = -2; d <= 2; d++) {
				check_trunc(halfway + (uint32_t)d);
			}
		}
	}
	// A spread over every float, and the edges of the exponents.
	for (uint64_t b = 0; b < 0x100000000ull; b += 257u) {
		check_trunc((uint32_t)b);
	}
	for (uint32_t e = 0; e < 512u; e++) {
		for (uint32_t d = 0; d < 3u; d++) {
			check_trunc((e << 23) + d);
			check_trunc((e << 23) - d - 1u);
		}
	}
	if (failures) {
		printf("%d failures\n", failures);
		return 1;
	}
	printf("half conversions match the compiler\n");
	return 0;
}
