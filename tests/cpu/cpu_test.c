// Checks the rules of code_runtime/source/cpu.c: that the detected features agree with the compiler's own detection, that every BLITZLLVM_CPU setting
// lowers them the way it says, and that no feature is usable without what it needs. Run as `cpu_test <case>`; ctest sets BLITZLLVM_CPU per case.
#include "cpu.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

// environment.c asks the runtime whether this is a debug build, which this test is not part of.
int32_t bb_is_debug(void)
{
	return 0;
}

static int failures = 0;

#define CHECK(condition)                                                          \
	do {                                                                          \
		if (!(condition)) {                                                       \
			fprintf(stderr, "%s:%d: failed: %s\n", __FILE__, __LINE__, #condition); \
			failures++;                                                           \
		}                                                                         \
	} while (0)

static int is_x86(void)
{
	return strcmp(bb_cpu_architecture(), "x86_64") == 0 || strcmp(bb_cpu_architecture(), "x86") == 0;
}

// Features as a made up CPU would report them, to test the override without that CPU.
static void test_rules(void)
{
	if (!is_x86()) {
		uint64_t cpu = BB_CPU_NEON | BB_CPU_DOTPROD | BB_CPU_FP16 | BB_CPU_SVE | BB_CPU_SVE2 | BB_CPU_CRC32;
		int      unknown;
		CHECK(bb_cpu_apply_override(cpu, NULL, &unknown) == cpu);
		CHECK(bb_cpu_apply_override(cpu, "baseline", &unknown) == BB_CPU_NEON);
		CHECK(bb_cpu_apply_override(cpu, "-fp16", &unknown) == (BB_CPU_NEON | BB_CPU_DOTPROD | BB_CPU_CRC32)); // SVE needs FP16, and SVE2 needs SVE
		CHECK(bb_cpu_apply_override(cpu, "-sve", &unknown) == (cpu & ~(BB_CPU_SVE | BB_CPU_SVE2)));
		CHECK(bb_cpu_apply_override(cpu, "native, -dotprod", &unknown) == (cpu & ~BB_CPU_DOTPROD));
		bb_cpu_apply_override(cpu, "avx2", &unknown);
		CHECK(unknown == 1);
		return;
	}
	uint64_t v4 = BB_CPU_SSE3 | BB_CPU_SSSE3 | BB_CPU_SSE41 | BB_CPU_SSE42 | BB_CPU_POPCNT | BB_CPU_AVX | BB_CPU_AVX2 | BB_CPU_FMA | BB_CPU_F16C | BB_CPU_BMI1 | BB_CPU_BMI2 | BB_CPU_LZCNT | BB_CPU_AVX512F | BB_CPU_AVX512BW | BB_CPU_AVX512CD | BB_CPU_AVX512DQ | BB_CPU_AVX512VL | BB_CPU_PCLMUL | BB_CPU_AES;
	int      unknown;
	CHECK(bb_cpu_apply_override(v4, NULL, &unknown) == v4 && unknown == 0);
	CHECK(bb_cpu_apply_override(v4, "native", &unknown) == v4);
	CHECK(bb_cpu_apply_override(v4, "baseline", &unknown) == 0);
	CHECK(bb_cpu_apply_override(v4, "BASELINE", &unknown) == 0);
	CHECK((bb_cpu_apply_override(v4, "v2", &unknown) & BB_CPU_AVX) == 0);
	CHECK((bb_cpu_apply_override(v4, "v2", &unknown) & BB_CPU_POPCNT) != 0);
	CHECK((bb_cpu_apply_override(v4, "v3", &unknown) & BB_CPU_AVX512F) == 0);
	CHECK((bb_cpu_apply_override(v4, "v3", &unknown) & BB_CPU_AVX2) != 0);
	CHECK(bb_cpu_apply_override(v4, "v4", &unknown) == v4);
	// Removing a feature removes what needs it.
	CHECK((bb_cpu_apply_override(v4, "-avx2", &unknown) & (BB_CPU_AVX2 | BB_CPU_AVX512F | BB_CPU_AVX512BW)) == 0);
	CHECK((bb_cpu_apply_override(v4, "-avx2", &unknown) & BB_CPU_FMA) != 0);
	CHECK((bb_cpu_apply_override(v4, "-avx", &unknown) & (BB_CPU_AVX | BB_CPU_AVX2 | BB_CPU_FMA | BB_CPU_F16C | BB_CPU_AVX512F)) == 0);
	CHECK((bb_cpu_apply_override(v4, "-sse4.1", &unknown) & (BB_CPU_SSE42 | BB_CPU_AVX | BB_CPU_AVX2)) == 0);
	CHECK((bb_cpu_apply_override(v4, "-bmi1", &unknown) & (BB_CPU_BMI1 | BB_CPU_BMI2)) == 0);
	CHECK((bb_cpu_apply_override(v4, "v3,-fma", &unknown) & (BB_CPU_FMA | BB_CPU_AVX512F)) == 0);
	CHECK((bb_cpu_apply_override(v4, "v3,-fma", &unknown) & BB_CPU_AVX2) != 0);
	CHECK(bb_cpu_apply_override(v4, " v2 , -popcnt", &unknown) == (bb_cpu_apply_override(v4, "v2", &unknown) & ~BB_CPU_POPCNT));
	// What the CPU does not have can't be added.
	CHECK(bb_cpu_apply_override(BB_CPU_SSE3, "v4", &unknown) == BB_CPU_SSE3);
	// A feature that lacks its requirement in the detection is not usable (a VM that hides the SSE4.1 it reports SSE4.2 for).
	CHECK(bb_cpu_apply_override(BB_CPU_SSE3 | BB_CPU_SSE42, NULL, &unknown) == BB_CPU_SSE3);
	// Unknown settings are counted and change nothing.
	CHECK(bb_cpu_apply_override(v4, "bogus", &unknown) == v4 && unknown == 1);
	CHECK(bb_cpu_apply_override(v4, "-bogus,v3,neon", &unknown) == bb_cpu_apply_override(v4, "v3", &unknown));
	bb_cpu_apply_override(v4, "-bogus,v3,neon", &unknown);
	CHECK(unknown == 2);
}

// With no setting the result is what the compiler reports for this CPU, and with a setting it never exceeds that.
static void test_host(const char* expected_level)
{
	uint64_t f = bb_cpu_features();
	char     text[512];
	bb_cpu_describe(text, sizeof(text));
	printf("%s\n", text);
	CHECK(strncmp(text, bb_cpu_architecture(), strlen(bb_cpu_architecture())) == 0);
	CHECK(bb_cpu_has(f));
	CHECK(bb_cpu_has(0));
	if (expected_level && *expected_level) {
		CHECK(strcmp(bb_cpu_level(), expected_level) == 0);
	}
#if (defined(__x86_64__) || defined(__i386__)) && (defined(__GNUC__) || defined(__clang__))
	__builtin_cpu_init();
	// Only in one direction: the compiler may know less (AVX-512 subsets), and the setting may lower ours.
	CHECK(!(f & BB_CPU_AVX2) || __builtin_cpu_supports("avx2"));
	CHECK(!(f & BB_CPU_AVX) || __builtin_cpu_supports("avx"));
	CHECK(!(f & BB_CPU_FMA) || __builtin_cpu_supports("fma"));
	CHECK(!(f & BB_CPU_SSE42) || __builtin_cpu_supports("sse4.2"));
	CHECK(!(f & BB_CPU_POPCNT) || __builtin_cpu_supports("popcnt"));
	CHECK(!(f & BB_CPU_BMI2) || __builtin_cpu_supports("bmi2"));
	CHECK(!(f & BB_CPU_AVX512F) || __builtin_cpu_supports("avx512f"));
	if (!getenv("BLITZLLVM_CPU") /* the same variable the runtime reads */) {
		CHECK(!!(f & BB_CPU_AVX2) == !!__builtin_cpu_supports("avx2"));
		CHECK(!!(f & BB_CPU_SSE42) == !!__builtin_cpu_supports("sse4.2"));
		CHECK(!!(f & BB_CPU_AVX512F) == !!__builtin_cpu_supports("avx512f"));
	}
#endif
	if (is_x86()) {
		CHECK(!(f & BB_CPU_NEON));
	} else if (strcmp(bb_cpu_architecture(), "arm64") == 0) {
		CHECK(f & BB_CPU_NEON);
	}
}

int main(int argc, char** argv)
{
	const char* mode = argc > 1 ? argv[1] : "host";
	if (strcmp(mode, "rules") == 0) {
		test_rules();
	} else {
		test_host(argc > 2 ? argv[2] : NULL);
	}
	return failures ? 1 : 0;
}
