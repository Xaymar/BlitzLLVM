import datetime
import json
import os
import statistics
import sys
import tempfile
import benchutil

GROUPS = ("core", "2d",)
LLVM_ONLY = ("llvm",)


def quartiles(values):
    ordered = sorted(values)
    if len(ordered) < 4:
        return ordered[0], ordered[-1]
    q = statistics.quantiles(ordered, n=4)
    return q[0], q[2]


def read_cases(path):
    """The cases of a result file: {name: {"n": iterations, "per": pieces of work per iteration, "us": [microseconds of each pass]}}, in
    the order they ran."""
    cases = {}
    with open(path) as f:
        for line in f:
            parts = line.split()
            if len(parts) >= 5 and parts[0] == "MICRO":
                cases[parts[1]] = {"n": int(parts[2]), "per": int(parts[3]), "us": [int(v) for v in parts[4:]]}
    return cases


def main():
    runner = benchutil.Runner("micro_core", __doc__, size="320x180")
    p = runner.parser
    p.add_argument("--group", default=os.environ.get("MICRO_GROUP", ",".join(GROUPS)), help="groups to run, separated by commas (default %(default)s)")
    p.add_argument("--filter", default=os.environ.get("MICRO_FILTER", ""), help="only the cases whose name contains one of these words, separated by commas")
    p.add_argument("--samples", type=int, default=int(os.environ.get("MICRO_SAMPLES", 11)), help="timed passes per case (default %(default)s)")
    p.add_argument("--target-us", type=int, default=int(os.environ.get("MICRO_TARGET_US", 0)),
                   help="length of one pass in microseconds (default 2000, 50000 with the original's millisecond timer)")
    args = runner.parse()
    if args.quick:
        args.samples = min(args.samples, 3)
        if not args.target_us:
            args.target_us = 200 if runner.llvm else 20000
    groups = [g.strip() for g in args.group.split(",") if g.strip()]
    for g in groups:
        if g not in GROUPS:
            sys.exit("Unknown group %s; the groups are %s." % (g, ", ".join(GROUPS)))
    if not runner.llvm:
        groups = [g for g in groups if g not in LLVM_ONLY]
    env = {"MICRO_SAMPLES": args.samples, "MICRO_FILTER": args.filter}
    if args.target_us:
        env["MICRO_TARGET_US"] = args.target_us
    cases = {}
    for group in groups:
        runner.name = runner.own = "micro_" + group
        with tempfile.TemporaryDirectory() as directory:
            program = runner.build(directory, files=[os.path.join(benchutil.HERE, "micro.bi")])
            print("Running %s, %d passes per case, build %s" % (runner.name, args.samples, " ".join(runner.flags) or "no options"), flush=True)
            runner.execute(program, directory, dict(env, MICRO_FILE=os.path.join(directory, "micro_file.tmp")))
            found = read_cases(os.path.join(directory, "result.txt"))
        for name, case in found.items():
            case["group"] = group
            cases[name] = case
    if not cases:
        sys.exit("No case ran%s." % (" (the filter %s matches none)" % args.filter if args.filter else ""))

    result = {}
    print()
    print("  %-40s %12s %12s %12s %8s" % ("case", "iterations", "ns median", "ns min", "spread"))
    for name, case in cases.items():
        per = [us * 1000.0 / (case["n"] * case["per"]) for us in case["us"]]
        median = statistics.median(per)
        low, high = quartiles(per)
        spread = 50.0 * (high - low) / median if median else 0.0
        case["ns_median"] = median
        case["ns_min"] = min(per)
        result["ns:" + name] = median
        print("  %-40s %12d %12.2f %12.2f %7.1f%%" % (name, case["n"] * case["per"], median, min(per), spread))
    print("  build       %s (%s)" % (" ".join(runner.flags) or "no options", runner.version or "unknown compiler"))

    record = {
        "date": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "label": args.label,
        "compiler": runner.version if runner.llvm else "Blitz3D " + runner.version,
        "build": " ".join(runner.flags),
        "display": "xvfb" if runner.display else "native",
        "samples": args.samples,
        "result": result,
        "micro": cases,
    }
    if args.json:
        with open(args.json, "w") as f:
            json.dump(record, f)
    if not args.no_save:
        out = os.path.join(benchutil.HERE, "results")
        os.makedirs(out, exist_ok=True)
        name = "micro-%s-%s.json" % (datetime.datetime.now().strftime("%Y%m%d-%H%M%S"), "llvm" if runner.llvm else "original")
        with open(os.path.join(out, name), "w") as f:
            json.dump(record, f, indent=1)
        print("  saved       benchmarks/results/%s" % name)


if __name__ == "__main__":
    main()
