RESAMPLES = 20000  # Of the bootstrap and of the permutation test: enough for a p value of 0.001 to be told from 0.002.


def mean(values):
    return sum(values) / len(values)


def bootstrap_interval(a, b, rng, level=0.95):
    """The interval that holds level of the differences mean(b) - mean(a) of resampled runs."""
    differences = sorted(mean(rng.choices(b, k=len(b))) - mean(rng.choices(a, k=len(a))) for _ in range(RESAMPLES))
    low = differences[int((1 - level) / 2 * RESAMPLES)]
    high = differences[min(RESAMPLES - 1, int((1 + level) / 2 * RESAMPLES))]
    return low, high


def permutation_p(a, b, rng):
    """Two-sided p value of mean(b) - mean(a): how often runs dealt out to the builds at random differ at least as much. Exact when there
    are few ways to deal them out, else from RESAMPLES random ones."""
    observed = abs(mean(b) - mean(a))
    joined = a + b
    n = len(a)
    total = sum(joined)
    # Every way of picking which runs are A's, when there are few of them (math.comb(20, 10) is 184756).
    if math.comb(len(joined), n) <= 200000:
        import itertools
        hits = count = 0
        for picked in itertools.combinations(range(len(joined)), n):
            sa = sum(joined[i] for i in picked)
            if abs((total - sa) / len(b) - sa / n) >= observed - 1e-12:
                hits += 1
            count += 1
        return hits / count
    hits = 0
    for _ in range(RESAMPLES):
        rng.shuffle(joined)
        sa = sum(joined[:n])
        if abs((total - sa) / len(b) - sa / n) >= observed - 1e-12:
            hits += 1
    return (hits + 1) / (RESAMPLES + 1)


def mann_whitney_p(a, b):
    """Two-sided p value of the Mann-Whitney U test, from the normal approximation with the correction for ties and for continuity."""
    joined = sorted([(v, 0) for v in a] + [(v, 1) for v in b])
    ranks = [0.0] * len(joined)
    ties = 0.0
    i = 0
    while i < len(joined):
        j = i
        while j + 1 < len(joined) and joined[j + 1][0] == joined[i][0]:
            j += 1
        for k in range(i, j + 1):
            ranks[k] = (i + j) / 2 + 1
        t = j - i + 1
        ties += t ** 3 - t
        i = j + 1
    n1, n2 = len(a), len(b)
    r1 = sum(r for r, (_, side) in zip(ranks, joined) if side == 0)
    u = r1 - n1 * (n1 + 1) / 2
    mu = n1 * n2 / 2
    n = n1 + n2
    sigma = math.sqrt(n1 * n2 / 12 * ((n + 1) - ties / (n * (n - 1))))
    if sigma == 0:
        return 1.0
    z = max(0.0, abs(u - mu) - 0.5) / sigma
    return math.erfc(z / math.sqrt(2))


def analyse(a, b, seed=1):
    """The statistics of the values of A and B: means, the 95% interval of mean(b) - mean(a), and the p values."""
    if len(a) < 2 or len(b) < 2:
        sys.exit("Each build needs at least two values.")
    rng = random.Random(seed)
    low, high = bootstrap_interval(a, b, rng)
    return {"ma": mean(a), "mb": mean(b), "low": low, "high": high, "p_perm": permutation_p(list(a), list(b), rng), "p_mw": mann_whitney_p(a, b)}


def compare(a, b, lower_is_better, alpha, unit, seed=1):
    """Prints the comparison of the values of A and B and returns True when B is faster."""
    r = analyse(a, b, seed)
    ma, mb, low, high, p_perm, p_mw = r["ma"], r["mb"], r["low"], r["high"], r["p_perm"], r["p_mw"]
    percent = (lambda d: 100.0 * d / ma) if ma else (lambda d: float("nan"))
    print()
    for name, values in (("A", a), ("B", b)):
        print("  %s  n %2d  mean %10.4f  sd %8.4f  median %10.4f  %s" % (name, len(values), mean(values), statistics.stdev(values), statistics.median(values),
                                                                   " ".join("%.4g" % v for v in values)))
    print("  B - A      %+.4f %s (%+.2f%%), 95%% interval %+.4f .. %+.4f (%+.2f%% .. %+.2f%%)" % (mb - ma, unit, percent(mb - ma), low, high, percent(low), percent(high)))
    print("  p          permutation %.4f, Mann-Whitney U %.4f" % (p_perm, p_mw))
    shown = p_perm < alpha and (low > 0 or high < 0)
    if not shown:
        print("  verdict    no difference shown (p %.4f, alpha %.3g, interval %s 0)" % (p_perm, alpha, "contains" if low <= 0 <= high else "excludes"))
        return False
    faster = (mb < ma) if lower_is_better else (mb > ma)
    print("  verdict    B is %s than A by %.2f%%" % ("faster" if faster else "slower", abs(percent(mb - ma))))
    return faster


def holm(p_values):
    """Holm-Bonferroni adjusted p values, in the order given: with many metrics, some of them fall below alpha by chance alone, and
    these do not."""
    order = sorted(range(len(p_values)), key=lambda i: p_values[i])
    adjusted = [1.0] * len(p_values)
    running = 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(p_values) - rank) * p_values[i]))
        adjusted[i] = running
    return adjusted


def compare_many(values, metrics, alpha, higher_is_better):
    """Prints one line per metric (a microbenchmark run has hundreds) and the ones that differ. A metric counts as different when its
    p value, adjusted for the number of metrics (Holm), is below alpha and its interval does not contain 0. Returns the number of
    metrics where B is faster and where it is slower."""
    rows = []
    for m in metrics:
        a, b = values["A"][m], values["B"][m]
        rows.append((m, analyse(a, b)))
    adjusted = holm([r["p_perm"] for _, r in rows])
    width = max(len(m) for m in metrics)
    print()
    print("  %-*s %12s %12s %9s %21s %8s %8s  %s" % (width, "metric", "A mean", "B mean", "B - A", "95% interval", "p", "p Holm", "verdict"))
    faster = slower = 0
    for (m, r), p_holm in zip(rows, adjusted):
        ma = r["ma"]
        percent = (lambda d: 100.0 * d / ma) if ma else (lambda d: float("nan"))
        lower = not (higher_is_better or m.startswith("fps"))
        verdict = ""
        if p_holm < alpha and (r["low"] > 0 or r["high"] < 0):
            better = (r["mb"] < ma) if lower else (r["mb"] > ma)
            verdict = "B faster" if better else "B slower"
            faster += better
            slower += not better
        elif r["p_perm"] < alpha and (r["low"] > 0 or r["high"] < 0):
            verdict = "(only without Holm)"
        print("  %-*s %12.4g %12.4g %+8.2f%% %+9.2f%% .. %+6.2f%% %8.4f %8.4f  %s" % (width, m, ma, r["mb"], percent(r["mb"] - ma), percent(r["low"]), percent(r["high"]),
                                                                            r["p_perm"], p_holm, verdict))
    print()
    print("  verdict    %d of %d metrics: B faster in %d, B slower in %d (Holm-adjusted p below %.3g and interval without 0)" % (faster + slower, len(metrics), faster, slower, alpha))
    return faster, slower


def is_pattern(metric):
    return any(c in metric for c in "*?[")


def run_once(runner, compiler, program, extra, metric, directory):
    """Runs the runner once with compiler, building to program, and returns its metric, or with a pattern for metric (ns:*) a dict of
    every metric that matches it."""
    out = os.path.join(directory, "result.json")
    if os.path.isfile(out):
        os.remove(out)
    env = dict(os.environ, BENCH_PROGRAM=program)
    result = procutil.run([sys.executable, os.path.join(HERE, runner + ".py"), "--blitzcc", compiler, "--no-save", "--json", out] + extra,
                          env=env, capture_output=True, text=True)
    if result.returncode != 0 or not os.path.isfile(out):
        sys.exit("%s failed with %s (exit code %d):\n%s" % (runner, compiler, result.returncode, (result.stdout + result.stderr)[-2000:]))
    values = json.load(open(out))["result"]
    if is_pattern(metric):
        found = {k: v for k, v in values.items() if fnmatch.fnmatchcase(k, metric)}
        if not found:
            sys.exit("%s has no metric that matches %s in its result; it has %s" % (runner, metric, ", ".join(sorted(values))))
        return found
    if metric not in values:
        sys.exit("%s has no %s in its result; it has %s" % (runner, metric, ", ".join(sorted(values))))
    return values[metric]


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[1].strip(), formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    p.add_argument("--a", help="the compiler of build A (the base)")
    p.add_argument("--b", help="the compiler of build B (the change)")
    p.add_argument("--rounds", type=int, default=10, help="rounds of A B B A (default %(default)s)")
    p.add_argument("--metric", default="ms_avg", help="value of the RESULT line that is compared (default %(default)s); a pattern such as 'ns:*' "
                   "compares every value that matches it, for micro.py")
    p.add_argument("--higher-is-better", action="store_true", help="the metric is a rate (fps) and not a time")
    p.add_argument("--alpha", type=float, default=0.05, help="p value below which a difference counts (default %(default)s)")
    p.add_argument("--values-a", help="values of A, separated by commas, instead of running anything")
    p.add_argument("--values-b", help="values of B")
    p.add_argument("runner", nargs="?", help="the benchmark runner, such as flythrough")
    p.add_argument("options", nargs=argparse.REMAINDER, help="options of the runner")
    args = p.parse_args()
    lower = not args.higher_is_better
    if args.values_a or args.values_b:
        if not (args.values_a and args.values_b):
            sys.exit("Give --values-a and --values-b.")
        a = [float(v) for v in args.values_a.split(",") if v.strip()]
        b = [float(v) for v in args.values_b.split(",") if v.strip()]
        compare(a, b, lower, args.alpha, "")
        return
    if not (args.a and args.b and args.runner):
        sys.exit("Give --a, --b and the runner (or --values-a and --values-b).")
    if args.metric.startswith("fps"):
        lower = False
    with tempfile.TemporaryDirectory() as directory:
        exe = ".exe" if os.name == "nt" else ""
        programs = {"A": os.path.join(directory, "a", benchutil.program_name() + exe), "B": os.path.join(directory, "b", benchutil.program_name() + exe)}
        compilers = {"A": os.path.abspath(args.a), "B": os.path.abspath(args.b)}
        for side in ("A", "B"):
            print("Warm-up run of %s (not counted)" % side, flush=True)
            run_once(args.runner, compilers[side], programs[side], args.options, args.metric, directory)
        many = is_pattern(args.metric)
        values = {"A": {}, "B": {}} if many else {"A": [], "B": []}
        for r in range(args.rounds):
            for side in ("A", "B", "B", "A"):
                v = run_once(args.runner, compilers[side], programs[side], args.options, args.metric, directory)
                if many:
                    for k, x in v.items():
                        values[side].setdefault(k, []).append(x)
                    print("Round %d/%d  %s  %d metrics" % (r + 1, args.rounds, side, len(v)), flush=True)
                else:
                    values[side].append(v)
                    print("Round %d/%d  %s  %s %.4f" % (r + 1, args.rounds, side, args.metric, v), flush=True)
    if many:
        # Only the metrics that every run of both builds has (a case that one build does not have is left out).
        runs = 2 * args.rounds
        metrics = [m for m in values["A"] if len(values["A"][m]) == runs and len(values["B"].get(m, ())) == runs]
        if not metrics:
            sys.exit("No metric is in every run of both builds.")
        compare_many(values, metrics, args.alpha, args.higher_is_better)
        return
    compare(values["A"], values["B"], lower, args.alpha, args.metric)


if __name__ == "__main__":
    main()
