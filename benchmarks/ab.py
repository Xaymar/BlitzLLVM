#!/usr/bin/env python3
"""
Tells whether build B is faster or slower than build A, and whether the difference is real or noise.

    python3 benchmarks/ab.py --a A/blitzcc --b B/blitzcc [--rounds 10] [--metric ms_avg] flythrough [runner options]
    python3 benchmarks/ab.py --values-a 33.52,33.52,33.25,33.42 --values-b 34.22,34.33,33.80,34.08 [--higher-is-better]
    python3 benchmarks/ab.py --a A/blitzcc --b B/blitzcc --metric 'ns:*' micro --filter banks,stride

The first form runs a benchmark runner of this folder (flythrough, dungeon, forest, ...; its own options come after its name) with
the compiler of A and of B, in rounds of A B B A, so that a machine that slowly warms up or cools down hits both builds alike. Before
the rounds, each build runs once untimed: the first start of a program pays for the shader and pipeline caches of the driver. Each
build keeps one program path for all its runs (BENCH_PROGRAM, a random name made once), so that those caches stay warm. One run gives
one value, the metric of its RESULT line (ms_avg by default, lower is better).

The second form only does the statistics, for values that were measured some other way (a game that prints its own frame rate).

The result:

* the mean, standard deviation and median of each build,
* the difference of the means, in units and in percent of A, with a 95% bootstrap confidence interval,
* the p value of a permutation test of the difference of the means (no assumption about the distribution), and of the Mann-Whitney
  U test (ranks, so that one odd run weighs little),
* a verdict: B is faster or slower when the permutation p is below --alpha (0.05) and the interval does not contain 0, else the
  difference is not shown by these runs.

Ten rounds (twenty runs of each build) find differences of about a third of the spread between runs. A difference smaller than that
needs more rounds, or a benchmark that times only the part that changed: micro.py, whose cases each time one builtin.

A --metric with * ? or [ in it (fnmatch) compares every value of the RESULT that matches it, such as 'ns:*' for all cases of micro.py
or 'ns:banks/*' for some, with one line each. With many metrics some fall below --alpha by chance alone (one in twenty), so their p
values are adjusted with the Holm-Bonferroni method, and only those count.
"""
